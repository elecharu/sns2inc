-- IFSTD
CREATE TABLE IF NOT EXISTS `IFSTD` (
  `IFNAME` varchar(100) NOT NULL DEFAULT '' COMMENT '이름',
  `IFGB` varchar(10) NOT NULL DEFAULT '' COMMENT 'ERP, APS 구분',
  `IFTYPE` varchar(10) NOT NULL DEFAULT '' COMMENT '유형',
  `SORTNO` int(11) NOT NULL DEFAULT 0 COMMENT '호출순번',
  `CYCLE` varchar(10) NOT NULL DEFAULT '' COMMENT '주기',
  `LASTTIME` varchar(19) NOT NULL DEFAULT '' COMMENT '최종수정시간',
  `PROCNAME` varchar(100) NOT NULL DEFAULT '' COMMENT '프로시저명',
  `IFDESC` varchar(1000) NOT NULL DEFAULT '' COMMENT '정의',
  `USEYN` varchar(1) NOT NULL DEFAULT 'Y' COMMENT '사용여부',
  `LASTSEQ` int(11) NOT NULL DEFAULT 0,
  `TABLENAME` varchar(100) NOT NULL DEFAULT '' COMMENT '테이블',
  `REMARK` varchar(255) DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8 AVG_ROW_LENGTH=963 ROW_FORMAT=DYNAMIC COMMENT='IF테이블리스트';

-- IF_ERR_LOG
CREATE TABLE IF NOT EXISTS `IF_ERR_LOG` (
  `IFKEY` int(11) DEFAULT NULL COMMENT 'IF키',
  `IFGB` varchar(10) DEFAULT '' COMMENT 'ERP, APS 구분',
  `IFNAME` varchar(255) NOT NULL DEFAULT '' COMMENT 'IF내용',
  `SENDTIME` varchar(19) NOT NULL DEFAULT '' COMMENT '전송시간',
  `IF_TYPE` varchar(1) NOT NULL DEFAULT '' COMMENT 'IF유형 (I, U ,D)',
  `READTIME` varchar(19) NOT NULL DEFAULT '' COMMENT '수신시간',
  `ERRMSG` varchar(1000) NOT NULL DEFAULT '' COMMENT '오류메시지',
  KEY `IDX_IF_ERR_LOG` (`IFKEY`,`IFGB`,`IFNAME`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8 AVG_ROW_LENGTH=102 ROW_FORMAT=DYNAMIC COMMENT='IF 오류 로그';

-- COMDEBUG
CREATE TABLE IF NOT EXISTS `COMDEBUG` (
  `DEBUGNM` varchar(20) NOT NULL DEFAULT '' COMMENT '로그유형',
  `DEBUGTIME` varchar(19) NOT NULL DEFAULT '' COMMENT '로그시간',
  `DEBUGMSG` varchar(20000) NOT NULL DEFAULT '' COMMENT '로그메시지',
  `PROCNAME` varchar(50) NOT NULL DEFAULT '' COMMENT '프로시저명',
  `CALLTYPE` varchar(50) NOT NULL DEFAULT '' COMMENT '호출명',
  `CALLPARAM` mediumtext NOT NULL COMMENT '파라미터',
  `CALLEMP` varchar(20) NOT NULL DEFAULT '' COMMENT '호출자',
  `CALLPRG` varchar(100) NOT NULL DEFAULT '' COMMENT '호출프로그램',
  `CALLHOST` varchar(100) NOT NULL DEFAULT '' COMMENT '호출컴퓨터',
  `CALLIP` varchar(100) NOT NULL DEFAULT '' COMMENT '호출IP',
  `CALLMAC` varchar(100) NOT NULL DEFAULT '' COMMENT '호출MAC',
  `REMARK` varchar(1000) NOT NULL DEFAULT '',
  `RTIME` varchar(19) NOT NULL DEFAULT '',
  `REMP` varchar(20) NOT NULL DEFAULT '',
  `RPRG` varchar(100) NOT NULL DEFAULT '',
  `MTIME` varchar(19) NOT NULL DEFAULT '',
  `MEMP` varchar(20) NOT NULL DEFAULT '',
  `MPRG` varchar(20) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8 AVG_ROW_LENGTH=744 ROW_FORMAT=DYNAMIC COMMENT='디버그';

