CREATE PROCEDURE `COMDEBUG`(
  IN $LINENUM INT, 
  IN $ERRMSG VARCHAR(20000)
)
PROC: BEGIN

  IF IFNULL(@ERR_PROC_MSG, '') = '' THEN 

    SET @ERR_PROC_MSG = CONCAT('Line ', $LINENUM, ': ', $ERRMSG);

  ELSE

    SET @ERR_PROC_MSG = CONCAT(@ERR_PROC_MSG, CHAR(10), 'Line ', $LINENUM, ': ', $ERRMSG);

  END IF;

END$$

