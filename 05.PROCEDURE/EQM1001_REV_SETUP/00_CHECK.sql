SELECT 'MSTEQMREV_HEADER' AS TABLENAME, COUNT(*) AS ROWCNT FROM MES_SNS2.MSTEQMREV_HEADER
UNION ALL SELECT 'MSTEQMREV_DETAIL', COUNT(*) FROM MES_SNS2.MSTEQMREV_DETAIL
UNION ALL SELECT 'CHKPLANEQM_APRV', COUNT(*) FROM MES_SNS2.CHKPLANEQM_APRV
UNION ALL SELECT 'CHKRSTEQM_02', COUNT(*) FROM MES_SNS2.CHKRSTEQM WHERE CHKTP = '02'
UNION ALL SELECT 'CHKRSTEQMKND_02', COUNT(*) FROM MES_SNS2.CHKRSTEQMKND D
INNER JOIN MES_SNS2.CHKRSTEQM H ON H.CHKRSTKEY = D.CHKRSTKEY WHERE H.CHKTP = '02';

SELECT TABLE_NAME, COLUMN_NAME, COLUMN_TYPE, COLUMN_KEY
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = 'MES_SNS2'
  AND TABLE_NAME IN ('MSTEQMREV_HEADER', 'MSTEQMREV_DETAIL', 'CHKPLANEQM_APRV', 'CHKRSTEQM', 'CHKRSTEQMKND')
ORDER BY TABLE_NAME, ORDINAL_POSITION;

SELECT TABLE_NAME, INDEX_NAME, GROUP_CONCAT(COLUMN_NAME ORDER BY SEQ_IN_INDEX) AS KEYCOLUMNS
FROM information_schema.STATISTICS
WHERE TABLE_SCHEMA = 'MES_SNS2'
  AND TABLE_NAME IN ('MSTEQMREV_HEADER', 'MSTEQMREV_DETAIL', 'CHKPLANEQM_APRV', 'CHKRSTEQM', 'CHKRSTEQMKND')
GROUP BY TABLE_NAME, INDEX_NAME ORDER BY TABLE_NAME, INDEX_NAME;
