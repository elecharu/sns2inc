CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.DC_POP(
-- *****************************************************************************
-- Comment: POPUP
-- Create: 2016-11-10 14:45: 
-- Modify: 2016-11-10 14:45: 
-- *****************************************************************************
  IN $GPCD VARCHAR(20),
  IN $KEYWORD VARCHAR(1000), -- 키워드
  IN $REF01    VARCHAR(20),
  IN $REF02    VARCHAR(20),
  IN $REF03    VARCHAR(20),
  IN $REF04    VARCHAR(20),
  IN $REF05    VARCHAR(20)
)
PROC: BEGIN
-- *****************************************************************************  
DECLARE _$GPCD VARCHAR(20);
SET _$GPCD = REPLACE(REPLACE(REPLACE($GPCD, '_HEAD', ''), '_LIST', ''), '_INFO', '');
IF EXISTS (SELECT GPCD FROM COMTYPEGP WHERE GPCD = _$GPCD ) THEN 
    
  IF RIGHT($GPCD, 5) = '_HEAD' THEN

    SELECT '유형코드' AS CODE, '유형명' AS NAME;
    SELECT 100 AS CODE, 150 AS NAME;

  ELSEIF RIGHT($GPCD, 5) = '_LIST' THEN

    SELECT COMTYPE.TPCD AS CODE, COMTYPE.TPNM AS NAME
      FROM COMTYPE
      WHERE COMTYPE.GPCD = _$GPCD
      AND COMTYPE.USEYN = 'Y'
      AND COMTYPE.REF01 LIKE CONCAT('%', $REF01, '%')
      AND COMTYPE.REF02 LIKE CONCAT('%', $REF02, '%')
      AND COMTYPE.REF03 LIKE CONCAT('%', $REF03, '%')
      AND COMTYPE.REF04 LIKE CONCAT('%', $REF04, '%')
      AND COMTYPE.REF05 LIKE CONCAT('%', $REF05, '%')
      AND (
        COMTYPE.TPCD LIKE CONCAT('%', $KEYWORD, '%')
        OR COMTYPE.TPNM LIKE CONCAT('%', $KEYWORD, '%')
      )
      ORDER BY COMTYPE.SORTNO;

  ELSEIF RIGHT($GPCD, 5) = '_INFO' THEN

    SELECT COMTYPE.TPCD AS CODE, COMTYPE.TPNM AS NAME
      FROM COMTYPE
      WHERE COMTYPE.GPCD = _$GPCD 
      AND COMTYPE.USEYN = 'Y'
      AND COMTYPE.REF01 LIKE CONCAT('%', $REF01, '%')
      AND COMTYPE.REF02 LIKE CONCAT('%', $REF02, '%')
      AND COMTYPE.REF03 LIKE CONCAT('%', $REF03, '%')
      AND COMTYPE.REF04 LIKE CONCAT('%', $REF04, '%')
      AND COMTYPE.REF05 LIKE CONCAT('%', $REF05, '%')
      AND COMTYPE.TPCD = $KEYWORD;

  END IF;

-- *****************************************************************************
ELSEIF $GPCD = 'ITEMID_HEAD' THEN

  SELECT '품목ID' AS CODE, '품목코드' AS NAME, '품명' AS REF01, '규격' AS REF02, '재질' AS REF03;
  SELECT 50 AS CODE, 200 AS NAME, 150 AS REF01, 80 AS REF02, 80 AS REF03;

ELSEIF $GPCD = 'ITEMID_LIST' THEN

   SELECT CAST(MSTITEM.ITEMID AS CHAR) AS CODE, MSTITEM.ITEMCD AS NAME, MSTITEM.ITEMNM AS REF01, MSTITEM.ITEMSPEC AS REF02, MSTITEM.SPEC6 AS REF03
      FROM MSTITEM
      WHERE COMPANYCD LIKE CONCAT('%', $REF01, '%')
        AND MSTITEM.ITEMCG LIKE CONCAT('%', $REF02, '%')
        AND (MSTITEM.ITEMCD LIKE CONCAT('%', $KEYWORD, '%')
           OR MSTITEM.ITEMNM LIKE CONCAT('%', $KEYWORD, '%')
           OR MSTITEM.ITEMSPEC LIKE CONCAT('%', $KEYWORD, '%')
           OR MSTITEM.SPEC6 LIKE CONCAT('%', $KEYWORD, '%') 
           OR MSTITEM.EONO LIKE CONCAT('%', $KEYWORD, '%'))
        AND MSTITEM.ENDYN = 'N'
    ;

  ELSEIF $GPCD = 'ITEMID_INFO' THEN
    
    SELECT CAST(MSTITEM.ITEMID AS CHAR) AS CODE, MSTITEM.ITEMCD AS NAME, MSTITEM.ITEMNM AS REF01, MSTITEM.ITEMSPEC AS REF02, MSTITEM.SPEC6 AS REF03
      FROM MSTITEM
      WHERE CASE WHEN $KEYWORD REGEXP ('^[0-9]+$') THEN MSTITEM.ITEMID = $KEYWORD ELSE FALSE END;

-- *****************************************************************************
ELSEIF $GPCD = 'ITEMCD_HEAD' THEN

  SELECT '품목코드' AS CODE, '품번' AS NAME, '품명' AS REF01, '품목유형' AS REF02, '단위' AS REF03;
  SELECT 100 AS CODE, 200 AS NAME, 100 AS REF01, 80 AS REF02, 50 AS REF03 ;

ELSEIF $GPCD = 'ITEMCD_LIST' THEN

  SELECT 
      MSTITEM.ITEMCD AS CODE
    , MSTITEM.ITEMNUM AS NAME
    , MSTITEM.ITEMNM AS REF01
    , GPCD('ITEMTP', MSTITEM.ITEMTP) AS REF02
    , GPCD('ITEMUNIT', MSTITEM.ITEMUNIT) AS REF03
  FROM MSTITEM
  WHERE MSTITEM.ITEMTP LIKE CONCAT('%', $REF01, '%')
   AND (  MSTITEM.ITEMCD = $KEYWORD
       OR MSTITEM.ITEMNUM LIKE CONCAT('%', $KEYWORD, '%')
       OR MSTITEM.ITEMNM LIKE CONCAT('%', $KEYWORD, '%'))
  ORDER BY MSTITEM.ITEMNM
  LIMIT 100;

ELSEIF $GPCD = 'ITEMCD_INFO' THEN

  SELECT 
      MSTITEM.ITEMCD AS CODE
    , MSTITEM.ITEMNUM AS NAME
    , MSTITEM.ITEMNM AS REF01
    , MSTITEM.ITEMTP AS REF02
    , MSTITEM.ITEMUNIT AS REF03
  FROM MSTITEM
  WHERE MSTITEM.ITEMTP LIKE CONCAT('%', $REF01, '%')
   AND (  MSTITEM.ITEMCD = $KEYWORD
       OR MSTITEM.ITEMNUM LIKE CONCAT('%', $KEYWORD, '%')
       OR MSTITEM.ITEMNM LIKE CONCAT('%', $KEYWORD, '%'))
  ORDER BY MSTITEM.ITEMNM
  LIMIT 100;

-- *****************************************************************************
  ELSEIF $GPCD = 'BOM_MITEM_HEAD' THEN
  
    SELECT '품목ID' AS CODE, '품목코드' AS NAME, '품명' AS REF01, '품목유형' AS SPEC;
    SELECT 80 AS CODE, 130 AS NAME, 250 AS REF01, 200 AS SPEC;

  ELSEIF $GPCD = 'BOM_MITEM_LIST' THEN

    SELECT
      A.MITEMID AS CODE,
      B.ITEMCD AS NAME,
      B.ITEMNM AS REF01,
      GPCD('DM100', B.ITEMCG) AS SPEC  
      FROM MSTBOM AS A
      INNER JOIN MSTITEM AS B ON A.MITEMID = B.ITEMID
      WHERE CITEMID = $REF01
        AND A.USEYN = 'Y'; 

  ELSEIF $GPCD = 'BOM_MITEM_INFO' THEN

    SELECT
      A.MITEMID AS CODE,
      B.ITEMCD AS NAME,
      B.ITEMNM AS REF01,
      GPCD('DM100', B.ITEMCG) AS SPEC  
      FROM MSTBOM AS A
      INNER JOIN MSTITEM AS B ON A.MITEMID = B.ITEMID
      WHERE CITEMID = $REF01
        AND A.USEYN = 'Y';

-- *****************************************************************************
ELSEIF $GPCD = 'CUSTCD_HEAD' THEN

  SELECT '거래처코드' AS CODE, '거래처명' AS NAME, '영문명' AS REF01;
  SELECT 100 AS CODE, 200 AS NAME, 100 AS REF01;

ELSEIF $GPCD = 'CUSTCD_LIST' THEN

  IF $REF03 <> '' THEN
  
   SELECT MSTCUST.CUSTCD AS CODE, MSTCUST.CUSTNM AS NAME, MSTCUST.CUSTNMEN AS REF01
    FROM MSTCUST
    WHERE MSTCUST.CUSTTP LIKE CONCAT('%', $REF01, '%')
      AND MSTCUST.PURYN  LIKE CONCAT('%', $REF02, '%')
      AND MSTCUST.SALEYN = 'Y'
      AND (MSTCUST.CUSTCD LIKE CONCAT('%', $KEYWORD, '%')
        OR MSTCUST.CUSTNM LIKE CONCAT('%', $KEYWORD, '%')
        OR MSTCUST.CUSTNMEN LIKE CONCAT('%', $KEYWORD, '%')
      )
    LIMIT 100;
  
  ELSE    
  
    SELECT MSTCUST.CUSTCD AS CODE, MSTCUST.CUSTNM AS NAME, MSTCUST.CUSTNMEN AS REF01
      FROM MSTCUST
      WHERE MSTCUST.CUSTTP LIKE CONCAT('%', $REF01, '%')
        AND MSTCUST.PURYN  LIKE CONCAT('%', $REF02, '%')
        AND (MSTCUST.CUSTCD LIKE CONCAT('%', $KEYWORD, '%')
          OR MSTCUST.CUSTNM LIKE CONCAT('%', $KEYWORD, '%')
          OR MSTCUST.CUSTNMEN LIKE CONCAT('%', $KEYWORD, '%')
        )
      
      LIMIT 100;
  END IF;

ELSEIF $GPCD = 'CUSTCD_INFO' THEN

    SELECT MSTCUST.CUSTCD AS CODE, MSTCUST.CUSTNM AS NAME
    FROM MSTCUST
      WHERE MSTCUST.CUSTTP LIKE CONCAT('%', $REF01, '%')
      AND MSTCUST.PURYN  LIKE CONCAT('%', $REF02, '%')
      AND MSTCUST.CUSTCD = $KEYWORD;

-- *****************************************************************************
ELSEIF $GPCD = 'CUSTCD_OSC_HEAD' THEN

  SELECT '거래처코드' AS CODE, '거래처명' AS NAME;
  SELECT 100 AS CODE, 200 AS NAME;

ELSEIF $GPCD = 'CUSTCD_OSC_LIST' THEN

  SELECT B.CUSTCD AS CODE, B.CUSTNM AS NAME
    FROM MSTWARE AS A
    INNER JOIN MSTCUST AS B ON A.CUSTCD = B.CUSTCD
    WHERE A.FACTORYCD = '07' 
      AND A.USEYN = 'Y'
      AND (B.CUSTCD LIKE CONCAT('%', $KEYWORD, '%')
       OR B.CUSTNM LIKE CONCAT('%', $KEYWORD, '%')
       OR B.CUSTNMEN LIKE CONCAT('%', $KEYWORD, '%'));

ELSEIF $GPCD = 'CUSTCD_OSC_INFO' THEN

  SELECT B.CUSTCD AS CODE, B.CUSTNM AS NAME
    FROM MSTWARE AS A
    INNER JOIN MSTCUST AS B ON A.CUSTCD = B.CUSTCD
    WHERE A.FACTORYCD = '07' 
      AND A.USEYN = 'Y'
      AND B.CUSTCD = $KEYWORD;

-- *****************************************************************************
ELSEIF $GPCD = 'CUSTITEM_HEAD' THEN

  SELECT '거래처코드' AS CODE, '거래처명' AS NAME, '영문명' AS REF01;
  SELECT 100 AS CODE, 200 AS NAME, 100 AS REF01;

ELSEIF $GPCD = 'CUSTITEM_LIST' THEN
  
  SELECT MSTCUSTITEM.CUSTCD AS CODE, MSTCUST.CUSTNM AS NAME, MSTCUST.CUSTNMEN AS REF01
    FROM MSTCUSTITEM
    LEFT JOIN MSTCUST ON MSTCUSTITEM.CUSTCD = MSTCUST.CUSTCD
    WHERE MSTCUSTITEM.ITEMCD = $REF01
      AND (MSTCUSTITEM.CUSTCD LIKE CONCAT('%', $KEYWORD, '%')
        OR MSTCUST.CUSTNM LIKE CONCAT('%', $KEYWORD, '%')
      )
      LIMIT 100;

ELSEIF $GPCD = 'CUSTITEM_INFO' THEN

  SELECT MSTCUSTITEM.CUSTCD AS CODE,  MSTCUST.CUSTNM AS NAME
    FROM MSTCUSTITEM
    LEFT JOIN MSTCUST ON MSTCUSTITEM.CUSTCD = MSTCUST.CUSTCD
    WHERE MSTCUSTITEM.ITEMCD = $REF01
      AND MSTCUSTITEM.CUSTCD = $KEYWORD;

-- *****************************************************************************
ELSEIF $GPCD = 'EMPCD_HEAD' THEN

  SELECT '사원코드' AS CODE, '사원명' AS NAME;
  SELECT 100 AS CODE, 100 AS NAME;

ELSEIF $GPCD = 'EMPCD_LIST' THEN
  
  SELECT MSTEMP.EMPCD AS CODE, MSTEMP.EMPNM AS NAME
    FROM MSTEMP
    WHERE FACTORYCD = '07'
    LIMIT 100;

ELSEIF $GPCD = 'EMPCD_INFO' THEN

    SELECT MSTEMP.EMPCD AS CODE, MSTEMP.EMPNM AS NAME
      FROM MSTEMP
      WHERE FACTORYCD = '07'
        AND EMPCD = $KEYWORD;

-- *****************************************************************************
ELSEIF $GPCD = 'TMLEMP_HEAD' THEN

  SELECT '사원코드' AS CODE, '사원명' AS NAME, '단말기명' AS REF01;
  SELECT 100 AS CODE, 100 AS NAME, 100 AS REF01;

ELSEIF $GPCD = 'TMLEMP_LIST' THEN
  
  SELECT MSTEMP.EMPCD AS CODE, MSTEMP.EMPNM AS NAME, MSTTMLEMP.TMLCD AS REF01
    FROM MSTTMLEMP
    LEFT JOIN MSTEMP ON MSTTMLEMP.EMPCD = MSTEMP.EMPCD
    WHERE MSTTMLEMP.TMLCD LIKE CONCAT('%', $REF01, '%')
      AND MSTEMP.EMPSTT <> '9'
    AND (MSTEMP.EMPCD LIKE CONCAT('%', $KEYWORD, '%')
      OR MSTEMP.EMPNM LIKE CONCAT('%', $KEYWORD, '%')
      OR MSTEMP.ENNM LIKE CONCAT('%', $KEYWORD, '%'))
    LIMIT 100;

ELSEIF $GPCD = 'TMLEMP_INFO' THEN

    SELECT MSTEMP.EMPCD AS CODE, MSTEMP.EMPNM AS NAME
      FROM MSTTMLEMP
      LEFT JOIN MSTEMP ON MSTTMLEMP.EMPCD = MSTEMP.EMPCD
      WHERE MSTTMLEMP.TMLCD LIKE CONCAT('%', $REF01, '%')
        AND MSTEMP.EMPSTT <> '9'
        AND MSTEMP.EMPCD = $KEYWORD;

-- *****************************************************************************
ELSEIF $GPCD = 'EQMCD_HEAD' THEN
  
  SELECT '설비코드' AS CODE, '설비명' AS NAME, '호기명' AS REF01;
  SELECT 100 AS CODE, 150 AS NAME, 100 AS REF01;

ELSEIF $GPCD = 'EQMCD_LIST' THEN

  IF $REF02 <> '' THEN

    -- 기타점검 설비 목록
    SELECT MSTEQM.EQMCD AS CODE, MSTEQM.EQMNM AS NAME, MSTEQM.EQMNO AS REF01
      FROM MSTEQM
      WHERE MSTEQM.EQMTP IN ('15', '16', '17', '99')
        AND MSTEQM.EQMTP <> '91'
        AND (MSTEQM.EQMCD LIKE CONCAT('%', $KEYWORD, '%')
        OR MSTEQM.EQMNM LIKE CONCAT('%', $KEYWORD, '%')
        OR MSTEQM.EQMNO LIKE CONCAT('%', $KEYWORD, '%'))
      LIMIT 100;

  ELSEIF $REF03 <> '' THEN

    SELECT MSTEQM.EQMCD AS CODE, MSTEQM.EQMNM AS NAME, MSTEQM.EQMNO AS REF01
      FROM MSTEQM
      WHERE MSTEQM.PRCCD LIKE CONCAT('%', $REF03, '%')
        AND MSTEQM.EQMTP <> '91'
        AND (MSTEQM.EQMCD LIKE CONCAT('%', $KEYWORD, '%')
        OR MSTEQM.EQMNM LIKE CONCAT('%', $KEYWORD, '%')
        OR MSTEQM.EQMNO LIKE CONCAT('%', $KEYWORD, '%'))
      LIMIT 100;

  ELSE

    SELECT MSTEQM.EQMCD AS CODE, MSTEQM.EQMNM AS NAME, MSTEQM.EQMNO AS REF01
      FROM MSTEQM
      WHERE MSTEQM.EQMTP LIKE CONCAT('%', $REF01, '%')
        AND MSTEQM.EQMTP <> '91'
        AND (MSTEQM.EQMCD LIKE CONCAT('%', $KEYWORD, '%')
        OR MSTEQM.EQMNM LIKE CONCAT('%', $KEYWORD, '%')
        OR MSTEQM.EQMNO LIKE CONCAT('%', $KEYWORD, '%'))
      LIMIT 100;

  END IF;

  ELSEIF $GPCD = 'EQMCD_INFO' THEN

    SELECT MSTEQM.EQMCD AS CODE, MSTEQM.EQMNM AS NAME
    FROM MSTEQM
      WHERE MSTEQM.EQMTP LIKE CONCAT('%', $REF01, '%')
        AND MSTEQM.EQMCD = $KEYWORD;

-- *****************************************************************************

  ELSEIF $GPCD = 'EQMFANO_HEAD' THEN

  SELECT '설비코드' AS CODE, '설비명' AS NAME;
  SELECT 100 AS CODE, 150 AS NAME, 100 AS REF01;
  SELECT 7 AS EVENTLENGTH;

  ELSEIF $GPCD = 'EQMFANO_LIST' THEN
  
    SELECT 
      MSTEQM.FANO AS CODE, MSTEQM.EQMNM AS NAME
    FROM MSTEQM
    LEFT JOIN MSTEQM_MATCH ON MSTEQM.FANO = MSTEQM_MATCH.FANO
    WHERE (MSTEQM.FANO LIKE CONCAT('%', $KEYWORD, '%')
      OR MSTEQM.EQMNM LIKE CONCAT('%', $KEYWORD, '%'))
      AND MSTEQM_MATCH.EQMCD LIKE CONCAT('%', $REF01, '%')
     LIMIT 100;
  
  ELSEIF $GPCD = 'EQMFANO_INFO' THEN

    SELECT FANO AS CODE, EQMNM AS NAME
    FROM MSTEQM
    WHERE FANO = $KEYWORD;

-- *****************************************************************************
ELSEIF $GPCD = 'WARECD_HEAD' THEN
  
  SELECT '창고코드' AS CODE, '창고명' AS NAME;
  SELECT 100 AS CODE, 150 AS NAME;

ELSEIF $GPCD = 'WARECD_LIST' THEN

  SELECT MSTWARE.WARECD AS CODE, MSTWARE.WARENM AS NAME
    FROM MSTWARE
    WHERE MSTWARE.WARETP LIKE CONCAT('%', $REF01, '%')
      AND (MSTWARE.WARECD LIKE CONCAT('%', $KEYWORD, '%')
      OR MSTWARE.WARENM LIKE CONCAT('%', $KEYWORD, '%'))
    LIMIT 100;

ELSEIF $GPCD = 'WARECD_INFO' THEN

    SELECT MSTWARE.WARECD AS CODE, MSTWARE.WARENM AS NAME
    FROM MSTWARE
      WHERE MSTWARE.WARETP LIKE CONCAT('%', $REF01, '%')
        AND MSTWARE.WARECD = $KEYWORD;

-- *****************************************************************************
ELSEIF $GPCD = 'TOOLCD_HEAD' THEN
  
  SELECT '금형코드' AS CODE, '금형명' AS NAME, '캐비티' AS REF01;
  SELECT 100 AS CODE, 150 AS NAME, 80 AS REF01;

ELSEIF $GPCD = 'TOOLCD_LIST' THEN

  IF $REF02 <> '' THEN

    SELECT MSTTOOL.TOOLCD AS CODE, MSTTOOL.TOOLNM AS NAME, MSTTOOL.MAXCAVITY AS REF01
      FROM MSTTOOL
      WHERE MSTTOOL.TOOLTP IN ('IP', 'IQ', 'IR')
        AND (MSTTOOL.TOOLCD LIKE CONCAT('%', $KEYWORD, '%')
        OR MSTTOOL.TOOLNM LIKE CONCAT('%', $KEYWORD, '%'))
      LIMIT 100;

  ELSEIF $REF03 <> '' THEN

    SELECT MSTTOOL.TOOLCD AS CODE, MSTTOOL.TOOLNM AS NAME, MSTTOOL.MAXCAVITY AS REF01
      FROM MSTTOOL
      WHERE MSTTOOL.TOOLTP IN ('IM', 'IN', 'IO')
        AND (MSTTOOL.TOOLCD LIKE CONCAT('%', $KEYWORD, '%')
        OR MSTTOOL.TOOLNM LIKE CONCAT('%', $KEYWORD, '%'))
      LIMIT 100;
  ELSE

    SELECT MSTTOOL.TOOLCD AS CODE, MSTTOOL.TOOLNM AS NAME, MSTTOOL.MAXCAVITY AS REF01
      FROM MSTTOOL
      WHERE MSTTOOL.TOOLTP LIKE CONCAT('%', $REF01, '%')
        AND (MSTTOOL.TOOLCD LIKE CONCAT('%', $KEYWORD, '%')
        OR MSTTOOL.TOOLNM LIKE CONCAT('%', $KEYWORD, '%'))
      LIMIT 100;

  END IF;

ELSEIF $GPCD = 'TOOLCD_INFO' THEN

  SELECT MSTTOOL.TOOLCD AS CODE, MSTTOOL.TOOLNM AS NAME
    FROM MSTTOOL
      WHERE MSTTOOL.TOOLTP LIKE CONCAT('%', $REF01, '%')
        AND MSTTOOL.TOOLCD = $KEYWORD;

-- *****************************************************************************
ELSEIF $GPCD = 'TOOLITEM_HEAD' THEN
  
  SELECT '금형코드' AS CODE, '금형명' AS NAME, '캐비티' AS REF01;
  SELECT 100 AS CODE, 150 AS NAME, 80 AS REF01;

ELSEIF $GPCD = 'TOOLITEM_LIST' THEN

  SELECT MSTTOOLITEM.TOOLCD AS CODE, MSTTOOL.TOOLNM AS NAME, MSTTOOL.MAXCAVITY AS REF01
    FROM MSTTOOLITEM
    LEFT JOIN MSTTOOL ON MSTTOOLITEM.TOOLCD = MSTTOOL.TOOLCD
    WHERE MSTTOOLITEM.ITEMCD = $REF01
      AND MSTTOOL.TOOLTP NOT IN ('IP','IQ','IR')
      AND (MSTTOOLITEM.TOOLCD LIKE CONCAT('%', $KEYWORD, '%')
      OR MSTTOOL.TOOLNM LIKE CONCAT('%', $KEYWORD, '%'))
    LIMIT 100;

ELSEIF $GPCD = 'TOOLITEM_INFO' THEN

  SELECT MSTTOOLITEM.TOOLCD AS CODE, MSTTOOL.TOOLNM AS NAME
    FROM MSTTOOLITEM
    LEFT JOIN MSTTOOL ON MSTTOOLITEM.TOOLCD = MSTTOOL.TOOLCD
      WHERE MSTTOOLITEM.ITEMCD = $REF01
        AND MSTTOOL.TOOLTP NOT IN ('IP','IQ','IR')
        AND MSTTOOLITEM.TOOLCD = $KEYWORD;

-- *****************************************************************************
ELSEIF $GPCD = 'AUTCD_HEAD' THEN
  
  SELECT '권한코드' AS CODE, '권한명' AS NAME;
  SELECT 100 AS CODE, 150 AS NAME;

ELSEIF $GPCD = 'AUTCD_LIST' THEN

  SELECT SYSAUT.AUTCD AS CODE, SYSAUT.AUTNM AS NAME
    FROM SYSAUT
    WHERE (SYSAUT.AUTCD LIKE CONCAT('%', $KEYWORD, '%')
      OR SYSAUT.AUTNM LIKE CONCAT('%', $KEYWORD, '%'))
    LIMIT 100;

ELSEIF $GPCD = 'AUTCD_INFO' THEN

  SELECT SYSAUT.AUTCD AS CODE, SYSAUT.AUTNM AS NAME
    FROM SYSAUT
    WHERE SYSAUT.AUTCD = $KEYWORD;

-- *****************************************************************************
  ELSEIF $GPCD = 'BADCD_HEAD' THEN

    SELECT '불량코드' AS CODE, '불량명' AS NAME, '공장구분' AS REF01, '대분류' AS REF02, '중분류' AS REF03;
    SELECT 100 AS CODE, 150 AS NAME, 100 AS REF01, 100 AS REF02, 100 AS REF03;

  ELSEIF $GPCD = 'BADCD_LIST' THEN
  
    SELECT 
        MSTBAD.BADCD AS CODE
      , MSTBAD.BADNM AS NAME
      , MSTFACTORY.FACTORYNM AS REF01
      , GPCD('QM210', MSTBAD.BADTP1) AS REF02
      , GPCD('QM220', MSTBAD.BADTP2) AS REF03
    FROM MSTBAD
    INNER JOIN MSTFACTORY
      ON MSTFACTORY.FACTORYCD = MSTBAD.M20
    WHERE MSTBAD.USEYN = 'Y'
      AND (MSTBAD.BADCD LIKE CONCAT('%', $KEYWORD, '%')
      OR MSTBAD.BADNM LIKE CONCAT('%', $KEYWORD, '%'))
      AND MSTBAD.M20 LIKE CONCAT('%', $REF01, '%')
      AND MSTBAD.BADTP1 LIKE CONCAT('%', $REF02, '%')
      AND MSTBAD.BADTP2 LIKE CONCAT('%', $REF03, '%')    
    ORDER BY MSTBAD.BADTP1, MSTBAD.BADTP2, MSTBAD.BADCD 
    ;
  
  ELSEIF $GPCD = 'BADCD_INFO' THEN
  
    SELECT MSTBAD.BADCD AS CODE, MSTBAD.BADNM AS NAME
      FROM MSTBAD
      WHERE MSTBAD.BADCD = $KEYWORD;
-- *****************************************************************************
ELSEIF $GPCD = 'IQCLOT_HEAD' THEN
  
  SELECT 'LOT번호' AS CODE, '품목코드' AS NAME, '품명' AS REF01, '대기수량' AS REF02;
  SELECT 120 AS CODE, 100 AS NAME, 200 AS REF01, 80 AS REF02;

ELSEIF $GPCD = 'IQCLOT_LIST' THEN

  SELECT MTRINLOT.LOTKEY AS CODE, MTRIN.ITEMCD AS NAME, 
    GPCD('ITEMCD', MTRIN.ITEMCD) AS REF01, 
    CAST(MTRINLOT.LOTQTY AS DECIMAL(20, 2)) AS REF02
    FROM MTRINLOT
    LEFT JOIN MTRIN ON MTRIN.MTRINKEY = MTRINLOT.MTRINKEY
    LEFT JOIN MSTITEM ON MTRIN.ITEMCD = MSTITEM.ITEMCD
    LEFT JOIN TQMIQC ON MTRINLOT.LOTKEY = TQMIQC.LOTKEY
    WHERE TQMIQC.LOTKEY IS NULL 
      AND (MTRINLOT.PRDDATE >= $REF02 AND MTRINLOT.PRDDATE <= $REF03)
      AND MTRINLOT.INYN = 'N'
      AND (MTRINLOT.LOTKEY LIKE CONCAT('%', $KEYWORD, '%')
      OR MTRIN.MTRINKEY LIKE CONCAT('%', $KEYWORD, '%')
      OR MTRIN.ITEMCD LIKE CONCAT('%', $KEYWORD, '%')
      OR MSTITEM.ITEMNM LIKE CONCAT('%', $KEYWORD, '%'))
    LIMIT 100;

ELSEIF $GPCD = 'IQCLOT_INFO' THEN

  SELECT MTRINLOT.LOTKEY AS CODE,
    CONCAT(CAST(MTRINLOT.LOTQTY AS DECIMAL(20, 2)), '/', MTRIN.ITEMCD, '/', IFNULL(MSTITEM.ITEMNM, '')) AS NAME
    FROM MTRINLOT
    LEFT JOIN MTRIN ON MTRIN.MTRINKEY = MTRINLOT.MTRINKEY
    LEFT JOIN MSTITEM ON MTRIN.ITEMCD = MSTITEM.ITEMCD
    LEFT JOIN TQMIQC ON MTRINLOT.LOTKEY = TQMIQC.LOTKEY
    WHERE TQMIQC.LOTKEY IS NULL 
      AND MTRINLOT.LOTKEY = $KEYWORD
      AND (MTRINLOT.PRDDATE >= $REF02 AND MTRINLOT.PRDDATE <= $REF03);

-- ****************************************************************************
ELSEIF $GPCD = 'SLCLOT_HEAD' THEN
  
  SELECT 'LOT번호' AS CODE, '품목코드' AS NAME, '품명' AS REF01, '대기수량' AS REF02;
  SELECT 120 AS CODE, 100 AS NAME, 200 AS REF01, 80 AS REF02;

ELSEIF $GPCD = 'SLCLOT_LIST' THEN

  SELECT 
    TQMSILICONE.LOTKEY AS CODE, COMLOT.ITEMCD AS NAME, 
    GPCD('ITEMCD', COMLOT.ITEMCD) AS REF01, 
    CAST(TQMSILICONE.LOTQTY AS DECIMAL(20, 2)) AS REF02
    FROM TQMSILICONE
    LEFT JOIN COMLOT ON TQMSILICONE.LOTKEY = COMLOT.LOTKEY
    WHERE TQMSILICONE.IQCYN ='N'    
      AND (COMLOT.ITEMCD LIKE CONCAT('%', $KEYWORD, '%')
       OR TQMSILICONE.LOTKEY LIKE CONCAT('%', $KEYWORD, '%'))
      AND TQMSILICONE.PRDDATE >= $REF02 
