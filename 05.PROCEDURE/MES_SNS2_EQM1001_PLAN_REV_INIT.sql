  PLANTP, PLANCD, REVNUM, APRVSTT, REMARK,
  RTIME, REMP, RPRG
)
SELECT
  'G', GRP_REV.PLANCD, 1, '', '',
  DATE_FORMAT(NOW(), '%Y-%m-%d %H:%i:%s'), 'SYSTEM', 'EQM1001_PLAN_REV_INIT'
FROM `MES_SNS2`.`MSTEQMREV_HEADER` GRP_REV
INNER JOIN (
  SELECT MSTEQM.EQMGUBUN
  FROM `MES_SNS2`.`MSTEQM`
  INNER JOIN `MES_SNS2`.`MSTEQMREV_HEADER` EQM_REV
    ON EQM_REV.PLANTP = 'E'
   AND EQM_REV.PLANCD = MSTEQM.FANO
   AND EQM_REV.REVNUM = 0
   AND EQM_REV.APRVSTT <> 'A'
  WHERE MSTEQM.USEYN = 'Y'
  GROUP BY MSTEQM.EQMGUBUN
) GRP_UNAPRV
  ON GRP_UNAPRV.EQMGUBUN = GRP_REV.PLANCD
LEFT JOIN `MES_SNS2`.`MSTEQMREV_HEADER` EXIST_REV
  ON EXIST_REV.PLANTP = 'G'
 AND EXIST_REV.PLANCD = GRP_REV.PLANCD
 AND EXIST_REV.REVNUM = 1
WHERE GRP_REV.PLANTP = 'G'
  AND GRP_REV.REVNUM = 0
  AND GRP_REV.APRVSTT = 'A'
  AND EXIST_REV.PLANCD IS NULL;

