-- 설비 REV.0 : 승인·반려는 현재 승인 상태를 옮기고, 승인 이력이 없으면 대기
INSERT INTO `MES_SNS2`.`MSTEQMREV_HEADER` (
  PLANTP, PLANCD, REVNUM, APRVSTT, REMARK,
  REQTIME, REQEMP, REQPRG,
  APRVTIME, APRVEMP, APRVPRG, REJREASON,
  RTIME, REMP, RPRG
)
SELECT
  'E', MSTEQM.FANO, 0,
  CASE WHEN EQM_APRV.APRVSTT IN ('A', 'R') THEN EQM_APRV.APRVSTT ELSE '' END,
  '제정',
  COALESCE(EQM_APRV.REQTIME, ''), COALESCE(EQM_APRV.REQEMP, ''), COALESCE(EQM_APRV.REQPRG, ''),
  COALESCE(EQM_APRV.APRVTIME, ''), COALESCE(EQM_APRV.APRVEMP, ''), COALESCE(EQM_APRV.APRVPRG, ''), COALESCE(EQM_APRV.REJREASON, ''),
  DATE_FORMAT(NOW(), '%Y-%m-%d %H:%i:%s'), 'SYSTEM', 'EQM1001_PLAN_REV_INIT'
FROM `MES_SNS2`.`MSTEQM`
INNER JOIN (
  SELECT CHKPLANEQM.EQMCD AS FANO
  FROM `MES_SNS2`.`CHKPLANEQM`
  WHERE CHKPLANEQM.CHKTP = '02'
  UNION
  SELECT CHKPLANEQM_APRV.PLANCD
  FROM `MES_SNS2`.`CHKPLANEQM_APRV`
  WHERE CHKPLANEQM_APRV.PLANTP = 'E'
) EQM_PLAN
  ON EQM_PLAN.FANO = MSTEQM.FANO
LEFT JOIN `MES_SNS2`.`CHKPLANEQM_APRV` EQM_APRV
  ON EQM_APRV.PLANTP = 'E'
 AND EQM_APRV.PLANCD = MSTEQM.FANO
LEFT JOIN `MES_SNS2`.`MSTEQMREV_HEADER` EXIST_REV
  ON EXIST_REV.PLANTP = 'E'
 AND EXIST_REV.PLANCD = MSTEQM.FANO
WHERE MSTEQM.USEYN = 'Y'
  AND EXIST_REV.PLANCD IS NULL;

