  SELECT CHKPLANEQM_APRV.PLANCD
  FROM `MES_SNS2`.`CHKPLANEQM_APRV`
  WHERE CHKPLANEQM_APRV.PLANTP = 'G'
) GRP_PLAN
LEFT JOIN `MES_SNS2`.`CHKPLANEQM_APRV` GRP_APRV
  ON GRP_APRV.PLANTP = 'G'
 AND GRP_APRV.PLANCD = GRP_PLAN.EQMGUBUN
LEFT JOIN `MES_SNS2`.`MSTEQMREV_HEADER` EXIST_REV
  ON EXIST_REV.PLANTP = 'G'
 AND EXIST_REV.PLANCD = GRP_PLAN.EQMGUBUN
WHERE EXIST_REV.PLANCD IS NULL;

