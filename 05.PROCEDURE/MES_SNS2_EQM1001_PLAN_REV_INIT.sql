FROM (
  SELECT MSTEQM.EQMGUBUN
  FROM `MES_SNS2`.`MSTEQM`
  INNER JOIN `MES_SNS2`.`CHKPLANEQM`
    ON CHKPLANEQM.EQMCD = MSTEQM.FANO
   AND CHKPLANEQM.CHKTP = '02'
