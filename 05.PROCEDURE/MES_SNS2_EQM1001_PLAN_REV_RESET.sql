-- 전환 작업 시 점검계획·점검실적 등록을 중지한 상태에서 전체 스크립트로 실행
-- 점검실적 내용, CHKPLANEQM, 월별 주기계획, 기준정보 및 발번값은 유지
-- 기존 PLAN_REV_INIT은 CHKPLANEQM에서 REV를 다시 생성하므로 초기화 후 재실행 금지

-- 초기화 전 확인
SELECT 'MSTEQMREV_HEADER' AS TABLENAME, COUNT(*) AS ROWCNT FROM MES_SNS2.MSTEQMREV_HEADER
UNION ALL
SELECT 'MSTEQMREV_DETAIL', COUNT(*) FROM MES_SNS2.MSTEQMREV_DETAIL
UNION ALL
SELECT 'CHKPLANEQM_APRV', COUNT(*) FROM MES_SNS2.CHKPLANEQM_APRV
UNION ALL
SELECT 'CHKRSTEQM_REVCD', COUNT(*) FROM MES_SNS2.CHKRSTEQM WHERE REVCD IS NOT NULL AND REVCD <> '';

DELIMITER $$
BEGIN NOT ATOMIC
  DECLARE _$RSTCNT INT DEFAULT 0;
  DECLARE _$APRVCNT INT DEFAULT 0;
  DECLARE _$DETAILCNT INT DEFAULT 0;
  DECLARE _$HEADERCNT INT DEFAULT 0;
  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    ROLLBACK;
    RESIGNAL;
  END;

  START TRANSACTION;

  -- 실적은 보존하고 제거할 REV와의 연결만 초기화
  UPDATE MES_SNS2.CHKRSTEQM SET REVCD = ''
  WHERE REVCD IS NOT NULL AND REVCD <> '';
  SET _$RSTCNT = ROW_COUNT();

  -- 전환 후 추가된 그룹 REV 연결도 초기화; 기존 스키마에서도 실행 가능
  IF EXISTS (SELECT 1 FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = 'MES_SNS2' AND TABLE_NAME = 'CHKRSTEQM' AND COLUMN_NAME = 'GRPREVCD') THEN
    SET @RESET_GRP_REV = 'UPDATE MES_SNS2.CHKRSTEQM SET GRPREVCD = '''' WHERE GRPREVCD <> ''''';
    PREPARE RESET_GRP_REV FROM @RESET_GRP_REV;
    EXECUTE RESET_GRP_REV;
    DEALLOCATE PREPARE RESET_GRP_REV;
  END IF;

  DELETE FROM MES_SNS2.CHKPLANEQM_APRV;
  SET _$APRVCNT = ROW_COUNT();

  DELETE FROM MES_SNS2.MSTEQMREV_DETAIL;
  SET _$DETAILCNT = ROW_COUNT();

  DELETE FROM MES_SNS2.MSTEQMREV_HEADER;
  SET _$HEADERCNT = ROW_COUNT();

  COMMIT;

  SELECT _$RSTCNT AS RESET_RST_REV, _$APRVCNT AS DELETE_APRV,
         _$DETAILCNT AS DELETE_DETAIL, _$HEADERCNT AS DELETE_HEADER;
END $$
DELIMITER ;

-- 초기화 후 확인: 각 건수 0
