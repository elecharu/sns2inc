-- EQM1001_R01 프로시저 저장 전에 MES_SNS2에서 1번 → 2번 → 3번 순서로 실행 (1·2번을 이미 반영한 DB는 3번만 실행)
-- 1·2번은 기존 데이터를 변경하지 않음 (추가 컬럼은 빈값 '', 고장현상·처리내용은 길이만 100 → 1000)
-- 3번은 이미 저장한 사용 부품의 출고일자(출고 부품만)와 단위(단위명 → 공통코드)를 채움
-- 되돌릴 때는 파일 아래 [롤백] 부분만 실행 (파일 전체를 한 번에 실행하면 추가 후 바로 롤백됨)

USE MES_SNS2;

-- 1. 설비/금형 수리정보(EQMREP) 공무작업일지 항목
--    고장현상/작업내용 = MALFUNCTION, 조치내역 = HANDLE (긴 글 입력을 위해 1000자로 확장)
ALTER TABLE EQMREP
  MODIFY COLUMN MALFUNCTION VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '고장현상',
  MODIFY COLUMN HANDLE      VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '처리내용',
  ADD COLUMN WORKTP    VARCHAR(20)   NOT NULL DEFAULT '' COMMENT '작업구분 (공통코드 FM300)' AFTER EQMREPTP,
  ADD COLUMN FAILTP    VARCHAR(20)   NOT NULL DEFAULT '' COMMENT '고장유형 (공통코드 FM307)' AFTER WORKTP,
  ADD COLUMN FAILPART  VARCHAR(20)   NOT NULL DEFAULT '' COMMENT '고장부위 (공통코드 FM303)' AFTER FAILTP,
  ADD COLUMN STOPTP    VARCHAR(20)   NOT NULL DEFAULT '' COMMENT '중단구분 (공통코드 FM304)' AFTER FAILPART,
  ADD COLUMN PRDNONKEY VARCHAR(20)   NOT NULL DEFAULT '' COMMENT '비가동키 (PRDRSTNON)' AFTER STOPTP,
  ADD COLUMN CAUSE     VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '원인분석' AFTER ISSUE,
  ADD COLUMN PREVENT   VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '특이사항 및 재발방지대책' AFTER CAUSE;

-- 2. 설비수리 사용 자재·부품 (출고 부품 = 설비부품 출고이력 연결, 스페셜 부품 = 기준정보 없이 직접 입력)
CREATE TABLE EQMREP_PART (
  EQMREPKEY VARCHAR(20)    NOT NULL DEFAULT '' COMMENT '설비수리키',
  SEQ       INT(4)         NOT NULL DEFAULT 0  COMMENT '순번',
  PARTTP    VARCHAR(10)    NOT NULL DEFAULT '' COMMENT '부품구분 (OUT 출고부품, SPECIAL 스페셜부품)',
  INOUTKEY  VARCHAR(100)   NOT NULL DEFAULT '' COMMENT '설비부품 출고키 (INOUT_EQMPARTS, 스페셜부품은 빈값)',
  ITEMID    VARCHAR(100)   NOT NULL DEFAULT '' COMMENT '설비부품ID (MSTITEM, 스페셜부품은 빈값)',
  PARTNM    VARCHAR(100)   NOT NULL DEFAULT '' COMMENT '부품명',
  PARTSPEC  VARCHAR(100)   NOT NULL DEFAULT '' COMMENT '규격',
  PARTQTY   DECIMAL(20,8)  NOT NULL DEFAULT 0  COMMENT '수량',
  PARTUNIT  VARCHAR(10)    NOT NULL DEFAULT '' COMMENT '단위',
  REMARK    VARCHAR(1000)  NOT NULL DEFAULT '' COMMENT '비고',
  RTIME     VARCHAR(19)    NOT NULL DEFAULT '' COMMENT '등록시간',
  REMP      VARCHAR(20)    NOT NULL DEFAULT '' COMMENT '등록자',
  RPRG      VARCHAR(100)   NOT NULL DEFAULT '' COMMENT '등록프로그램',
  MTIME     VARCHAR(19)    NOT NULL DEFAULT '' COMMENT '수정시간',
  MEMP      VARCHAR(20)    NOT NULL DEFAULT '' COMMENT '수정자',
  MPRG      VARCHAR(100)   NOT NULL DEFAULT '' COMMENT '수정프로그램',
  PRIMARY KEY (EQMREPKEY, SEQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COLLATE=utf8_general_ci COMMENT='설비수리 사용 자재·부품';

-- 3. (2026-11-20) 사용 자재·부품 출고일자 컬럼 추가, 단위는 공통코드(DM150) 코드값으로 저장
--    출고일자: 출고 부품은 출고이력 일자를 기본값으로 화면에서 수정, 스페셜 부품은 직접 입력
ALTER TABLE EQMREP_PART
  ADD COLUMN INOUTDATE VARCHAR(10) NOT NULL DEFAULT '' COMMENT '출고일자' AFTER ITEMID,
  MODIFY COLUMN PARTUNIT VARCHAR(10) NOT NULL DEFAULT '' COMMENT '단위 (공통코드 DM150)';

UPDATE EQMREP_PART AS P
INNER JOIN INOUT_EQMPARTS AS I ON I.INOUTKEY = P.INOUTKEY
   SET P.INOUTDATE = I.INOUTDATE
 WHERE P.PARTTP = 'OUT'
   AND P.INOUTDATE = '';

UPDATE EQMREP_PART AS P
INNER JOIN COMTYPE AS C ON C.GPCD = 'DM150' AND C.TPNM = P.PARTUNIT
   SET P.PARTUNIT = C.TPCD
 WHERE P.PARTUNIT <> '';

-- 확인
SELECT COLUMN_NAME, COLUMN_TYPE, COLUMN_COMMENT
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = 'MES_SNS2' AND TABLE_NAME = 'EQMREP'
  AND COLUMN_NAME IN ('WORKTP', 'FAILTP', 'FAILPART', 'STOPTP', 'PRDNONKEY', 'CAUSE', 'PREVENT', 'MALFUNCTION', 'HANDLE')
ORDER BY ORDINAL_POSITION;

SELECT COUNT(*) AS EQMREP_PART_COLS
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = 'MES_SNS2' AND TABLE_NAME = 'EQMREP_PART';

SELECT P.EQMREPKEY, P.SEQ, P.PARTTP, P.INOUTDATE, P.PARTNM, P.PARTUNIT, IFNULL(C.TPNM, '단위코드 없음') AS PARTUNITNM
FROM EQMREP_PART AS P
LEFT JOIN COMTYPE AS C ON C.GPCD = 'DM150' AND C.TPCD = P.PARTUNIT
ORDER BY P.EQMREPKEY, P.SEQ;

-- *****************************************************************************
-- [롤백] 위 1·2·3번을 원래대로 되돌림 (반영 후 되돌릴 때만 이 아래를 R1 → R4 순서로 실행, 3번 출고일자 컬럼은 R3 테이블 삭제로 함께 삭제)
-- 주의: 입력한 작업구분·고장유형·고장부위·중단구분·비가동·원인분석·재발방지대책·사용 부품 데이터는 삭제됨
--       고장현상·처리내용이 100자를 넘는 행이 있으면 R2가 오류로 멈춤(데이터 잘림 방지) → R1 결과를 100자 이내로 정리 후 다시 실행
--       롤백 후 EQM1001_R01·TML2050_R01 프로시저와 EQM1001_R01 SYSTEM_PARAMETERS도 이전 버전으로 다시 저장
-- *****************************************************************************

-- R1. 100자를 넘는 고장현상·처리내용 확인 (0건이어야 R2 실행 가능)
SELECT EQMREPKEY, CHAR_LENGTH(MALFUNCTION) AS MALFUNCTION_LEN, CHAR_LENGTH(HANDLE) AS HANDLE_LEN
FROM EQMREP
WHERE CHAR_LENGTH(MALFUNCTION) > 100
   OR CHAR_LENGTH(HANDLE) > 100;

-- R2. EQMREP 추가 컬럼 삭제, 고장현상·처리내용 1000 → 100자 (원래 정의)
ALTER TABLE EQMREP
  DROP COLUMN WORKTP,
  DROP COLUMN FAILTP,
  DROP COLUMN FAILPART,
  DROP COLUMN STOPTP,
  DROP COLUMN PRDNONKEY,
  DROP COLUMN CAUSE,
  DROP COLUMN PREVENT,
  MODIFY COLUMN MALFUNCTION VARCHAR(100) NOT NULL DEFAULT '' COMMENT '고장현상',
  MODIFY COLUMN HANDLE      VARCHAR(100) NOT NULL DEFAULT '' COMMENT '처리내용';

-- R3. 사용 자재·부품 테이블 삭제
DROP TABLE IF EXISTS EQMREP_PART;

-- R4. 롤백 확인 (추가 컬럼 0건, 고장현상·처리내용 varchar(100), EQMREP_PART 0건)
SELECT COLUMN_NAME, COLUMN_TYPE, COLUMN_COMMENT
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = 'MES_SNS2' AND TABLE_NAME = 'EQMREP'
  AND COLUMN_NAME IN ('WORKTP', 'FAILTP', 'FAILPART', 'STOPTP', 'PRDNONKEY', 'CAUSE', 'PREVENT', 'MALFUNCTION', 'HANDLE')
ORDER BY ORDINAL_POSITION;

SELECT COUNT(*) AS EQMREP_PART_TABLE
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = 'MES_SNS2' AND TABLE_NAME = 'EQMREP_PART';
