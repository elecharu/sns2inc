CREATE DEFINER=`root`@`%` PROCEDURE `MES_SNS2`.`EQM1001_R03`(
-- *****************************************************************************
-- Comment: 설비점검계획 
-- Create: 	2025-06-27  	생성 			이대규
-- Modify: 	2026-09-15 		마이그레이션	한성수
-- 			2026-09-16 					한성수	MSTEQM.FANO(설비코드) 컬럼 바인딩 변경
-- 			2026-09-21 					한성수	설비별·설비그룹 정기점검 조회/CRUD 추가 및 불필요 조인 단순화
-- 			2026-09-22 					한성수	설비그룹 재조회 선택 키를 EQMGUBUN 기준으로 정리
-- 			2026-09-23 					한성수	정기점검 주기관리 설비등급 조회 추가
-- 			2026-09-29 					한성수	설비그룹 점검계획 그룹코드 단위 변경, 승인상태·반려사유 표시 및 사전집계 튜닝
-- 			2026-09-30 					한성수	승인 리비전(REV) 기준 승인 검증 적용 및 점검항목·주기관리 코드명 반환 추가
-- 			2026-10-01 					한성수	설비그룹 없는 설비의 주기관리 조회·저장·삭제 지원 (설비 승인 기준)
-- 			2026-10-02 					한성수	주기관리 점검자 사원코드화·실적 월 잠금·승인본 대상 통일, 복사 검증 및 성능 개선
-- 			2026-10-06 					한성수	REV·승인·출력 R03 통합, 그룹 체크 제거·최신 REV 조회, DETAIL 중복 컬럼 제거·APRVKEY 이력 발번, 주기 승인 제한 해제·빈 개정내용 승인/반려 차단
-- 			2026-10-07 					한성수	표시 체크·전용 JOIN 제거, 중복 등록 방지, 양 탭 최신 REV·미등록 상태 공란, 최신 계획·REV별 최종 상태 개정이력 출력
-- *****************************************************************************
  IN $FANO           VARCHAR(20),
  IN $FANO_COPY      VARCHAR(20),
  IN $SYEAR          VARCHAR(50),
  IN $EQMGRP         VARCHAR(50),
  IN $CHKKNDCD_LIST  MEDIUMTEXT,
  IN $REMARK_LIST    MEDIUMTEXT,
  IN $USEYN_LIST     MEDIUMTEXT,
  IN $SORTNO_LIST    MEDIUMTEXT,
  IN $YEAR_LIST      MEDIUMTEXT,
  IN $FANO_LIST      MEDIUMTEXT,
  IN $M01_LIST       MEDIUMTEXT,
  IN $M02_LIST       MEDIUMTEXT,
  IN $M03_LIST       MEDIUMTEXT,
  IN $M04_LIST       MEDIUMTEXT,
  IN $M05_LIST       MEDIUMTEXT,
  IN $M06_LIST       MEDIUMTEXT,
  IN $M07_LIST       MEDIUMTEXT,
  IN $M08_LIST       MEDIUMTEXT,
  IN $M09_LIST       MEDIUMTEXT,
  IN $M10_LIST       MEDIUMTEXT,
  IN $M11_LIST       MEDIUMTEXT,
  IN $M12_LIST       MEDIUMTEXT,
  IN $PLANTP         CHAR(1),
  IN $PLANCD         VARCHAR(50),
  IN $REVNUM         VARCHAR(20),
  IN $REMARK         VARCHAR(1000),
  IN $APRVSTT        CHAR(1),
  IN $REJREASON      VARCHAR(1000),

-- *****************************************************************************
IN  $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  DECLARE _$CHKKNDCD      VARCHAR(20);
  DECLARE _$REMARK        VARCHAR(1000);
  DECLARE _$CHKTP         VARCHAR(20);
  DECLARE _$SORTNO        DECIMAL(20, 8);
  DECLARE _$MAXSORTNO     DECIMAL(20, 8);
  DECLARE _$USEYN         VARCHAR(2);

  DECLARE _$M01           VARCHAR(20);
  DECLARE _$M02           VARCHAR(20);
  DECLARE _$M03           VARCHAR(20);
  DECLARE _$M04           VARCHAR(20);
  DECLARE _$M05           VARCHAR(20);
  DECLARE _$M06           VARCHAR(20);
  DECLARE _$M07           VARCHAR(20);
  DECLARE _$M08           VARCHAR(20);
  DECLARE _$M09           VARCHAR(20);
  DECLARE _$M10           VARCHAR(20);
  DECLARE _$M11           VARCHAR(20);
  DECLARE _$M12           VARCHAR(20);
  DECLARE _$YEAR          VARCHAR(20);
  DECLARE _$FANO          VARCHAR(20);
  DECLARE _$LOCKMM        VARCHAR(100);
  DECLARE _$PLANTP        CHAR(1);
  DECLARE _$PLANCD        VARCHAR(50);
  DECLARE _$EQMGRPNM      VARCHAR(1000);
  DECLARE _$EQMCNT        INT;
  DECLARE _$COPYGRP       VARCHAR(50);
  DECLARE _$REVCD         VARCHAR(20);
  DECLARE _$REVNUM        INT;
  DECLARE _$APRVSTT       CHAR(1);
  DECLARE _$REVDATE       VARCHAR(10);
  DECLARE _$REJECT_CNT    INT DEFAULT 0;
  DECLARE _$REJECT_EQM    VARCHAR(1000);

-- 정기점검 CRUD 공통 승인 요청
IF $CALLTYPE IN ('REG_GRP_EQM02', 'SAVE_GRP_EQM02', 'DEL_GRP_EQM02', 'COPY_GRP_EQM02',
                 'REG_EQM02', 'SAVE_EQM02', 'DEL_EQM02', 'COPY_EQM02') THEN
  IF $CALLTYPE LIKE '%GRP%' THEN
    SET _$PLANTP = 'G';
    SET _$PLANCD = $EQMGRP;
    IF COALESCE(_$PLANCD, '') = '' THEN
      CALL COMERR('설비그룹을 지정해주세요.');
      LEAVE PROC;
    END IF;
  ELSE
    SET _$PLANTP = 'E';
    SET _$PLANCD = $FANO;
    IF COALESCE(_$PLANCD, '') = '' THEN
      CALL COMERR('설비를 지정해주세요.');
      LEAVE PROC;
    END IF;
  END IF;

  IF $CALLTYPE IN ('COPY_GRP_EQM02', 'COPY_EQM02') AND COALESCE($FANO_COPY, '') = '' THEN
    CALL COMERR(CASE WHEN _$PLANTP = 'G' THEN '복사할 설비그룹을 지정해주세요.' ELSE '복사할 설비를 지정해주세요.' END);
    LEAVE PROC;
  END IF;

  -- 수정 대상과 연동 대상(설비그룹이면 소속 설비, 설비면 소속 설비그룹)의 반려·대기 리비전은 같은 번호로 다시 대기
  UPDATE MSTEQMREV_HEADER
  INNER JOIN (
    SELECT _$PLANTP AS PLANTP, _$PLANCD AS PLANCD
    UNION ALL
    SELECT 'E', MSTEQM.FANO FROM MSTEQM WHERE _$PLANTP = 'G' AND MSTEQM.EQMGUBUN = _$PLANCD AND MSTEQM.USEYN = 'Y'
    UNION ALL
    SELECT 'G', MSTEQM.EQMGUBUN FROM MSTEQM WHERE _$PLANTP = 'E' AND MSTEQM.FANO = _$PLANCD AND MSTEQM.EQMGUBUN <> ''
  ) PLAN_KEY
    ON PLAN_KEY.PLANTP = MSTEQMREV_HEADER.PLANTP
   AND PLAN_KEY.PLANCD = MSTEQMREV_HEADER.PLANCD
  SET
    MSTEQMREV_HEADER.APRVSTT = '',
    MSTEQMREV_HEADER.APRVTIME = '',
    MSTEQMREV_HEADER.APRVEMP  = '',
    MSTEQMREV_HEADER.APRVPRG  = '',
    MSTEQMREV_HEADER.REJREASON = '',
    MSTEQMREV_HEADER.REQTIME = CALLTIME(),
    MSTEQMREV_HEADER.REQEMP  = CALLEMP(),
    MSTEQMREV_HEADER.REQPRG  = CALLPRG(),
    MSTEQMREV_HEADER.MTIME   = CALLTIME(),
    MSTEQMREV_HEADER.MEMP    = CALLEMP(),
    MSTEQMREV_HEADER.MPRG    = CALLPRG()
  WHERE MSTEQMREV_HEADER.APRVSTT <> 'A';

  -- 마지막 리비전이 승인이거나 없으면 다음 번호로 대기 리비전 생성 (처음은 0: 제정)
  INSERT INTO MSTEQMREV_HEADER (
    REVCD, PLANTP, PLANCD, REVNUM, APRVSTT,
    REQTIME, REQEMP, REQPRG,
    RTIME, REMP, RPRG
  )
  SELECT
    GETKEY('REVCD'), PLAN_KEY.PLANTP, PLAN_KEY.PLANCD, COALESCE(LAST_REV.REVNUM + 1, 0), '',
    CALLTIME(), CALLEMP(), CALLPRG(),
    CALLTIME(), CALLEMP(), CALLPRG()
  FROM (
    SELECT _$PLANTP AS PLANTP, _$PLANCD AS PLANCD
    UNION ALL
    SELECT 'E', MSTEQM.FANO FROM MSTEQM WHERE _$PLANTP = 'G' AND MSTEQM.EQMGUBUN = _$PLANCD AND MSTEQM.USEYN = 'Y'
    UNION ALL
    SELECT 'G', MSTEQM.EQMGUBUN FROM MSTEQM WHERE _$PLANTP = 'E' AND MSTEQM.FANO = _$PLANCD AND MSTEQM.EQMGUBUN <> ''
  ) PLAN_KEY
  LEFT JOIN (
    SELECT PLANTP, PLANCD, MAX(REVNUM) AS REVNUM,
           MAX(CASE WHEN APRVSTT <> 'A' THEN REVNUM END) AS OPENREVNUM
    FROM MSTEQMREV_HEADER
    GROUP BY PLANTP, PLANCD
  ) LAST_REV
    ON LAST_REV.PLANTP = PLAN_KEY.PLANTP
   AND LAST_REV.PLANCD = PLAN_KEY.PLANCD
  WHERE LAST_REV.OPENREVNUM IS NULL
     OR LAST_REV.OPENREVNUM < LAST_REV.REVNUM;
END IF;

CASE $CALLTYPE
-- *****************************************************************************
WHEN 'LIST_MSTEQM_GRP' THEN -- 설비그룹 최신 리비전 조회
  -- 같은 이름의 그룹코드 함께 조회
  SET _$EQMGRPNM = (SELECT TPNM FROM COMTYPE WHERE GPCD = 'FM116' AND TPCD = $EQMGRP LIMIT 1);

  SELECT
    GRP_EQM.EQMGUBUN,
    COMTYPE.TPNM AS EQMGRPNM,
    COMTYPE.SORTNO AS EQMGRPSORTNO,
    PLAN_REV.REVCD,
    COALESCE(CONCAT('REV.', PLAN_REV.REVNUM), '') AS REVNM,
    CASE
      WHEN PLAN_REV.REVCD IS NULL OR PLAN_REV.REVCD = '' THEN ''
      WHEN PLAN_REV.APRVSTT = 'A' THEN '승인'
      WHEN PLAN_REV.APRVSTT = 'R' THEN '반려'
      ELSE '대기'
    END AS APRVSTTNM,
    COALESCE(PLAN_REV.APRVSTT, '') AS APRVSTT,
    CASE WHEN PLAN_REV.APRVSTT = 'R' THEN PLAN_REV.REJREASON ELSE '' END AS REJREASON
  FROM COMTYPE
  INNER JOIN (
    SELECT DISTINCT EQMGUBUN
    FROM MSTEQM
    WHERE USEYN = 'Y'
  ) GRP_EQM
    ON GRP_EQM.EQMGUBUN = COMTYPE.TPCD
  LEFT JOIN (
    SELECT PLANCD, MAX(REVNUM) AS REVNUM
    FROM MSTEQMREV_HEADER
    WHERE PLANTP = 'G'
    GROUP BY PLANCD
  ) LAST_REV
    ON LAST_REV.PLANCD = GRP_EQM.EQMGUBUN
  LEFT JOIN MSTEQMREV_HEADER PLAN_REV
    ON PLAN_REV.PLANTP = 'G'
   AND PLAN_REV.PLANCD = LAST_REV.PLANCD
   AND PLAN_REV.REVNUM = LAST_REV.REVNUM
  WHERE COMTYPE.GPCD = 'FM116'
    AND COMTYPE.USEYN = 'Y'
    AND ($EQMGRP IS NULL OR $EQMGRP = '' OR COMTYPE.TPNM = _$EQMGRPNM)
  ORDER BY COMTYPE.SORTNO, GRP_EQM.EQMGUBUN;
-- *****************************************************************************
WHEN 'LIST_GRP_EQM02' THEN -- 설비그룹 정기점검 항목 조회

  SELECT
    CHKPLANEQM.CHKKNDCD,
    MSTCHKKND.CHKKNDNM,
    MSTCHKKND.CHKLOC,
    MSTCHKKND.CHKMTH,
    MSTCHKKND.CHKVALTP,
    COALESCE(NULLIF(GPCD('CHKLOC', MSTCHKKND.CHKLOC), ''), MSTCHKKND.CHKLOC) AS CHKLOCNM,
    COALESCE(NULLIF(GPCD('CHKMTH', MSTCHKKND.CHKMTH), ''), MSTCHKKND.CHKMTH) AS CHKMTHNM,
    COALESCE(NULLIF(GPCD('CHKVALTP', MSTCHKKND.CHKVALTP), ''), MSTCHKKND.CHKVALTP) AS CHKVALTPNM,
    MSTCHKKND.CHKCYCLE,
    MIN(CHKPLANEQM.SORTNO) AS SORTNO,
    MAX(CASE WHEN CHKPLANEQM.USEYN = 'Y' THEN 'Y' ELSE 'N' END) AS USEYN,
    MAX(CHKPLANEQM.REMARK) AS REMARK
  FROM CHKPLANEQM
  INNER JOIN MSTCHKKND
    ON MSTCHKKND.CHKKNDCD = CHKPLANEQM.CHKKNDCD
  INNER JOIN MSTEQM
    ON MSTEQM.FANO = CHKPLANEQM.EQMCD
  WHERE MSTEQM.EQMGUBUN = $EQMGRP
    AND MSTEQM.USEYN = 'Y'
    AND MSTCHKKND.CHKTP = '02'
  GROUP BY CHKPLANEQM.CHKKNDCD, MSTCHKKND.CHKKNDNM, MSTCHKKND.CHKLOC, MSTCHKKND.CHKMTH, MSTCHKKND.CHKVALTP, MSTCHKKND.CHKCYCLE
  ORDER BY MIN(CHKPLANEQM.SORTNO)
  ;

-- *****************************************************************************
WHEN 'LIST_GRP_EQM02_ADD' THEN -- 설비그룹 미등록 정기점검 항목 조회
  SELECT COUNT(*) INTO _$EQMCNT FROM MSTEQM WHERE EQMGUBUN = $EQMGRP AND USEYN = 'Y';

  SELECT
    MSTCHKKND.CHKKNDCD,
    MSTCHKKND.CHKKNDNM,
    MSTCHKKND.CHKTP,
    MSTCHKKND.CHKLOC,
    MSTCHKKND.CHKMTH,
    MSTCHKKND.CHKVALTP,
    COALESCE(NULLIF(GPCD('CHKLOC', MSTCHKKND.CHKLOC), ''), MSTCHKKND.CHKLOC) AS CHKLOCNM,
    COALESCE(NULLIF(GPCD('CHKMTH', MSTCHKKND.CHKMTH), ''), MSTCHKKND.CHKMTH) AS CHKMTHNM,
    COALESCE(NULLIF(GPCD('CHKVALTP', MSTCHKKND.CHKVALTP), ''), MSTCHKKND.CHKVALTP) AS CHKVALTPNM,
    MSTCHKKND.SORTNO,
    MSTCHKKND.USEYN,
    '' AS REMARK
  FROM MSTCHKKND
  -- 점검항목별 등록 설비 수
  LEFT JOIN (
    SELECT CHKPLANEQM.CHKKNDCD, COUNT(*) AS EQMCNT
    FROM CHKPLANEQM
    INNER JOIN MSTEQM
      ON MSTEQM.FANO = CHKPLANEQM.EQMCD
    WHERE MSTEQM.EQMGUBUN = $EQMGRP
      AND MSTEQM.USEYN = 'Y'
      AND CHKPLANEQM.CHKTP = '02'
    GROUP BY CHKPLANEQM.CHKKNDCD
  ) REG_EQM
    ON REG_EQM.CHKKNDCD = MSTCHKKND.CHKKNDCD
  WHERE MSTCHKKND.USEYN = 'Y'
    AND MSTCHKKND.CHKTP = '02'
    AND COALESCE(REG_EQM.EQMCNT, 0) < _$EQMCNT
  ORDER BY MSTCHKKND.SORTNO
  ;

-- *****************************************************************************
WHEN 'REG_GRP_EQM02' THEN -- 설비그룹 정기점검 항목 등록


  WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
    CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);
    CALL COMSPLIT($REMARK_LIST, _$REMARK);

    SET _$CHKTP = (SELECT CHKTP FROM MSTCHKKND WHERE CHKKNDCD = _$CHKKNDCD LIMIT 1);

    INSERT INTO CHKPLANEQM (
      EQMCD, CHKTP, CHKKNDCD, CHKCYCLE,
      SORTNO, USEYN, REMARK,
      RTIME, REMP, RPRG
    )
    SELECT
      MSTEQM.FANO, _$CHKTP, _$CHKKNDCD, 'MONTH',
      COALESCE(SORT_INFO.MAXSORTNO, 0) + 1, 'Y', _$REMARK,
      CALLTIME(), CALLEMP(), CALLPRG()
    FROM MSTEQM
    -- 기존 항목 유무와 마지막 순서를 함께 집계
    LEFT JOIN (
      SELECT EQMCD,
             MAX(CASE WHEN CHKTP = '02' THEN SORTNO END) AS MAXSORTNO,
             MAX(CASE WHEN CHKKNDCD = _$CHKKNDCD AND CHKTP = _$CHKTP THEN 1 ELSE 0 END) AS ITEMEXIST
      FROM CHKPLANEQM
      WHERE CHKTP IN ('02', _$CHKTP)
      GROUP BY EQMCD
    ) SORT_INFO
      ON SORT_INFO.EQMCD = MSTEQM.FANO
    WHERE MSTEQM.EQMGUBUN = $EQMGRP
      AND MSTEQM.USEYN = 'Y'
      AND COALESCE(SORT_INFO.ITEMEXIST, 0) = 0;
  END WHILE;

-- *****************************************************************************
WHEN 'SAVE_GRP_EQM02' THEN -- 설비그룹 정기점검 항목 저장


  WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
    CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);
    CALL COMSPLIT($USEYN_LIST, _$USEYN);
    CALL COMSPLIT($SORTNO_LIST, _$SORTNO);
    CALL COMSPLIT($REMARK_LIST, _$REMARK);

    UPDATE CHKPLANEQM
    INNER JOIN MSTEQM
      ON MSTEQM.FANO = CHKPLANEQM.EQMCD
    SET
      CHKPLANEQM.USEYN  = _$USEYN,
      CHKPLANEQM.SORTNO = _$SORTNO,
      CHKPLANEQM.REMARK = _$REMARK,
      CHKPLANEQM.MTIME  = CALLTIME(),
      CHKPLANEQM.MEMP   = CALLEMP(),
      CHKPLANEQM.MPRG   = CALLPRG()
    WHERE MSTEQM.EQMGUBUN = $EQMGRP
      AND MSTEQM.USEYN = 'Y'
      AND CHKPLANEQM.CHKKNDCD = _$CHKKNDCD
      AND CHKPLANEQM.CHKTP = '02'
    ;
  END WHILE;

-- *****************************************************************************
WHEN 'DEL_GRP_EQM02' THEN -- 설비그룹 정기점검 항목 삭제


  WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
    CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);

    DELETE CHKPLANEQM
    FROM CHKPLANEQM
    INNER JOIN MSTEQM
      ON MSTEQM.FANO = CHKPLANEQM.EQMCD
    WHERE MSTEQM.EQMGUBUN = $EQMGRP
      AND MSTEQM.USEYN = 'Y'
      AND CHKPLANEQM.CHKKNDCD = _$CHKKNDCD
      AND CHKPLANEQM.CHKTP = '02';
  END WHILE;

-- *****************************************************************************
WHEN 'LIST_COPY_GRP_EQM02' THEN -- 설비그룹 복사 원본 목록 조회

  SELECT
    MSTEQM.EQMGUBUN AS EQMGRP,
    COMTYPE.TPNM AS EQMGRPNM,
    MIN(MSTEQM.FANO) AS FANO,
    COUNT(DISTINCT CHKPLANEQM.CHKKNDCD) AS EQM02CNT
  FROM MSTEQM
  INNER JOIN COMTYPE
    ON COMTYPE.GPCD = 'FM116'
   AND COMTYPE.TPCD = MSTEQM.EQMGUBUN
  INNER JOIN CHKPLANEQM
    ON CHKPLANEQM.EQMCD = MSTEQM.FANO
   AND CHKPLANEQM.CHKTP = '02'
  WHERE MSTEQM.USEYN = 'Y'
    AND MSTEQM.EQMGUBUN <> $EQMGRP
  GROUP BY MSTEQM.EQMGUBUN, COMTYPE.TPNM, COMTYPE.SORTNO
  ORDER BY COMTYPE.SORTNO, MSTEQM.EQMGUBUN
  ;

-- *****************************************************************************
WHEN 'LIST_COPY_GRP_EQM02_DTL' THEN -- 설비그룹 복사 상세 항목 조회

  SELECT
    CHKPLANEQM.CHKKNDCD,
    MSTCHKKND.CHKKNDNM,
    MSTCHKKND.CHKLOC,
    MSTCHKKND.CHKMTH,
    MSTCHKKND.CHKVALTP,
    COALESCE(NULLIF(GPCD('CHKLOC', MSTCHKKND.CHKLOC), ''), MSTCHKKND.CHKLOC) AS CHKLOCNM,
    COALESCE(NULLIF(GPCD('CHKMTH', MSTCHKKND.CHKMTH), ''), MSTCHKKND.CHKMTH) AS CHKMTHNM,
    COALESCE(NULLIF(GPCD('CHKVALTP', MSTCHKKND.CHKVALTP), ''), MSTCHKKND.CHKVALTP) AS CHKVALTPNM,
    MIN(CHKPLANEQM.SORTNO) AS SORTNO,
    MAX(CASE WHEN CHKPLANEQM.USEYN = 'Y' THEN 'Y' ELSE 'N' END) AS USEYN
  FROM CHKPLANEQM
  INNER JOIN MSTEQM
    ON MSTEQM.FANO = CHKPLANEQM.EQMCD
  INNER JOIN MSTCHKKND
    ON MSTCHKKND.CHKKNDCD = CHKPLANEQM.CHKKNDCD
  WHERE MSTEQM.EQMGUBUN = $EQMGRP
    AND MSTEQM.USEYN = 'Y'
    AND CHKPLANEQM.CHKTP = '02'
  GROUP BY CHKPLANEQM.CHKKNDCD, MSTCHKKND.CHKKNDNM, MSTCHKKND.CHKLOC, MSTCHKKND.CHKMTH, MSTCHKKND.CHKVALTP
  ORDER BY MIN(CHKPLANEQM.SORTNO), CHKPLANEQM.CHKKNDCD
  ;

-- *****************************************************************************
WHEN 'COPY_GRP_EQM02' THEN -- 설비그룹 정기점검 항목 복사
  SET _$COPYGRP = (SELECT EQMGUBUN FROM MSTEQM WHERE FANO = $FANO_COPY LIMIT 1);


  DROP TEMPORARY TABLE IF EXISTS TMP_COPY_EQM02;
  CREATE TEMPORARY TABLE TMP_COPY_EQM02 AS
  SELECT
    CHKPLANEQM.CHKTP,
    CHKPLANEQM.CHKKNDCD,
    MIN(CHKPLANEQM.CHKCYCLE) AS CHKCYCLE,
    MIN(CHKPLANEQM.SORTNO) AS SORTNO,
    MAX(CHKPLANEQM.USEYN) AS USEYN,
    MAX(CHKPLANEQM.REMARK) AS REMARK
  FROM MSTEQM SOURCE_EQM
  INNER JOIN CHKPLANEQM
    ON CHKPLANEQM.EQMCD = SOURCE_EQM.FANO
   AND CHKPLANEQM.CHKTP = '02'
  WHERE SOURCE_EQM.USEYN = 'Y'
    AND SOURCE_EQM.EQMGUBUN = _$COPYGRP
  GROUP BY CHKPLANEQM.CHKTP, CHKPLANEQM.CHKKNDCD;

  IF (SELECT COUNT(*) FROM TMP_COPY_EQM02) = 0 THEN
    DROP TEMPORARY TABLE IF EXISTS TMP_COPY_EQM02;
    CALL COMERR('복사할 정기점검 항목이 없습니다.');
    LEAVE PROC;
  END IF;

  INSERT INTO CHKPLANEQM (
    EQMCD, CHKTP, CHKKNDCD, CHKCYCLE,
    SORTNO, USEYN, REMARK,
    RTIME, REMP, RPRG
  )
  SELECT
    MSTEQM.FANO, TMP_COPY_EQM02.CHKTP, TMP_COPY_EQM02.CHKKNDCD, TMP_COPY_EQM02.CHKCYCLE,
