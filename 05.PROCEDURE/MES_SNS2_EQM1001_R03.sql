    CALL COMSPLIT($M03_LIST, _$M03);
    CALL COMSPLIT($M04_LIST, _$M04);
    CALL COMSPLIT($M05_LIST, _$M05);
    CALL COMSPLIT($M06_LIST, _$M06);
    CALL COMSPLIT($M07_LIST, _$M07);
    CALL COMSPLIT($M08_LIST, _$M08);
    CALL COMSPLIT($M09_LIST, _$M09);
    CALL COMSPLIT($M10_LIST, _$M10);
    CALL COMSPLIT($M11_LIST, _$M11);
    CALL COMSPLIT($M12_LIST, _$M12);
    CALL COMSPLIT($REMARK_LIST, _$REMARK);

