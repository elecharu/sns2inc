CREATE DEFINER=`root`@`%` PROCEDURE `MES_SNS2`.`EQM1001_R03`(
-- *****************************************************************************
-- Comment: 설비점검계획 
-- Create: 	2025-06-27  	생성 			이대규
-- Modify: 	2026-09-15 		마이그레이션	한성수
-- 			2026-09-16 					한성수	MSTEQM.FANO(설비코드) 컬럼 바인딩 변경
-- 			2026-09-21 					한성수	설비별·설비그룹 정기점검 조회/CRUD 추가 및 불필요 조인 단순화
-- 			2026-09-22 					한성수	설비그룹 재조회 선택 키를 EQMGUBUN 기준으로 정리
-- 			2026-09-23 					한성수	정기점검 주기관리 설비등급 조회 추가
-- 			2026-09-29 					한성수	설비그룹 점검계획 그룹코드 단위 변경, 승인상태·반려사유 표시 및 사전집계 튜닝
-- 			2026-09-30 					한성수	승인 리비전(REV) 기준 승인 검증 적용 및 점검항목·주기관리 코드명 반환 추가
-- 			2026-10-01 					한성수	설비그룹 없는 설비의 주기관리 조회·저장·삭제 지원 (설비 승인 기준)
-- 			2026-10-02 					한성수	주기관리 점검자 사원코드화·실적 월 잠금·승인본 대상 통일, 복사 검증 및 성능 개선
-- 			2026-10-06 					한성수	REV·승인·출력 R03 통합, 그룹 체크 제거·최신 REV 조회, DETAIL 중복 컬럼 제거·APRVKEY 이력 발번, 주기 승인 제한 해제·빈 개정내용 승인/반려 차단
-- 			2026-10-07 					한성수	설비별 정리·중복 방지, 보완 재요청·일괄 승인, 주기 성능개선, 계획서 출력 최신 REV 자동선택·전체 이력화
-- 			2026-10-08 					한성수	항목 추가·삭제·승인 검증·그룹 검색, HEADER·DETAIL 작업본·그룹/설비 REV 독립 관리 및 DETAIL 사용여부 제거
-- *****************************************************************************
  IN $FANO           VARCHAR(20),
  IN $FANO_COPY      VARCHAR(20),
  IN $SYEAR          VARCHAR(50),
  IN $EQMGRP         VARCHAR(50),
  IN $CHKKNDCD_LIST  MEDIUMTEXT,
  IN $REMARK_LIST    MEDIUMTEXT,
  IN $SORTNO_LIST    MEDIUMTEXT,
  IN $YEAR_LIST      MEDIUMTEXT,
  IN $FANO_LIST      MEDIUMTEXT,
  IN $M01_LIST       MEDIUMTEXT,
  IN $M02_LIST       MEDIUMTEXT,
  IN $M03_LIST       MEDIUMTEXT,
  IN $M04_LIST       MEDIUMTEXT,
  IN $M05_LIST       MEDIUMTEXT,
  IN $M06_LIST       MEDIUMTEXT,
  IN $M07_LIST       MEDIUMTEXT,
  IN $M08_LIST       MEDIUMTEXT,
  IN $M09_LIST       MEDIUMTEXT,
  IN $M10_LIST       MEDIUMTEXT,
  IN $M11_LIST       MEDIUMTEXT,
  IN $M12_LIST       MEDIUMTEXT,
  IN $PLANTP         CHAR(1),
  IN $PLANCD         VARCHAR(50),
  IN $REVNUM         VARCHAR(20),
  IN $REMARK         VARCHAR(1000),
  IN $APRVSTT        CHAR(1),
  IN $REJREASON      VARCHAR(1000),

-- *****************************************************************************
  IN $CALLTYPE       VARCHAR(50),
  IN $KEYWORD        VARCHAR(1000)
)
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  DECLARE _$CHKKNDCD      VARCHAR(20);
  DECLARE _$REMARK        VARCHAR(1000);
  DECLARE _$SORTNO        DECIMAL(20, 8);
  DECLARE _$MAXSORTNO     DECIMAL(20, 8);

  DECLARE _$M01           VARCHAR(20);
  DECLARE _$M02           VARCHAR(20);
  DECLARE _$M03           VARCHAR(20);
  DECLARE _$M04           VARCHAR(20);
  DECLARE _$M05           VARCHAR(20);
  DECLARE _$M06           VARCHAR(20);
  DECLARE _$M07           VARCHAR(20);
  DECLARE _$M08           VARCHAR(20);
  DECLARE _$M09           VARCHAR(20);
  DECLARE _$M10           VARCHAR(20);
  DECLARE _$M11           VARCHAR(20);
  DECLARE _$M12           VARCHAR(20);
  DECLARE _$YEAR          VARCHAR(20);
  DECLARE _$FANO          VARCHAR(20);
  DECLARE _$LOCKMM        VARCHAR(100);
  DECLARE _$PLANTP        CHAR(1);
  DECLARE _$PLANCD        VARCHAR(50);
  DECLARE _$EQMGRPNM      VARCHAR(1000);
  DECLARE _$LOCKKEY       VARCHAR(50);
  DECLARE _$OLDREVCD      VARCHAR(20);
  DECLARE _$COPYREVCD     VARCHAR(20);
  DECLARE _$NEWREV        INT DEFAULT 0;
  DECLARE _$REVCD         VARCHAR(20);
  DECLARE _$REVNUM        INT;
  DECLARE _$PLAN_CHANGED  INT DEFAULT 0;
  DECLARE _$REQTIME       VARCHAR(19);
  DECLARE _$APRVSTT       CHAR(1);
  DECLARE _$REVDATE       VARCHAR(10);

  -- 그룹·설비 공통 CRUD: 선택 대상의 작업 REV만 변경
  IF $CALLTYPE IN ('REG_GRP_EQM02', 'SAVE_GRP_EQM02', 'DEL_GRP_EQM02', 'COPY_GRP_EQM02',
                   'REG_EQM02', 'SAVE_EQM02', 'DEL_EQM02', 'COPY_EQM02') THEN
    SET _$PLANTP = IF($CALLTYPE LIKE '%GRP%', 'G', 'E');
    SET _$PLANCD = IF(_$PLANTP = 'G', $EQMGRP, $FANO);

    IF COALESCE(_$PLANCD, '') = '' THEN
      CALL COMERR(IF(_$PLANTP = 'G', '설비그룹을 지정해주세요.', '설비를 지정해주세요.'));
      LEAVE PROC;
    END IF;

    -- 같은 대상의 동시 변경은 기준정보 행에서 직렬화
    IF _$PLANTP = 'G' THEN
      SET _$LOCKKEY = (SELECT TPCD FROM COMTYPE WHERE GPCD = 'FM116' AND TPCD = _$PLANCD AND USEYN = 'Y' LIMIT 1 FOR UPDATE);

      IF NOT EXISTS (SELECT 1 FROM MSTEQM WHERE EQMGUBUN = _$PLANCD AND USEYN = 'Y' LIMIT 1) THEN
        SET _$LOCKKEY = NULL;
      END IF;
    ELSE
      SET _$LOCKKEY = (SELECT FANO FROM MSTEQM WHERE FANO = _$PLANCD AND USEYN = 'Y' LIMIT 1 FOR UPDATE);
    END IF;

    IF _$LOCKKEY IS NULL THEN
      CALL COMERR('사용 중인 설비그룹 또는 설비를 선택해주세요.');
      LEAVE PROC;
    END IF;

    SET _$REVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = _$PLANTP AND PLANCD = _$PLANCD ORDER BY REVNUM DESC LIMIT 1 FOR UPDATE);

    IF _$REVCD IS NOT NULL THEN
      SELECT REVNUM, APRVSTT INTO _$REVNUM, _$APRVSTT
      FROM MSTEQMREV_HEADER
      WHERE REVCD = _$REVCD;
    END IF;

    IF COALESCE($REVNUM, '') <> '' AND ($REVNUM NOT REGEXP '^[0-9]+$' OR _$REVNUM IS NULL OR _$REVNUM <> CAST($REVNUM AS UNSIGNED)) THEN
      CALL COMERR('점검계획이 변경되었습니다. 최신 REV를 다시 조회해주세요.');
      LEAVE PROC;
    END IF;

    IF $CALLTYPE LIKE 'COPY%' THEN
      IF COALESCE($FANO_COPY, '') = '' OR $FANO_COPY = _$PLANCD THEN
        CALL COMERR('다른 설비그룹 또는 설비를 복사 원본으로 선택해주세요.');
        LEAVE PROC;
      END IF;

      IF (_$PLANTP = 'G' AND NOT EXISTS (SELECT 1 FROM COMTYPE WHERE GPCD = 'FM116' AND TPCD = $FANO_COPY AND USEYN = 'Y' LIMIT 1))
         OR (_$PLANTP = 'E' AND NOT EXISTS (SELECT 1 FROM MSTEQM WHERE FANO = $FANO_COPY AND USEYN = 'Y' LIMIT 1)) THEN
        CALL COMERR('사용 중인 복사 원본을 선택해주세요.');
        LEAVE PROC;
      END IF;

      SET _$COPYREVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = _$PLANTP AND PLANCD = $FANO_COPY ORDER BY REVNUM DESC LIMIT 1);

      IF NOT EXISTS (SELECT 1 FROM MSTEQMREV_DETAIL WHERE REVCD = _$COPYREVCD LIMIT 1) THEN
        CALL COMERR('복사할 정기점검 항목이 없습니다.');
        LEAVE PROC;
      END IF;
    ELSEIF COALESCE($CHKKNDCD_LIST, '') = '' THEN
      CALL COMERR('정기점검 항목을 선택해주세요.');
      LEAVE PROC;
    END IF;

    -- 승인본은 그대로 두고 변경할 다음 REV에 항목을 복사
    IF _$REVCD IS NULL OR _$APRVSTT = 'A' THEN
      SET _$OLDREVCD = _$REVCD;
      SET _$REVCD    = GETKEY('REVCD');
      SET _$NEWREV   = 1;

      INSERT INTO MSTEQMREV_HEADER (
        REVCD, PLANTP, PLANCD, REVNUM, RTIME, REMP, RPRG
      ) VALUES (
        _$REVCD, _$PLANTP, _$PLANCD, COALESCE(_$REVNUM + 1, 0), CALLTIME(), CALLEMP(), CALLPRG()
      );

      INSERT INTO MSTEQMREV_DETAIL (
        REVCD, CHKKNDCD, CHKCYCLE, SORTNO, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, REMARK, RTIME, REMP, RPRG
      )
      SELECT _$REVCD, CHKKNDCD, CHKCYCLE, SORTNO, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, REMARK,
             CALLTIME(), CALLEMP(), CALLPRG()
      FROM MSTEQMREV_DETAIL
      WHERE REVCD = _$OLDREVCD;
    END IF;

    CASE SUBSTRING_INDEX($CALLTYPE, '_', 1)
    -- *****************************************************************************

    WHEN 'REG' THEN -- 정기점검 항목 등록
      WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
        CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);
        CALL COMSPLIT($REMARK_LIST, _$REMARK);

        IF NOT EXISTS (SELECT 1 FROM MSTCHKKND WHERE CHKKNDCD = _$CHKKNDCD AND CHKTP = '02' AND USEYN = 'Y' LIMIT 1) THEN
          CALL COMERR('사용 중인 정기점검 항목만 추가할 수 있습니다.');
          LEAVE PROC;
        END IF;

        IF NOT EXISTS (SELECT 1 FROM MSTEQMREV_DETAIL WHERE REVCD = _$REVCD AND CHKKNDCD = _$CHKKNDCD LIMIT 1) THEN
          SET _$MAXSORTNO = (SELECT COALESCE(MAX(SORTNO), 0) FROM MSTEQMREV_DETAIL WHERE REVCD = _$REVCD);

          INSERT INTO MSTEQMREV_DETAIL (
            REVCD, CHKKNDCD, CHKCYCLE, SORTNO, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, REMARK, RTIME, REMP, RPRG
          )
          SELECT _$REVCD, CHKKNDCD, 'MONTH', _$MAXSORTNO + 1, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, _$REMARK,
                 CALLTIME(), CALLEMP(), CALLPRG()
          FROM MSTCHKKND
          WHERE CHKKNDCD = _$CHKKNDCD;

          SET _$PLAN_CHANGED = _$PLAN_CHANGED + ROW_COUNT();
        END IF;
      END WHILE;

    -- *****************************************************************************

    WHEN 'SAVE' THEN -- 정기점검 항목 저장
      WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
        CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);
        CALL COMSPLIT($SORTNO_LIST, _$SORTNO);
        CALL COMSPLIT($REMARK_LIST, _$REMARK);

        IF _$SORTNO IS NULL
           OR NOT EXISTS (SELECT 1 FROM MSTEQMREV_DETAIL WHERE REVCD = _$REVCD AND CHKKNDCD = _$CHKKNDCD LIMIT 1) THEN
          CALL COMERR('저장할 점검항목과 정렬순서를 확인해주세요.');
          LEAVE PROC;
        END IF;

        UPDATE MSTEQMREV_DETAIL
        SET SORTNO = _$SORTNO,
            REMARK = _$REMARK,
            MTIME  = CALLTIME(),
            MEMP   = CALLEMP(),
            MPRG   = CALLPRG()
        WHERE REVCD = _$REVCD
          AND CHKKNDCD = _$CHKKNDCD
          AND NOT (SORTNO <=> _$SORTNO AND REMARK <=> _$REMARK);

        SET _$PLAN_CHANGED = _$PLAN_CHANGED + ROW_COUNT();
      END WHILE;

    -- *****************************************************************************

    WHEN 'DEL' THEN -- 작업 REV의 정기점검 항목 삭제
      WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
        CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);

        DELETE FROM MSTEQMREV_DETAIL
        WHERE REVCD = _$REVCD
          AND CHKKNDCD = _$CHKKNDCD;

        SET _$PLAN_CHANGED = _$PLAN_CHANGED + ROW_COUNT();
      END WHILE;

    -- *****************************************************************************

    WHEN 'COPY' THEN -- 선택 대상의 항목 전체 교체
      DELETE FROM MSTEQMREV_DETAIL
      WHERE REVCD = _$REVCD;

      INSERT INTO MSTEQMREV_DETAIL (
        REVCD, CHKKNDCD, CHKCYCLE, SORTNO, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, REMARK, RTIME, REMP, RPRG
      )
      SELECT _$REVCD, CHKKNDCD, CHKCYCLE, SORTNO, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, REMARK,
             CALLTIME(), CALLEMP(), CALLPRG()
      FROM MSTEQMREV_DETAIL
      WHERE REVCD = _$COPYREVCD;

      SET _$PLAN_CHANGED = ROW_COUNT();

    -- *****************************************************************************

    END CASE;

    IF _$PLAN_CHANGED > 0 THEN
      UPDATE MSTEQMREV_HEADER
      SET REQTIME = '',
          REQEMP  = '',
          REQPRG  = '',
          MTIME   = CALLTIME(),
          MEMP    = CALLEMP(),
          MPRG    = CALLPRG()
      WHERE REVCD = _$REVCD;
    ELSEIF _$NEWREV = 1 THEN
      DELETE FROM MSTEQMREV_DETAIL WHERE REVCD = _$REVCD;
      DELETE FROM MSTEQMREV_HEADER WHERE REVCD = _$REVCD;
    END IF;

  ELSE

  CASE $CALLTYPE
  -- *****************************************************************************

  WHEN 'LIST_MSTEQM_GRP' THEN -- 설비그룹 최신 리비전 조회
    -- 같은 이름의 그룹코드 함께 조회
    SET _$EQMGRPNM = (SELECT TPNM FROM COMTYPE WHERE GPCD = 'FM116' AND TPCD = $EQMGRP LIMIT 1);

    SELECT GRP_EQM.EQMGUBUN,
           COMTYPE.TPNM AS EQMGRPNM,
           COMTYPE.SORTNO AS EQMGRPSORTNO,
           PLAN_REV.REVCD,
           COALESCE(CONCAT('REV.', PLAN_REV.REVNUM), '') AS REVNM,
           CASE WHEN PLAN_REV.REVCD IS NULL OR PLAN_REV.REVCD = '' THEN ''
                WHEN PLAN_REV.APRVSTT = 'A' THEN '승인'
                WHEN PLAN_REV.APRVSTT = 'R' THEN '반려'
                ELSE '대기' END AS APRVSTTNM,
           COALESCE(PLAN_REV.APRVSTT, '') AS APRVSTT,
           CASE WHEN PLAN_REV.APRVSTT = 'R' THEN PLAN_REV.REJREASON ELSE '' END AS REJREASON
    FROM COMTYPE
    INNER JOIN (
      SELECT DISTINCT EQMGUBUN
      FROM MSTEQM
      WHERE USEYN = 'Y'
    ) GRP_EQM ON GRP_EQM.EQMGUBUN = COMTYPE.TPCD
    LEFT JOIN (
      SELECT PLANCD, MAX(REVNUM) AS REVNUM
      FROM MSTEQMREV_HEADER
      WHERE PLANTP = 'G'
      GROUP BY PLANCD
    ) LAST_REV ON LAST_REV.PLANCD = GRP_EQM.EQMGUBUN
    LEFT JOIN MSTEQMREV_HEADER PLAN_REV
      ON PLAN_REV.PLANTP = 'G'
     AND PLAN_REV.PLANCD = LAST_REV.PLANCD
     AND PLAN_REV.REVNUM = LAST_REV.REVNUM
    WHERE COMTYPE.GPCD = 'FM116'
      AND COMTYPE.USEYN = 'Y'
      AND ($EQMGRP IS NULL OR $EQMGRP = '' OR COMTYPE.TPNM = _$EQMGRPNM)
    ORDER BY COMTYPE.SORTNO, GRP_EQM.EQMGUBUN;

  -- *****************************************************************************

  WHEN 'LIST_GRP_EQM02' THEN -- 최신 정기점검 항목 조회
    SET _$REVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'G' AND PLANCD = $EQMGRP ORDER BY REVNUM DESC LIMIT 1);

    SELECT MSTEQMREV_DETAIL.CHKKNDCD,
           MSTEQMREV_DETAIL.CHKKNDNM,
           MSTEQMREV_DETAIL.CHKLOC,
           MSTEQMREV_DETAIL.CHKMTH,
           MSTEQMREV_DETAIL.CHKVALTP,
           COALESCE(NULLIF(GPCD('CHKLOC', MSTEQMREV_DETAIL.CHKLOC), ''), MSTEQMREV_DETAIL.CHKLOC) AS CHKLOCNM,
           COALESCE(NULLIF(GPCD('CHKMTH', MSTEQMREV_DETAIL.CHKMTH), ''), MSTEQMREV_DETAIL.CHKMTH) AS CHKMTHNM,
           COALESCE(NULLIF(GPCD('CHKVALTP', MSTEQMREV_DETAIL.CHKVALTP), ''), MSTEQMREV_DETAIL.CHKVALTP) AS CHKVALTPNM,
           MSTEQMREV_DETAIL.CHKCYCLE,
           MSTEQMREV_DETAIL.SORTNO,
           MSTEQMREV_DETAIL.REMARK
    FROM MSTEQMREV_DETAIL
    WHERE REVCD = _$REVCD
    ORDER BY SORTNO, CHKKNDCD;

  -- *****************************************************************************

  WHEN 'LIST_GRP_EQM02_ADD' THEN -- 미등록 정기점검 항목 조회
    SET _$REVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'G' AND PLANCD = $EQMGRP ORDER BY REVNUM DESC LIMIT 1);

    SELECT MSTCHKKND.CHKKNDCD,
           MSTCHKKND.CHKKNDNM,
           MSTCHKKND.CHKLOC,
           MSTCHKKND.CHKMTH,
           MSTCHKKND.CHKVALTP,
           COALESCE(NULLIF(GPCD('CHKLOC', MSTCHKKND.CHKLOC), ''), MSTCHKKND.CHKLOC) AS CHKLOCNM,
           COALESCE(NULLIF(GPCD('CHKMTH', MSTCHKKND.CHKMTH), ''), MSTCHKKND.CHKMTH) AS CHKMTHNM,
           COALESCE(NULLIF(GPCD('CHKVALTP', MSTCHKKND.CHKVALTP), ''), MSTCHKKND.CHKVALTP) AS CHKVALTPNM,
           MSTCHKKND.CHKCYCLE,
           MSTCHKKND.SORTNO,
           '' AS REMARK,
           MSTCHKKND.CHKTP
    FROM MSTCHKKND
    LEFT JOIN MSTEQMREV_DETAIL PLAN_ITEM
      ON PLAN_ITEM.REVCD = _$REVCD
     AND PLAN_ITEM.CHKKNDCD = MSTCHKKND.CHKKNDCD
    WHERE MSTCHKKND.CHKTP = '02'
      AND MSTCHKKND.USEYN = 'Y'
      AND PLAN_ITEM.CHKKNDCD IS NULL
    ORDER BY MSTCHKKND.SORTNO, MSTCHKKND.CHKKNDCD;

  -- *****************************************************************************

  WHEN 'LIST_COPY_GRP_EQM02' THEN -- 설비그룹 복사 원본 목록
    SELECT COMTYPE.TPCD AS EQMGRP,
           COMTYPE.TPNM AS EQMGRPNM,
           COUNT(*) AS EQM02CNT
    FROM COMTYPE
    INNER JOIN MSTEQMREV_HEADER PLAN_REV
      ON PLAN_REV.PLANTP = 'G'
     AND PLAN_REV.PLANCD = COMTYPE.TPCD
    INNER JOIN (
      SELECT PLANCD, MAX(REVNUM) AS REVNUM
      FROM MSTEQMREV_HEADER
      WHERE PLANTP = 'G'
      GROUP BY PLANCD
    ) LAST_REV
      ON LAST_REV.PLANCD = PLAN_REV.PLANCD
     AND LAST_REV.REVNUM = PLAN_REV.REVNUM
    INNER JOIN MSTEQMREV_DETAIL
      ON MSTEQMREV_DETAIL.REVCD = PLAN_REV.REVCD
    WHERE COMTYPE.GPCD = 'FM116'
      AND COMTYPE.USEYN = 'Y'
      AND COMTYPE.TPCD <> $EQMGRP
    GROUP BY COMTYPE.TPCD, COMTYPE.TPNM, COMTYPE.SORTNO
    ORDER BY COMTYPE.SORTNO, COMTYPE.TPCD;

  -- *****************************************************************************

  WHEN 'LIST_COPY_GRP_EQM02_DTL' THEN -- 최신 정기점검 항목 조회
    SET _$REVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'G' AND PLANCD = $EQMGRP ORDER BY REVNUM DESC LIMIT 1);

    SELECT MSTEQMREV_DETAIL.CHKKNDCD,
           MSTEQMREV_DETAIL.CHKKNDNM,
           MSTEQMREV_DETAIL.CHKLOC,
           MSTEQMREV_DETAIL.CHKMTH,
           MSTEQMREV_DETAIL.CHKVALTP,
           COALESCE(NULLIF(GPCD('CHKLOC', MSTEQMREV_DETAIL.CHKLOC), ''), MSTEQMREV_DETAIL.CHKLOC) AS CHKLOCNM,
           COALESCE(NULLIF(GPCD('CHKMTH', MSTEQMREV_DETAIL.CHKMTH), ''), MSTEQMREV_DETAIL.CHKMTH) AS CHKMTHNM,
           COALESCE(NULLIF(GPCD('CHKVALTP', MSTEQMREV_DETAIL.CHKVALTP), ''), MSTEQMREV_DETAIL.CHKVALTP) AS CHKVALTPNM,
           MSTEQMREV_DETAIL.CHKCYCLE,
           MSTEQMREV_DETAIL.SORTNO,
           MSTEQMREV_DETAIL.REMARK
    FROM MSTEQMREV_DETAIL
    WHERE REVCD = _$REVCD
    ORDER BY SORTNO, CHKKNDCD;

  -- *****************************************************************************

  WHEN 'LIST_MSTEQM' THEN -- 설비 목록 조회
    SELECT MSTEQM.FANO,
           COALESCE(MSTEQM.EQMGUBUN, '') AS EQMGUBUN,
           COALESCE(COMTYPE.TPNM, '') AS EQMGRPNM,
           MSTEQM.EQMNM,
           COALESCE(CONCAT('REV.', PLAN_REV.REVNUM), '') AS REVNM,
           CASE WHEN PLAN_REV.REVCD IS NULL OR PLAN_REV.REVCD = '' THEN ''
                WHEN PLAN_REV.APRVSTT = 'A' THEN '승인'
                WHEN PLAN_REV.APRVSTT = 'R' THEN '반려'
                ELSE '대기' END AS APRVSTTNM,
           COALESCE(PLAN_REV.APRVSTT, '') AS APRVSTT,
           CASE WHEN PLAN_REV.APRVSTT = 'R' THEN PLAN_REV.REJREASON ELSE '' END AS REJREASON
    FROM MSTEQM
    LEFT JOIN COMTYPE
      ON COMTYPE.GPCD = 'FM116'
     AND COMTYPE.TPCD = MSTEQM.EQMGUBUN
    LEFT JOIN (
      SELECT PLANCD, MAX(REVNUM) AS REVNUM
      FROM MSTEQMREV_HEADER
      WHERE PLANTP = 'E'
      GROUP BY PLANCD
    ) LAST_REV ON LAST_REV.PLANCD = MSTEQM.FANO
    LEFT JOIN MSTEQMREV_HEADER PLAN_REV
      ON PLAN_REV.PLANTP = 'E'
     AND PLAN_REV.PLANCD = LAST_REV.PLANCD
     AND PLAN_REV.REVNUM = LAST_REV.REVNUM
    WHERE MSTEQM.USEYN = 'Y'
      AND (COALESCE($EQMGRP, '') = '' OR MSTEQM.EQMGUBUN LIKE CONCAT('%', $EQMGRP, '%') OR COMTYPE.TPNM LIKE CONCAT('%', $EQMGRP, '%'))
      AND (COALESCE($FANO, '') = '' OR MSTEQM.FANO LIKE CONCAT('%', $FANO, '%') OR MSTEQM.EQMNM LIKE CONCAT('%', $FANO, '%'))
    ORDER BY MSTEQM.FANO;

  -- *****************************************************************************

  WHEN 'LIST_MSTEQM_EQM02' THEN -- 최신 정기점검 항목 조회
    SET _$REVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'E' AND PLANCD = $FANO ORDER BY REVNUM DESC LIMIT 1);

    SELECT MSTEQMREV_DETAIL.CHKKNDCD,
           MSTEQMREV_DETAIL.CHKKNDNM,
           MSTEQMREV_DETAIL.CHKLOC,
           MSTEQMREV_DETAIL.CHKMTH,
           MSTEQMREV_DETAIL.CHKVALTP,
           COALESCE(NULLIF(GPCD('CHKLOC', MSTEQMREV_DETAIL.CHKLOC), ''), MSTEQMREV_DETAIL.CHKLOC) AS CHKLOCNM,
           COALESCE(NULLIF(GPCD('CHKMTH', MSTEQMREV_DETAIL.CHKMTH), ''), MSTEQMREV_DETAIL.CHKMTH) AS CHKMTHNM,
           COALESCE(NULLIF(GPCD('CHKVALTP', MSTEQMREV_DETAIL.CHKVALTP), ''), MSTEQMREV_DETAIL.CHKVALTP) AS CHKVALTPNM,
           MSTEQMREV_DETAIL.CHKCYCLE,
           MSTEQMREV_DETAIL.SORTNO,
           MSTEQMREV_DETAIL.REMARK
    FROM MSTEQMREV_DETAIL
    WHERE REVCD = _$REVCD
    ORDER BY SORTNO, CHKKNDCD;

  -- *****************************************************************************

  WHEN 'LIST_EQM02' THEN -- 미등록 정기점검 항목 조회
    SET _$REVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'E' AND PLANCD = $FANO ORDER BY REVNUM DESC LIMIT 1);

    SELECT MSTCHKKND.CHKKNDCD,
           MSTCHKKND.CHKKNDNM,
           MSTCHKKND.CHKLOC,
           MSTCHKKND.CHKMTH,
           MSTCHKKND.CHKVALTP,
           COALESCE(NULLIF(GPCD('CHKLOC', MSTCHKKND.CHKLOC), ''), MSTCHKKND.CHKLOC) AS CHKLOCNM,
           COALESCE(NULLIF(GPCD('CHKMTH', MSTCHKKND.CHKMTH), ''), MSTCHKKND.CHKMTH) AS CHKMTHNM,
           COALESCE(NULLIF(GPCD('CHKVALTP', MSTCHKKND.CHKVALTP), ''), MSTCHKKND.CHKVALTP) AS CHKVALTPNM,
           MSTCHKKND.CHKCYCLE,
           MSTCHKKND.SORTNO,
           '' AS REMARK,
           MSTCHKKND.CHKTP
    FROM MSTCHKKND
    LEFT JOIN MSTEQMREV_DETAIL PLAN_ITEM
      ON PLAN_ITEM.REVCD = _$REVCD
     AND PLAN_ITEM.CHKKNDCD = MSTCHKKND.CHKKNDCD
    WHERE MSTCHKKND.CHKTP = '02'
      AND MSTCHKKND.USEYN = 'Y'
      AND PLAN_ITEM.CHKKNDCD IS NULL
    ORDER BY MSTCHKKND.SORTNO, MSTCHKKND.CHKKNDCD;

  -- *****************************************************************************

  WHEN 'LIST_COPY_EQM02' THEN -- 설비 복사 원본 목록·상세
    SELECT MSTEQM.FANO,
           MSTEQM.EQMNM
    FROM MSTEQM
    INNER JOIN MSTEQMREV_HEADER PLAN_REV
      ON PLAN_REV.PLANTP = 'E'
     AND PLAN_REV.PLANCD = MSTEQM.FANO
    INNER JOIN (
      SELECT PLANCD, MAX(REVNUM) AS REVNUM
      FROM MSTEQMREV_HEADER
      WHERE PLANTP = 'E'
      GROUP BY PLANCD
    ) LAST_REV
      ON LAST_REV.PLANCD = PLAN_REV.PLANCD
     AND LAST_REV.REVNUM = PLAN_REV.REVNUM
    INNER JOIN MSTEQMREV_DETAIL
      ON MSTEQMREV_DETAIL.REVCD = PLAN_REV.REVCD
    WHERE MSTEQM.USEYN = 'Y'
      AND MSTEQM.FANO <> $FANO
    GROUP BY MSTEQM.FANO, MSTEQM.EQMNM
    ORDER BY MSTEQM.FANO;

    SET _$REVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'E' AND PLANCD = $FANO ORDER BY REVNUM DESC LIMIT 1);

    SELECT MSTEQMREV_DETAIL.CHKKNDCD,
           MSTEQMREV_DETAIL.CHKKNDNM,
           MSTEQMREV_DETAIL.CHKLOC,
           MSTEQMREV_DETAIL.CHKMTH,
           MSTEQMREV_DETAIL.CHKVALTP,
           COALESCE(NULLIF(GPCD('CHKLOC', MSTEQMREV_DETAIL.CHKLOC), ''), MSTEQMREV_DETAIL.CHKLOC) AS CHKLOCNM,
           COALESCE(NULLIF(GPCD('CHKMTH', MSTEQMREV_DETAIL.CHKMTH), ''), MSTEQMREV_DETAIL.CHKMTH) AS CHKMTHNM,
           COALESCE(NULLIF(GPCD('CHKVALTP', MSTEQMREV_DETAIL.CHKVALTP), ''), MSTEQMREV_DETAIL.CHKVALTP) AS CHKVALTPNM,
           MSTEQMREV_DETAIL.CHKCYCLE,
           MSTEQMREV_DETAIL.SORTNO,
           MSTEQMREV_DETAIL.REMARK
    FROM MSTEQMREV_DETAIL
    WHERE REVCD = _$REVCD
    ORDER BY SORTNO, CHKKNDCD;

  -- *****************************************************************************

  WHEN 'LIST_PLAN_REV' THEN -- 점검계획 리비전 이력 조회
    SELECT CONCAT('REV.', MSTEQMREV_HEADER.REVNUM) AS REVNM,
           CASE MSTEQMREV_HEADER.APRVSTT
             WHEN 'A' THEN '승인'
             WHEN 'R' THEN '반려'
             ELSE '대기' END AS APRVSTTNM,
           MSTEQMREV_HEADER.REMARK,
           COALESCE(REQ_EMP.EMPNM, MSTEQMREV_HEADER.REQEMP) AS REQEMP,
           MSTEQMREV_HEADER.REQTIME,
           CASE WHEN MSTEQMREV_HEADER.APRVSTT = 'A' THEN COALESCE(APRV_EMP.EMPNM, MSTEQMREV_HEADER.APRVEMP) ELSE '' END AS APRVEMP,
           CASE WHEN MSTEQMREV_HEADER.APRVSTT IN ('A', 'R') THEN MSTEQMREV_HEADER.APRVTIME ELSE '' END AS APRVTIME,
           CASE WHEN MSTEQMREV_HEADER.APRVSTT = 'R' THEN MSTEQMREV_HEADER.REJREASON ELSE '' END AS REJREASON,
           MSTEQMREV_HEADER.REVNUM,
           MSTEQMREV_HEADER.APRVSTT
    FROM MSTEQMREV_HEADER
    LEFT JOIN MSTEMP REQ_EMP
      ON REQ_EMP.EMPCD = MSTEQMREV_HEADER.REQEMP
    LEFT JOIN MSTEMP APRV_EMP
      ON APRV_EMP.EMPCD = MSTEQMREV_HEADER.APRVEMP
    WHERE MSTEQMREV_HEADER.PLANTP = $PLANTP
      AND MSTEQMREV_HEADER.PLANCD = $PLANCD
    ORDER BY MSTEQMREV_HEADER.REVNUM DESC;

  -- *****************************************************************************

  WHEN 'LIST_PLAN_REV_ITEM' THEN -- 리비전 승인본 점검 항목 조회
    SELECT MSTEQMREV_DETAIL.CHKKNDCD,
           MSTEQMREV_DETAIL.CHKKNDNM,
           MSTEQMREV_DETAIL.CHKLOC,
           MSTEQMREV_DETAIL.CHKMTH,
           MSTEQMREV_DETAIL.CHKVALTP,
           COALESCE(NULLIF(GPCD('CHKLOC', MSTEQMREV_DETAIL.CHKLOC), ''), MSTEQMREV_DETAIL.CHKLOC) AS CHKLOCNM,
           COALESCE(NULLIF(GPCD('CHKMTH', MSTEQMREV_DETAIL.CHKMTH), ''), MSTEQMREV_DETAIL.CHKMTH) AS CHKMTHNM,
           COALESCE(NULLIF(GPCD('CHKVALTP', MSTEQMREV_DETAIL.CHKVALTP), ''), MSTEQMREV_DETAIL.CHKVALTP) AS CHKVALTPNM,
           MSTEQMREV_DETAIL.SORTNO,
           MSTEQMREV_DETAIL.REMARK
    FROM MSTEQMREV_HEADER ITEM_REV
    INNER JOIN MSTEQMREV_DETAIL
      ON MSTEQMREV_DETAIL.REVCD = ITEM_REV.REVCD
    WHERE ITEM_REV.PLANTP = $PLANTP
      AND ITEM_REV.PLANCD = $PLANCD
      AND ITEM_REV.REVNUM = $REVNUM
    ORDER BY MSTEQMREV_DETAIL.SORTNO;

  -- *****************************************************************************

  WHEN 'SAVE_PLAN_REV' THEN -- 개정내용 저장 및 승인 재요청
    IF COALESCE($PLANTP, '') NOT IN ('G', 'E') OR COALESCE($PLANCD, '') = '' OR COALESCE($REVNUM, '') NOT REGEXP '^[0-9]+$' THEN
      CALL COMERR('저장·재요청할 최신 REV를 선택해주세요.');
      LEAVE PROC;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM MSTEQMREV_HEADER WHERE PLANTP = $PLANTP AND PLANCD = $PLANCD LIMIT 1) THEN
      CALL COMERR('저장·재요청할 REV가 없습니다. 점검항목을 먼저 등록해주세요.');
      LEAVE PROC;
    END IF;

    SELECT REVCD, REVNUM, APRVSTT INTO _$REVCD, _$REVNUM, _$APRVSTT
    FROM MSTEQMREV_HEADER
    WHERE PLANTP = $PLANTP
      AND PLANCD = $PLANCD
    ORDER BY REVNUM DESC
    LIMIT 1 FOR UPDATE;

    IF _$REVNUM IS NULL OR _$REVNUM <> CAST($REVNUM AS UNSIGNED) OR _$APRVSTT = 'A' THEN
      CALL COMERR('최신 대기 REV만 개정내용을 저장할 수 있습니다.');
      LEAVE PROC;
    END IF;

    IF TRIM(COALESCE($REMARK, '')) = '' THEN
      CALL COMERR('개정내용을 입력해주세요.');
      LEAVE PROC;
    END IF;

    UPDATE MSTEQMREV_HEADER
    SET REMARK    = $REMARK,
        APRVSTT   = '',
        APRVTIME  = '',
        APRVEMP   = '',
        APRVPRG   = '',
        REJREASON = '',
        REQTIME   = CALLTIME(),
        REQEMP    = CALLEMP(),
        REQPRG    = CALLPRG(),
        MTIME     = CALLTIME(),
        MEMP      = CALLEMP(),
        MPRG      = CALLPRG()
    WHERE REVCD = _$REVCD;

  -- *****************************************************************************

  WHEN 'SAVE_PLAN_STATUS' THEN -- 점검계획 승인 상태 저장
    IF COALESCE($PLANCD, '') = '' THEN
      CALL COMERR('승인할 점검계획을 선택해주세요.');
      LEAVE PROC;
    END IF;

    IF $PLANTP IS NULL OR $PLANTP NOT IN ('G', 'E') THEN
      CALL COMERR('승인 대상이 올바르지 않습니다.');
      LEAVE PROC;
    END IF;

    IF $APRVSTT IS NULL OR $APRVSTT <> 'A' THEN
      CALL COMERR('승인 상태가 올바르지 않습니다.');
      LEAVE PROC;
    END IF;

    IF COALESCE($REVNUM, '') NOT REGEXP '^[0-9]+$' THEN
      CALL COMERR('승인할 REV를 선택해주세요.');
      LEAVE PROC;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM MSTEQMREV_HEADER WHERE PLANTP = $PLANTP AND PLANCD = $PLANCD LIMIT 1) THEN
      CALL COMERR('처리할 REV가 없습니다. 점검항목을 먼저 등록해주세요.');
      LEAVE PROC;
    END IF;

    SELECT MSTEQMREV_HEADER.REVCD, MSTEQMREV_HEADER.REVNUM, MSTEQMREV_HEADER.REMARK, MSTEQMREV_HEADER.APRVSTT, MSTEQMREV_HEADER.REQTIME
      INTO _$REVCD, _$REVNUM, _$REMARK, _$APRVSTT, _$REQTIME
    FROM MSTEQMREV_HEADER
    WHERE MSTEQMREV_HEADER.PLANTP = $PLANTP
      AND MSTEQMREV_HEADER.PLANCD = $PLANCD
    ORDER BY MSTEQMREV_HEADER.REVNUM DESC
    LIMIT 1 FOR UPDATE;

    IF _$REVNUM IS NOT NULL AND _$REVNUM <> CAST($REVNUM AS UNSIGNED) THEN
      CALL COMERR('최신 REV만 승인할 수 있습니다. 다시 조회해주세요.');
      LEAVE PROC;
    END IF;

    IF _$REVNUM IS NULL OR _$APRVSTT = 'A' THEN
      CALL COMERR('진행 중인 개정이 없습니다. 점검계획을 수정한 뒤 승인해주세요.');
      LEAVE PROC;
    END IF;

    IF _$APRVSTT = 'R' THEN
      CALL COMERR('반려된 계획입니다. 보완 후 [개정내용 저장·재요청]을 눌러주세요.');
      LEAVE PROC;
    END IF;

    IF COALESCE(_$REQTIME, '') = '' THEN
      CALL COMERR('점검계획이 변경되었습니다. [개정내용 저장·재요청] 후 처리해주세요.');
      LEAVE PROC;
    END IF;

    IF COALESCE(_$REMARK, '') <> COALESCE($REMARK, '') THEN
      CALL COMERR('개정내용이 변경되었습니다. 개정내용 저장 후 다시 조회해주세요.');
      LEAVE PROC;
    END IF;

    IF TRIM(COALESCE(_$REMARK, '')) = '' THEN
      CALL COMERR('개정내용을 입력하고 [개정내용 저장] 후 승인해주세요.');
      LEAVE PROC;
    END IF;

    -- 승인 시 항목 복사 없이 선택 REV의 상태만 확정
    INSERT INTO CHKPLANEQM_APRV (
      APRVKEY, REVCD, PLANTP, PLANCD, APRVSTT, REQTIME, REQEMP, REQPRG,
      APRVTIME, APRVEMP, APRVPRG, REJREASON, RTIME, REMP, RPRG
    )
    SELECT GETKEY('APRVKEY'), REVCD, PLANTP, PLANCD, 'A', REQTIME, REQEMP, REQPRG,
           CALLTIME(), CALLEMP(), CALLPRG(), '', CALLTIME(), CALLEMP(), CALLPRG()
    FROM MSTEQMREV_HEADER
    WHERE REVCD = _$REVCD;

    UPDATE MSTEQMREV_HEADER
    SET APRVSTT   = 'A',
        APRVTIME  = CALLTIME(),
        APRVEMP   = CALLEMP(),
        APRVPRG   = CALLPRG(),
        REJREASON = '',
        MTIME     = CALLTIME(),
        MEMP      = CALLEMP(),
        MPRG      = CALLPRG()
    WHERE REVCD = _$REVCD;

  -- *****************************************************************************

  WHEN 'CALL_PLAN_RPT' THEN -- 점검계획서 출력 데이터 조회 (설비그룹·설비, 승인상태와 무관)
    SET _$PLANTP = CASE WHEN $PLANTP = 'E' THEN 'E' ELSE 'G' END;
    SET _$PLANCD = $PLANCD;

    IF COALESCE(_$PLANCD, '') = '' THEN
      CALL COMERR(CASE WHEN _$PLANTP = 'E' THEN '설비를 선택해주세요.' ELSE '설비그룹을 선택해주세요.' END);
      LEAVE PROC;
    END IF;

    -- 대상 리비전 결정 ($REVNUM이 숫자로 전달되면 해당 REV, 없거나 빈 값이면 최신 REV 자동 선택)
    IF COALESCE($REVNUM, '') REGEXP '^[0-9]+$' THEN
      SELECT MSTEQMREV_HEADER.REVCD, MSTEQMREV_HEADER.REVNUM, MSTEQMREV_HEADER.APRVSTT,
             LEFT(CASE WHEN MSTEQMREV_HEADER.APRVSTT = 'A' THEN MSTEQMREV_HEADER.APRVTIME ELSE MSTEQMREV_HEADER.REQTIME END, 10)
        INTO _$REVCD, _$REVNUM, _$APRVSTT, _$REVDATE
      FROM MSTEQMREV_HEADER
      WHERE MSTEQMREV_HEADER.PLANTP = _$PLANTP
        AND MSTEQMREV_HEADER.PLANCD = _$PLANCD
        AND MSTEQMREV_HEADER.REVNUM = $REVNUM
      LIMIT 1;
    ELSE
      SELECT MSTEQMREV_HEADER.REVCD, MSTEQMREV_HEADER.REVNUM, MSTEQMREV_HEADER.APRVSTT,
             LEFT(CASE WHEN MSTEQMREV_HEADER.APRVSTT = 'A' THEN MSTEQMREV_HEADER.APRVTIME ELSE MSTEQMREV_HEADER.REQTIME END, 10)
        INTO _$REVCD, _$REVNUM, _$APRVSTT, _$REVDATE
      FROM MSTEQMREV_HEADER
      WHERE MSTEQMREV_HEADER.PLANTP = _$PLANTP
        AND MSTEQMREV_HEADER.PLANCD = _$PLANCD
      ORDER BY MSTEQMREV_HEADER.REVNUM DESC
      LIMIT 1;
    END IF;

    IF _$REVCD IS NULL THEN
      CALL COMERR('출력할 정기점검 계획이 없습니다.');
      LEAVE PROC;
    END IF;

    -- 계획서 상단 (설비그룹은 소속 설비의 설비번호·규격·라인·공정을 모아서 표시)
    SELECT CASE WHEN _$PLANTP = 'E' THEN MAX(MSTEQM.EQMNM) ELSE COALESCE(MAX(COMTYPE.TPNM), _$PLANCD) END AS EQMNM,
           GROUP_CONCAT(MSTEQM.FANO ORDER BY MSTEQM.FANO SEPARATOR ', ') AS EQMCD,
           COALESCE(GROUP_CONCAT(DISTINCT NULLIF(MSTEQM.EQMNM_DETAIL, '') SEPARATOR ', '), '') AS EQMSPEC,
           COALESCE(GROUP_CONCAT(DISTINCT COALESCE(NULLIF(MSTLINE.LINENM, ''), NULLIF(MSTEQM.LINECD, '')) SEPARATOR ', '), '') AS LINENM,
           COALESCE(GROUP_CONCAT(DISTINCT COALESCE(NULLIF(GPCD('FM100', MSTEQM.EQMTP), ''), NULLIF(MSTEQM.EQMTP, '')) SEPARATOR ', '), '') AS PROCESSNM,
           COALESCE(CONCAT('REV.', _$REVNUM), '') AS REVNM,
           COALESCE(_$REVDATE, '') AS REVDATE
    FROM MSTEQM
    LEFT JOIN MSTLINE
      ON MSTLINE.LINECD = MSTEQM.LINECD
    LEFT JOIN COMTYPE
      ON COMTYPE.GPCD = 'FM116'
     AND COMTYPE.TPCD = MSTEQM.EQMGUBUN
    WHERE MSTEQM.USEYN = 'Y'
      AND ((_$PLANTP = 'E' AND MSTEQM.FANO = _$PLANCD)
        OR (_$PLANTP = 'G' AND MSTEQM.EQMGUBUN = _$PLANCD))
    HAVING COUNT(*) > 0;

    -- 계획서 점검 항목: 선택 REV의 사용 항목
    SELECT ROW_NUMBER() OVER (ORDER BY MSTEQMREV_DETAIL.SORTNO, MSTEQMREV_DETAIL.CHKKNDCD) AS NO,
           COALESCE(NULLIF(GPCD('CHKLOC', MSTEQMREV_DETAIL.CHKLOC), ''), MSTEQMREV_DETAIL.CHKLOC) AS CHKITEM,
           MSTEQMREV_DETAIL.CHKKNDNM AS CHKCONTENT,
           COALESCE(NULLIF(GPCD('CHKMTH', MSTEQMREV_DETAIL.CHKMTH), ''), MSTEQMREV_DETAIL.CHKMTH) AS CHKDEVICE,
           COALESCE(NULLIF(GPCD('CHKVALTP', MSTEQMREV_DETAIL.CHKVALTP), ''), MSTEQMREV_DETAIL.CHKVALTP) AS CHKRESULT,
           '' AS CONFIRM,
           '' AS REMARK
    FROM MSTEQMREV_DETAIL
    WHERE MSTEQMREV_DETAIL.REVCD = _$REVCD
    ORDER BY MSTEQMREV_DETAIL.SORTNO, MSTEQMREV_DETAIL.CHKKNDCD;

    -- 개정 이력 (전체 리비전별 최종 상태 한 건씩)
    SELECT MSTEQMREV_HEADER.REVNUM,
           LEFT(CASE WHEN MSTEQMREV_HEADER.APRVSTT = 'A' THEN MSTEQMREV_HEADER.APRVTIME ELSE MSTEQMREV_HEADER.REQTIME END, 10) AS REVDATE,
           CASE MSTEQMREV_HEADER.APRVSTT
             WHEN 'A' THEN '승인'
             WHEN 'R' THEN '반려'
             ELSE '대기' END AS APRVSTTNM,
           MSTEQMREV_HEADER.APRVSTT,
           MSTEQMREV_HEADER.REMARK,
           COALESCE(REQ_EMP.EMPNM, MSTEQMREV_HEADER.REQEMP) AS REQEMPNM,
           CASE WHEN MSTEQMREV_HEADER.APRVSTT = 'A' THEN COALESCE(APRV_EMP.EMPNM, MSTEQMREV_HEADER.APRVEMP) ELSE '' END AS APRVEMPNM
    FROM MSTEQMREV_HEADER
    LEFT JOIN MSTEMP REQ_EMP
      ON REQ_EMP.EMPCD = MSTEQMREV_HEADER.REQEMP
    LEFT JOIN MSTEMP APRV_EMP
      ON APRV_EMP.EMPCD = MSTEQMREV_HEADER.APRVEMP
    WHERE MSTEQMREV_HEADER.PLANTP = _$PLANTP
      AND MSTEQMREV_HEADER.PLANCD = _$PLANCD
    ORDER BY MSTEQMREV_HEADER.REVNUM DESC;

  -- *****************************************************************************

  WHEN 'LIST_CYCLE_EQMCD' THEN -- 설비별 월별 점검계획 조회
    IF $SYEAR = '' THEN
      CALL COMERR('조회년도를 지정해주세요.');
      LEAVE PROC;
    END IF;

    SELECT MSTEQM.FANO,
           MSTEQM.EQMNM,
           MSTEQM.EQMGRADE,
           CASE WHEN LENGTH(MSTEQM.EQMGRADE) > 0 THEN
             COALESCE(NULLIF(GPCD('FM110', MSTEQM.EQMGRADE), ''), MSTEQM.EQMGRADE)
           ELSE MSTEQM.EQMGRADE END AS EQMGRADENM,
           $SYEAR AS YEAR,
           -- 월별 점검자: 빈 값은 코드명 조회 생략, MxxCD는 저장값 유지
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_01) > 0 THEN
             COALESCE(NULLIF(GPCD('EMPCD', CHKPLANEQM_YEARPLAN.MONTH_01), ''), CHKPLANEQM_YEARPLAN.MONTH_01)
           ELSE '' END AS M01,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_01, '') AS M01CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_02) > 0 THEN
             COALESCE(NULLIF(GPCD('EMPCD', CHKPLANEQM_YEARPLAN.MONTH_02), ''), CHKPLANEQM_YEARPLAN.MONTH_02)
           ELSE '' END AS M02,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_02, '') AS M02CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_03) > 0 THEN
             COALESCE(NULLIF(GPCD('EMPCD', CHKPLANEQM_YEARPLAN.MONTH_03), ''), CHKPLANEQM_YEARPLAN.MONTH_03)
           ELSE '' END AS M03,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_03, '') AS M03CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_04) > 0 THEN
             COALESCE(NULLIF(GPCD('EMPCD', CHKPLANEQM_YEARPLAN.MONTH_04), ''), CHKPLANEQM_YEARPLAN.MONTH_04)
           ELSE '' END AS M04,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_04, '') AS M04CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_05) > 0 THEN
             COALESCE(NULLIF(GPCD('EMPCD', CHKPLANEQM_YEARPLAN.MONTH_05), ''), CHKPLANEQM_YEARPLAN.MONTH_05)
           ELSE '' END AS M05,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_05, '') AS M05CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_06) > 0 THEN
             COALESCE(NULLIF(GPCD('EMPCD', CHKPLANEQM_YEARPLAN.MONTH_06), ''), CHKPLANEQM_YEARPLAN.MONTH_06)
           ELSE '' END AS M06,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_06, '') AS M06CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_07) > 0 THEN
             COALESCE(NULLIF(GPCD('EMPCD', CHKPLANEQM_YEARPLAN.MONTH_07), ''), CHKPLANEQM_YEARPLAN.MONTH_07)
           ELSE '' END AS M07,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_07, '') AS M07CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_08) > 0 THEN
             COALESCE(NULLIF(GPCD('EMPCD', CHKPLANEQM_YEARPLAN.MONTH_08), ''), CHKPLANEQM_YEARPLAN.MONTH_08)
           ELSE '' END AS M08,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_08, '') AS M08CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_09) > 0 THEN
             COALESCE(NULLIF(GPCD('EMPCD', CHKPLANEQM_YEARPLAN.MONTH_09), ''), CHKPLANEQM_YEARPLAN.MONTH_09)
           ELSE '' END AS M09,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_09, '') AS M09CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_10) > 0 THEN
             COALESCE(NULLIF(GPCD('EMPCD', CHKPLANEQM_YEARPLAN.MONTH_10), ''), CHKPLANEQM_YEARPLAN.MONTH_10)
           ELSE '' END AS M10,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_10, '') AS M10CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_11) > 0 THEN
             COALESCE(NULLIF(GPCD('EMPCD', CHKPLANEQM_YEARPLAN.MONTH_11), ''), CHKPLANEQM_YEARPLAN.MONTH_11)
           ELSE '' END AS M11,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_11, '') AS M11CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_12) > 0 THEN
             COALESCE(NULLIF(GPCD('EMPCD', CHKPLANEQM_YEARPLAN.MONTH_12), ''), CHKPLANEQM_YEARPLAN.MONTH_12)
           ELSE '' END AS M12,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_12, '') AS M12CD,
           IFNULL(CHKPLANEQM_YEARPLAN.REMARK, '') AS REMARK
    FROM MSTEQM
    LEFT JOIN CHKPLANEQM_YEARPLAN
      ON CHKPLANEQM_YEARPLAN.EQMCD = MSTEQM.FANO
     AND CHKPLANEQM_YEARPLAN.YEAR = $SYEAR
     AND CHKPLANEQM_YEARPLAN.CHKTP = '02'
    WHERE MSTEQM.USEYN = 'Y'
      AND (MSTEQM.FANO LIKE CONCAT('%', $FANO, '%') OR MSTEQM.EQMNM LIKE CONCAT('%', $FANO, '%'))
    ORDER BY MSTEQM.FANO;

  -- *****************************************************************************

  WHEN 'SAVE_CYCLE_EQMCD' THEN -- 설비별 월별 점검계획 저장
    WHILE LENGTH($FANO_LIST) > 0 DO
      CALL COMSPLIT($FANO_LIST, _$FANO);
      CALL COMSPLIT($YEAR_LIST, _$YEAR);
      CALL COMSPLIT($M01_LIST, _$M01);
      CALL COMSPLIT($M02_LIST, _$M02);
      CALL COMSPLIT($M03_LIST, _$M03);
      CALL COMSPLIT($M04_LIST, _$M04);
      CALL COMSPLIT($M05_LIST, _$M05);
      CALL COMSPLIT($M06_LIST, _$M06);
      CALL COMSPLIT($M07_LIST, _$M07);
      CALL COMSPLIT($M08_LIST, _$M08);
      CALL COMSPLIT($M09_LIST, _$M09);
      CALL COMSPLIT($M10_LIST, _$M10);
      CALL COMSPLIT($M11_LIST, _$M11);
      CALL COMSPLIT($M12_LIST, _$M12);
      CALL COMSPLIT($REMARK_LIST, _$REMARK);

      IF NOT EXISTS (SELECT 1 FROM MSTEQM WHERE FANO = _$FANO AND USEYN = 'Y') THEN
        CALL COMERR('사용 중인 설비를 선택해주세요.');
        LEAVE PROC;
      END IF;

      -- 정기점검 실적이 있는 월은 점검자 변경·삭제 불가 (점검자가 없던 월에 새로 지정하는 것은 허용)
      SELECT GROUP_CONCAT(DISTINCT CONCAT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED), '월')
                          ORDER BY SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) SEPARATOR ', ')
        INTO _$LOCKMM
      FROM CHKRSTEQM
      INNER JOIN CHKPLANEQM_YEARPLAN
        ON CHKPLANEQM_YEARPLAN.EQMCD = CHKRSTEQM.EQMCD
       AND CHKPLANEQM_YEARPLAN.YEAR = _$YEAR
       AND CHKPLANEQM_YEARPLAN.CHKTP = '02'
      WHERE CHKRSTEQM.EQMCD = _$FANO
        AND CHKRSTEQM.CHKTP = '02'
        AND CHKRSTEQM.BASEDATE LIKE CONCAT(_$YEAR, '-%')
        AND IFNULL(ELT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED),
                    CHKPLANEQM_YEARPLAN.MONTH_01, CHKPLANEQM_YEARPLAN.MONTH_02, CHKPLANEQM_YEARPLAN.MONTH_03,
                    CHKPLANEQM_YEARPLAN.MONTH_04, CHKPLANEQM_YEARPLAN.MONTH_05, CHKPLANEQM_YEARPLAN.MONTH_06,
                    CHKPLANEQM_YEARPLAN.MONTH_07, CHKPLANEQM_YEARPLAN.MONTH_08, CHKPLANEQM_YEARPLAN.MONTH_09,
                    CHKPLANEQM_YEARPLAN.MONTH_10, CHKPLANEQM_YEARPLAN.MONTH_11, CHKPLANEQM_YEARPLAN.MONTH_12), '') <> ''
        AND IFNULL(ELT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED),
                    CHKPLANEQM_YEARPLAN.MONTH_01, CHKPLANEQM_YEARPLAN.MONTH_02, CHKPLANEQM_YEARPLAN.MONTH_03,
                    CHKPLANEQM_YEARPLAN.MONTH_04, CHKPLANEQM_YEARPLAN.MONTH_05, CHKPLANEQM_YEARPLAN.MONTH_06,
                    CHKPLANEQM_YEARPLAN.MONTH_07, CHKPLANEQM_YEARPLAN.MONTH_08, CHKPLANEQM_YEARPLAN.MONTH_09,
                    CHKPLANEQM_YEARPLAN.MONTH_10, CHKPLANEQM_YEARPLAN.MONTH_11, CHKPLANEQM_YEARPLAN.MONTH_12), '') <> IFNULL(ELT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED),
                    _$M01, _$M02, _$M03, _$M04, _$M05, _$M06,
                    _$M07, _$M08, _$M09, _$M10, _$M11, _$M12), '');

      IF _$LOCKMM IS NOT NULL THEN
        CALL COMERR(CONCAT('[', _$FANO, '] ', _$YEAR, '년 ', _$LOCKMM, '은 정기점검 실적이 있어 점검자를 변경·삭제할 수 없습니다. 설비 정기점검 등록에서 해당 월 점검 실적을 먼저 삭제해주세요.'));
        LEAVE PROC;
      END IF;
    
      IF EXISTS (SELECT 1 FROM CHKPLANEQM_YEARPLAN WHERE EQMCD = _$FANO AND YEAR = _$YEAR AND CHKTP = '02') THEN  
        UPDATE CHKPLANEQM_YEARPLAN
        SET MONTH_01 = _$M01,
            MONTH_02 = _$M02,
            MONTH_03 = _$M03,
            MONTH_04 = _$M04,
            MONTH_05 = _$M05,
            MONTH_06 = _$M06,
            MONTH_07 = _$M07,
            MONTH_08 = _$M08,
            MONTH_09 = _$M09,
            MONTH_10 = _$M10,
            MONTH_11 = _$M11,
            MONTH_12 = _$M12,
            REMARK   = _$REMARK,
            MTIME    = CALLTIME(),
            MEMP     = CALLEMP(),
            MPRG     = CALLPRG()
        WHERE EQMCD = _$FANO
          AND YEAR  = _$YEAR
          AND CHKTP = '02';
          
        IF EXISTS (
          SELECT 1 FROM CHKPLANEQM_YEARPLAN
          WHERE EQMCD = _$FANO AND YEAR = _$YEAR AND CHKTP = '02' AND REMARK = ''
            AND MONTH_01 = '' AND MONTH_02 = '' AND MONTH_03 = '' AND MONTH_04 = ''
            AND MONTH_05 = '' AND MONTH_06 = '' AND MONTH_07 = '' AND MONTH_08 = ''
            AND MONTH_09 = '' AND MONTH_10 = '' AND MONTH_11 = '' AND MONTH_12 = ''
        ) THEN
          DELETE FROM CHKPLANEQM_YEARPLAN 
          WHERE EQMCD = _$FANO 
            AND YEAR  = _$YEAR 
            AND CHKTP = '02';
        END IF;  
      ELSE
        INSERT INTO CHKPLANEQM_YEARPLAN (
          EQMCD, CHKTP, YEAR, 
          MONTH_01, MONTH_02, MONTH_03, MONTH_04, 
          MONTH_05, MONTH_06, MONTH_07, MONTH_08, 
          MONTH_09, MONTH_10, MONTH_11, MONTH_12, 
          REMARK, RTIME, REMP, RPRG
        ) VALUES (
          _$FANO, '02', _$YEAR,
          _$M01, _$M02, _$M03, _$M04,
          _$M05, _$M06, _$M07, _$M08,
          _$M09, _$M10, _$M11, _$M12,
          _$REMARK, CALLTIME(), CALLEMP(), CALLPRG()
        );
     
        IF EXISTS (
          SELECT 1 FROM CHKPLANEQM_YEARPLAN
          WHERE EQMCD = _$FANO AND YEAR = _$YEAR AND CHKTP = '02' AND REMARK = ''
            AND MONTH_01 = '' AND MONTH_02 = '' AND MONTH_03 = '' AND MONTH_04 = ''
            AND MONTH_05 = '' AND MONTH_06 = '' AND MONTH_07 = '' AND MONTH_08 = ''
            AND MONTH_09 = '' AND MONTH_10 = '' AND MONTH_11 = '' AND MONTH_12 = ''
        ) THEN
          DELETE FROM CHKPLANEQM_YEARPLAN 
          WHERE EQMCD = _$FANO
            AND YEAR  = _$YEAR 
            AND CHKTP = '02';
        END IF;
      END IF;
    END WHILE;

  -- *****************************************************************************

  WHEN 'DELETE_CYCLE_EQMCD' THEN -- 설비별 월별 점검계획 삭제
    WHILE LENGTH($FANO_LIST) > 0 DO
      CALL COMSPLIT($FANO_LIST, _$FANO);
      CALL COMSPLIT($YEAR_LIST, _$YEAR);

      IF NOT EXISTS (SELECT 1 FROM MSTEQM WHERE FANO = _$FANO AND USEYN = 'Y') THEN
        CALL COMERR('사용 중인 설비를 선택해주세요.');
        LEAVE PROC;
      END IF;

      -- 정기점검 실적이 있는 월이 있으면 삭제 불가
      SELECT GROUP_CONCAT(DISTINCT CONCAT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED), '월')
                          ORDER BY SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) SEPARATOR ', ')
        INTO _$LOCKMM
      FROM CHKRSTEQM
      INNER JOIN CHKPLANEQM_YEARPLAN
        ON CHKPLANEQM_YEARPLAN.EQMCD = CHKRSTEQM.EQMCD
       AND CHKPLANEQM_YEARPLAN.YEAR = _$YEAR
       AND CHKPLANEQM_YEARPLAN.CHKTP = '02'
      WHERE CHKRSTEQM.EQMCD = _$FANO
        AND CHKRSTEQM.CHKTP = '02'
        AND CHKRSTEQM.BASEDATE LIKE CONCAT(_$YEAR, '-%')
        AND IFNULL(ELT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED),
                    CHKPLANEQM_YEARPLAN.MONTH_01, CHKPLANEQM_YEARPLAN.MONTH_02, CHKPLANEQM_YEARPLAN.MONTH_03,
                    CHKPLANEQM_YEARPLAN.MONTH_04, CHKPLANEQM_YEARPLAN.MONTH_05, CHKPLANEQM_YEARPLAN.MONTH_06,
                    CHKPLANEQM_YEARPLAN.MONTH_07, CHKPLANEQM_YEARPLAN.MONTH_08, CHKPLANEQM_YEARPLAN.MONTH_09,
                    CHKPLANEQM_YEARPLAN.MONTH_10, CHKPLANEQM_YEARPLAN.MONTH_11, CHKPLANEQM_YEARPLAN.MONTH_12), '') <> '';

      IF _$LOCKMM IS NOT NULL THEN
        CALL COMERR(CONCAT('[', _$FANO, '] ', _$YEAR, '년 ', _$LOCKMM, '은 정기점검 실적이 있어 점검자를 삭제할 수 없습니다. 설비 정기점검 등록에서 해당 월 점검 실적을 먼저 삭제해주세요.'));
        LEAVE PROC;
      END IF;
    
      DELETE FROM CHKPLANEQM_YEARPLAN 
      WHERE EQMCD = _$FANO 
        AND YEAR  = _$YEAR 
        AND CHKTP = '02';
    END WHILE;

  -- *****************************************************************************

  END CASE;

  END IF;
END
