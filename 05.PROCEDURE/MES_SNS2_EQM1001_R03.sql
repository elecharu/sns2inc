    COALESCE(NULLIF(GPCD('EMPCD', CHKPLANEQM_YEARPLAN.MONTH_07), ''), IFNULL(CHKPLANEQM_YEARPLAN.MONTH_07, '')) AS M07,
    IFNULL(CHKPLANEQM_YEARPLAN.MONTH_07, '') AS M07CD,
    COALESCE(NULLIF(GPCD('EMPCD', CHKPLANEQM_YEARPLAN.MONTH_08), ''), IFNULL(CHKPLANEQM_YEARPLAN.MONTH_08, '')) AS M08,
    IFNULL(CHKPLANEQM_YEARPLAN.MONTH_08, '') AS M08CD,
    COALESCE(NULLIF(GPCD('EMPCD', CHKPLANEQM_YEARPLAN.MONTH_09), ''), IFNULL(CHKPLANEQM_YEARPLAN.MONTH_09, '')) AS M09,
    IFNULL(CHKPLANEQM_YEARPLAN.MONTH_09, '') AS M09CD,
    COALESCE(NULLIF(GPCD('EMPCD', CHKPLANEQM_YEARPLAN.MONTH_10), ''), IFNULL(CHKPLANEQM_YEARPLAN.MONTH_10, '')) AS M10,
