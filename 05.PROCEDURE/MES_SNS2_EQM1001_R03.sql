CREATE DEFINER=`root`@`%` PROCEDURE `MES_SNS2`.`EQM1001_R03`(
-- *****************************************************************************
-- Comment: 설비점검계획 
-- Create: 	2025-06-27  	생성 			이대규
-- Modify: 	2026-09-15 		마이그레이션	한성수
-- 			2026-10-12 					한성수	승인 상태 체계 단순화 (대기·승인 통일)
-- 			2026-10-20 					한성수	설비 목록 조회 잉여 컬럼 및 조인 정리
-- 			2026-10-23 					한성수	리비전 헤더 점검구분('02') 기본값 저장
-- 			2026-11-06 					한성수	계획서 출력 특이사항 연동 및 점검자명 조회 최적화
-- 			2026-11-09 					한성수	정기점검('02') REV 분리·조회, 월별 점검계획 출력 추가 및 삭제 검증 보강
-- 			2026-11-16 					한성수	설비 분류·공장 필터 추가, 주기관리 잠금·등급별 주기 검증, 승인 제거 및 REV 갱신·삭제 추가, 실적 REV 항목 변경 차단
-- *****************************************************************************
  IN $FANO           VARCHAR(20),
  IN $FANO_COPY      VARCHAR(20),
  IN $SYEAR          VARCHAR(50),
  IN $EQMGRP         VARCHAR(50),
  IN $FACTORYCD      VARCHAR(20),
  IN $LINECD         VARCHAR(20),
  IN $EQMTP          VARCHAR(20),
  IN $EQMGROUP1      VARCHAR(20),
  IN $CHKKNDCD_LIST  MEDIUMTEXT,
  IN $REMARK_LIST    MEDIUMTEXT,
  IN $SORTNO_LIST    MEDIUMTEXT,
  IN $YEAR_LIST      MEDIUMTEXT,
  IN $FANO_LIST      MEDIUMTEXT,
  IN $M01_LIST       MEDIUMTEXT,
  IN $M02_LIST       MEDIUMTEXT,
  IN $M03_LIST       MEDIUMTEXT,
  IN $M04_LIST       MEDIUMTEXT,
  IN $M05_LIST       MEDIUMTEXT,
  IN $M06_LIST       MEDIUMTEXT,
  IN $M07_LIST       MEDIUMTEXT,
  IN $M08_LIST       MEDIUMTEXT,
  IN $M09_LIST       MEDIUMTEXT,
  IN $M10_LIST       MEDIUMTEXT,
  IN $M11_LIST       MEDIUMTEXT,
  IN $M12_LIST       MEDIUMTEXT,
  IN $PLANTP         CHAR(1),
  IN $PLANCD         VARCHAR(50),
  IN $REVNUM         VARCHAR(20),
  IN $REMARK         VARCHAR(1000),

-- *****************************************************************************
  IN $CALLTYPE       VARCHAR(50),
  IN $KEYWORD        VARCHAR(1000)
)
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  DECLARE _$CHKKNDCD      VARCHAR(20);
  DECLARE _$REMARK        VARCHAR(1000);
  DECLARE _$SORTNO        DECIMAL(20, 8);
  DECLARE _$MAXSORTNO     DECIMAL(20, 8);

  DECLARE _$M01           VARCHAR(20);
  DECLARE _$M02           VARCHAR(20);
  DECLARE _$M03           VARCHAR(20);
  DECLARE _$M04           VARCHAR(20);
  DECLARE _$M05           VARCHAR(20);
  DECLARE _$M06           VARCHAR(20);
  DECLARE _$M07           VARCHAR(20);
  DECLARE _$M08           VARCHAR(20);
  DECLARE _$M09           VARCHAR(20);
  DECLARE _$M10           VARCHAR(20);
  DECLARE _$M11           VARCHAR(20);
  DECLARE _$M12           VARCHAR(20);
  DECLARE _$YEAR          VARCHAR(20);
  DECLARE _$FANO          VARCHAR(20);
  DECLARE _$LOCKMM        VARCHAR(100);
  DECLARE _$GRADENM       VARCHAR(100);
  DECLARE _$CHKCYCLE      VARCHAR(10);
  DECLARE _$CHKCNT        INT;
  DECLARE _$CHKYEAR       INT;
  DECLARE _$NEWCNT        INT;
  DECLARE _$OLDCNT        INT;
  DECLARE _$PREVCNT       INT;
  DECLARE _$NEXTCNT       INT;
  DECLARE _$PLANTP        CHAR(1);
  DECLARE _$PLANCD        VARCHAR(50);
  DECLARE _$EQMGRPNM      VARCHAR(1000);
  DECLARE _$LOCKKEY       VARCHAR(50);
  DECLARE _$OLDREVCD      VARCHAR(20);
  DECLARE _$COPYREVCD     VARCHAR(20);
  DECLARE _$NEWREV        INT DEFAULT 0;
  DECLARE _$REVCD         VARCHAR(20);
  DECLARE _$REVNUM        INT;
  DECLARE _$NEXTREVNUM    INT;
  DECLARE _$PLAN_CHANGED  INT DEFAULT 0;
  DECLARE _$REQTIME       VARCHAR(19);
  DECLARE _$REVDATE       VARCHAR(10);

  -- 그룹·설비 공통 CRUD: 선택 대상의 작업 REV만 변경
  IF $CALLTYPE IN ('REG_GRP_EQM02', 'SAVE_GRP_EQM02', 'DEL_GRP_EQM02', 'COPY_GRP_EQM02',
                   'REG_EQM02', 'SAVE_EQM02', 'DEL_EQM02', 'COPY_EQM02') THEN
    SET _$PLANTP = IF($CALLTYPE LIKE '%GRP%', 'G', 'E');
    SET _$PLANCD = IF(_$PLANTP = 'G', $EQMGRP, $FANO);

    IF COALESCE(_$PLANCD, '') = '' THEN
      CALL COMERR(IF(_$PLANTP = 'G', '설비그룹을 지정해주세요.', '설비를 지정해주세요.'));
      LEAVE PROC;
    END IF;

    -- 같은 대상의 동시 변경은 기준정보 행에서 직렬화
    IF _$PLANTP = 'G' THEN
      SET _$LOCKKEY = (SELECT TPCD FROM COMTYPE WHERE GPCD = 'FM116' AND TPCD = _$PLANCD AND USEYN = 'Y' LIMIT 1 FOR UPDATE);

      IF NOT EXISTS (SELECT 1 FROM MSTEQM WHERE EQMGUBUN = _$PLANCD AND USEYN = 'Y' LIMIT 1) THEN
        SET _$LOCKKEY = NULL;
      END IF;
    ELSE
      SET _$LOCKKEY = (SELECT FANO FROM MSTEQM WHERE FANO = _$PLANCD AND USEYN = 'Y' LIMIT 1 FOR UPDATE);
    END IF;

    IF _$LOCKKEY IS NULL THEN
      CALL COMERR('사용 중인 설비그룹 또는 설비를 선택해주세요.');
      LEAVE PROC;
    END IF;

    -- 수정 대상: 정기점검(CHKTP '02') 최신 REV
    SET _$REVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE CHKTP = '02' AND PLANTP = _$PLANTP AND PLANCD = _$PLANCD ORDER BY REVNUM DESC LIMIT 1 FOR UPDATE);

    IF _$REVCD IS NOT NULL THEN
      SET _$REVNUM = (SELECT REVNUM FROM MSTEQMREV_HEADER WHERE REVCD = _$REVCD);
    END IF;

    IF COALESCE($REVNUM, '') <> '' AND ($REVNUM NOT REGEXP '^[0-9]+$' OR _$REVNUM IS NULL OR _$REVNUM <> CAST($REVNUM AS UNSIGNED)) THEN
      CALL COMERR('점검계획이 변경되었습니다. 최신 REV를 다시 조회해주세요.');
      LEAVE PROC;
    END IF;

    -- 점검 실적이 등록된 REV는 항목 변경 불가 (계획서 REV와 실제 점검한 REV 항목 일치 유지, 리비전 갱신 후 새 REV에서 수정)
    IF _$REVCD IS NOT NULL AND EXISTS (SELECT 1 FROM CHKRSTEQM WHERE REVCD = _$REVCD OR GRPREVCD = _$REVCD LIMIT 1) THEN
      CALL COMERR(CONCAT('[', _$PLANCD, '] REV.', _$REVNUM, '에 점검 실적이 있어 항목을 변경할 수 없습니다. [리비전 갱신] 후 새 REV에서 수정해주세요.'));
      LEAVE PROC;
    END IF;

    IF $CALLTYPE LIKE 'COPY%' THEN
      IF COALESCE($FANO_COPY, '') = '' OR $FANO_COPY = _$PLANCD THEN
        CALL COMERR('다른 설비그룹 또는 설비를 복사 원본으로 선택해주세요.');
        LEAVE PROC;
      END IF;

      IF (_$PLANTP = 'G' AND NOT EXISTS (SELECT 1 FROM COMTYPE WHERE GPCD = 'FM116' AND TPCD = $FANO_COPY AND USEYN = 'Y' LIMIT 1))
         OR (_$PLANTP = 'E' AND NOT EXISTS (SELECT 1 FROM MSTEQM WHERE FANO = $FANO_COPY AND USEYN = 'Y' LIMIT 1)) THEN
        CALL COMERR('사용 중인 복사 원본을 선택해주세요.');
        LEAVE PROC;
      END IF;

      SET _$COPYREVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE CHKTP = '02' AND PLANTP = _$PLANTP AND PLANCD = $FANO_COPY ORDER BY REVNUM DESC LIMIT 1);

      IF NOT EXISTS (SELECT 1 FROM MSTEQMREV_DETAIL WHERE REVCD = _$COPYREVCD LIMIT 1) THEN
        CALL COMERR('복사할 정기점검 항목이 없습니다.');
        LEAVE PROC;
      END IF;
    ELSEIF COALESCE($CHKKNDCD_LIST, '') = '' THEN
      CALL COMERR('정기점검 항목을 선택해주세요.');
      LEAVE PROC;
    END IF;

    -- 항목 변경은 최신 REV(사용 리비전)에 바로 반영, 새 개정은 [리비전 갱신](RENEW_REV)으로 생성
    -- REV가 하나도 없으면 첫 REV(제정)를 만들어 반영
    IF _$REVCD IS NULL THEN
      SET _$REVCD    = GETKEY('REVCD');
      SET _$NEWREV   = 1;

      -- 새 REV 번호: 고유키(PLANTP, PLANCD, REVNUM)를 일상점검과 함께 쓰므로 점검구분과 무관한 최대 번호 다음
      SET _$NEXTREVNUM = (SELECT COALESCE(MAX(REVNUM) + 1, 0) FROM MSTEQMREV_HEADER WHERE PLANTP = _$PLANTP AND PLANCD = _$PLANCD);

      INSERT INTO MSTEQMREV_HEADER (
        REVCD, CHKTP, PLANTP, PLANCD, REVNUM, REQTIME, REQEMP, REQPRG, RTIME, REMP, RPRG
      ) VALUES (
        _$REVCD, '02', _$PLANTP, _$PLANCD, _$NEXTREVNUM, CALLTIME(), CALLEMP(), CALLPRG(), CALLTIME(), CALLEMP(), CALLPRG()
      );
    END IF;

    CASE SUBSTRING_INDEX($CALLTYPE, '_', 1)
    -- *****************************************************************************

    WHEN 'REG' THEN -- 정기점검 항목 등록
      WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
        CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);
        CALL COMSPLIT($REMARK_LIST, _$REMARK);

        IF NOT EXISTS (SELECT 1 FROM MSTCHKKND WHERE CHKKNDCD = _$CHKKNDCD AND CHKTP = '02' AND USEYN = 'Y' LIMIT 1) THEN
          CALL COMERR('사용 중인 정기점검 항목만 추가할 수 있습니다.');
          LEAVE PROC;
        END IF;

        IF NOT EXISTS (SELECT 1 FROM MSTEQMREV_DETAIL WHERE REVCD = _$REVCD AND CHKKNDCD = _$CHKKNDCD LIMIT 1) THEN
          SET _$MAXSORTNO = (SELECT COALESCE(MAX(SORTNO), 0) FROM MSTEQMREV_DETAIL WHERE REVCD = _$REVCD);

          INSERT INTO MSTEQMREV_DETAIL (
            REVCD, CHKKNDCD, CHKCYCLE, SORTNO, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, REMARK, RTIME, REMP, RPRG
          )
          SELECT _$REVCD, CHKKNDCD, 'MONTH', _$MAXSORTNO + 1, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP,
                 COALESCE(NULLIF(_$REMARK, ''), MSTCHKKND.REMARK, ''),
                 CALLTIME(), CALLEMP(), CALLPRG()
          FROM MSTCHKKND
          WHERE CHKKNDCD = _$CHKKNDCD;

          SET _$PLAN_CHANGED = _$PLAN_CHANGED + ROW_COUNT();
        END IF;
      END WHILE;

    -- *****************************************************************************

    WHEN 'SAVE' THEN -- 정기점검 항목 저장
      WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
        CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);
        CALL COMSPLIT($SORTNO_LIST, _$SORTNO);
        CALL COMSPLIT($REMARK_LIST, _$REMARK);

        IF _$SORTNO IS NULL
           OR NOT EXISTS (SELECT 1 FROM MSTEQMREV_DETAIL WHERE REVCD = _$REVCD AND CHKKNDCD = _$CHKKNDCD LIMIT 1) THEN
          CALL COMERR('저장할 점검항목과 정렬순서를 확인해주세요.');
          LEAVE PROC;
        END IF;

        UPDATE MSTEQMREV_DETAIL
        SET SORTNO = _$SORTNO,
            REMARK = CASE WHEN _$REMARK IS NOT NULL AND _$REMARK != '' THEN _$REMARK ELSE REMARK END,
            MTIME  = CALLTIME(),
            MEMP   = CALLEMP(),
            MPRG   = CALLPRG()
        WHERE REVCD = _$REVCD
          AND CHKKNDCD = _$CHKKNDCD
          AND NOT (SORTNO <=> _$SORTNO AND REMARK <=> (CASE WHEN _$REMARK IS NOT NULL AND _$REMARK != '' THEN _$REMARK ELSE REMARK END));

        SET _$PLAN_CHANGED = _$PLAN_CHANGED + ROW_COUNT();
      END WHILE;

    -- *****************************************************************************

    WHEN 'DEL' THEN -- 작업 REV의 정기점검 항목 삭제
      WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
        CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);

        DELETE FROM MSTEQMREV_DETAIL
        WHERE REVCD = _$REVCD
          AND CHKKNDCD = _$CHKKNDCD;

        SET _$PLAN_CHANGED = _$PLAN_CHANGED + ROW_COUNT();
      END WHILE;

    -- *****************************************************************************

    WHEN 'COPY' THEN -- 선택 대상의 항목 전체 교체
      DELETE FROM MSTEQMREV_DETAIL
      WHERE REVCD = _$REVCD;

      INSERT INTO MSTEQMREV_DETAIL (
        REVCD, CHKKNDCD, CHKCYCLE, SORTNO, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, REMARK, RTIME, REMP, RPRG
      )
      SELECT _$REVCD, CHKKNDCD, CHKCYCLE, SORTNO, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, REMARK,
             CALLTIME(), CALLEMP(), CALLPRG()
      FROM MSTEQMREV_DETAIL
      WHERE REVCD = _$COPYREVCD;

      SET _$PLAN_CHANGED = ROW_COUNT();

    -- *****************************************************************************

    END CASE;

    -- 삭제할 정기점검 항목이 없으면 (화면 항목이 최신 정기점검 REV에 없음) 새로 만든 REV를 지우고 안내
    IF _$PLAN_CHANGED = 0 AND SUBSTRING_INDEX($CALLTYPE, '_', 1) = 'DEL' THEN
      IF _$NEWREV = 1 THEN
        DELETE FROM MSTEQMREV_DETAIL WHERE REVCD = _$REVCD;
        DELETE FROM MSTEQMREV_HEADER WHERE REVCD = _$REVCD;
      END IF;
      CALL COMERR('삭제할 정기점검 항목이 없습니다. 화면을 다시 조회해주세요.');
      LEAVE PROC;
    END IF;

    IF _$PLAN_CHANGED > 0 THEN
      UPDATE MSTEQMREV_HEADER
      SET MTIME   = CALLTIME(),
          MEMP    = CALLEMP(),
          MPRG    = CALLPRG()
      WHERE REVCD = _$REVCD;
    ELSEIF _$NEWREV = 1 THEN
      DELETE FROM MSTEQMREV_DETAIL WHERE REVCD = _$REVCD;
      DELETE FROM MSTEQMREV_HEADER WHERE REVCD = _$REVCD;
    END IF;

  ELSE

  CASE $CALLTYPE
  -- *****************************************************************************

  WHEN 'LIST_MSTEQM_GRP' THEN -- 설비그룹 최신 리비전 조회
    -- 같은 이름의 그룹코드 함께 조회
    SET _$EQMGRPNM = (SELECT TPNM FROM COMTYPE WHERE GPCD = 'FM116' AND TPCD = $EQMGRP LIMIT 1);

    SELECT GRP_EQM.EQMGUBUN,
           COMTYPE.TPNM AS EQMGRPNM,
           COMTYPE.SORTNO AS EQMGRPSORTNO,
           PLAN_REV.REVCD,
           COALESCE(CONCAT('REV.', PLAN_REV.REVNUM), '') AS REVNM
    FROM COMTYPE
    INNER JOIN (
      SELECT DISTINCT EQMGUBUN
      FROM MSTEQM
      WHERE USEYN = 'Y'
    ) GRP_EQM ON GRP_EQM.EQMGUBUN = COMTYPE.TPCD
    LEFT JOIN (
      SELECT PLANCD, MAX(REVNUM) AS REVNUM
      FROM MSTEQMREV_HEADER
      WHERE PLANTP = 'G' AND CHKTP = '02'
      GROUP BY PLANCD
    ) LAST_REV ON LAST_REV.PLANCD = GRP_EQM.EQMGUBUN
    LEFT JOIN MSTEQMREV_HEADER PLAN_REV
      ON PLAN_REV.PLANTP = 'G'
     AND PLAN_REV.PLANCD = LAST_REV.PLANCD
     AND PLAN_REV.REVNUM = LAST_REV.REVNUM
    WHERE COMTYPE.GPCD = 'FM116'
      AND COMTYPE.USEYN = 'Y'
      AND ($EQMGRP IS NULL OR $EQMGRP = '' OR COMTYPE.TPNM = _$EQMGRPNM)
    ORDER BY COMTYPE.SORTNO, GRP_EQM.EQMGUBUN;

  -- *****************************************************************************

  WHEN 'LIST_GRP_EQM02' THEN -- 최신 정기점검 항목 조회
    SET _$REVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'G' AND PLANCD = $EQMGRP AND CHKTP = '02' ORDER BY REVNUM DESC LIMIT 1);

    SELECT MSTEQMREV_DETAIL.CHKKNDCD,
           MSTEQMREV_DETAIL.CHKKNDNM,
           MSTEQMREV_DETAIL.CHKLOC,
           MSTEQMREV_DETAIL.CHKMTH,
           MSTEQMREV_DETAIL.CHKVALTP,
           COALESCE(NULLIF(GPCD('CHKLOC', MSTEQMREV_DETAIL.CHKLOC), ''), MSTEQMREV_DETAIL.CHKLOC) AS CHKLOCNM,
           COALESCE(NULLIF(GPCD('CHKMTH', MSTEQMREV_DETAIL.CHKMTH), ''), MSTEQMREV_DETAIL.CHKMTH) AS CHKMTHNM,
           COALESCE(NULLIF(GPCD('CHKVALTP', MSTEQMREV_DETAIL.CHKVALTP), ''), MSTEQMREV_DETAIL.CHKVALTP) AS CHKVALTPNM,
           MSTEQMREV_DETAIL.CHKCYCLE,
           MSTEQMREV_DETAIL.SORTNO,
           MSTEQMREV_DETAIL.REMARK
    FROM MSTEQMREV_DETAIL
    WHERE REVCD = _$REVCD
    ORDER BY SORTNO, CHKKNDCD;

  -- *****************************************************************************

  WHEN 'LIST_GRP_EQM02_ADD' THEN -- 미등록 정기점검 항목 조회
    SET _$REVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'G' AND PLANCD = $EQMGRP AND CHKTP = '02' ORDER BY REVNUM DESC LIMIT 1);

    SELECT MSTCHKKND.CHKKNDCD,
           MSTCHKKND.CHKKNDNM,
           MSTCHKKND.CHKLOC,
           MSTCHKKND.CHKMTH,
           MSTCHKKND.CHKVALTP,
           COALESCE(NULLIF(GPCD('CHKLOC', MSTCHKKND.CHKLOC), ''), MSTCHKKND.CHKLOC) AS CHKLOCNM,
           COALESCE(NULLIF(GPCD('CHKMTH', MSTCHKKND.CHKMTH), ''), MSTCHKKND.CHKMTH) AS CHKMTHNM,
           COALESCE(NULLIF(GPCD('CHKVALTP', MSTCHKKND.CHKVALTP), ''), MSTCHKKND.CHKVALTP) AS CHKVALTPNM,
           MSTCHKKND.CHKCYCLE,
           MSTCHKKND.SORTNO,
           COALESCE(MSTCHKKND.REMARK, '') AS REMARK,
           MSTCHKKND.CHKTP
    FROM MSTCHKKND
    LEFT JOIN MSTEQMREV_DETAIL PLAN_ITEM
      ON PLAN_ITEM.REVCD = _$REVCD
     AND PLAN_ITEM.CHKKNDCD = MSTCHKKND.CHKKNDCD
    WHERE MSTCHKKND.CHKTP = '02'
      AND MSTCHKKND.USEYN = 'Y'
      AND PLAN_ITEM.CHKKNDCD IS NULL
    ORDER BY MSTCHKKND.SORTNO, MSTCHKKND.CHKKNDCD;

  -- *****************************************************************************

  WHEN 'LIST_COPY_GRP_EQM02' THEN -- 설비그룹 복사 원본 목록
    SELECT COMTYPE.TPCD AS EQMGRP,
           COMTYPE.TPNM AS EQMGRPNM,
           COUNT(*) AS EQM02CNT
    FROM COMTYPE
    INNER JOIN MSTEQMREV_HEADER PLAN_REV
      ON PLAN_REV.PLANTP = 'G'
     AND PLAN_REV.PLANCD = COMTYPE.TPCD
    INNER JOIN (
      SELECT PLANCD, MAX(REVNUM) AS REVNUM
      FROM MSTEQMREV_HEADER
      WHERE PLANTP = 'G' AND CHKTP = '02'
      GROUP BY PLANCD
    ) LAST_REV
      ON LAST_REV.PLANCD = PLAN_REV.PLANCD
     AND LAST_REV.REVNUM = PLAN_REV.REVNUM
    INNER JOIN MSTEQMREV_DETAIL
      ON MSTEQMREV_DETAIL.REVCD = PLAN_REV.REVCD
    WHERE COMTYPE.GPCD = 'FM116'
      AND COMTYPE.USEYN = 'Y'
      AND COMTYPE.TPCD <> $EQMGRP
    GROUP BY COMTYPE.TPCD, COMTYPE.TPNM, COMTYPE.SORTNO
    ORDER BY COMTYPE.SORTNO, COMTYPE.TPCD;

  -- *****************************************************************************

  WHEN 'LIST_COPY_GRP_EQM02_DTL' THEN -- 최신 정기점검 항목 조회
    SET _$REVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'G' AND PLANCD = $EQMGRP AND CHKTP = '02' ORDER BY REVNUM DESC LIMIT 1);

    SELECT MSTEQMREV_DETAIL.CHKKNDCD,
           MSTEQMREV_DETAIL.CHKKNDNM,
           MSTEQMREV_DETAIL.CHKLOC,
           MSTEQMREV_DETAIL.CHKMTH,
           MSTEQMREV_DETAIL.CHKVALTP,
           COALESCE(NULLIF(GPCD('CHKLOC', MSTEQMREV_DETAIL.CHKLOC), ''), MSTEQMREV_DETAIL.CHKLOC) AS CHKLOCNM,
           COALESCE(NULLIF(GPCD('CHKMTH', MSTEQMREV_DETAIL.CHKMTH), ''), MSTEQMREV_DETAIL.CHKMTH) AS CHKMTHNM,
           COALESCE(NULLIF(GPCD('CHKVALTP', MSTEQMREV_DETAIL.CHKVALTP), ''), MSTEQMREV_DETAIL.CHKVALTP) AS CHKVALTPNM,
           MSTEQMREV_DETAIL.CHKCYCLE,
           MSTEQMREV_DETAIL.SORTNO,
           MSTEQMREV_DETAIL.REMARK
    FROM MSTEQMREV_DETAIL
    WHERE REVCD = _$REVCD
    ORDER BY SORTNO, CHKKNDCD;

  -- *****************************************************************************

  WHEN 'LIST_MSTEQM' THEN -- 설비 목록 조회
    SET $FACTORYCD = '07';

    SELECT MSTEQM.FANO,
           COALESCE(MSTEQM.EQMGUBUN, '') AS EQMGUBUN,
           MSTEQM.EQMNM,
           IFNULL(MSTEQM.FACTORYCD, '') AS FACTORYCD,
           IFNULL(MSTEQM.LINECD, '')    AS LINECD,
           IFNULL(MSTEQM.EQMTP, '')     AS EQMTP,
           IFNULL(MSTEQM.EQMGROUP1, '') AS EQMGROUP1,
           COALESCE(CONCAT('REV.', PLAN_REV.REVNUM), '') AS REVNM
    FROM MSTEQM
    LEFT JOIN (
      SELECT PLANCD, MAX(REVNUM) AS REVNUM
      FROM MSTEQMREV_HEADER
      WHERE PLANTP = 'E' AND CHKTP = '02'
      GROUP BY PLANCD
    ) LAST_REV ON LAST_REV.PLANCD = MSTEQM.FANO
    LEFT JOIN MSTEQMREV_HEADER PLAN_REV
      ON PLAN_REV.PLANTP = 'E'
     AND PLAN_REV.PLANCD = LAST_REV.PLANCD
     AND PLAN_REV.REVNUM = LAST_REV.REVNUM
    WHERE MSTEQM.USEYN = 'Y'
      AND ($FACTORYCD = '' OR MSTEQM.FACTORYCD = $FACTORYCD)
      AND ($LINECD = '' OR MSTEQM.LINECD = $LINECD)
      AND ($EQMTP = '' OR MSTEQM.EQMTP = $EQMTP)
      AND ($EQMGROUP1 = '' OR MSTEQM.EQMGROUP1 = $EQMGROUP1)
      AND (COALESCE($EQMGRP, '') = '' OR MSTEQM.EQMGUBUN LIKE CONCAT('%', $EQMGRP, '%'))
      AND (COALESCE($FANO, '') = '' OR MSTEQM.FANO LIKE CONCAT('%', $FANO, '%') OR MSTEQM.EQMNM LIKE CONCAT('%', $FANO, '%'))
    ORDER BY MSTEQM.FANO;

  -- *****************************************************************************

  WHEN 'LIST_MSTEQM_EQM02' THEN -- 최신 정기점검 항목 조회
    SET _$REVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'E' AND PLANCD = $FANO AND CHKTP = '02' ORDER BY REVNUM DESC LIMIT 1);

    SELECT MSTEQMREV_DETAIL.CHKKNDCD,
           MSTEQMREV_DETAIL.CHKKNDNM,
           MSTEQMREV_DETAIL.CHKLOC,
           MSTEQMREV_DETAIL.CHKMTH,
           MSTEQMREV_DETAIL.CHKVALTP,
           COALESCE(NULLIF(GPCD('CHKLOC', MSTEQMREV_DETAIL.CHKLOC), ''), MSTEQMREV_DETAIL.CHKLOC) AS CHKLOCNM,
           COALESCE(NULLIF(GPCD('CHKMTH', MSTEQMREV_DETAIL.CHKMTH), ''), MSTEQMREV_DETAIL.CHKMTH) AS CHKMTHNM,
           COALESCE(NULLIF(GPCD('CHKVALTP', MSTEQMREV_DETAIL.CHKVALTP), ''), MSTEQMREV_DETAIL.CHKVALTP) AS CHKVALTPNM,
           MSTEQMREV_DETAIL.CHKCYCLE,
           MSTEQMREV_DETAIL.SORTNO,
           MSTEQMREV_DETAIL.REMARK
    FROM MSTEQMREV_DETAIL
    WHERE REVCD = _$REVCD
    ORDER BY SORTNO, CHKKNDCD;

  -- *****************************************************************************

  WHEN 'LIST_EQM02' THEN -- 미등록 정기점검 항목 조회
    SET _$REVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'E' AND PLANCD = $FANO AND CHKTP = '02' ORDER BY REVNUM DESC LIMIT 1);

    SELECT MSTCHKKND.CHKKNDCD,
           MSTCHKKND.CHKKNDNM,
           MSTCHKKND.CHKLOC,
           MSTCHKKND.CHKMTH,
           MSTCHKKND.CHKVALTP,
           COALESCE(NULLIF(GPCD('CHKLOC', MSTCHKKND.CHKLOC), ''), MSTCHKKND.CHKLOC) AS CHKLOCNM,
           COALESCE(NULLIF(GPCD('CHKMTH', MSTCHKKND.CHKMTH), ''), MSTCHKKND.CHKMTH) AS CHKMTHNM,
           COALESCE(NULLIF(GPCD('CHKVALTP', MSTCHKKND.CHKVALTP), ''), MSTCHKKND.CHKVALTP) AS CHKVALTPNM,
           MSTCHKKND.CHKCYCLE,
           MSTCHKKND.SORTNO,
           COALESCE(MSTCHKKND.REMARK, '') AS REMARK,
           MSTCHKKND.CHKTP
    FROM MSTCHKKND
    LEFT JOIN MSTEQMREV_DETAIL PLAN_ITEM
      ON PLAN_ITEM.REVCD = _$REVCD
     AND PLAN_ITEM.CHKKNDCD = MSTCHKKND.CHKKNDCD
    WHERE MSTCHKKND.CHKTP = '02'
      AND MSTCHKKND.USEYN = 'Y'
      AND PLAN_ITEM.CHKKNDCD IS NULL
    ORDER BY MSTCHKKND.SORTNO, MSTCHKKND.CHKKNDCD;

  -- *****************************************************************************

  WHEN 'LIST_COPY_EQM02' THEN -- 설비 복사 원본 목록·상세
    SELECT MSTEQM.FANO,
           MSTEQM.EQMNM
    FROM MSTEQM
    INNER JOIN MSTEQMREV_HEADER PLAN_REV
      ON PLAN_REV.PLANTP = 'E'
     AND PLAN_REV.PLANCD = MSTEQM.FANO
    INNER JOIN (
      SELECT PLANCD, MAX(REVNUM) AS REVNUM
      FROM MSTEQMREV_HEADER
      WHERE PLANTP = 'E' AND CHKTP = '02'
      GROUP BY PLANCD
    ) LAST_REV
      ON LAST_REV.PLANCD = PLAN_REV.PLANCD
     AND LAST_REV.REVNUM = PLAN_REV.REVNUM
    INNER JOIN MSTEQMREV_DETAIL
      ON MSTEQMREV_DETAIL.REVCD = PLAN_REV.REVCD
    WHERE MSTEQM.USEYN = 'Y'
      AND MSTEQM.FANO <> $FANO
    GROUP BY MSTEQM.FANO, MSTEQM.EQMNM
    ORDER BY MSTEQM.FANO;

    SET _$REVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'E' AND PLANCD = $FANO AND CHKTP = '02' ORDER BY REVNUM DESC LIMIT 1);

    SELECT MSTEQMREV_DETAIL.CHKKNDCD,
           MSTEQMREV_DETAIL.CHKKNDNM,
           MSTEQMREV_DETAIL.CHKLOC,
           MSTEQMREV_DETAIL.CHKMTH,
           MSTEQMREV_DETAIL.CHKVALTP,
           COALESCE(NULLIF(GPCD('CHKLOC', MSTEQMREV_DETAIL.CHKLOC), ''), MSTEQMREV_DETAIL.CHKLOC) AS CHKLOCNM,
           COALESCE(NULLIF(GPCD('CHKMTH', MSTEQMREV_DETAIL.CHKMTH), ''), MSTEQMREV_DETAIL.CHKMTH) AS CHKMTHNM,
           COALESCE(NULLIF(GPCD('CHKVALTP', MSTEQMREV_DETAIL.CHKVALTP), ''), MSTEQMREV_DETAIL.CHKVALTP) AS CHKVALTPNM,
           MSTEQMREV_DETAIL.CHKCYCLE,
           MSTEQMREV_DETAIL.SORTNO,
           MSTEQMREV_DETAIL.REMARK
    FROM MSTEQMREV_DETAIL
    WHERE REVCD = _$REVCD
    ORDER BY SORTNO, CHKKNDCD;

  -- *****************************************************************************

  WHEN 'LIST_PLAN_REV' THEN -- 점검계획 리비전 이력 조회 (맨 위 최신 REV가 사용 리비전)
    SELECT CONCAT('REV.', MSTEQMREV_HEADER.REVNUM) AS REVNM,
           MSTEQMREV_HEADER.REMARK,
           COALESCE(REQ_EMP.EMPNM, MSTEQMREV_HEADER.REQEMP) AS REQEMP,
           MSTEQMREV_HEADER.REQTIME,
           MSTEQMREV_HEADER.REVNUM
    FROM MSTEQMREV_HEADER
    LEFT JOIN MSTEMP REQ_EMP
      ON REQ_EMP.EMPCD = MSTEQMREV_HEADER.REQEMP
    WHERE MSTEQMREV_HEADER.CHKTP = '02'
      AND MSTEQMREV_HEADER.PLANTP = $PLANTP
      AND MSTEQMREV_HEADER.PLANCD = $PLANCD
    ORDER BY MSTEQMREV_HEADER.REVNUM DESC;

  -- *****************************************************************************

  WHEN 'LIST_PLAN_REV_ITEM' THEN -- 선택 리비전 점검 항목 조회
    SELECT MSTEQMREV_DETAIL.CHKKNDCD,
           MSTEQMREV_DETAIL.CHKKNDNM,
           MSTEQMREV_DETAIL.CHKLOC,
           MSTEQMREV_DETAIL.CHKMTH,
           MSTEQMREV_DETAIL.CHKVALTP,
           COALESCE(NULLIF(GPCD('CHKLOC', MSTEQMREV_DETAIL.CHKLOC), ''), MSTEQMREV_DETAIL.CHKLOC) AS CHKLOCNM,
           COALESCE(NULLIF(GPCD('CHKMTH', MSTEQMREV_DETAIL.CHKMTH), ''), MSTEQMREV_DETAIL.CHKMTH) AS CHKMTHNM,
           COALESCE(NULLIF(GPCD('CHKVALTP', MSTEQMREV_DETAIL.CHKVALTP), ''), MSTEQMREV_DETAIL.CHKVALTP) AS CHKVALTPNM,
           MSTEQMREV_DETAIL.SORTNO,
           MSTEQMREV_DETAIL.REMARK
    FROM MSTEQMREV_HEADER ITEM_REV
    INNER JOIN MSTEQMREV_DETAIL
      ON MSTEQMREV_DETAIL.REVCD = ITEM_REV.REVCD
    WHERE ITEM_REV.CHKTP = '02'
      AND ITEM_REV.PLANTP = $PLANTP
      AND ITEM_REV.PLANCD = $PLANCD
      AND ITEM_REV.REVNUM = $REVNUM
    ORDER BY MSTEQMREV_DETAIL.SORTNO;

  -- *****************************************************************************

  WHEN 'SAVE_PLAN_REV' THEN -- 선택 REV 개정내용 저장 (개정내용·작성자·수정일시만 반영)
    IF COALESCE($PLANTP, '') NOT IN ('G', 'E') OR COALESCE($PLANCD, '') = '' OR COALESCE($REVNUM, '') NOT REGEXP '^[0-9]+$' THEN
      CALL COMERR('개정내용을 저장할 리비전을 선택해주세요.');
      LEAVE PROC;
    END IF;

    SET _$REVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE CHKTP = '02' AND PLANTP = $PLANTP AND PLANCD = $PLANCD AND REVNUM = $REVNUM LIMIT 1 FOR UPDATE);

    IF _$REVCD IS NULL THEN
      CALL COMERR('선택한 리비전이 없습니다. 다시 조회해주세요.');
      LEAVE PROC;
    END IF;

    IF TRIM(COALESCE($REMARK, '')) = '' THEN
      CALL COMERR('개정내용을 입력해주세요.');
      LEAVE PROC;
    END IF;

    UPDATE MSTEQMREV_HEADER
    SET REMARK  = $REMARK,
        REQTIME = CALLTIME(),
        REQEMP  = CALLEMP(),
        REQPRG  = CALLPRG(),
        MTIME   = CALLTIME(),
        MEMP    = CALLEMP(),
        MPRG    = CALLPRG()
    WHERE REVCD = _$REVCD;

  -- *****************************************************************************

  WHEN 'RENEW_REV' THEN -- 리비전 갱신 (TQC1001_R02 방식: 선택 REV의 정기점검 항목을 복사해 다음 번호 REV 생성, 최신 REV가 사용 리비전)
    IF COALESCE($PLANTP, '') NOT IN ('G', 'E') OR COALESCE($PLANCD, '') = '' THEN
      CALL COMERR('설비그룹 또는 설비를 선택해주세요.');
      LEAVE PROC;
    END IF;

    -- 같은 대상의 동시 변경은 기준정보 행에서 직렬화
    IF $PLANTP = 'G' THEN
      SET _$LOCKKEY = (SELECT TPCD FROM COMTYPE WHERE GPCD = 'FM116' AND TPCD = $PLANCD AND USEYN = 'Y' LIMIT 1 FOR UPDATE);

      IF NOT EXISTS (SELECT 1 FROM MSTEQM WHERE EQMGUBUN = $PLANCD AND USEYN = 'Y' LIMIT 1) THEN
        SET _$LOCKKEY = NULL;
      END IF;
    ELSE
      SET _$LOCKKEY = (SELECT FANO FROM MSTEQM WHERE FANO = $PLANCD AND USEYN = 'Y' LIMIT 1 FOR UPDATE);
    END IF;

    IF _$LOCKKEY IS NULL THEN
      CALL COMERR('사용 중인 설비그룹 또는 설비를 선택해주세요.');
      LEAVE PROC;
    END IF;

    -- 복사 원본: 선택 REV (REV가 하나도 없을 때만 빈 REV로 시작)
    IF COALESCE($REVNUM, '') = '' THEN
      IF EXISTS (SELECT 1 FROM MSTEQMREV_HEADER WHERE CHKTP = '02' AND PLANTP = $PLANTP AND PLANCD = $PLANCD LIMIT 1) THEN
        CALL COMERR('갱신할 리비전을 선택해주세요.');
        LEAVE PROC;
      END IF;
    ELSE
      IF $REVNUM NOT REGEXP '^[0-9]+$' THEN
        CALL COMERR('갱신할 리비전을 선택해주세요.');
        LEAVE PROC;
      END IF;

      SET _$OLDREVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE CHKTP = '02' AND PLANTP = $PLANTP AND PLANCD = $PLANCD AND REVNUM = $REVNUM LIMIT 1);

      IF _$OLDREVCD IS NULL THEN
        CALL COMERR('선택한 리비전이 없습니다. 다시 조회해주세요.');
        LEAVE PROC;
      END IF;
    END IF;

    -- 새 REV 번호: 고유키(PLANTP, PLANCD, REVNUM)를 일상점검과 함께 쓰므로 점검구분과 무관한 최대 번호 다음
    SET _$NEXTREVNUM = (SELECT COALESCE(MAX(REVNUM) + 1, 0) FROM MSTEQMREV_HEADER WHERE PLANTP = $PLANTP AND PLANCD = $PLANCD);
    SET _$REVCD = GETKEY('REVCD');

    INSERT INTO MSTEQMREV_HEADER (
      REVCD, CHKTP, PLANTP, PLANCD, REVNUM, REQTIME, REQEMP, REQPRG, RTIME, REMP, RPRG
    ) VALUES (
      _$REVCD, '02', $PLANTP, $PLANCD, _$NEXTREVNUM, CALLTIME(), CALLEMP(), CALLPRG(), CALLTIME(), CALLEMP(), CALLPRG()
    );

    INSERT INTO MSTEQMREV_DETAIL (
      REVCD, CHKKNDCD, CHKCYCLE, SORTNO, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, REMARK, RTIME, REMP, RPRG
    )
    SELECT _$REVCD, CHKKNDCD, CHKCYCLE, SORTNO, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, REMARK,
           CALLTIME(), CALLEMP(), CALLPRG()
    FROM MSTEQMREV_DETAIL
    WHERE REVCD = _$OLDREVCD;

    -- 갱신한 REV 번호 반환 (REVNUM은 저장값, REVNM은 화면 안내용)
    SELECT _$NEXTREVNUM AS REVNUM, CONCAT('REV.', _$NEXTREVNUM) AS REVNM;

  -- *****************************************************************************

  WHEN 'DEL_REV' THEN -- 리비전 삭제 (TQC1001_R02 방식: 점검 실적이 있는 REV는 삭제 불가, 남은 최신 REV가 사용 리비전)
    IF COALESCE($PLANTP, '') NOT IN ('G', 'E') OR COALESCE($PLANCD, '') = '' OR COALESCE($REVNUM, '') NOT REGEXP '^[0-9]+$' THEN
      CALL COMERR('삭제할 리비전을 선택해주세요.');
      LEAVE PROC;
    END IF;

    SET _$REVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE CHKTP = '02' AND PLANTP = $PLANTP AND PLANCD = $PLANCD AND REVNUM = $REVNUM LIMIT 1 FOR UPDATE);

    IF _$REVCD IS NULL THEN
      CALL COMERR('삭제할 리비전이 없습니다. 다시 조회해주세요.');
      LEAVE PROC;
    END IF;

    IF EXISTS (SELECT 1 FROM CHKRSTEQM WHERE REVCD = _$REVCD OR GRPREVCD = _$REVCD LIMIT 1) THEN
      CALL COMERR('해당 리비전으로 등록한 점검 실적이 있어서 삭제할 수 없습니다.');
      LEAVE PROC;
    END IF;

    DELETE FROM MSTEQMREV_DETAIL WHERE REVCD = _$REVCD;
    DELETE FROM CHKPLANEQM_APRV  WHERE REVCD = _$REVCD; -- 승인 제거 전 남은 승인 이력 정리 (테이블은 일상점검 PRD6001_R02가 계속 사용)
    DELETE FROM MSTEQMREV_HEADER WHERE REVCD = _$REVCD;

  -- *****************************************************************************

  WHEN 'CALL_PLAN_RPT' THEN -- 점검계획서 출력 데이터 조회 (설비그룹·설비)
    SET _$PLANTP = CASE WHEN $PLANTP = 'E' THEN 'E' ELSE 'G' END;
    SET _$PLANCD = $PLANCD;

    IF COALESCE(_$PLANCD, '') = '' THEN
      CALL COMERR(CASE WHEN _$PLANTP = 'E' THEN '설비를 선택해주세요.' ELSE '설비그룹을 선택해주세요.' END);
      LEAVE PROC;
    END IF;

    -- 대상 리비전 결정 ($REVNUM이 숫자로 전달되면 해당 REV, 없거나 빈 값이면 최신 REV 자동 선택)
    IF COALESCE($REVNUM, '') REGEXP '^[0-9]+$' THEN
      SELECT MSTEQMREV_HEADER.REVCD, MSTEQMREV_HEADER.REVNUM, LEFT(COALESCE(NULLIF(MSTEQMREV_HEADER.REQTIME, ''), MSTEQMREV_HEADER.RTIME), 10)
        INTO _$REVCD, _$REVNUM, _$REVDATE
      FROM MSTEQMREV_HEADER
      WHERE MSTEQMREV_HEADER.CHKTP = '02'
        AND MSTEQMREV_HEADER.PLANTP = _$PLANTP
        AND MSTEQMREV_HEADER.PLANCD = _$PLANCD
        AND MSTEQMREV_HEADER.REVNUM = $REVNUM
      LIMIT 1;
    ELSE
      SELECT MSTEQMREV_HEADER.REVCD, MSTEQMREV_HEADER.REVNUM, LEFT(COALESCE(NULLIF(MSTEQMREV_HEADER.REQTIME, ''), MSTEQMREV_HEADER.RTIME), 10)
        INTO _$REVCD, _$REVNUM, _$REVDATE
      FROM MSTEQMREV_HEADER
      WHERE MSTEQMREV_HEADER.CHKTP = '02'
        AND MSTEQMREV_HEADER.PLANTP = _$PLANTP
        AND MSTEQMREV_HEADER.PLANCD = _$PLANCD
      ORDER BY MSTEQMREV_HEADER.REVNUM DESC
      LIMIT 1;
    END IF;

    IF _$REVCD IS NULL THEN
      CALL COMERR('출력할 정기점검 계획이 없습니다.');
      LEAVE PROC;
    END IF;

    -- 계획서 상단 (설비그룹은 소속 설비의 설비번호·규격·라인·공정을 모아서 표시)
    SELECT CASE WHEN _$PLANTP = 'E' THEN MAX(MSTEQM.EQMNM) ELSE COALESCE(MAX(COMTYPE.TPNM), _$PLANCD) END AS EQMNM,
           GROUP_CONCAT(MSTEQM.FANO ORDER BY MSTEQM.FANO SEPARATOR ', ') AS EQMCD,
           COALESCE(GROUP_CONCAT(DISTINCT NULLIF(MSTEQM.EQMNM_DETAIL, '') SEPARATOR ', '), '') AS EQMSPEC,
           COALESCE(GROUP_CONCAT(DISTINCT COALESCE(NULLIF(MSTLINE.LINENM, ''), NULLIF(MSTEQM.LINECD, '')) SEPARATOR ', '), '') AS LINENM,
           COALESCE(GROUP_CONCAT(DISTINCT COALESCE(NULLIF(GPCD('FM100', MSTEQM.EQMTP), ''), NULLIF(MSTEQM.EQMTP, '')) SEPARATOR ', '), '') AS PROCESSNM,
           COALESCE(CONCAT('REV.', _$REVNUM), '') AS REVNM,
           COALESCE(_$REVDATE, '') AS REVDATE
    FROM MSTEQM
    LEFT JOIN MSTLINE
      ON MSTLINE.LINECD = MSTEQM.LINECD
    LEFT JOIN COMTYPE
      ON COMTYPE.GPCD = 'FM116'
     AND COMTYPE.TPCD = MSTEQM.EQMGUBUN
    WHERE MSTEQM.USEYN = 'Y'
      AND ((_$PLANTP = 'E' AND MSTEQM.FANO = _$PLANCD)
        OR (_$PLANTP = 'G' AND MSTEQM.EQMGUBUN = _$PLANCD))
    HAVING COUNT(*) > 0;

    -- 계획서 점검 항목: 선택 REV의 사용 항목
    SELECT ROW_NUMBER() OVER (ORDER BY MSTEQMREV_DETAIL.SORTNO, MSTEQMREV_DETAIL.CHKKNDCD) AS NO,
           COALESCE(NULLIF(GPCD('CHKLOC', MSTEQMREV_DETAIL.CHKLOC), ''), MSTEQMREV_DETAIL.CHKLOC) AS CHKITEM,
           MSTEQMREV_DETAIL.CHKKNDNM AS CHKCONTENT,
           COALESCE(NULLIF(GPCD('CHKMTH', MSTEQMREV_DETAIL.CHKMTH), ''), MSTEQMREV_DETAIL.CHKMTH) AS CHKDEVICE,
           COALESCE(NULLIF(GPCD('CHKVALTP', MSTEQMREV_DETAIL.CHKVALTP), ''), MSTEQMREV_DETAIL.CHKVALTP) AS CHKRESULT,
           '' AS CONFIRM,
           COALESCE(MSTEQMREV_DETAIL.REMARK, '') AS REMARK
    FROM MSTEQMREV_DETAIL
    WHERE MSTEQMREV_DETAIL.REVCD = _$REVCD
    ORDER BY MSTEQMREV_DETAIL.SORTNO, MSTEQMREV_DETAIL.CHKKNDCD;

    -- 개정 이력 (전체 리비전, 최신순, 개정일은 개정내용 작성일)
    SELECT MSTEQMREV_HEADER.REVNUM,
           LEFT(COALESCE(NULLIF(MSTEQMREV_HEADER.REQTIME, ''), MSTEQMREV_HEADER.RTIME), 10) AS REVDATE,
           MSTEQMREV_HEADER.REMARK,
           COALESCE(REQ_EMP.EMPNM, MSTEQMREV_HEADER.REQEMP) AS REQEMPNM
    FROM MSTEQMREV_HEADER
    LEFT JOIN MSTEMP REQ_EMP
      ON REQ_EMP.EMPCD = MSTEQMREV_HEADER.REQEMP
    WHERE MSTEQMREV_HEADER.CHKTP = '02'
      AND MSTEQMREV_HEADER.PLANTP = _$PLANTP
      AND MSTEQMREV_HEADER.PLANCD = _$PLANCD
    ORDER BY MSTEQMREV_HEADER.REVNUM DESC;

  -- *****************************************************************************

  WHEN 'LIST_CYCLE_EQMCD' THEN -- 설비별 월별 점검계획 조회
    IF $SYEAR = '' THEN
      CALL COMERR('조회년도를 지정해주세요.');
      LEAVE PROC;
    END IF;

    SET $FACTORYCD = '07';

    SELECT IFNULL(MSTEQM.FACTORYCD, '') AS FACTORYCD,
           IFNULL(MSTEQM.LINECD, '')    AS LINECD,
           IFNULL(MSTEQM.EQMTP, '')     AS EQMTP,
           IFNULL(MSTEQM.EQMGROUP1, '') AS EQMGROUP1,
           MSTEQM.FANO,
           MSTEQM.EQMNM,
           MSTEQM.EQMGRADE,
           CASE WHEN LENGTH(MSTEQM.EQMGRADE) > 0 THEN
             COALESCE(NULLIF(GPCD('FM110', MSTEQM.EQMGRADE), ''), MSTEQM.EQMGRADE)
           ELSE MSTEQM.EQMGRADE END AS EQMGRADENM,
           IFNULL(GRADE_SCORE.CHKCYCLE2, '') AS CHKCYCLE2,
           -- 점검주기 문구 해석: CHKYEAR년에 CHKCNT회 (해석 불가 시 NULL, 화면 검증 생략)
           GRADE_SCORE.CHKCNT,
           GRADE_SCORE.CHKYEAR,
           -- 주기 안의 앞뒤 년도 배정 횟수와 현황 (2년/1회면 전년·다음년)
           (SELECT IFNULL(SUM((OTHER_PLAN.MONTH_01 <> '') + (OTHER_PLAN.MONTH_02 <> '') + (OTHER_PLAN.MONTH_03 <> '') + (OTHER_PLAN.MONTH_04 <> '') +
                              (OTHER_PLAN.MONTH_05 <> '') + (OTHER_PLAN.MONTH_06 <> '') + (OTHER_PLAN.MONTH_07 <> '') + (OTHER_PLAN.MONTH_08 <> '') +
                              (OTHER_PLAN.MONTH_09 <> '') + (OTHER_PLAN.MONTH_10 <> '') + (OTHER_PLAN.MONTH_11 <> '') + (OTHER_PLAN.MONTH_12 <> '')), 0)
            FROM CHKPLANEQM_YEARPLAN OTHER_PLAN
            WHERE OTHER_PLAN.EQMCD = MSTEQM.FANO
              AND OTHER_PLAN.CHKTP = '02'
              AND OTHER_PLAN.YEAR + 0 BETWEEN $SYEAR - (GRADE_SCORE.CHKYEAR - 1) AND $SYEAR - 1) AS PREVCNT,
           (SELECT IFNULL(SUM((OTHER_PLAN.MONTH_01 <> '') + (OTHER_PLAN.MONTH_02 <> '') + (OTHER_PLAN.MONTH_03 <> '') + (OTHER_PLAN.MONTH_04 <> '') +
                              (OTHER_PLAN.MONTH_05 <> '') + (OTHER_PLAN.MONTH_06 <> '') + (OTHER_PLAN.MONTH_07 <> '') + (OTHER_PLAN.MONTH_08 <> '') +
                              (OTHER_PLAN.MONTH_09 <> '') + (OTHER_PLAN.MONTH_10 <> '') + (OTHER_PLAN.MONTH_11 <> '') + (OTHER_PLAN.MONTH_12 <> '')), 0)
            FROM CHKPLANEQM_YEARPLAN OTHER_PLAN
            WHERE OTHER_PLAN.EQMCD = MSTEQM.FANO
              AND OTHER_PLAN.CHKTP = '02'
              AND OTHER_PLAN.YEAR + 0 BETWEEN $SYEAR + 1 AND $SYEAR + (GRADE_SCORE.CHKYEAR - 1)) AS NEXTCNT,
           IFNULL((SELECT GROUP_CONCAT(CONCAT(OTHER_PLAN.YEAR, '년 ',
                                              (OTHER_PLAN.MONTH_01 <> '') + (OTHER_PLAN.MONTH_02 <> '') + (OTHER_PLAN.MONTH_03 <> '') + (OTHER_PLAN.MONTH_04 <> '') +
                                              (OTHER_PLAN.MONTH_05 <> '') + (OTHER_PLAN.MONTH_06 <> '') + (OTHER_PLAN.MONTH_07 <> '') + (OTHER_PLAN.MONTH_08 <> '') +
                                              (OTHER_PLAN.MONTH_09 <> '') + (OTHER_PLAN.MONTH_10 <> '') + (OTHER_PLAN.MONTH_11 <> '') + (OTHER_PLAN.MONTH_12 <> ''), '회')
                                       ORDER BY OTHER_PLAN.YEAR SEPARATOR ', ')
                   FROM CHKPLANEQM_YEARPLAN OTHER_PLAN
                   WHERE OTHER_PLAN.EQMCD = MSTEQM.FANO
                     AND OTHER_PLAN.CHKTP = '02'
                     AND OTHER_PLAN.YEAR <> $SYEAR
                     AND OTHER_PLAN.YEAR + 0 BETWEEN $SYEAR - (GRADE_SCORE.CHKYEAR - 1) AND $SYEAR + (GRADE_SCORE.CHKYEAR - 1)), '') AS OTHERPLAN,
           $SYEAR AS YEAR,
           -- 월별 점검자: MSTEMP 일괄 LEFT JOIN 사원명 매핑 (매핑 실패 시 사원코드 fallback, MxxCD는 저장값 유지)
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_01) > 0 THEN
             COALESCE(EMP01.EMPNM, CHKPLANEQM_YEARPLAN.MONTH_01)
           ELSE '' END AS M01,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_01, '') AS M01CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_02) > 0 THEN
             COALESCE(EMP02.EMPNM, CHKPLANEQM_YEARPLAN.MONTH_02)
           ELSE '' END AS M02,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_02, '') AS M02CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_03) > 0 THEN
             COALESCE(EMP03.EMPNM, CHKPLANEQM_YEARPLAN.MONTH_03)
           ELSE '' END AS M03,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_03, '') AS M03CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_04) > 0 THEN
             COALESCE(EMP04.EMPNM, CHKPLANEQM_YEARPLAN.MONTH_04)
           ELSE '' END AS M04,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_04, '') AS M04CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_05) > 0 THEN
             COALESCE(EMP05.EMPNM, CHKPLANEQM_YEARPLAN.MONTH_05)
           ELSE '' END AS M05,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_05, '') AS M05CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_06) > 0 THEN
             COALESCE(EMP06.EMPNM, CHKPLANEQM_YEARPLAN.MONTH_06)
           ELSE '' END AS M06,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_06, '') AS M06CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_07) > 0 THEN
             COALESCE(EMP07.EMPNM, CHKPLANEQM_YEARPLAN.MONTH_07)
           ELSE '' END AS M07,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_07, '') AS M07CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_08) > 0 THEN
             COALESCE(EMP08.EMPNM, CHKPLANEQM_YEARPLAN.MONTH_08)
           ELSE '' END AS M08,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_08, '') AS M08CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_09) > 0 THEN
             COALESCE(EMP09.EMPNM, CHKPLANEQM_YEARPLAN.MONTH_09)
           ELSE '' END AS M09,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_09, '') AS M09CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_10) > 0 THEN
             COALESCE(EMP10.EMPNM, CHKPLANEQM_YEARPLAN.MONTH_10)
           ELSE '' END AS M10,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_10, '') AS M10CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_11) > 0 THEN
             COALESCE(EMP11.EMPNM, CHKPLANEQM_YEARPLAN.MONTH_11)
           ELSE '' END AS M11,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_11, '') AS M11CD,
           CASE WHEN LENGTH(CHKPLANEQM_YEARPLAN.MONTH_12) > 0 THEN
             COALESCE(EMP12.EMPNM, CHKPLANEQM_YEARPLAN.MONTH_12)
           ELSE '' END AS M12,
           IFNULL(CHKPLANEQM_YEARPLAN.MONTH_12, '') AS M12CD,
           IFNULL(CHKPLANEQM_YEARPLAN.REMARK, '') AS REMARK,
           -- 정기점검 실적이 있는 점검자 배정 월 (예: ',3,11,'), 화면에서 해당 월 점검자 변경·삭제 차단
           IFNULL(LOCK_MM.LOCKMM, '') AS LOCKMM
    FROM MSTEQM
    LEFT JOIN CHKPLANEQM_YEARPLAN
      ON CHKPLANEQM_YEARPLAN.EQMCD = MSTEQM.FANO
     AND CHKPLANEQM_YEARPLAN.YEAR = $SYEAR
     AND CHKPLANEQM_YEARPLAN.CHKTP = '02'
    LEFT JOIN (
      SELECT CHKRSTEQM.EQMCD,
             CONCAT(',', GROUP_CONCAT(DISTINCT CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED)), ',') AS LOCKMM
      FROM CHKRSTEQM
      INNER JOIN CHKPLANEQM_YEARPLAN
        ON CHKPLANEQM_YEARPLAN.EQMCD = CHKRSTEQM.EQMCD
       AND CHKPLANEQM_YEARPLAN.YEAR = $SYEAR
       AND CHKPLANEQM_YEARPLAN.CHKTP = '02'
      WHERE CHKRSTEQM.CHKTP = '02'
        AND CHKRSTEQM.BASEDATE LIKE CONCAT($SYEAR, '-%')
        AND IFNULL(ELT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED),
                    CHKPLANEQM_YEARPLAN.MONTH_01, CHKPLANEQM_YEARPLAN.MONTH_02, CHKPLANEQM_YEARPLAN.MONTH_03,
                    CHKPLANEQM_YEARPLAN.MONTH_04, CHKPLANEQM_YEARPLAN.MONTH_05, CHKPLANEQM_YEARPLAN.MONTH_06,
                    CHKPLANEQM_YEARPLAN.MONTH_07, CHKPLANEQM_YEARPLAN.MONTH_08, CHKPLANEQM_YEARPLAN.MONTH_09,
                    CHKPLANEQM_YEARPLAN.MONTH_10, CHKPLANEQM_YEARPLAN.MONTH_11, CHKPLANEQM_YEARPLAN.MONTH_12), '') <> ''
      GROUP BY CHKRSTEQM.EQMCD
    ) LOCK_MM
      ON LOCK_MM.EQMCD = MSTEQM.FANO
    -- 설비등급별 정기점검주기 (설비등급기준 관리의 사용중 리비전, ERP는 등급 코드만 보내고 주기 문구는 MES에서 관리)
    -- 문구 해석: 'N년/M회'·'년 M회 점검' → N년(없으면 1년)에 M회, '오버홀' 등 횟수 없는 문구는 NULL
    LEFT JOIN (
      SELECT MSTEQM_GRADEREV_SCORE.EQMGRADE,
             MSTEQM_GRADEREV_SCORE.CHKCYCLE2,
             CASE WHEN MSTEQM_GRADEREV_SCORE.CHKCYCLE2 REGEXP '(년|연)' AND MSTEQM_GRADEREV_SCORE.CHKCYCLE2 REGEXP '[0-9]+ *회' THEN
               CAST(REGEXP_REPLACE(REGEXP_SUBSTR(MSTEQM_GRADEREV_SCORE.CHKCYCLE2, '[0-9]+ *회'), '[^0-9]', '') AS SIGNED)
             END AS CHKCNT,
             CASE WHEN MSTEQM_GRADEREV_SCORE.CHKCYCLE2 REGEXP '(년|연)' AND MSTEQM_GRADEREV_SCORE.CHKCYCLE2 REGEXP '[0-9]+ *회' THEN
               IFNULL(CAST(NULLIF(REGEXP_REPLACE(REGEXP_SUBSTR(MSTEQM_GRADEREV_SCORE.CHKCYCLE2, '[0-9]+ *(년|연)'), '[^0-9]', ''), '') AS SIGNED), 1)
             END AS CHKYEAR
      FROM MSTEQM_GRADEREV_SCORE
      WHERE MSTEQM_GRADEREV_SCORE.REVCD = (SELECT REVCD FROM MSTEQM_GRADEREV WHERE USEYN = 'Y' LIMIT 1)
    ) GRADE_SCORE
      ON GRADE_SCORE.EQMGRADE = MSTEQM.EQMGRADE
    LEFT JOIN MSTEMP EMP01 ON EMP01.EMPCD = CHKPLANEQM_YEARPLAN.MONTH_01
    LEFT JOIN MSTEMP EMP02 ON EMP02.EMPCD = CHKPLANEQM_YEARPLAN.MONTH_02
    LEFT JOIN MSTEMP EMP03 ON EMP03.EMPCD = CHKPLANEQM_YEARPLAN.MONTH_03
    LEFT JOIN MSTEMP EMP04 ON EMP04.EMPCD = CHKPLANEQM_YEARPLAN.MONTH_04
    LEFT JOIN MSTEMP EMP05 ON EMP05.EMPCD = CHKPLANEQM_YEARPLAN.MONTH_05
    LEFT JOIN MSTEMP EMP06 ON EMP06.EMPCD = CHKPLANEQM_YEARPLAN.MONTH_06
    LEFT JOIN MSTEMP EMP07 ON EMP07.EMPCD = CHKPLANEQM_YEARPLAN.MONTH_07
    LEFT JOIN MSTEMP EMP08 ON EMP08.EMPCD = CHKPLANEQM_YEARPLAN.MONTH_08
    LEFT JOIN MSTEMP EMP09 ON EMP09.EMPCD = CHKPLANEQM_YEARPLAN.MONTH_09
    LEFT JOIN MSTEMP EMP10 ON EMP10.EMPCD = CHKPLANEQM_YEARPLAN.MONTH_10
    LEFT JOIN MSTEMP EMP11 ON EMP11.EMPCD = CHKPLANEQM_YEARPLAN.MONTH_11
    LEFT JOIN MSTEMP EMP12 ON EMP12.EMPCD = CHKPLANEQM_YEARPLAN.MONTH_12
    WHERE MSTEQM.USEYN = 'Y'
      AND ($FACTORYCD = '' OR MSTEQM.FACTORYCD = $FACTORYCD)
      AND ($LINECD = '' OR MSTEQM.LINECD = $LINECD)
      AND ($EQMTP = '' OR MSTEQM.EQMTP = $EQMTP)
      AND ($EQMGROUP1 = '' OR MSTEQM.EQMGROUP1 = $EQMGROUP1)
      AND (MSTEQM.FANO LIKE CONCAT('%', $FANO, '%') OR MSTEQM.EQMNM LIKE CONCAT('%', $FANO, '%'))
    ORDER BY MSTEQM.FANO;

  -- *****************************************************************************

  WHEN 'CALL_CYCLE_RPT' THEN -- 월별 점검계획 레포트 출력 데이터 조회 (점검자가 배정된 월만)
    IF COALESCE($SYEAR, '') = '' THEN
      CALL COMERR('조회년도를 지정해주세요.');
      LEAVE PROC;
    END IF;

    -- 연간 계획(MONTH_01~12)을 월 단위 행으로 펼치고 점검자 배정 월만 출력, 점검실시일은 해당 월 정기점검 실적의 첫 점검일자
    SELECT ROW_NUMBER() OVER (ORDER BY PLAN_MONTH.MM, MSTEQM.LINECD, MSTEQM.EQMTP, MSTEQM.EQMGROUP1, MSTEQM.EQMGROUP2, MSTEQM.EQMGROUP3, MSTEQM.FANO) AS NO,
           PLAN_MONTH.MM,
           COALESCE(NULLIF(MSTLINE.LINENM, ''), MSTEQM.LINECD, '') AS LINENM,
           COALESCE(NULLIF(GPCD('FM100', MSTEQM.EQMTP), ''), MSTEQM.EQMTP, '') AS EQMTPNM,
           COALESCE(NULLIF(GPCD('FM113', MSTEQM.EQMGROUP1), ''), MSTEQM.EQMGROUP1, '') AS EQMGROUP1NM,
           COALESCE(NULLIF(GPCD('FM114', MSTEQM.EQMGROUP2), ''), MSTEQM.EQMGROUP2, '') AS EQMGROUP2NM,
           COALESCE(NULLIF(GPCD('FM115', MSTEQM.EQMGROUP3), ''), MSTEQM.EQMGROUP3, '') AS EQMGROUP3NM,
           COALESCE(MSTEQM.EQMNM, '') AS EQMNM,
           COALESCE(MSTEQM.EQMNM_DETAIL, '') AS EQMSPEC,
           CONCAT(RIGHT($SYEAR, 2), '.', LPAD(PLAN_MONTH.MM, 2, '0')) AS PLANYM,
           COALESCE(DATE_FORMAT(CHK_RST.CHKDATE, '%y.%m.%d'), '') AS CHKDATE,
           COALESCE(MSTEMP.EMPNM, PLAN_MONTH.EMPCD) AS EMPNM
    FROM (
      SELECT CHKPLANEQM_YEARPLAN.EQMCD,
             MONTH_NO.MM,
             ELT(MONTH_NO.MM, CHKPLANEQM_YEARPLAN.MONTH_01, CHKPLANEQM_YEARPLAN.MONTH_02, CHKPLANEQM_YEARPLAN.MONTH_03,
                              CHKPLANEQM_YEARPLAN.MONTH_04, CHKPLANEQM_YEARPLAN.MONTH_05, CHKPLANEQM_YEARPLAN.MONTH_06,
                              CHKPLANEQM_YEARPLAN.MONTH_07, CHKPLANEQM_YEARPLAN.MONTH_08, CHKPLANEQM_YEARPLAN.MONTH_09,
                              CHKPLANEQM_YEARPLAN.MONTH_10, CHKPLANEQM_YEARPLAN.MONTH_11, CHKPLANEQM_YEARPLAN.MONTH_12) AS EMPCD
      FROM CHKPLANEQM_YEARPLAN
      CROSS JOIN (SELECT 1 AS MM UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6
                  UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9 UNION ALL SELECT 10 UNION ALL SELECT 11 UNION ALL SELECT 12) MONTH_NO
      WHERE CHKPLANEQM_YEARPLAN.YEAR = $SYEAR
        AND CHKPLANEQM_YEARPLAN.CHKTP = '02'
    ) PLAN_MONTH
    INNER JOIN MSTEQM
      ON MSTEQM.FANO = PLAN_MONTH.EQMCD
    LEFT JOIN MSTLINE
      ON MSTLINE.LINECD = MSTEQM.LINECD
    LEFT JOIN MSTEMP
      ON MSTEMP.EMPCD = PLAN_MONTH.EMPCD
    LEFT JOIN (
      SELECT CHKRSTEQM.EQMCD,
             CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED) AS MM,
             MIN(CHKRSTEQM.BASEDATE) AS CHKDATE
      FROM CHKRSTEQM
      WHERE CHKRSTEQM.CHKTP = '02'
        AND CHKRSTEQM.BASEDATE LIKE CONCAT($SYEAR, '-%')
      GROUP BY CHKRSTEQM.EQMCD, CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED)
    ) CHK_RST
      ON CHK_RST.EQMCD = PLAN_MONTH.EQMCD
     AND CHK_RST.MM = PLAN_MONTH.MM
    WHERE COALESCE(PLAN_MONTH.EMPCD, '') <> ''
      AND MSTEQM.USEYN = 'Y'
      AND (MSTEQM.FANO LIKE CONCAT('%', COALESCE($FANO, ''), '%') OR MSTEQM.EQMNM LIKE CONCAT('%', COALESCE($FANO, ''), '%'))
    ORDER BY NO;

  -- *****************************************************************************

  WHEN 'SAVE_CYCLE_EQMCD' THEN -- 설비별 월별 점검계획 저장
    WHILE LENGTH($FANO_LIST) > 0 DO
      CALL COMSPLIT($FANO_LIST, _$FANO);
      CALL COMSPLIT($YEAR_LIST, _$YEAR);
      CALL COMSPLIT($M01_LIST, _$M01);
      CALL COMSPLIT($M02_LIST, _$M02);
      CALL COMSPLIT($M03_LIST, _$M03);
      CALL COMSPLIT($M04_LIST, _$M04);
      CALL COMSPLIT($M05_LIST, _$M05);
      CALL COMSPLIT($M06_LIST, _$M06);
      CALL COMSPLIT($M07_LIST, _$M07);
      CALL COMSPLIT($M08_LIST, _$M08);
      CALL COMSPLIT($M09_LIST, _$M09);
      CALL COMSPLIT($M10_LIST, _$M10);
      CALL COMSPLIT($M11_LIST, _$M11);
      CALL COMSPLIT($M12_LIST, _$M12);
      CALL COMSPLIT($REMARK_LIST, _$REMARK);

      IF NOT EXISTS (SELECT 1 FROM MSTEQM WHERE FANO = _$FANO AND USEYN = 'Y') THEN
        CALL COMERR('사용 중인 설비를 선택해주세요.');
        LEAVE PROC;
      END IF;

      -- 정기점검 실적이 있는 월은 점검자 변경·삭제 불가 (점검자가 없던 월에 새로 지정하는 것은 허용)
      SELECT GROUP_CONCAT(DISTINCT CONCAT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED), '월')
                          ORDER BY SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) SEPARATOR ', ')
        INTO _$LOCKMM
      FROM CHKRSTEQM
      INNER JOIN CHKPLANEQM_YEARPLAN
        ON CHKPLANEQM_YEARPLAN.EQMCD = CHKRSTEQM.EQMCD
       AND CHKPLANEQM_YEARPLAN.YEAR = _$YEAR
       AND CHKPLANEQM_YEARPLAN.CHKTP = '02'
      WHERE CHKRSTEQM.EQMCD = _$FANO
        AND CHKRSTEQM.CHKTP = '02'
        AND CHKRSTEQM.BASEDATE LIKE CONCAT(_$YEAR, '-%')
        AND IFNULL(ELT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED),
                    CHKPLANEQM_YEARPLAN.MONTH_01, CHKPLANEQM_YEARPLAN.MONTH_02, CHKPLANEQM_YEARPLAN.MONTH_03,
                    CHKPLANEQM_YEARPLAN.MONTH_04, CHKPLANEQM_YEARPLAN.MONTH_05, CHKPLANEQM_YEARPLAN.MONTH_06,
                    CHKPLANEQM_YEARPLAN.MONTH_07, CHKPLANEQM_YEARPLAN.MONTH_08, CHKPLANEQM_YEARPLAN.MONTH_09,
                    CHKPLANEQM_YEARPLAN.MONTH_10, CHKPLANEQM_YEARPLAN.MONTH_11, CHKPLANEQM_YEARPLAN.MONTH_12), '') <> ''
        AND IFNULL(ELT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED),
                    CHKPLANEQM_YEARPLAN.MONTH_01, CHKPLANEQM_YEARPLAN.MONTH_02, CHKPLANEQM_YEARPLAN.MONTH_03,
                    CHKPLANEQM_YEARPLAN.MONTH_04, CHKPLANEQM_YEARPLAN.MONTH_05, CHKPLANEQM_YEARPLAN.MONTH_06,
                    CHKPLANEQM_YEARPLAN.MONTH_07, CHKPLANEQM_YEARPLAN.MONTH_08, CHKPLANEQM_YEARPLAN.MONTH_09,
                    CHKPLANEQM_YEARPLAN.MONTH_10, CHKPLANEQM_YEARPLAN.MONTH_11, CHKPLANEQM_YEARPLAN.MONTH_12), '') <> IFNULL(ELT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED),
                    _$M01, _$M02, _$M03, _$M04, _$M05, _$M06,
                    _$M07, _$M08, _$M09, _$M10, _$M11, _$M12), '');

      IF _$LOCKMM IS NOT NULL THEN
        CALL COMERR(CONCAT('[', _$FANO, '] ', _$YEAR, '년 ', _$LOCKMM, '은 정기점검 실적이 있어 점검자를 변경·삭제할 수 없습니다. 설비 정기점검 등록에서 해당 월 점검 실적을 먼저 삭제해주세요.'));
        LEAVE PROC;
      END IF;

      -- 설비등급 점검주기(설비등급기준 문구 'N년/M회'·'년 M회') 초과 배정 차단
      -- 배정 월 수가 늘어날 때만 검사 (ERP 등급 변경으로 이미 초과된 계획은 점검자 변경·축소 허용), 문구 해석 불가 등급은 검사 안 함
      SET _$NEWCNT = (_$M01 <> '') + (_$M02 <> '') + (_$M03 <> '') + (_$M04 <> '') + (_$M05 <> '') + (_$M06 <> '') +
                     (_$M07 <> '') + (_$M08 <> '') + (_$M09 <> '') + (_$M10 <> '') + (_$M11 <> '') + (_$M12 <> '');
      SET _$OLDCNT = IFNULL((
        SELECT (MONTH_01 <> '') + (MONTH_02 <> '') + (MONTH_03 <> '') + (MONTH_04 <> '') + (MONTH_05 <> '') + (MONTH_06 <> '') +
               (MONTH_07 <> '') + (MONTH_08 <> '') + (MONTH_09 <> '') + (MONTH_10 <> '') + (MONTH_11 <> '') + (MONTH_12 <> '')
        FROM CHKPLANEQM_YEARPLAN
        WHERE EQMCD = _$FANO AND YEAR = _$YEAR AND CHKTP = '02'
      ), 0);

      IF _$NEWCNT > _$OLDCNT THEN
        SET _$GRADENM = (SELECT GPCD('FM110', EQMGRADE) FROM MSTEQM WHERE FANO = _$FANO LIMIT 1);
        SET _$CHKCYCLE = (
          SELECT MSTEQM_GRADEREV_SCORE.CHKCYCLE2
          FROM MSTEQM
          INNER JOIN MSTEQM_GRADEREV_SCORE
            ON MSTEQM_GRADEREV_SCORE.REVCD = (SELECT REVCD FROM MSTEQM_GRADEREV WHERE USEYN = 'Y' LIMIT 1)
           AND MSTEQM_GRADEREV_SCORE.EQMGRADE = MSTEQM.EQMGRADE
          WHERE MSTEQM.FANO = _$FANO
          LIMIT 1
        );

        SET _$CHKCNT = NULL;
        SET _$CHKYEAR = NULL;
        IF _$CHKCYCLE REGEXP '(년|연)' AND _$CHKCYCLE REGEXP '[0-9]+ *회' THEN
          SET _$CHKCNT  = CAST(REGEXP_REPLACE(REGEXP_SUBSTR(_$CHKCYCLE, '[0-9]+ *회'), '[^0-9]', '') AS SIGNED);
          SET _$CHKYEAR = IFNULL(CAST(NULLIF(REGEXP_REPLACE(REGEXP_SUBSTR(_$CHKCYCLE, '[0-9]+ *(년|연)'), '[^0-9]', ''), '') AS SIGNED), 1);
        END IF;

        IF _$CHKCNT > 0 AND _$CHKYEAR > 0 THEN
          SET _$PREVCNT = IFNULL((
            SELECT SUM((MONTH_01 <> '') + (MONTH_02 <> '') + (MONTH_03 <> '') + (MONTH_04 <> '') + (MONTH_05 <> '') + (MONTH_06 <> '') +
                       (MONTH_07 <> '') + (MONTH_08 <> '') + (MONTH_09 <> '') + (MONTH_10 <> '') + (MONTH_11 <> '') + (MONTH_12 <> ''))
            FROM CHKPLANEQM_YEARPLAN
            WHERE EQMCD = _$FANO AND CHKTP = '02'
              AND YEAR + 0 BETWEEN _$YEAR - (_$CHKYEAR - 1) AND _$YEAR - 1
          ), 0);
          SET _$NEXTCNT = IFNULL((
            SELECT SUM((MONTH_01 <> '') + (MONTH_02 <> '') + (MONTH_03 <> '') + (MONTH_04 <> '') + (MONTH_05 <> '') + (MONTH_06 <> '') +
                       (MONTH_07 <> '') + (MONTH_08 <> '') + (MONTH_09 <> '') + (MONTH_10 <> '') + (MONTH_11 <> '') + (MONTH_12 <> ''))
            FROM CHKPLANEQM_YEARPLAN
            WHERE EQMCD = _$FANO AND CHKTP = '02'
              AND YEAR + 0 BETWEEN _$YEAR + 1 AND _$YEAR + (_$CHKYEAR - 1)
          ), 0);

          IF _$PREVCNT + _$NEWCNT > _$CHKCNT OR _$NEWCNT + _$NEXTCNT > _$CHKCNT THEN
            CALL COMERR(CONCAT('[', _$FANO, '] ', IFNULL(_$GRADENM, ''), '등급(', _$CHKCYCLE, ')은 ',
                               IF(_$CHKYEAR > 1, CONCAT(_$CHKYEAR, '년에 '), '한 해에 '), _$CHKCNT, '회까지 점검자를 배정할 수 있습니다. (',
                               _$YEAR, '년 ', _$NEWCNT, '회',
                               IF(_$PREVCNT + _$NEXTCNT > 0, CONCAT(', 주기 안 다른 년도 ', _$PREVCNT + _$NEXTCNT, '회'), ''), ')'));
            LEAVE PROC;
          END IF;
        END IF;
      END IF;

      IF EXISTS (SELECT 1 FROM CHKPLANEQM_YEARPLAN WHERE EQMCD = _$FANO AND YEAR = _$YEAR AND CHKTP = '02') THEN
        UPDATE CHKPLANEQM_YEARPLAN
        SET MONTH_01 = _$M01,
            MONTH_02 = _$M02,
            MONTH_03 = _$M03,
            MONTH_04 = _$M04,
            MONTH_05 = _$M05,
            MONTH_06 = _$M06,
            MONTH_07 = _$M07,
            MONTH_08 = _$M08,
            MONTH_09 = _$M09,
            MONTH_10 = _$M10,
            MONTH_11 = _$M11,
            MONTH_12 = _$M12,
            REMARK   = _$REMARK,
            MTIME    = CALLTIME(),
            MEMP     = CALLEMP(),
            MPRG     = CALLPRG()
        WHERE EQMCD = _$FANO
          AND YEAR  = _$YEAR
          AND CHKTP = '02';
          
        IF EXISTS (
          SELECT 1 FROM CHKPLANEQM_YEARPLAN
          WHERE EQMCD = _$FANO AND YEAR = _$YEAR AND CHKTP = '02' AND REMARK = ''
            AND MONTH_01 = '' AND MONTH_02 = '' AND MONTH_03 = '' AND MONTH_04 = ''
            AND MONTH_05 = '' AND MONTH_06 = '' AND MONTH_07 = '' AND MONTH_08 = ''
            AND MONTH_09 = '' AND MONTH_10 = '' AND MONTH_11 = '' AND MONTH_12 = ''
        ) THEN
          DELETE FROM CHKPLANEQM_YEARPLAN 
          WHERE EQMCD = _$FANO 
            AND YEAR  = _$YEAR 
            AND CHKTP = '02';
        END IF;  
      ELSE
        INSERT INTO CHKPLANEQM_YEARPLAN (
          EQMCD, CHKTP, YEAR, 
          MONTH_01, MONTH_02, MONTH_03, MONTH_04, 
          MONTH_05, MONTH_06, MONTH_07, MONTH_08, 
          MONTH_09, MONTH_10, MONTH_11, MONTH_12, 
          REMARK, RTIME, REMP, RPRG
        ) VALUES (
          _$FANO, '02', _$YEAR,
          _$M01, _$M02, _$M03, _$M04,
          _$M05, _$M06, _$M07, _$M08,
          _$M09, _$M10, _$M11, _$M12,
          _$REMARK, CALLTIME(), CALLEMP(), CALLPRG()
        );
     
        IF EXISTS (
          SELECT 1 FROM CHKPLANEQM_YEARPLAN
          WHERE EQMCD = _$FANO AND YEAR = _$YEAR AND CHKTP = '02' AND REMARK = ''
            AND MONTH_01 = '' AND MONTH_02 = '' AND MONTH_03 = '' AND MONTH_04 = ''
            AND MONTH_05 = '' AND MONTH_06 = '' AND MONTH_07 = '' AND MONTH_08 = ''
            AND MONTH_09 = '' AND MONTH_10 = '' AND MONTH_11 = '' AND MONTH_12 = ''
        ) THEN
          DELETE FROM CHKPLANEQM_YEARPLAN 
          WHERE EQMCD = _$FANO
            AND YEAR  = _$YEAR 
            AND CHKTP = '02';
        END IF;
      END IF;
    END WHILE;

  -- *****************************************************************************

  WHEN 'DELETE_CYCLE_EQMCD' THEN -- 설비별 월별 점검계획 삭제
    WHILE LENGTH($FANO_LIST) > 0 DO
      CALL COMSPLIT($FANO_LIST, _$FANO);
      CALL COMSPLIT($YEAR_LIST, _$YEAR);

      IF NOT EXISTS (SELECT 1 FROM MSTEQM WHERE FANO = _$FANO AND USEYN = 'Y') THEN
        CALL COMERR('사용 중인 설비를 선택해주세요.');
        LEAVE PROC;
      END IF;

      -- 정기점검 실적이 있는 월이 있으면 삭제 불가
      SELECT GROUP_CONCAT(DISTINCT CONCAT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED), '월')
                          ORDER BY SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) SEPARATOR ', ')
        INTO _$LOCKMM
      FROM CHKRSTEQM
      INNER JOIN CHKPLANEQM_YEARPLAN
        ON CHKPLANEQM_YEARPLAN.EQMCD = CHKRSTEQM.EQMCD
       AND CHKPLANEQM_YEARPLAN.YEAR = _$YEAR
       AND CHKPLANEQM_YEARPLAN.CHKTP = '02'
      WHERE CHKRSTEQM.EQMCD = _$FANO
        AND CHKRSTEQM.CHKTP = '02'
        AND CHKRSTEQM.BASEDATE LIKE CONCAT(_$YEAR, '-%')
        AND IFNULL(ELT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED),
                    CHKPLANEQM_YEARPLAN.MONTH_01, CHKPLANEQM_YEARPLAN.MONTH_02, CHKPLANEQM_YEARPLAN.MONTH_03,
                    CHKPLANEQM_YEARPLAN.MONTH_04, CHKPLANEQM_YEARPLAN.MONTH_05, CHKPLANEQM_YEARPLAN.MONTH_06,
                    CHKPLANEQM_YEARPLAN.MONTH_07, CHKPLANEQM_YEARPLAN.MONTH_08, CHKPLANEQM_YEARPLAN.MONTH_09,
                    CHKPLANEQM_YEARPLAN.MONTH_10, CHKPLANEQM_YEARPLAN.MONTH_11, CHKPLANEQM_YEARPLAN.MONTH_12), '') <> '';

      IF _$LOCKMM IS NOT NULL THEN
        CALL COMERR(CONCAT('[', _$FANO, '] ', _$YEAR, '년 ', _$LOCKMM, '은 정기점검 실적이 있어 점검자를 삭제할 수 없습니다. 설비 정기점검 등록에서 해당 월 점검 실적을 먼저 삭제해주세요.'));
        LEAVE PROC;
      END IF;
    
      DELETE FROM CHKPLANEQM_YEARPLAN 
      WHERE EQMCD = _$FANO 
        AND YEAR  = _$YEAR 
        AND CHKTP = '02';
    END WHILE;

  -- *****************************************************************************

  END CASE;

  END IF;
