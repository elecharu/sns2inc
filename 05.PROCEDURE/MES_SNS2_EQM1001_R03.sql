      ON CHKPLANEQM_YEARPLAN.EQMCD = CHKRSTEQM.EQMCD
     AND CHKPLANEQM_YEARPLAN.YEAR = _$YEAR
     AND CHKPLANEQM_YEARPLAN.CHKTP = '02'
    WHERE CHKRSTEQM.EQMCD = _$FANO
      AND CHKRSTEQM.CHKTP = '02'
      AND CHKRSTEQM.BASEDATE LIKE CONCAT(_$YEAR, '-%')
      AND IFNULL(ELT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED),
                  CHKPLANEQM_YEARPLAN.MONTH_01, CHKPLANEQM_YEARPLAN.MONTH_02, CHKPLANEQM_YEARPLAN.MONTH_03,
                  CHKPLANEQM_YEARPLAN.MONTH_04, CHKPLANEQM_YEARPLAN.MONTH_05, CHKPLANEQM_YEARPLAN.MONTH_06,
                  CHKPLANEQM_YEARPLAN.MONTH_07, CHKPLANEQM_YEARPLAN.MONTH_08, CHKPLANEQM_YEARPLAN.MONTH_09,
                  CHKPLANEQM_YEARPLAN.MONTH_10, CHKPLANEQM_YEARPLAN.MONTH_11, CHKPLANEQM_YEARPLAN.MONTH_12), '') <> ''
      AND IFNULL(ELT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED),
                  CHKPLANEQM_YEARPLAN.MONTH_01, CHKPLANEQM_YEARPLAN.MONTH_02, CHKPLANEQM_YEARPLAN.MONTH_03,
                  CHKPLANEQM_YEARPLAN.MONTH_04, CHKPLANEQM_YEARPLAN.MONTH_05, CHKPLANEQM_YEARPLAN.MONTH_06,
                  CHKPLANEQM_YEARPLAN.MONTH_07, CHKPLANEQM_YEARPLAN.MONTH_08, CHKPLANEQM_YEARPLAN.MONTH_09,
                  CHKPLANEQM_YEARPLAN.MONTH_10, CHKPLANEQM_YEARPLAN.MONTH_11, CHKPLANEQM_YEARPLAN.MONTH_12), '') <> IFNULL(ELT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED),
                  _$M01, _$M02, _$M03, _$M04, _$M05, _$M06,
                  _$M07, _$M08, _$M09, _$M10, _$M11, _$M12), '');

    IF _$LOCKMM IS NOT NULL THEN
      CALL COMERR(CONCAT('[', _$FANO, '] ', _$YEAR, '년 ', _$LOCKMM, '은 정기점검 실적이 있어 점검자를 변경·삭제할 수 없습니다. 설비 정기점검 등록에서 해당 월 점검 실적을 먼저 삭제해주세요.'));
      LEAVE PROC;
    END IF;
  
    IF EXISTS (SELECT 1 FROM CHKPLANEQM_YEARPLAN WHERE EQMCD = _$FANO AND YEAR =_$YEAR AND CHKTP = '02') THEN  
      
      UPDATE CHKPLANEQM_YEARPLAN SET
        MONTH_01 = _$M01, 
        MONTH_02 = _$M02, 
        MONTH_03 = _$M03, 
        MONTH_04 = _$M04, 
        MONTH_05 = _$M05, 
        MONTH_06 = _$M06, 
        MONTH_07 = _$M07, 
        MONTH_08 = _$M08, 
        MONTH_09 = _$M09, 
        MONTH_10 = _$M10, 
        MONTH_11 = _$M11, 
        MONTH_12 = _$M12, 
        REMARK   = _$REMARK,
        MTIME = CALLTIME(),
        MEMP = CALLEMP(),
        MPRG = CALLPRG()
      WHERE EQMCD = _$FANO
        AND YEAR  = _$YEAR
        AND CHKTP = '02'
     ;
        
      IF EXISTS (
        SELECT 1 FROM CHKPLANEQM_YEARPLAN WHERE EQMCD = _$FANO AND YEAR = _$YEAR AND CHKTP = '02' AND REMARK = ''
                                                                AND MONTH_01 = '' AND MONTH_02 = '' AND MONTH_03 = '' AND MONTH_04 = ''
                                                                AND MONTH_05 = '' AND MONTH_06 = '' AND MONTH_07 = '' AND MONTH_08 = ''
                                                                AND MONTH_09 = '' AND MONTH_10 = '' AND MONTH_11 = '' AND MONTH_12 = '') THEN

        DELETE FROM CHKPLANEQM_YEARPLAN 
        WHERE EQMCD = _$FANO 
        AND YEAR = _$YEAR 
        AND CHKTP = '02';
      END IF;  
    ELSE
      INSERT INTO CHKPLANEQM_YEARPLAN (
        EQMCD, CHKTP, YEAR, 
        MONTH_01, MONTH_02, MONTH_03, MONTH_04, 
        MONTH_05, MONTH_06, MONTH_07, MONTH_08, 
        MONTH_09, MONTH_10, MONTH_11, MONTH_12, 
        REMARK, RTIME, REMP, RPRG
      ) 
      VALUES (
        _$FANO, '02', _$YEAR,
        _$M01, _$M02, _$M03, _$M04,
        _$M05, _$M06, _$M07, _$M08,
        _$M09, _$M10, _$M11, _$M12,
        _$REMARK, CALLTIME(), CALLEMP(), CALLPRG()
      );
   
      IF EXISTS (
        SELECT 1 FROM CHKPLANEQM_YEARPLAN WHERE EQMCD = _$FANO AND YEAR = _$YEAR AND CHKTP = '02' AND REMARK = ''
                                                                AND MONTH_01 = '' AND MONTH_02 = '' AND MONTH_03 = '' AND MONTH_04 = ''
                                                                AND MONTH_05 = '' AND MONTH_06 = '' AND MONTH_07 = '' AND MONTH_08 = ''
                                                                AND MONTH_09 = '' AND MONTH_10 = '' AND MONTH_11 = '' AND MONTH_12 = '') THEN

        DELETE FROM CHKPLANEQM_YEARPLAN 
        WHERE EQMCD = _$FANO
        AND YEAR = _$YEAR 
        AND CHKTP = '02';
      END IF;
    END IF;
  END WHILE;
-- *****************************************************************************
WHEN 'DELETE_CYCLE_EQMCD' THEN -- 설비별 월별 점검계획 삭제

  WHILE LENGTH($FANO_LIST) > 0 DO
    CALL COMSPLIT($FANO_LIST, _$FANO);
    CALL COMSPLIT($YEAR_LIST, _$YEAR);

    IF NOT EXISTS (SELECT 1 FROM MSTEQM WHERE FANO = _$FANO AND USEYN = 'Y') THEN
      CALL COMERR('사용 중인 설비를 선택해주세요.');
      LEAVE PROC;
    END IF;

    -- 정기점검 실적이 있는 월이 있으면 삭제 불가
    SELECT GROUP_CONCAT(DISTINCT CONCAT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED), '월')
                        ORDER BY SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) SEPARATOR ', ')
      INTO _$LOCKMM
    FROM CHKRSTEQM
    INNER JOIN CHKPLANEQM_YEARPLAN
      ON CHKPLANEQM_YEARPLAN.EQMCD = CHKRSTEQM.EQMCD
     AND CHKPLANEQM_YEARPLAN.YEAR = _$YEAR
     AND CHKPLANEQM_YEARPLAN.CHKTP = '02'
    WHERE CHKRSTEQM.EQMCD = _$FANO
      AND CHKRSTEQM.CHKTP = '02'
      AND CHKRSTEQM.BASEDATE LIKE CONCAT(_$YEAR, '-%')
      AND IFNULL(ELT(CAST(SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS UNSIGNED),
                  CHKPLANEQM_YEARPLAN.MONTH_01, CHKPLANEQM_YEARPLAN.MONTH_02, CHKPLANEQM_YEARPLAN.MONTH_03,
                  CHKPLANEQM_YEARPLAN.MONTH_04, CHKPLANEQM_YEARPLAN.MONTH_05, CHKPLANEQM_YEARPLAN.MONTH_06,
                  CHKPLANEQM_YEARPLAN.MONTH_07, CHKPLANEQM_YEARPLAN.MONTH_08, CHKPLANEQM_YEARPLAN.MONTH_09,
                  CHKPLANEQM_YEARPLAN.MONTH_10, CHKPLANEQM_YEARPLAN.MONTH_11, CHKPLANEQM_YEARPLAN.MONTH_12), '') <> '';

    IF _$LOCKMM IS NOT NULL THEN
      CALL COMERR(CONCAT('[', _$FANO, '] ', _$YEAR, '년 ', _$LOCKMM, '은 정기점검 실적이 있어 점검자를 삭제할 수 없습니다. 설비 정기점검 등록에서 해당 월 점검 실적을 먼저 삭제해주세요.'));
      LEAVE PROC;
    END IF;
  
    DELETE FROM CHKPLANEQM_YEARPLAN 
    WHERE EQMCD = _$FANO 
    AND YEAR = _$YEAR 
    AND CHKTP = '02';
  END WHILE;

