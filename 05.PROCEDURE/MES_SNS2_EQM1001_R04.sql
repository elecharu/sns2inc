CREATE DEFINER=`root`@`%` 
PROCEDURE `MES_SNS2`.`EQM1001_R04`(
-- *****************************************************************************
-- Comment: 설비 정기점검 등록 
-- Create: 	2025-06-27  	생성 			이대규
-- Modify: 	2026-09-15 		마이그레이션	한성수
-- 			2026-10-12 					한성수	월별 점검계획 직접 조회 및 중복 쿼리 정리
-- 			2026-10-23 					한성수	등록·수정 항목 조회 및 검증을 정기점검('02')으로 제한
-- 			2026-11-09 					한성수	점검항목 특이사항(REMARK) CRUD 추가 및 월별 점검자 배정 설비 연동
-- 			2026-11-10 					한성수	신규 점검 시 특이사항 기본값 초기화 (계획 특이사항 대체 제거)
-- 			2026-11-13 					한성수	월별 현황 점검자명 표시, 점검일자 년월 일치 검증 제거 및 계획월 이동·중복 계획 차단
-- *****************************************************************************
  IN $SYEAR           VARCHAR(50),
  IN $YYYYMM          VARCHAR(50),

  IN $EQMCD           VARCHAR(20),
  IN $CHKRSTKEY       VARCHAR(20),
  IN $CHKKNDCD_LIST   MEDIUMTEXT,
  IN $CHKVALUE_LIST   MEDIUMTEXT,
    
  IN $BASEDATE        VARCHAR(50),
  IN $EMPCD           VARCHAR(20),
  IN $PROBLEM         VARCHAR(1000),
  IN $SOLUTION        VARCHAR(1000),
  IN $GRPREVCD        VARCHAR(20),
  IN $PLANTP_LIST     MEDIUMTEXT,
  IN $REVCD           VARCHAR(20),
  IN $REMARK_LIST     MEDIUMTEXT,

-- *****************************************************************************
  IN $CALLTYPE        VARCHAR(50),
  IN $KEYWORD         VARCHAR(1000)
)
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  DECLARE _$EQMGRP       VARCHAR(50);
  DECLARE _$EQMREVCD     VARCHAR(20);
  DECLARE _$GRPREVCD     VARCHAR(20);
  DECLARE _$ITEMTP       CHAR(1);
  DECLARE _$ITEMREVCD    VARCHAR(20);
  DECLARE _$CHKRSTKEY    VARCHAR(20);
  DECLARE _$CHKKNDCD     VARCHAR(100);
  DECLARE _$CHKVALUE     VARCHAR(1000);
  DECLARE _$REMARK       VARCHAR(1000);
  DECLARE _$PLANEMP      VARCHAR(1000);
  DECLARE _$TGTEMP       VARCHAR(1000);
  DECLARE _$PLANEMPCD    VARCHAR(20);
  DECLARE _$ITEMCNT      INT;
  DECLARE _$ROWCNT       INT DEFAULT 0;
  DECLARE _$CHKYM        VARCHAR(7);

  -- 등록·수정 입력값 검증
  IF $CALLTYPE IN ('ADD_CHKRSTEQM', 'SAVE_CHKRSTEQM') THEN
    IF COALESCE($BASEDATE, '') = '' THEN
      CALL COMERR('점검일자를 선택해주세요.');
      LEAVE PROC;
    END IF;

    IF STR_TO_DATE($BASEDATE, '%Y-%m-%d') IS NULL THEN
      CALL COMERR('점검일자 형식이 올바르지 않습니다.');
      LEAVE PROC;
    END IF;

    IF COALESCE($YYYYMM, '') NOT REGEXP '^[0-9]{4}-(0[1-9]|1[0-2])$' THEN
      CALL COMERR('계획년월 정보가 올바르지 않습니다. 다시 조회해주세요.');
      LEAVE PROC;
    END IF;

    SET _$CHKYM = LEFT($BASEDATE, 7);

    IF COALESCE($EMPCD, '') = '' THEN
      CALL COMERR('점검자를 선택해주세요.');
      LEAVE PROC;
    END IF;

    IF COALESCE($CHKKNDCD_LIST, '') = '' THEN
      CALL COMERR('정기점검 항목이 없습니다.');
      LEAVE PROC;
    END IF;
  END IF;

  -- 설비 및 적용 승인본 확인
  IF $CALLTYPE IN ('LIST_PLAN_EQM02', 'ADD_CHKRSTEQM') THEN
    IF $CALLTYPE = 'ADD_CHKRSTEQM' THEN
      SET _$EQMGRP = (SELECT COALESCE(EQMGUBUN, '') FROM MSTEQM WHERE FANO = $EQMCD AND USEYN = 'Y' LIMIT 1 FOR UPDATE);
    ELSE
      SET _$EQMGRP = (SELECT COALESCE(EQMGUBUN, '') FROM MSTEQM WHERE FANO = $EQMCD AND USEYN = 'Y' LIMIT 1);
    END IF;

    IF _$EQMGRP IS NULL THEN
      CALL COMERR('사용 중인 설비를 선택해주세요.');
      LEAVE PROC;
    END IF;

    IF $CALLTYPE = 'LIST_PLAN_EQM02' THEN
      -- // 적용할 REV 찾기 (CHKTP = 02 -> 정기점검)
      SET _$GRPREVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'G' AND PLANCD = _$EQMGRP AND CHKTP = '02' AND APRVSTT = 'A' ORDER BY REVNUM DESC LIMIT 1);
      SET _$EQMREVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'E' AND PLANCD = $EQMCD AND CHKTP = '02' AND APRVSTT = 'A' ORDER BY REVNUM DESC LIMIT 1);
    ELSE
      -- 팝업에서 조회한 승인본 유지
      SET _$GRPREVCD = NULLIF($GRPREVCD, '');
      SET _$EQMREVCD = NULLIF($REVCD, '');

      -- 유효한 REV 인지 확인
      IF (_$GRPREVCD IS NOT NULL AND NOT EXISTS (SELECT 1 FROM MSTEQMREV_HEADER WHERE REVCD = _$GRPREVCD AND PLANTP = 'G' AND PLANCD = _$EQMGRP AND CHKTP = '02' AND APRVSTT = 'A' LIMIT 1))
         OR (_$EQMREVCD IS NOT NULL AND NOT EXISTS (SELECT 1 FROM MSTEQMREV_HEADER WHERE REVCD = _$EQMREVCD AND PLANTP = 'E' AND PLANCD = $EQMCD AND CHKTP = '02' AND APRVSTT = 'A' LIMIT 1)) THEN
        CALL COMERR('조회한 승인 계획이 변경되었습니다. 등록 창을 다시 열어주세요.');
        LEAVE PROC;
      END IF;
    END IF;

    SELECT COUNT(*) INTO _$ITEMCNT
    FROM MSTEQMREV_DETAIL
    WHERE REVCD IN (_$GRPREVCD, _$EQMREVCD);

    IF _$ITEMCNT = 0 THEN
      CALL COMERR('승인된 정기점검 계획이 없습니다. 점검계획을 승인한 후 등록해주세요.');
      LEAVE PROC;
    END IF;

    -- 조회·등록에서 같은 정기점검 월 배정 사용
    SET _$PLANEMP = (SELECT ELT(CAST(RIGHT($YYYYMM, 2) AS UNSIGNED),
                                MONTH_01, MONTH_02, MONTH_03, MONTH_04, MONTH_05, MONTH_06,
                                MONTH_07, MONTH_08, MONTH_09, MONTH_10, MONTH_11, MONTH_12)
                     FROM CHKPLANEQM_YEARPLAN
                     WHERE EQMCD = $EQMCD AND CHKTP = '02' AND YEAR = LEFT($YYYYMM, 4));
  END IF;

  -- 수정·삭제 대상 실적 확인
  IF $CALLTYPE IN ('SAVE_CHKRSTEQM', 'DELETE_CHKRSTEQM') THEN
    SET _$CHKRSTKEY = (SELECT CHKRSTKEY FROM CHKRSTEQM WHERE CHKRSTKEY = $CHKRSTKEY AND CHKTP = '02' LIMIT 1 FOR UPDATE);

    IF _$CHKRSTKEY IS NULL THEN
      CALL COMERR('수정·삭제할 정기점검 실적이 없습니다. 다시 조회해주세요.');
      LEAVE PROC;
    END IF;

    IF $CALLTYPE = 'SAVE_CHKRSTEQM' AND NOT EXISTS (SELECT 1 FROM CHKRSTEQM WHERE CHKRSTKEY = _$CHKRSTKEY AND EQMCD = $EQMCD AND LEFT(BASEDATE, 7) = $YYYYMM LIMIT 1) THEN
      CALL COMERR('조회한 설비·점검월과 저장 대상이 다릅니다. 다시 조회해주세요.');
      LEAVE PROC;
    END IF;
  END IF;

  -- 점검월에 다른 실적이나 기존 계획이 있으면 등록·수정 불가
  IF $CALLTYPE IN ('ADD_CHKRSTEQM', 'SAVE_CHKRSTEQM') THEN
    IF EXISTS (SELECT 1 FROM CHKRSTEQM WHERE EQMCD = $EQMCD AND CHKTP = '02' AND LEFT(BASEDATE, 7) = _$CHKYM AND CHKRSTKEY <> COALESCE(_$CHKRSTKEY, '') LIMIT 1) THEN
      CALL COMERR('해당 월에 이미 등록된 정기점검이 있습니다. 화면을 다시 조회해주세요.');
      LEAVE PROC;
    END IF;

    IF _$CHKYM <> $YYYYMM THEN
      SET _$TGTEMP = (SELECT ELT(CAST(RIGHT(_$CHKYM, 2) AS UNSIGNED),
                                 MONTH_01, MONTH_02, MONTH_03, MONTH_04, MONTH_05, MONTH_06,
                                 MONTH_07, MONTH_08, MONTH_09, MONTH_10, MONTH_11, MONTH_12)
                      FROM CHKPLANEQM_YEARPLAN
                      WHERE EQMCD = $EQMCD AND CHKTP = '02' AND YEAR = LEFT(_$CHKYM, 4)
                      LIMIT 1 FOR UPDATE);

      IF TRIM(COALESCE(_$TGTEMP, '')) <> '' THEN
        CALL COMERR('변경하려는 월에 이미 정기점검 계획이 있습니다.');
        LEAVE PROC;
      END IF;
    END IF;
  END IF;

  CASE $CALLTYPE
  -- *****************************************************************************

  WHEN 'LIST_CYCLE_EQMCD' THEN -- 월별 정기점검 현황
    WITH APPROVED_PLAN AS (
      SELECT PLAN_REV.PLANTP, PLAN_REV.PLANCD, 1 AS HASPLAN
      FROM (
        SELECT PLANTP, PLANCD, MAX(REVNUM) AS REVNUM
        FROM MSTEQMREV_HEADER
        WHERE APRVSTT = 'A' AND CHKTP = '02'
        GROUP BY PLANTP, PLANCD
      ) LAST_REV
      INNER JOIN MSTEQMREV_HEADER PLAN_REV
        ON PLAN_REV.PLANTP = LAST_REV.PLANTP AND PLAN_REV.PLANCD = LAST_REV.PLANCD AND PLAN_REV.REVNUM = LAST_REV.REVNUM
       AND PLAN_REV.CHKTP = '02' AND PLAN_REV.APRVSTT = 'A'
      INNER JOIN MSTEQMREV_DETAIL PLAN_ITEM ON PLAN_ITEM.REVCD = PLAN_REV.REVCD
      GROUP BY PLAN_REV.PLANTP, PLAN_REV.PLANCD
    )
    -- 실적이 있으면 점검완료(실적 점검자), 계획만 있으면 점검필요(계획 점검자)
    SELECT MSTEQM.FANO AS EQMCD, MSTEQM.EQMNM, $SYEAR AS YEAR,
           CASE WHEN RST.EMP01 IS NOT NULL THEN CONCAT('점검완료\n(', RST.EMP01, ')')
                WHEN YEAR_PLAN.MONTH_01 <> '' THEN CONCAT('점검필요\n(', COALESCE(EMP01.EMPNM, YEAR_PLAN.MONTH_01), ')') ELSE '' END AS M01,
           CASE WHEN RST.EMP02 IS NOT NULL THEN CONCAT('점검완료\n(', RST.EMP02, ')')
                WHEN YEAR_PLAN.MONTH_02 <> '' THEN CONCAT('점검필요\n(', COALESCE(EMP02.EMPNM, YEAR_PLAN.MONTH_02), ')') ELSE '' END AS M02,
           CASE WHEN RST.EMP03 IS NOT NULL THEN CONCAT('점검완료\n(', RST.EMP03, ')')
                WHEN YEAR_PLAN.MONTH_03 <> '' THEN CONCAT('점검필요\n(', COALESCE(EMP03.EMPNM, YEAR_PLAN.MONTH_03), ')') ELSE '' END AS M03,
           CASE WHEN RST.EMP04 IS NOT NULL THEN CONCAT('점검완료\n(', RST.EMP04, ')')
                WHEN YEAR_PLAN.MONTH_04 <> '' THEN CONCAT('점검필요\n(', COALESCE(EMP04.EMPNM, YEAR_PLAN.MONTH_04), ')') ELSE '' END AS M04,
           CASE WHEN RST.EMP05 IS NOT NULL THEN CONCAT('점검완료\n(', RST.EMP05, ')')
                WHEN YEAR_PLAN.MONTH_05 <> '' THEN CONCAT('점검필요\n(', COALESCE(EMP05.EMPNM, YEAR_PLAN.MONTH_05), ')') ELSE '' END AS M05,
           CASE WHEN RST.EMP06 IS NOT NULL THEN CONCAT('점검완료\n(', RST.EMP06, ')')
                WHEN YEAR_PLAN.MONTH_06 <> '' THEN CONCAT('점검필요\n(', COALESCE(EMP06.EMPNM, YEAR_PLAN.MONTH_06), ')') ELSE '' END AS M06,
           CASE WHEN RST.EMP07 IS NOT NULL THEN CONCAT('점검완료\n(', RST.EMP07, ')')
                WHEN YEAR_PLAN.MONTH_07 <> '' THEN CONCAT('점검필요\n(', COALESCE(EMP07.EMPNM, YEAR_PLAN.MONTH_07), ')') ELSE '' END AS M07,
           CASE WHEN RST.EMP08 IS NOT NULL THEN CONCAT('점검완료\n(', RST.EMP08, ')')
                WHEN YEAR_PLAN.MONTH_08 <> '' THEN CONCAT('점검필요\n(', COALESCE(EMP08.EMPNM, YEAR_PLAN.MONTH_08), ')') ELSE '' END AS M08,
           CASE WHEN RST.EMP09 IS NOT NULL THEN CONCAT('점검완료\n(', RST.EMP09, ')')
                WHEN YEAR_PLAN.MONTH_09 <> '' THEN CONCAT('점검필요\n(', COALESCE(EMP09.EMPNM, YEAR_PLAN.MONTH_09), ')') ELSE '' END AS M09,
           CASE WHEN RST.EMP10 IS NOT NULL THEN CONCAT('점검완료\n(', RST.EMP10, ')')
                WHEN YEAR_PLAN.MONTH_10 <> '' THEN CONCAT('점검필요\n(', COALESCE(EMP10.EMPNM, YEAR_PLAN.MONTH_10), ')') ELSE '' END AS M10,
           CASE WHEN RST.EMP11 IS NOT NULL THEN CONCAT('점검완료\n(', RST.EMP11, ')')
                WHEN YEAR_PLAN.MONTH_11 <> '' THEN CONCAT('점검필요\n(', COALESCE(EMP11.EMPNM, YEAR_PLAN.MONTH_11), ')') ELSE '' END AS M11,
           CASE WHEN RST.EMP12 IS NOT NULL THEN CONCAT('점검완료\n(', RST.EMP12, ')')
                WHEN YEAR_PLAN.MONTH_12 <> '' THEN CONCAT('점검필요\n(', COALESCE(EMP12.EMPNM, YEAR_PLAN.MONTH_12), ')') ELSE '' END AS M12
    FROM MSTEQM
    LEFT JOIN CHKPLANEQM_YEARPLAN YEAR_PLAN
      ON YEAR_PLAN.EQMCD = MSTEQM.FANO
     AND YEAR_PLAN.CHKTP = '02'
     AND YEAR_PLAN.YEAR = $SYEAR
    LEFT JOIN MSTEMP EMP01 ON EMP01.EMPCD = YEAR_PLAN.MONTH_01
    LEFT JOIN MSTEMP EMP02 ON EMP02.EMPCD = YEAR_PLAN.MONTH_02
    LEFT JOIN MSTEMP EMP03 ON EMP03.EMPCD = YEAR_PLAN.MONTH_03
    LEFT JOIN MSTEMP EMP04 ON EMP04.EMPCD = YEAR_PLAN.MONTH_04
    LEFT JOIN MSTEMP EMP05 ON EMP05.EMPCD = YEAR_PLAN.MONTH_05
    LEFT JOIN MSTEMP EMP06 ON EMP06.EMPCD = YEAR_PLAN.MONTH_06
    LEFT JOIN MSTEMP EMP07 ON EMP07.EMPCD = YEAR_PLAN.MONTH_07
    LEFT JOIN MSTEMP EMP08 ON EMP08.EMPCD = YEAR_PLAN.MONTH_08
    LEFT JOIN MSTEMP EMP09 ON EMP09.EMPCD = YEAR_PLAN.MONTH_09
    LEFT JOIN MSTEMP EMP10 ON EMP10.EMPCD = YEAR_PLAN.MONTH_10
    LEFT JOIN MSTEMP EMP11 ON EMP11.EMPCD = YEAR_PLAN.MONTH_11
    LEFT JOIN MSTEMP EMP12 ON EMP12.EMPCD = YEAR_PLAN.MONTH_12
    LEFT JOIN (
      SELECT RST_MM.EQMCD,
             MAX(IF(RST_MM.MM = '01', RST_MM.EMPNM, NULL)) AS EMP01,
             MAX(IF(RST_MM.MM = '02', RST_MM.EMPNM, NULL)) AS EMP02,
             MAX(IF(RST_MM.MM = '03', RST_MM.EMPNM, NULL)) AS EMP03,
             MAX(IF(RST_MM.MM = '04', RST_MM.EMPNM, NULL)) AS EMP04,
             MAX(IF(RST_MM.MM = '05', RST_MM.EMPNM, NULL)) AS EMP05,
             MAX(IF(RST_MM.MM = '06', RST_MM.EMPNM, NULL)) AS EMP06,
             MAX(IF(RST_MM.MM = '07', RST_MM.EMPNM, NULL)) AS EMP07,
             MAX(IF(RST_MM.MM = '08', RST_MM.EMPNM, NULL)) AS EMP08,
             MAX(IF(RST_MM.MM = '09', RST_MM.EMPNM, NULL)) AS EMP09,
             MAX(IF(RST_MM.MM = '10', RST_MM.EMPNM, NULL)) AS EMP10,
             MAX(IF(RST_MM.MM = '11', RST_MM.EMPNM, NULL)) AS EMP11,
             MAX(IF(RST_MM.MM = '12', RST_MM.EMPNM, NULL)) AS EMP12
      FROM (
        SELECT CHKRSTEQM.EQMCD, SUBSTRING(CHKRSTEQM.BASEDATE, 6, 2) AS MM, COALESCE(MSTEMP.EMPNM, CHKRSTEQM.EMPCD) AS EMPNM
        FROM CHKRSTEQM
        LEFT JOIN MSTEMP ON MSTEMP.EMPCD = CHKRSTEQM.EMPCD
        WHERE CHKRSTEQM.CHKTP = '02' AND CHKRSTEQM.BASEDATE LIKE CONCAT($SYEAR, '-%')
      ) RST_MM
      GROUP BY RST_MM.EQMCD
    ) RST ON RST.EQMCD = MSTEQM.FANO
    LEFT JOIN APPROVED_PLAN GRP_PLAN ON GRP_PLAN.PLANTP = 'G' AND GRP_PLAN.PLANCD = MSTEQM.EQMGUBUN
    LEFT JOIN APPROVED_PLAN EQM_PLAN ON EQM_PLAN.PLANTP = 'E' AND EQM_PLAN.PLANCD = MSTEQM.FANO
    WHERE MSTEQM.USEYN = 'Y'
      AND (   GRP_PLAN.HASPLAN = 1
           OR EQM_PLAN.HASPLAN = 1
           OR RST.EQMCD IS NOT NULL
           OR CONCAT(YEAR_PLAN.MONTH_01, YEAR_PLAN.MONTH_02, YEAR_PLAN.MONTH_03, YEAR_PLAN.MONTH_04, YEAR_PLAN.MONTH_05, YEAR_PLAN.MONTH_06,
                     YEAR_PLAN.MONTH_07, YEAR_PLAN.MONTH_08, YEAR_PLAN.MONTH_09, YEAR_PLAN.MONTH_10, YEAR_PLAN.MONTH_11, YEAR_PLAN.MONTH_12) <> ''
          )
      AND (MSTEQM.FANO LIKE CONCAT('%', $EQMCD, '%') OR MSTEQM.EQMNM LIKE CONCAT('%', $EQMCD, '%'))
    ORDER BY MSTEQM.FANO;

  -- *****************************************************************************

  WHEN 'LIST_PLAN_EQM02' THEN -- 그룹·설비 최신 승인 항목 조회 
    SET _$PLANEMP = TRIM(COALESCE(_$PLANEMP, ''));

    IF _$PLANEMP <> '' THEN
      SET _$PLANEMPCD = (SELECT EMPCD FROM MSTEMP WHERE EMPCD = _$PLANEMP LIMIT 1);
    END IF;

    -- 두 계획은 합쳐 저장하지 않고 점검할 때만 함께 표시 (앞에 CHKTP = '02' 조건 선언 되어있음)
    SELECT 'G' AS PLANTP,
           CONCAT('REV.', PLAN_REV.REVNUM) AS REVNM,
           COALESCE(_$EQMREVCD, '') AS EQMREVCD, COALESCE(_$GRPREVCD, '') AS GRPREVCD,
           PLAN_ITEM.CHKKNDCD, PLAN_ITEM.CHKKNDNM, PLAN_ITEM.CHKLOC, PLAN_ITEM.CHKMTH, PLAN_ITEM.CHKVALTP, PLAN_ITEM.SORTNO, '' AS CHKVALUE, '' AS REMARK,
           COALESCE(_$PLANEMPCD, '') AS PLANEMPCD, _$PLANEMP AS PLANEMPNM
    FROM MSTEQMREV_DETAIL PLAN_ITEM
    INNER JOIN MSTEQMREV_HEADER PLAN_REV ON PLAN_REV.REVCD = PLAN_ITEM.REVCD
    WHERE PLAN_ITEM.REVCD = _$GRPREVCD

    UNION ALL

    SELECT 'E' AS PLANTP,
           CONCAT('REV.', PLAN_REV.REVNUM) AS REVNM,
           COALESCE(_$EQMREVCD, '') AS EQMREVCD, COALESCE(_$GRPREVCD, '') AS GRPREVCD,
           PLAN_ITEM.CHKKNDCD, PLAN_ITEM.CHKKNDNM, PLAN_ITEM.CHKLOC, PLAN_ITEM.CHKMTH, PLAN_ITEM.CHKVALTP, PLAN_ITEM.SORTNO, '' AS CHKVALUE, '' AS REMARK,
           COALESCE(_$PLANEMPCD, '') AS PLANEMPCD, _$PLANEMP AS PLANEMPNM
    FROM MSTEQMREV_DETAIL PLAN_ITEM
    INNER JOIN MSTEQMREV_HEADER PLAN_REV ON PLAN_REV.REVCD = PLAN_ITEM.REVCD
    WHERE PLAN_ITEM.REVCD = _$EQMREVCD
    ORDER BY PLANTP DESC, SORTNO, CHKKNDCD;

  -- *****************************************************************************

  WHEN 'ADD_CHKRSTEQM' THEN -- 정기점검 등록
    IF COALESCE(_$PLANEMP, '') = '' THEN
      CALL COMERR('주기관리에서 점검자가 지정된 달만 정기점검을 등록할 수 있습니다. 화면을 다시 조회해주세요.');
      LEAVE PROC;
    END IF;

    SET _$CHKRSTKEY = GETKEY('CHKRSTKEY');

    INSERT INTO CHKRSTEQM (
      CHKRSTKEY, CHKTP, EQMCD, EMPCD, BASEDATE, PROBLEM, SOLUTION, REVCD, GRPREVCD, RTIME, REMP, RPRG
    ) VALUES (
      _$CHKRSTKEY, '02', $EQMCD, $EMPCD, $BASEDATE, $PROBLEM, $SOLUTION, COALESCE(_$EQMREVCD, ''), COALESCE(_$GRPREVCD, ''), CALLTIME(), CALLEMP(), CALLPRG()
    );

    WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
      CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);
      CALL COMSPLIT($PLANTP_LIST, _$ITEMTP);
      CALL COMSPLIT($CHKVALUE_LIST, _$CHKVALUE);
      CALL COMSPLIT($REMARK_LIST, _$REMARK);

      SET _$ITEMREVCD = CASE _$ITEMTP WHEN 'G' THEN _$GRPREVCD WHEN 'E' THEN _$EQMREVCD END;

      IF _$ITEMREVCD IS NULL OR NOT EXISTS (SELECT 1 FROM MSTEQMREV_DETAIL WHERE REVCD = _$ITEMREVCD AND CHKKNDCD = _$CHKKNDCD LIMIT 1) THEN
        CALL COMERR('조회한 승인 계획에 없는 점검항목입니다. 등록 창을 다시 열어주세요.');
        LEAVE PROC;
      END IF;

      IF TRIM(COALESCE(_$CHKVALUE, '')) = '' THEN
        CALL COMERR(CONCAT('점검코드 ', _$CHKKNDCD, '의 점검값을 입력해주세요.'));
        LEAVE PROC;
      END IF;

      -- 승인본의 항목정보 저장
      INSERT INTO CHKRSTEQMKND (
        CHKRSTKEY, PLANTP, CHKKNDCD, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, CHKVALUE, REMARK, SORTNO, RTIME, REMP, RPRG
      )
      SELECT _$CHKRSTKEY, _$ITEMTP,
             CHKKNDCD, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, _$CHKVALUE, COALESCE(_$REMARK, ''), SORTNO,
             CALLTIME(), CALLEMP(), CALLPRG()
      FROM MSTEQMREV_DETAIL
      WHERE REVCD = _$ITEMREVCD AND CHKKNDCD = _$CHKKNDCD;

      SET _$ROWCNT = _$ROWCNT + 1;
    END WHILE;

    IF _$ROWCNT <> _$ITEMCNT OR LENGTH(COALESCE($PLANTP_LIST, '')) > 0 OR LENGTH(COALESCE($CHKVALUE_LIST, '')) > 0
       OR LENGTH(COALESCE($REMARK_LIST, '')) > 0 THEN
      CALL COMERR('승인 계획의 모든 점검항목을 입력해주세요. 등록 창을 다시 열어주세요.');
      LEAVE PROC;
    END IF;

  -- *****************************************************************************

  WHEN 'SEARCH_CHKRSTEQM' THEN -- 저장된 월별 실적 조회
    SET _$CHKRSTKEY = (SELECT CHKRSTKEY FROM CHKRSTEQM WHERE EQMCD = $EQMCD AND CHKTP = '02' AND LEFT(BASEDATE, 7) = $YYYYMM ORDER BY BASEDATE, CHKRSTKEY LIMIT 1);
    
    IF _$CHKRSTKEY IS NULL THEN
      CALL COMERR('조회할 정기점검 실적이 없습니다. 다시 조회해주세요.');
      LEAVE PROC;
    END IF;

    SELECT CHKRSTKEY, EQMCD, EMPCD, BASEDATE, LEFT(BASEDATE, 7) AS YYYYMM, PROBLEM, SOLUTION
    FROM CHKRSTEQM
    WHERE CHKRSTKEY = _$CHKRSTKEY;

    SELECT RST_ITEM.PLANTP,
           RST_ITEM.CHKKNDCD, RST_ITEM.CHKKNDNM, RST_ITEM.CHKLOC, RST_ITEM.CHKMTH, RST_ITEM.CHKVALTP, RST_ITEM.CHKVALUE, RST_ITEM.REMARK,
           CONCAT('REV.', PLAN_REV.REVNUM) AS REVNM
    FROM CHKRSTEQMKND RST_ITEM
    INNER JOIN CHKRSTEQM RST ON RST.CHKRSTKEY = RST_ITEM.CHKRSTKEY
    INNER JOIN MSTEQMREV_HEADER PLAN_REV
      ON PLAN_REV.REVCD = IF(RST_ITEM.PLANTP = 'G', RST.GRPREVCD, RST.REVCD)
     AND PLAN_REV.CHKTP = '02'
    WHERE RST_ITEM.CHKRSTKEY = _$CHKRSTKEY
    ORDER BY (RST_ITEM.PLANTP = 'G') DESC, RST_ITEM.SORTNO, RST_ITEM.CHKKNDCD;

  -- *****************************************************************************

  WHEN 'SAVE_CHKRSTEQM' THEN -- 기존 실적의 점검값 수정
    SELECT COUNT(*) INTO _$ITEMCNT
    FROM CHKRSTEQMKND
    WHERE CHKRSTKEY = _$CHKRSTKEY;

    -- 같은 항목을 중복 전달하면 전체 저장을 취소
    DROP TEMPORARY TABLE IF EXISTS TMP_RST_ITEM;
    CREATE TEMPORARY TABLE TMP_RST_ITEM (
      PLANTP   CHAR(1)      NOT NULL,
      CHKKNDCD VARCHAR(100) NOT NULL,
      PRIMARY KEY (PLANTP, CHKKNDCD)
    ) ENGINE=InnoDB;

    WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
      CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);
      CALL COMSPLIT($PLANTP_LIST, _$ITEMTP);
      CALL COMSPLIT($CHKVALUE_LIST, _$CHKVALUE);
      CALL COMSPLIT($REMARK_LIST, _$REMARK);

      IF _$ITEMTP IS NULL OR NOT EXISTS (SELECT 1 FROM CHKRSTEQMKND WHERE CHKRSTKEY = _$CHKRSTKEY AND PLANTP = _$ITEMTP AND CHKKNDCD = _$CHKKNDCD LIMIT 1) THEN
        DROP TEMPORARY TABLE IF EXISTS TMP_RST_ITEM;
        CALL COMERR('저장된 실적과 점검항목이 다릅니다. 다시 조회해주세요.');
        LEAVE PROC;
      END IF;

      IF TRIM(COALESCE(_$CHKVALUE, '')) = '' THEN
        DROP TEMPORARY TABLE IF EXISTS TMP_RST_ITEM;
        CALL COMERR(CONCAT('점검코드 ', _$CHKKNDCD, '의 점검값을 입력해주세요.'));
        LEAVE PROC;
      END IF;

      INSERT INTO TMP_RST_ITEM VALUES (_$ITEMTP, _$CHKKNDCD);

      UPDATE CHKRSTEQMKND
      SET CHKVALUE = _$CHKVALUE,
          REMARK   = COALESCE(_$REMARK, ''),
          MTIME    = CALLTIME(),
          MEMP     = CALLEMP(),
          MPRG     = CALLPRG()
      WHERE CHKRSTKEY = _$CHKRSTKEY
        AND PLANTP = _$ITEMTP
        AND CHKKNDCD = _$CHKKNDCD;

      SET _$ROWCNT = _$ROWCNT + 1;
    END WHILE;

    DROP TEMPORARY TABLE IF EXISTS TMP_RST_ITEM;

    IF _$ROWCNT <> _$ITEMCNT OR LENGTH(COALESCE($PLANTP_LIST, '')) > 0 OR LENGTH(COALESCE($CHKVALUE_LIST, '')) > 0
       OR LENGTH(COALESCE($REMARK_LIST, '')) > 0 THEN
      CALL COMERR('실적의 모든 점검항목을 입력해주세요. 다시 조회해주세요.');
      LEAVE PROC;
    END IF;

    UPDATE CHKRSTEQM
    SET EMPCD    = $EMPCD,
        BASEDATE = $BASEDATE,
        PROBLEM  = $PROBLEM,
        SOLUTION = $SOLUTION,
        MTIME    = CALLTIME(),
        MEMP     = CALLEMP(),
        MPRG     = CALLPRG()
    WHERE CHKRSTKEY = _$CHKRSTKEY;

  -- *****************************************************************************

  WHEN 'DELETE_CHKRSTEQM' THEN -- 정기점검 실적 삭제
    DELETE FROM CHKRSTEQMKND WHERE CHKRSTKEY = _$CHKRSTKEY;
    DELETE FROM CHKRSTEQM WHERE CHKRSTKEY = _$CHKRSTKEY;

  -- *****************************************************************************

  END CASE;

  -- 점검월이 계획월과 다르면 주기관리 계획을 점검월로 이동
  IF $CALLTYPE IN ('ADD_CHKRSTEQM', 'SAVE_CHKRSTEQM') AND _$CHKYM <> $YYYYMM THEN
    IF NOT EXISTS (SELECT 1 FROM CHKPLANEQM_YEARPLAN WHERE EQMCD = $EQMCD AND CHKTP = '02' AND YEAR = LEFT(_$CHKYM, 4)) THEN
      INSERT INTO CHKPLANEQM_YEARPLAN (
        EQMCD, CHKTP, YEAR,
        MONTH_01, MONTH_02, MONTH_03, MONTH_04, MONTH_05, MONTH_06,
        MONTH_07, MONTH_08, MONTH_09, MONTH_10, MONTH_11, MONTH_12,
        REMARK, RTIME, REMP, RPRG
      ) VALUES (
        $EQMCD, '02', LEFT(_$CHKYM, 4),
        '', '', '', '', '', '', '', '', '', '', '', '',
        '', CALLTIME(), CALLEMP(), CALLPRG()
      );
    END IF;

    UPDATE CHKPLANEQM_YEARPLAN
    SET MONTH_01 = CASE CONCAT(YEAR, '-01') WHEN _$CHKYM THEN $EMPCD WHEN $YYYYMM THEN '' ELSE MONTH_01 END,
        MONTH_02 = CASE CONCAT(YEAR, '-02') WHEN _$CHKYM THEN $EMPCD WHEN $YYYYMM THEN '' ELSE MONTH_02 END,
        MONTH_03 = CASE CONCAT(YEAR, '-03') WHEN _$CHKYM THEN $EMPCD WHEN $YYYYMM THEN '' ELSE MONTH_03 END,
        MONTH_04 = CASE CONCAT(YEAR, '-04') WHEN _$CHKYM THEN $EMPCD WHEN $YYYYMM THEN '' ELSE MONTH_04 END,
        MONTH_05 = CASE CONCAT(YEAR, '-05') WHEN _$CHKYM THEN $EMPCD WHEN $YYYYMM THEN '' ELSE MONTH_05 END,
        MONTH_06 = CASE CONCAT(YEAR, '-06') WHEN _$CHKYM THEN $EMPCD WHEN $YYYYMM THEN '' ELSE MONTH_06 END,
        MONTH_07 = CASE CONCAT(YEAR, '-07') WHEN _$CHKYM THEN $EMPCD WHEN $YYYYMM THEN '' ELSE MONTH_07 END,
        MONTH_08 = CASE CONCAT(YEAR, '-08') WHEN _$CHKYM THEN $EMPCD WHEN $YYYYMM THEN '' ELSE MONTH_08 END,
        MONTH_09 = CASE CONCAT(YEAR, '-09') WHEN _$CHKYM THEN $EMPCD WHEN $YYYYMM THEN '' ELSE MONTH_09 END,
        MONTH_10 = CASE CONCAT(YEAR, '-10') WHEN _$CHKYM THEN $EMPCD WHEN $YYYYMM THEN '' ELSE MONTH_10 END,
        MONTH_11 = CASE CONCAT(YEAR, '-11') WHEN _$CHKYM THEN $EMPCD WHEN $YYYYMM THEN '' ELSE MONTH_11 END,
        MONTH_12 = CASE CONCAT(YEAR, '-12') WHEN _$CHKYM THEN $EMPCD WHEN $YYYYMM THEN '' ELSE MONTH_12 END,
        MTIME    = CALLTIME(),
        MEMP     = CALLEMP(),
        MPRG     = CALLPRG()
    WHERE EQMCD = $EQMCD
      AND CHKTP = '02'
      AND YEAR IN (LEFT($YYYYMM, 4), LEFT(_$CHKYM, 4));

    -- 년도가 바뀌어 비게 된 기존 계획 행 정리
    DELETE FROM CHKPLANEQM_YEARPLAN
    WHERE EQMCD = $EQMCD AND CHKTP = '02' AND YEAR = LEFT($YYYYMM, 4) AND REMARK = ''
      AND CONCAT(MONTH_01, MONTH_02, MONTH_03, MONTH_04, MONTH_05, MONTH_06,
                 MONTH_07, MONTH_08, MONTH_09, MONTH_10, MONTH_11, MONTH_12) = '';
  END IF;
END
