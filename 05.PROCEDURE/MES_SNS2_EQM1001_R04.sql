CREATE DEFINER=`root`@`%` PROCEDURE `MES_SNS2`.`EQM1001_R04`(
-- *****************************************************************************
-- Comment: 설비 정기점검 등록 
-- Create: 	2025-06-27  	생성 			이대규
-- Modify: 	2026-09-15 		마이그레이션	한성수
-- 			2026-09-16 					한성수	MSTEQM.FANO(설비코드) 컬럼 바인딩 변경
-- 			2026-09-22 					한성수	승인된 설비그룹·설비별 정기점검 계획만 실행
-- 			2026-09-30 					한성수	설비 승인 리비전(REV) 승인본 기준 점검 및 점검실적 적용 리비전 기록
-- 			2026-10-01 					한성수	REVCD 기준 승인본/실적 처리, 설비그룹 없는 설비 지원 및 해당 월 점검자 반환
-- 			2026-10-02 					한성수	수정 조회 적용 리비전 반환, 중복·미계획 등록 차단, 항목·점검값 검증 및 성능 개선
-- 			2026-10-06 					한성수	승인 REV 조회 통합, 계획조회 REV 표시 및 DETAIL 설비코드 중복 제거
-- 			2026-10-08 					한성수	미사용 입력값 제거, 그룹·설비 승인본 독립 적용·실적 출처 저장·REV 번호 표시 및 DETAIL 사용여부 조건 제거
-- 			2026-10-12 					한성수	정기점검 월계획 직접 조회·중복 조회 정리 및 미사용 반환 컬럼 제거
-- *****************************************************************************
  IN $SYEAR           VARCHAR(50),
  IN $YYYYMM          VARCHAR(50),

  IN $EQMCD           VARCHAR(20),
  IN $CHKRSTKEY       VARCHAR(20),
  IN $CHKKNDCD_LIST   MEDIUMTEXT,
  IN $CHKVALUE_LIST   MEDIUMTEXT,
    
  IN $BASEDATE        VARCHAR(50),
  IN $EMPCD           VARCHAR(20),
  IN $PROBLEM         VARCHAR(1000),
  IN $SOLUTION        VARCHAR(1000),
  IN $GRPREVCD        VARCHAR(20),
  IN $PLANTP_LIST     MEDIUMTEXT,
  IN $REVCD           VARCHAR(20),

-- *****************************************************************************
IN  $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  DECLARE _$EQMGRP       VARCHAR(50);
  DECLARE _$EQMREVCD     VARCHAR(20);
  DECLARE _$GRPREVCD     VARCHAR(20);
  DECLARE _$ITEMTP       CHAR(1);
  DECLARE _$ITEMREVCD    VARCHAR(20);
  DECLARE _$CHKRSTKEY    VARCHAR(20);
  DECLARE _$CHKKNDCD     VARCHAR(100);
  DECLARE _$CHKVALUE     VARCHAR(1000);
  DECLARE _$PLANEMP      VARCHAR(1000);
  DECLARE _$PLANEMPCD    VARCHAR(20);
  DECLARE _$ITEMCNT      INT;
  DECLARE _$ROWCNT       INT DEFAULT 0;

-- 등록·수정 입력값 검증
IF $CALLTYPE IN ('ADD_CHKRSTEQM', 'SAVE_CHKRSTEQM') THEN
  IF COALESCE($BASEDATE, '') = '' THEN
    CALL COMERR('점검일자를 선택해주세요.');
    LEAVE PROC;
  END IF;
  IF COALESCE($YYYYMM, '') NOT REGEXP '^[0-9]{4}-(0[1-9]|1[0-2])$' OR LEFT($BASEDATE, 7) <> $YYYYMM
     OR STR_TO_DATE($BASEDATE, '%Y-%m-%d') IS NULL THEN
    CALL COMERR('점검일자의 년월이 계획년월과 다릅니다.');
    LEAVE PROC;
  END IF;
  IF COALESCE($EMPCD, '') = '' THEN
    CALL COMERR('점검자를 선택해주세요.');
    LEAVE PROC;
  END IF;
  IF COALESCE($CHKKNDCD_LIST, '') = '' THEN
    CALL COMERR('정기점검 항목이 없습니다.');
    LEAVE PROC;
  END IF;
END IF;

-- 설비 및 적용 승인본 확인
IF $CALLTYPE IN ('LIST_PLAN_EQM02', 'ADD_CHKRSTEQM') THEN
  IF $CALLTYPE = 'ADD_CHKRSTEQM' THEN
    SET _$EQMGRP = (SELECT COALESCE(EQMGUBUN, '') FROM MSTEQM WHERE FANO = $EQMCD AND USEYN = 'Y' LIMIT 1 FOR UPDATE);
  ELSE
    SET _$EQMGRP = (SELECT COALESCE(EQMGUBUN, '') FROM MSTEQM WHERE FANO = $EQMCD AND USEYN = 'Y' LIMIT 1);
  END IF;
  IF _$EQMGRP IS NULL THEN
    CALL COMERR('사용 중인 설비를 선택해주세요.');
    LEAVE PROC;
  END IF;
  IF $CALLTYPE = 'LIST_PLAN_EQM02' THEN
    SET _$GRPREVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'G' AND PLANCD = _$EQMGRP AND APRVSTT = 'A' ORDER BY REVNUM DESC LIMIT 1);
    SET _$EQMREVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'E' AND PLANCD = $EQMCD AND APRVSTT = 'A' ORDER BY REVNUM DESC LIMIT 1);
  ELSE
    -- 팝업에서 조회한 승인본 유지
    SET _$GRPREVCD = NULLIF($GRPREVCD, '');
    SET _$EQMREVCD = NULLIF($REVCD, '');
    IF (_$GRPREVCD IS NOT NULL AND NOT EXISTS (SELECT 1 FROM MSTEQMREV_HEADER WHERE REVCD = _$GRPREVCD AND PLANTP = 'G' AND PLANCD = _$EQMGRP AND APRVSTT = 'A' LIMIT 1))
       OR (_$EQMREVCD IS NOT NULL AND NOT EXISTS (SELECT 1 FROM MSTEQMREV_HEADER WHERE REVCD = _$EQMREVCD AND PLANTP = 'E' AND PLANCD = $EQMCD AND APRVSTT = 'A' LIMIT 1)) THEN
      CALL COMERR('조회한 승인 계획이 변경되었습니다. 등록 창을 다시 열어주세요.');
      LEAVE PROC;
    END IF;
  END IF;
  SELECT COUNT(*) INTO _$ITEMCNT FROM MSTEQMREV_DETAIL WHERE REVCD IN (_$GRPREVCD, _$EQMREVCD);
  IF _$ITEMCNT = 0 THEN
    CALL COMERR('승인된 정기점검 항목이 없습니다.');
    LEAVE PROC;
  END IF;

  -- 조회·등록에서 같은 정기점검 월 배정 사용
  SET _$PLANEMP = (SELECT ELT(CAST(RIGHT($YYYYMM, 2) AS UNSIGNED),
                              MONTH_01, MONTH_02, MONTH_03, MONTH_04, MONTH_05, MONTH_06,
                              MONTH_07, MONTH_08, MONTH_09, MONTH_10, MONTH_11, MONTH_12)
                   FROM CHKPLANEQM_YEARPLAN
                   WHERE EQMCD = $EQMCD AND CHKTP = '02' AND YEAR = LEFT($YYYYMM, 4));
END IF;

-- 수정·삭제 대상 실적 확인
IF $CALLTYPE IN ('SAVE_CHKRSTEQM', 'DELETE_CHKRSTEQM') THEN
  SET _$CHKRSTKEY = (SELECT CHKRSTKEY FROM CHKRSTEQM WHERE CHKRSTKEY = $CHKRSTKEY AND CHKTP = '02' LIMIT 1 FOR UPDATE);
  IF _$CHKRSTKEY IS NULL THEN
    CALL COMERR('수정·삭제할 정기점검 실적이 없습니다. 다시 조회해주세요.');
    LEAVE PROC;
  END IF;
  IF $CALLTYPE = 'SAVE_CHKRSTEQM' AND NOT EXISTS (SELECT 1 FROM CHKRSTEQM WHERE CHKRSTKEY = _$CHKRSTKEY AND EQMCD = $EQMCD AND LEFT(BASEDATE, 7) = $YYYYMM LIMIT 1) THEN
    CALL COMERR('조회한 설비·점검월과 저장 대상이 다릅니다. 다시 조회해주세요.');
    LEAVE PROC;
  END IF;
END IF;

CASE $CALLTYPE
-- *****************************************************************************

WHEN 'LIST_CYCLE_EQMCD' THEN -- 월별 정기점검 현황
  WITH APPROVED_PLAN AS (
    SELECT PLAN_REV.PLANTP, PLAN_REV.PLANCD, 1 AS HASPLAN
    FROM (SELECT PLANTP, PLANCD, MAX(REVNUM) AS REVNUM FROM MSTEQMREV_HEADER WHERE APRVSTT = 'A' GROUP BY PLANTP, PLANCD) LAST_REV
    INNER JOIN MSTEQMREV_HEADER PLAN_REV
      ON PLAN_REV.PLANTP = LAST_REV.PLANTP AND PLAN_REV.PLANCD = LAST_REV.PLANCD AND PLAN_REV.REVNUM = LAST_REV.REVNUM
    INNER JOIN MSTEQMREV_DETAIL PLAN_ITEM ON PLAN_ITEM.REVCD = PLAN_REV.REVCD
    GROUP BY PLAN_REV.PLANTP, PLAN_REV.PLANCD
  )
  SELECT MSTEQM.FANO AS EQMCD, MSTEQM.EQMNM, $SYEAR AS YEAR,
    CASE WHEN FIND_IN_SET('01', RST.RSTMM) THEN '점검완료'
         WHEN YEAR_PLAN.MONTH_01 <> '' AND (GRP_PLAN.HASPLAN = 1 OR EQM_PLAN.HASPLAN = 1) THEN '점검필요' ELSE '' END AS M01,
    CASE WHEN FIND_IN_SET('02', RST.RSTMM) THEN '점검완료'
         WHEN YEAR_PLAN.MONTH_02 <> '' AND (GRP_PLAN.HASPLAN = 1 OR EQM_PLAN.HASPLAN = 1) THEN '점검필요' ELSE '' END AS M02,
    CASE WHEN FIND_IN_SET('03', RST.RSTMM) THEN '점검완료'
         WHEN YEAR_PLAN.MONTH_03 <> '' AND (GRP_PLAN.HASPLAN = 1 OR EQM_PLAN.HASPLAN = 1) THEN '점검필요' ELSE '' END AS M03,
    CASE WHEN FIND_IN_SET('04', RST.RSTMM) THEN '점검완료'
         WHEN YEAR_PLAN.MONTH_04 <> '' AND (GRP_PLAN.HASPLAN = 1 OR EQM_PLAN.HASPLAN = 1) THEN '점검필요' ELSE '' END AS M04,
    CASE WHEN FIND_IN_SET('05', RST.RSTMM) THEN '점검완료'
         WHEN YEAR_PLAN.MONTH_05 <> '' AND (GRP_PLAN.HASPLAN = 1 OR EQM_PLAN.HASPLAN = 1) THEN '점검필요' ELSE '' END AS M05,
    CASE WHEN FIND_IN_SET('06', RST.RSTMM) THEN '점검완료'
         WHEN YEAR_PLAN.MONTH_06 <> '' AND (GRP_PLAN.HASPLAN = 1 OR EQM_PLAN.HASPLAN = 1) THEN '점검필요' ELSE '' END AS M06,
    CASE WHEN FIND_IN_SET('07', RST.RSTMM) THEN '점검완료'
         WHEN YEAR_PLAN.MONTH_07 <> '' AND (GRP_PLAN.HASPLAN = 1 OR EQM_PLAN.HASPLAN = 1) THEN '점검필요' ELSE '' END AS M07,
    CASE WHEN FIND_IN_SET('08', RST.RSTMM) THEN '점검완료'
         WHEN YEAR_PLAN.MONTH_08 <> '' AND (GRP_PLAN.HASPLAN = 1 OR EQM_PLAN.HASPLAN = 1) THEN '점검필요' ELSE '' END AS M08,
    CASE WHEN FIND_IN_SET('09', RST.RSTMM) THEN '점검완료'
         WHEN YEAR_PLAN.MONTH_09 <> '' AND (GRP_PLAN.HASPLAN = 1 OR EQM_PLAN.HASPLAN = 1) THEN '점검필요' ELSE '' END AS M09,
    CASE WHEN FIND_IN_SET('10', RST.RSTMM) THEN '점검완료'
         WHEN YEAR_PLAN.MONTH_10 <> '' AND (GRP_PLAN.HASPLAN = 1 OR EQM_PLAN.HASPLAN = 1) THEN '점검필요' ELSE '' END AS M10,
    CASE WHEN FIND_IN_SET('11', RST.RSTMM) THEN '점검완료'
         WHEN YEAR_PLAN.MONTH_11 <> '' AND (GRP_PLAN.HASPLAN = 1 OR EQM_PLAN.HASPLAN = 1) THEN '점검필요' ELSE '' END AS M11,
    CASE WHEN FIND_IN_SET('12', RST.RSTMM) THEN '점검완료'
         WHEN YEAR_PLAN.MONTH_12 <> '' AND (GRP_PLAN.HASPLAN = 1 OR EQM_PLAN.HASPLAN = 1) THEN '점검필요' ELSE '' END AS M12
  FROM MSTEQM
  LEFT JOIN CHKPLANEQM_YEARPLAN YEAR_PLAN
    ON YEAR_PLAN.EQMCD = MSTEQM.FANO
   AND YEAR_PLAN.CHKTP = '02'
   AND YEAR_PLAN.YEAR = $SYEAR
  LEFT JOIN (
    SELECT EQMCD, GROUP_CONCAT(DISTINCT SUBSTRING(BASEDATE, 6, 2)) AS RSTMM
    FROM CHKRSTEQM WHERE CHKTP = '02' AND BASEDATE LIKE CONCAT($SYEAR, '-%') GROUP BY EQMCD
  ) RST ON RST.EQMCD = MSTEQM.FANO
  LEFT JOIN APPROVED_PLAN GRP_PLAN ON GRP_PLAN.PLANTP = 'G' AND GRP_PLAN.PLANCD = MSTEQM.EQMGUBUN
  LEFT JOIN APPROVED_PLAN EQM_PLAN ON EQM_PLAN.PLANTP = 'E' AND EQM_PLAN.PLANCD = MSTEQM.FANO
  WHERE MSTEQM.USEYN = 'Y' AND (GRP_PLAN.HASPLAN = 1 OR EQM_PLAN.HASPLAN = 1 OR RST.EQMCD IS NOT NULL)
    AND (MSTEQM.FANO LIKE CONCAT('%', $EQMCD, '%') OR MSTEQM.EQMNM LIKE CONCAT('%', $EQMCD, '%'))
  ORDER BY MSTEQM.FANO;

-- *****************************************************************************

WHEN 'LIST_PLAN_EQM02' THEN -- 그룹·설비 최신 승인 항목 조회
  SET _$PLANEMP = TRIM(COALESCE(_$PLANEMP, ''));
  IF _$PLANEMP <> '' THEN
    SET _$PLANEMPCD = (SELECT EMPCD FROM MSTEMP WHERE EMPCD = _$PLANEMP LIMIT 1);
  END IF;
  -- 두 계획은 합쳐 저장하지 않고 점검할 때만 함께 표시
  SELECT 'G' AS PLANTP,
         CONCAT('REV.', PLAN_REV.REVNUM) AS REVNM,
         COALESCE(_$EQMREVCD, '') AS EQMREVCD, COALESCE(_$GRPREVCD, '') AS GRPREVCD,
         PLAN_ITEM.CHKKNDCD, PLAN_ITEM.CHKKNDNM, PLAN_ITEM.CHKLOC, PLAN_ITEM.CHKMTH, PLAN_ITEM.CHKVALTP, PLAN_ITEM.SORTNO, '' AS CHKVALUE,
         COALESCE(_$PLANEMPCD, '') AS PLANEMPCD, _$PLANEMP AS PLANEMPNM
  FROM MSTEQMREV_DETAIL PLAN_ITEM
  INNER JOIN MSTEQMREV_HEADER PLAN_REV ON PLAN_REV.REVCD = PLAN_ITEM.REVCD
  WHERE PLAN_ITEM.REVCD = _$GRPREVCD
  UNION ALL
  SELECT 'E' AS PLANTP,
         CONCAT('REV.', PLAN_REV.REVNUM) AS REVNM,
         COALESCE(_$EQMREVCD, '') AS EQMREVCD, COALESCE(_$GRPREVCD, '') AS GRPREVCD,
         PLAN_ITEM.CHKKNDCD, PLAN_ITEM.CHKKNDNM, PLAN_ITEM.CHKLOC, PLAN_ITEM.CHKMTH, PLAN_ITEM.CHKVALTP, PLAN_ITEM.SORTNO, '' AS CHKVALUE,
         COALESCE(_$PLANEMPCD, '') AS PLANEMPCD, _$PLANEMP AS PLANEMPNM
  FROM MSTEQMREV_DETAIL PLAN_ITEM
  INNER JOIN MSTEQMREV_HEADER PLAN_REV ON PLAN_REV.REVCD = PLAN_ITEM.REVCD
  WHERE PLAN_ITEM.REVCD = _$EQMREVCD
  ORDER BY PLANTP DESC, SORTNO, CHKKNDCD;

-- *****************************************************************************

WHEN 'ADD_CHKRSTEQM' THEN -- 정기점검 등록
  IF COALESCE(_$PLANEMP, '') = '' THEN
    CALL COMERR('주기관리에서 점검자가 지정된 달만 정기점검을 등록할 수 있습니다. 화면을 다시 조회해주세요.');
    LEAVE PROC;
  END IF;
  IF EXISTS (SELECT 1 FROM CHKRSTEQM WHERE EQMCD = $EQMCD AND CHKTP = '02' AND LEFT(BASEDATE, 7) = $YYYYMM LIMIT 1) THEN
    CALL COMERR('이미 등록된 정기점검이 있습니다. 화면을 다시 조회해주세요.');
    LEAVE PROC;
  END IF;
  SET _$CHKRSTKEY = GETKEY('CHKRSTKEY');
  INSERT INTO CHKRSTEQM (CHKRSTKEY, CHKTP, EQMCD, EMPCD, BASEDATE, PROBLEM, SOLUTION, REVCD, GRPREVCD, RTIME, REMP, RPRG)
  VALUES (_$CHKRSTKEY, '02', $EQMCD, $EMPCD, $BASEDATE, $PROBLEM, $SOLUTION, COALESCE(_$EQMREVCD, ''), COALESCE(_$GRPREVCD, ''), CALLTIME(), CALLEMP(), CALLPRG());
  WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
    CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);
    CALL COMSPLIT($PLANTP_LIST, _$ITEMTP);
    CALL COMSPLIT($CHKVALUE_LIST, _$CHKVALUE);
    SET _$ITEMREVCD = CASE _$ITEMTP WHEN 'G' THEN _$GRPREVCD WHEN 'E' THEN _$EQMREVCD END;
    IF _$ITEMREVCD IS NULL OR NOT EXISTS (SELECT 1 FROM MSTEQMREV_DETAIL WHERE REVCD = _$ITEMREVCD AND CHKKNDCD = _$CHKKNDCD LIMIT 1) THEN
      CALL COMERR('조회한 승인 계획에 없는 점검항목입니다. 등록 창을 다시 열어주세요.');
      LEAVE PROC;
    END IF;
    IF TRIM(COALESCE(_$CHKVALUE, '')) = '' THEN
      CALL COMERR(CONCAT('점검코드 ', _$CHKKNDCD, '의 점검값을 입력해주세요.'));
      LEAVE PROC;
    END IF;
    -- 승인본의 항목정보 저장
    INSERT INTO CHKRSTEQMKND (CHKRSTKEY, PLANTP, CHKKNDCD, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, CHKVALUE, SORTNO, RTIME, REMP, RPRG)
    SELECT _$CHKRSTKEY, _$ITEMTP, CHKKNDCD, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, _$CHKVALUE, SORTNO, CALLTIME(), CALLEMP(), CALLPRG()
    FROM MSTEQMREV_DETAIL WHERE REVCD = _$ITEMREVCD AND CHKKNDCD = _$CHKKNDCD;
    SET _$ROWCNT = _$ROWCNT + 1;
  END WHILE;
  IF _$ROWCNT <> _$ITEMCNT OR LENGTH(COALESCE($PLANTP_LIST, '')) > 0 OR LENGTH(COALESCE($CHKVALUE_LIST, '')) > 0 THEN
    CALL COMERR('승인 계획의 모든 점검항목을 입력해주세요. 등록 창을 다시 열어주세요.');
    LEAVE PROC;
  END IF;

-- *****************************************************************************

WHEN 'SEARCH_CHKRSTEQM' THEN -- 저장된 월별 실적 조회
  SET _$CHKRSTKEY = (SELECT CHKRSTKEY FROM CHKRSTEQM WHERE EQMCD = $EQMCD AND CHKTP = '02' AND LEFT(BASEDATE, 7) = $YYYYMM ORDER BY BASEDATE, CHKRSTKEY LIMIT 1);
  IF _$CHKRSTKEY IS NULL THEN
    CALL COMERR('조회할 정기점검 실적이 없습니다. 다시 조회해주세요.');
    LEAVE PROC;
  END IF;
  SELECT CHKRSTKEY, EQMCD, EMPCD, BASEDATE, LEFT(BASEDATE, 7) AS YYYYMM, PROBLEM, SOLUTION
  FROM CHKRSTEQM WHERE CHKRSTKEY = _$CHKRSTKEY;
  SELECT RST_ITEM.PLANTP, RST_ITEM.CHKKNDCD, RST_ITEM.CHKKNDNM, RST_ITEM.CHKLOC, RST_ITEM.CHKMTH, RST_ITEM.CHKVALTP, RST_ITEM.CHKVALUE,
         COALESCE(CONCAT('REV.', PLAN_REV.REVNUM), '') AS REVNM
  FROM CHKRSTEQMKND RST_ITEM
  INNER JOIN CHKRSTEQM RST ON RST.CHKRSTKEY = RST_ITEM.CHKRSTKEY
  LEFT JOIN MSTEQMREV_HEADER PLAN_REV ON PLAN_REV.REVCD = IF(RST_ITEM.PLANTP = 'G', RST.GRPREVCD, RST.REVCD)
  WHERE RST_ITEM.CHKRSTKEY = _$CHKRSTKEY
  ORDER BY (RST_ITEM.PLANTP = 'G') DESC, RST_ITEM.SORTNO, RST_ITEM.CHKKNDCD;

-- *****************************************************************************

WHEN 'SAVE_CHKRSTEQM' THEN -- 기존 실적의 점검값 수정
  SELECT COUNT(*) INTO _$ITEMCNT FROM CHKRSTEQMKND WHERE CHKRSTKEY = _$CHKRSTKEY;
  -- 같은 항목을 중복 전달하면 전체 저장을 취소
  DROP TEMPORARY TABLE IF EXISTS TMP_RST_ITEM;
  CREATE TEMPORARY TABLE TMP_RST_ITEM (PLANTP CHAR(1) NOT NULL, CHKKNDCD VARCHAR(100) NOT NULL, PRIMARY KEY (PLANTP, CHKKNDCD)) ENGINE=InnoDB;
  WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
    CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);
    CALL COMSPLIT($PLANTP_LIST, _$ITEMTP);
    CALL COMSPLIT($CHKVALUE_LIST, _$CHKVALUE);
    IF _$ITEMTP IS NULL OR NOT EXISTS (SELECT 1 FROM CHKRSTEQMKND WHERE CHKRSTKEY = _$CHKRSTKEY AND PLANTP = _$ITEMTP AND CHKKNDCD = _$CHKKNDCD LIMIT 1) THEN
      DROP TEMPORARY TABLE IF EXISTS TMP_RST_ITEM;
      CALL COMERR('저장된 실적과 점검항목이 다릅니다. 다시 조회해주세요.');
      LEAVE PROC;
    END IF;
    IF TRIM(COALESCE(_$CHKVALUE, '')) = '' THEN
      DROP TEMPORARY TABLE IF EXISTS TMP_RST_ITEM;
      CALL COMERR(CONCAT('점검코드 ', _$CHKKNDCD, '의 점검값을 입력해주세요.'));
      LEAVE PROC;
    END IF;
    INSERT INTO TMP_RST_ITEM VALUES (_$ITEMTP, _$CHKKNDCD);
    UPDATE CHKRSTEQMKND
    SET CHKVALUE = _$CHKVALUE, MTIME = CALLTIME(), MEMP = CALLEMP(), MPRG = CALLPRG()
    WHERE CHKRSTKEY = _$CHKRSTKEY AND PLANTP = _$ITEMTP AND CHKKNDCD = _$CHKKNDCD;
    SET _$ROWCNT = _$ROWCNT + 1;
  END WHILE;
  DROP TEMPORARY TABLE IF EXISTS TMP_RST_ITEM;
  IF _$ROWCNT <> _$ITEMCNT OR LENGTH(COALESCE($PLANTP_LIST, '')) > 0 OR LENGTH(COALESCE($CHKVALUE_LIST, '')) > 0 THEN
    CALL COMERR('실적의 모든 점검항목을 입력해주세요. 다시 조회해주세요.');
    LEAVE PROC;
  END IF;
  UPDATE CHKRSTEQM
  SET EMPCD = $EMPCD, BASEDATE = $BASEDATE, PROBLEM = $PROBLEM, SOLUTION = $SOLUTION, MTIME = CALLTIME(), MEMP = CALLEMP(), MPRG = CALLPRG()
  WHERE CHKRSTKEY = _$CHKRSTKEY;

-- *****************************************************************************

WHEN 'DELETE_CHKRSTEQM' THEN -- 정기점검 실적 삭제
  DELETE FROM CHKRSTEQMKND WHERE CHKRSTKEY = _$CHKRSTKEY;
  DELETE FROM CHKRSTEQM WHERE CHKRSTKEY = _$CHKRSTKEY;

-- *****************************************************************************

END CASE;
END
