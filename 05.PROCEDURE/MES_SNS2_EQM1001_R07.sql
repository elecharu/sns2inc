CREATE DEFINER=`root`@`%`
PROCEDURE `MES_SNS2`.`EQM1001_R07`(
-- *****************************************************************************
-- Comment: 설비 예방보전 점검등록 (수시 점검, 항목은 설비의 최신 정기점검 계획 REV, 실적은 CHKRSTEQM CHKTP '03')
-- Create: 	2026-11-16  	생성 			한성수	설비 목록 조회 (TAL0001_R05와 같은 조건)
-- Modify: 	2026-11-17 					한성수	예방보전 점검(CHKTP '03') 수시 등록·수정·삭제, 점검항목은 정기점검 계획(설비그룹·설비 최신 REV) 항목 사용, 등록·수정 처리 R04 방식으로 단순화, 같은 날 승인 전 이력 중복 등록 차단(점검 등록 클릭 시 포함)
-- *****************************************************************************
  IN $SDATE          VARCHAR(10),     -- 조회 시작일자 (점검일자)
  IN $EDATE          VARCHAR(10),     -- 조회 종료일자 (점검일자)
  IN $LINECD         VARCHAR(20),     -- 조회조건 작업장
  IN $EQMTP          VARCHAR(50),     -- 조회조건 공정 (MSTEQM.EQMTP, FM100)
  IN $EQMGROUP1      VARCHAR(50),     -- 조회조건 라인 (MSTEQM.EQMGROUP1, FM113)
  IN $EQMCD          VARCHAR(20),     -- 설비 (MSTEQM.FANO)
  IN $CHKRSTKEY      VARCHAR(20),     -- 점검실적키
  IN $BASEDATE       VARCHAR(10),     -- 점검일자
  IN $EMPCD          VARCHAR(20),     -- 점검자
  IN $PROBLEM        VARCHAR(1000),   -- 문제점
  IN $SOLUTION       VARCHAR(1000),   -- 조치사항
  IN $GRPREVCD       VARCHAR(20),     -- 팝업에서 조회한 설비그룹 정기점검 REV
  IN $REVCD          VARCHAR(20),     -- 팝업에서 조회한 설비 정기점검 REV
  IN $PLANTP_LIST    MEDIUMTEXT,      -- 점검항목 그리드 행별 계획구분 (G 설비그룹, E 설비)
  IN $CHKKNDCD_LIST  MEDIUMTEXT,      -- 점검항목 그리드 행별 점검코드
  IN $CHKVALUE_LIST  MEDIUMTEXT,      -- 점검항목 그리드 행별 점검값
  IN $REMARK_LIST    MEDIUMTEXT,      -- 점검항목 그리드 행별 특이사항
-- *****************************************************************************
  IN $CALLTYPE       VARCHAR(50),
  IN $KEYWORD        VARCHAR(1000)
)
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  DECLARE _$EQMGRP       VARCHAR(50);
  DECLARE _$GRPREVCD     VARCHAR(20);
  DECLARE _$EQMREVCD     VARCHAR(20);
  DECLARE _$ITEMREVCD    VARCHAR(20);
  DECLARE _$ITEMTP       VARCHAR(10);
  DECLARE _$CHKKNDCD     VARCHAR(100);
  DECLARE _$CHKVALUE     VARCHAR(20000);
  DECLARE _$REMARK       VARCHAR(20000);
  DECLARE _$ITEMCNT      INT DEFAULT 0;
  DECLARE _$ROWCNT       INT DEFAULT 0;

  -- 점검항목 조회·등록 설비: 2공장 사용 설비와 그 설비그룹
  IF $CALLTYPE IN ('LIST_PLAN_ITEM', 'ADD_CHKRST') THEN
    SET _$EQMGRP = (SELECT COALESCE(EQMGUBUN, '') FROM MSTEQM WHERE FANO = $EQMCD AND FACTORYCD = '07' AND USEYN = 'Y' LIMIT 1);

    IF _$EQMGRP IS NULL THEN
      CALL COMERR('좌측에서 사용 중인 설비를 선택해주세요.');
      LEAVE PROC;
    END IF;
  END IF;

  -- 수정·삭제 대상: 같은 설비의 예방보전('03') 실적, 승인 전만
  IF $CALLTYPE IN ('SAVE_CHKRST', 'DELETE_CHKRST') THEN
    IF NOT EXISTS (SELECT 1 FROM CHKRSTEQM WHERE CHKRSTKEY = $CHKRSTKEY AND CHKTP = '03' AND EQMCD = $EQMCD LIMIT 1) THEN
      CALL COMERR('선택한 예방보전 이력이 없습니다. 다시 조회해주세요.');
      LEAVE PROC;
    END IF;

    IF EXISTS (SELECT 1 FROM CHKRSTEQM WHERE CHKRSTKEY = $CHKRSTKEY AND APRVTIME <> '' LIMIT 1) THEN
      CALL COMERR('승인된 예방보전 이력은 삭제할 수 없습니다.\n설비점검 이력에서 승인취소 후 처리해주세요.');
      LEAVE PROC;
    END IF;
  END IF;

  -- 등록·수정 점검일자·점검자 확인
  IF $CALLTYPE IN ('ADD_CHKRST', 'SAVE_CHKRST') THEN
    IF COALESCE($BASEDATE, '') NOT REGEXP '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' OR DATE($BASEDATE) IS NULL THEN
      CALL COMERR('점검일자를 올바르게 입력해주세요.');
      LEAVE PROC;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM MSTEMP WHERE EMPCD = $EMPCD LIMIT 1) THEN
      CALL COMERR('점검자를 선택해주세요.');
      LEAVE PROC;
    END IF;
  END IF;

  -- 같은 설비·같은 점검일자에 승인 전 예방보전 이력은 1건만 (점검 등록 클릭 시 오늘 기준, 수정은 자기 자신 제외)
  IF $CALLTYPE IN ('LIST_PLAN_ITEM', 'ADD_CHKRST', 'SAVE_CHKRST') THEN
    IF EXISTS (SELECT 1 FROM CHKRSTEQM
               WHERE EQMCD = $EQMCD AND CHKTP = '03' AND BASEDATE = $BASEDATE
                 AND COALESCE(APRVTIME, '') = '' AND CHKRSTKEY <> COALESCE($CHKRSTKEY, '') LIMIT 1) THEN
      CALL COMERR(CONCAT($BASEDATE, '에 승인되지 않은 예방보전 이력이 있습니다. \n기존 이력을 삭제한 후 다시 등록해주세요.'));
      LEAVE PROC;
    END IF;
  END IF;

CASE $CALLTYPE
-- *****************************************************************************
WHEN 'LIST_EQMCD' THEN -- 설비 목록 (2공장 사용 설비, 작업장·공정·라인 조건, 최근 예방보전일)
  SELECT MSTEQM.FANO AS EQMCD,
         MSTEQM.EQMNM,
         IFNULL(MSTEQM.FACTORYCD, '') AS FACTORYCD,
         IFNULL(MSTEQM.LINECD, '')    AS LINECD,
         IFNULL(MSTEQM.EQMTP, '')     AS EQMTP,
         IFNULL(MSTEQM.EQMGROUP1, '') AS EQMGROUP1,
         COALESCE(PM.LASTDAY, '')     AS LASTDAY
  FROM MSTEQM
  LEFT JOIN (
    SELECT EQMCD,
           MAX(BASEDATE) AS LASTDAY
    FROM CHKRSTEQM
    WHERE CHKTP = '03'
    GROUP BY EQMCD
  ) PM ON PM.EQMCD = MSTEQM.FANO
  WHERE MSTEQM.FACTORYCD = '07'
    AND MSTEQM.USEYN = 'Y'
    AND ($LINECD = '' OR MSTEQM.LINECD = $LINECD)
    AND ($EQMTP = '' OR MSTEQM.EQMTP = $EQMTP)
    AND ($EQMGROUP1 = '' OR MSTEQM.EQMGROUP1 = $EQMGROUP1)
  ORDER BY MSTEQM.FANO;

-- *****************************************************************************
WHEN 'LIST_CHKRST' THEN -- 선택 설비의 예방보전 이력 (점검일자 기간, 최신순, 항목 수·NG 수·승인)
  SELECT CHKRSTEQM.CHKRSTKEY,
         CHKRSTEQM.BASEDATE,
         CHKRSTEQM.EMPCD,
         COALESCE(CHK_EMP.EMPNM, CHKRSTEQM.EMPCD) AS EMPNM,
         COALESCE(RST_ITEM.ITEMCNT, 0) AS ITEMCNT,
         COALESCE(RST_ITEM.NGCNT, 0)   AS NGCNT,
         CHKRSTEQM.PROBLEM,
         CHKRSTEQM.SOLUTION,
         COALESCE(APRV_EMP.EMPNM, CHKRSTEQM.APRVEMP) AS APRVEMPNM,
         LEFT(CHKRSTEQM.APRVTIME, 16) AS APRVTIME,
         LEFT(CHKRSTEQM.RTIME, 16)    AS RTIME
  FROM CHKRSTEQM
  LEFT JOIN (
    SELECT CHKRSTEQMKND.CHKRSTKEY,
           COUNT(*) AS ITEMCNT,
           SUM(CHKRSTEQMKND.CHKVALUE = 'NG') AS NGCNT
    FROM CHKRSTEQM PM_RST
    INNER JOIN CHKRSTEQMKND ON CHKRSTEQMKND.CHKRSTKEY = PM_RST.CHKRSTKEY
    WHERE PM_RST.EQMCD = $EQMCD
      AND PM_RST.CHKTP = '03'
    GROUP BY CHKRSTEQMKND.CHKRSTKEY
  ) RST_ITEM ON RST_ITEM.CHKRSTKEY = CHKRSTEQM.CHKRSTKEY
  LEFT JOIN MSTEMP CHK_EMP  ON CHK_EMP.EMPCD = CHKRSTEQM.EMPCD
  LEFT JOIN MSTEMP APRV_EMP ON APRV_EMP.EMPCD = NULLIF(CHKRSTEQM.APRVEMP, '')
  WHERE CHKRSTEQM.EQMCD = $EQMCD
    AND CHKRSTEQM.CHKTP = '03'
    AND CHKRSTEQM.BASEDATE BETWEEN $SDATE AND $EDATE
  ORDER BY CHKRSTEQM.BASEDATE DESC, CHKRSTEQM.CHKRSTKEY DESC;

-- *****************************************************************************
WHEN 'LIST_CHKRSTKND' THEN -- 예방보전 이력의 점검항목별 결과 (등록 당시 항목, 설비그룹 항목 먼저)
  SELECT CHKRSTEQMKND.PLANTP,
         CASE CHKRSTEQMKND.PLANTP WHEN 'G' THEN '설비그룹' ELSE '설비' END AS PLANTPNM,
         COALESCE(CONCAT('REV.', PLAN_REV.REVNUM), '') AS REVNM,
         CHKRSTEQMKND.CHKKNDCD, CHKRSTEQMKND.CHKKNDNM, CHKRSTEQMKND.CHKLOC, CHKRSTEQMKND.CHKMTH,
         CHKRSTEQMKND.CHKVALTP, CHKRSTEQMKND.CHKVALUE, CHKRSTEQMKND.REMARK, CHKRSTEQMKND.SORTNO
  FROM CHKRSTEQMKND
  INNER JOIN CHKRSTEQM ON CHKRSTEQM.CHKRSTKEY = CHKRSTEQMKND.CHKRSTKEY
  LEFT JOIN MSTEQMREV_HEADER PLAN_REV
    ON PLAN_REV.REVCD = IF(CHKRSTEQMKND.PLANTP = 'G', CHKRSTEQM.GRPREVCD, CHKRSTEQM.REVCD)
  WHERE CHKRSTEQMKND.CHKRSTKEY = $CHKRSTKEY
  ORDER BY (CHKRSTEQMKND.PLANTP = 'G') DESC, CHKRSTEQMKND.SORTNO, CHKRSTEQMKND.CHKKNDCD;

-- *****************************************************************************
WHEN 'LIST_PLAN_ITEM' THEN -- 등록할 점검항목: 설비그룹·설비의 최신 정기점검 REV 항목 (R04 LIST_PLAN_EQM02와 같은 기준)
  SET _$GRPREVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'G' AND PLANCD = _$EQMGRP AND CHKTP = '02' ORDER BY REVNUM DESC LIMIT 1);
  SET _$EQMREVCD = (SELECT REVCD FROM MSTEQMREV_HEADER WHERE PLANTP = 'E' AND PLANCD = $EQMCD AND CHKTP = '02' ORDER BY REVNUM DESC LIMIT 1);

  IF NOT EXISTS (SELECT 1 FROM MSTEQMREV_DETAIL WHERE REVCD IN (_$GRPREVCD, _$EQMREVCD) LIMIT 1) THEN
    CALL COMERR('이 설비에 등록된 정기점검 계획 항목이 없습니다.');
    LEAVE PROC;
  END IF;

  SELECT 'G' AS PLANTP, '설비그룹' AS PLANTPNM,
         CONCAT('REV.', PLAN_REV.REVNUM) AS REVNM,
         COALESCE(_$GRPREVCD, '') AS GRPREVCD, COALESCE(_$EQMREVCD, '') AS EQMREVCD,
         PLAN_ITEM.CHKKNDCD, PLAN_ITEM.CHKKNDNM, PLAN_ITEM.CHKLOC, PLAN_ITEM.CHKMTH, PLAN_ITEM.CHKVALTP,
         '' AS CHKVALUE, '' AS REMARK, PLAN_ITEM.SORTNO
  FROM MSTEQMREV_DETAIL PLAN_ITEM
  INNER JOIN MSTEQMREV_HEADER PLAN_REV ON PLAN_REV.REVCD = PLAN_ITEM.REVCD
  WHERE PLAN_ITEM.REVCD = _$GRPREVCD

  UNION ALL

  SELECT 'E' AS PLANTP, '설비' AS PLANTPNM,
         CONCAT('REV.', PLAN_REV.REVNUM) AS REVNM,
         COALESCE(_$GRPREVCD, '') AS GRPREVCD, COALESCE(_$EQMREVCD, '') AS EQMREVCD,
         PLAN_ITEM.CHKKNDCD, PLAN_ITEM.CHKKNDNM, PLAN_ITEM.CHKLOC, PLAN_ITEM.CHKMTH, PLAN_ITEM.CHKVALTP,
         '' AS CHKVALUE, '' AS REMARK, PLAN_ITEM.SORTNO
  FROM MSTEQMREV_DETAIL PLAN_ITEM
  INNER JOIN MSTEQMREV_HEADER PLAN_REV ON PLAN_REV.REVCD = PLAN_ITEM.REVCD
  WHERE PLAN_ITEM.REVCD = _$EQMREVCD
  ORDER BY PLANTP DESC, SORTNO, CHKKNDCD;

-- *****************************************************************************
WHEN 'ADD_CHKRST' THEN -- 예방보전 등록 (CHKTP '03', 점검항목 그리드 행마다 조회한 계획 REV 항목으로 저장)
  SET _$GRPREVCD = NULLIF($GRPREVCD, '');
  SET _$EQMREVCD = NULLIF($REVCD, '');

  IF (_$GRPREVCD IS NOT NULL AND NOT EXISTS (SELECT 1 FROM MSTEQMREV_HEADER WHERE REVCD = _$GRPREVCD AND PLANTP = 'G' AND PLANCD = _$EQMGRP AND CHKTP = '02' LIMIT 1))
     OR (_$EQMREVCD IS NOT NULL AND NOT EXISTS (SELECT 1 FROM MSTEQMREV_HEADER WHERE REVCD = _$EQMREVCD AND PLANTP = 'E' AND PLANCD = $EQMCD AND CHKTP = '02' LIMIT 1)) THEN
    CALL COMERR('조회한 정기점검 계획이 변경되었습니다. 점검 등록 창을 다시 열어주세요.');
    LEAVE PROC;
  END IF;

  SET _$ITEMCNT = (SELECT COUNT(*) FROM MSTEQMREV_DETAIL WHERE REVCD IN (_$GRPREVCD, _$EQMREVCD));
  SET $CHKRSTKEY = GETKEY('CHKRSTKEY');

  INSERT INTO CHKRSTEQM (
    CHKRSTKEY, CHKTP, EQMCD, EMPCD, BASEDATE, PROBLEM, SOLUTION, REVCD, GRPREVCD, RTIME, REMP, RPRG
  ) VALUES (
    $CHKRSTKEY, '03', $EQMCD, $EMPCD, $BASEDATE, COALESCE($PROBLEM, ''), COALESCE($SOLUTION, ''), COALESCE(_$EQMREVCD, ''), COALESCE(_$GRPREVCD, ''), CALLTIME(), CALLEMP(), CALLPRG()
  );

  WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
    CALL COMSPLIT($PLANTP_LIST, _$ITEMTP);
    CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);
    CALL COMSPLIT($CHKVALUE_LIST, _$CHKVALUE);
    CALL COMSPLIT($REMARK_LIST, _$REMARK);

    SET _$ITEMREVCD = CASE _$ITEMTP WHEN 'G' THEN _$GRPREVCD WHEN 'E' THEN _$EQMREVCD END;

    IF _$ITEMREVCD IS NULL OR NOT EXISTS (SELECT 1 FROM MSTEQMREV_DETAIL WHERE REVCD = _$ITEMREVCD AND CHKKNDCD = _$CHKKNDCD LIMIT 1) THEN
      CALL COMERR('조회한 점검계획에 없는 점검항목입니다. 점검 등록 창을 다시 열어주세요.');
      LEAVE PROC;
    END IF;

    IF TRIM(COALESCE(_$CHKVALUE, '')) = '' THEN
      CALL COMERR(CONCAT('점검코드 ', _$CHKKNDCD, '의 점검값을 입력해주세요.'));
      LEAVE PROC;
    END IF;

    INSERT INTO CHKRSTEQMKND (
      CHKRSTKEY, PLANTP, CHKKNDCD, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, CHKVALUE, REMARK, SORTNO, RTIME, REMP, RPRG
    )
    SELECT $CHKRSTKEY, _$ITEMTP, CHKKNDCD, CHKKNDNM, CHKLOC, CHKMTH, CHKVALTP, TRIM(_$CHKVALUE), COALESCE(_$REMARK, ''), SORTNO, CALLTIME(), CALLEMP(), CALLPRG()
    FROM MSTEQMREV_DETAIL
    WHERE REVCD = _$ITEMREVCD AND CHKKNDCD = _$CHKKNDCD;

    SET _$ROWCNT = _$ROWCNT + 1;
  END WHILE;

  IF _$ROWCNT = 0 OR _$ROWCNT <> _$ITEMCNT THEN
    CALL COMERR('점검계획의 모든 점검항목을 입력해주세요. 점검 등록 창을 다시 열어주세요.');
    LEAVE PROC;
  END IF;

-- *****************************************************************************
WHEN 'SAVE_CHKRST' THEN -- 예방보전 수정 (점검일자·점검자·문제점·조치사항, 점검항목 그리드 행마다 점검값·특이사항)
  UPDATE CHKRSTEQM
  SET BASEDATE = $BASEDATE,
      EMPCD    = $EMPCD,
      PROBLEM  = COALESCE($PROBLEM, ''),
      SOLUTION = COALESCE($SOLUTION, ''),
      MTIME    = CALLTIME(),
      MEMP     = CALLEMP(),
      MPRG     = CALLPRG()
  WHERE CHKRSTKEY = $CHKRSTKEY;

  WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
    CALL COMSPLIT($PLANTP_LIST, _$ITEMTP);
    CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);
    CALL COMSPLIT($CHKVALUE_LIST, _$CHKVALUE);
    CALL COMSPLIT($REMARK_LIST, _$REMARK);

    IF NOT EXISTS (SELECT 1 FROM CHKRSTEQMKND WHERE CHKRSTKEY = $CHKRSTKEY AND PLANTP = _$ITEMTP AND CHKKNDCD = _$CHKKNDCD LIMIT 1) THEN
      CALL COMERR('저장된 점검항목이 아닙니다. 수정 창을 다시 열어주세요.');
      LEAVE PROC;
    END IF;

    IF TRIM(COALESCE(_$CHKVALUE, '')) = '' THEN
      CALL COMERR(CONCAT('점검코드 ', _$CHKKNDCD, '의 점검값을 입력해주세요.'));
      LEAVE PROC;
    END IF;

    UPDATE CHKRSTEQMKND
    SET CHKVALUE = TRIM(_$CHKVALUE),
        REMARK   = COALESCE(_$REMARK, ''),
        MTIME    = CALLTIME(),
        MEMP     = CALLEMP(),
        MPRG     = CALLPRG()
    WHERE CHKRSTKEY = $CHKRSTKEY
      AND PLANTP = _$ITEMTP
      AND CHKKNDCD = _$CHKKNDCD;

    SET _$ROWCNT = _$ROWCNT + 1;
  END WHILE;

  IF _$ROWCNT <> (SELECT COUNT(*) FROM CHKRSTEQMKND WHERE CHKRSTKEY = $CHKRSTKEY) THEN
    CALL COMERR('모든 점검항목의 점검값을 입력해주세요. 수정 창을 다시 열어주세요.');
    LEAVE PROC;
  END IF;

-- *****************************************************************************
WHEN 'DELETE_CHKRST' THEN -- 예방보전 삭제 (항목 포함)
  DELETE FROM CHKRSTEQMKND WHERE CHKRSTKEY = $CHKRSTKEY;
  DELETE FROM CHKRSTEQM    WHERE CHKRSTKEY = $CHKRSTKEY;

-- *****************************************************************************
END CASE; END
