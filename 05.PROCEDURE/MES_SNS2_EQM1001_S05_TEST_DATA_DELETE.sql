-- 테스트 데이터만 삭제 (키 'TESTS05-'·'TESTS05W-'(탭2 직접 수리) 또는 SEQ 901 ~ 905, RPRG = 'TEST_S05' 둘 다 맞는 행)
START TRANSACTION;

DELETE FROM MES_SNS2.EQMREP
WHERE (EQMREPKEY LIKE 'TESTS05-%' OR EQMREPKEY LIKE 'TESTS05W-%')
  AND RPRG = 'TEST_S05';

DELETE FROM MES_SNS2.PRDWORK
WHERE PRDWORKKEY LIKE 'TESTS05-%'
  AND RPRG = 'TEST_S05';

DELETE FROM MES_SNS2.MSTEQM_MATCH
WHERE EQMCD = 'I2M160_N-Q0001_N'
  AND SEQ BETWEEN 901 AND 905
  AND RPRG = 'TEST_S05';

COMMIT;

-- 삭제 확인 (모두 0)
SELECT 'MSTEQM_MATCH' AS TBL, COUNT(*) AS CNT FROM MES_SNS2.MSTEQM_MATCH WHERE EQMCD = 'I2M160_N-Q0001_N' AND RPRG = 'TEST_S05'
UNION ALL SELECT 'PRDWORK', COUNT(*) FROM MES_SNS2.PRDWORK WHERE PRDWORKKEY LIKE 'TESTS05-%' AND RPRG = 'TEST_S05'
UNION ALL SELECT 'EQMREP', COUNT(*) FROM MES_SNS2.EQMREP WHERE (EQMREPKEY LIKE 'TESTS05-%' OR EQMREPKEY LIKE 'TESTS05W-%') AND RPRG = 'TEST_S05';
