CREATE DEFINER=`root`@`%`
PROCEDURE `MES_SNS2`.`IO_COMCHK_CONFIRM`(
-- *****************************************************************************
-- Comment: 실사승인
-- Create: 	2024-10-31  	생성 			이대규
-- Modify: 	2026-11-11 					한성수	SNS2 마이그레이션 (품목 ITEMID, 입출고구분 SNS2 기준정보 INTP·OUTTP 08 실사, IFS_* 인터페이스 제외)
-- *****************************************************************************
  IN $CHKKEY    VARCHAR(20)
)
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  DECLARE _$CHKITEMID     VARCHAR(100);
  DECLARE _$CHKWARECD     VARCHAR(100);

  DECLARE _$CHKLOTLIST    MEDIUMTEXT;
  DECLARE _$OLDQTYLIST    MEDIUMTEXT;
  DECLARE _$CHKQTYLIST    MEDIUMTEXT;
  DECLARE _$DIFFQTYLIST   MEDIUMTEXT;

  DECLARE _$LOTKEY        VARCHAR(100);
  DECLARE _$OLDQTY        DECIMAL(20, 8);
  DECLARE _$CHKQTY        DECIMAL(20, 8);
  DECLARE _$DIFFQTY       DECIMAL(20, 8);

  DECLARE _$OUTKEY        VARCHAR(20);
  DECLARE _$OUTQTY        DECIMAL(20, 8);
  DECLARE _$INKEY         VARCHAR(20);
  DECLARE _$INQTY         DECIMAL(20, 8);

  DECLARE _$INTP          VARCHAR(10);
  DECLARE _$OUTTP         VARCHAR(10);

  DECLARE _$COUNT_IN      DECIMAL(20, 8);
  DECLARE _$COUNT_OUT     DECIMAL(20, 8);
  DECLARE _$COUNT_Y       DECIMAL(20, 8);
  DECLARE _$COUNT_ALL     DECIMAL(20, 8);

  DECLARE _$CHKGROUPKEY   VARCHAR(20);

  SET _$INTP  = '08'; -- 실사 (SNS2 INTP)
  SET _$OUTTP = '08'; -- 실사 (SNS2 OUTTP)

  SET _$COUNT_IN  = 0;
  SET _$COUNT_OUT = 0;
  SET _$COUNT_Y   = 0;
  SET _$COUNT_ALL = 0;

  SET _$OUTQTY = 0;
  SET _$INQTY  = 0;

  SET _$OUTKEY = GETKEY('OUTKEY');
  SET _$INKEY  = GETKEY('INKEY');
-- *****************************************************************************
  IF (SELECT CHKAPPYN FROM COMCHK WHERE CHKKEY = $CHKKEY) = 'Y' THEN
    CALL COMERR('이미 승인되었습니다.');
    LEAVE PROC;
  END IF;

  DROP TABLE IF EXISTS TEMP_COMCHKLOT;
  CREATE TEMPORARY TABLE TEMP_COMCHKLOT (
    LOTKEY  VARCHAR(100) NOT NULL,
    DIFFQTY DECIMAL(20, 8) NOT NULL
  );

  SELECT COMCHK.CHKITEMCD, COMCHK_GROUP.CHKWARECD
    INTO _$CHKITEMID, _$CHKWARECD
  FROM COMCHK
  INNER JOIN COMCHK_GROUP
    ON COMCHK_GROUP.CHKGROUPKEY = COMCHK.CHKGROUPKEY
  WHERE COMCHK.CHKKEY = $CHKKEY;

  -- 1. 실사로트리스트 생성
  SELECT CONCAT(GROUP_CONCAT(COMCHKLOT.CHKLOTKEY SEPARATOR '»'), '»'),
         CONCAT(GROUP_CONCAT(COMCHKLOT.LOTOLDQTY SEPARATOR '»'), '»'),
         CONCAT(GROUP_CONCAT(COMCHKLOT.LOTCHKQTY SEPARATOR '»'), '»')
    INTO _$CHKLOTLIST, _$OLDQTYLIST, _$CHKQTYLIST
  FROM COMCHKLOT
  WHERE COMCHKLOT.CHKKEY = $CHKKEY;

  -- 2. 로트별 실사차이 합산 (차이 = 실사수량 - 전산수량)
  while_A: WHILE LENGTH(_$CHKLOTLIST) > 0 DO
    CALL COMSPLIT(_$CHKLOTLIST, _$LOTKEY);
    CALL COMSPLIT(_$OLDQTYLIST, _$OLDQTY);
    CALL COMSPLIT(_$CHKQTYLIST, _$CHKQTY);

    SET _$DIFFQTY = (_$CHKQTY - _$OLDQTY);

    IF _$DIFFQTY = 0 THEN
      ITERATE while_A;
    END IF;

    IF EXISTS (SELECT LOTKEY FROM TEMP_COMCHKLOT WHERE LOTKEY = _$LOTKEY) THEN
      UPDATE TEMP_COMCHKLOT
         SET DIFFQTY = DIFFQTY + _$DIFFQTY
       WHERE LOTKEY = _$LOTKEY;
    ELSE
      INSERT INTO TEMP_COMCHKLOT (LOTKEY, DIFFQTY)
      VALUES (_$LOTKEY, _$DIFFQTY);
    END IF;
  END WHILE;

  SET _$CHKLOTLIST  = '';
  SET _$DIFFQTYLIST = '';

  -- 3. COMLOT 업데이트 (차이가 0보다 작으면 실사출고, 크면 실사입고)
  SELECT CONCAT(GROUP_CONCAT(LOTKEY SEPARATOR '»'), '»'),
         CONCAT(GROUP_CONCAT(DIFFQTY SEPARATOR '»'), '»')
    INTO _$CHKLOTLIST, _$DIFFQTYLIST
  FROM TEMP_COMCHKLOT;

  SET _$OLDQTY = 0;

  while_B: WHILE LENGTH(_$CHKLOTLIST) > 0 DO
    CALL COMSPLIT(_$CHKLOTLIST, _$LOTKEY);
    CALL COMSPLIT(_$DIFFQTYLIST, _$DIFFQTY);

    IF _$DIFFQTY = 0 THEN
      ITERATE while_B;
    END IF;

    SET _$OLDQTY = (SELECT LOTQTY FROM COMLOT WHERE WARECD = _$CHKWARECD AND LOTKEY = _$LOTKEY);

    IF _$DIFFQTY < 0 THEN
      INSERT INTO COMOUTLOT (OUTKEY, LOTKEY, WARECD, OUTTP, OUTDATE, OUTQTY, ITEMID, OLDQTY, RTIME, REMP, RPRG)
      VALUES (_$OUTKEY, _$LOTKEY, _$CHKWARECD, _$OUTTP, GETDATE(), -(_$DIFFQTY), _$CHKITEMID, _$OLDQTY, CALLTIME(), CALLEMP(), CALLPRG());

      SET _$OUTQTY    = _$OUTQTY + _$DIFFQTY;
      SET _$COUNT_OUT = _$COUNT_OUT + 1;
    ELSE
      INSERT INTO COMINLOT (INKEY, LOTKEY, WARECD, INTP, INDATE, INQTY, ITEMID, OLDQTY, RTIME, REMP, RPRG)
      VALUES (_$INKEY, _$LOTKEY, _$CHKWARECD, _$INTP, GETDATE(), _$DIFFQTY, _$CHKITEMID, _$OLDQTY, CALLTIME(), CALLEMP(), CALLPRG());

      SET _$INQTY    = _$INQTY + _$DIFFQTY;
      SET _$COUNT_IN = _$COUNT_IN + 1;
    END IF;

    UPDATE COMLOT
       SET LOTQTY = LOTQTY + _$DIFFQTY,
           MTIME = CALLTIME(), MEMP = CALLEMP(), MPRG = CALLPRG()
     WHERE WARECD = _$CHKWARECD
       AND LOTKEY = _$LOTKEY;
  END WHILE;

  -- 4. COMIN, COMOUT 생성
  IF _$COUNT_OUT > 0 THEN
    INSERT INTO COMOUT (OUTKEY, WARECD, OUTTP, OUTDATE, OUTQTY, ITEMID, EMPCD, CHKKEY, RTIME, REMP, RPRG)
    VALUES (_$OUTKEY, _$CHKWARECD, _$OUTTP, GETDATE(), -(_$OUTQTY), _$CHKITEMID, CALLEMP(), $CHKKEY, CALLTIME(), CALLEMP(), CALLPRG());
  END IF;

  IF _$COUNT_IN > 0 THEN
    INSERT INTO COMIN (INKEY, WARECD, INTP, INDATE, INQTY, ITEMID, EMPCD, CHKKEY, RTIME, REMP, RPRG)
    VALUES (_$INKEY, _$CHKWARECD, _$INTP, GETDATE(), _$INQTY, _$CHKITEMID, CALLEMP(), $CHKKEY, CALLTIME(), CALLEMP(), CALLPRG());
  END IF;

  -- 5. COMCHK 승인 처리
  UPDATE COMCHK
     SET CHKAPPYN = 'Y', CHKAPPEMP = CALLEMP(), CHKAPPTIME = CALLTIME(),
         MTIME = CALLTIME(), MEMP = CALLEMP(), MPRG = CALLPRG()
   WHERE CHKKEY = $CHKKEY;

  SET _$CHKGROUPKEY = (SELECT CHKGROUPKEY FROM COMCHK WHERE CHKKEY = $CHKKEY);
  SET _$COUNT_Y     = (SELECT COUNT(CHKKEY) FROM COMCHK WHERE CHKGROUPKEY = _$CHKGROUPKEY AND CHKAPPYN = 'Y');
  SET _$COUNT_ALL   = (SELECT COUNT(CHKKEY) FROM COMCHK WHERE CHKGROUPKEY = _$CHKGROUPKEY);

  IF _$COUNT_Y = _$COUNT_ALL THEN
    UPDATE COMCHK_GROUP
       SET CHKAPPYN = 'Y', CHKAPPEMP = CALLEMP(), CHKAPPTIME = CALLTIME(),
           MTIME = CALLTIME(), MEMP = CALLEMP(), MPRG = CALLPRG()
     WHERE CHKGROUPKEY = _$CHKGROUPKEY;
  END IF;

  DROP TABLE IF EXISTS TEMP_COMCHKLOT;
-- *****************************************************************************
END
