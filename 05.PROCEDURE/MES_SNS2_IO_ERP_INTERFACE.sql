    IFNULL(SALOUT.CUSTCD, ''), IFNULL(SALODR.CUSTCD2, ''),
    LEFT(IFNULL(SALOUTLOT.REMARK, ''), 100), IFNULL(SALOUTLOT.REMP, ''),
