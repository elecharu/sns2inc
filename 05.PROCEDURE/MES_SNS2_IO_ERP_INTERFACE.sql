    CASE $INTERFACENAME WHEN 'WORK_20' THEN 'LE920390' WHEN 'WORK_40' THEN 'LE920210' WHEN 'WORK_22' THEN 'LE920910' WHEN 'WORK_23' THEN 'LE920912' WHEN 'WORK_10' THEN 'LE920520' END,   -- ENT_BC 입고구분
