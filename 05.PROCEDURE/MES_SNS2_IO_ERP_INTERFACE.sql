                        WHEN 'WORK_23' THEN LEFT(IFNULL(OUTW.CUSTCD, ''), 10)   -- 외주재작업입고 : 출고창고의 외주처
                        ELSE LEFT(IFNULL(INW.CUSTCD, ''), 10)                   -- 외주반출·외주재작업반출 : 입고창고의 외주처
