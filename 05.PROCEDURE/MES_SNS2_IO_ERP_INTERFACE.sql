-- CALL PROC
-- IO_MOVELOT_OSC : I (TML1010_R04 외주간이동, KEY = 거래명세서번호)
WHEN $INTERFACENAME = 'WORK_30' THEN -- 창고이동 30 외주간이동 (KEY = 거래명세서번호 INVOICEKEY)

  -- 외주간 이동(04) 거래명세서만 송신
  IF NOT EXISTS (SELECT 1
                   FROM MTRCUST_INVOICE_HEADER
                  WHERE INVOICEKEY = $KEY
                    AND INVOICETP  = '04') THEN
    LEAVE PROC;
  END IF;

  -- ERP 마감 확인 (이동일자)
  SET _$MAGAMDT = (SELECT LEFT(INVOICEDATE, 10) FROM MTRCUST_INVOICE_HEADER WHERE INVOICEKEY = $KEY);

  IF EXISTS (SELECT 1 FROM MSTMAGAM_PRD WHERE MSTMAGAM_PRD.BDVCD = '71' AND MSTMAGAM_PRD.EDT = _$MAGAMDT) THEN
    CALL COMERR(CONCAT('ERP에서 마감된 일자 입니다. (', _$MAGAMDT, ')'));
    LEAVE PROC;
  END IF;

  INSERT INTO IF_MES_SNS_FAC2.FAC2_ERP_IF_WORK (
    OUTFACTORY, INFACTORY, MOVENO, MOVESEQ, OUTDT,
    OUTWARE, INWARE, ITEMID, LOTKEY, ITEMUNIT,
    OUTQTY, CUSTCD, REMARK, REMP, MOV_BC, ENT_BC, LOCATION,
    IF_TYPE, IF_YN, IF_TIME
  )
  SELECT
    T.OUTFAC, T.INFAC, T.MOVENO, ROW_NUMBER() OVER (ORDER BY T.LOTKEY, T.RN), T.OUTDT,
    T.OUTWARE, T.INWARE, T.ITEMID, T.LOTKEY, T.ITEMUNIT,
    T.QTY, T.CUSTCD, '', T.REMP, 'LE300110', 'LE920392', '',
    $IF_TYPE, 'N', GETTIME()
    FROM (
      -- 1. 정상 이동분 (이동량 - 시편수량). 시편 LOT(LOTTP 02) 는 전체를 시편창고로
      SELECT
        1 AS RN,
        IFNULL(NULLIF(OUTW.FACTORYCD, ''), '07') AS OUTFAC, IFNULL(NULLIF(INW.FACTORYCD, ''), '07') AS INFAC,
        CONCAT('2MES', H.INVOICEKEY) AS MOVENO, LEFT(H.INVOICEDATE, 10) AS OUTDT,
        COMOUTLOT.WARECD AS OUTWARE, IF(IFNULL(DTL.LOTTP, '') = '02', '04S132_N', COMIN.WARECD) AS INWARE,
        COMOUTLOT.ITEMID AS ITEMID, COMOUTLOT.LOTKEY AS LOTKEY, IFNULL(MSTITEM.ITEMUNIT, '') AS ITEMUNIT,
        COMOUTLOT.OUTQTY - IF(IFNULL(DTL.LOTTP, '') = '02', 0, IFNULL(DTL.TESTQTY, 0)) AS QTY,
        LEFT(IFNULL(H.CUSTCD_RECIEVER, ''), 10) AS CUSTCD, IFNULL(COMOUTLOT.REMP, '') AS REMP   -- 외주처 = 이동받는 외주처
        FROM MTRCUST_INVOICE_HEADER AS H
       INNER JOIN COMOUT ON COMOUT.INVOICEKEY = H.INVOICEKEY
       INNER JOIN COMOUTLOT ON COMOUTLOT.OUTKEY = COMOUT.OUTKEY
       INNER JOIN COMIN ON COMIN.INVOICEKEY = H.INVOICEKEY
                       AND COMIN.ITEMID = COMOUTLOT.ITEMID
        LEFT JOIN MTRCUST_INVOICE_DETAIL AS DTL ON DTL.INVOICEKEY = H.INVOICEKEY
                                               AND DTL.LOTKEY = COMOUTLOT.LOTKEY
        LEFT JOIN MSTITEM ON MSTITEM.ITEMID = COMOUTLOT.ITEMID
        LEFT JOIN MSTWARE AS OUTW ON OUTW.WARECD = COMOUTLOT.WARECD
        LEFT JOIN MSTWARE AS INW ON INW.WARECD = IF(IFNULL(DTL.LOTTP, '') = '02', '04S132_N', COMIN.WARECD)
       WHERE H.INVOICEKEY = $KEY
         AND COMOUTLOT.OUTQTY - IF(IFNULL(DTL.LOTTP, '') = '02', 0, IFNULL(DTL.TESTQTY, 0)) > 0
      UNION ALL
      -- 2. 시편수량 (1공장과 같게 시편창고로 별도 행)
      SELECT
        2 AS RN,
        IFNULL(NULLIF(OUTW.FACTORYCD, ''), '07'), IFNULL(NULLIF(TESTW.FACTORYCD, ''), '07'),
        CONCAT('2MES', H.INVOICEKEY), LEFT(H.INVOICEDATE, 10),
        COMOUTLOT.WARECD, '04S132_N',
        COMOUTLOT.ITEMID, COMOUTLOT.LOTKEY, IFNULL(MSTITEM.ITEMUNIT, ''),
        DTL.TESTQTY,
        LEFT(IFNULL(H.CUSTCD_RECIEVER, ''), 10), IFNULL(COMOUTLOT.REMP, '')
        FROM MTRCUST_INVOICE_HEADER AS H
       INNER JOIN COMOUT ON COMOUT.INVOICEKEY = H.INVOICEKEY
       INNER JOIN COMOUTLOT ON COMOUTLOT.OUTKEY = COMOUT.OUTKEY
       INNER JOIN MTRCUST_INVOICE_DETAIL AS DTL ON DTL.INVOICEKEY = H.INVOICEKEY
                                               AND DTL.LOTKEY = COMOUTLOT.LOTKEY
        LEFT JOIN MSTITEM ON MSTITEM.ITEMID = COMOUTLOT.ITEMID
        LEFT JOIN MSTWARE AS OUTW ON OUTW.WARECD = COMOUTLOT.WARECD
        LEFT JOIN MSTWARE AS TESTW ON TESTW.WARECD = '04S132_N'
       WHERE H.INVOICEKEY = $KEY
         AND IFNULL(DTL.TESTQTY, 0) > 0
         AND IFNULL(DTL.LOTTP, '') <> '02'
    ) AS T
   ORDER BY T.LOTKEY, T.RN;

