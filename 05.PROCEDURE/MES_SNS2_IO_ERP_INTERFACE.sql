    PRDRSTNON.NONCD,
    PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME,
    TIMESTAMPDIFF(MINUTE, PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME),
    IFNULL(PRDRSTNON.PROBLEM, ''), IFNULL(PRDRSTNON.SOLUTION, ''),
    $IF_TYPE, 'N', GETTIME()
    FROM PRDRSTNON
