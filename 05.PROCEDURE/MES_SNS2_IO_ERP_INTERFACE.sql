-- CALL PROC
-- TML2010_R01 : END_NON (I)
-- TML2040_R01 : ADD_PRDRSTNON (I), END_NON (I), UP_PRDRSTNON (U), UP_PRDRSTNON_PROBLEM (U)
WHEN $INTERFACENAME = 'PRDRSTNON' THEN -- 비가동 송신 (KEY = 비가동번호 PRDNONKEY) : 종료된 비가동만 송신, 종료 시 I, 수정 시 U

  IF NOT EXISTS (SELECT 1
                   FROM PRDRSTNON
                  WHERE PRDRSTNON.PRDNONKEY = $KEY
                    AND PRDRSTNON.NONETIME <> '') THEN
    LEAVE PROC;
  END IF;

  -- ERP 마감 확인 (비가동 시작일)
  SET _$MAGAMDT = (SELECT LEFT(PRDRSTNON.NONSTIME, 10) FROM PRDRSTNON WHERE PRDRSTNON.PRDNONKEY = $KEY);

  IF EXISTS (SELECT 1 FROM MSTMAGAM_PRD WHERE MSTMAGAM_PRD.BDVCD = '71' AND MSTMAGAM_PRD.EDT = _$MAGAMDT) THEN
    CALL COMERR(CONCAT('ERP에서 마감된 일자 입니다. (', _$MAGAMDT, ')'));
    LEAVE PROC;
  END IF;

  INSERT INTO IF_MES_SNS_FAC2.FAC2_ERP_IF_PRDRSTNON (
    PRDNONKEY, WORKDATE, FACTORYCD, LINECD,
    PRCCD, EQMCD, ITEMID, NONCD,
    NONSTIME, NONETIME, NONTIME,
    PROBLEM, SOLUTION,
    IF_TYPE, IF_YN, IF_TIME
  )
  SELECT
    CONCAT('2MES', PRDRSTNON.PRDNONKEY),                    -- 1&2공장 구분을 위해 앞에 2MES
    IFNULL(PRDWORK.WORKDATE, LEFT(PRDRSTNON.NONSTIME, 10)),
    IFNULL(NULLIF(MSTLINE.FACTORYCD, ''), '07'),
    IFNULL(MSTLINE.LINECD, ''),
    -- 공정·품목 : 작업이력이 있으면 그것, 없으면 그 라인에 지금 설정된 생산품 (비가동 종료 시점에는 작업이력이 아직 없음)
    IFNULL(PRDWORK.PRCCD, IFNULL((SELECT L.PRCCD FROM PRDLINEITEM AS L
                                   WHERE L.LINECD = MSTLINE.LINECD AND L.EQMCD = PRDRSTNON.EQMCD LIMIT 1), '')),
    PRDRSTNON.EQMCD,
    IFNULL(PRDWORK.ITEMID, IFNULL((SELECT L.ITEMID FROM PRDLINEITEM AS L
