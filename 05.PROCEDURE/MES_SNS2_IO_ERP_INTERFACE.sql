CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.IO_ERP_INTERFACE(
-- *****************************************************************************
-- Comment: ERP INTERFACE IO (2공장)  - 1공장 MES_SNS.IO_ERP_INTERFACE 와 같은 방식, 송신 테이블은 IF_MES_SNS_FAC2.FAC2_ERP_IF_*
-- Create: 2026-11-11 : 외주처 원자재 납품(DLV) 송신 추가
-- Modify: 2026-11-11 : 소모자재 입출내역(USEINOUT) 송신 추가
-- Modify: 2026-11-11 : 작업지시(PRDINS), 생산실적(PRDRST: 실적·실적LOT·소요자재·작업자·불량) 송신 추가
-- Modify: 2026-11-11 : 외주 생산실적(OSCRST: 실적·실적LOT·소요자재) 송신 추가
-- Modify: 2026-11-11 : 비가동(PRDRSTNON) 송신 추가
-- Modify: 2026-11-11 : 출하LOT(SALOUTLOT), 기타입고(ETC_IN)·기타출고(ETC_OUT) 송신 추가
-- Modify: 2026-11-11 : 창고이동(WORK) 외주반출 FLAG 20 (WORK_20), 외주간이동 FLAG 30 (WORK_30) 송신 추가
-- Modify: 2026-11-12 : 창고이동(WORK) FLAG 대신 MOV_BC/ENT_BC 사용. 사업장 간 이동(WORK_40), 외주재작업반출(WORK_22), 외주재작업입고(WORK_23), 외주입고(WORK_21) 송신 추가
-- Modify: 2026-11-12 : 시편수량(거래명세서 상세 TESTQTY) 은 1공장과 같게 시편창고(04S132_N) 로 별도 행 송신 (외주입고 WORK_21, 외주간이동 WORK_30)
-- Modify: 2026-11-12 : 원자재 이동(WORK_10) 송신 추가
-- Modify: 2026-11-12 : 시편 LOT(LOTTP 02)는 1공장과 같게 입고창고를 시편창고(04S132_N)로 송신 (외주입고 WORK_21, 외주간이동 WORK_30)
-- Modify: 2026-11-11 : 송신 전 ERP 마감 확인 추가 (MSTMAGAM_PRD 사업장 71 + 일자, 생산실적은 MSTMAGAM_MON PPJ 실적LOT 마감도)
-- Modify: 2026-11-18 : ERP 수신 정의서 V1.3 반영 - DLV 에 PO_BC 추가, 무상사급 구매(MM100910) 입고확인은 PUR 로 송신(DLV_INV: 납품등록만 따로 송신),
--                      유상사급 자재입고확인 CSM(2CM + 이동 GROUPKEY), 유상사급 자재반출 CSM_RETURN 추가. 반출 중 납품 삭제 DLV D 는 송신 안 함(@ERP_SKIP_DLV_D)
-- Modify: 2026-11-23 : 유상사급 납품등록이 거래명세서를 만들지 않으므로 DLV(입고 때 송신)·CSM·CSM_RETURN 의 납품번호를 자재이동 거래명세서(05) 기준(2MES + 거래명세서번호)으로 변경
-- *****************************************************************************
  IN $INTERFACENAME VARCHAR(20),  -- INTERFACE 호출명
  IN $KEY           VARCHAR(100), -- KEY
  IN $IF_TYPE       VARCHAR(1)    -- IFTYPE(I,U,D)
)
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************

  DECLARE _$INVOICEKEY VARCHAR(50);   -- 거래명세서번호
  DECLARE _$ITEMID     VARCHAR(50);   -- 입고 품목
  DECLARE _$MAGAMDT    VARCHAR(10);   -- ERP 마감 확인할 일자
  DECLARE _$RTNKEY     VARCHAR(30);   -- 유상사급 자재반출 : 반출번호 (2MES + MOVEOUTKEY)
  DECLARE _$RTNOFF     INT;           -- 유상사급 자재반출 : 이 반출번호로 이미 보낸 행 수 (거래명세서 여러 장일 때 순번 이어붙이기)

-- ****************************************************************************
CASE
-- ****************************************************************************
WHEN $INTERFACENAME = 'DLV' THEN -- 외주처 원자재 납품 (KEY = 입고번호 MTRINKEY) : 입고등록 시 I, 입고취소 시 D
                                 --   무상사급 구매(MM100910) 는 입고확인이므로 FAC2_ERP_IF_PUR 로 송신 (납품등록은 DLV_INV)

  -- 유상사급 자재반출(TML1020_R08)은 반출 한 건(CSM_RETURN)으로 ERP 가 납품까지 지우므로, 반출 중 납품 삭제의 D 는 보내지 않음
  IF $IF_TYPE = 'D' AND IFNULL(@ERP_SKIP_DLV_D, '') = 'Y' THEN
    LEAVE PROC;
  END IF;

  SELECT MTRIN.INVOICEKEY, MTRIN.ITEMID
    INTO _$INVOICEKEY, _$ITEMID
    FROM MTRIN
   WHERE MTRIN.MTRINKEY = $KEY;

  -- 거래명세서 없는 입고, 납품(01) 이 아닌 거래명세서는 송신하지 않음
  IF IFNULL(_$INVOICEKEY, '') = '' THEN
    LEAVE PROC;
  END IF;

  IF NOT EXISTS (SELECT 1
                   FROM MTRCUST_INVOICE_HEADER
                  WHERE INVOICEKEY = _$INVOICEKEY
                    AND INVOICETP IN ('01', '05')) THEN   -- 05 = 유상사급 자재이동 거래명세서 (입고확인 때 입고)
    LEAVE PROC;
  END IF;

  -- ERP 마감 확인 (입고일자)
  SET _$MAGAMDT = (SELECT MTRIN.INDATE FROM MTRIN WHERE MTRIN.MTRINKEY = $KEY);

  IF EXISTS (SELECT 1 FROM MSTMAGAM_PRD WHERE MSTMAGAM_PRD.BDVCD = '71' AND MSTMAGAM_PRD.EDT = _$MAGAMDT) THEN
    CALL COMERR(CONCAT('ERP에서 마감된 일자 입니다. (', _$MAGAMDT, ')'));
    LEAVE PROC;
  END IF;

  -- 무상사급 구매(MM100910) 입고확인 : DLV 가 아니라 PUR (원자재·상품 구매 입고확인) 로 송신. 납품(DLV_NO, DLV_SQ)은 납품등록 때 DLV_INV 로 이미 보냄
  IF EXISTS (SELECT 1
               FROM MTRCUST_INVOICE_DETAIL AS D
              INNER JOIN MTRCUSTLOT AS L ON L.LOTKEY = D.LOTKEY
              INNER JOIN MTRODR AS O ON O.MTRODRKEY = L.MTRODRKEY
              WHERE D.INVOICEKEY = _$INVOICEKEY
                AND O.ODRBC = 'MM100910') THEN

    INSERT INTO IF_MES_SNS_FAC2.FAC2_ERP_IF_PUR (
      FACTORYCD, DLV_NO, DLV_SQ, INDATE, LOTKEY, INQTY,
      PO_NO, PO_SQ, REMP,
      IF_TYPE, IF_YN, IF_TIME
    )
    SELECT
      '07',                                        -- INC 2공장
      CONCAT('2MES', _$INVOICEKEY),                -- 납품등록(DLV_INV)으로 보낸 DLV_NO 그대로
      T.SQ,                                        -- 납품등록 DLV_SQ 와 같은 순번 (거래명세서 전체 기준)
      MTRIN.INDATE, T.LOTKEY, T.LOTQTY,
      IFNULL(MTRCUSTLOT.MTRODRKEY, ''), IFNULL(MTRCUSTLOT.MTRODRSEQ, 0),
      IFNULL(MTRIN.REMP, ''),
      $IF_TYPE, 'N', GETTIME()
      FROM MTRIN
     INNER JOIN (SELECT D.INVOICEKEY, D.ITEMID, D.LOTKEY, D.LOTQTY,
                        ROW_NUMBER() OVER(ORDER BY D.ITEMID, D.LOTKEY) AS SQ
                   FROM MTRCUST_INVOICE_DETAIL AS D
                  WHERE D.INVOICEKEY = _$INVOICEKEY) AS T
             ON T.ITEMID = MTRIN.ITEMID
      LEFT JOIN MTRCUSTLOT ON MTRCUSTLOT.LOTKEY = T.LOTKEY
     WHERE MTRIN.MTRINKEY = $KEY
     ORDER BY T.SQ;

    LEAVE PROC;
  END IF;

  INSERT INTO IF_MES_SNS_FAC2.FAC2_ERP_IF_DLV (
    FACTORYCD, DLV_NO, DLV_SQ, DLV_DT, INDATE,
    ITEMID, ITEMUNIT, LOTKEY, LOTQTY,
    PO_NO, PO_SQ, CUSTCD, HEATNO,
    REMARK, PO_BC, REMP,
    IF_TYPE, IF_YN, IF_TIME
  )
  SELECT
    HEADER.CUSTCD_GIVER,                         -- 외주처 (납품한 곳)
    CONCAT('2MES', HEADER.INVOICEKEY),           -- 1&2공장 구분을 위해 앞에 2MES
    T.SQ,                                        -- 거래명세서 전체 기준 순번
    LEFT(IFNULL(MTRCUSTLOT.PRDDATE, HEADER.INVOICEDATE), 10),   -- 납품일자 = 납품 LOT 의 납품(출하)일자
    MTRIN.INDATE,
    T.ITEMID, MSTITEM.ITEMUNIT, T.LOTKEY, T.LOTQTY,
    -- ERP 발주번호/순번 : MTRODR/MTRODRD 는 ERP 에서 받은 발주라 발주번호·순번이 곧 ERP 발주번호·순번
    IFNULL(MTRCUSTLOT.MTRODRKEY, ''), IFNULL(MTRCUSTLOT.MTRODRSEQ, 0),
    HEADER.CUSTCD_GIVER, IFNULL(MTRCUSTLOT.HEATNO, ''),
    IFNULL(MTRIN.REMARK, ''), IFNULL(MTRODR.ODRBC, ''),   -- PO_BC : MM100900 유상사급 납품등록 / MM100910 원자재·상품 구매
    IFNULL(MTRIN.REMP, ''),
    $IF_TYPE, 'N', GETTIME()
    FROM MTRIN
   INNER JOIN MTRCUST_INVOICE_HEADER AS HEADER
           ON HEADER.INVOICEKEY = MTRIN.INVOICEKEY
   INNER JOIN (SELECT D.INVOICEKEY, D.ITEMID, D.LOTKEY, D.LOTQTY,
                      ROW_NUMBER() OVER(ORDER BY D.ITEMID, D.LOTKEY) AS SQ
                 FROM MTRCUST_INVOICE_DETAIL AS D
                WHERE D.INVOICEKEY = _$INVOICEKEY) AS T
           ON T.ITEMID = MTRIN.ITEMID
   INNER JOIN MSTITEM ON MSTITEM.ITEMID = T.ITEMID
    LEFT JOIN MTRCUSTLOT ON MTRCUSTLOT.LOTKEY = T.LOTKEY
    LEFT JOIN MTRODR ON MTRODR.MTRODRKEY = MTRCUSTLOT.MTRODRKEY
   WHERE MTRIN.MTRINKEY = $KEY
   ORDER BY T.SQ;

-- ****************************************************************************
-- CALL PROC
-- TML1010_R07 : I (원자재·상품 납품등록), D (납품 취소). KEY = 거래명세서번호 (입고는 TML1020_R09 입고확인 때 PUR 로 송신)
WHEN $INTERFACENAME = 'DLV_INV' THEN -- 무상사급 구매(MM100910) 납품등록 송신 (입고 없이 납품만, INDATE 는 비움)

  IF NOT EXISTS (SELECT 1
                   FROM MTRCUST_INVOICE_HEADER
                  WHERE INVOICEKEY = $KEY
                    AND INVOICETP  = '01') THEN
    LEAVE PROC;
  END IF;

  INSERT INTO IF_MES_SNS_FAC2.FAC2_ERP_IF_DLV (
    FACTORYCD, DLV_NO, DLV_SQ, DLV_DT, INDATE,
    ITEMID, ITEMUNIT, LOTKEY, LOTQTY,
    PO_NO, PO_SQ, CUSTCD, HEATNO,
    REMARK, PO_BC, REMP,
    IF_TYPE, IF_YN, IF_TIME
  )
  SELECT
    HEADER.CUSTCD_GIVER,
    CONCAT('2MES', HEADER.INVOICEKEY),
    ROW_NUMBER() OVER(ORDER BY D.ITEMID, D.LOTKEY),   -- 입고확인(PUR)의 DLV_SQ 와 같은 순번
    LEFT(HEADER.INVOICEDATE, 10),
    '',
    D.ITEMID, MSTITEM.ITEMUNIT, D.LOTKEY, D.LOTQTY,
    IFNULL(MTRCUSTLOT.MTRODRKEY, ''), IFNULL(MTRCUSTLOT.MTRODRSEQ, 0),
    HEADER.CUSTCD_GIVER, IFNULL(MTRCUSTLOT.HEATNO, ''),
    '', IFNULL(MTRODR.ODRBC, ''),
    IFNULL(HEADER.REMP, ''),
    $IF_TYPE, 'N', GETTIME()
    FROM MTRCUST_INVOICE_DETAIL AS D
   INNER JOIN MTRCUST_INVOICE_HEADER AS HEADER ON HEADER.INVOICEKEY = D.INVOICEKEY
   INNER JOIN MSTITEM ON MSTITEM.ITEMID = D.ITEMID
    LEFT JOIN MTRCUSTLOT ON MTRCUSTLOT.LOTKEY = D.LOTKEY
    LEFT JOIN MTRODR ON MTRODR.MTRODRKEY = MTRCUSTLOT.MTRODRKEY
   WHERE D.INVOICEKEY = $KEY
   ORDER BY D.ITEMID, D.LOTKEY;

-- ****************************************************************************
-- CALL PROC
-- TML1020_R07 : I (유상사급 자재입고확인). KEY = IO_MOVELOT_WARE 가 만든 이동 GROUPKEY (거래명세서 헤더 MOVEGROUPKEY 에 저장한 뒤 호출)
WHEN $INTERFACENAME = 'CSM' THEN -- 유상사급 자재입고확인 (사내창고 04S100_N → 자재투입창고 04S111_N)

  -- ERP 마감 확인 (입고확인일자)
  SET _$MAGAMDT = (SELECT MIN(COMOUT.OUTDATE) FROM COMOUT WHERE COMOUT.GROUPKEY = $KEY);

  IF EXISTS (SELECT 1 FROM MSTMAGAM_PRD WHERE MSTMAGAM_PRD.BDVCD = '71' AND MSTMAGAM_PRD.EDT = _$MAGAMDT) THEN
    CALL COMERR(CONCAT('ERP에서 마감된 일자 입니다. (', _$MAGAMDT, ')'));
    LEAVE PROC;
  END IF;

  INSERT INTO IF_MES_SNS_FAC2.FAC2_ERP_IF_CSM (
    FACTORYCD, CSM_NO, CSM_SQ, INDATE,
    DLV_NO, DLV_SQ, LEN_NO, LEN_SQ,
    ITEMID, LOTKEY, ITEMUNIT, MOVQTY, INQTY,
    OUTWARE, INWARE, REMP,
    IF_TYPE, IF_YN, IF_TIME
  )
  SELECT
    '07',                                              -- INC 2공장
    CONCAT('2CM', $KEY),                               -- 입고확인번호 = 2CM + 이동 GROUPKEY
    ROW_NUMBER() OVER (ORDER BY D.LOTKEY),
    LEFT(_$MAGAMDT, 10),
    CONCAT('2MES', H.INVOICEKEY), X.SQ,                -- 납품번호·순번 = 입고확인 때 보낸 DLV (2MES + 자재이동 거래명세서번호, 거래명세서 안의 순번)
    D.INVOICEKEY, ROW_NUMBER() OVER (ORDER BY D.LOTKEY),   -- 자재이동 거래명세서 (추적용)
    D.ITEMID, D.LOTKEY, IFNULL(MSTITEM.ITEMUNIT, ''),
    D.LOTQTY, D.LOTQTY - IFNULL(D.TESTQTY, 0),         -- 입고수량 = 이동수량 - 시편수량
    '04S100_N', '04S111_N',                            -- 자재창고 → 자재투입창고
    IFNULL(CALLEMP(), ''),
    $IF_TYPE, 'N', GETTIME()
    FROM MTRCUST_INVOICE_HEADER AS H
   INNER JOIN MTRCUST_INVOICE_DETAIL AS D ON D.INVOICEKEY = H.INVOICEKEY
    LEFT JOIN MSTITEM ON MSTITEM.ITEMID = D.ITEMID
    LEFT JOIN (SELECT D1.INVOICEKEY, D1.LOTKEY,
                      ROW_NUMBER() OVER (PARTITION BY D1.INVOICEKEY ORDER BY D1.ITEMID, D1.LOTKEY) AS SQ
                 FROM MTRCUST_INVOICE_DETAIL AS D1
                INNER JOIN MTRCUST_INVOICE_HEADER AS H1 ON H1.INVOICEKEY = D1.INVOICEKEY AND H1.INVOICETP = '05') AS X
           ON X.INVOICEKEY = D.INVOICEKEY AND X.LOTKEY = D.LOTKEY
   WHERE H.MOVEGROUPKEY = $KEY
     AND H.INVOICETP = '05'
   ORDER BY D.LOTKEY;

-- ****************************************************************************
-- CALL PROC
-- TML1020_R08 : I (유상사급 자재반출). KEY = 자재이동 거래명세서번호 (반출 이력 MTRCUST_MOVEOUTD 를 저장한 뒤, 거래명세서를 지우기 전에 호출)
WHEN $INTERFACENAME = 'CSM_RETURN' THEN -- 유상사급 자재반출 (반출 한 건으로 ERP 가 입고확인 이동 · 구매입고 · 납품을 지움)

  SET _$RTNKEY = (SELECT CONCAT('2MES', MIN(MO.MOVEOUTKEY)) FROM MTRCUST_MOVEOUTD AS MO WHERE MO.MOVEINVOICEKEY = $KEY);

  IF IFNULL(_$RTNKEY, '') = '' THEN
    LEAVE PROC;
  END IF;

  -- 같은 반출번호로 이미 보낸 행 수 (거래명세서가 여러 장이면 순번을 이어서 붙임)
  SET _$RTNOFF = (SELECT COUNT(*) FROM IF_MES_SNS_FAC2.FAC2_ERP_IF_CSM_RETURN WHERE RTN_NO = _$RTNKEY);

  INSERT INTO IF_MES_SNS_FAC2.FAC2_ERP_IF_CSM_RETURN (
    FACTORYCD, RTN_NO, RTN_SQ, RTNDATE,
    DLV_NO, DLV_SQ, CSM_NO, CSM_SQ, LEN_NO, LEN_SQ,
    ITEMID, LOTKEY, RTNQTY, REMP,
    IF_TYPE, IF_YN, IF_TIME
  )
  SELECT
    '07',                                              -- INC 2공장
    _$RTNKEY,
    _$RTNOFF + ROW_NUMBER() OVER (ORDER BY MO.LOTKEY),
    LEFT(MH.MOVEOUTDATE, 10),
    IFNULL(CONCAT('2MES', X.INVOICEKEY), ''), X.SQ,    -- 반출할 납품 (납품등록 DLV)
    CONCAT('2CM', H.MOVEGROUPKEY), N.SQ,               -- 입고확인번호·순번 (CSM 으로 보낸 것과 같은 값)
    H.INVOICEKEY, N.SQ,                                -- 자재이동 거래명세서 (추적용)
    MO.ITEMID, MO.LOTKEY, MO.MOVEOUTQTY, IFNULL(CALLEMP(), ''),
    $IF_TYPE, 'N', GETTIME()
    FROM MTRCUST_MOVEOUTD AS MO
   INNER JOIN MTRCUST_MOVEOUT AS MH ON MH.MOVEOUTKEY = MO.MOVEOUTKEY
   INNER JOIN MTRCUST_INVOICE_HEADER AS H ON H.INVOICEKEY = MO.MOVEINVOICEKEY
    LEFT JOIN (SELECT D2.INVOICEKEY, D2.LOTKEY,
                      ROW_NUMBER() OVER (PARTITION BY D2.INVOICEKEY ORDER BY D2.LOTKEY) AS SQ
                 FROM MTRCUST_INVOICE_DETAIL AS D2) AS N
           ON N.INVOICEKEY = MO.MOVEINVOICEKEY AND N.LOTKEY = MO.LOTKEY
    LEFT JOIN (SELECT D1.INVOICEKEY, D1.LOTKEY,
                      ROW_NUMBER() OVER (PARTITION BY D1.INVOICEKEY ORDER BY D1.ITEMID, D1.LOTKEY) AS SQ
                 FROM MTRCUST_INVOICE_DETAIL AS D1
                INNER JOIN MTRCUST_INVOICE_HEADER AS H1 ON H1.INVOICEKEY = D1.INVOICEKEY AND H1.INVOICETP = '05') AS X
           ON X.INVOICEKEY = MO.DLVINVOICEKEY AND X.LOTKEY = MO.LOTKEY
   WHERE MO.MOVEINVOICEKEY = $KEY
   ORDER BY MO.LOTKEY;

-- ****************************************************************************
WHEN $INTERFACENAME = 'USEINOUT' THEN -- 소모자재 입출내역 (KEY = 소모품 입출고번호 INOUTKEY) : 소모품 입고/출고 등록 시 I

  -- ERP 마감 확인 (입/출고일자)
  SET _$MAGAMDT = (SELECT IOT.INOUTDATE FROM INOUT_PRDCONSUM AS IOT WHERE IOT.INOUTKEY = $KEY);

  IF EXISTS (SELECT 1 FROM MSTMAGAM_PRD WHERE MSTMAGAM_PRD.BDVCD = '71' AND MSTMAGAM_PRD.EDT = _$MAGAMDT) THEN
    CALL COMERR(CONCAT('ERP에서 마감된 일자 입니다. (', _$MAGAMDT, ')'));
    LEAVE PROC;
  END IF;

  INSERT INTO IF_MES_SNS_FAC2.FAC2_ERP_IF_USEINOUT (
    FLAG, SO_NO, SO_SQ, FACTORYCD, ITEMID,
    MOV_DT, ITEMUNIT, ETC_QTY, WH_CD, ETC_UP,
    DEPT_NO, REMP, CUST_CD, REQ_NO, REQ_SQ,
    RMKS, IF_TYPE, IF_YN, IF_TIME
  )
  SELECT
    IOT.INOROUT,                                   -- 입고 IN / 출고 OUT
    CONCAT('2MES', IOT.INOUTKEY),                  -- 1&2공장 구분을 위해 앞에 2MES
    1,
    '07',                                          -- 2공장
    IOT.ITEMID,
    IOT.INOUTDATE, MSTITEM.ITEMUNIT, IOT.INOUTQTY,
    -- ERP 의뢰정보 : 입고는 매칭된 ERP 발주(MTRODR/MTRODRD) 에서, 출고는 발주 매칭이 없어 빈 값
    IFNULL(MTRODR.INWARECD, ''), MTRODRD.MTRODRPRICE,
    IFNULL((SELECT E.DEPTCD FROM MSTEMP AS E WHERE E.EMPCD = IOT.EMPCD LIMIT 1), ''),
    IFNULL(IOT.EMPCD, ''),
    IFNULL(MTRODR.CUSTCD, ''), IFNULL(IOT.MTRODRKEY, ''), IOT.MTRODRSEQ,
    LEFT(IFNULL(IOT.REMARK, ''), 50),
    $IF_TYPE, 'N', GETTIME()
    FROM INOUT_PRDCONSUM AS IOT
   INNER JOIN MSTITEM ON MSTITEM.ITEMID = IOT.ITEMID
    LEFT JOIN MTRODRD ON MTRODRD.MTRODRKEY = IOT.MTRODRKEY
                     AND MTRODRD.MTRODRSEQ = IOT.MTRODRSEQ
    LEFT JOIN MTRODR  ON MTRODR.MTRODRKEY  = MTRODRD.MTRODRKEY
   WHERE IOT.INOUTKEY = $KEY;

-- ****************************************************************************
-- CALL PROC
-- IO_PRDRST : I (작업지시 PRDINS → 생산실적 PRDRST 순서로 호출)
WHEN $INTERFACENAME = 'PRDINS' THEN -- 작업지시 정보 송신 (KEY = 작업지시번호 PRDINSKEY)

  -- ERP 마감 확인 (작업지시일자)
  SET _$MAGAMDT = (SELECT PRDINS.INSDATE FROM PRDINS WHERE PRDINS.PRDINSKEY = $KEY);

  IF EXISTS (SELECT 1 FROM MSTMAGAM_PRD WHERE MSTMAGAM_PRD.BDVCD = '71' AND MSTMAGAM_PRD.EDT = _$MAGAMDT) THEN
    CALL COMERR(CONCAT('ERP에서 마감된 일자 입니다. (', _$MAGAMDT, ')'));
    LEAVE PROC;
  END IF;

  INSERT INTO IF_MES_SNS_FAC2.FAC2_ERP_IF_PRDINS (
    PRDINSKEY, INDATE, PLANFACTORY, WORKSTIME, WORKETIME,
    ITEMID, LOTNO, INSQTY, LINECD, PRCCD, EQMCD,
    ROUTCD, WGTP, WORKSEQ, EMRCYN,
    REWORKYN, INSTP, PLANNO, PLANSEQ,
    EMPCD, WORKSTT, ENTBC, REMARK,
    REMP, RTIME, MEMP, MTIME,
    REQNO, REQSEQ, LINKWONO, LINKPLANNO,
    LINKPLANSEQ, LINKPLANREV,
    IF_TYPE, IF_YN, IF_TIME
  )
  SELECT
    CONCAT('2MES', PRDINS.PRDINSKEY),                       -- 1&2공장 구분을 위해 앞에 2MES
    PRDINS.INSDATE,
    IFNULL(NULLIF(MSTLINE.FACTORYCD, ''), '07'),            -- 계획공장
    IFNULL(PRDINS.INSSTIME, ''), IFNULL(PRDINS.INSETIME, ''),
    PRDINS.ITEMID, '', PRDINS.INSQTY, PRDINS.LINECD, PRDINS.PRCCD, PRDINS.EQMCD,
    '', IF(PRDINS.DNTP = 'NIGHT', 'PP160150N', 'PP160100N'), 0, 'N',   -- 주야구분 (DAY/NIGHT → PP160)
    'N', IFNULL(PRDINS.INSTP, ''), '', 0,
    IFNULL((SELECT CAST(PRDWORK.EMPCD AS UNSIGNED)          -- 작업자 (사원코드 순 첫 번째)
              FROM PRDWORK
             WHERE PRDWORK.PRDINSKEY = PRDINS.PRDINSKEY
             ORDER BY PRDWORK.PRDWORKKEY
             LIMIT 1), 0),
    CASE PRDINS.WORKSTT WHEN 'END' THEN 'PP250400' ELSE '' END,       -- 작업종료
    'PP251960',
    LEFT(IFNULL(PRDINS.REMARK, ''), 50),
    IFNULL(PRDINS.REMP, ''), IFNULL(PRDINS.RTIME, ''), IFNULL(PRDINS.MEMP, ''), IFNULL(PRDINS.MTIME, ''),
    '', 0, '', '',
    0, 0,
    $IF_TYPE, 'N', GETTIME()
    FROM PRDINS
    LEFT JOIN MSTLINE ON MSTLINE.LINECD = PRDINS.LINECD
   WHERE PRDINS.PRDINSKEY = $KEY;

-- ****************************************************************************
WHEN $INTERFACENAME = 'PRDRST' THEN -- 생산실적 정보 송신 (KEY = 생산실적번호 PRDRSTKEY) : 실적 + 실적LOT + 소요자재 + 작업자 + 불량

  -- ERP 마감 확인 (작업일 마감, 실적LOT 마감)
  SET _$MAGAMDT = (SELECT PRDWORK.WORKDATE
                     FROM PRDRST
                    INNER JOIN PRDWORK ON PRDWORK.PRDWORKKEY = PRDRST.PRDWORKKEY
                    WHERE PRDRST.PRDRSTKEY = $KEY);

  IF EXISTS (SELECT 1 FROM MSTMAGAM_PRD WHERE MSTMAGAM_PRD.BDVCD = '71' AND MSTMAGAM_PRD.EDT = _$MAGAMDT) THEN
    CALL COMERR(CONCAT('ERP에서 마감된 실적입니다. (', _$MAGAMDT, ')'));
    LEAVE PROC;
  END IF;

  IF EXISTS (SELECT 1
               FROM PRDRSTLOT
              INNER JOIN MSTMAGAM_MON ON MSTMAGAM_MON.LOTEKEY = PRDRSTLOT.LOTKEY
                                     AND MSTMAGAM_MON.MAGAMTP = 'PPJ'
              WHERE PRDRSTLOT.PRDRSTKEY = $KEY) THEN
    CALL COMERR('ERP에서 마감된 실적입니다.');
    LEAVE PROC;
  END IF;

  -- 생산실적
  INSERT INTO IF_MES_SNS_FAC2.FAC2_ERP_IF_PRDRST (
    FACTORYCD, PRDINSKEY, PRDRSTKEY, RSTTIME,
    WORKSDATE, WORKEDATE, ITEMID, LINECD,
    PRCCD, EQMCD, WGTP, INSTP,
    LOTSEQ, LOTKEY, GOODQTY, BADQTY,
    WORKTIME, WORKSTIME, WORKETIME,
    NONTIME, REALTIME, CITEMQTY, ITWEIGHT, CUTLENGTH,
    REMP, TAG, EMPQTY, RERST,
    BOXSEQ, BOXNO, LOCATION, RFID,
    IF_TYPE, IF_YN, IF_TIME
  )
  SELECT
    IFNULL(NULLIF(MSTLINE.FACTORYCD, ''), '07'),
    CONCAT('2MES', PRDWORK.PRDINSKEY),
    PRDRST.PRDRSTKEY,
    PRDWORK.WORKDATE,                                       -- 작업일
    LEFT(PRDWORK.WORKSTIME, 10), LEFT(PRDWORK.WORKETIME, 10),
    PRDRST.ITEMID, PRDRST.LINECD,
    PRDRST.PRCCD, PRDRST.EQMCD, IF(PRDINS.DNTP = 'NIGHT', 'PP160150N', 'PP160100N'), IFNULL(PRDINS.INSTP, ''),
