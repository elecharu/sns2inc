    FACTORYCD, PRDRSTKEY, LOTKEY, PRDWORKDATE,
    BADCD, BADQTY, REMP,
    IF_TYPE, IF_YN, IF_TIME
  )
  SELECT
    IFNULL(NULLIF(MSTLINE.FACTORYCD, ''), '07'), PRDRSTBAD.PRDRSTKEY, IFNULL(RSTLOT.LOTKEY, ''), PRDWORK.WORKDATE,
    PRDRSTBAD.BADCD, PRDRSTBAD.BADQTY, IFNULL(PRDRSTBAD.REMP, ''),
    $IF_TYPE, 'N', GETTIME()
    FROM PRDRSTBAD
   INNER JOIN PRDRST ON PRDRST.PRDRSTKEY = PRDRSTBAD.PRDRSTKEY
   INNER JOIN PRDWORK ON PRDWORK.PRDWORKKEY = PRDRST.PRDWORKKEY
    LEFT JOIN MSTLINE ON MSTLINE.LINECD = PRDRST.LINECD
    LEFT JOIN (SELECT PRDRSTLOT.PRDRSTKEY, MIN(PRDRSTLOT.LOTKEY) AS LOTKEY
                 FROM PRDRSTLOT
                GROUP BY PRDRSTLOT.PRDRSTKEY) AS RSTLOT
           ON RSTLOT.PRDRSTKEY = PRDRSTBAD.PRDRSTKEY
   WHERE PRDRSTBAD.PRDRSTKEY = $KEY;

