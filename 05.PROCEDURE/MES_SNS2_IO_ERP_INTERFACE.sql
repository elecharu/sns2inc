  SELECT
    IFNULL(NULLIF(MSTLINE.FACTORYCD, ''), '07'),
    CONCAT('2MES', PRDWORK.PRDINSKEY), PRDRST.PRDRSTKEY, PRDRSTLOT.LOTKEY,
    PRDRSTLOT.LOTQTY, PRDWORK.WORKDATE, PRDRST.EQMCD, NULL, NULL,
    'LT100IRN2', IFNULL(PRDRSTLOT.REMP, ''), IFNULL(PRDRSTLOT.RTIME, ''), IFNULL(PRDRSTLOT.RPRG, ''),
    IFNULL(PRDRSTLOT.MEMP, ''), IFNULL(PRDRSTLOT.MTIME, ''), IFNULL(PRDRSTLOT.MPRG, ''),
    $IF_TYPE, 'N', GETTIME()
    FROM PRDRSTLOT
   INNER JOIN PRDRST ON PRDRST.PRDRSTKEY = PRDRSTLOT.PRDRSTKEY
   INNER JOIN PRDWORK ON PRDWORK.PRDWORKKEY = PRDRST.PRDWORKKEY
    LEFT JOIN MSTLINE ON MSTLINE.LINECD = PRDRST.LINECD
   WHERE PRDRSTLOT.PRDRSTKEY = $KEY;

  -- 소요자재 (출고번호 = 그 실적의 품목별 자재출고 COMOUT.OUTKEY)
  INSERT INTO IF_MES_SNS_FAC2.FAC2_ERP_IF_PRDRSTUSE (
    FACTORYCD, PRDRSTUSEKEY, PRDRSTKEY, USEDT,
    USEITEMID, ITEMUNIT, USELOTKEY, USEQTY,
    USEWARECD, REMP, REF01, BOXSEQ,
    BOXNO, YARD, RFID,
    RTIME, RPRG, MEMP, MTIME, MPRG,
    IF_TYPE, IF_YN, IF_TIME
  )
  SELECT
    IFNULL(NULLIF(MSTLINE.FACTORYCD, ''), '07'),
    IFNULL(COMOUT.OUTKEY, ''), PRDRSTUSE.PRDRSTKEY, PRDWORK.WORKDATE,
    PRDRSTUSE.USEITEMID, IFNULL(MSTITEM.ITEMUNIT, ''), PRDRSTUSE.USELOTKEY,
    CAST(CAST(PRDRSTUSE.USEQTY AS DOUBLE) AS CHAR),
    PRDRSTUSE.USEWARECD, IFNULL(PRDRSTUSE.REMP, ''), NULL, 0,
    '', 'LT100IRN2', '',
    IFNULL(PRDRSTUSE.RTIME, ''), IFNULL(PRDRSTUSE.RPRG, ''), IFNULL(PRDRSTUSE.MEMP, ''), IFNULL(PRDRSTUSE.MTIME, ''), IFNULL(PRDRSTUSE.MPRG, ''),
    $IF_TYPE, 'N', GETTIME()
    FROM PRDRSTUSE
   INNER JOIN PRDRST ON PRDRST.PRDRSTKEY = PRDRSTUSE.PRDRSTKEY
   INNER JOIN PRDWORK ON PRDWORK.PRDWORKKEY = PRDRST.PRDWORKKEY
    LEFT JOIN MSTLINE ON MSTLINE.LINECD = PRDRST.LINECD
    LEFT JOIN MSTITEM ON MSTITEM.ITEMID = PRDRSTUSE.USEITEMID
    LEFT JOIN COMOUT ON COMOUT.PRDRSTKEY = PRDRSTUSE.PRDRSTKEY
                    AND COMOUT.WARECD = PRDRSTUSE.USEWARECD
                    AND COMOUT.ITEMID = PRDRSTUSE.USEITEMID
   WHERE PRDRSTUSE.PRDRSTKEY = $KEY;

  -- 작업자
  INSERT INTO IF_MES_SNS_FAC2.FAC2_ERP_IF_WORKEMP (
    FACTORYCD, PRDRSTKEY, WORKDATE,
    EMPCD, EMPQTY, REMP,
    IF_TYPE, IF_YN, IF_TIME
  )
  SELECT
    IFNULL(NULLIF(MSTLINE.FACTORYCD, ''), '07'), PRDRST.PRDRSTKEY, PRDWORK.WORKDATE,
    PRDWORK_EMP.EMPCD, 1, IFNULL(PRDWORK.REMP, ''),
    $IF_TYPE, 'N', GETTIME()
    FROM PRDWORK_EMP
   INNER JOIN PRDWORK ON PRDWORK.PRDWORKKEY = PRDWORK_EMP.PRDWORKKEY
   INNER JOIN PRDRST ON PRDRST.PRDWORKKEY = PRDWORK.PRDWORKKEY
    LEFT JOIN MSTLINE ON MSTLINE.LINECD = PRDRST.LINECD
   WHERE PRDRST.PRDRSTKEY = $KEY
   ORDER BY PRDWORK_EMP.EMPCD;

  -- 불량 (불량 LOT 번호는 실적 LOT 번호와 같음)
