    LEFT JOIN MSTLINE ON MSTLINE.LINECD = IFNULL(NULLIF(PRDRSTNON.LINECD, ''), MSTLINE_EQM.LINECD)
    LEFT JOIN PRDWORK ON PRDWORK.PRDWORKKEY = PRDRSTNON.PRDWORKKEY
   WHERE PRDRSTNON.PRDNONKEY = $KEY;

