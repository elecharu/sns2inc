WHEN $INTERFACENAME IN ('WORK_20', 'WORK_40', 'WORK_22', 'WORK_23', 'WORK_10') THEN -- 창고이동 20 외주반출 / 40 사업장 간 이동 / 22 외주재작업반출 / 23 외주재작업입고 / 10 원자재 이동

  -- ERP 마감 확인 (이동일자)
  SET _$MAGAMDT = (SELECT MIN(COMOUT.OUTDATE) FROM COMOUT WHERE COMOUT.GROUPKEY = $KEY);

  IF EXISTS (SELECT 1 FROM MSTMAGAM_PRD WHERE MSTMAGAM_PRD.BDVCD = '71' AND MSTMAGAM_PRD.EDT = _$MAGAMDT) THEN
    CALL COMERR(CONCAT('ERP에서 마감된 일자 입니다. (', _$MAGAMDT, ')'));
    LEAVE PROC;
  END IF;

  INSERT INTO IF_MES_SNS_FAC2.FAC2_ERP_IF_WORK (
    OUTFACTORY, INFACTORY, MOVENO, MOVESEQ, OUTDT,
    OUTWARE, INWARE, ITEMID, LOTKEY, ITEMUNIT,
    OUTQTY, CUSTCD, REMARK, REMP, MOV_BC, ENT_BC, LOCATION,
    IF_TYPE, IF_YN, IF_TIME
  )
  SELECT
    IFNULL(NULLIF(OUTW.FACTORYCD, ''), '07'), IFNULL(NULLIF(INW.FACTORYCD, ''), '07'),
