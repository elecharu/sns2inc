    TIMESTAMPDIFF(MINUTE, PRDWORK.WORKSTIME, PRDWORK.WORKETIME),
    RIGHT(PRDWORK.WORKSTIME, 8), RIGHT(PRDWORK.WORKETIME, 8),
    0, TIMESTAMPDIFF(MINUTE, PRDWORK.WORKSTIME, PRDWORK.WORKETIME), NULL, NULL, NULL,
    IFNULL(PRDRST.REMP, ''), '', IFNULL(WORKEMP.EMPCNT, 0), '',
    0, '', 'LT100IRN2', '',
    $IF_TYPE, 'N', GETTIME()
    FROM PRDRST
   INNER JOIN PRDWORK ON PRDWORK.PRDWORKKEY = PRDRST.PRDWORKKEY
   INNER JOIN PRDINS ON PRDINS.PRDINSKEY = PRDWORK.PRDINSKEY
    LEFT JOIN MSTLINE ON MSTLINE.LINECD = PRDRST.LINECD
    LEFT JOIN (SELECT PRDRSTLOT.PRDRSTKEY, MIN(PRDRSTLOT.LOTKEY) AS LOTKEY
                 FROM PRDRSTLOT
                GROUP BY PRDRSTLOT.PRDRSTKEY) AS RSTLOT
           ON RSTLOT.PRDRSTKEY = PRDRST.PRDRSTKEY
    LEFT JOIN (SELECT PRDWORK_EMP.PRDWORKKEY, COUNT(*) AS EMPCNT
                 FROM PRDWORK_EMP
                GROUP BY PRDWORK_EMP.PRDWORKKEY) AS WORKEMP
           ON WORKEMP.PRDWORKKEY = PRDRST.PRDWORKKEY
   WHERE PRDRST.PRDRSTKEY = $KEY;

  -- 실적 LOT
  INSERT INTO IF_MES_SNS_FAC2.FAC2_ERP_IF_PRDRSTLOT (
    FACTORYCD, PRDINSKEY, PRDRSTKEY, LOTKEY,
    LOTQTY, WORKDT, EQMCD, INPUTQTY, REALQTY,
    YARD, REMP, RTIME, RPRG, MEMP, MTIME, MPRG,
    IF_TYPE, IF_YN, IF_TIME
