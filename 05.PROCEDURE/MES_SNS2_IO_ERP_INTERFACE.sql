-- CALL PROC
-- TML1020_R02 : I (외주반출), TML1020_R03 : I (사업장 간 이동), TML1020_R04 : I (외주재작업반출), TML1020_R05 : I (외주재작업입고), TML1020_R06 : I (원자재 이동)
