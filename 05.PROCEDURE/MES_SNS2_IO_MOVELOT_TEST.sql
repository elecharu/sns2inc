CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.IO_MOVELOT_TEST(
-- *****************************************************************************
-- Comment: 거래명세서의 시편수량을 시편창고(04S132_N)로 이동 (외주이동 입고 / 외주간이동 등록 때 호출)
--          LOT 별 시편수량(MTRCUST_INVOICE_DETAIL.TESTQTY) 만큼 출발창고 재고를 빼고 시편창고에 같은 LOT 번호로 더함 (창고이동 02)
--          입고·출고 이력은 거래명세서(INVOICEKEY) 없이 남김 (ERP 송신에서 거래명세서 단위 이력과 섞이지 않게)
-- Create: 2026-11-12
-- Modify: 2026-11-19: 같은 품목은 COMOUT·COMIN 1건으로 묶고 LOT 상세만 LOT 마다 남김
-- *****************************************************************************
  IN $INVOICEKEY    VARCHAR(50),
  IN $FROMWARECD    VARCHAR(20),    -- 출발창고. 비우면 거래명세서 입고이력(MTRIN) 의 입고창고
  IN $MOVEDATE      VARCHAR(10)     -- 이동일자
-- *****************************************************************************
)
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************

  DECLARE _$TESTWARE  VARCHAR(20) DEFAULT '04S132_N';   -- 2공장 시편창고
  DECLARE _$LIST      MEDIUMTEXT;
  DECLARE _$LOTKEY    VARCHAR(100);
  DECLARE _$ITEMID    VARCHAR(100);
  DECLARE _$FROMWARE  VARCHAR(20);
  DECLARE _$TESTQTY   DECIMAL(20, 8);
  DECLARE _$LOTQTY    DECIMAL(20, 8);
  DECLARE _$DSTQTY    DECIMAL(20, 8);
  DECLARE _$PRCCD     VARCHAR(100);
  DECLARE _$GROUPKEY  VARCHAR(100);
  DECLARE _$OUTKEY    VARCHAR(100);
  DECLARE _$INKEY     VARCHAR(100);
  DECLARE _$MOVETIME  VARCHAR(19);

-- ****************************************************************************
IF IFNULL(@ERRMSG, '') = '' THEN
-- ****************************************************************************

  SET _$LIST = IFNULL((SELECT GROUP_CONCAT(MTRCUST_INVOICE_DETAIL.LOTKEY ORDER BY MTRCUST_INVOICE_DETAIL.LOTKEY ASC SEPARATOR '»')
                         FROM MTRCUST_INVOICE_DETAIL
                        WHERE MTRCUST_INVOICE_DETAIL.INVOICEKEY = $INVOICEKEY
                          AND IFNULL(MTRCUST_INVOICE_DETAIL.TESTQTY, 0) > 0), '');

  IF _$LIST = '' THEN
    LEAVE PROC;   -- 시편수량 없음
  END IF;

  SET _$GROUPKEY = GETKEY('GETGROUPKEY');
  SET _$MOVETIME = CONCAT(LEFT(IF(IFNULL($MOVEDATE, '') = '', GETDATE(), $MOVEDATE), 10), ' ', RIGHT(GETTIME(), 8));

  DROP TEMPORARY TABLE IF EXISTS TEMP_TESTMOVE_ITEMKEY;
  CREATE TEMPORARY TABLE TEMP_TESTMOVE_ITEMKEY (
    ITEMID    VARCHAR(100) NOT NULL,
    FROMWARE  VARCHAR(20)  NOT NULL,
    OUTKEY    VARCHAR(100) NOT NULL,
    INKEY     VARCHAR(100) NOT NULL,
    PRIMARY KEY (ITEMID, FROMWARE)
  );

  WHILE LENGTH(IFNULL(_$LIST, '')) > 0 DO
    CALL COMSPLIT(_$LIST, _$LOTKEY);

    IF IFNULL(_$LOTKEY, '') <> '' THEN

      SELECT MTRCUST_INVOICE_DETAIL.TESTQTY, MTRCUST_INVOICE_DETAIL.ITEMID
        INTO _$TESTQTY, _$ITEMID
        FROM MTRCUST_INVOICE_DETAIL
       WHERE MTRCUST_INVOICE_DETAIL.INVOICEKEY = $INVOICEKEY
         AND MTRCUST_INVOICE_DETAIL.LOTKEY = _$LOTKEY;

      SET _$FROMWARE = IF(IFNULL($FROMWARECD, '') <> '', $FROMWARECD,
                          IFNULL((SELECT MTRIN.WARECD
                                    FROM MTRIN
                                   INNER JOIN MTRINLOT ON MTRINLOT.MTRINKEY = MTRIN.MTRINKEY
                                   WHERE MTRIN.INVOICEKEY = $INVOICEKEY
                                     AND MTRINLOT.LOTKEY = _$LOTKEY
                                   LIMIT 1), ''));

      IF IFNULL(_$FROMWARE, '') = '' THEN
        CALL COMERR(CONCAT('시편을 뺄 창고를 찾을 수 없습니다.', '\n- 로트번호: ', _$LOTKEY));
        LEAVE PROC;
      END IF;

      SET _$LOTQTY = NULL;
      SELECT COMLOT.LOTQTY, COMLOT.PRCCD
        INTO _$LOTQTY, _$PRCCD
        FROM COMLOT
       WHERE COMLOT.LOTKEY = _$LOTKEY
         AND COMLOT.WARECD = _$FROMWARE;

      IF _$LOTQTY IS NULL OR _$LOTQTY < _$TESTQTY THEN
        CALL COMERR(CONCAT('시편수량이 재고보다 많습니다.', '\n- 로트번호: ', _$LOTKEY));
        LEAVE PROC;
      END IF;

      -- 품목(+출발창고)별 출고(COMOUT)·입고(COMIN) 1건 : 첫 LOT 이면 새로 만들고, 같은 품목의 다음 LOT 은 수량만 더함
      SET _$OUTKEY = NULL;
      SET _$INKEY  = NULL;
      SELECT TEMP_TESTMOVE_ITEMKEY.OUTKEY, TEMP_TESTMOVE_ITEMKEY.INKEY
        INTO _$OUTKEY, _$INKEY
        FROM TEMP_TESTMOVE_ITEMKEY
       WHERE TEMP_TESTMOVE_ITEMKEY.ITEMID = _$ITEMID
         AND TEMP_TESTMOVE_ITEMKEY.FROMWARE = _$FROMWARE;

      IF _$OUTKEY IS NULL THEN
        SET _$OUTKEY = GETKEY('OUTKEY');
        SET _$INKEY  = GETKEY('INKEY');

        -- INTP, OUTTP : 025	창고이동(무상사급 시편입고) (2026-11-23 신정수)

        INSERT INTO TEMP_TESTMOVE_ITEMKEY (ITEMID, FROMWARE, OUTKEY, INKEY) VALUES (_$ITEMID, _$FROMWARE, _$OUTKEY, _$INKEY);

        INSERT INTO COMOUT (OUTKEY, WARECD, OUTTP, OUTDATE, OUTQTY, ITEMID, PRCCD, EMPCD, GROUPKEY, RTIME, REMP, RPRG)
        VALUES (_$OUTKEY, _$FROMWARE, '025', LEFT(_$MOVETIME, 10), _$TESTQTY, _$ITEMID, _$PRCCD, CALLEMP(), _$GROUPKEY, CALLTIME(), CALLEMP(), CALLPRG());

        INSERT INTO COMIN (INKEY, WARECD, INTP, INDATE, INQTY, ITEMID, PRCCD, EMPCD, GROUPKEY, RTIME, REMP, RPRG)
        VALUES (_$INKEY, _$TESTWARE, '025', LEFT(_$MOVETIME, 10), _$TESTQTY, _$ITEMID, _$PRCCD, CALLEMP(), _$GROUPKEY, CALLTIME(), CALLEMP(), CALLPRG());
      ELSE
        UPDATE COMOUT SET COMOUT.OUTQTY = COMOUT.OUTQTY + _$TESTQTY WHERE COMOUT.OUTKEY = _$OUTKEY;
        UPDATE COMIN  SET COMIN.INQTY   = COMIN.INQTY   + _$TESTQTY WHERE COMIN.INKEY   = _$INKEY;
      END IF;

      -- 1. 출고 : 출발창고 LOT 차감

      INSERT INTO COMOUTLOT (OUTKEY, LOTKEY, WARECD, OUTTP, OUTDATE, OUTQTY, PRCCD, ITEMID, OLDQTY, RTIME, REMP, RPRG)
      VALUES (_$OUTKEY, _$LOTKEY, _$FROMWARE, '025', LEFT(_$MOVETIME, 10), _$TESTQTY, _$PRCCD, _$ITEMID, _$LOTQTY, CALLTIME(), CALLEMP(), CALLPRG());

      UPDATE COMLOT
         SET COMLOT.LOTQTY = COMLOT.LOTQTY - _$TESTQTY
           , COMLOT.MTIME  = CALLTIME()
           , COMLOT.MEMP   = CALLEMP()
           , COMLOT.MPRG   = CALLPRG()
       WHERE COMLOT.LOTKEY = _$LOTKEY
         AND COMLOT.WARECD = _$FROMWARE;

      -- 2. 입고 : 시편창고에 같은 LOT 번호로 더함 (없으면 새로 만듦, 재고유형 시편 02)
      SET _$DSTQTY = IFNULL((SELECT COMLOT.LOTQTY FROM COMLOT WHERE COMLOT.LOTKEY = _$LOTKEY AND COMLOT.WARECD = _$TESTWARE), 0);

      INSERT INTO COMINLOT (INKEY, LOTKEY, WARECD, INTP, INDATE, INQTY, PRCCD, ITEMID, OLDQTY, RTIME, REMP, RPRG)
      VALUES (_$INKEY, _$LOTKEY, _$TESTWARE, '025', LEFT(_$MOVETIME, 10), _$TESTQTY, _$PRCCD, _$ITEMID, _$DSTQTY, CALLTIME(), CALLEMP(), CALLPRG());

      IF EXISTS (SELECT 1 FROM COMLOT WHERE COMLOT.LOTKEY = _$LOTKEY AND COMLOT.WARECD = _$TESTWARE) THEN
        UPDATE COMLOT
           SET COMLOT.LOTQTY = COMLOT.LOTQTY + _$TESTQTY
             , COMLOT.CRTQTY = COMLOT.CRTQTY + _$TESTQTY
             , COMLOT.MTIME  = CALLTIME()
             , COMLOT.MEMP   = CALLEMP()
             , COMLOT.MPRG   = CALLPRG()
         WHERE COMLOT.LOTKEY = _$LOTKEY
           AND COMLOT.WARECD = _$TESTWARE;
      ELSE
        INSERT INTO COMLOT (
            LOTKEY, WARECD, LABELCD, LOTQTY, HEATNO, ITEMID, PRCCD, CRTTIME, CRTQTY, PRDDATE, CUSTCD, CUSTLOTKEY, LOTTP, GROUPKEY
          , RTIME, REMP, RPRG)
        SELECT
            COMLOT.LOTKEY, _$TESTWARE, COMLOT.LABELCD, _$TESTQTY, COMLOT.HEATNO, COMLOT.ITEMID, COMLOT.PRCCD, _$MOVETIME, _$TESTQTY
          , COMLOT.PRDDATE, COMLOT.CUSTCD, COMLOT.CUSTLOTKEY, '02', _$GROUPKEY
          , CALLTIME(), CALLEMP(), CALLPRG()
        FROM COMLOT
        WHERE COMLOT.LOTKEY = _$LOTKEY
          AND COMLOT.WARECD = _$FROMWARE;
      END IF;

    END IF;
  END WHILE;

  DROP TEMPORARY TABLE IF EXISTS TEMP_TESTMOVE_ITEMKEY;

-- ****************************************************************************
END IF; END