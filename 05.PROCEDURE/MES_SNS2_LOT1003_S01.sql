CREATE DEFINER=`root`@`%`
PROCEDURE `MES_SNS2`.`LOT1003_S01`(
-- *****************************************************************************
-- Comment: 재고 실사,조정 이력조회
-- Create: 	2024-11-01  	생성 			이대규
-- Modify: 	2025-02-05 					이대규	실사관리 수량 변동 없는 부분 추가
-- 			2026-11-11 					한성수	마이그레이션 (품목 ITEMID·품목유형 ITEMCG·창고명 MSTWARE, 실사 INTP·OUTTP 08만 조회(재고조정 97은 기타입출고 ERP 송신 대상이라 제외), 행위구분 변동없음·실사입고·실사출고, 조정사유 COMIN·COMOUT.REMARK)
-- *****************************************************************************
  IN $SDATE           VARCHAR(10),
  IN $EDATE           VARCHAR(10),
  IN $WARECD          VARCHAR(100),
  IN $ITEMCG          VARCHAR(100),
  IN $ITEMID          VARCHAR(100),

-- *****************************************************************************
  IN $CALLTYPE        VARCHAR(50),
  IN $KEYWORD         VARCHAR(1000)
)
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  CASE $CALLTYPE
  -- *****************************************************************************
  WHEN 'LIST_COMLOT_INOUT' THEN -- 재고 실사,조정 이력조회 (변동없음 + 실사·조정 입고 + 실사·조정 출고)

    SELECT COMCHK_GROUP.CHKDATE AS INOUTDATE, '변동없음' AS ACTION, '' AS INOUTTP,
           COMCHK_GROUP.CHKWARECD AS WARECD, MSTWARE.WARENM,
           COMCHKLOT.CHKLOTKEY AS LOTKEY, COMCHKLOT.LOTCHKQTY AS INOUTQTY, '' AS ADJUSTWHY, COMCHKLOT.REMP AS EMPCD,
           MSTITEM.ITEMCG, MSTITEM.ITEMCD, MSTITEM.ITEMNM
    FROM COMCHK_GROUP
    INNER JOIN COMCHK
      ON COMCHK.CHKGROUPKEY = COMCHK_GROUP.CHKGROUPKEY
    LEFT JOIN COMCHKLOT
      ON COMCHKLOT.CHKKEY = COMCHK.CHKKEY
    INNER JOIN MSTITEM
      ON MSTITEM.ITEMID = COMCHK.CHKITEMCD
    LEFT JOIN MSTWARE
      ON MSTWARE.WARECD = COMCHK_GROUP.CHKWARECD
    WHERE COMCHK_GROUP.CHKDATE BETWEEN $SDATE AND $EDATE
      AND COMCHK_GROUP.CHKWARECD LIKE CONCAT('%', $WARECD, '%')
      AND MSTITEM.ITEMCG LIKE CONCAT('%', $ITEMCG, '%')
      AND COMCHKLOT.LOTCHKQTY = COMCHKLOT.LOTOLDQTY

    UNION ALL

    SELECT COMIN.INDATE AS INOUTDATE, '실사입고' AS ACTION, '입고' AS INOUTTP,
           COMIN.WARECD, MSTWARE.WARENM,
           COMINLOT.LOTKEY, COMINLOT.INQTY AS INOUTQTY, COMIN.REMARK AS ADJUSTWHY, COMINLOT.REMP AS EMPCD,
           MSTITEM.ITEMCG, MSTITEM.ITEMCD, MSTITEM.ITEMNM
    FROM COMIN
    LEFT JOIN COMINLOT
      ON COMINLOT.INKEY = COMIN.INKEY
    INNER JOIN MSTITEM
      ON MSTITEM.ITEMID = COMIN.ITEMID
    LEFT JOIN MSTWARE
      ON MSTWARE.WARECD = COMIN.WARECD
    WHERE COMIN.INDATE BETWEEN $SDATE AND $EDATE
      AND COMIN.INTP = '08'
      AND COMIN.WARECD LIKE CONCAT('%', $WARECD, '%')
      AND ($ITEMID = '' OR COMIN.ITEMID = $ITEMID)
      AND MSTITEM.ITEMCG LIKE CONCAT('%', $ITEMCG, '%')

    UNION ALL

    SELECT COMOUT.OUTDATE AS INOUTDATE, '실사출고' AS ACTION, '출고' AS INOUTTP,
           COMOUT.WARECD, MSTWARE.WARENM,
           COMOUTLOT.LOTKEY, COMOUTLOT.OUTQTY AS INOUTQTY, COMOUT.REMARK AS ADJUSTWHY, COMOUTLOT.REMP AS EMPCD,
           MSTITEM.ITEMCG, MSTITEM.ITEMCD, MSTITEM.ITEMNM
    FROM COMOUT
    LEFT JOIN COMOUTLOT
      ON COMOUTLOT.OUTKEY = COMOUT.OUTKEY
    INNER JOIN MSTITEM
      ON MSTITEM.ITEMID = COMOUT.ITEMID
    LEFT JOIN MSTWARE
      ON MSTWARE.WARECD = COMOUT.WARECD
    WHERE COMOUT.OUTDATE BETWEEN $SDATE AND $EDATE
      AND COMOUT.OUTTP = '08'
      AND COMOUT.WARECD LIKE CONCAT('%', $WARECD, '%')
      AND ($ITEMID = '' OR COMOUT.ITEMID = $ITEMID)
      AND MSTITEM.ITEMCG LIKE CONCAT('%', $ITEMCG, '%')

    ORDER BY INOUTDATE, ACTION, INOUTTP, WARENM, LOTKEY;

  -- *****************************************************************************
  END CASE;
END
