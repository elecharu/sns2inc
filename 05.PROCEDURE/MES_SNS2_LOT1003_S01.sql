CREATE DEFINER=`root`@`%`
PROCEDURE `MES_SNS2`.`LOT1003_S01`(
-- *****************************************************************************
-- Comment: 재고 실사,조정 이력조회
-- Create: 	2024-11-01  	생성 			이대규
-- Modify: 	2025-02-05 					이대규	실사관리 수량 변동 없는 부분 추가
-- 			2026-11-11 					한성수	재고실사 이력조회 마이그레이션 (원본 UNION ALL 구조 유지, 실사 INTP·OUTTP 08만 조회, 행위구분 재고정정)
-- *****************************************************************************
  IN $SDATE           VARCHAR(10),
  IN $EDATE           VARCHAR(10),
  IN $WARECD          VARCHAR(100),
  IN $ITEMCG          VARCHAR(100),
  IN $ITEMID          VARCHAR(100),

-- *****************************************************************************
  IN $CALLTYPE        VARCHAR(50),
  IN $KEYWORD         VARCHAR(1000)
)
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  CASE $CALLTYPE
  -- *****************************************************************************
  WHEN 'LIST_COMLOT_INOUT' THEN -- 재고 실사 이력조회

    IF $WARECD = '' THEN
      CALL COMERR('창고를 선택하세요.');
      LEAVE PROC;
    END IF;

    SELECT COMCHK_GROUP.CHKDATE AS INOUTDATE, '재고정정' AS ACTION, '변동없음' AS INOUTTP,
           COMCHK_GROUP.CHKWARECD AS WARECD, MSTWARE.WARENM,
           COMCHKLOT.CHKLOTKEY AS LOTKEY, COMCHKLOT.LOTCHKQTY AS INOUTQTY, MSTEMP.EMPNM,
           MSTITEM.ITEMCG, MSTITEM.ITEMCD, MSTITEM.ITEMNM
    FROM COMCHK_GROUP
    INNER JOIN COMCHK
      ON COMCHK.CHKGROUPKEY = COMCHK_GROUP.CHKGROUPKEY
    INNER JOIN COMCHKLOT
      ON COMCHKLOT.CHKKEY = COMCHK.CHKKEY
    INNER JOIN MSTITEM
      ON MSTITEM.ITEMID = COMCHK.CHKITEMCD
    LEFT JOIN MSTWARE
      ON MSTWARE.WARECD = COMCHK_GROUP.CHKWARECD
    LEFT JOIN SYSUSER
      ON SYSUSER.USERID = COMCHKLOT.REMP
    LEFT JOIN MSTEMP
      ON MSTEMP.EMPCD = SYSUSER.EMPCD
    WHERE COMCHK_GROUP.CHKDATE BETWEEN $SDATE AND $EDATE
      AND COMCHK_GROUP.CHKWARECD = $WARECD
      AND ($ITEMID = '' OR COMCHK.CHKITEMCD = $ITEMID)
      AND MSTITEM.ITEMCG LIKE CONCAT('%', $ITEMCG, '%')
      AND COMCHKLOT.LOTCHKQTY = COMCHKLOT.LOTOLDQTY

    UNION ALL

    SELECT COMIN.INDATE AS INOUTDATE, '재고정정' AS ACTION, '입고' AS INOUTTP,
           COMIN.WARECD, MSTWARE.WARENM,
           COMINLOT.LOTKEY, COMINLOT.INQTY AS INOUTQTY, MSTEMP.EMPNM,
           MSTITEM.ITEMCG, MSTITEM.ITEMCD, MSTITEM.ITEMNM
    FROM COMIN
    INNER JOIN COMINLOT
      ON COMINLOT.INKEY = COMIN.INKEY
    INNER JOIN MSTITEM
      ON MSTITEM.ITEMID = COMIN.ITEMID
    LEFT JOIN MSTWARE
      ON MSTWARE.WARECD = COMIN.WARECD
    LEFT JOIN MSTEMP
      ON MSTEMP.EMPCD = COMIN.EMPCD
    WHERE COMIN.INDATE BETWEEN $SDATE AND $EDATE
      AND COMIN.INTP = '08'
      AND COMIN.WARECD = $WARECD
      AND ($ITEMID = '' OR COMIN.ITEMID = $ITEMID)
      AND MSTITEM.ITEMCG LIKE CONCAT('%', $ITEMCG, '%')

    UNION ALL

    SELECT COMOUT.OUTDATE AS INOUTDATE, '재고정정' AS ACTION, '출고' AS INOUTTP,
           COMOUT.WARECD, MSTWARE.WARENM,
           COMOUTLOT.LOTKEY, COMOUTLOT.OUTQTY AS INOUTQTY, MSTEMP.EMPNM,
           MSTITEM.ITEMCG, MSTITEM.ITEMCD, MSTITEM.ITEMNM
    FROM COMOUT
    INNER JOIN COMOUTLOT
      ON COMOUTLOT.OUTKEY = COMOUT.OUTKEY
    INNER JOIN MSTITEM
      ON MSTITEM.ITEMID = COMOUT.ITEMID
    LEFT JOIN MSTWARE
      ON MSTWARE.WARECD = COMOUT.WARECD
    LEFT JOIN MSTEMP
      ON MSTEMP.EMPCD = COMOUT.EMPCD
    WHERE COMOUT.OUTDATE BETWEEN $SDATE AND $EDATE
      AND COMOUT.OUTTP = '08'
      AND COMOUT.WARECD = $WARECD
      AND ($ITEMID = '' OR COMOUT.ITEMID = $ITEMID)
      AND MSTITEM.ITEMCG LIKE CONCAT('%', $ITEMCG, '%')

    ORDER BY INOUTDATE, INOUTTP, WARENM, LOTKEY;

  -- *****************************************************************************
  END CASE;
END
