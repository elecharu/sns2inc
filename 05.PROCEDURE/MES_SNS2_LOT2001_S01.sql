CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.LOT2001_S01(
-- *****************************************************************************
-- Comment: 로트추적 조회 (웹)
--          ) LIST : 조회한 로트의 계보. 조회로트(0) + 역추적(투입된 로트, 원소재까지) + 정추적(이 로트를 쓴 곳, 출하까지)
--                   역추적 = 사내 실적(PRDRSTLOT → PRDRSTUSE), 외주 실적(OSCRSTLOT → OSCRSTUSE), 둘 다 없으면 자재(원소재)
--                   정추적 = 이 로트를 투입한 사내·외주 실적의 실적로트 + 이 로트가 나간 출하(SALOUTLOT)
--                   투입로트가 여러 개면 모두 펼친다. 30단계 넘으면 끊음 (잘못된 순환 방지)
--                   줄 순서는 트리 모양 (PATH = 부모 PATH + 6자리 순번)
--          ) INFO : 선택한 줄의 상세 (결과: 0 기본정보 '항목/내용' 줄 / 1 입출고 이력 / 2 품질 이력)
--                   자주검사(TQMRST)는 작업키가 없어서 PRD5001_S01 과 같은 기준
--                   (같은 라인·품목에서 작업시작~작업종료 사이 검사)으로 찾는다
--          역추적 로직은 TML2010_R01 PRINT_MOVE(공정이동표)와 같은 방식
-- Create: 2026-11-25
-- Modify: 2026-11-25 INFO 기본정보의 CTE·파생테이블을 지역변수·임시테이블로 변경 (Unknown column '$LOTKEY' 오류)
--         2026-11-25 LIST 결과를 역추적·정추적 2개로 나눔, 작업장/거래처 칸을 작업장·라인·거래처로 나눔, 출하 줄에 '(출하번호)' (사용자 요청)
-- *****************************************************************************
  IN $KEYTP VARCHAR(10),        -- 추적번호 종류 (LOT 로트번호 / LABEL 라벨번호 / SALOUT 출하번호)
  IN $KEYVAL VARCHAR(100),      -- 추적번호
  IN $DIRTP VARCHAR(10),        -- 방향 (ALL 양방향 / BACK 역추적 / FWD 정추적)
  IN $LOTKEY VARCHAR(100),      -- INFO: 선택 줄의 로트번호
  IN $NODETP VARCHAR(10),       -- INFO: 선택 줄의 구분 (P 생산 / O 외주 / M 자재 / S 출하)
  IN $RSTKEY VARCHAR(100),      -- INFO: 선택 줄의 실적번호·입고번호·출하번호
-- *****************************************************************************
  IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  DECLARE _$LVL INT DEFAULT 0;
  DECLARE _$EQMCD VARCHAR(100);
  DECLARE _$ITEMID VARCHAR(100);
  DECLARE _$WORKSTIME VARCHAR(19);
  DECLARE _$WORKETIME VARCHAR(19);
  DECLARE _$ITEMCD VARCHAR(100);       -- INFO 기본정보
  DECLARE _$ITEMNM VARCHAR(200);
  DECLARE _$ITEMSPEC VARCHAR(200);
  DECLARE _$PRCNM VARCHAR(100);
  DECLARE _$PLACENM VARCHAR(200);
  DECLARE _$EQMNM VARCHAR(100);
  DECLARE _$WORKDATE VARCHAR(10);
  DECLARE _$DNTPNM VARCHAR(20);
  DECLARE _$WORKTIME VARCHAR(50);
  DECLARE _$EMPNM VARCHAR(500);
  DECLARE _$GOODQTY DECIMAL(20, 8);
  DECLARE _$BADQTY DECIMAL(20, 8);
  DECLARE _$LABELKEY VARCHAR(100);
  DECLARE _$HEATNO VARCHAR(100);
  DECLARE _$STOCKQTY DECIMAL(20, 8);
  DECLARE _$OUTYNNM VARCHAR(10);
-- *****************************************************************************
CASE $CALLTYPE
-- ****************************************************************************
WHEN 'LIST' THEN  -- 로트 계보

  IF IFNULL($KEYVAL, '') = '' THEN
    CALL COMERR('추적번호를 입력하세요.');
    LEAVE PROC;
  END IF;

  -- 1. 시작 로트 (라벨번호 = 그 라벨의 실적로트, 출하번호 = 그 출하에 나간 로트 전부)
  DROP TEMPORARY TABLE IF EXISTS TMP_LOT2001_START;
  CREATE TEMPORARY TABLE TMP_LOT2001_START (
    LOTKEY VARCHAR(100) NOT NULL
  );

  IF $KEYTP = 'LABEL' THEN
    INSERT INTO TMP_LOT2001_START (LOTKEY)
    SELECT DISTINCT PRDRSTLOT.LOTKEY
    FROM PRDRSTLOT
    WHERE PRDRSTLOT.LABELKEY = $KEYVAL;
  ELSEIF $KEYTP = 'SALOUT' THEN
    INSERT INTO TMP_LOT2001_START (LOTKEY)
    SELECT DISTINCT SALOUTLOT.LOTKEY
    FROM SALOUTLOT
    WHERE SALOUTLOT.SALOUTKEY = $KEYVAL;
  ELSE
    INSERT INTO TMP_LOT2001_START (LOTKEY)
    SELECT $KEYVAL
    FROM DUAL
    WHERE EXISTS (SELECT 1 FROM COMLOT WHERE COMLOT.LOTKEY = $KEYVAL)
       OR EXISTS (SELECT 1 FROM PRDRSTLOT WHERE PRDRSTLOT.LOTKEY = $KEYVAL)
       OR EXISTS (SELECT 1 FROM OSCRSTLOT WHERE OSCRSTLOT.LOTKEY = $KEYVAL);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM TMP_LOT2001_START) THEN
    CALL COMERR(CONCAT('찾는 로트가 없습니다.', '\n- 추적번호: ', $KEYVAL));
    DROP TEMPORARY TABLE IF EXISTS TMP_LOT2001_START;
    LEAVE PROC;
  END IF;

  -- 2. 계보 (DIRTP: C 조회로트 / B 역추적 / F 정추적, NODETP: P 생산 / O 외주 / M 자재 / S 출하)
  DROP TEMPORARY TABLE IF EXISTS TMP_LOT2001_TRACE;
  CREATE TEMPORARY TABLE TMP_LOT2001_TRACE (
    SEQ     INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    DIRTP   VARCHAR(1) NOT NULL,
    LVL     INT NOT NULL,
    LOTKEY  VARCHAR(100) NOT NULL,
    NODETP  VARCHAR(1) NOT NULL,
    RSTKEY  VARCHAR(100) NOT NULL,
    USEQTY  DECIMAL(20, 8) NULL,     -- 역추적: 부모 실적이 이 로트를 쓴 양 / 정추적: 이 실적이 부모 로트를 쓴 양, 출하는 출하수량
    PATH    VARCHAR(2000) NOT NULL
  );

  DROP TEMPORARY TABLE IF EXISTS TMP_LOT2001_CUR;
  CREATE TEMPORARY TABLE TMP_LOT2001_CUR (
    LOTKEY  VARCHAR(100) NOT NULL,
    NODETP  VARCHAR(1) NOT NULL,
    RSTKEY  VARCHAR(100) NOT NULL,
    PATH    VARCHAR(2000) NOT NULL
  );

  DROP TEMPORARY TABLE IF EXISTS TMP_LOT2001_NEXT;
  CREATE TEMPORARY TABLE TMP_LOT2001_NEXT (
    PATH    VARCHAR(2000) NOT NULL,
    LOTKEY  VARCHAR(100) NOT NULL,
    NODETP  VARCHAR(1) NOT NULL,
    RSTKEY  VARCHAR(100) NOT NULL,
    USEQTY  DECIMAL(20, 8) NULL
  );

  -- 조회로트: 그 로트를 만든 실적 (사내 → 외주 → 자재 입고 순으로 찾음)
  INSERT INTO TMP_LOT2001_TRACE (DIRTP, LVL, LOTKEY, NODETP, RSTKEY, USEQTY, PATH)
  SELECT
      'C'
    , 0
    , STARTLOT.LOTKEY
    , IF(STARTLOT.PRDRSTKEY <> '', 'P', IF(STARTLOT.OSCRSTKEY <> '', 'O', 'M'))
    , IF(STARTLOT.PRDRSTKEY <> '', STARTLOT.PRDRSTKEY, IF(STARTLOT.OSCRSTKEY <> '', STARTLOT.OSCRSTKEY, STARTLOT.MTRINKEY))
    , NULL
    , ''
  FROM (SELECT
            TMP_LOT2001_START.LOTKEY
          , IFNULL((SELECT PRDRSTLOT.PRDRSTKEY FROM PRDRSTLOT WHERE PRDRSTLOT.LOTKEY = TMP_LOT2001_START.LOTKEY LIMIT 1), '') AS PRDRSTKEY
          , IFNULL((SELECT OSCRSTLOT.OSCRSTKEY FROM OSCRSTLOT WHERE OSCRSTLOT.LOTKEY = TMP_LOT2001_START.LOTKEY LIMIT 1), '') AS OSCRSTKEY
          , IFNULL((SELECT COMLOT.MTRINKEY FROM COMLOT WHERE COMLOT.LOTKEY = TMP_LOT2001_START.LOTKEY AND IFNULL(COMLOT.MTRINKEY, '') <> '' LIMIT 1), '') AS MTRINKEY
        FROM TMP_LOT2001_START) AS STARTLOT
  ORDER BY STARTLOT.LOTKEY;

  UPDATE TMP_LOT2001_TRACE
  SET PATH = LPAD(TMP_LOT2001_TRACE.SEQ, 6, '0')
  WHERE TMP_LOT2001_TRACE.DIRTP = 'C';

  -- 2-1. 역추적: 로트를 만든 실적의 투입로트를 거슬러 올라감
  IF IFNULL($DIRTP, '') IN ('', 'ALL', 'BACK') THEN
    DELETE FROM TMP_LOT2001_CUR;

    INSERT INTO TMP_LOT2001_CUR (LOTKEY, NODETP, RSTKEY, PATH)
    SELECT TMP_LOT2001_TRACE.LOTKEY, TMP_LOT2001_TRACE.NODETP, TMP_LOT2001_TRACE.RSTKEY, TMP_LOT2001_TRACE.PATH
    FROM TMP_LOT2001_TRACE
    WHERE TMP_LOT2001_TRACE.DIRTP = 'C'
      AND TMP_LOT2001_TRACE.NODETP IN ('P', 'O');

    SET _$LVL = 1;
    WHILE _$LVL <= 30 AND EXISTS (SELECT 1 FROM TMP_LOT2001_CUR) DO
      DELETE FROM TMP_LOT2001_NEXT;

      INSERT INTO TMP_LOT2001_NEXT (PATH, LOTKEY, NODETP, RSTKEY, USEQTY)
      SELECT TMP_LOT2001_CUR.PATH, PRDRSTUSE.USELOTKEY, '', '', SUM(PRDRSTUSE.USEQTY)
      FROM PRDRSTUSE
      INNER JOIN TMP_LOT2001_CUR
        ON TMP_LOT2001_CUR.NODETP = 'P'
       AND TMP_LOT2001_CUR.RSTKEY = PRDRSTUSE.PRDRSTKEY
      GROUP BY TMP_LOT2001_CUR.PATH, PRDRSTUSE.USELOTKEY;

      INSERT INTO TMP_LOT2001_NEXT (PATH, LOTKEY, NODETP, RSTKEY, USEQTY)
      SELECT TMP_LOT2001_CUR.PATH, OSCRSTUSE.USELOTKEY, '', '', SUM(OSCRSTUSE.USEQTY)
      FROM OSCRSTUSE
      INNER JOIN TMP_LOT2001_CUR
        ON TMP_LOT2001_CUR.NODETP = 'O'
       AND TMP_LOT2001_CUR.RSTKEY = OSCRSTUSE.OSCRSTKEY
      GROUP BY TMP_LOT2001_CUR.PATH, OSCRSTUSE.USELOTKEY;

      -- 투입로트마다 그 로트를 만든 실적 (사내 → 외주 → 자재 입고 순)
      INSERT INTO TMP_LOT2001_TRACE (DIRTP, LVL, LOTKEY, NODETP, RSTKEY, USEQTY, PATH)
      SELECT
          'B'
        , _$LVL
        , NEXTLOT.LOTKEY
        , IF(NEXTLOT.PRDRSTKEY <> '', 'P', IF(NEXTLOT.OSCRSTKEY <> '', 'O', 'M'))
        , IF(NEXTLOT.PRDRSTKEY <> '', NEXTLOT.PRDRSTKEY, IF(NEXTLOT.OSCRSTKEY <> '', NEXTLOT.OSCRSTKEY, NEXTLOT.MTRINKEY))
        , NEXTLOT.USEQTY
        , NEXTLOT.PATH
      FROM (SELECT
                TMP_LOT2001_NEXT.PATH
              , TMP_LOT2001_NEXT.LOTKEY
              , TMP_LOT2001_NEXT.USEQTY
              , IFNULL((SELECT PRDRSTLOT.PRDRSTKEY FROM PRDRSTLOT WHERE PRDRSTLOT.LOTKEY = TMP_LOT2001_NEXT.LOTKEY LIMIT 1), '') AS PRDRSTKEY
              , IFNULL((SELECT OSCRSTLOT.OSCRSTKEY FROM OSCRSTLOT WHERE OSCRSTLOT.LOTKEY = TMP_LOT2001_NEXT.LOTKEY LIMIT 1), '') AS OSCRSTKEY
              , IFNULL((SELECT COMLOT.MTRINKEY FROM COMLOT WHERE COMLOT.LOTKEY = TMP_LOT2001_NEXT.LOTKEY AND IFNULL(COMLOT.MTRINKEY, '') <> '' LIMIT 1), '') AS MTRINKEY
            FROM TMP_LOT2001_NEXT) AS NEXTLOT
      ORDER BY NEXTLOT.PATH, NEXTLOT.LOTKEY;

      UPDATE TMP_LOT2001_TRACE
      SET PATH = CONCAT(TMP_LOT2001_TRACE.PATH, LPAD(TMP_LOT2001_TRACE.SEQ, 6, '0'))
      WHERE TMP_LOT2001_TRACE.DIRTP = 'B'
        AND TMP_LOT2001_TRACE.LVL = _$LVL;

      DELETE FROM TMP_LOT2001_CUR;

      INSERT INTO TMP_LOT2001_CUR (LOTKEY, NODETP, RSTKEY, PATH)
      SELECT TMP_LOT2001_TRACE.LOTKEY, TMP_LOT2001_TRACE.NODETP, TMP_LOT2001_TRACE.RSTKEY, TMP_LOT2001_TRACE.PATH
      FROM TMP_LOT2001_TRACE
      WHERE TMP_LOT2001_TRACE.DIRTP = 'B'
        AND TMP_LOT2001_TRACE.LVL = _$LVL
        AND TMP_LOT2001_TRACE.NODETP IN ('P', 'O');

      SET _$LVL = _$LVL + 1;
    END WHILE;
  END IF;

  -- 2-2. 정추적: 이 로트를 투입한 실적의 실적로트, 이 로트가 나간 출하를 따라 내려감 (출하는 끝)
  IF IFNULL($DIRTP, '') IN ('', 'ALL', 'FWD') THEN
    DELETE FROM TMP_LOT2001_CUR;

    INSERT INTO TMP_LOT2001_CUR (LOTKEY, NODETP, RSTKEY, PATH)
    SELECT TMP_LOT2001_TRACE.LOTKEY, TMP_LOT2001_TRACE.NODETP, TMP_LOT2001_TRACE.RSTKEY, TMP_LOT2001_TRACE.PATH
    FROM TMP_LOT2001_TRACE
    WHERE TMP_LOT2001_TRACE.DIRTP = 'C';

    SET _$LVL = 1;
    WHILE _$LVL <= 30 AND EXISTS (SELECT 1 FROM TMP_LOT2001_CUR) DO
      DELETE FROM TMP_LOT2001_NEXT;

      INSERT INTO TMP_LOT2001_NEXT (PATH, LOTKEY, NODETP, RSTKEY, USEQTY)
      SELECT TMP_LOT2001_CUR.PATH, PRDRSTLOT.LOTKEY, 'P', PRDRSTLOT.PRDRSTKEY, SUM(PRDRSTUSE.USEQTY)
      FROM PRDRSTUSE
      INNER JOIN TMP_LOT2001_CUR
        ON TMP_LOT2001_CUR.LOTKEY = PRDRSTUSE.USELOTKEY
      INNER JOIN PRDRSTLOT
        ON PRDRSTLOT.PRDRSTKEY = PRDRSTUSE.PRDRSTKEY
      GROUP BY TMP_LOT2001_CUR.PATH, PRDRSTLOT.LOTKEY, PRDRSTLOT.PRDRSTKEY;

      INSERT INTO TMP_LOT2001_NEXT (PATH, LOTKEY, NODETP, RSTKEY, USEQTY)
      SELECT TMP_LOT2001_CUR.PATH, OSCRSTLOT.LOTKEY, 'O', OSCRSTLOT.OSCRSTKEY, SUM(OSCRSTUSE.USEQTY)
      FROM OSCRSTUSE
      INNER JOIN TMP_LOT2001_CUR
        ON TMP_LOT2001_CUR.LOTKEY = OSCRSTUSE.USELOTKEY
      INNER JOIN OSCRSTLOT
        ON OSCRSTLOT.OSCRSTKEY = OSCRSTUSE.OSCRSTKEY
      GROUP BY TMP_LOT2001_CUR.PATH, OSCRSTLOT.LOTKEY, OSCRSTLOT.OSCRSTKEY;

      INSERT INTO TMP_LOT2001_NEXT (PATH, LOTKEY, NODETP, RSTKEY, USEQTY)
      SELECT TMP_LOT2001_CUR.PATH, TMP_LOT2001_CUR.LOTKEY, 'S', SALOUTLOT.SALOUTKEY, SUM(SALOUTLOT.LOTQTY)
      FROM SALOUTLOT
      INNER JOIN TMP_LOT2001_CUR
        ON TMP_LOT2001_CUR.LOTKEY = SALOUTLOT.LOTKEY
      GROUP BY TMP_LOT2001_CUR.PATH, TMP_LOT2001_CUR.LOTKEY, SALOUTLOT.SALOUTKEY;

      INSERT INTO TMP_LOT2001_TRACE (DIRTP, LVL, LOTKEY, NODETP, RSTKEY, USEQTY, PATH)
      SELECT
          'F'
        , _$LVL
        , TMP_LOT2001_NEXT.LOTKEY
        , TMP_LOT2001_NEXT.NODETP
        , TMP_LOT2001_NEXT.RSTKEY
        , TMP_LOT2001_NEXT.USEQTY
        , TMP_LOT2001_NEXT.PATH
      FROM TMP_LOT2001_NEXT
      ORDER BY TMP_LOT2001_NEXT.PATH, IF(TMP_LOT2001_NEXT.NODETP = 'S', 1, 0), TMP_LOT2001_NEXT.LOTKEY, TMP_LOT2001_NEXT.RSTKEY;

      UPDATE TMP_LOT2001_TRACE
      SET PATH = CONCAT(TMP_LOT2001_TRACE.PATH, LPAD(TMP_LOT2001_TRACE.SEQ, 6, '0'))
      WHERE TMP_LOT2001_TRACE.DIRTP = 'F'
        AND TMP_LOT2001_TRACE.LVL = _$LVL;

      DELETE FROM TMP_LOT2001_CUR;

      INSERT INTO TMP_LOT2001_CUR (LOTKEY, NODETP, RSTKEY, PATH)
      SELECT TMP_LOT2001_TRACE.LOTKEY, TMP_LOT2001_TRACE.NODETP, TMP_LOT2001_TRACE.RSTKEY, TMP_LOT2001_TRACE.PATH
      FROM TMP_LOT2001_TRACE
      WHERE TMP_LOT2001_TRACE.DIRTP = 'F'
        AND TMP_LOT2001_TRACE.LVL = _$LVL
        AND TMP_LOT2001_TRACE.NODETP IN ('P', 'O');

      SET _$LVL = _$LVL + 1;
    END WHILE;
  END IF;

  -- 3. 결과: 로트번호 칸은 단계만큼 들여쓰기 (전각 공백), 출하 줄은 '출하번호 (출하번호)'
  --    결과 0 = 역추적 그리드 (조회로트 + 역추적), 결과 1 = 정추적 그리드 (조회로트 + 정추적)
  --    두 번 내리려고 결과를 임시테이블에 한 번 만들어 둔다
  DROP TEMPORARY TABLE IF EXISTS TMP_LOT2001_RESULT;
  CREATE TEMPORARY TABLE TMP_LOT2001_RESULT (
    DIRTP     VARCHAR(1) NOT NULL,
    PATH      VARCHAR(2000) NOT NULL,
    LVL       INT NOT NULL,
    LOTDISP   VARCHAR(300) NOT NULL,
    NODETPNM  VARCHAR(20) NOT NULL,
    ITEMCD    VARCHAR(100) NULL,
    ITEMNM    VARCHAR(200) NULL,
    LINENM    VARCHAR(200) NULL,
    PRCNM     VARCHAR(100) NULL,
    EQMNM     VARCHAR(100) NULL,
    CUSTNM    VARCHAR(200) NULL,
    WORKDATE  VARCHAR(10) NULL,
    LOTQTY    DECIMAL(20, 8) NULL,
    USEQTY    DECIMAL(20, 8) NULL,
    STOCKQTY  DECIMAL(20, 8) NULL,
    LOTKEY    VARCHAR(100) NOT NULL,
    NODETP    VARCHAR(1) NOT NULL,
    RSTKEY    VARCHAR(100) NOT NULL
  );

  INSERT INTO TMP_LOT2001_RESULT (
      DIRTP, PATH, LVL, LOTDISP, NODETPNM
    , ITEMCD, ITEMNM, LINENM, PRCNM, EQMNM
    , CUSTNM, WORKDATE, LOTQTY, USEQTY, STOCKQTY
    , LOTKEY, NODETP, RSTKEY)
  SELECT
      TMP_LOT2001_TRACE.DIRTP
    , TMP_LOT2001_TRACE.PATH
    , IF(TMP_LOT2001_TRACE.DIRTP = 'B', -TMP_LOT2001_TRACE.LVL, TMP_LOT2001_TRACE.LVL) AS LVL
    , CONCAT(REPEAT('　', TMP_LOT2001_TRACE.LVL), IF(TMP_LOT2001_TRACE.LVL > 0, '└ ', '')
           , IF(TMP_LOT2001_TRACE.NODETP = 'S', CONCAT(TMP_LOT2001_TRACE.RSTKEY, ' (출하번호)'), TMP_LOT2001_TRACE.LOTKEY)) AS LOTDISP
    , CASE TMP_LOT2001_TRACE.NODETP
        WHEN 'P' THEN '생산'
        WHEN 'O' THEN '외주'
        WHEN 'M' THEN '자재'
        WHEN 'S' THEN IF(SALOUT.OUTYN = 'Y', '출하', '출하(미확정)')
      ELSE '' END AS NODETPNM
    , IFNULL(MSTITEM.ITEMCD, '') AS ITEMCD
    , IFNULL(MSTITEM.ITEMNM, '') AS ITEMNM
    , IFNULL(MSTLINE.LINENM, IFNULL(PRDRST.LINECD, '')) AS LINENM       -- 작업장 (생산만)
    , IFNULL(MSTPRC.PRCNM, '') AS PRCNM
    , IFNULL(MSTLINE_EQM.EQMNM, IFNULL(PRDRST.EQMCD, '')) AS EQMNM      -- 라인 (생산만)
    , IFNULL(MSTCUST.CUSTNM, '') AS CUSTNM                               -- 거래처: 외주 = 외주처, 자재 = 입고거래처, 출하 = 고객사
    , CASE TMP_LOT2001_TRACE.NODETP
        WHEN 'P' THEN PRDWORK.WORKDATE
        WHEN 'O' THEN LEFT(OSCRST.RSTTIME, 10)
        WHEN 'M' THEN IFNULL(LEFT(MTRIN.INDATE, 10)
                           , (SELECT LEFT(MIN(COMLOT.CRTTIME), 10) FROM COMLOT WHERE COMLOT.LOTKEY = TMP_LOT2001_TRACE.LOTKEY))
        WHEN 'S' THEN LEFT(SALOUT.SALOUTDATE, 10)
      ELSE '' END AS WORKDATE                              -- 생산일자 / 외주실적일 / 입고일 / 출하일
    , CASE TMP_LOT2001_TRACE.NODETP
        WHEN 'P' THEN PRDRSTLOT.LOTQTY
        WHEN 'O' THEN OSCRSTLOT.LOTQTY
        WHEN 'M' THEN MTRINLOT.LOTQTY
        WHEN 'S' THEN TMP_LOT2001_TRACE.USEQTY
      ELSE NULL END AS LOTQTY                              -- 생산·외주 양품 / 입고수량 / 출하수량
    , IF(TMP_LOT2001_TRACE.NODETP = 'S', NULL, TMP_LOT2001_TRACE.USEQTY) AS USEQTY
    , IF(TMP_LOT2001_TRACE.NODETP = 'S', NULL
       , (SELECT SUM(COMLOT.LOTQTY) FROM COMLOT WHERE COMLOT.LOTKEY = TMP_LOT2001_TRACE.LOTKEY)) AS STOCKQTY
    , TMP_LOT2001_TRACE.LOTKEY
    , TMP_LOT2001_TRACE.NODETP
    , TMP_LOT2001_TRACE.RSTKEY
  FROM TMP_LOT2001_TRACE
  LEFT JOIN PRDRST
    ON TMP_LOT2001_TRACE.NODETP = 'P'
   AND PRDRST.PRDRSTKEY = TMP_LOT2001_TRACE.RSTKEY
  LEFT JOIN PRDRSTLOT
    ON TMP_LOT2001_TRACE.NODETP = 'P'
   AND PRDRSTLOT.PRDRSTKEY = TMP_LOT2001_TRACE.RSTKEY
   AND PRDRSTLOT.LOTKEY = TMP_LOT2001_TRACE.LOTKEY
  LEFT JOIN PRDWORK
    ON PRDWORK.PRDWORKKEY = PRDRST.PRDWORKKEY
  LEFT JOIN OSCRST
    ON TMP_LOT2001_TRACE.NODETP = 'O'
   AND OSCRST.OSCRSTKEY = TMP_LOT2001_TRACE.RSTKEY
  LEFT JOIN OSCRSTLOT
    ON TMP_LOT2001_TRACE.NODETP = 'O'
   AND OSCRSTLOT.OSCRSTKEY = TMP_LOT2001_TRACE.RSTKEY
   AND OSCRSTLOT.LOTKEY = TMP_LOT2001_TRACE.LOTKEY
  LEFT JOIN MTRIN
    ON TMP_LOT2001_TRACE.NODETP = 'M'
   AND MTRIN.MTRINKEY = TMP_LOT2001_TRACE.RSTKEY
  LEFT JOIN MTRINLOT
    ON MTRINLOT.MTRINKEY = MTRIN.MTRINKEY
   AND MTRINLOT.LOTKEY = TMP_LOT2001_TRACE.LOTKEY
  LEFT JOIN SALOUT
    ON TMP_LOT2001_TRACE.NODETP = 'S'
   AND SALOUT.SALOUTKEY = TMP_LOT2001_TRACE.RSTKEY
  LEFT JOIN MSTITEM
    ON MSTITEM.ITEMID = COALESCE(PRDRST.ITEMID, OSCRST.ITEMID, SALOUT.ITEMID
                               , (SELECT COMLOT.ITEMID FROM COMLOT WHERE COMLOT.LOTKEY = TMP_LOT2001_TRACE.LOTKEY LIMIT 1))
  LEFT JOIN MSTPRC
    ON MSTPRC.PRCCD = COALESCE(PRDRST.PRCCD, OSCRST.PRCCD)
  LEFT JOIN MSTLINE
    ON MSTLINE.LINECD = PRDRST.LINECD
  LEFT JOIN MSTLINE_EQM
    ON MSTLINE_EQM.EQMCD = PRDRST.EQMCD
  LEFT JOIN MSTCUST
    ON MSTCUST.CUSTCD = CASE TMP_LOT2001_TRACE.NODETP
                          WHEN 'O' THEN OSCRST.CUSTCD
                          WHEN 'M' THEN IFNULL(MTRIN.CUSTCD, (SELECT COMLOT.CUSTCD FROM COMLOT WHERE COMLOT.LOTKEY = TMP_LOT2001_TRACE.LOTKEY LIMIT 1))
                          WHEN 'S' THEN SALOUT.CUSTCD
                        END;

  -- 결과 0: 역추적 그리드
  SELECT
      TMP_LOT2001_RESULT.LVL, TMP_LOT2001_RESULT.LOTDISP, TMP_LOT2001_RESULT.NODETPNM, TMP_LOT2001_RESULT.ITEMCD, TMP_LOT2001_RESULT.ITEMNM
    , TMP_LOT2001_RESULT.LINENM, TMP_LOT2001_RESULT.PRCNM, TMP_LOT2001_RESULT.EQMNM, TMP_LOT2001_RESULT.CUSTNM, TMP_LOT2001_RESULT.WORKDATE
    , TMP_LOT2001_RESULT.LOTQTY, TMP_LOT2001_RESULT.USEQTY, TMP_LOT2001_RESULT.STOCKQTY
    , TMP_LOT2001_RESULT.LOTKEY, TMP_LOT2001_RESULT.NODETP, TMP_LOT2001_RESULT.RSTKEY
  FROM TMP_LOT2001_RESULT
  WHERE TMP_LOT2001_RESULT.DIRTP IN ('C', 'B')
  ORDER BY TMP_LOT2001_RESULT.PATH;

  -- 결과 1: 정추적 그리드
  SELECT
      TMP_LOT2001_RESULT.LVL, TMP_LOT2001_RESULT.LOTDISP, TMP_LOT2001_RESULT.NODETPNM, TMP_LOT2001_RESULT.ITEMCD, TMP_LOT2001_RESULT.ITEMNM
    , TMP_LOT2001_RESULT.LINENM, TMP_LOT2001_RESULT.PRCNM, TMP_LOT2001_RESULT.EQMNM, TMP_LOT2001_RESULT.CUSTNM, TMP_LOT2001_RESULT.WORKDATE
    , TMP_LOT2001_RESULT.LOTQTY, TMP_LOT2001_RESULT.USEQTY, TMP_LOT2001_RESULT.STOCKQTY
    , TMP_LOT2001_RESULT.LOTKEY, TMP_LOT2001_RESULT.NODETP, TMP_LOT2001_RESULT.RSTKEY
  FROM TMP_LOT2001_RESULT
  WHERE TMP_LOT2001_RESULT.DIRTP IN ('C', 'F')
  ORDER BY TMP_LOT2001_RESULT.PATH;

  DROP TEMPORARY TABLE IF EXISTS TMP_LOT2001_RESULT;
  DROP TEMPORARY TABLE IF EXISTS TMP_LOT2001_START;
  DROP TEMPORARY TABLE IF EXISTS TMP_LOT2001_TRACE;
  DROP TEMPORARY TABLE IF EXISTS TMP_LOT2001_CUR;
  DROP TEMPORARY TABLE IF EXISTS TMP_LOT2001_NEXT;

-- ****************************************************************************
WHEN 'INFO' THEN  -- 선택 줄 상세 (결과: 0 기본정보 / 1 입출고 이력 / 2 품질 이력)

  IF IFNULL($LOTKEY, '') = '' THEN
    CALL COMERR('로트를 선택하세요.');
    LEAVE PROC;
  END IF;

  -- 0. 기본정보: 선택 줄 1건을 변수에 읽고, 구분별로 필요한 항목만 '항목 / 내용' 줄로 내린다 (빈 값은 뺀다)
  --    2026-11-25 CTE(WITH) · 파생테이블 안에서 프로시저 파라미터를 쓰면 MariaDB 가 Unknown column '$LOTKEY' 오류를 내서
  --               선택 줄 1건은 임시테이블(TMP_LOT2001_SEL)로 받고, 항목 줄은 임시테이블(TMP_LOT2001_INFO)에 넣어 내린다
  DROP TEMPORARY TABLE IF EXISTS TMP_LOT2001_SEL;
  CREATE TEMPORARY TABLE TMP_LOT2001_SEL (
    LOTKEY  VARCHAR(100) NOT NULL
  );

  INSERT INTO TMP_LOT2001_SEL (LOTKEY)
  VALUES ($LOTKEY);

  SELECT
      IFNULL(MSTITEM.ITEMCD, '') AS ITEMCD
    , IFNULL(MSTITEM.ITEMNM, '') AS ITEMNM
    , IFNULL(MSTITEM.ITEMSPEC, '') AS ITEMSPEC
    , IFNULL(MSTPRC.PRCNM, '') AS PRCNM
    , CASE $NODETP
        WHEN 'P' THEN IFNULL(MSTLINE.LINENM, PRDRST.LINECD)
      ELSE IFNULL(MSTCUST.CUSTNM, '') END AS PLACENM
    , IFNULL(MSTLINE_EQM.EQMNM, IFNULL(PRDRST.EQMCD, '')) AS EQMNM
    , CASE $NODETP
        WHEN 'P' THEN PRDWORK.WORKDATE
        WHEN 'O' THEN LEFT(OSCRST.RSTTIME, 10)
        WHEN 'M' THEN IFNULL(LEFT(MTRIN.INDATE, 10), (SELECT LEFT(MIN(COMLOT.CRTTIME), 10) FROM COMLOT WHERE COMLOT.LOTKEY = $LOTKEY))
        WHEN 'S' THEN LEFT(SALOUT.SALOUTDATE, 10)
      ELSE '' END AS WORKDATE
    , CASE PRDINS.DNTP
        WHEN 'DAY' THEN '주간'
        WHEN 'NIGHT' THEN '야간'
      ELSE IFNULL(PRDINS.DNTP, '') END AS DNTPNM
    , CASE $NODETP
        WHEN 'P' THEN CONCAT(MID(PRDWORK.WORKSTIME, 6, 11), ' ~ ', MID(PRDWORK.WORKETIME, 6, 11))
        WHEN 'O' THEN CONCAT(MID(OSCRST.WORKSTIME, 6, 11), ' ~ ', MID(OSCRST.WORKETIME, 6, 11))
      ELSE '' END AS WORKTIME
    , IFNULL((SELECT GROUP_CONCAT(IFNULL(MSTEMP.EMPNM, PRDWORK_EMP.EMPCD) ORDER BY PRDWORK_EMP.EMPCD SEPARATOR ', ')
                FROM PRDWORK_EMP
                LEFT JOIN MSTEMP
                  ON MSTEMP.EMPCD = PRDWORK_EMP.EMPCD
                WHERE PRDWORK_EMP.PRDWORKKEY = PRDWORK.PRDWORKKEY), '') AS EMPNM
    , CASE $NODETP
        WHEN 'P' THEN PRDRSTLOT.LOTQTY
        WHEN 'O' THEN OSCRSTLOT.LOTQTY
        WHEN 'M' THEN MTRINLOT.LOTQTY
        WHEN 'S' THEN (SELECT SUM(SALOUTLOT.LOTQTY) FROM SALOUTLOT WHERE SALOUTLOT.SALOUTKEY = $RSTKEY AND SALOUTLOT.LOTKEY = $LOTKEY)
      ELSE NULL END AS GOODQTY
    , PRDRSTLOT.BADQTY
    , IFNULL(PRDRSTLOT.LABELKEY, '') AS LABELKEY
    , IFNULL((SELECT COMLOT.HEATNO FROM COMLOT WHERE COMLOT.LOTKEY = $LOTKEY AND IFNULL(COMLOT.HEATNO, '') <> '' LIMIT 1), '') AS HEATNO
    , (SELECT SUM(COMLOT.LOTQTY) FROM COMLOT WHERE COMLOT.LOTKEY = $LOTKEY) AS STOCKQTY
    , CASE SALOUT.OUTYN
        WHEN 'Y' THEN '확정'
        WHEN 'N' THEN '미확정'
      ELSE '' END AS OUTYNNM
    INTO _$ITEMCD, _$ITEMNM, _$ITEMSPEC, _$PRCNM, _$PLACENM
       , _$EQMNM, _$WORKDATE, _$DNTPNM, _$WORKTIME, _$EMPNM
       , _$GOODQTY, _$BADQTY, _$LABELKEY, _$HEATNO, _$STOCKQTY
       , _$OUTYNNM
  FROM TMP_LOT2001_SEL
  LEFT JOIN PRDRST
    ON $NODETP = 'P'
   AND PRDRST.PRDRSTKEY = $RSTKEY
  LEFT JOIN PRDRSTLOT
    ON $NODETP = 'P'
   AND PRDRSTLOT.PRDRSTKEY = $RSTKEY
   AND PRDRSTLOT.LOTKEY = $LOTKEY
  LEFT JOIN PRDWORK
    ON PRDWORK.PRDWORKKEY = PRDRST.PRDWORKKEY
  LEFT JOIN PRDINS
    ON PRDINS.PRDINSKEY = PRDWORK.PRDINSKEY
  LEFT JOIN OSCRST
    ON $NODETP = 'O'
   AND OSCRST.OSCRSTKEY = $RSTKEY
  LEFT JOIN OSCRSTLOT
    ON $NODETP = 'O'
   AND OSCRSTLOT.OSCRSTKEY = $RSTKEY
   AND OSCRSTLOT.LOTKEY = $LOTKEY
  LEFT JOIN MTRIN
    ON $NODETP = 'M'
   AND MTRIN.MTRINKEY = $RSTKEY
  LEFT JOIN MTRINLOT
    ON MTRINLOT.MTRINKEY = MTRIN.MTRINKEY
   AND MTRINLOT.LOTKEY = $LOTKEY
  LEFT JOIN SALOUT
    ON $NODETP = 'S'
   AND SALOUT.SALOUTKEY = $RSTKEY
  LEFT JOIN MSTITEM
    ON MSTITEM.ITEMID = COALESCE(PRDRST.ITEMID, OSCRST.ITEMID, SALOUT.ITEMID
                               , (SELECT COMLOT.ITEMID FROM COMLOT WHERE COMLOT.LOTKEY = $LOTKEY LIMIT 1))
  LEFT JOIN MSTPRC
    ON MSTPRC.PRCCD = COALESCE(PRDRST.PRCCD, OSCRST.PRCCD)
  LEFT JOIN MSTLINE
    ON MSTLINE.LINECD = PRDRST.LINECD
  LEFT JOIN MSTLINE_EQM
    ON MSTLINE_EQM.EQMCD = PRDRST.EQMCD
  LEFT JOIN MSTCUST
    ON MSTCUST.CUSTCD = CASE $NODETP
                          WHEN 'O' THEN OSCRST.CUSTCD
                          WHEN 'M' THEN IFNULL(MTRIN.CUSTCD, (SELECT COMLOT.CUSTCD FROM COMLOT WHERE COMLOT.LOTKEY = $LOTKEY LIMIT 1))
                          WHEN 'S' THEN SALOUT.CUSTCD
                        END
  LIMIT 1;

  DROP TEMPORARY TABLE IF EXISTS TMP_LOT2001_INFO;
  CREATE TEMPORARY TABLE TMP_LOT2001_INFO (
    SORTNO   INT NOT NULL,
    INFONM   VARCHAR(50) NOT NULL,
    INFOVAL  VARCHAR(500) NULL
  );

  INSERT INTO TMP_LOT2001_INFO (SORTNO, INFONM, INFOVAL)
  VALUES
      (1, '구분', CASE $NODETP WHEN 'P' THEN '생산' WHEN 'O' THEN '외주' WHEN 'M' THEN '자재' WHEN 'S' THEN '출하' ELSE '' END)
    , (2, '로트번호', $LOTKEY)
    , (3, '품번', _$ITEMCD)
    , (4, '품명', _$ITEMNM)
    , (5, '규격', _$ITEMSPEC)
    , (6, '공정', IF($NODETP IN ('P', 'O'), _$PRCNM, ''))
    , (7, CASE $NODETP WHEN 'P' THEN '작업장' WHEN 'O' THEN '외주처' WHEN 'M' THEN '입고거래처' ELSE '고객사' END, _$PLACENM)
    , (8, '라인', IF($NODETP = 'P', _$EQMNM, ''))
    , (9, CASE $NODETP WHEN 'P' THEN '생산일자' WHEN 'O' THEN '실적일자' WHEN 'M' THEN '입고일자' ELSE '출하일자' END, _$WORKDATE)
    , (10, '주야', IF($NODETP = 'P', _$DNTPNM, ''))
    , (11, '작업시간', IF($NODETP IN ('P', 'O'), _$WORKTIME, ''))
    , (12, '작업자', IF($NODETP = 'P', _$EMPNM, ''))
    , (13, CASE $NODETP WHEN 'M' THEN '입고수량' WHEN 'S' THEN '출하수량' ELSE '양품수량' END, FORMAT(_$GOODQTY, 0))
    , (14, '불량수량', IF($NODETP = 'P', FORMAT(_$BADQTY, 0), ''))
    , (15, '라벨번호', IF($NODETP = 'P', _$LABELKEY, ''))
    , (16, 'HEAT NO', _$HEATNO)
    , (17, '현재고(전체 창고)', IF($NODETP <> 'S', FORMAT(_$STOCKQTY, 0), ''))
    , (18, '출하확정', IF($NODETP = 'S', _$OUTYNNM, ''))
    , (19, CASE $NODETP WHEN 'P' THEN '실적번호' WHEN 'O' THEN '외주실적번호' WHEN 'M' THEN '입고번호' ELSE '출하번호' END, $RSTKEY);

  SELECT
      TMP_LOT2001_INFO.INFONM
    , TMP_LOT2001_INFO.INFOVAL
  FROM TMP_LOT2001_INFO
  WHERE IFNULL(TMP_LOT2001_INFO.INFOVAL, '') <> ''
  ORDER BY TMP_LOT2001_INFO.SORTNO;

  DROP TEMPORARY TABLE IF EXISTS TMP_LOT2001_SEL;
  DROP TEMPORARY TABLE IF EXISTS TMP_LOT2001_INFO;

  -- 1. 입출고 이력 (모든 창고, 입고 +, 출고 -. 출하반품 반입은 출고수량이 마이너스라 + 로 나온다)
  SELECT
      LEFT(COMINLOT.INDATE, 10) AS IODATE
    , '입고' AS IOTPNM
    , IFNULL(COMTYPE.TPNM, COMINLOT.INTP) AS TPNM
    , IFNULL(MSTWARE.WARENM, COMINLOT.WARECD) AS WARENM
    , COMINLOT.INQTY AS IOQTY
    , LEFT(COMINLOT.RTIME, 16) AS RTIME
  FROM COMINLOT
  LEFT JOIN COMTYPE
    ON COMTYPE.GPCD = 'INTP'
   AND COMTYPE.TPCD = COMINLOT.INTP
  LEFT JOIN MSTWARE
    ON MSTWARE.WARECD = COMINLOT.WARECD
  WHERE COMINLOT.LOTKEY = $LOTKEY
  UNION ALL
  SELECT
      LEFT(COMOUTLOT.OUTDATE, 10) AS IODATE
    , '출고' AS IOTPNM
    , IFNULL(COMTYPE.TPNM, COMOUTLOT.OUTTP) AS TPNM
    , IFNULL(MSTWARE.WARENM, COMOUTLOT.WARECD) AS WARENM
    , -COMOUTLOT.OUTQTY AS IOQTY
    , LEFT(COMOUTLOT.RTIME, 16) AS RTIME
  FROM COMOUTLOT
  LEFT JOIN COMTYPE
    ON COMTYPE.GPCD = 'OUTTP'
   AND COMTYPE.TPCD = COMOUTLOT.OUTTP
  LEFT JOIN MSTWARE
    ON MSTWARE.WARECD = COMOUTLOT.WARECD
  WHERE COMOUTLOT.LOTKEY = $LOTKEY
  ORDER BY RTIME, IODATE, IOTPNM DESC;

  -- 2. 품질 이력: 자주검사(생산 줄만, 작업 중 검사) + 부적합 판정(이 로트)
  IF $NODETP = 'P' THEN
    SELECT PRDWORK.EQMCD, PRDWORK.ITEMID, PRDWORK.WORKSTIME, IF(PRDWORK.WORKETIME = '', CALLTIME(), PRDWORK.WORKETIME)
      INTO _$EQMCD, _$ITEMID, _$WORKSTIME, _$WORKETIME
      FROM PRDRST
      INNER JOIN PRDWORK
        ON PRDWORK.PRDWORKKEY = PRDRST.PRDWORKKEY
      WHERE PRDRST.PRDRSTKEY = $RSTKEY
      LIMIT 1;
  END IF;

  SELECT
      '자주검사' AS QCTPNM
    , LEFT(TQMRST.FIXTIME, 16) AS QCTIME
    , CASE TQMRST.FINALJUDGE
        WHEN 'Y' THEN '합격'
        WHEN 'N' THEN '불합격'
      ELSE '검사중' END AS RESULTNM
    , NULL AS QCQTY
    , IFNULL(MSTEMP.EMPNM, IFNULL(TQMRST.EMPCD, '')) AS QCDESC
  FROM TQMRST
  INNER JOIN MSTRPTREV_HEADER
    ON MSTRPTREV_HEADER.REVCD = TQMRST.REVCD
   AND MSTRPTREV_HEADER.STDTP = 'PRCTEST'  -- 자주검사
  LEFT JOIN MSTEMP
    ON MSTEMP.EMPCD = TQMRST.EMPCD
  WHERE $NODETP = 'P'
    AND TQMRST.LINECD = _$EQMCD
    AND TQMRST.ITEMID = _$ITEMID
    AND TQMRST.FIXTIME >= _$WORKSTIME
    AND TQMRST.FIXTIME <= _$WORKETIME
  UNION ALL
  SELECT
      '부적합판정' AS QCTPNM
    , LEFT(TQMJUDGE.JUDGEDATE, 16) AS QCTIME
    , IFNULL(COMTYPE.TPNM, TQMJUDGE.JUDGETP) AS RESULTNM
    , TQMJUDGE.JUDGEQTY AS QCQTY
    , CONCAT_WS(' / ', NULLIF(IFNULL(MSTBAD.BADNM, ''), ''), NULLIF(IFNULL(TQMJUDGE.REMARK, ''), '')) AS QCDESC
  FROM TQMJUDGE
  LEFT JOIN COMTYPE
    ON COMTYPE.GPCD = 'JUDGETP'
   AND COMTYPE.TPCD = TQMJUDGE.JUDGETP
  LEFT JOIN MSTBAD
    ON MSTBAD.BADCD = TQMJUDGE.BADCD
  WHERE $NODETP <> 'S'
    AND TQMJUDGE.LOTKEY = $LOTKEY
  ORDER BY QCTIME;

