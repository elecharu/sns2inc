      MSTITEM.ITEMSRC, MSTITEM.ITEMCG, MSTITEM.ITEM_LVL1, MSTITEM.ITEM_LVL2, 
      MSTITEM.ITEM_LVL3, MSTITEM.ITEM_LVL4, MSTITEM.VALID_FROM_DT, MSTITEM.VALID_TO_DT, 
      MSTITEM.ENDYN, MSTITEM.ENDUSEID, MSTITEM.ENDREASON, MSTITEM.INSPEC, 
      MSTITEM.PRDPLANGROUP, MSTITEM.ITEMOLDCD, MSTITEM.BARCD, 
      MSTITEM.GRADE, MSTITEM.CBITEMNO, MSTITEM.CBYN, MSTITEM.ITEM_LVL5, 
      MSTITEM.PARTNO, MSTITEM.INITCD, MSTITEM.IOYN, MSTITEM.SEPAYN, 
