      MSTITEM.SPEC4, MSTITEM.SPEC5, MSTITEM.SPEC6, MSTITEM.SPEC7, 
      MSTITEM.SPEC8, MSTITEM.SPEC9, MSTITEM.SPEC10, MSTITEM.SPEC11, 
      MSTITEM.SPEC12, MSTITEM.SPEC13, MSTITEM.SPEC14, MSTITEM.SPEC15, 
      MSTITEM.SPEC16, MSTITEM.SPEC17, MSTITEM.SPEC18, MSTITEM.SPEC19,
