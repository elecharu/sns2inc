    FROM MSTITEM
    WHERE MSTITEM.COMPANYCD = $COMPANYCD
      AND MSTITEM.ITEMCG = $ITEMCG
      AND MSTITEM.ENDYN = $ENDYN
      AND (   MSTITEM.ITEMID LIKE CONCAT('%', $ITEMID, '%')
           OR MSTITEM.ITEMCD LIKE CONCAT('%', $ITEMID, '%')
          )
    ORDER BY MSTITEM.COMPANYCD, MSTITEM.ITEMCD
