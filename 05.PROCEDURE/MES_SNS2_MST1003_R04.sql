  IN $FACTORYCD VARCHAR(100),
  IN $ITEMID VARCHAR(100),
  IN $ITEMCG VARCHAR(100),
  IN $CALLTYPE VARCHAR(100),
  IN $ENDYN VARCHAR(1), 
  IN $KEYWORD VARCHAR(1000)
  )
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- SET @DEBUGLOGYN = 'Y';
-- *****************************************************************************
  CASE $CALLTYPE
-- ****************************************************************************
  WHEN 'SEL_ITEM' THEN
   IF $COMPANYCD = '' THEN 
      CALL COMERR('법인을 선택하십시오.');
      LEAVE PROC;
   END IF; 

   IF $ITEMCG = '' THEN 
      CALL COMERR('품목분류을 선택하십시오.');
      LEAVE PROC;
   END IF; 
  
    SELECT
      CAST(MSTITEM.ITEMID AS CHAR) AS ITEMID, 
      MSTITEM.ITEMCD, MSTITEM.COMPANYCD, MSTITEM.MODELCD, 
      MSTITEM.COLORCD, MSTITEM.MYCD, MSTITEM.ITEMNM, MSTITEM.ITEMBNM, 
      MSTITEM.MAINPARTID, MSTITEM.MAINITEMID, MSTITEM.TRANGOODSID, 
