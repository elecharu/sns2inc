CREATE DEFINER=`root`@`%`
PROCEDURE `MES_SNS2`.`MST1005_R01`(
-- *****************************************************************************
-- Comment: 설비등급 평가등록
-- Create: 	2026-11-05  	생성 			한성수
-- Modify: 	2026-11-05 					한성수	설비 목록·평가이력 조회, 자동 점수·등급 판정, 평가 등록·승인, 점수기준 비고 추가, 평가표 출력
-- Modify: 	2026-11-06 					한성수	승인 대기 평가이력이 있으면 신규 평가 차단, 평가·승인일자 오늘 이후 및 최종 승인 평가일자 이전 평가 차단, 평가 승인 시 비고(REMARK) 갱신 반영
-- *****************************************************************************
  IN $SDATE             VARCHAR(10),   -- 조회 시작일자
  IN $EDATE             VARCHAR(10),   -- 조회 종료일자
  IN $LINECD            VARCHAR(10),   -- 작업장
  IN $EQMTP             VARCHAR(10),   -- 공정(설비구분)
  IN $EQMGROUP1         VARCHAR(10),   -- 라인(설비대분류)
  IN $FANO              VARCHAR(50),   -- 설비번호
  IN $EQMGRADEEVALKEY   VARCHAR(30),   -- 설비등급평가키 (빈 값이면 신규 평가)
  IN $REVCD             VARCHAR(20),   -- 평가기준 리비전 코드
  IN $GMCD              VARCHAR(20),   -- 평가항목코드
  IN $EVALDATE          VARCHAR(10),   -- 평가일자
  IN $EMPCD             VARCHAR(20),   -- 평가자
  IN $REMARK            VARCHAR(1000), -- 비고
  IN $APRVEMP           VARCHAR(20),   -- 승인자
  IN $APRVDATE          VARCHAR(10),   -- 승인일자
  IN $GMCD_LIST         MEDIUMTEXT,    -- 직접 선택 항목 (계산구분 없는 평가항목)
  IN $SCORE_LIST        MEDIUMTEXT,

-- *****************************************************************************
  IN $CALLTYPE          VARCHAR(50),
  IN $KEYWORD           VARCHAR(1000)
)
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  DECLARE _$KEY         VARCHAR(30);
  DECLARE _$REVCD       VARCHAR(20);
  DECLARE _$FANO        VARCHAR(50);
  DECLARE _$EVALDATE    VARCHAR(10);
  DECLARE _$EQMGRADE    VARCHAR(10);
  DECLARE _$APRVTIME    VARCHAR(19);
  DECLARE _$LASTDATE    VARCHAR(10);   -- 설비의 최종 승인 평가일자
  DECLARE _$FIXCOUNT    DOUBLE;        -- 고장건수 (최근 1년)
  DECLARE _$FIXTIME     DOUBLE;        -- 월 평균 수리시간(분) (최근 1년 합계 ÷ 12)
  DECLARE _$USEMONTHS   DOUBLE;        -- 사용개월 (설치일자 ~ 평가일자)
  DECLARE _$GMCD        VARCHAR(20);
  DECLARE _$GMNM        VARCHAR(100);
  DECLARE _$SCORE       VARCHAR(20);
  DECLARE _$TOTSCORE    DECIMAL(18,0);
  DECLARE _$MSG         VARCHAR(500);

  -- 승인·삭제는 평가이력 선택 필수
  IF $CALLTYPE IN ('APPROVE_EVAL', 'DEL_EVAL') AND $EQMGRADEEVALKEY = '' THEN
    CALL COMERR('평가이력을 선택하세요.');
    LEAVE PROC;
  END IF;

  -- 평가 대상 확인 (평가키가 없으면 선택 설비의 신규 평가 : 사용중 리비전 기준)
  IF $CALLTYPE IN ('LIST_EVAL_D', 'SAVE_EVAL', 'APPROVE_EVAL', 'DEL_EVAL') THEN
    IF $EQMGRADEEVALKEY = '' THEN
      IF NOT EXISTS (SELECT 1 FROM MSTEQM WHERE FANO = $FANO LIMIT 1) THEN
        CALL COMERR('설비를 선택하세요.');
        LEAVE PROC;
      END IF;

      -- 승인 대기중인 평가이력이 있으면 신규 평가 불가 (설비별 승인 대기 1건만 유지)
      SET _$EVALDATE = (SELECT MAX(EVALDATE) FROM EQMGRADEEVAL WHERE FANO = $FANO AND APRVTIME = '');

      IF _$EVALDATE IS NOT NULL THEN
        CALL COMERR(CONCAT('승인 대기중인 평가이력(평가일자 ', _$EVALDATE, ')이 있습니다.<br>승인 대기중인 평가이력을 삭제 후 새로 생성해주세요.'));
        LEAVE PROC;
      END IF;

      SET _$FANO     = $FANO;
      SET _$APRVTIME = '';
      SET _$REVCD    = (SELECT REVCD FROM MSTEQM_GRADEREV WHERE USEYN = 'Y' LIMIT 1);

      IF _$REVCD IS NULL THEN
        CALL COMERR('사용중인 설비등급기준이 없습니다.<br>설비등급기준 관리에서 확인하세요.');
        LEAVE PROC;
      END IF;
    ELSE
      IF NOT EXISTS (SELECT 1 FROM EQMGRADEEVAL WHERE EQMGRADEEVALKEY = $EQMGRADEEVALKEY LIMIT 1) THEN
        CALL COMERR('선택한 평가이력이 없습니다.<br>다시 조회하세요.');
        LEAVE PROC;
      END IF;

      SELECT REVCD, FANO, EVALDATE, EQMGRADE, APRVTIME
        INTO _$REVCD, _$FANO, _$EVALDATE, _$EQMGRADE, _$APRVTIME
      FROM EQMGRADEEVAL
      WHERE EQMGRADEEVALKEY = $EQMGRADEEVALKEY
      LIMIT 1
      FOR UPDATE;

      IF _$APRVTIME <> '' AND $CALLTYPE = 'APPROVE_EVAL' THEN
        CALL COMERR('이미 승인된 평가이력입니다.');
        LEAVE PROC;
      END IF;

      IF _$APRVTIME <> '' AND $CALLTYPE IN ('SAVE_EVAL', 'DEL_EVAL') THEN
        CALL COMERR('승인된 평가이력은 수정·삭제할 수 없습니다.');
        LEAVE PROC;
      END IF;
    END IF;
  END IF;

  -- 계산구분별 산출값 (평가 상세조회·저장 공통, 최근 1년 : 평가일자 1년 전 다음날 ~ 평가일자)
  IF $CALLTYPE IN ('LIST_EVAL_D', 'SAVE_EVAL') THEN
    IF $EVALDATE NOT REGEXP '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN
      CALL COMERR('평가일자를 입력하세요.');
      LEAVE PROC;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM MSTEQM_GRADEREV_D WHERE REVCD = _$REVCD LIMIT 1) THEN
      CALL COMERR('설비등급기준에 평가항목이 없습니다.<br>설비등급기준 관리에서 확인하세요.');
      LEAVE PROC;
    END IF;

    SELECT COUNT(*), ROUND(COALESCE(SUM(CASE WHEN REPETIME > REPSTIME THEN TIMESTAMPDIFF(MINUTE, REPSTIME, REPETIME) ELSE 0 END), 0) / 12, 2)
      INTO _$FIXCOUNT, _$FIXTIME
    FROM EQMREP
    WHERE EQMCD = _$FANO
      AND EQMREPTP = 'EQM01'
      AND REPSTIME >= DATE_ADD(DATE_SUB($EVALDATE, INTERVAL 1 YEAR), INTERVAL 1 DAY)
      AND REPSTIME <  DATE_ADD($EVALDATE, INTERVAL 1 DAY);

    SET _$USEMONTHS = (SELECT CASE WHEN SETDATE <> '' THEN TIMESTAMPDIFF(MONTH, SETDATE, $EVALDATE) END FROM MSTEQM WHERE FANO = _$FANO LIMIT 1);
  END IF;

-- *****************************************************************************
CASE $CALLTYPE
-- *****************************************************************************

  WHEN 'LIST_EQM' THEN -- 설비 목록 조회

    SELECT MSTLINE.LINENM, MSTEQM.EQMTP, MSTEQM.EQMGROUP1, MSTEQM.EQMGUBUN,
           MSTEQM.FANO, MSTEQM.EQMNM, MSTEQM.EQMGRADE
    FROM MSTEQM
    LEFT JOIN MSTLINE
      ON MSTLINE.LINECD = MSTEQM.LINECD
    WHERE MSTEQM.USEYN = 'Y'
      AND MSTEQM.FACTORYCD = '07'
      AND ($LINECD = '' OR MSTEQM.LINECD = $LINECD)
      AND ($EQMTP = '' OR MSTEQM.EQMTP = $EQMTP)
      AND ($EQMGROUP1 = '' OR MSTEQM.EQMGROUP1 = $EQMGROUP1)
    ORDER BY MSTEQM.LINECD, MSTEQM.EQMTP, MSTEQM.EQMGROUP1, MSTEQM.FANO;

-- *****************************************************************************

  WHEN 'LIST_EVAL' THEN -- 선택 설비의 평가이력 조회 (평가일자 기준)

    SELECT EQMGRADEEVAL.EQMGRADEEVALKEY, EQMGRADEEVAL.EVALDATE, EQMGRADEEVAL.EQMGRADE, EQMGRADEEVAL.TOTSCORE,
           EQMGRADEEVAL.EMPCD, EVAL_EMP.EMPNM, APRV_EMP.EMPNM AS APRVEMPNM, EQMGRADEEVAL.APRVTIME, EQMGRADEEVAL.REMARK
    FROM EQMGRADEEVAL
    LEFT JOIN MSTEMP AS EVAL_EMP
      ON EVAL_EMP.EMPCD = EQMGRADEEVAL.EMPCD
    LEFT JOIN MSTEMP AS APRV_EMP
      ON APRV_EMP.EMPCD = EQMGRADEEVAL.APRVEMP
    WHERE EQMGRADEEVAL.FANO = $FANO
      AND EQMGRADEEVAL.EVALDATE BETWEEN $SDATE AND $EDATE
    ORDER BY EQMGRADEEVAL.EVALDATE DESC, EQMGRADEEVAL.EQMGRADEEVALKEY DESC;

-- *****************************************************************************

  WHEN 'LIST_EVAL_D' THEN -- 평가항목별 점수 조회 (계산구분 항목은 산출값 구간 점수, 그 외는 저장 점수, 승인 이력은 저장 점수)

    SELECT MSTEQM_GRADEREV_D.REVCD, MSTEQM_GRADEREV_D.GMCD, MSTEQM_GRADEREV_D.GMTP, MSTEQM_GRADEREV_D.GMNM, MSTEQM_GRADEREV_D.CALCTP,
           CALC.CALCVAL, SCORE_D2.SCORE, SCORE_D2.SCORENM
    FROM MSTEQM_GRADEREV_D
    LEFT JOIN (SELECT 'FIXCOUNT' AS CALCTP, _$FIXCOUNT AS CALCVAL
               UNION ALL SELECT 'FIXTIME', _$FIXTIME
               UNION ALL SELECT 'USEMONTHS', _$USEMONTHS) AS CALC
      ON CALC.CALCTP = MSTEQM_GRADEREV_D.CALCTP
    LEFT JOIN MSTEQM_GRADEREV_D2 AS AUTO_D2
      ON AUTO_D2.REVCD = MSTEQM_GRADEREV_D.REVCD
     AND AUTO_D2.GMCD = MSTEQM_GRADEREV_D.GMCD
     AND NOT (AUTO_D2.MINVAL = '' AND AUTO_D2.MAXVAL = '')
     AND (CASE WHEN AUTO_D2.MINVAL <> '' AND AUTO_D2.MINVAL = AUTO_D2.MAXVAL THEN CALC.CALCVAL = AUTO_D2.MINVAL + 0E0
               ELSE CALC.CALCVAL >= IF(AUTO_D2.MINVAL = '', '-1E300', AUTO_D2.MINVAL) + 0E0
                AND CALC.CALCVAL <  IF(AUTO_D2.MAXVAL = '', '1E300', AUTO_D2.MAXVAL) + 0E0 END)
    LEFT JOIN EQMGRADEEVAL_D
      ON EQMGRADEEVAL_D.EQMGRADEEVALKEY = $EQMGRADEEVALKEY
     AND EQMGRADEEVAL_D.GMCD = MSTEQM_GRADEREV_D.GMCD
    LEFT JOIN MSTEQM_GRADEREV_D2 AS SCORE_D2
      ON SCORE_D2.REVCD = MSTEQM_GRADEREV_D.REVCD
     AND SCORE_D2.GMCD = MSTEQM_GRADEREV_D.GMCD
     AND SCORE_D2.SCORE = IF(MSTEQM_GRADEREV_D.CALCTP = '' OR _$APRVTIME <> '', EQMGRADEEVAL_D.SCORE, AUTO_D2.SCORE)
    WHERE MSTEQM_GRADEREV_D.REVCD = _$REVCD
    ORDER BY MSTEQM_GRADEREV_D.SORTNO, MSTEQM_GRADEREV_D.GMCD;

-- *****************************************************************************

  WHEN 'LIST_EVAL_D2' THEN -- 선택 평가항목의 점수별 평가기준 조회

    IF $GMCD NOT REGEXP '^[0-9]+$' THEN
      CALL COMERR('평가항목을 선택하세요.');
      LEAVE PROC;
    END IF;

    SELECT SCORE, SCORENM, MINVAL, MAXVAL, REMARK
    FROM MSTEQM_GRADEREV_D2
    WHERE REVCD = $REVCD
      AND GMCD = $GMCD
    ORDER BY SCORE;

-- *****************************************************************************

  WHEN 'LIST_EVAL_SCORE' THEN -- 설비등급 기준 조회

    SELECT MSTEQM_GRADEREV_SCORE.EQMGRADE, MSTEQM_GRADEREV_SCORE.SCORENM, MSTEQM_GRADEREV_SCORE.MINVAL, MSTEQM_GRADEREV_SCORE.MAXVAL,
           MSTEQM_GRADEREV_SCORE.MNGNM, MSTEQM_GRADEREV_SCORE.CHKCYCLE2
    FROM MSTEQM_GRADEREV_SCORE
    LEFT JOIN COMTYPE
      ON COMTYPE.GPCD = 'FM110'
     AND COMTYPE.TPCD = MSTEQM_GRADEREV_SCORE.EQMGRADE
    WHERE MSTEQM_GRADEREV_SCORE.REVCD = $REVCD
    ORDER BY COMTYPE.SORTNO, MSTEQM_GRADEREV_SCORE.EQMGRADE;

-- *****************************************************************************

  WHEN 'SAVE_EVAL' THEN -- 평가 저장 (계산구분 항목은 산출값으로 점수 재계산, 합계점수로 평가등급 판정)

    IF NOT EXISTS (SELECT 1 FROM MSTEMP WHERE EMPCD = $EMPCD LIMIT 1) THEN
      CALL COMERR('평가자를 선택하세요.');
      LEAVE PROC;
    END IF;

    -- 평가 이력은 날짜 순서대로만 쌓임 : 오늘 이후 불가, 최종 승인 평가일자 이전 불가 (같은 날짜는 허용)
    IF $EVALDATE > LEFT(CALLTIME(), 10) THEN
      CALL COMERR('평가일자는 오늘 이후로 입력할 수 없습니다.');
      LEAVE PROC;
    END IF;

    SET _$LASTDATE = (SELECT MAX(EVALDATE) FROM EQMGRADEEVAL WHERE FANO = _$FANO AND APRVTIME <> '');

    IF $EVALDATE < _$LASTDATE THEN
      CALL COMERR(CONCAT('최종 승인 평가일자(', _$LASTDATE, ') 이전 날짜로 평가할 수 없습니다.'));
      LEAVE PROC;
    END IF;

    IF $EQMGRADEEVALKEY = '' THEN
      SET _$KEY = GETKEY('EQMGRADEEVALKEY');
    ELSE
      SET _$KEY = $EQMGRADEEVALKEY;

      -- 항목별 점수는 저장할 때마다 다시 만듦
      DELETE FROM EQMGRADEEVAL_D WHERE EQMGRADEEVALKEY = _$KEY;
    END IF;

    -- 계산구분 항목 : 산출값이 들어가는 점수 구간 (최소값 이상 ~ 최대값 미만, 최소 = 최대면 그 값)
    INSERT INTO EQMGRADEEVAL_D (
      EQMGRADEEVALKEY, GMCD, SCORE, RTIME, REMP, RPRG
    )
    SELECT _$KEY, MSTEQM_GRADEREV_D.GMCD, AUTO_D2.SCORE, CALLTIME(), CALLEMP(), CALLPRG()
    FROM MSTEQM_GRADEREV_D
    INNER JOIN (SELECT 'FIXCOUNT' AS CALCTP, _$FIXCOUNT AS CALCVAL
                UNION ALL SELECT 'FIXTIME', _$FIXTIME
                UNION ALL SELECT 'USEMONTHS', _$USEMONTHS) AS CALC
      ON CALC.CALCTP = MSTEQM_GRADEREV_D.CALCTP
    INNER JOIN MSTEQM_GRADEREV_D2 AS AUTO_D2
      ON AUTO_D2.REVCD = MSTEQM_GRADEREV_D.REVCD
     AND AUTO_D2.GMCD = MSTEQM_GRADEREV_D.GMCD
     AND NOT (AUTO_D2.MINVAL = '' AND AUTO_D2.MAXVAL = '')
     AND (CASE WHEN AUTO_D2.MINVAL <> '' AND AUTO_D2.MINVAL = AUTO_D2.MAXVAL THEN CALC.CALCVAL = AUTO_D2.MINVAL + 0E0
               ELSE CALC.CALCVAL >= IF(AUTO_D2.MINVAL = '', '-1E300', AUTO_D2.MINVAL) + 0E0
                AND CALC.CALCVAL <  IF(AUTO_D2.MAXVAL = '', '1E300', AUTO_D2.MAXVAL) + 0E0 END)
    WHERE MSTEQM_GRADEREV_D.REVCD = _$REVCD;

    -- 계산구분 없는 항목 : 화면에서 선택한 점수
    WHILE LENGTH($GMCD_LIST) > 0 DO
      CALL COMSPLIT($GMCD_LIST, _$GMCD);
      CALL COMSPLIT($SCORE_LIST, _$SCORE);

      SET _$GMNM = NULL;
      IF _$GMCD REGEXP '^[0-9]+$' THEN
        SET _$GMNM = (SELECT GMNM FROM MSTEQM_GRADEREV_D WHERE REVCD = _$REVCD AND GMCD = _$GMCD AND CALCTP = '' LIMIT 1);
      END IF;

      IF _$GMNM IS NULL THEN
        CALL COMERR('평가항목을 다시 조회하세요.');
        LEAVE PROC;
      END IF;

      IF _$SCORE <> '' THEN
        IF _$SCORE NOT REGEXP '^-?[0-9]{1,5}$'
           OR NOT EXISTS (SELECT 1 FROM MSTEQM_GRADEREV_D2 WHERE REVCD = _$REVCD AND GMCD = _$GMCD AND SCORE = _$SCORE LIMIT 1) THEN
          CALL COMERR(CONCAT(_$GMNM, '의 점수(', _$SCORE, ')를 확인하세요.<br>점수별 평가기준에 있는 점수를 선택하세요.'));
          LEAVE PROC;
        END IF;

        INSERT INTO EQMGRADEEVAL_D (
          EQMGRADEEVALKEY, GMCD, SCORE, RTIME, REMP, RPRG
        ) VALUES (
          _$KEY, _$GMCD, _$SCORE, CALLTIME(), CALLEMP(), CALLPRG()
        );
      END IF;
    END WHILE;

    -- 점수가 정해지지 않은 평가항목이 있으면 저장 불가
    SET _$MSG = (
      SELECT CASE WHEN MSTEQM_GRADEREV_D.CALCTP = '' THEN CONCAT(MSTEQM_GRADEREV_D.GMNM, '의 점수를 선택하세요.')
                  ELSE CONCAT(MSTEQM_GRADEREV_D.GMNM, '의 산출값에 맞는 점수별 평가기준이 없습니다.<br>점수별 평가기준과 설비정보(설치일자)를 확인하세요.') END
      FROM MSTEQM_GRADEREV_D
      LEFT JOIN EQMGRADEEVAL_D
        ON EQMGRADEEVAL_D.EQMGRADEEVALKEY = _$KEY
       AND EQMGRADEEVAL_D.GMCD = MSTEQM_GRADEREV_D.GMCD
      WHERE MSTEQM_GRADEREV_D.REVCD = _$REVCD
        AND EQMGRADEEVAL_D.GMCD IS NULL
      ORDER BY MSTEQM_GRADEREV_D.SORTNO, MSTEQM_GRADEREV_D.GMCD
      LIMIT 1
    );

    IF _$MSG IS NOT NULL THEN
      CALL COMERR(_$MSG);
      LEAVE PROC;
    END IF;

    -- 합계점수가 들어가는 설비등급 (최소점수 이상 ~ 최대점수 미만, 최소 = 최대면 그 점수)
    SET _$TOTSCORE = (SELECT SUM(SCORE) FROM EQMGRADEEVAL_D WHERE EQMGRADEEVALKEY = _$KEY);
    SET _$EQMGRADE = (
      SELECT EQMGRADE
      FROM MSTEQM_GRADEREV_SCORE
      WHERE REVCD = _$REVCD
        AND NOT (MINVAL = '' AND MAXVAL = '')
        AND (CASE WHEN MINVAL <> '' AND MINVAL = MAXVAL THEN _$TOTSCORE = MINVAL + 0E0
                  ELSE _$TOTSCORE >= IF(MINVAL = '', '-1E300', MINVAL) + 0E0
                   AND _$TOTSCORE <  IF(MAXVAL = '', '1E300', MAXVAL) + 0E0 END)
      LIMIT 1
    );

    IF _$EQMGRADE IS NULL THEN
      CALL COMERR(CONCAT('합계점수(', _$TOTSCORE, '점)에 맞는 설비등급 기준이 없습니다.<br>설비등급기준 관리에서 확인하세요.'));
      LEAVE PROC;
    END IF;

    IF $EQMGRADEEVALKEY = '' THEN
      INSERT INTO EQMGRADEEVAL (
        EQMGRADEEVALKEY, REVCD, FANO, EVALDATE, EMPCD, TOTSCORE, EQMGRADE, REMARK, RTIME, REMP, RPRG
      ) VALUES (
        _$KEY, _$REVCD, _$FANO, $EVALDATE, $EMPCD, _$TOTSCORE, _$EQMGRADE, $REMARK, CALLTIME(), CALLEMP(), CALLPRG()
      );
    ELSE
      UPDATE EQMGRADEEVAL
      SET EVALDATE = $EVALDATE,
          EMPCD    = $EMPCD,
          TOTSCORE = _$TOTSCORE,
          EQMGRADE = _$EQMGRADE,
          REMARK   = $REMARK,
          MTIME    = CALLTIME(),
          MEMP     = CALLEMP(),
          MPRG     = CALLPRG()
      WHERE EQMGRADEEVALKEY = _$KEY;
    END IF;

    -- 저장한 평가키 반환 (화면에서 저장한 평가이력 다시 선택)
    SELECT _$KEY AS EQMGRADEEVALKEY;

-- *****************************************************************************

  WHEN 'APPROVE_EVAL' THEN -- 평가 승인 (승인 전 설비등급 보관 후 설비등급을 평가등급으로 변경)

    IF NOT EXISTS (SELECT 1 FROM MSTEMP WHERE EMPCD = $APRVEMP LIMIT 1) THEN
      CALL COMERR('승인자를 선택하세요.');
      LEAVE PROC;
    END IF;

    IF $APRVDATE NOT REGEXP '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN
      CALL COMERR('승인일자를 입력하세요.');
      LEAVE PROC;
    END IF;

    IF $APRVDATE > LEFT(CALLTIME(), 10) THEN
      CALL COMERR('승인일자는 오늘 이후로 입력할 수 없습니다.');
      LEAVE PROC;
    END IF;

    IF $APRVDATE < _$EVALDATE THEN
      CALL COMERR(CONCAT('승인일자는 평가일자(', _$EVALDATE, ')보다 빠를 수 없습니다.'));
      LEAVE PROC;
    END IF;

    -- 평가일자가 더 늦은 승인 이력이 있으면 설비등급이 이전 평가로 바뀌므로 승인 불가
    IF EXISTS (SELECT 1 FROM EQMGRADEEVAL WHERE FANO = _$FANO AND APRVTIME <> '' AND EVALDATE > _$EVALDATE LIMIT 1) THEN
      CALL COMERR('평가일자가 더 늦은 승인 이력이 있어 승인할 수 없습니다.');
      LEAVE PROC;
    END IF;

    UPDATE EQMGRADEEVAL
    SET EQMGRADE_BEFORE = COALESCE((SELECT EQMGRADE FROM MSTEQM WHERE FANO = _$FANO LIMIT 1), ''),
        APRVEMP         = $APRVEMP,
        APRVTIME        = CONCAT($APRVDATE, ' ', RIGHT(CALLTIME(), 8)),
        REMARK          = $REMARK,
        MTIME           = CALLTIME(),
        MEMP            = CALLEMP(),
        MPRG            = CALLPRG()
    WHERE EQMGRADEEVALKEY = $EQMGRADEEVALKEY;

    UPDATE MSTEQM
    SET EQMGRADE = _$EQMGRADE,
        MTIME    = CALLTIME(),
        MEMP     = CALLEMP(),
        MPRG     = CALLPRG()
    WHERE FANO = _$FANO;

-- *****************************************************************************

  WHEN 'DEL_EVAL' THEN -- 평가 삭제 (미승인 평가만)

    DELETE FROM EQMGRADEEVAL_D WHERE EQMGRADEEVALKEY = $EQMGRADEEVALKEY;
    DELETE FROM EQMGRADEEVAL WHERE EQMGRADEEVALKEY = $EQMGRADEEVALKEY;

-- *****************************************************************************

  WHEN 'CALL_EVAL_RPT' THEN -- 설비등급 평가표 출력 (평가 정보, 평가항목별 평가기준, 설비등급 기준)

    IF NOT EXISTS (SELECT 1 FROM EQMGRADEEVAL WHERE EQMGRADEEVALKEY = $EQMGRADEEVALKEY LIMIT 1) THEN
      CALL COMERR('출력할 평가이력을 선택하세요.');
      LEAVE PROC;
    END IF;

    -- 평가 정보 (1행 : 라인명 = 작업장 공정 라인, 관리책임자 = 관리부서장, 결재 작성 = 평가자, 승인 = 승인자)
    SELECT EQMGRADEEVAL.FANO, MSTEQM.EQMNM, MSTEQM.EQMNM_DETAIL, REPLACE(LEFT(MSTEQM.MKDATE, 7), '-', '.') AS MKDATE,
           CONCAT_WS(' ', NULLIF(GPCD('N_LINECD', MSTEQM.LINECD), ''), NULLIF(GPCD('FM100', MSTEQM.EQMTP), ''), NULLIF(GPCD('FM113', MSTEQM.EQMGROUP1), '')) AS LINENM,
           COALESCE(CONCAT(NULLIF(MSTDEPT.DEPTNM, ''), '장'), '') AS MNGNM,
           EQMGRADEEVAL.EVALDATE, GPCD('EMPCD', EQMGRADEEVAL.EMPCD) AS EMPNM,
           GPCD('EMPCD', EQMGRADEEVAL.APRVEMP) AS APRVEMPNM, EQMGRADEEVAL.APRVTIME,
           FORMAT(EQMGRADEEVAL.TOTSCORE, 0) AS TOTSCORE, EQMGRADEEVAL.EQMGRADE
    FROM EQMGRADEEVAL
    LEFT JOIN MSTEQM
      ON MSTEQM.FANO = EQMGRADEEVAL.FANO
    LEFT JOIN MSTDEPT
      ON MSTDEPT.DEPTCD = MSTEQM.DEPTCD
    WHERE EQMGRADEEVAL.EQMGRADEEVALKEY = $EQMGRADEEVALKEY;

    -- 평가항목별 평가기준 (평가기준 1줄당 1행, 항목 단위 병합은 레포트에서 GMCD 기준)
    SELECT MSTEQM_GRADEREV_D.GMCD, GMTP.TPNM AS GMTPNM,
           DENSE_RANK() OVER (ORDER BY MSTEQM_GRADEREV_D.SORTNO, MSTEQM_GRADEREV_D.GMCD) AS NO,
           MSTEQM_GRADEREV_D.GMNM, EQMGRADEEVAL_D.SCORE,
           CONCAT(MSTEQM_GRADEREV_D2.SCORE, '점 : ', MSTEQM_GRADEREV_D2.SCORENM) AS CRITERIA,
           IF(MSTEQM_GRADEREV_D2.SCORE = EQMGRADEEVAL_D.SCORE, 'Y', 'N') AS SELYN
    FROM EQMGRADEEVAL
    INNER JOIN MSTEQM_GRADEREV_D
      ON MSTEQM_GRADEREV_D.REVCD = EQMGRADEEVAL.REVCD
    LEFT JOIN EQMGRADEEVAL_D
      ON EQMGRADEEVAL_D.EQMGRADEEVALKEY = EQMGRADEEVAL.EQMGRADEEVALKEY
     AND EQMGRADEEVAL_D.GMCD = MSTEQM_GRADEREV_D.GMCD
    LEFT JOIN MSTEQM_GRADEREV_D2
      ON MSTEQM_GRADEREV_D2.REVCD = MSTEQM_GRADEREV_D.REVCD
     AND MSTEQM_GRADEREV_D2.GMCD = MSTEQM_GRADEREV_D.GMCD
    LEFT JOIN COMTYPE AS GMTP
      ON GMTP.GPCD = 'GMTP'
     AND GMTP.TPCD = MSTEQM_GRADEREV_D.GMTP
    WHERE EQMGRADEEVAL.EQMGRADEEVALKEY = $EQMGRADEEVALKEY
    ORDER BY MSTEQM_GRADEREV_D.SORTNO, MSTEQM_GRADEREV_D.GMCD, MSTEQM_GRADEREV_D2.SCORE;

    -- 설비등급 기준
    SELECT MSTEQM_GRADEREV_SCORE.EQMGRADE, COMTYPE.TPNM AS EQMGRADENM, MSTEQM_GRADEREV_SCORE.SCORENM,
           MSTEQM_GRADEREV_SCORE.MNGNM, MSTEQM_GRADEREV_SCORE.CHKCYCLE2
    FROM EQMGRADEEVAL
    INNER JOIN MSTEQM_GRADEREV_SCORE
      ON MSTEQM_GRADEREV_SCORE.REVCD = EQMGRADEEVAL.REVCD
    LEFT JOIN COMTYPE
      ON COMTYPE.GPCD = 'FM110'
     AND COMTYPE.TPCD = MSTEQM_GRADEREV_SCORE.EQMGRADE
    WHERE EQMGRADEEVAL.EQMGRADEEVALKEY = $EQMGRADEEVALKEY
    ORDER BY COMTYPE.SORTNO, MSTEQM_GRADEREV_SCORE.EQMGRADE;

-- *****************************************************************************
END CASE;

END
