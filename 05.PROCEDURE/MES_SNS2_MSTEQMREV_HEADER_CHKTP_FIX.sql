-- *****************************************************************************
-- 배경: REV 헤더에 점검구분을 저장하기 시작한 2026-10-23 이전에 EQM1001_R03(정기점검 계획)에서 만든 REV는 CHKTP가 빈 값
--       EQM1001_R03·EQM1001_R04·TAL0001_R08은 CHKTP = '02'만 정기점검으로 보므로 빈 값 REV는 화면·점검에서 빠짐
-- 대상(2026-11-09 사용자 조회): G FM116I210N REV.0~3, E I2C-003N REV.0, E A-003 REV.0 (모두 승인)
-- 순서: 1. 대상 확인 → 2. 같은 번호 정기점검 REV 중복 확인(0건이어야 함) → 3. 변경 트랜잭션 → 4. 결과 확인 후 COMMIT

-- 1. 대상 확인 (6건 예상)
SELECT REVCD, PLANTP, PLANCD, REVNUM, CHKTP, APRVSTT, REQTIME, APRVTIME
FROM MES_SNS2.MSTEQMREV_HEADER
WHERE CHKTP = '' OR CHKTP IS NULL
ORDER BY PLANTP, PLANCD, REVNUM;

-- 2. 중복 확인: 같은 대상·번호의 정기점검 REV가 이미 있으면 안 됨 (0건이어야 함)
SELECT BLANK_REV.PLANTP, BLANK_REV.PLANCD, BLANK_REV.REVNUM
FROM MES_SNS2.MSTEQMREV_HEADER BLANK_REV
INNER JOIN MES_SNS2.MSTEQMREV_HEADER PERIODIC_REV
  ON PERIODIC_REV.PLANTP = BLANK_REV.PLANTP
 AND PERIODIC_REV.PLANCD = BLANK_REV.PLANCD
 AND PERIODIC_REV.REVNUM = BLANK_REV.REVNUM
 AND PERIODIC_REV.CHKTP = '02'
WHERE BLANK_REV.CHKTP = '' OR BLANK_REV.CHKTP IS NULL;

-- 3. 변경
START TRANSACTION;

UPDATE MES_SNS2.MSTEQMREV_HEADER
SET CHKTP = '02'
WHERE CHKTP = '' OR CHKTP IS NULL;

-- 4. 결과 확인: 빈 값 0건, 대상 6건이 '02'
SELECT PLANTP, PLANCD, REVNUM, CHKTP, APRVSTT
FROM MES_SNS2.MSTEQMREV_HEADER
WHERE (PLANTP = 'G' AND PLANCD = 'FM116I210N')
   OR (PLANTP = 'E' AND PLANCD IN ('I2C-003N', 'A-003'))
ORDER BY PLANTP, PLANCD, REVNUM;

SELECT COUNT(*) AS BLANK_CNT
FROM MES_SNS2.MSTEQMREV_HEADER
WHERE CHKTP = '' OR CHKTP IS NULL;

