CREATE DEFINER=`root`@`%` PROCEDURE `MES_SNS2`.`MTR0001_R04`(
-- *****************************************************************************
-- Comment: 설비부품 발주조회
-- Create:  2026-10-12  생성  한성수  설비부품 발주 및 ERP 수신 조회/저장 로직 구축
-- Modify:  2026-10-13  한성수  선언 형식 통일, 실제 품목·발주 구조 및 ERP 원본 수신·발주 입고처 적용
-- *****************************************************************************
  IN $MTRODRKEY        VARCHAR(20),
  IN $MTRODRSEQ        INT,
  IN $SDATE            VARCHAR(10),
  IN $EDATE            VARCHAR(10),
  IN $EMPCD            VARCHAR(20),
  IN $CUSTCD           VARCHAR(20),
  IN $ITEMCG           VARCHAR(10),
  IN $ITEMCD           VARCHAR(50),
  IN $IF_KEY_LIST      MEDIUMTEXT,
  IN $MTRODRKEY_LIST   MEDIUMTEXT,
  IN $INCUSTCD_LIST    MEDIUMTEXT,

-- *****************************************************************************
  IN $CALLTYPE        VARCHAR(50),
  IN $KEYWORD         VARCHAR(1000)
)
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  DECLARE _$IFKEY       VARCHAR(20);
  DECLARE _$IFMKEY      INT;
  DECLARE _$MTRODRKEY   VARCHAR(20);
  DECLARE _$MTRODRSEQ   INT;
  DECLARE _$INCUSTCD    VARCHAR(20);

  CASE $CALLTYPE
  -- *****************************************************************************

  WHEN 'LIST_MTRODR' THEN -- 설비부품 발주목록 조회
    SELECT ODR.MTRODRDATE AS ODRDATE,
           ODR.MTRODRKEY, ODRD.MTRODRSEQ, ODRD.MTRODRSTT,
           ODR.ODRTP AS PO,
           ODR.CUSTCD, CUST.CUSTNM,
           ODR.INCUSTCD, INCUST.CUSTNM AS INCUSTNM,
           ITEM.ITEMCG, ITEM.ITEMCD, ITEM.ITEMNM, ITEM.ITEMSPEC, ITEM.ITEMUNIT,
           LEFT(COALESCE(NULLIF(ODRD.EXPDATE, ''), ODR.EXPDATE), 10) AS EXPDATE,
           ODR.ODREMPID AS BUYER,
           ODRD.ODRQTY,
           COALESCE(RECEIPT.INQTY, 0) AS MTRINQTY,
           COALESCE(ODRD.INQTY, 0) AS COMINQTY,
           GREATEST(0, COALESCE(ODRD.ODRQTY, 0) - COALESCE(ODRD.INQTY, 0)) AS NOTINQTY
    FROM MTRODR ODR
    INNER JOIN MTRODRD ODRD ON ODRD.MTRODRKEY = ODR.MTRODRKEY
    INNER JOIN MSTITEM ITEM ON ITEM.ITEMID = ODRD.ITEMID
    LEFT JOIN MSTCUST CUST ON CUST.CUSTCD = ODR.CUSTCD
    LEFT JOIN MSTCUST INCUST ON INCUST.CUSTCD = ODR.INCUSTCD
    LEFT JOIN (
      SELECT MTRODRKEY, MTRODRSEQ, SUM(INQTY) AS INQTY
      FROM MTRIN
      GROUP BY MTRODRKEY, MTRODRSEQ
    ) RECEIPT ON RECEIPT.MTRODRKEY = ODRD.MTRODRKEY AND RECEIPT.MTRODRSEQ = ODRD.MTRODRSEQ
    WHERE ODR.MTRODRDATE BETWEEN $SDATE AND $EDATE
      AND (COALESCE($CUSTCD, '') = '' OR ODR.CUSTCD = $CUSTCD)
      AND (COALESCE($ITEMCG, '') = '' OR ITEM.ITEMCG = $ITEMCG)
      AND (COALESCE($ITEMCD, '') = '' OR ITEM.ITEMCD LIKE CONCAT('%', $ITEMCD, '%'))
    ORDER BY ODR.MTRODRDATE DESC, ODR.MTRODRKEY DESC, ODRD.MTRODRSEQ;

  -- *****************************************************************************

  WHEN 'LIST_MTRODR_1' THEN -- ERP 및 MES 발주목록 조회
    SELECT IFD.IF_KEY, IFD.IF_YN AS IFYN,
           LEFT(IFM.ODRDT, 10) AS ODRDATE,
           IFD.MTRODRKEY, IFD.MTRODRSEQ, IFD.MTRODRSTT,
           IFM.MTRODRTP AS PO,
           IFM.CUSTCD, CUST.CUSTNM,
           ITEM.ITEMCG, ITEM.ITEMCD, ITEM.ITEMNM, ITEM.ITEMSPEC,
           LEFT(COALESCE(NULLIF(IFD.DELIVERYDT, ''), IFM.DELIVERYDT), 10) AS EXPDATE,
           IFM.EMPCD AS BUYER, IFD.ODRQTY
    FROM IF_MES_SNS_FAC2.FAC2_ERP_IF_MTRODRD IFD
    INNER JOIN (
      SELECT MTRODRKEY, MTRODRSEQ, MAX(IF_KEY) AS IF_KEY
      FROM IF_MES_SNS_FAC2.FAC2_ERP_IF_MTRODRD
      GROUP BY MTRODRKEY, MTRODRSEQ
    ) LAST_D ON LAST_D.IF_KEY = IFD.IF_KEY
    INNER JOIN (
      SELECT MTRODRKEY, MAX(IF_KEY) AS IF_KEY
      FROM IF_MES_SNS_FAC2.FAC2_ERP_IF_MTRODR
      GROUP BY MTRODRKEY
    ) LAST_M ON LAST_M.MTRODRKEY = IFD.MTRODRKEY
    INNER JOIN IF_MES_SNS_FAC2.FAC2_ERP_IF_MTRODR IFM ON IFM.IF_KEY = LAST_M.IF_KEY
    LEFT JOIN MSTITEM ITEM ON ITEM.ITEMID = IFD.ITEMID
    LEFT JOIN MSTCUST CUST ON CUST.CUSTCD = IFM.CUSTCD
    WHERE IFM.ODRDT >= $SDATE AND IFM.ODRDT < CONCAT(DATE_ADD($EDATE, INTERVAL 1 DAY), ' 00:00:00')
      AND (COALESCE($CUSTCD, '') = '' OR IFM.CUSTCD = $CUSTCD)
      AND (COALESCE($ITEMCG, '') = '' OR ITEM.ITEMCG = $ITEMCG)
      AND (COALESCE($ITEMCD, '') = '' OR ITEM.ITEMCD LIKE CONCAT('%', $ITEMCD, '%'))
    ORDER BY IFD.IF_YN, IFM.ODRDT DESC, IFD.MTRODRKEY DESC, IFD.MTRODRSEQ;

    SELECT ODR.MTRODRDATE AS ODRDATE,
           ODR.MTRODRKEY, ODRD.MTRODRSEQ, ODRD.MTRODRSTT,
           ODR.ODRTP AS PO,
           ODR.CUSTCD, CUST.CUSTNM,
           ITEM.ITEMCG, ITEM.ITEMCD, ITEM.ITEMNM, ITEM.ITEMSPEC,
           LEFT(COALESCE(NULLIF(ODRD.EXPDATE, ''), ODR.EXPDATE), 10) AS EXPDATE,
           ODR.ODREMPID AS BUYER, ODRD.ODRQTY,
           ODRD.RTIME AS RCVTIME
    FROM MTRODR ODR
    INNER JOIN MTRODRD ODRD ON ODRD.MTRODRKEY = ODR.MTRODRKEY
    INNER JOIN MSTITEM ITEM ON ITEM.ITEMID = ODRD.ITEMID
    LEFT JOIN MSTCUST CUST ON CUST.CUSTCD = ODR.CUSTCD
    WHERE ODR.MTRODRDATE BETWEEN $SDATE AND $EDATE
      AND (COALESCE($CUSTCD, '') = '' OR ODR.CUSTCD = $CUSTCD)
      AND (COALESCE($ITEMCG, '') = '' OR ITEM.ITEMCG = $ITEMCG)
      AND (COALESCE($ITEMCD, '') = '' OR ITEM.ITEMCD LIKE CONCAT('%', $ITEMCD, '%'))
    ORDER BY ODR.MTRODRDATE DESC, ODR.MTRODRKEY DESC, ODRD.MTRODRSEQ;

  -- *****************************************************************************

  WHEN 'RCV_ERPDATA' THEN -- 선택 ERP 발주 원본 수신
    IF COALESCE($EMPCD, '') = '' OR NOT EXISTS (SELECT 1 FROM MSTEMP WHERE EMPCD = $EMPCD LIMIT 1) THEN
      CALL COMERR('수신자를 선택해주세요.');
      LEAVE PROC;
    END IF;
    IF COALESCE($IF_KEY_LIST, '') = '' THEN
      CALL COMERR('수신할 대상을 선택해주세요.');
      LEAVE PROC;
    END IF;

    WHILE LENGTH($IF_KEY_LIST) > 0 DO
      CALL COMSPLIT($IF_KEY_LIST, _$IFKEY);
      IF _$IFKEY NOT REGEXP '^[0-9]+$' OR NOT EXISTS (
        SELECT 1
        FROM IF_MES_SNS_FAC2.FAC2_ERP_IF_MTRODRD IFD
        INNER JOIN MSTITEM ITEM ON ITEM.ITEMID = IFD.ITEMID
        WHERE IFD.IF_KEY = _$IFKEY LIMIT 1
      ) THEN
        CALL COMERR('ERP 발주 또는 품목정보가 없습니다. 다시 조회해주세요.');
        LEAVE PROC;
      END IF;

      SELECT MTRODRKEY, MTRODRSEQ INTO _$MTRODRKEY, _$MTRODRSEQ
      FROM IF_MES_SNS_FAC2.FAC2_ERP_IF_MTRODRD
      WHERE IF_KEY = _$IFKEY FOR UPDATE;

      IF EXISTS (SELECT 1 FROM IF_MES_SNS_FAC2.FAC2_ERP_IF_MTRODRD
                 WHERE MTRODRKEY = _$MTRODRKEY AND MTRODRSEQ = _$MTRODRSEQ AND IF_KEY > _$IFKEY LIMIT 1) THEN
        CALL COMERR('ERP 발주가 변경되었습니다. 다시 조회한 뒤 수신해주세요.');
        LEAVE PROC;
      END IF;
      SET _$IFMKEY = (SELECT MAX(IF_KEY) FROM IF_MES_SNS_FAC2.FAC2_ERP_IF_MTRODR WHERE MTRODRKEY = _$MTRODRKEY);
      IF _$IFMKEY IS NULL THEN
        CALL COMERR('ERP 발주 헤더가 없습니다. 다시 조회해주세요.');
        LEAVE PROC;
      END IF;

      INSERT INTO MTRODR (
        MTRODRKEY, MTRODRDATE, EXPDATE, CUSTEMPID, CUSTCD, ODRTP, ODRBC, URGBC,
        CURYBC, EXRT, DIBC, ODRDEPT, ODREMPID, ODRFACTORY, INFACTORYCD, INWARECD,
        INCUSTCD, MTRODRSTT, ODRENTBC, MOVNO, MOVSQ, REMARK, RTIME, REMP, RPRG
      )
      SELECT MTRODRKEY, LEFT(ODRDT, 10), DELIVERYDT, DELIVEREMPCD, CUSTCD, MTRODRTP, MTRODRGB, EMRCYN,
             CURYBC, EXRT, DIBC, DEPTCD, EMPCD, FACTORYCD, INFACTORYCD, INWARECD,
             INCUSTCT, STATUS, MTRODRSTT, MOVENO, MOVESEQ, REMARK, CALLTIME(), $EMPCD, CALLPRG()
      FROM IF_MES_SNS_FAC2.FAC2_ERP_IF_MTRODR
      WHERE IF_KEY = _$IFMKEY
      ON DUPLICATE KEY UPDATE
        MTRODRDATE = VALUES(MTRODRDATE), EXPDATE = VALUES(EXPDATE), CUSTEMPID = VALUES(CUSTEMPID),
        CUSTCD = VALUES(CUSTCD), ODRTP = VALUES(ODRTP), ODRBC = VALUES(ODRBC), URGBC = VALUES(URGBC),
        CURYBC = VALUES(CURYBC), EXRT = VALUES(EXRT), DIBC = VALUES(DIBC), ODRDEPT = VALUES(ODRDEPT),
        ODREMPID = VALUES(ODREMPID), ODRFACTORY = VALUES(ODRFACTORY), INFACTORYCD = VALUES(INFACTORYCD),
        INWARECD = VALUES(INWARECD), INCUSTCD = VALUES(INCUSTCD), MTRODRSTT = VALUES(MTRODRSTT),
        ODRENTBC = VALUES(ODRENTBC), MOVNO = VALUES(MOVNO), MOVSQ = VALUES(MOVSQ), REMARK = VALUES(REMARK),
        MTIME = CALLTIME(), MEMP = $EMPCD, MPRG = CALLPRG();

      INSERT INTO MTRODRD (
        MTRODRKEY, MTRODRSEQ, ITEMID, ODRQTY, MTRODRPRICE, MTRODRAMT, MTRODRFPRICE, MTRODRFAMT,
        DLVUM, EXPDATE, ODRDELDT, ODRDELEMPID, REQNO, REQSEQ, MRPNO, MRPSEQ, DLVQTY, INQTY,
        MTRODRSTT, CLSREMARK, FILENO, MOVSQ, MOVNO, RMKS2, FILESQ, REMARK, RTIME, REMP, RPRG
      )
      SELECT MTRODRKEY, MTRODRSEQ, ITEMID, ODRQTY, ODRUP, ODRAMT, ODRFUP, ODRFAMT,
             DELIVERYUM, DELIVERYDT, DELDT, DELEMPCD, REQNO, REQSEQ, MRPNO, MRPSEQ, DELIVERYQTY, INQTY,
             MTRODRSTT, CLSREMARK, FILENO, MOVESEQ, MOVENO, REMARK2, FILESEQ, REMARK, CALLTIME(), $EMPCD, CALLPRG()
      FROM IF_MES_SNS_FAC2.FAC2_ERP_IF_MTRODRD
      WHERE IF_KEY = _$IFKEY
      ON DUPLICATE KEY UPDATE
        ITEMID = VALUES(ITEMID), ODRQTY = VALUES(ODRQTY), MTRODRPRICE = VALUES(MTRODRPRICE),
        MTRODRAMT = VALUES(MTRODRAMT), MTRODRFPRICE = VALUES(MTRODRFPRICE), MTRODRFAMT = VALUES(MTRODRFAMT),
        DLVUM = VALUES(DLVUM), EXPDATE = VALUES(EXPDATE), ODRDELDT = VALUES(ODRDELDT), ODRDELEMPID = VALUES(ODRDELEMPID),
        REQNO = VALUES(REQNO), REQSEQ = VALUES(REQSEQ), MRPNO = VALUES(MRPNO), MRPSEQ = VALUES(MRPSEQ),
        DLVQTY = VALUES(DLVQTY), INQTY = VALUES(INQTY), MTRODRSTT = VALUES(MTRODRSTT),
        CLSREMARK = VALUES(CLSREMARK), FILENO = VALUES(FILENO), MOVSQ = VALUES(MOVSQ), MOVNO = VALUES(MOVNO),
        RMKS2 = VALUES(RMKS2), FILESQ = VALUES(FILESQ), REMARK = VALUES(REMARK),
        MTIME = CALLTIME(), MEMP = $EMPCD, MPRG = CALLPRG();

      UPDATE IF_MES_SNS_FAC2.FAC2_ERP_IF_MTRODRD
      SET IF_YN = 'Y', IF_TIME = CALLTIME()
      WHERE IF_KEY = _$IFKEY;
      IF NOT EXISTS (
        SELECT 1 FROM IF_MES_SNS_FAC2.FAC2_ERP_IF_MTRODRD IFD
        INNER JOIN (
          SELECT MTRODRSEQ, MAX(IF_KEY) AS IF_KEY FROM IF_MES_SNS_FAC2.FAC2_ERP_IF_MTRODRD
          WHERE MTRODRKEY = _$MTRODRKEY GROUP BY MTRODRSEQ
        ) LAST_D ON LAST_D.IF_KEY = IFD.IF_KEY
        WHERE COALESCE(IFD.IF_YN, '') <> 'Y' LIMIT 1
      ) THEN
        UPDATE IF_MES_SNS_FAC2.FAC2_ERP_IF_MTRODR
        SET IF_YN = 'Y', IF_TIME = CALLTIME()
        WHERE IF_KEY = _$IFMKEY;
      END IF;
    END WHILE;

  -- *****************************************************************************

  WHEN 'DELETE_MESDATA' THEN -- MES 발주상세 삭제
    IF COALESCE($MTRODRKEY, '') = '' OR COALESCE($MTRODRSEQ, 0) <= 0 THEN
      CALL COMERR('삭제할 발주상세를 선택해주세요.');
      LEAVE PROC;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM MTRODRD WHERE MTRODRKEY = $MTRODRKEY AND MTRODRSEQ = $MTRODRSEQ LIMIT 1) THEN
      CALL COMERR('삭제할 발주상세가 없습니다. 다시 조회해주세요.');
      LEAVE PROC;
    END IF;
    IF EXISTS (SELECT 1 FROM MTRIN WHERE MTRODRKEY = $MTRODRKEY AND MTRODRSEQ = $MTRODRSEQ LIMIT 1)
       OR EXISTS (SELECT 1 FROM MTRODRD WHERE MTRODRKEY = $MTRODRKEY AND MTRODRSEQ = $MTRODRSEQ AND INQTY > 0 LIMIT 1) THEN
      CALL COMERR('입고 이력이 존재하여 삭제할 수 없습니다.');
      LEAVE PROC;
    END IF;
    IF EXISTS (SELECT 1 FROM OSCINS WHERE MTRODRDKEY = CONCAT($MTRODRKEY, '-', $MTRODRSEQ) LIMIT 1) THEN
      CALL COMERR('외주지시가 연결된 발주상세는 삭제할 수 없습니다.');
      LEAVE PROC;
    END IF;

    DELETE FROM MTRODRD WHERE MTRODRKEY = $MTRODRKEY AND MTRODRSEQ = $MTRODRSEQ;
    IF NOT EXISTS (SELECT 1 FROM MTRODRD WHERE MTRODRKEY = $MTRODRKEY LIMIT 1) THEN
      DELETE FROM MTRODR WHERE MTRODRKEY = $MTRODRKEY;
    END IF;

  -- *****************************************************************************

  WHEN 'UPDATE_INCUSTCD' THEN -- 발주 전체 입고처 저장
    IF COALESCE($MTRODRKEY_LIST, '') = '' THEN
      CALL COMERR('저장할 발주를 선택해주세요.');
      LEAVE PROC;
    END IF;
    WHILE LENGTH($MTRODRKEY_LIST) > 0 DO
      CALL COMSPLIT($MTRODRKEY_LIST, _$MTRODRKEY);
      CALL COMSPLIT($INCUSTCD_LIST, _$INCUSTCD);
      IF NOT EXISTS (SELECT 1 FROM MTRODR WHERE MTRODRKEY = _$MTRODRKEY LIMIT 1) THEN
        CALL COMERR('저장할 발주가 없습니다. 다시 조회해주세요.');
        LEAVE PROC;
      END IF;
      IF _$INCUSTCD IS NULL OR (_$INCUSTCD <> '' AND NOT EXISTS (SELECT 1 FROM MSTCUST WHERE CUSTCD = _$INCUSTCD LIMIT 1)) THEN
        CALL COMERR('입고처를 거래처 목록에서 선택해주세요.');
        LEAVE PROC;
      END IF;
      UPDATE MTRODR
      SET INCUSTCD = _$INCUSTCD, MTIME = CALLTIME(), MEMP = CALLEMP(), MPRG = CALLPRG()
      WHERE MTRODRKEY = _$MTRODRKEY;
    END WHILE;

  -- *****************************************************************************
  ELSE
    CALL COMERR('파라미터값을 확인해주세요.');
    LEAVE PROC;
  -- *****************************************************************************
  END CASE;
END
