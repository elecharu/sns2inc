CREATE DEFINER=`root`@`%` 
PROCEDURE `MES_SNS2`.`MTR0001_R04`(
-- *****************************************************************************
-- Comment: 설비부품 발주관리 (발주헤더 및 발주상세 조회)
-- Create:  2026-10-12  생성    한성수
-- Modify:  2026-10-14          한성수  발주헤더·상세 분리 조회, 사원명 조인(DOUBLE 에러 방지) 및 발주서 출력 리포트(CALL_RPT) 조회 추가
-- *****************************************************************************
  IN $COMPANYCD       VARCHAR(100),
  IN $FACTORYCD       VARCHAR(100),
  IN $SDATE           VARCHAR(10),
  IN $EDATE           VARCHAR(10),
  IN $CUSTCD          VARCHAR(20),
  IN $MTRODRKEY       VARCHAR(20),

-- *****************************************************************************
  IN $CALLTYPE        VARCHAR(50),
  IN $KEYWORD         VARCHAR(1000)
)
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************

  CASE $CALLTYPE
  -- *****************************************************************************

  WHEN 'LIST_MTRODR' THEN -- 설비부품 발주헤더 목록 조회 (발주디테일에 설비부품이 있는 발주헤더만 조회)

    SET $SDATE = REPLACE(COALESCE($SDATE, ''), '-', '');
    SET $EDATE = REPLACE(COALESCE($EDATE, ''), '-', '');

    SELECT MTRODR.MTRODRDATE, MTRODR.MTRODRKEY, MTRODR.MTRODRSTT,
           MTRODR.CUSTCD, MSTCUST.CUSTNM,
           MTRODR.EXPDATE,
           CASE 
             WHEN COALESCE(MTRODR.ODREMPID, 0) = 0 THEN ''
             ELSE COALESCE(MSTEMP.EMPNM, SNS_EMP.EMPNM, CAST(MTRODR.ODREMPID AS CHAR))
           END AS ODREMPID
    FROM MTRODR
    INNER JOIN (
      SELECT DISTINCT D.MTRODRKEY
      FROM MTRODRD D
      INNER JOIN MSTITEM I 
        ON I.ITEMID = D.ITEMID
       AND (COALESCE($COMPANYCD, '') = '' OR I.COMPANYCD = $COMPANYCD)
       AND (I.ITEMCG = 'DM100700' OR I.ITEMCG LIKE 'DM1007%' OR I.ITEMCG = 'DM100750')
    ) EQM_ODR
      ON EQM_ODR.MTRODRKEY = MTRODR.MTRODRKEY
    LEFT JOIN MSTCUST
      ON MSTCUST.CUSTCD = MTRODR.CUSTCD
    LEFT JOIN MSTEMP
      ON MTRODR.ODREMPID > 0
     AND (MSTEMP.EMPID = CAST(MTRODR.ODREMPID AS CHAR) OR MSTEMP.EMPCD = CAST(MTRODR.ODREMPID AS CHAR))
    LEFT JOIN MES_SNS.MSTEMP AS SNS_EMP
      ON MTRODR.ODREMPID > 0
     AND SNS_EMP.EMPID = CAST(MTRODR.ODREMPID AS CHAR)
    WHERE (   $SDATE = ''
           OR LEFT(REPLACE(MTRODR.MTRODRDATE, '-', ''), 8) >= $SDATE
          )
      AND (   $EDATE = ''
           OR LEFT(REPLACE(MTRODR.MTRODRDATE, '-', ''), 8) <= $EDATE
          )
      AND (   COALESCE($FACTORYCD, '') = ''
           OR MTRODR.INFACTORYCD = $FACTORYCD
           OR MTRODR.ODRFACTORY = $FACTORYCD
           OR COALESCE(MTRODR.INFACTORYCD, '') = ''
          )
      AND (COALESCE($CUSTCD, '') = '' OR MTRODR.CUSTCD = $CUSTCD)
    ORDER BY MTRODR.MTRODRDATE DESC, MTRODR.MTRODRKEY DESC;

  -- *****************************************************************************

  WHEN 'LIST_MTRODRD' THEN -- 선택된 발주헤더의 설비부품 발주상세 목록 조회

    IF COALESCE($MTRODRKEY, '') = '' THEN
      LEAVE PROC;
    END IF;

    SELECT MTRODRD.MTRODRSEQ, MTRODRD.MTRODRSTT,
           MSTITEM.ITEMCG, MSTITEM.ITEMCD, MSTITEM.ITEMNM, MSTITEM.ITEMSPEC,
           MTRODRD.EXPDATE,
           CASE 
             WHEN COALESCE(MTRODRD.ODRDELEMPID, 0) = 0 THEN ''
             ELSE COALESCE(MSTEMP.EMPNM, SNS_EMP.EMPNM, CAST(MTRODRD.ODRDELEMPID AS CHAR))
           END AS ODRDELEMPID,
           MTRODRD.ODRQTY, MTRODRD.MTRODRPRICE, MTRODRD.MTRODRAMT,
           MTRODRD.MTRODRFPRICE, MTRODRD.MTRODRFAMT
    FROM MTRODRD
    LEFT JOIN MSTITEM
      ON MSTITEM.ITEMID = MTRODRD.ITEMID
     AND (COALESCE($COMPANYCD, '') = '' OR MSTITEM.COMPANYCD = $COMPANYCD)
    LEFT JOIN MSTEMP
      ON MTRODRD.ODRDELEMPID > 0
     AND (MSTEMP.EMPID = CAST(MTRODRD.ODRDELEMPID AS CHAR) OR MSTEMP.EMPCD = CAST(MTRODRD.ODRDELEMPID AS CHAR))
    LEFT JOIN MES_SNS.MSTEMP AS SNS_EMP
      ON MTRODRD.ODRDELEMPID > 0
     AND SNS_EMP.EMPID = CAST(MTRODRD.ODRDELEMPID AS CHAR)
    WHERE MTRODRD.MTRODRKEY = $MTRODRKEY
      AND (MSTITEM.ITEMCG IS NULL OR MSTITEM.ITEMCG = 'DM100700' OR MSTITEM.ITEMCG LIKE 'DM1007%' OR MSTITEM.ITEMCG = 'DM100750')
    ORDER BY MTRODRD.MTRODRSEQ ASC;

  -- *****************************************************************************

  WHEN 'CALL_RPT' THEN -- 설비부품 발주서 출력 리포트 데이터 조회 (Table 0: 헤더/공급자/공급받는자, Table 1: 디테일 품목)

    IF COALESCE($MTRODRKEY, '') = '' THEN
      CALL COMERR('발주번호를 확인해주세요.');
      LEAVE PROC;
    END IF;

    -- Table 0: 발주 헤더 및 공급자(자사)·공급받는자(거래처) 정보
    SELECT MTRODR.MTRODRKEY,
           MTRODR.MTRODRDATE,
           LEFT(MTRODR.EXPDATE, 10) AS EXPDATE,
           MTRODR.MTRODRSTT,
           COALESCE(CT_STT.TPNM, '발주승인완료') AS APRVSTTNM,
           COALESCE(LEFT(MTRODR.MTIME, 10), MTRODR.MTRODRDATE) AS APRVDATE,
           MTRODR.CUSTCD,
           COALESCE(MSTCUST.CUSTNM, '') AS CUSTNM,
           COALESCE(MSTCUST.REPRETEL, '') AS CUSTTEL,
           COALESCE(MSTCUST.CUSTFAX, '') AS CUSTFAX,
           COALESCE(MSTCUST.REGBUSSNUM, '') AS CUSTBIZNO,
           COALESCE(MSTBDV.BDVBNM_PRT, '에스앤에스아이앤씨(주)') AS COMPANYNM,
           COALESCE(MSTBDV.BDVREGNO, '339-85-02766') AS COMPANYBIZNO,
           COALESCE(MSTBDV.BDVNMENG, '양주현') AS PRESIDENT,
           COALESCE(MSTBDV.ADDR_PRT, '충청남도 보령시 주교면 관창공단길 241') AS COMPANYADDR,
           COALESCE(MSTBDV.REPRETEL, '041-931-6320') AS COMPANYTEL,
           COALESCE(MSTBDV.FAXNO, '041-931-9105') AS COMPANYFAX,
           CONCAT(
             COALESCE(GPCD('DEPTCD', MSTEMP.DEPTCD), '설비보전팀'),
             ' (',
             COALESCE(MSTEMP.EMPNM, SNS_EMP.EMPNM, '김보현'),
             CASE WHEN COALESCE(GPCD('POSBC', MSTEMP.POSBC), '') <> '' THEN CONCAT(' ', GPCD('POSBC', MSTEMP.POSBC)) ELSE ' Senior' END,
             CASE WHEN COALESCE(MSTEMP.MOBILE, '') <> '' THEN CONCAT(' ', MSTEMP.MOBILE) ELSE ' 010-4447-4873' END,
             ')'
           ) AS EMPINFO,
           COALESCE(MTRODR.REMARK, '') AS REMARK
    FROM MTRODR
    LEFT JOIN MSTCUST
      ON MSTCUST.CUSTCD = MTRODR.CUSTCD
    LEFT JOIN MSTBDV
      ON MSTBDV.BDVCD = CASE WHEN MTRODR.ODRFACTORY = '07' OR MTRODR.INFACTORYCD = '07' THEN '71' ELSE '61' END
    LEFT JOIN MSTEMP
      ON MTRODR.ODREMPID > 0
     AND (MSTEMP.EMPID = CAST(MTRODR.ODREMPID AS CHAR) OR MSTEMP.EMPCD = CAST(MTRODR.ODREMPID AS CHAR))
    LEFT JOIN MES_SNS.MSTEMP AS SNS_EMP
      ON MTRODR.ODREMPID > 0
     AND SNS_EMP.EMPID = CAST(MTRODR.ODREMPID AS CHAR)
    LEFT JOIN COMTYPE CT_STT
      ON CT_STT.GPCD = 'MM110'
     AND CT_STT.TPCD = MTRODR.MTRODRSTT
    WHERE MTRODR.MTRODRKEY = $MTRODRKEY
    LIMIT 1;

    -- Table 1: 발주 품목 디테일 목록 (15행 그리드 바인딩용)
    SELECT CAST(ROW_NUMBER() OVER(ORDER BY MTRODRD.MTRODRSEQ ASC) AS CHAR) AS NO,
           MTRODRD.MTRODRSEQ,
           MSTITEM.ITEMCD,
           MSTITEM.ITEMNM,
           MSTITEM.ITEMSPEC,
           CASE 
             WHEN MSTITEM.ITEMUNIT = 'DM150100' THEN 'EA'
             ELSE COALESCE(GPCD('DM150', MSTITEM.ITEMUNIT), 'EA')
           END AS ITEMUNIT,
           COALESCE(MTRODRD.MTRODRPRICE, 0) AS PRICE,
           COALESCE(MTRODRD.ODRQTY, 0) AS QTY,
           COALESCE(MTRODRD.MTRODRAMT, 0) AS AMT,
           COALESCE(MTRODRD.REMARK, '') AS REMARK
    FROM MTRODRD
    LEFT JOIN MSTITEM
      ON MSTITEM.ITEMID = MTRODRD.ITEMID
    WHERE MTRODRD.MTRODRKEY = $MTRODRKEY
    ORDER BY MTRODRD.MTRODRSEQ ASC;

  -- *****************************************************************************
  ELSE
    CALL COMERR('파라미터값을 확인해주세요.');
    LEAVE PROC;
  -- *****************************************************************************
  END CASE;

END