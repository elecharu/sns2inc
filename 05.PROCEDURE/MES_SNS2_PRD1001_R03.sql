CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.PRD1001_R03(
  -- *****************************************************************************
-- Comment: 자재, 외주품 발주량 계산
-- Create: 2026-10-14 신정수 
-- Modify: 
-- *****************************************************************************
  IN $SDATE VARCHAR(10),      
  IN $EDATE VARCHAR(10),      
  IN $FACTORYCD VARCHAR(100),   -- 공장코드
  IN $ITEMID INT,              -- 품목번호
  IN $ITEMCD VARCHAR(100),      -- 품목코드   

-- *****************************************************************************
 IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- SET @DEBUGLOGYN = 'Y'; 
-- *****************************************************************************
  DECLARE _$PRODUCT_LIST MEDIUMTEXT;
  DECLARE _$ITEMID_PRODUCT INT;
  DECLARE _$COUNT INT;
-- ****************************************************************************
CASE $CALLTYPE
-- ****************************************************************************
WHEN 'LIST_MTRPLAN' THEN  -- 자재, 외주품 발주량 계산

  IF LEFT($SDATE, 7) != LEFT($EDATE, 7) THEN
    CALL COMERR('시작일과 종료일의 월이 다르게 조회할 수는 없습니다.');
    LEAVE PROC;
  END IF;

  IF NOT EXISTS (SELECT ITEMID FROM PRDPLAN_M WHERE PMONTH = LEFT($SDATE, 7) AND APPYN = 'Y') THEN
    CALL COMERR(CONCAT('확정된 월생산계획이 없습니다.'
                      , '\n- 계획월: ', LEFT($SDATE, 7)
                      )
               );
    LEAVE PROC;
  END IF;

  -- 주간 생산계획 만들 반제품 찾기 (열전, 열후, 롤링, 조립, 절단 공정만)
  DROP TABLE IF EXISTS TEMP_END;
  CREATE TEMPORARY TABLE TEMP_END (
    LEVEL  DECIMAL(20, 0) NOT NULL,
    ENDYN  VARCHAR(1) NOT NULL,
    IDX    VARCHAR(1000) NOT NULL,
    PIDX   VARCHAR(1000) NOT NULL,
    RITEMID VARCHAR(100) NOT NULL,
    MITEMID VARCHAR(100) NOT NULL,
    ITEMID VARCHAR(100) NOT NULL,
    MUSAGE DECIMAL(20, 8),
    CUSAGE DECIMAL(20, 8),
    MPLANQTY DECIMAL(20, 8),
    CPLANQTY DECIMAL(20, 8),
    PRCCD VARCHAR(100) NOT NULL,
    BOMSEQ INT 
  );

  DROP TABLE IF EXISTS TEMP_CUR;
  CREATE TEMPORARY TABLE TEMP_CUR (
    IDX    VARCHAR(1000) NOT NULL,
    PIDX   VARCHAR(1000) NOT NULL,
    RITEMID VARCHAR(100) NOT NULL,
    MITEMID VARCHAR(100) NOT NULL,
    ITEMID VARCHAR(100) NOT NULL,
    MUSAGE DECIMAL(20, 8),
    CUSAGE DECIMAL(20, 8),
    MPLANQTY DECIMAL(20, 8),
    CPLANQTY DECIMAL(20, 8),
    PRCCD VARCHAR(100) NOT NULL,
    BOMSEQ INT 
  );

  DROP TABLE IF EXISTS TEMP_MTRPLAN;
  CREATE TEMPORARY TABLE TEMP_MTRPLAN (
    IDX    VARCHAR(1000) NOT NULL,
    PIDX   VARCHAR(1000) NOT NULL,
    RITEMID VARCHAR(100) NOT NULL,
    MITEMID VARCHAR(100) NOT NULL,
    ITEMID VARCHAR(100) NOT NULL,
    PRCCD VARCHAR(100) NOT NULL,
    QTYTP VARCHAR(100) NOT NULL,

    QTY_1 VARCHAR(100) NOT NULL,
    QTY_2 VARCHAR(100) NOT NULL,
    QTY_3 VARCHAR(100) NOT NULL,
    QTY_4 VARCHAR(100) NOT NULL,
    QTY_5 VARCHAR(100) NOT NULL,
    QTY_6 VARCHAR(100) NOT NULL,
    QTY_7 VARCHAR(100) NOT NULL,
    QTY_8 VARCHAR(100) NOT NULL,
    QTY_9 VARCHAR(100) NOT NULL,
    QTY_10 VARCHAR(100) NOT NULL,

    QTY_11 VARCHAR(100) NOT NULL,
    QTY_12 VARCHAR(100) NOT NULL,
    QTY_13 VARCHAR(100) NOT NULL,
    QTY_14 VARCHAR(100) NOT NULL,
    QTY_15 VARCHAR(100) NOT NULL,
    QTY_16 VARCHAR(100) NOT NULL,
    QTY_17 VARCHAR(100) NOT NULL,
    QTY_18 VARCHAR(100) NOT NULL,
    QTY_19 VARCHAR(100) NOT NULL,
    QTY_20 VARCHAR(100) NOT NULL,

    QTY_21 VARCHAR(100) NOT NULL,
    QTY_22 VARCHAR(100) NOT NULL,
    QTY_23 VARCHAR(100) NOT NULL,
    QTY_24 VARCHAR(100) NOT NULL,
    QTY_25 VARCHAR(100) NOT NULL,
    QTY_26 VARCHAR(100) NOT NULL,
    QTY_27 VARCHAR(100) NOT NULL,
    QTY_28 VARCHAR(100) NOT NULL,
    QTY_29 VARCHAR(100) NOT NULL,
    QTY_30 VARCHAR(100) NOT NULL,
    QTY_31 VARCHAR(100) NOT NULL
  );

  SET _$PRODUCT_LIST = IFNULL((
                                SELECT
                                  GROUP_CONCAT(PLAN_M.ITEMID ORDER BY ITEMID ASC SEPARATOR '»')
                                FROM PRDPLAN_M AS PLAN_M
                                WHERE PLAN_M.PMONTH = LEFT($SDATE, 7)
                                  AND PLAN_M.APPYN = 'Y'
                              ), '');


  WHILE LENGTH(_$PRODUCT_LIST) > 0 DO
    CALL COMSPLIT(_$PRODUCT_LIST, _$ITEMID_PRODUCT);

    INSERT INTO TEMP_END (LEVEL, ENDYN, IDX, PIDX, RITEMID, MITEMID, ITEMID, BOMSEQ,  PRCCD, CPLANQTY)
    SELECT 0, 'N', MSTITEM.ITEMID, '', MSTITEM.ITEMID, '', MSTITEM.ITEMID, 0, '', PLAN_M.PLANQTY
    FROM MSTITEM
    INNER JOIN PRDPLAN_M AS PLAN_M
      ON PLAN_M.ITEMID = MSTITEM.ITEMID
    WHERE MSTITEM.ITEMID = _$ITEMID_PRODUCT;
  
    SET _$COUNT = 1;
  
    WHILE _$COUNT < 20 DO
  
      TRUNCATE TABLE TEMP_CUR;
      INSERT INTO TEMP_CUR (
        IDX,  PIDX, 
        RITEMID,
        MITEMID, ITEMID, 
        MUSAGE, CUSAGE, BOMSEQ,
        MPLANQTY, CPLANQTY,
        PRCCD
      )
      SELECT 
        CONCAT(TEMP_END.IDX, '      ' , MSTBOM.CITEMID),   TEMP_END.IDX,     
        TEMP_END.RITEMID,
        MSTBOM.MITEMID,  MSTBOM.CITEMID,    
        IF(MSTBOM.MUSAGE IN (NULL, 0), 1, MSTBOM.MUSAGE), IF(MSTBOM.CUSAGE IN (NULL, 0), 1, MSTBOM.CUSAGE), MSTBOM.PRCSEQ,
        TEMP_END.CPLANQTY, TEMP_END.CPLANQTY * (IF(MSTBOM.CUSAGE IN (NULL, 0), 1, MSTBOM.CUSAGE) / IF(MSTBOM.MUSAGE IN (NULL, 0), 1, MSTBOM.MUSAGE)),
        MSTBOM.PRCCD
      FROM TEMP_END
      INNER JOIN MSTBOM 
       ON TEMP_END.ITEMID = MSTBOM.MITEMID
      WHERE TEMP_END.ENDYN = 'N'
      ;
  
      UPDATE TEMP_END SET ENDYN = 'Y';
  
      INSERT INTO TEMP_END (LEVEL, ENDYN, IDX, PIDX, RITEMID, MITEMID, ITEMID, MUSAGE, CUSAGE, MPLANQTY, CPLANQTY, BOMSEQ, PRCCD)
      SELECT _$COUNT, 'N', IDX, PIDX, RITEMID, MITEMID, ITEMID, MUSAGE, CUSAGE, MPLANQTY, CPLANQTY, BOMSEQ, PRCCD
      FROM TEMP_CUR;
  
      SET _$COUNT = _$COUNT + 1;   
    END WHILE;
  END WHILE;

  SELECT
      TEMP_END.RITEMID
    , CONCAT(RITEM.ITEMCD, ' (', RITEM.ITEMNM, ')') AS RITEMNM
    , TEMP_END.IDX
    , TEMP_END.MITEMID
    , TEMP_END.ITEMID
    , MSTITEM.ITEMCD
    , MSTITEM.ITEMNM
    , MSTITEM.ITEMSPEC
    , MSTROUT_DETAIL.ROUTCD
    , MSTPRC.PRCCD
    , MSTPRC.PRCNM
  FROM TEMP_END
  INNER JOIN MSTITEM AS RITEM
    ON RITEM.ITEMID = TEMP_END.RITEMID
  INNER JOIN MSTITEM
    ON MSTITEM.ITEMID = TEMP_END.ITEMID
  INNER JOIN MSTROUT_MATCH
    ON MSTROUT_MATCH.ITEMID = MSTITEM.ITEMID
   AND MSTROUT_MATCH.BASEYN = 'Y'
  INNER JOIN MSTROUT_DETAIL
    ON MSTROUT_DETAIL.ROUTCD = MSTROUT_MATCH.ROUTCD
  LEFT JOIN MSTPRC
    ON MSTPRC.PRCCD = TEMP_END.PRCCD
  WHERE IF(RITEM.ITEMID = MSTITEM.ITEMID, 1=1,
            (  MSTPRC.USEYN = 'Y'
               AND MSTPRC.FACTORYCD = '07'
--                AND MSTPRC.PRCCD NOT IN ('I2M1400_N', 'I2M1600_N')
            )
          )    
  GROUP BY  TEMP_END.RITEMID
          , TEMP_END.ITEMID 
  ORDER BY TEMP_END.RITEMID
         , TEMP_END.IDX DESC
  ;

  -- 1. 현재고 구하기(첫날 소재잔량)
--   INSERT INTO TEMP_MTRPLAN (IDX, PIDX, RITEMID, MITEMID, ITEMID, PRCCD
--     , QTYTP
--     , QTY_1, QTY_2, QTY_3, QTY_4, QTY_5, QTY_6, QTY_7, QTY_8, QTY_9, QTY_10
--     , QTY_11, QTY_12, QTY_13, QTY_14, QTY_15, QTY_16, QTY_17, QTY_18, QTY_19, QTY_20
--     , QTY_21, QTY_22, QTY_23, QTY_24, QTY_25, QTY_26, QTY_27, QTY_28, QTY_29, QTY_30, QTY_31)
  SELECT
      TEMP_END.IDX, TEMP_END.PIDX, TEMP_END.RITEMID, TEMP_END.MITEMID, TEMP_END.ITEMID, TEMP_END.PRCCD
    , SUM(COMLOT.LOTQTY) AS SUMQTY
  FROM TEMP_END
  LEFT JOIN COMLOT
    ON COMLOT.ITEMID = TEMP_END.ITEMID
  WHERE COMLOT.LOTQTY > 0
    AND COMLOT.WARECD NOT IN (
    '04S130_N',
    '04S132_N',
    '04S230_N',
    '04S990_N',
    '04S991_N',
    '04S992_N',
    '04U001_N',
    '04U030_N',
    '04U050_N',
    '04Z100_N'
  );

  -- 2. 당일 생산계획 구하기 (제품은 출하계획)
  -- 3. 당일 소재입고 로우 만들기 (제품은 제품생산입고)

  -- 근무시간
  SELECT
      WORKDATE
    , DAYTIME + OVERTIME_DY AS WORKTIME_DAY
    , NIGHTTIME + OVERTIME_NT AS WORKTIME_NIGHT
  FROM PRDWORKTIME
  WHERE WORKMONTH = LEFT($SDATE, 7) 
  ;

  DROP TABLE IF EXISTS TEMP_END;
  DROP TABLE IF EXISTS TEMP_CUR;
  DROP TABLE IF EXISTS TEMP_MTRPLAN;

-- ****************************************************************************
END CASE; END