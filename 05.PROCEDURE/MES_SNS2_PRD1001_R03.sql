      TRUNCATE TABLE TEMP_CUR;
      INSERT INTO TEMP_CUR (
        IDX,  PIDX, 
        RITEMID,
        MITEMID, ITEMID, 
        MUSAGE, CUSAGE, BOMSEQ,
        MPLANQTY, CPLANQTY,
        PRCCD
      )
      SELECT 
        CONCAT(TEMP_END.IDX, '      ' , MSTBOM.CITEMID),   TEMP_END.IDX,     
        TEMP_END.RITEMID,
        MSTBOM.MITEMID,  MSTBOM.CITEMID,    
        IF(MSTBOM.MUSAGE IN (NULL, 0), 1, MSTBOM.MUSAGE), IF(MSTBOM.CUSAGE IN (NULL, 0), 1, MSTBOM.CUSAGE), MSTBOM.PRCSEQ,
        TEMP_END.CPLANQTY, TEMP_END.CPLANQTY * (IF(MSTBOM.CUSAGE IN (NULL, 0), 1, MSTBOM.CUSAGE) / IF(MSTBOM.MUSAGE IN (NULL, 0), 1, MSTBOM.MUSAGE)),
        MSTBOM.PRCCD
      FROM TEMP_END
      INNER JOIN MSTBOM 
       ON TEMP_END.ITEMID = MSTBOM.MITEMID
      WHERE TEMP_END.ENDYN = 'N'
      ;
  
      UPDATE TEMP_END SET ENDYN = 'Y';
  
      INSERT INTO TEMP_END (LEVEL, ENDYN, IDX, PIDX, RITEMID, MITEMID, ITEMID, MUSAGE, CUSAGE, MPLANQTY, CPLANQTY, BOMSEQ, PRCCD)
      SELECT _$COUNT, 'N', IDX, PIDX, RITEMID, MITEMID, ITEMID, MUSAGE, CUSAGE, MPLANQTY, CPLANQTY, BOMSEQ, PRCCD
      FROM TEMP_CUR;
  
      SET _$COUNT = _$COUNT + 1;   
    END WHILE;
  END WHILE;


  -- 1. 현재고 구하기(첫날 소재잔량)
  INSERT INTO TEMP_MTRPLAN (
      IDX, RITEMID, MITEMID, ITEMID, PRCCD
    , QTYTP
    , QTY_1, QTY_2, QTY_3, QTY_4, QTY_5, QTY_6, QTY_7, QTY_8, QTY_9, QTY_10
    , QTY_11, QTY_12, QTY_13, QTY_14, QTY_15, QTY_16, QTY_17, QTY_18, QTY_19, QTY_20
    , QTY_21, QTY_22, QTY_23, QTY_24, QTY_25, QTY_26, QTY_27, QTY_28, QTY_29, QTY_30, QTY_31
  )
  SELECT
      STOCK_RESULT.IDX, STOCK_RESULT.RITEMID, STOCK_RESULT.MITEMID, STOCK_RESULT.ITEMID, STOCK_RESULT.PRCCD
    , STOCK_RESULT.QTYTP
    , IF(STOCK_RESULT.QTY_1 = 0, '', STOCK_RESULT.QTY_1)
    , IF(STOCK_RESULT.QTY_2 = 0, '', STOCK_RESULT.QTY_2)
    , IF(STOCK_RESULT.QTY_3 = 0, '', STOCK_RESULT.QTY_3)
    , IF(STOCK_RESULT.QTY_4 = 0, '', STOCK_RESULT.QTY_4)
    , IF(STOCK_RESULT.QTY_5 = 0, '', STOCK_RESULT.QTY_5)
    , IF(STOCK_RESULT.QTY_6 = 0, '', STOCK_RESULT.QTY_6)
    , IF(STOCK_RESULT.QTY_7 = 0, '', STOCK_RESULT.QTY_7)
    , IF(STOCK_RESULT.QTY_8 = 0, '', STOCK_RESULT.QTY_8)
    , IF(STOCK_RESULT.QTY_9 = 0, '', STOCK_RESULT.QTY_9)
    , IF(STOCK_RESULT.QTY_10 = 0, '', STOCK_RESULT.QTY_10)

    , IF(STOCK_RESULT.QTY_11 = 0, '', STOCK_RESULT.QTY_11)
    , IF(STOCK_RESULT.QTY_12 = 0, '', STOCK_RESULT.QTY_12)
    , IF(STOCK_RESULT.QTY_13 = 0, '', STOCK_RESULT.QTY_13)
    , IF(STOCK_RESULT.QTY_14 = 0, '', STOCK_RESULT.QTY_14)
    , IF(STOCK_RESULT.QTY_15 = 0, '', STOCK_RESULT.QTY_15)
    , IF(STOCK_RESULT.QTY_16 = 0, '', STOCK_RESULT.QTY_16)
    , IF(STOCK_RESULT.QTY_17 = 0, '', STOCK_RESULT.QTY_17)
    , IF(STOCK_RESULT.QTY_18 = 0, '', STOCK_RESULT.QTY_18)
    , IF(STOCK_RESULT.QTY_19 = 0, '', STOCK_RESULT.QTY_19)
    , IF(STOCK_RESULT.QTY_20 = 0, '', STOCK_RESULT.QTY_20)

    , IF(STOCK_RESULT.QTY_21 = 0, '', STOCK_RESULT.QTY_21)
    , IF(STOCK_RESULT.QTY_22 = 0, '', STOCK_RESULT.QTY_22)
    , IF(STOCK_RESULT.QTY_23 = 0, '', STOCK_RESULT.QTY_23)
    , IF(STOCK_RESULT.QTY_24 = 0, '', STOCK_RESULT.QTY_24)
    , IF(STOCK_RESULT.QTY_25 = 0, '', STOCK_RESULT.QTY_25)
    , IF(STOCK_RESULT.QTY_26 = 0, '', STOCK_RESULT.QTY_26)
    , IF(STOCK_RESULT.QTY_27 = 0, '', STOCK_RESULT.QTY_27)
    , IF(STOCK_RESULT.QTY_28 = 0, '', STOCK_RESULT.QTY_28)
    , IF(STOCK_RESULT.QTY_29 = 0, '', STOCK_RESULT.QTY_29)
    , IF(STOCK_RESULT.QTY_30 = 0, '', STOCK_RESULT.QTY_30)
    , IF(STOCK_RESULT.QTY_31 = 0, '', STOCK_RESULT.QTY_31)
  FROM (
          SELECT
              STOCK.IDX, STOCK.RITEMID, STOCK.MITEMID, STOCK.ITEMID, STOCK.PRCCD
            , '소재잔량' AS QTYTP
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '01', STOCK.SUMQTY, 0)) AS QTY_1
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '02', STOCK.SUMQTY, 0)) AS QTY_2
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '03', STOCK.SUMQTY, 0)) AS QTY_3
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '04', STOCK.SUMQTY, 0)) AS QTY_4
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '05', STOCK.SUMQTY, 0)) AS QTY_5
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '06', STOCK.SUMQTY, 0)) AS QTY_6
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '07', STOCK.SUMQTY, 0)) AS QTY_7
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '08', STOCK.SUMQTY, 0)) AS QTY_8
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '09', STOCK.SUMQTY, 0)) AS QTY_9
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '10', STOCK.SUMQTY, 0)) AS QTY_10
        
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '11', STOCK.SUMQTY, 0)) AS QTY_11
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '12', STOCK.SUMQTY, 0)) AS QTY_12
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '13', STOCK.SUMQTY, 0)) AS QTY_13
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '14', STOCK.SUMQTY, 0)) AS QTY_14
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '15', STOCK.SUMQTY, 0)) AS QTY_15
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '16', STOCK.SUMQTY, 0)) AS QTY_16
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '17', STOCK.SUMQTY, 0)) AS QTY_17
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '18', STOCK.SUMQTY, 0)) AS QTY_18
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '19', STOCK.SUMQTY, 0)) AS QTY_19
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '20', STOCK.SUMQTY, 0)) AS QTY_20
        
        
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '21', STOCK.SUMQTY, 0)) AS QTY_21
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '22', STOCK.SUMQTY, 0)) AS QTY_22
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '23', STOCK.SUMQTY, 0)) AS QTY_23
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '24', STOCK.SUMQTY, 0)) AS QTY_24
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '25', STOCK.SUMQTY, 0)) AS QTY_25
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '26', STOCK.SUMQTY, 0)) AS QTY_26
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '27', STOCK.SUMQTY, 0)) AS QTY_27
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '28', STOCK.SUMQTY, 0)) AS QTY_28
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '29', STOCK.SUMQTY, 0)) AS QTY_29
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '30', STOCK.SUMQTY, 0)) AS QTY_30
            , SUM(IF(RIGHT(STOCK.STOCKDATE, 2) = '31', STOCK.SUMQTY, 0)) AS QTY_31
          FROM (
                  SELECT
                      TEMP_END.IDX, TEMP_END.RITEMID, TEMP_END.MITEMID, TEMP_END.ITEMID, TEMP_END.PRCCD
                    , $SDATE AS STOCKDATE
                    , IFNULL(SUM(COMLOT.LOTQTY), 0) AS SUMQTY
                  FROM TEMP_END
                  LEFT JOIN COMLOT
                    ON COMLOT.ITEMID = TEMP_END.ITEMID
                   AND COMLOT.LOTQTY > 0
                   -- 제외창고
                   AND COMLOT.WARECD NOT IN (  
                    '04S130_N',
                    '04S132_N',
                    '04S230_N',
                    '04S990_N',
                    '04S991_N',
                    '04S992_N',
                    '04U001_N',
                    '04U030_N',
                    '04U050_N',
                    '04Z100_N'
                  )
                  GROUP BY TEMP_END.RITEMID, TEMP_END.MITEMID, TEMP_END.ITEMID
               ) AS STOCK
          GROUP BY STOCK.RITEMID, STOCK.MITEMID, STOCK.ITEMID
       ) AS STOCK_RESULT
  ;



  -- 2. 당일 생산계획 구하기 (제품은 출하계획)
  INSERT INTO TEMP_MTRPLAN (
      IDX, RITEMID, MITEMID, ITEMID, PRCCD
    , QTYTP
    , QTY_1, QTY_2, QTY_3, QTY_4, QTY_5, QTY_6, QTY_7, QTY_8, QTY_9, QTY_10
    , QTY_11, QTY_12, QTY_13, QTY_14, QTY_15, QTY_16, QTY_17, QTY_18, QTY_19, QTY_20
    , QTY_21, QTY_22, QTY_23, QTY_24, QTY_25, QTY_26, QTY_27, QTY_28, QTY_29, QTY_30, QTY_31
  )
  SELECT
      WEEKPLAN_RESULT.IDX, WEEKPLAN_RESULT.RITEMID, WEEKPLAN_RESULT.MITEMID, WEEKPLAN_RESULT.ITEMID, WEEKPLAN_RESULT.PRCCD
    , WEEKPLAN_RESULT.QTYTP
    , IF(WEEKPLAN_RESULT.QTY_1 = 0, '', WEEKPLAN_RESULT.QTY_1)
    , IF(WEEKPLAN_RESULT.QTY_2 = 0, '', WEEKPLAN_RESULT.QTY_2)
    , IF(WEEKPLAN_RESULT.QTY_3 = 0, '', WEEKPLAN_RESULT.QTY_3)
    , IF(WEEKPLAN_RESULT.QTY_4 = 0, '', WEEKPLAN_RESULT.QTY_4)
    , IF(WEEKPLAN_RESULT.QTY_5 = 0, '', WEEKPLAN_RESULT.QTY_5)
    , IF(WEEKPLAN_RESULT.QTY_6 = 0, '', WEEKPLAN_RESULT.QTY_6)
    , IF(WEEKPLAN_RESULT.QTY_7 = 0, '', WEEKPLAN_RESULT.QTY_7)
    , IF(WEEKPLAN_RESULT.QTY_8 = 0, '', WEEKPLAN_RESULT.QTY_8)
    , IF(WEEKPLAN_RESULT.QTY_9 = 0, '', WEEKPLAN_RESULT.QTY_9)
    , IF(WEEKPLAN_RESULT.QTY_10 = 0, '', WEEKPLAN_RESULT.QTY_10)

    , IF(WEEKPLAN_RESULT.QTY_11 = 0, '', WEEKPLAN_RESULT.QTY_11)
    , IF(WEEKPLAN_RESULT.QTY_12 = 0, '', WEEKPLAN_RESULT.QTY_12)
    , IF(WEEKPLAN_RESULT.QTY_13 = 0, '', WEEKPLAN_RESULT.QTY_13)
    , IF(WEEKPLAN_RESULT.QTY_14 = 0, '', WEEKPLAN_RESULT.QTY_14)
    , IF(WEEKPLAN_RESULT.QTY_15 = 0, '', WEEKPLAN_RESULT.QTY_15)
    , IF(WEEKPLAN_RESULT.QTY_16 = 0, '', WEEKPLAN_RESULT.QTY_16)
    , IF(WEEKPLAN_RESULT.QTY_17 = 0, '', WEEKPLAN_RESULT.QTY_17)
    , IF(WEEKPLAN_RESULT.QTY_18 = 0, '', WEEKPLAN_RESULT.QTY_18)
    , IF(WEEKPLAN_RESULT.QTY_19 = 0, '', WEEKPLAN_RESULT.QTY_19)
    , IF(WEEKPLAN_RESULT.QTY_20 = 0, '', WEEKPLAN_RESULT.QTY_20)

    , IF(WEEKPLAN_RESULT.QTY_21 = 0, '', WEEKPLAN_RESULT.QTY_21)
    , IF(WEEKPLAN_RESULT.QTY_22 = 0, '', WEEKPLAN_RESULT.QTY_22)
    , IF(WEEKPLAN_RESULT.QTY_23 = 0, '', WEEKPLAN_RESULT.QTY_23)
    , IF(WEEKPLAN_RESULT.QTY_24 = 0, '', WEEKPLAN_RESULT.QTY_24)
    , IF(WEEKPLAN_RESULT.QTY_25 = 0, '', WEEKPLAN_RESULT.QTY_25)
    , IF(WEEKPLAN_RESULT.QTY_26 = 0, '', WEEKPLAN_RESULT.QTY_26)
    , IF(WEEKPLAN_RESULT.QTY_27 = 0, '', WEEKPLAN_RESULT.QTY_27)
    , IF(WEEKPLAN_RESULT.QTY_28 = 0, '', WEEKPLAN_RESULT.QTY_28)
    , IF(WEEKPLAN_RESULT.QTY_29 = 0, '', WEEKPLAN_RESULT.QTY_29)
    , IF(WEEKPLAN_RESULT.QTY_30 = 0, '', WEEKPLAN_RESULT.QTY_30)
    , IF(WEEKPLAN_RESULT.QTY_31 = 0, '', WEEKPLAN_RESULT.QTY_31)
  FROM (
          SELECT
              WEEKPLAN.IDX, WEEKPLAN.RITEMID, WEEKPLAN.MITEMID, WEEKPLAN.ITEMID, WEEKPLAN.PRCCD
            , '생산계획' AS QTYTP
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '01', WEEKPLAN.PLANQTY, 0)) AS QTY_1
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '02', WEEKPLAN.PLANQTY, 0)) AS QTY_2
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '03', WEEKPLAN.PLANQTY, 0)) AS QTY_3
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '04', WEEKPLAN.PLANQTY, 0)) AS QTY_4
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '05', WEEKPLAN.PLANQTY, 0)) AS QTY_5
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '06', WEEKPLAN.PLANQTY, 0)) AS QTY_6
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '07', WEEKPLAN.PLANQTY, 0)) AS QTY_7
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '08', WEEKPLAN.PLANQTY, 0)) AS QTY_8
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '09', WEEKPLAN.PLANQTY, 0)) AS QTY_9
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '10', WEEKPLAN.PLANQTY, 0)) AS QTY_10
        
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '11', WEEKPLAN.PLANQTY, 0)) AS QTY_11
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '12', WEEKPLAN.PLANQTY, 0)) AS QTY_12
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '13', WEEKPLAN.PLANQTY, 0)) AS QTY_13
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '14', WEEKPLAN.PLANQTY, 0)) AS QTY_14
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '15', WEEKPLAN.PLANQTY, 0)) AS QTY_15
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '16', WEEKPLAN.PLANQTY, 0)) AS QTY_16
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '17', WEEKPLAN.PLANQTY, 0)) AS QTY_17
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '18', WEEKPLAN.PLANQTY, 0)) AS QTY_18
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '19', WEEKPLAN.PLANQTY, 0)) AS QTY_19
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '20', WEEKPLAN.PLANQTY, 0)) AS QTY_20
        
        
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '21', WEEKPLAN.PLANQTY, 0)) AS QTY_21
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '22', WEEKPLAN.PLANQTY, 0)) AS QTY_22
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '23', WEEKPLAN.PLANQTY, 0)) AS QTY_23
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '24', WEEKPLAN.PLANQTY, 0)) AS QTY_24
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '25', WEEKPLAN.PLANQTY, 0)) AS QTY_25
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '26', WEEKPLAN.PLANQTY, 0)) AS QTY_26
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '27', WEEKPLAN.PLANQTY, 0)) AS QTY_27
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '28', WEEKPLAN.PLANQTY, 0)) AS QTY_28
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '29', WEEKPLAN.PLANQTY, 0)) AS QTY_29
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '30', WEEKPLAN.PLANQTY, 0)) AS QTY_30
            , SUM(IF(RIGHT(WEEKPLAN.PDATE, 2) = '31', WEEKPLAN.PLANQTY, 0)) AS QTY_31
          FROM (
                  SELECT
                      TEMP_END.IDX, TEMP_END.RITEMID, TEMP_END.MITEMID, TEMP_END.ITEMID, TEMP_END.PRCCD
                    , PRDPLAN_W.PDATE
                    , PRDPLAN_W.PLANQTY_DAY + PRDPLAN_W.PLANQTY_NIGHT AS PLANQTY
                  FROM TEMP_END
                  LEFT JOIN PRDPLAN_W
                    ON PRDPLAN_W.PMONTH = _$PMONTH
                   AND PRDPLAN_W.ITEMID = IF(TEMP_END.MITEMID = '', 0, TEMP_END.MITEMID)
               ) AS WEEKPLAN
          GROUP BY WEEKPLAN.RITEMID, WEEKPLAN.MITEMID, WEEKPLAN.ITEMID
