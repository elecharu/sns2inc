CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.PRD2001_S01(
-- *****************************************************************************
-- Comment: 생산실적조회 (웹)
--          ) LIST_PRDWORK: 사내공정(MSTPRC.GUBUN_BC = 'PP412001') 작업지시의 작업 목록 (작업 1건 = 1줄)
--          ) LIST_DETAIL : 선택 작업의 생산실적 / 비가동이력 / 불량상세
--          ) PRINT_DAILY : 생산일보 리포트(PRD2001.exe S01) - 선택 작업과 생산일·라인·품목이 같은 작업 전체
-- Create: 2026-11-05
-- Modify: 2026-11-05 작업 목록에 주야구분(PRDINS.DNTP: DAY 주간 / NIGHT 야간) 추가
--         2026-11-05 상세의 생산실적·사용로트·생산로트를 생산실적 하나로 합침 (결과: 생산실적 / 비가동 / 불량)
--         2026-11-06 생산일보 출력(PRINT_DAILY) 추가
--         2026-11-06 생산일보 불량현황을 중분류(QM220)·불량명별로 변경 (불량상세 제외)
-- *****************************************************************************
  IN $SDATE VARCHAR(10),        -- 작업일자 시작
  IN $EDATE VARCHAR(10),        -- 작업일자 종료
  IN $LINECD VARCHAR(100),      -- 작업장
  IN $PRCCD VARCHAR(100),       -- 공정
  IN $EQMCD VARCHAR(100),       -- 라인
  IN $ITEMID VARCHAR(100),      -- 품목ID
  IN $PRDWORKKEY VARCHAR(100),  -- 작업키
-- *****************************************************************************
  IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  DECLARE _$WORKDATE VARCHAR(10);
  DECLARE _$EQMCD VARCHAR(100);
  DECLARE _$ITEMID VARCHAR(100);
-- *****************************************************************************
CASE $CALLTYPE
-- ****************************************************************************
WHEN 'LIST_PRDWORK' THEN  -- 작업 목록

  IF $SDATE = '' OR $EDATE = '' THEN
    CALL COMERR('작업일자를 입력하세요.');
    LEAVE PROC;
  END IF;

  SELECT
      PRDWORK.WORKDATE
    , CASE PRDINS.DNTP
        WHEN 'DAY' THEN '주간'
        WHEN 'NIGHT' THEN '야간'
        ELSE PRDINS.DNTP
      END AS DNTPNM
    , PRDWORK.WORKSTIME
    , PRDWORK.WORKETIME
    , IFNULL(MSTLINE.LINENM, PRDWORK.LINECD) AS LINENM
    , MSTPRC.PRCNM
    , IFNULL(MSTLINE_EQM.EQMNM, PRDWORK.EQMCD) AS EQMNM
    , MSTITEM.ITEMCD
    , MSTITEM.ITEMNM
    , MSTITEM.ITEMSPEC
    , IFNULL(WORK_EMP.EMPNM, '') AS EMPNM
    , PRDINS.INSQTY
    , IFNULL(WORK_RST.PRODQTY, 0) AS PRODQTY
    , IFNULL(WORK_RST.GOODQTY, 0) AS GOODQTY
    , IFNULL(WORK_RST.BADQTY, 0) AS BADQTY
    , IFNULL(WORK_NON.NONMIN, 0) AS NONMIN
    , PRDWORK.WORKSTT
    , PRDWORK.PRDINSKEY
    , PRDWORK.PRDWORKKEY
  FROM PRDWORK
  INNER JOIN PRDINS
    ON PRDINS.PRDINSKEY = PRDWORK.PRDINSKEY
  INNER JOIN MSTPRC
    ON MSTPRC.PRCCD = PRDINS.PRCCD
   AND MSTPRC.GUBUN_BC = 'PP412001' -- 사내공정
  LEFT JOIN MSTLINE
    ON MSTLINE.LINECD = PRDWORK.LINECD
  LEFT JOIN MSTLINE_EQM
    ON MSTLINE_EQM.EQMCD = PRDWORK.EQMCD
  LEFT JOIN MSTITEM
    ON MSTITEM.ITEMID = PRDWORK.ITEMID
  LEFT JOIN (
              -- 작업자 (PRDWORK_EMP, 이름순)
              SELECT
                  PRDWORK_EMP.PRDWORKKEY
                , GROUP_CONCAT(IFNULL(MSTEMP.EMPNM, PRDWORK_EMP.EMPCD) SEPARATOR ', ') AS EMPNM
              FROM PRDWORK_EMP
              LEFT JOIN MSTEMP
                ON MSTEMP.EMPCD = PRDWORK_EMP.EMPCD
              GROUP BY PRDWORK_EMP.PRDWORKKEY
            ) AS WORK_EMP
    ON WORK_EMP.PRDWORKKEY = PRDWORK.PRDWORKKEY
  LEFT JOIN (
              -- 작업별 실적 합계
              SELECT
                  PRDRST.PRDWORKKEY
                , SUM(PRDRST.PRODQTY) AS PRODQTY
                , SUM(PRDRST.GOODQTY) AS GOODQTY
                , SUM(PRDRST.BADQTY) AS BADQTY
              FROM PRDRST
              GROUP BY PRDRST.PRDWORKKEY
            ) AS WORK_RST
    ON WORK_RST.PRDWORKKEY = PRDWORK.PRDWORKKEY
  LEFT JOIN (
              -- 작업별 비가동 시간 합계 (끝난 것만)
              SELECT
                  PRDRSTNON.PRDWORKKEY
                , SUM(TIMESTAMPDIFF(MINUTE, PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME)) AS NONMIN
              FROM PRDRSTNON
              WHERE PRDRSTNON.PRDWORKKEY <> ''
                AND PRDRSTNON.NONETIME <> ''
              GROUP BY PRDRSTNON.PRDWORKKEY
            ) AS WORK_NON
    ON WORK_NON.PRDWORKKEY = PRDWORK.PRDWORKKEY
  WHERE PRDWORK.WORKDATE BETWEEN $SDATE AND $EDATE
    AND ($LINECD = '' OR PRDWORK.LINECD = $LINECD)
    AND ($PRCCD = '' OR PRDWORK.PRCCD = $PRCCD)
    AND ($EQMCD = '' OR PRDWORK.EQMCD = $EQMCD)
    AND ($ITEMID = '' OR PRDWORK.ITEMID = $ITEMID)
  ORDER BY PRDWORK.WORKDATE, PRDWORK.WORKSTIME, PRDWORK.PRDWORKKEY
  ;

-- ****************************************************************************
WHEN 'LIST_DETAIL' THEN  -- 선택 작업 상세

  IF $PRDWORKKEY = '' THEN
    CALL COMERR('작업을 선택하세요.');
    LEAVE PROC;
  END IF;

  -- 0. 생산실적 (투입로트 1개 = 1줄, 가공완료 로트·수량은 실적 값을 줄마다 반복 → 화면에서 셀 병합)
  SELECT
      IFNULL(PRDRSTUSE.USELOTKEY, '') AS USELOTKEY
    , IFNULL(PRDRSTLOT.LOTKEY, '') AS LOTKEY
    , PRDRST.GOODQTY
    , PRDRST.BADQTY
    , PRDRST.PRODQTY
  FROM PRDRST
  LEFT JOIN PRDRSTUSE
    ON PRDRSTUSE.PRDRSTKEY = PRDRST.PRDRSTKEY
  LEFT JOIN PRDRSTLOT
    ON PRDRSTLOT.PRDRSTKEY = PRDRST.PRDRSTKEY
  WHERE PRDRST.PRDWORKKEY = $PRDWORKKEY
  ORDER BY PRDRST.RSTTIME, PRDRST.PRDRSTKEY, PRDRSTUSE.RTIME, PRDRSTUSE.USELOTKEY
  ;

  -- 1. 비가동이력
  SELECT
      IFNULL(GPCD('PP409', MSTNON.NONGROUPCD1), '') AS NONTPNM
    , IFNULL(MSTNON.NONNM, PRDRSTNON.NONCD) AS NONNM
    , PRDRSTNON.NONSTIME
    , PRDRSTNON.NONETIME
    , IF(PRDRSTNON.NONETIME = '', NULL, TIMESTAMPDIFF(MINUTE, PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME)) AS NONMIN
    , PRDRSTNON.AUTOYN
    , PRDRSTNON.PROBLEM
    , PRDRSTNON.SOLUTION
    , PRDRSTNON.REMARK
  FROM PRDRSTNON
  LEFT JOIN MSTNON
    ON MSTNON.LINECD = PRDRSTNON.LINECD
   AND MSTNON.NONCD = PRDRSTNON.NONCD
  WHERE PRDRSTNON.PRDWORKKEY = $PRDWORKKEY
  ORDER BY PRDRSTNON.NONSTIME
  ;

  -- 2. 불량상세
  SELECT
      GPCD('QM210', MSTBAD.BADTP1) AS BADTP1NM
    , GPCD('QM220', MSTBAD.BADTP2) AS BADTP2NM
    , IFNULL(MSTBAD.BADNM, PRDRSTBAD.BADCD) AS BADNM
    , PRDRSTBAD.BADDETAIL
    , PRDRSTBAD.BADQTY
    , PRDRSTBAD.REMARK
  FROM PRDRSTBAD
  INNER JOIN PRDRST
    ON PRDRST.PRDRSTKEY = PRDRSTBAD.PRDRSTKEY
  LEFT JOIN MSTBAD
    ON MSTBAD.BADCD = PRDRSTBAD.BADCD
  WHERE PRDRST.PRDWORKKEY = $PRDWORKKEY
  ORDER BY PRDRSTBAD.RTIME, PRDRSTBAD.BADCD
  ;

-- ****************************************************************************
WHEN 'PRINT_DAILY' THEN  -- 생산일보 (선택 작업과 생산일·라인·품목이 같은 사내공정 작업 전체, 주야는 PRDINS.DNTP)

  IF $PRDWORKKEY = '' THEN
    CALL COMERR('작업을 선택하세요.');
    LEAVE PROC;
  END IF;

  SELECT PRDWORK.WORKDATE, PRDWORK.EQMCD, PRDWORK.ITEMID
    INTO _$WORKDATE, _$EQMCD, _$ITEMID
    FROM PRDWORK
    WHERE PRDWORK.PRDWORKKEY = $PRDWORKKEY;

  IF IFNULL(_$WORKDATE, '') = '' THEN
    CALL COMERR('선택한 작업을 찾을 수 없습니다.');
    LEAVE PROC;
  END IF;

  -- 0. 머리 (1행): 생산일, 주·야 작업시간·작업자, 생산라인, 품명·품번, 주·야 ISSUE
  SELECT
      CONCAT(DATE_FORMAT(_$WORKDATE, '%Y년 %m월 %d일'), ' (', ELT(DAYOFWEEK(_$WORKDATE), '일', '월', '화', '수', '목', '금', '토'), '요일)') AS PRDDATE
    , IFNULL(CONCAT(SUBSTRING(MIN(IF(PRDINS.DNTP <> 'NIGHT', PRDWORK.WORKSTIME, NULL)), 12, 5), ' ~ ', SUBSTRING(MAX(IF(PRDINS.DNTP <> 'NIGHT', PRDWORK.WORKETIME, NULL)), 12, 5)), '') AS DAYTIME
    , IFNULL(CONCAT(SUBSTRING(MIN(IF(PRDINS.DNTP = 'NIGHT', PRDWORK.WORKSTIME, NULL)), 12, 5), ' ~ ', SUBSTRING(MAX(IF(PRDINS.DNTP = 'NIGHT', PRDWORK.WORKETIME, NULL)), 12, 5)), '') AS NIGHTTIME
    , IFNULL(GROUP_CONCAT(DISTINCT IF(PRDINS.DNTP <> 'NIGHT', IFNULL(MSTEMP.EMPNM, PRDWORK_EMP.EMPCD), NULL) SEPARATOR ', '), '') AS DAYEMP
    , IFNULL(GROUP_CONCAT(DISTINCT IF(PRDINS.DNTP = 'NIGHT', IFNULL(MSTEMP.EMPNM, PRDWORK_EMP.EMPCD), NULL) SEPARATOR ', '), '') AS NIGHTEMP
    , IFNULL((SELECT MSTLINE_EQM.EQMNM FROM MSTLINE_EQM WHERE MSTLINE_EQM.EQMCD = _$EQMCD LIMIT 1), _$EQMCD) AS EQMNM
    , IFNULL((SELECT MSTITEM.ITEMNM FROM MSTITEM WHERE MSTITEM.ITEMID = _$ITEMID), '') AS ITEMNM
    , IFNULL((SELECT MSTITEM.ITEMCD FROM MSTITEM WHERE MSTITEM.ITEMID = _$ITEMID), '') AS ITEMCD
    , IFNULL(GROUP_CONCAT(DISTINCT IF(PRDINS.DNTP <> 'NIGHT' AND PRDINS.ISSUE <> '', PRDINS.ISSUE, NULL) SEPARATOR '\n'), '') AS DAYISSUE
    , IFNULL(GROUP_CONCAT(DISTINCT IF(PRDINS.DNTP = 'NIGHT' AND PRDINS.ISSUE <> '', PRDINS.ISSUE, NULL) SEPARATOR '\n'), '') AS NIGHTISSUE
  FROM PRDWORK
  INNER JOIN PRDINS
    ON PRDINS.PRDINSKEY = PRDWORK.PRDINSKEY
  INNER JOIN MSTPRC
    ON MSTPRC.PRCCD = PRDINS.PRCCD
   AND MSTPRC.GUBUN_BC = 'PP412001' -- 사내공정
  LEFT JOIN PRDWORK_EMP
    ON PRDWORK_EMP.PRDWORKKEY = PRDWORK.PRDWORKKEY
  LEFT JOIN MSTEMP
    ON MSTEMP.EMPCD = PRDWORK_EMP.EMPCD
  WHERE PRDWORK.WORKDATE = _$WORKDATE
    AND PRDWORK.EQMCD = _$EQMCD
    AND PRDWORK.ITEMID = _$ITEMID
  ;

  -- 1. 생산 줄 (투입로트 1개 = 1줄, 실적 값은 줄마다 반복 → 리포트가 실적의 첫 줄에만 찍음)
  --    SHIFT: DAY(주간, DNTP 가 비어 있는 옛 자료 포함) / NIGHT(야간)
  SELECT
      IF(PRDINS.DNTP = 'NIGHT', 'NIGHT', 'DAY') AS SHIFT
    , PRDWORK.PRDWORKKEY
    , IFNULL(PRDRST.PRDRSTKEY, '') AS PRDRSTKEY
    , IFNULL(PRDRSTUSE.USELOTKEY, '') AS USELOTKEY
    , IFNULL(PRDRSTLOT.LOTKEY, '') AS LOTKEY
    , IFNULL(PRDRST.GOODQTY, 0) AS GOODQTY
    , IFNULL(PRDRST.BADQTY, 0) AS BADQTY
    , IFNULL(PRDRST.PRODQTY, 0) AS PRODQTY
  FROM PRDWORK
  INNER JOIN PRDINS
    ON PRDINS.PRDINSKEY = PRDWORK.PRDINSKEY
  INNER JOIN MSTPRC
    ON MSTPRC.PRCCD = PRDINS.PRCCD
   AND MSTPRC.GUBUN_BC = 'PP412001' -- 사내공정
  LEFT JOIN PRDRST
    ON PRDRST.PRDWORKKEY = PRDWORK.PRDWORKKEY
  LEFT JOIN PRDRSTUSE
    ON PRDRSTUSE.PRDRSTKEY = PRDRST.PRDRSTKEY
  LEFT JOIN PRDRSTLOT
    ON PRDRSTLOT.PRDRSTKEY = PRDRST.PRDRSTKEY
  WHERE PRDWORK.WORKDATE = _$WORKDATE
    AND PRDWORK.EQMCD = _$EQMCD
    AND PRDWORK.ITEMID = _$ITEMID
  ORDER BY SHIFT, PRDWORK.WORKSTIME, PRDWORK.PRDWORKKEY, PRDRST.RSTTIME, PRDRST.PRDRSTKEY, PRDRSTUSE.RTIME, PRDRSTUSE.USELOTKEY
  ;

  -- 2. 작업별 비가동 시간(분, 끝난 것만) - 양식 칸별로 비가동코드(NONCD) 매핑, 매핑 안 된 코드는 기타
  --    설비고장 칸은 해당 비가동코드가 없어 비워 둠 (2026-11-06)
  SELECT
      PRDRSTNON.PRDWORKKEY
    , SUM(IF(PRDRSTNON.NONCD IN ('I2100N', 'I2101N', 'I2102N', 'I2120N'), TIMESTAMPDIFF(MINUTE, PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME), 0)) AS NON_TO     -- T/O
    , SUM(IF(PRDRSTNON.NONCD = 'I2114N', TIMESTAMPDIFF(MINUTE, PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME), 0)) AS NON_LINE                               -- 라인지원
    , SUM(IF(PRDRSTNON.NONCD = 'I2113N', TIMESTAMPDIFF(MINUTE, PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME), 0)) AS NON_PLAN                               -- 계획정지
    , SUM(IF(PRDRSTNON.NONCD = 'I2111N', TIMESTAMPDIFF(MINUTE, PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME), 0)) AS NON_EDU                                -- 조회/교육
    , SUM(IF(PRDRSTNON.NONCD = 'I2112N', TIMESTAMPDIFF(MINUTE, PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME), 0)) AS NON_3J5H                               -- 3정5행
    , SUM(IF(PRDRSTNON.NONCD = 'I2110N', TIMESTAMPDIFF(MINUTE, PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME), 0)) AS NON_PREP                               -- 작업준비
    , SUM(IF(PRDRSTNON.NONCD = 'I2131N', TIMESTAMPDIFF(MINUTE, PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME), 0)) AS NON_ST                                 -- S/T (셋팅)
    , SUM(IF(PRDRSTNON.NONCD IN ('I2136N', 'I2137N'), TIMESTAMPDIFF(MINUTE, PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME), 0)) AS NON_TOOL                  -- 공구교환 (치구교환 포함)
    , SUM(IF(PRDRSTNON.NONCD = 'I2135N', TIMESTAMPDIFF(MINUTE, PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME), 0)) AS NON_MODEL                              -- 기종교환
    , SUM(IF(PRDRSTNON.NONCD = 'I2121N', TIMESTAMPDIFF(MINUTE, PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME), 0)) AS NON_MTR                                -- 소재대기
    , SUM(IF(PRDRSTNON.NONCD = 'I2122N', TIMESTAMPDIFF(MINUTE, PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME), 0)) AS NON_MEAS                               -- 측정대기
    , SUM(IF(PRDRSTNON.NONCD NOT IN ('I2100N', 'I2101N', 'I2102N', 'I2120N', 'I2114N', 'I2113N', 'I2111N', 'I2112N', 'I2110N', 'I2131N'
                                   , 'I2136N', 'I2137N', 'I2135N', 'I2121N', 'I2122N'), TIMESTAMPDIFF(MINUTE, PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME), 0)) AS NON_ETC -- 기타
  FROM PRDRSTNON
  INNER JOIN PRDWORK
    ON PRDWORK.PRDWORKKEY = PRDRSTNON.PRDWORKKEY
  WHERE PRDWORK.WORKDATE = _$WORKDATE
    AND PRDWORK.EQMCD = _$EQMCD
    AND PRDWORK.ITEMID = _$ITEMID
    AND PRDRSTNON.NONETIME <> ''
  GROUP BY PRDRSTNON.PRDWORKKEY
  ;

  -- 3. 불량현황 (중분류·불량명별 합계)
  SELECT
      IFNULL(GPCD('QM220', MSTBAD.BADTP2), '') AS BADTP2NM
    , IFNULL(MSTBAD.BADNM, PRDRSTBAD.BADCD) AS BADNM
    , SUM(PRDRSTBAD.BADQTY) AS BADQTY
  FROM PRDRSTBAD
  INNER JOIN PRDRST
    ON PRDRST.PRDRSTKEY = PRDRSTBAD.PRDRSTKEY
  INNER JOIN PRDWORK
    ON PRDWORK.PRDWORKKEY = PRDRST.PRDWORKKEY
  INNER JOIN PRDINS
    ON PRDINS.PRDINSKEY = PRDWORK.PRDINSKEY
  INNER JOIN MSTPRC
    ON MSTPRC.PRCCD = PRDINS.PRCCD
   AND MSTPRC.GUBUN_BC = 'PP412001' -- 사내공정
  LEFT JOIN MSTBAD
    ON MSTBAD.BADCD = PRDRSTBAD.BADCD
  WHERE PRDWORK.WORKDATE = _$WORKDATE
    AND PRDWORK.EQMCD = _$EQMCD
    AND PRDWORK.ITEMID = _$ITEMID
  GROUP BY MSTBAD.BADTP2, PRDRSTBAD.BADCD, MSTBAD.BADNM
  ORDER BY MSTBAD.BADTP2, MSTBAD.BADNM
  ;

END CASE;
-- *****************************************************************************
END
