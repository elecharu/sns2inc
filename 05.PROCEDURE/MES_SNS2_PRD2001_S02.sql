CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.PRD2001_S02(
-- *****************************************************************************
-- Comment: 주간생산실적 조회 (웹) - 생산팀 "주간 업무추진현황" 양식
--          ) 행 기준: 라인 기준정보(MSTLINE_EQM, 2공장 사내 작업장) × (그 달 계획·실적이 있는 품목 + 생산기준정보 MSTEQM_STD 매칭 품목)
--            품목이 하나도 없는 라인은 품목 빈 줄 1개
--          ) 주간 = 시작일 ~ +6일, 월 누적 = 시작일이 속한 달 1일 ~ 주간 끝날(그 달 안에서)
--          ) 계획 = 주간생산계획(PRDPLAN_W, 같은 날짜가 계획월별로 여러 줄이면 MAX), 월 계획 = 그 달 전체 PRDPLAN_W 합계
--          ) 실적 = 생산실적 양품수량(PRDRST.GOODQTY), 주야 = PRDINS.DNTP(NIGHT 외는 주간), 불량률 PPM = 불량 / 생산 × 1,000,000
--          ) 가동율(시간·성능·종합)은 계산식 미정이라 빈칸 (2026-11-06)
--          ) LIST: 0 기간 / 1 주간 생산실적 / 2 가동률 ISSUE(비가동) / 3 불량률 ISSUE
-- Create: 2026-11-06
-- Modify: 2026-11-06 생산기준정보(MSTEQM_STD) 라인별 매칭 품목은 계획·실적이 없어도 표시
--         2026-11-06 MSTEQM_STD 적용기간을 시각까지 비교
--         2026-11-06 주간 생산실적에 품목유형(DM100)·품목ID·품목코드 추가
--         2026-11-06 MSTEQM_STD 매칭 품목은 주간생산계획 대상 공정(MSTPRC.WEEKPLANYN = 'Y')만
--         2026-11-06 합계 행 배경색: 작업장 합계 #FCE4D6(살구색), 공정 합계 #FEF2EA(연한 살구색)
--         2026-11-06 제품(MSTITEM.ITEMCG = 'DM100100')은 주간 생산실적에서 제외
--         2026-11-06 제품품명 추가 (BOM 을 위로 따라가 만나는 제품, 여러 개면 쉼표로)
--         2026-11-06 품목 공정을 생산기준정보(MSTEQM_STD) 공정으로 표시 (없으면 라인 공정), 공정 합계도 품목 공정 기준
-- *****************************************************************************
  IN $SDATE VARCHAR(10),        -- 시작일
  IN $LINECD VARCHAR(100),      -- 작업장 (빈 값이면 전체)
-- *****************************************************************************
  IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  DECLARE _$EDATE VARCHAR(10);    -- 주간 끝날
  DECLARE _$MSDATE VARCHAR(10);   -- 그 달 1일
  DECLARE _$MEDATE VARCHAR(10);   -- 그 달 말일
  DECLARE _$MRDATE VARCHAR(10);   -- 월 누적 실적 끝날 (주간 끝날, 그 달을 넘으면 말일)
  DECLARE _$COUNT INT;            -- BOM 단계
-- *****************************************************************************
CASE $CALLTYPE
-- ****************************************************************************
WHEN 'LIST' THEN  -- 주간생산실적

  IF $SDATE = '' THEN
    CALL COMERR('시작일을 입력하세요.');
    LEAVE PROC;
  END IF;

  SET _$EDATE = DATE_FORMAT(DATE_ADD($SDATE, INTERVAL 6 DAY), '%Y-%m-%d');
  SET _$MSDATE = CONCAT(LEFT($SDATE, 7), '-01');
  SET _$MEDATE = DATE_FORMAT(LAST_DAY($SDATE), '%Y-%m-%d');
  SET _$MRDATE = LEAST(_$EDATE, _$MEDATE);

  -- 대상 라인 (2공장 사내 작업장의 사용 중 라인)
  DROP TABLE IF EXISTS TEMP_LINE;
  CREATE TEMPORARY TABLE TEMP_LINE (
    LINECD VARCHAR(100) NOT NULL,
    PRCCD  VARCHAR(100) NOT NULL,
    EQMCD  VARCHAR(100) NOT NULL,
    LINENM VARCHAR(100) NOT NULL,
    PRCNM  VARCHAR(100) NOT NULL,
    EQMNM  VARCHAR(100) NOT NULL
  );

  INSERT INTO TEMP_LINE
  SELECT
      MSTLINE_EQM.LINECD
    , MSTLINE_EQM.PRCCD
    , MSTLINE_EQM.EQMCD
    , IFNULL(MSTLINE.LINENM, MSTLINE_EQM.LINECD)
    , IFNULL(MSTPRC.PRCNM, MSTLINE_EQM.PRCCD)
    , IFNULL(MSTLINE_EQM.EQMNM, MSTLINE_EQM.EQMCD)
  FROM MSTLINE_EQM
  INNER JOIN MSTLINE
    ON MSTLINE.LINECD = MSTLINE_EQM.LINECD
  LEFT JOIN MSTPRC
    ON MSTPRC.PRCCD = MSTLINE_EQM.PRCCD
  WHERE MSTLINE_EQM.USEYN = 'Y'
    AND MSTLINE.USEYN = 'Y'
    AND MSTLINE.EDT = ''
    AND MSTLINE.FACTORYCD = '07'  -- 2공장
    AND MSTLINE.OSCCUSTCD = ''    -- 사내 작업장
    AND ($LINECD = '' OR MSTLINE_EQM.LINECD = $LINECD);

  -- 라인·품목별 계획 (같은 날짜가 계획월별로 여러 줄일 수 있어 날짜별 MAX 후 합계)
  DROP TABLE IF EXISTS TEMP_PLAN;
  CREATE TEMPORARY TABLE TEMP_PLAN (
    EQMCD  VARCHAR(100) NOT NULL,
    ITEMID VARCHAR(100) NOT NULL,
    W_PLAN_DAY   DECIMAL(20, 8) NOT NULL,
    W_PLAN_NIGHT DECIMAL(20, 8) NOT NULL,
    M_PLAN       DECIMAL(20, 8) NOT NULL
  );

  INSERT INTO TEMP_PLAN
  SELECT
      PLAN_DAY.EQMCD
    , PLAN_DAY.ITEMID
    , SUM(IF(PLAN_DAY.PDATE BETWEEN $SDATE AND _$EDATE, PLAN_DAY.PLANQTY_DAY, 0))
    , SUM(IF(PLAN_DAY.PDATE BETWEEN $SDATE AND _$EDATE, PLAN_DAY.PLANQTY_NIGHT, 0))
    , SUM(PLAN_DAY.PLANQTY_DAY + PLAN_DAY.PLANQTY_NIGHT)
  FROM (
         SELECT
             PRDPLAN_W.PDATE
           , PRDPLAN_W.EQMCD
           , CAST(PRDPLAN_W.ITEMID AS CHAR) AS ITEMID
           , MAX(PRDPLAN_W.PLANQTY_DAY) AS PLANQTY_DAY
           , MAX(PRDPLAN_W.PLANQTY_NIGHT) AS PLANQTY_NIGHT
         FROM PRDPLAN_W
         WHERE PRDPLAN_W.PDATE BETWEEN _$MSDATE AND _$MEDATE
         GROUP BY PRDPLAN_W.PDATE, PRDPLAN_W.EQMCD, PRDPLAN_W.ITEMID
       ) AS PLAN_DAY
  GROUP BY PLAN_DAY.EQMCD, PLAN_DAY.ITEMID
  HAVING SUM(PLAN_DAY.PLANQTY_DAY + PLAN_DAY.PLANQTY_NIGHT) <> 0;

  -- 라인·품목별 실적 (작업일자 기준, 사내공정 작업지시)
  DROP TABLE IF EXISTS TEMP_RST;
  CREATE TEMPORARY TABLE TEMP_RST (
    EQMCD  VARCHAR(100) NOT NULL,
    ITEMID VARCHAR(100) NOT NULL,
    W_RST_DAY   DECIMAL(20, 8) NOT NULL,
    W_RST_NIGHT DECIMAL(20, 8) NOT NULL,
    W_PROD      DECIMAL(20, 8) NOT NULL,
    W_BAD       DECIMAL(20, 8) NOT NULL,
    M_RST       DECIMAL(20, 8) NOT NULL,
    M_PROD      DECIMAL(20, 8) NOT NULL,
    M_BAD       DECIMAL(20, 8) NOT NULL
  );

  INSERT INTO TEMP_RST
  SELECT
      PRDRST.EQMCD
    , PRDRST.ITEMID
    , SUM(IF(PRDWORK.WORKDATE >= $SDATE AND PRDINS.DNTP <> 'NIGHT', PRDRST.GOODQTY, 0))
    , SUM(IF(PRDWORK.WORKDATE >= $SDATE AND PRDINS.DNTP = 'NIGHT', PRDRST.GOODQTY, 0))
    , SUM(IF(PRDWORK.WORKDATE >= $SDATE, PRDRST.PRODQTY, 0))
    , SUM(IF(PRDWORK.WORKDATE >= $SDATE, PRDRST.BADQTY, 0))
    , SUM(IF(PRDWORK.WORKDATE >= _$MSDATE AND PRDWORK.WORKDATE <= _$MRDATE, PRDRST.GOODQTY, 0))
    , SUM(IF(PRDWORK.WORKDATE >= _$MSDATE AND PRDWORK.WORKDATE <= _$MRDATE, PRDRST.PRODQTY, 0))
    , SUM(IF(PRDWORK.WORKDATE >= _$MSDATE AND PRDWORK.WORKDATE <= _$MRDATE, PRDRST.BADQTY, 0))
  FROM PRDRST
  INNER JOIN PRDWORK
    ON PRDWORK.PRDWORKKEY = PRDRST.PRDWORKKEY
  INNER JOIN PRDINS
    ON PRDINS.PRDINSKEY = PRDWORK.PRDINSKEY
  INNER JOIN MSTPRC
    ON MSTPRC.PRCCD = PRDINS.PRCCD
   AND MSTPRC.GUBUN_BC = 'PP412001' -- 사내공정
  WHERE PRDWORK.WORKDATE BETWEEN LEAST($SDATE, _$MSDATE) AND _$EDATE
  GROUP BY PRDRST.EQMCD, PRDRST.ITEMID;

  -- 라인별 품목 (계획·실적이 있는 것 + 생산기준정보 매칭). 임시 테이블은 한 문장에서 두 번 못 읽어서 따로 모은다.
  DROP TABLE IF EXISTS TEMP_ITEM;
  CREATE TEMPORARY TABLE TEMP_ITEM (
    EQMCD  VARCHAR(100) NOT NULL,
    ITEMID VARCHAR(100) NOT NULL,
    PRIMARY KEY (EQMCD, ITEMID)
  );

  INSERT IGNORE INTO TEMP_ITEM
  SELECT TEMP_PLAN.EQMCD, TEMP_PLAN.ITEMID
  FROM TEMP_PLAN;

  INSERT IGNORE INTO TEMP_ITEM
  SELECT TEMP_RST.EQMCD, TEMP_RST.ITEMID
  FROM TEMP_RST
  WHERE TEMP_RST.M_PROD <> 0
     OR TEMP_RST.W_PROD <> 0;

  -- 생산기준정보(MSTEQM_STD)에 라인별로 매칭된 품목은 계획·실적이 없어도 표시
  -- 적용기간(SDT~EDT, 시각 포함)이 그 달 1일 00:00:00 ~ 주간 끝날 23:59:59 와 겹치고, 주간생산계획 대상 공정(MSTPRC.WEEKPLANYN = 'Y')인 품목
  INSERT IGNORE INTO TEMP_ITEM
  SELECT MSTEQM_STD.EQMCD, MSTEQM_STD.ITEMID
  FROM MSTEQM_STD
  INNER JOIN MSTPRC
    ON MSTPRC.PRCCD = MSTEQM_STD.PRCCD
   AND MSTPRC.WEEKPLANYN = 'Y'
  WHERE MSTEQM_STD.FACTORYCD = '07'  -- 2공장
    AND MSTEQM_STD.SDT <= CONCAT(_$EDATE, ' 23:59:59')
    AND (IFNULL(MSTEQM_STD.EDT, '') = '' OR MSTEQM_STD.EDT >= CONCAT(_$MSDATE, ' 00:00:00'));

  -- 제품(품목분류 DM100100)은 표시하지 않음 (계획·실적·생산기준정보 어디서 왔든). 품목이 다 빠진 라인은 빈 줄 1개로 남는다.
  DELETE TEMP_ITEM
  FROM TEMP_ITEM
  INNER JOIN MSTITEM
    ON MSTITEM.ITEMID = TEMP_ITEM.ITEMID
  WHERE MSTITEM.ITEMCG = 'DM100100';

  -- 제품품명: 품목에서 BOM(MSTBOM, 사용 중)을 위로 따라 올라가 만나는 제품(DM100100). 여러 개면 모두 (최대 20단계)
  DROP TABLE IF EXISTS TEMP_PROD;
  CREATE TEMPORARY TABLE TEMP_PROD (
    ITEMID VARCHAR(100) NOT NULL,
    PRODID VARCHAR(100) NOT NULL,
    PRIMARY KEY (ITEMID, PRODID)
  );

  DROP TABLE IF EXISTS TEMP_BOMCUR;
  CREATE TEMPORARY TABLE TEMP_BOMCUR (
    ITEMID VARCHAR(100) NOT NULL,
    CURID  VARCHAR(100) NOT NULL,
    PRIMARY KEY (ITEMID, CURID)
  );

  DROP TABLE IF EXISTS TEMP_BOMNEXT;
  CREATE TEMPORARY TABLE TEMP_BOMNEXT LIKE TEMP_BOMCUR;

  INSERT IGNORE INTO TEMP_BOMCUR
  SELECT TEMP_ITEM.ITEMID, TEMP_ITEM.ITEMID
  FROM TEMP_ITEM;

  SET _$COUNT = 0;
  WHILE _$COUNT < 20 DO
    -- 이번 단계 상위 품목
    DELETE FROM TEMP_BOMNEXT;
    INSERT IGNORE INTO TEMP_BOMNEXT
    SELECT TEMP_BOMCUR.ITEMID, MSTBOM.MITEMID
    FROM TEMP_BOMCUR
    INNER JOIN MSTBOM
      ON MSTBOM.CITEMID = TEMP_BOMCUR.CURID
     AND MSTBOM.USEYN = 'Y';

    -- 제품이면 기록하고 더 올라가지 않음
    INSERT IGNORE INTO TEMP_PROD
    SELECT TEMP_BOMNEXT.ITEMID, TEMP_BOMNEXT.CURID
    FROM TEMP_BOMNEXT
    INNER JOIN MSTITEM
      ON MSTITEM.ITEMID = TEMP_BOMNEXT.CURID
    WHERE MSTITEM.ITEMCG = 'DM100100';

    DELETE FROM TEMP_BOMCUR;
    INSERT IGNORE INTO TEMP_BOMCUR
    SELECT TEMP_BOMNEXT.ITEMID, TEMP_BOMNEXT.CURID
    FROM TEMP_BOMNEXT
    INNER JOIN MSTITEM
      ON MSTITEM.ITEMID = TEMP_BOMNEXT.CURID
    WHERE IFNULL(MSTITEM.ITEMCG, '') <> 'DM100100';

    IF NOT EXISTS (SELECT TEMP_BOMCUR.ITEMID FROM TEMP_BOMCUR) THEN
      SET _$COUNT = 20;
    END IF;
    SET _$COUNT = _$COUNT + 1;
  END WHILE;

  -- 품목 공정: 생산기준정보(MSTEQM_STD)의 라인·품목 공정 (적용시작이 가장 늦은 것). 없으면 라인 공정(MSTLINE_EQM)
  --   라인 하나에서 공정이 다른 품목을 만들 수 있어서(예: M13 절단·열전) 라인 공정만으로는 틀린다 (2026-11-06)
  DROP TABLE IF EXISTS TEMP_ITEMPRC;
  CREATE TEMPORARY TABLE TEMP_ITEMPRC (
    EQMCD  VARCHAR(100) NOT NULL,
    ITEMID VARCHAR(100) NOT NULL,
    PRCCD  VARCHAR(100) NOT NULL,
    PRIMARY KEY (EQMCD, ITEMID)
  );

  INSERT IGNORE INTO TEMP_ITEMPRC
  SELECT MSTEQM_STD.EQMCD, MSTEQM_STD.ITEMID, MSTEQM_STD.PRCCD
  FROM MSTEQM_STD
  WHERE MSTEQM_STD.FACTORYCD = '07'  -- 2공장
    AND IFNULL(MSTEQM_STD.PRCCD, '') <> ''
    AND MSTEQM_STD.SDT <= CONCAT(_$EDATE, ' 23:59:59')
  ORDER BY MSTEQM_STD.SDT DESC;  -- INSERT IGNORE 라 먼저 들어간 최신 적용분이 남는다

  -- 주간 생산실적 상세 행 (D)
  DROP TABLE IF EXISTS TEMP_WEEKRST;
  CREATE TEMPORARY TABLE TEMP_WEEKRST (
    ROWTP  VARCHAR(1) NOT NULL,
    SORT1  VARCHAR(100) NOT NULL,
    SORT2  VARCHAR(100) NOT NULL,
    SORT3  VARCHAR(100) NOT NULL,
    LINECD VARCHAR(100) NOT NULL,
    PRCCD  VARCHAR(100) NOT NULL,
    LINENM VARCHAR(100) NOT NULL,
    ITEMCGNM VARCHAR(100) NOT NULL,
    ITEMID VARCHAR(100) NOT NULL,
    ITEMCD VARCHAR(100) NOT NULL,
    ITEMNM VARCHAR(200) NOT NULL,
    PRODNM VARCHAR(1000) NOT NULL,
    PRCNM  VARCHAR(100) NOT NULL,
    EQMNM  VARCHAR(100) NOT NULL,
    W_PLAN_DAY   DECIMAL(20, 8) NOT NULL,
    W_PLAN_NIGHT DECIMAL(20, 8) NOT NULL,
    W_RST_DAY    DECIMAL(20, 8) NOT NULL,
    W_RST_NIGHT  DECIMAL(20, 8) NOT NULL,
    W_PROD       DECIMAL(20, 8) NOT NULL,
    W_BAD        DECIMAL(20, 8) NOT NULL,
    M_PLAN       DECIMAL(20, 8) NOT NULL,
    M_RST        DECIMAL(20, 8) NOT NULL,
    M_PROD       DECIMAL(20, 8) NOT NULL,
    M_BAD        DECIMAL(20, 8) NOT NULL
  );

  -- D: 라인 × (계획 또는 실적이 있는 품목), 품목이 없는 라인도 1줄. 공정은 품목 공정(TEMP_ITEMPRC), 없으면 라인 공정
  INSERT INTO TEMP_WEEKRST
  SELECT
      'D'
    , TEMP_LINE.LINECD
    , IFNULL(TEMP_ITEMPRC.PRCCD, TEMP_LINE.PRCCD)
    , CONCAT('0', TEMP_LINE.EQMCD, '|', IFNULL(MSTITEM.ITEMNM, ''))
    , TEMP_LINE.LINECD
    , IFNULL(TEMP_ITEMPRC.PRCCD, TEMP_LINE.PRCCD)
    , TEMP_LINE.LINENM
    , IFNULL(GPCD('DM100', MSTITEM.ITEMCG), '')
    , IFNULL(TEMP_ITEM.ITEMID, '')
    , IFNULL(MSTITEM.ITEMCD, '')
    , IFNULL(MSTITEM.ITEMNM, '')
    , IFNULL(ITEM_PROD.PRODNM, '')
    , IF(TEMP_ITEMPRC.PRCCD IS NULL, TEMP_LINE.PRCNM, IFNULL(MSTPRC.PRCNM, TEMP_ITEMPRC.PRCCD))
    , TEMP_LINE.EQMNM
    , IFNULL(TEMP_PLAN.W_PLAN_DAY, 0)
    , IFNULL(TEMP_PLAN.W_PLAN_NIGHT, 0)
    , IFNULL(TEMP_RST.W_RST_DAY, 0)
    , IFNULL(TEMP_RST.W_RST_NIGHT, 0)
    , IFNULL(TEMP_RST.W_PROD, 0)
    , IFNULL(TEMP_RST.W_BAD, 0)
    , IFNULL(TEMP_PLAN.M_PLAN, 0)
    , IFNULL(TEMP_RST.M_RST, 0)
    , IFNULL(TEMP_RST.M_PROD, 0)
    , IFNULL(TEMP_RST.M_BAD, 0)
  FROM TEMP_LINE
  LEFT JOIN TEMP_ITEM
    ON TEMP_ITEM.EQMCD = TEMP_LINE.EQMCD
  LEFT JOIN MSTITEM
    ON MSTITEM.ITEMID = TEMP_ITEM.ITEMID
  LEFT JOIN TEMP_ITEMPRC
    ON TEMP_ITEMPRC.EQMCD = TEMP_ITEM.EQMCD
   AND TEMP_ITEMPRC.ITEMID = TEMP_ITEM.ITEMID
  LEFT JOIN MSTPRC
    ON MSTPRC.PRCCD = TEMP_ITEMPRC.PRCCD
  LEFT JOIN (
              SELECT
                  TEMP_PROD.ITEMID
                , GROUP_CONCAT(DISTINCT MSTITEM.ITEMNM ORDER BY MSTITEM.ITEMNM SEPARATOR ', ') AS PRODNM
              FROM TEMP_PROD
              INNER JOIN MSTITEM
                ON MSTITEM.ITEMID = TEMP_PROD.PRODID
              GROUP BY TEMP_PROD.ITEMID
            ) AS ITEM_PROD
    ON ITEM_PROD.ITEMID = TEMP_ITEM.ITEMID
  LEFT JOIN TEMP_PLAN
    ON TEMP_PLAN.EQMCD = TEMP_ITEM.EQMCD
   AND TEMP_PLAN.ITEMID = TEMP_ITEM.ITEMID
  LEFT JOIN TEMP_RST
    ON TEMP_RST.EQMCD = TEMP_ITEM.EQMCD
   AND TEMP_RST.ITEMID = TEMP_ITEM.ITEMID;

  -- 합계 행 (P 공정 합계 / L 작업장 합계 / T 누적)
  DROP TABLE IF EXISTS TEMP_WEEKSUM;
  CREATE TEMPORARY TABLE TEMP_WEEKSUM LIKE TEMP_WEEKRST;

  -- 상세 줄 기준으로 공정이 2개 이상인 작업장 (품목 공정 기준, 공정 합계를 넣을지 판단)
  DROP TABLE IF EXISTS TEMP_MULTIPRC;
  CREATE TEMPORARY TABLE TEMP_MULTIPRC (
    LINECD VARCHAR(100) NOT NULL,
    PRIMARY KEY (LINECD)
  );

  INSERT INTO TEMP_MULTIPRC
  SELECT TEMP_WEEKRST.LINECD
  FROM TEMP_WEEKRST
  WHERE TEMP_WEEKRST.ROWTP = 'D'
  GROUP BY TEMP_WEEKRST.LINECD
  HAVING COUNT(DISTINCT TEMP_WEEKRST.PRCCD) > 1;

  -- P: 작업장에 공정이 2개 이상이고 그 공정 줄이 2줄 이상일 때 공정 합계 (예: M3 열전 합계)
  INSERT INTO TEMP_WEEKSUM
  SELECT
      'P', TEMP_WEEKRST.LINECD, TEMP_WEEKRST.PRCCD, '1'
    , TEMP_WEEKRST.LINECD, TEMP_WEEKRST.PRCCD
    , MAX(TEMP_WEEKRST.LINENM), '', '', '', '', '', CONCAT(MAX(TEMP_WEEKRST.LINENM), ' ', MAX(TEMP_WEEKRST.PRCNM), ' 합계'), ''
    , SUM(TEMP_WEEKRST.W_PLAN_DAY), SUM(TEMP_WEEKRST.W_PLAN_NIGHT), SUM(TEMP_WEEKRST.W_RST_DAY), SUM(TEMP_WEEKRST.W_RST_NIGHT)
    , SUM(TEMP_WEEKRST.W_PROD), SUM(TEMP_WEEKRST.W_BAD)
    , SUM(TEMP_WEEKRST.M_PLAN), SUM(TEMP_WEEKRST.M_RST), SUM(TEMP_WEEKRST.M_PROD), SUM(TEMP_WEEKRST.M_BAD)
  FROM TEMP_WEEKRST
  WHERE TEMP_WEEKRST.ROWTP = 'D'
    AND TEMP_WEEKRST.LINECD IN (SELECT TEMP_MULTIPRC.LINECD FROM TEMP_MULTIPRC)
  GROUP BY TEMP_WEEKRST.LINECD, TEMP_WEEKRST.PRCCD
  HAVING COUNT(*) > 1;

  -- L: 작업장 줄이 2줄 이상이면 작업장 합계 (예: M2 합계). 정렬 키 '힣' = 공정 줄들 뒤
  INSERT INTO TEMP_WEEKSUM
  SELECT
      'L', TEMP_WEEKRST.LINECD, '힣', '2'
    , TEMP_WEEKRST.LINECD, ''
    , CONCAT(MAX(TEMP_WEEKRST.LINENM), ' 합계'), '', '', '', '', '', '', ''
    , SUM(TEMP_WEEKRST.W_PLAN_DAY), SUM(TEMP_WEEKRST.W_PLAN_NIGHT), SUM(TEMP_WEEKRST.W_RST_DAY), SUM(TEMP_WEEKRST.W_RST_NIGHT)
    , SUM(TEMP_WEEKRST.W_PROD), SUM(TEMP_WEEKRST.W_BAD)
    , SUM(TEMP_WEEKRST.M_PLAN), SUM(TEMP_WEEKRST.M_RST), SUM(TEMP_WEEKRST.M_PROD), SUM(TEMP_WEEKRST.M_BAD)
  FROM TEMP_WEEKRST
  WHERE TEMP_WEEKRST.ROWTP = 'D'
  GROUP BY TEMP_WEEKRST.LINECD
  HAVING COUNT(*) > 1;

  -- T: 누적 (상세 줄 전체). 정렬 키 '힣' = 맨 끝
  INSERT INTO TEMP_WEEKSUM
  SELECT
      'T', '힣', '', '9'
    , '', ''
    , '누적', '', '', '', '', '', '', ''
    , IFNULL(SUM(TEMP_WEEKRST.W_PLAN_DAY), 0), IFNULL(SUM(TEMP_WEEKRST.W_PLAN_NIGHT), 0), IFNULL(SUM(TEMP_WEEKRST.W_RST_DAY), 0), IFNULL(SUM(TEMP_WEEKRST.W_RST_NIGHT), 0)
    , IFNULL(SUM(TEMP_WEEKRST.W_PROD), 0), IFNULL(SUM(TEMP_WEEKRST.W_BAD), 0)
    , IFNULL(SUM(TEMP_WEEKRST.M_PLAN), 0), IFNULL(SUM(TEMP_WEEKRST.M_RST), 0), IFNULL(SUM(TEMP_WEEKRST.M_PROD), 0), IFNULL(SUM(TEMP_WEEKRST.M_BAD), 0)
  FROM TEMP_WEEKRST
  WHERE TEMP_WEEKRST.ROWTP = 'D';

  -- 0. 기간
  SELECT
      CONCAT(DATE_FORMAT($SDATE, '%Y-%m-%d'), ' ~ ', _$EDATE) AS WEEKTEXT
    , CONCAT(DATE_FORMAT($SDATE, '%Y년 %m월'), ' (', _$MSDATE, ' ~ ', _$MRDATE, ')') AS MONTHTEXT;

  -- 1. 주간 생산실적 (상세 + 합계)
  SELECT
      WEEK_ROW.ROWTP
    , WEEK_ROW.LINENM
    , WEEK_ROW.ITEMCGNM
    , WEEK_ROW.ITEMID
    , WEEK_ROW.ITEMCD
    , WEEK_ROW.ITEMNM
    , WEEK_ROW.PRODNM
    , WEEK_ROW.PRCNM
    , WEEK_ROW.EQMNM
    , WEEK_ROW.W_PLAN_DAY
    , WEEK_ROW.W_PLAN_NIGHT
    , WEEK_ROW.W_RST_DAY
    , WEEK_ROW.W_RST_NIGHT
    , IF(WEEK_ROW.W_PLAN_DAY + WEEK_ROW.W_PLAN_NIGHT = 0, NULL
        , ROUND((WEEK_ROW.W_RST_DAY + WEEK_ROW.W_RST_NIGHT) / (WEEK_ROW.W_PLAN_DAY + WEEK_ROW.W_PLAN_NIGHT) * 100, 1)) AS W_RATE
    , NULL AS W_TIMEOEE
    , NULL AS W_PERFOEE
    , NULL AS W_OEE
    , IF(WEEK_ROW.W_PROD = 0, NULL, ROUND(WEEK_ROW.W_BAD / WEEK_ROW.W_PROD * 1000000, 0)) AS W_BADPPM
    , WEEK_ROW.M_PLAN
    , WEEK_ROW.M_RST
    , IF(WEEK_ROW.M_PLAN = 0, NULL, ROUND(WEEK_ROW.M_RST / WEEK_ROW.M_PLAN * 100, 1)) AS M_RATE
    , NULL AS M_TIMEOEE
    , NULL AS M_PERFOEE
    , NULL AS M_OEE
    , IF(WEEK_ROW.M_PROD = 0, NULL, ROUND(WEEK_ROW.M_BAD / WEEK_ROW.M_PROD * 1000000, 0)) AS M_BADPPM
    , CASE WEEK_ROW.ROWTP
        WHEN 'P' THEN '#FEF2EA'  -- 공정 합계 (작업장 합계보다 연한 살구색)
        WHEN 'L' THEN '#FCE4D6'  -- 작업장 합계 (살구색)
        WHEN 'T' THEN '#E4DFEC'
        ELSE ''
      END AS BACKGROUND
  FROM (
         SELECT * FROM TEMP_WEEKRST
         UNION ALL
         SELECT * FROM TEMP_WEEKSUM
       ) AS WEEK_ROW
  ORDER BY WEEK_ROW.SORT1, WEEK_ROW.SORT2, WEEK_ROW.SORT3
  ;

  -- 2. 가동률 ISSUE: 라인별 주간 비가동(끝난 것) 항목별 분 + 작업지시 ISSUE
  SELECT
      TEMP_LINE.LINENM
    , TEMP_LINE.PRCNM
    , TEMP_LINE.EQMNM
    , IFNULL(LINE_NON.NONMIN, 0) AS NONMIN
    , IFNULL(LINE_NON.NONTEXT, '') AS NONTEXT
    , IFNULL(LINE_ISSUE.ISSUE, '') AS ISSUE
  FROM TEMP_LINE
  LEFT JOIN (
              SELECT
                  NON_ITEM.EQMCD
                , SUM(NON_ITEM.NONMIN) AS NONMIN
                , GROUP_CONCAT(CONCAT(NON_ITEM.NONNM, ' ', FORMAT(NON_ITEM.NONMIN, 0), '분') ORDER BY NON_ITEM.NONMIN DESC SEPARATOR ', ') AS NONTEXT
              FROM (
                     SELECT
                         PRDRSTNON.EQMCD
                       , IFNULL(MSTNON.NONNM, PRDRSTNON.NONCD) AS NONNM
                       , SUM(TIMESTAMPDIFF(MINUTE, PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME)) AS NONMIN
                     FROM PRDRSTNON
                     LEFT JOIN MSTNON
                       ON MSTNON.LINECD = PRDRSTNON.LINECD
                      AND MSTNON.NONCD = PRDRSTNON.NONCD
                     WHERE LEFT(PRDRSTNON.NONSTIME, 10) BETWEEN $SDATE AND _$EDATE
                       AND PRDRSTNON.NONETIME <> ''
                     GROUP BY PRDRSTNON.EQMCD, IFNULL(MSTNON.NONNM, PRDRSTNON.NONCD)
                   ) AS NON_ITEM
              GROUP BY NON_ITEM.EQMCD
            ) AS LINE_NON
    ON LINE_NON.EQMCD = TEMP_LINE.EQMCD
  LEFT JOIN (
              SELECT
                  PRDWORK.EQMCD
                , GROUP_CONCAT(DISTINCT PRDINS.ISSUE SEPARATOR ' / ') AS ISSUE
              FROM PRDWORK
              INNER JOIN PRDINS
                ON PRDINS.PRDINSKEY = PRDWORK.PRDINSKEY
              WHERE PRDWORK.WORKDATE BETWEEN $SDATE AND _$EDATE
                AND PRDINS.ISSUE <> ''
              GROUP BY PRDWORK.EQMCD
            ) AS LINE_ISSUE
    ON LINE_ISSUE.EQMCD = TEMP_LINE.EQMCD
  WHERE LINE_NON.EQMCD IS NOT NULL
     OR LINE_ISSUE.EQMCD IS NOT NULL
  ORDER BY TEMP_LINE.LINECD, TEMP_LINE.PRCCD, TEMP_LINE.EQMCD
  ;

  -- 3. 불량률 ISSUE: 라인별 주간 불량 불량명별 EA
  SELECT
      TEMP_LINE.LINENM
    , TEMP_LINE.PRCNM
    , TEMP_LINE.EQMNM
    , LINE_BAD.BADQTY
    , LINE_BAD.BADTEXT
  FROM TEMP_LINE
  INNER JOIN (
               SELECT
                   BAD_ITEM.EQMCD
                 , SUM(BAD_ITEM.BADQTY) AS BADQTY
                 , GROUP_CONCAT(CONCAT(BAD_ITEM.BADNM, ' ', FORMAT(BAD_ITEM.BADQTY, 0), 'EA') ORDER BY BAD_ITEM.BADQTY DESC SEPARATOR ', ') AS BADTEXT
               FROM (
                      SELECT
                          PRDRST.EQMCD
                        , IFNULL(MSTBAD.BADNM, PRDRSTBAD.BADCD) AS BADNM
                        , SUM(PRDRSTBAD.BADQTY) AS BADQTY
                      FROM PRDRSTBAD
                      INNER JOIN PRDRST
                        ON PRDRST.PRDRSTKEY = PRDRSTBAD.PRDRSTKEY
                      INNER JOIN PRDWORK
                        ON PRDWORK.PRDWORKKEY = PRDRST.PRDWORKKEY
                      LEFT JOIN MSTBAD
                        ON MSTBAD.BADCD = PRDRSTBAD.BADCD
                      WHERE PRDWORK.WORKDATE BETWEEN $SDATE AND _$EDATE
                      GROUP BY PRDRST.EQMCD, IFNULL(MSTBAD.BADNM, PRDRSTBAD.BADCD)
                    ) AS BAD_ITEM
               GROUP BY BAD_ITEM.EQMCD
             ) AS LINE_BAD
    ON LINE_BAD.EQMCD = TEMP_LINE.EQMCD
  WHERE LINE_BAD.BADQTY <> 0
  ORDER BY TEMP_LINE.LINECD, TEMP_LINE.PRCCD, TEMP_LINE.EQMCD
  ;

  DROP TABLE IF EXISTS TEMP_LINE;
  DROP TABLE IF EXISTS TEMP_PLAN;
  DROP TABLE IF EXISTS TEMP_RST;
  DROP TABLE IF EXISTS TEMP_ITEM;
  DROP TABLE IF EXISTS TEMP_PROD;
  DROP TABLE IF EXISTS TEMP_BOMCUR;
  DROP TABLE IF EXISTS TEMP_BOMNEXT;
  DROP TABLE IF EXISTS TEMP_WEEKRST;
  DROP TABLE IF EXISTS TEMP_WEEKSUM;
  DROP TABLE IF EXISTS TEMP_ITEMPRC;
  DROP TABLE IF EXISTS TEMP_MULTIPRC;

