CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.PRD5001_S01(
-- *****************************************************************************
-- Comment: 자주검사 조회 (웹)
--          ) LIST_PRDWORK : 사내공정(MSTPRC.GUBUN_BC = 'PP412001') 작업 목록 (작업 1건 = 1줄) + 작업 중 자주검사 횟수
--          ) LIST_TQM     : 선택 작업의 자주검사 체크시트 (화면 그리드 + 리포트 PRD5001.exe S01 이 같이 씀)
--                           줄 = 검사항목 × 시료, 열 = 작업 중 실제 검사 회차(검사일시 순, 최대 30회)
--          자주검사(TQMRST, 태블릿 TAL2001_R01)에는 작업키가 없어서
--          같은 라인(TQMRST.LINECD = PRDWORK.EQMCD)·품목에서 작업시작~작업종료 사이에 한 검사를 그 작업의 검사로 본다.
--          작업종료가 비어 있으면(진행 중) 지금까지.
-- Create: 2026-11-17
-- Modify: 2026-11-17 위 목록을 검사 1회 → 생산 작업(PRDWORK) 1건으로 변경, 아래는 작업 중 검사의 항목결과 (사용자 요청)
--         2026-11-17 LIST_TQM 을 자주검사 체크시트 모양(검사항목×시료 줄, 검사 회차 열)으로 변경, 리포트 머리 결과 추가 (사용자 요청)
-- *****************************************************************************
  IN $SDATE VARCHAR(10),        -- 생산일자 시작
  IN $EDATE VARCHAR(10),        -- 생산일자 종료
  IN $LINECD VARCHAR(100),      -- 작업장
  IN $PRCCD VARCHAR(100),       -- 공정
  IN $EQMCD VARCHAR(100),       -- 라인
  IN $ITEMID VARCHAR(100),      -- 품목ID
  IN $PRDWORKKEY VARCHAR(100),  -- 작업키
-- *****************************************************************************
  IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  DECLARE _$EQMCD VARCHAR(100);
  DECLARE _$ITEMID VARCHAR(100);
  DECLARE _$WORKSTIME VARCHAR(19);
  DECLARE _$WORKETIME VARCHAR(19);
  DECLARE _$REVCD VARCHAR(100);
  DECLARE _$NO INT DEFAULT 0;
-- *****************************************************************************
CASE $CALLTYPE
-- ****************************************************************************
WHEN 'LIST_PRDWORK' THEN  -- 작업 목록

  IF $SDATE = '' OR $EDATE = '' THEN
    CALL COMERR('생산일자를 입력하세요.');
    LEAVE PROC;
  END IF;

  SELECT
      PRDWORK.WORKDATE
    , CASE PRDINS.DNTP
        WHEN 'DAY' THEN '주간'
        WHEN 'NIGHT' THEN '야간'
      ELSE PRDINS.DNTP END AS DNTPNM
    , PRDWORK.WORKSTIME
    , PRDWORK.WORKETIME
    , IFNULL(WORK_EMP.EMPNM, '') AS EMPNM
    , IFNULL(MSTLINE.LINENM, PRDWORK.LINECD) AS LINENM
    , MSTPRC.PRCNM
    , IFNULL(MSTLINE_EQM.EQMNM, PRDWORK.EQMCD) AS EQMNM
    , MSTITEM.ITEMCD
    , MSTITEM.ITEMNM
    , MSTITEM.ITEMSPEC
    , (SELECT COUNT(*)
         FROM TQMRST
         INNER JOIN MSTRPTREV_HEADER
           ON MSTRPTREV_HEADER.REVCD = TQMRST.REVCD
          AND MSTRPTREV_HEADER.STDTP = 'PRCTEST'
        WHERE TQMRST.LINECD = PRDWORK.EQMCD
          AND TQMRST.ITEMID = PRDWORK.ITEMID
          AND TQMRST.FIXTIME >= PRDWORK.WORKSTIME
          AND TQMRST.FIXTIME <= IF(PRDWORK.WORKETIME = '', CALLTIME(), PRDWORK.WORKETIME)) AS TQMCNT    -- 자주검사 횟수
    , (SELECT COUNT(*)
         FROM TQMRST
         INNER JOIN MSTRPTREV_HEADER
           ON MSTRPTREV_HEADER.REVCD = TQMRST.REVCD
          AND MSTRPTREV_HEADER.STDTP = 'PRCTEST'
        WHERE TQMRST.LINECD = PRDWORK.EQMCD
          AND TQMRST.ITEMID = PRDWORK.ITEMID
          AND TQMRST.FIXTIME >= PRDWORK.WORKSTIME
          AND TQMRST.FIXTIME <= IF(PRDWORK.WORKETIME = '', CALLTIME(), PRDWORK.WORKETIME)
          AND TQMRST.FINALJUDGE = 'N') AS NGCNT    -- 불합격 검사 횟수
    , PRDWORK.PRDWORKKEY
  FROM PRDWORK
  INNER JOIN PRDINS
    ON PRDINS.PRDINSKEY = PRDWORK.PRDINSKEY
  INNER JOIN MSTPRC
    ON MSTPRC.PRCCD = PRDINS.PRCCD
   AND MSTPRC.GUBUN_BC = 'PP412001' -- 사내공정
  LEFT JOIN MSTLINE
    ON MSTLINE.LINECD = PRDWORK.LINECD
  LEFT JOIN MSTLINE_EQM
    ON MSTLINE_EQM.EQMCD = PRDWORK.EQMCD
  LEFT JOIN MSTITEM
    ON MSTITEM.ITEMID = PRDWORK.ITEMID
  LEFT JOIN (
              -- 작업자 (PRDWORK_EMP)
              SELECT
                  PRDWORK_EMP.PRDWORKKEY
                , GROUP_CONCAT(IFNULL(MSTEMP.EMPNM, PRDWORK_EMP.EMPCD) SEPARATOR ', ') AS EMPNM
              FROM PRDWORK_EMP
              LEFT JOIN MSTEMP
                ON MSTEMP.EMPCD = PRDWORK_EMP.EMPCD
              GROUP BY PRDWORK_EMP.PRDWORKKEY
            ) AS WORK_EMP
    ON WORK_EMP.PRDWORKKEY = PRDWORK.PRDWORKKEY
  WHERE PRDWORK.WORKDATE BETWEEN $SDATE AND $EDATE
    AND ($LINECD = '' OR PRDWORK.LINECD = $LINECD)
    AND ($PRCCD = '' OR PRDWORK.PRCCD = $PRCCD)
    AND ($EQMCD = '' OR PRDWORK.EQMCD = $EQMCD)
    AND ($ITEMID = '' OR PRDWORK.ITEMID = $ITEMID)
  ORDER BY PRDWORK.WORKDATE, PRDWORK.WORKSTIME, PRDWORK.PRDWORKKEY
  ;

-- ****************************************************************************
WHEN 'LIST_TQM' THEN  -- 선택 작업의 자주검사 체크시트 (결과: 0 머리 / 1 검사 회차 / 2 검사항목×시료 줄)

  IF $PRDWORKKEY = '' THEN
    CALL COMERR('작업을 선택하세요.');
    LEAVE PROC;
  END IF;

  SELECT PRDWORK.EQMCD, PRDWORK.ITEMID, PRDWORK.WORKSTIME, PRDWORK.WORKETIME
    INTO _$EQMCD, _$ITEMID, _$WORKSTIME, _$WORKETIME
    FROM PRDWORK
    WHERE PRDWORK.PRDWORKKEY = $PRDWORKKEY;

  IF IFNULL(_$WORKSTIME, '') = '' THEN
    CALL COMERR('선택한 작업을 찾을 수 없습니다.');
    LEAVE PROC;
  END IF;

  IF _$WORKETIME = '' THEN
    SET _$WORKETIME = CALLTIME();
  END IF;

  -- 작업 중 자주검사 (검사일시 순 회차 번호)
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD5001_RST;
  CREATE TEMPORARY TABLE TMP_PRD5001_RST (
      SEQNO INT
    , TQMRSTKEY VARCHAR(100)
    , REVCD VARCHAR(100)
    , FIXTIME VARCHAR(19)
    , EMPCD VARCHAR(100)
    , FINALJUDGE VARCHAR(1)
  );

  INSERT INTO TMP_PRD5001_RST (SEQNO, TQMRSTKEY, REVCD, FIXTIME, EMPCD, FINALJUDGE)
  SELECT
      ROW_NUMBER() OVER (ORDER BY TQMRST.FIXTIME, TQMRST.TQMRSTKEY)
    , TQMRST.TQMRSTKEY
    , TQMRST.REVCD
    , TQMRST.FIXTIME
    , TQMRST.EMPCD
    , TQMRST.FINALJUDGE
  FROM TQMRST
  INNER JOIN MSTRPTREV_HEADER
    ON MSTRPTREV_HEADER.REVCD = TQMRST.REVCD
   AND MSTRPTREV_HEADER.STDTP = 'PRCTEST'  -- 자주검사
  WHERE TQMRST.LINECD = _$EQMCD
    AND TQMRST.ITEMID = _$ITEMID
    AND TQMRST.FIXTIME >= _$WORKSTIME
    AND TQMRST.FIXTIME <= _$WORKETIME;

  -- 화면·리포트 열은 30회까지
  DELETE FROM TMP_PRD5001_RST
  WHERE TMP_PRD5001_RST.SEQNO > 30;

  -- 줄(검사항목)은 작업 중 마지막 검사의 리비전, 검사가 없으면 품목의 사용중인 자주검사 리비전
  SET _$REVCD = IFNULL((SELECT TMP_PRD5001_RST.REVCD
                          FROM TMP_PRD5001_RST
                         ORDER BY TMP_PRD5001_RST.SEQNO DESC
                         LIMIT 1), '');

  IF _$REVCD = '' THEN
    SET _$REVCD = IFNULL((SELECT MSTRPTREV_HEADER.REVCD
                            FROM MSTRPTREV_ITEM
                            INNER JOIN MSTRPTREV_HEADER
                              ON MSTRPTREV_HEADER.REVCD = MSTRPTREV_ITEM.REVCD
                           WHERE MSTRPTREV_ITEM.ITEMID = _$ITEMID
                             AND MSTRPTREV_HEADER.STDTP = 'PRCTEST'
                             AND MSTRPTREV_HEADER.USEYN = 'Y'
                           ORDER BY MSTRPTREV_HEADER.REVNUM DESC
                           LIMIT 1), '');
  END IF;

  IF _$REVCD = '' THEN
    CALL COMERR('이 품목의 자주검사 기준이 없습니다.\n검사표준관리에서 검사기준을 등록하세요.');
    LEAVE PROC;
  END IF;

  -- 칸 값 (회차·검사항목·시료번호별)
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD5001_VAL;
  CREATE TEMPORARY TABLE TMP_PRD5001_VAL (
      SEQNO INT
    , STDCD VARCHAR(100)
    , STDPART VARCHAR(100)
    , PRCDETAIL VARCHAR(100)
    , SAMPLENO INT
    , VAL VARCHAR(200)
    , NG VARCHAR(1)        -- 그 회차 그 항목이 불합격이면 Y (화면·리포트 빨간 글자)
  );

  -- 측정 항목: 시료 검사값 (입력 순서 = 시료번호, 좌·우 값이 둘 다 있으면 'L / R')
  INSERT INTO TMP_PRD5001_VAL (SEQNO, STDCD, STDPART, PRCDETAIL, SAMPLENO, VAL, NG)
  SELECT
      TMP_PRD5001_RST.SEQNO
    , TQMRST_VALUE.STDCD
    , TQMRST_VALUE.STDPART
    , TQMRST_VALUE.PRCDETAIL
    , ROW_NUMBER() OVER (PARTITION BY TQMRST_VALUE.TQMRSTKEY, TQMRST_VALUE.STDCD, TQMRST_VALUE.PRCCD, TQMRST_VALUE.STDPART, TQMRST_VALUE.PRCDETAIL
                         ORDER BY TQMRST_VALUE.VALUEKEY)
    , CASE
        WHEN TQMRST_VALUE.VALUE <> '' AND TQMRST_VALUE.VALUE2 <> '' THEN CONCAT(TQMRST_VALUE.VALUE, ' / ', TQMRST_VALUE.VALUE2)
        WHEN TQMRST_VALUE.VALUE <> '' THEN TQMRST_VALUE.VALUE
      ELSE TQMRST_VALUE.VALUE2 END
    , IF(TQMRSTKND.JUDGE = 'N', 'Y', '')
  FROM TQMRST_VALUE
  INNER JOIN TMP_PRD5001_RST
    ON TMP_PRD5001_RST.TQMRSTKEY = TQMRST_VALUE.TQMRSTKEY
  INNER JOIN MSTRPTREV_DETAIL
    ON MSTRPTREV_DETAIL.REVCD = _$REVCD
   AND MSTRPTREV_DETAIL.STDCD = TQMRST_VALUE.STDCD
   AND MSTRPTREV_DETAIL.STDPART = TQMRST_VALUE.STDPART
   AND MSTRPTREV_DETAIL.PRCDETAIL = TQMRST_VALUE.PRCDETAIL
   AND MSTRPTREV_DETAIL.STDCHKTP = '02'  -- 측정
  LEFT JOIN TQMRSTKND
    ON TQMRSTKND.TQMRSTKEY = TQMRST_VALUE.TQMRSTKEY
   AND TQMRSTKND.STDCD = TQMRST_VALUE.STDCD
   AND TQMRSTKND.PRCCD = TQMRST_VALUE.PRCCD
   AND TQMRSTKND.STDPART = TQMRST_VALUE.STDPART
   AND TQMRSTKND.PRCDETAIL = TQMRST_VALUE.PRCDETAIL;

  -- 측정이 아닌 항목(게이지·육안 등)과 검사값 없이 판정만 있는 항목: 시료 1번 칸에 OK / NG
  INSERT INTO TMP_PRD5001_VAL (SEQNO, STDCD, STDPART, PRCDETAIL, SAMPLENO, VAL, NG)
  SELECT
      TMP_PRD5001_RST.SEQNO
    , TQMRSTKND.STDCD
    , TQMRSTKND.STDPART
    , TQMRSTKND.PRCDETAIL
    , 1
    , CASE TQMRSTKND.JUDGE
        WHEN 'Y' THEN 'OK'
        WHEN 'N' THEN 'NG'
      ELSE '' END
    , IF(TQMRSTKND.JUDGE = 'N', 'Y', '')
  FROM TQMRSTKND
  INNER JOIN TMP_PRD5001_RST
    ON TMP_PRD5001_RST.TQMRSTKEY = TQMRSTKND.TQMRSTKEY
  INNER JOIN MSTRPTREV_DETAIL
    ON MSTRPTREV_DETAIL.REVCD = _$REVCD
   AND MSTRPTREV_DETAIL.STDCD = TQMRSTKND.STDCD
   AND MSTRPTREV_DETAIL.STDPART = TQMRSTKND.STDPART
   AND MSTRPTREV_DETAIL.PRCDETAIL = TQMRSTKND.PRCDETAIL
  WHERE MSTRPTREV_DETAIL.STDCHKTP <> '02'
     OR NOT EXISTS (SELECT TQMRST_VALUE.VALUEKEY
                      FROM TQMRST_VALUE
                     WHERE TQMRST_VALUE.TQMRSTKEY = TQMRSTKND.TQMRSTKEY
                       AND TQMRST_VALUE.STDCD = TQMRSTKND.STDCD
                       AND TQMRST_VALUE.PRCCD = TQMRSTKND.PRCCD
                       AND TQMRST_VALUE.STDPART = TQMRSTKND.STDPART
                       AND TQMRST_VALUE.PRCDETAIL = TQMRSTKND.PRCDETAIL);

  -- 검사항목별 실제 입력된 시료 수 (기준 시료수보다 많이 입력했으면 그만큼 줄을 늘린다)
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD5001_CNT;
  CREATE TEMPORARY TABLE TMP_PRD5001_CNT (
      STDCD VARCHAR(100)
    , STDPART VARCHAR(100)
    , PRCDETAIL VARCHAR(100)
    , MAXNO INT
  );

  INSERT INTO TMP_PRD5001_CNT (STDCD, STDPART, PRCDETAIL, MAXNO)
  SELECT
      TMP_PRD5001_VAL.STDCD
    , TMP_PRD5001_VAL.STDPART
    , TMP_PRD5001_VAL.PRCDETAIL
    , MAX(TMP_PRD5001_VAL.SAMPLENO)
  FROM TMP_PRD5001_VAL
  GROUP BY TMP_PRD5001_VAL.STDCD, TMP_PRD5001_VAL.STDPART, TMP_PRD5001_VAL.PRCDETAIL;

  -- 시료번호 1~50
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD5001_NO;
  CREATE TEMPORARY TABLE TMP_PRD5001_NO (
      NO INT
  );

  SET _$NO = 1;
  WHILE _$NO <= 50 DO
    INSERT INTO TMP_PRD5001_NO (NO) VALUES (_$NO);
    SET _$NO = _$NO + 1;
  END WHILE;

  -- 0. 머리 (리포트): 제목, 작성일자(생산일자), 작업자(주간·야간 칸), 품명, 품번
  SELECT
      CONCAT(IFNULL(MSTLINE_EQM.EQMNM, PRDWORK.EQMCD), ' LINE 자주검사 체크시트') AS TITLE
    , DATE_FORMAT(PRDWORK.WORKDATE, '%Y 년      %m 월      %d 일') AS WORKDATE_TXT
    , IF(PRDINS.DNTP = 'NIGHT', '', IFNULL(WORK_EMP.EMPNM, '')) AS DAYEMP
    , IF(PRDINS.DNTP = 'NIGHT', IFNULL(WORK_EMP.EMPNM, ''), '') AS NIGHTEMP
    , IFNULL(MSTITEM.ITEMNM, '') AS ITEMNM
    , IFNULL(MSTITEM.ITEMCD, '') AS ITEMCD
  FROM PRDWORK
  INNER JOIN PRDINS
    ON PRDINS.PRDINSKEY = PRDWORK.PRDINSKEY
  LEFT JOIN MSTLINE_EQM
    ON MSTLINE_EQM.EQMCD = PRDWORK.EQMCD
  LEFT JOIN MSTITEM
    ON MSTITEM.ITEMID = PRDWORK.ITEMID
  LEFT JOIN (
              -- 작업자 (PRDWORK_EMP)
              SELECT
                  PRDWORK_EMP.PRDWORKKEY
                , GROUP_CONCAT(IFNULL(MSTEMP.EMPNM, PRDWORK_EMP.EMPCD) SEPARATOR ', ') AS EMPNM
              FROM PRDWORK_EMP
              LEFT JOIN MSTEMP
                ON MSTEMP.EMPCD = PRDWORK_EMP.EMPCD
              WHERE PRDWORK_EMP.PRDWORKKEY = $PRDWORKKEY
              GROUP BY PRDWORK_EMP.PRDWORKKEY
            ) AS WORK_EMP
    ON WORK_EMP.PRDWORKKEY = PRDWORK.PRDWORKKEY
  WHERE PRDWORK.PRDWORKKEY = $PRDWORKKEY
  ;

  -- 1. 검사 회차 (열 제목 = 검사시각)
  SELECT
      TMP_PRD5001_RST.SEQNO
    , SUBSTRING(TMP_PRD5001_RST.FIXTIME, 12, 5) AS HHMM
    , TMP_PRD5001_RST.FIXTIME
    , IFNULL(MSTEMP.EMPNM, TMP_PRD5001_RST.EMPCD) AS EMPNM
    , TMP_PRD5001_RST.FINALJUDGE
  FROM TMP_PRD5001_RST
  LEFT JOIN MSTEMP
    ON MSTEMP.EMPCD = TMP_PRD5001_RST.EMPCD
  ORDER BY TMP_PRD5001_RST.SEQNO
  ;

  -- 2. 검사항목 × 시료 줄 (검사기준의 전 항목. 항목 정보는 시료 1번 줄에만, T01~T30 = 회차별 값, N01~N30 = 불합격 Y)
  SELECT
      IF(TMP_PRD5001_NO.NO = 1, COALESCE(NULLIF(GPCD('PRCDETAIL', MSTRPTREV_DETAIL.PRCDETAIL), ''), MSTRPTREV_DETAIL.PRCDETAIL), '') AS PRCDETAILNM
    , IF(TMP_PRD5001_NO.NO = 1, MSTRPTREV_DETAIL.STDNM, '') AS STDNM
    , IF(TMP_PRD5001_NO.NO = 1, MSTRPTREV_DETAIL.STDPART, '') AS STDPART
    , IF(TMP_PRD5001_NO.NO = 1, MSTRPTREV_DETAIL.FEATURE, '') AS FEATURE
    , IF(TMP_PRD5001_NO.NO = 1,
         CASE
           WHEN MSTRPTREV_DETAIL.STDCHKTP = '02' THEN FIND_STDJUDGE_MEASURE(MSTRPTREV_DETAIL.STDRANGE, MSTRPTREV_DETAIL.STDVAL, MSTRPTREV_DETAIL.STDUNIT, MSTRPTREV_DETAIL.STDMINUS, MSTRPTREV_DETAIL.STDPLUS)
         ELSE MSTRPTREV_DETAIL.STDJUDGE END, '') AS STDJUDGE  -- 검사규격 (측정이면 기준값·공차로 생성, TAL2001_R01 과 같음)
    , IF(TMP_PRD5001_NO.NO = 1, COALESCE(NULLIF(GPCD('STDCYCLE', MSTRPTREV_DETAIL.STDCYCLE), ''), MSTRPTREV_DETAIL.STDCYCLE), '') AS STDCYCLENM
    , IF(TMP_PRD5001_NO.NO = 1, COALESCE(NULLIF(GPCD('STDMACHINE', MSTRPTREV_DETAIL.STDMACHINE), ''), MSTRPTREV_DETAIL.STDMACHINE), '') AS STDMACHINENM
    , TMP_PRD5001_NO.NO AS SAMPLENO
    , IF(MSTRPTREV_DETAIL.STDCHKTP = '02', GREATEST(IFNULL(MSTRPTREV_DETAIL.SAMPLESIZE + 0, 0), IFNULL(TMP_PRD5001_CNT.MAXNO, 0), 1), 1) AS SAMPLECNT
    , IFNULL(TQM_PIVOT.T01, '') AS T01
    , IFNULL(TQM_PIVOT.T02, '') AS T02
    , IFNULL(TQM_PIVOT.T03, '') AS T03
    , IFNULL(TQM_PIVOT.T04, '') AS T04
    , IFNULL(TQM_PIVOT.T05, '') AS T05
    , IFNULL(TQM_PIVOT.T06, '') AS T06
    , IFNULL(TQM_PIVOT.T07, '') AS T07
    , IFNULL(TQM_PIVOT.T08, '') AS T08
    , IFNULL(TQM_PIVOT.T09, '') AS T09
    , IFNULL(TQM_PIVOT.T10, '') AS T10
    , IFNULL(TQM_PIVOT.T11, '') AS T11
    , IFNULL(TQM_PIVOT.T12, '') AS T12
    , IFNULL(TQM_PIVOT.T13, '') AS T13
    , IFNULL(TQM_PIVOT.T14, '') AS T14
    , IFNULL(TQM_PIVOT.T15, '') AS T15
    , IFNULL(TQM_PIVOT.T16, '') AS T16
    , IFNULL(TQM_PIVOT.T17, '') AS T17
    , IFNULL(TQM_PIVOT.T18, '') AS T18
    , IFNULL(TQM_PIVOT.T19, '') AS T19
    , IFNULL(TQM_PIVOT.T20, '') AS T20
    , IFNULL(TQM_PIVOT.T21, '') AS T21
    , IFNULL(TQM_PIVOT.T22, '') AS T22
    , IFNULL(TQM_PIVOT.T23, '') AS T23
    , IFNULL(TQM_PIVOT.T24, '') AS T24
    , IFNULL(TQM_PIVOT.T25, '') AS T25
    , IFNULL(TQM_PIVOT.T26, '') AS T26
    , IFNULL(TQM_PIVOT.T27, '') AS T27
    , IFNULL(TQM_PIVOT.T28, '') AS T28
    , IFNULL(TQM_PIVOT.T29, '') AS T29
    , IFNULL(TQM_PIVOT.T30, '') AS T30
    , IFNULL(TQM_PIVOT.N01, '') AS N01
    , IFNULL(TQM_PIVOT.N02, '') AS N02
    , IFNULL(TQM_PIVOT.N03, '') AS N03
    , IFNULL(TQM_PIVOT.N04, '') AS N04
    , IFNULL(TQM_PIVOT.N05, '') AS N05
    , IFNULL(TQM_PIVOT.N06, '') AS N06
    , IFNULL(TQM_PIVOT.N07, '') AS N07
    , IFNULL(TQM_PIVOT.N08, '') AS N08
    , IFNULL(TQM_PIVOT.N09, '') AS N09
    , IFNULL(TQM_PIVOT.N10, '') AS N10
    , IFNULL(TQM_PIVOT.N11, '') AS N11
    , IFNULL(TQM_PIVOT.N12, '') AS N12
    , IFNULL(TQM_PIVOT.N13, '') AS N13
    , IFNULL(TQM_PIVOT.N14, '') AS N14
    , IFNULL(TQM_PIVOT.N15, '') AS N15
    , IFNULL(TQM_PIVOT.N16, '') AS N16
    , IFNULL(TQM_PIVOT.N17, '') AS N17
    , IFNULL(TQM_PIVOT.N18, '') AS N18
    , IFNULL(TQM_PIVOT.N19, '') AS N19
    , IFNULL(TQM_PIVOT.N20, '') AS N20
    , IFNULL(TQM_PIVOT.N21, '') AS N21
