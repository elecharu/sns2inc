CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.PRD6001_R02(
-- *****************************************************************************
-- Comment: 설비 일상점검 계획등록 (설비그룹·설비별 점검계획 리비전 관리, CHKTP = '01' 일상점검)
-- Create: 2026-10-23 10:25:
-- Modify: 2026-10-23 10:39:      회사 표준 구조로 정리 (CASE $CALLTYPE 단일 구조, 설비그룹/설비 CALLTYPE 을 $PLANTP 로 통합)
--         2026-10-23 11:00:      설비는 2공장(MSTEQM.FACTORYCD = '07')만 조회·등록
--         2026-10-23 16:05:      설비 목록에 작업장·공정(EQMTP)·라인(EQMGROUP1) 조회조건과 표시 컬럼 추가
--         2026-10-23 16:22:      설비 목록에 설비그룹명 추가, 작업장·공정·라인·설비그룹·설비 순 정렬
--         2026-11-03:            리비전 점검항목 조회(LIST_PLAN_REV_ITEM)에 점검주기(CHKCYCLE) 추가
--         2026-11-03:            추가할 일상점검 항목 조회(LIST_CHKKND_ADD)에 점검주기(CHKCYCLE) 추가
--         2026-11-26:            설비그룹 탭 삭제(화면). 점검주기는 기준정보(MSTCHKKND)에서 가져오지 않고 이 화면에서 선택
--                                - LIST_CHKKND_ADD 점검주기 제외, ADD_PLAN_ITEM 점검주기 빈값
--                                - 점검기준(CHKSTD 글자) + 판정값(STDTP, MINVAL, MAXVAL: 화면에서 글자를 해석한 값) 저장 (SAVE_PLAN_ITEM)
--                                - 점검항목 위치사진(MSTEQMREV_DETAIL_IMG): LIST_ITEMIMG, ADD_ITEMIMG, DEL_ITEMIMG, 새 REV 만들 때 같이 복사
--                                $CHKKNDCD, $FILEKEY, $CHKCYCLE_LIST, $CHKSTD_LIST, $STDTP_LIST, $MINVAL_LIST, $MAXVAL_LIST 파라미터 추가
--                                - PRINT_CHKSHEET: 설비 일상점검표 출력 데이터 (리포트 PRD6001_R02)
-- *****************************************************************************
  IN $PLANTP        CHAR(1),          -- 계획구분 (G: 설비그룹, E: 설비)
  IN $PLANCD        VARCHAR(50),      -- 설비그룹코드 또는 설비코드
  IN $PLANCD_COPY   VARCHAR(50),      -- 복사 원본 설비그룹코드 또는 설비코드
  IN $REVNUM        VARCHAR(20),      -- 리비전 번호
  IN $REMARK        VARCHAR(1000),    -- 개정내용
  IN $EQMGRP        VARCHAR(50),      -- 조회조건 설비그룹
  IN $FANO          VARCHAR(20),      -- 조회조건 설비
  IN $LINECD        VARCHAR(20),      -- 조회조건 작업장
  IN $EQMTP         VARCHAR(50),      -- 조회조건 공정 (MSTEQM.EQMTP, FM100)
  IN $EQMGROUP1     VARCHAR(50),      -- 조회조건 라인 (MSTEQM.EQMGROUP1, FM113)

  IN $CHKKNDCD      VARCHAR(20),      -- 사진: 점검코드
  IN $FILEKEY       VARCHAR(100),     -- 사진: 파일키

  IN $CHKKNDCD_LIST MEDIUMTEXT,
  IN $SORTNO_LIST   MEDIUMTEXT,
  IN $REMARK_LIST   MEDIUMTEXT,
  IN $CHKCYCLE_LIST MEDIUMTEXT,       -- 점검주기 (CHKCYCLE)
  IN $CHKSTD_LIST   MEDIUMTEXT,       -- 점검기준 (입력 글자)
  IN $STDTP_LIST    MEDIUMTEXT,       -- 판정방식 (RANGE / OKNG / 빈값)
  IN $MINVAL_LIST   MEDIUMTEXT,       -- 판정 하한 (빈값이면 검사 안 함)
  IN $MAXVAL_LIST   MEDIUMTEXT,       -- 판정 상한 (빈값이면 검사 안 함)
-- *****************************************************************************
  IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- SET @DEBUGLOGYN = 'Y';
-- *****************************************************************************
  DECLARE _$CHKKNDCD   VARCHAR(20);
  DECLARE _$SORTNO     VARCHAR(100);
  DECLARE _$REMARK     VARCHAR(1000);
  DECLARE _$CHKCYCLE   VARCHAR(10);
  DECLARE _$CHKSTD     VARCHAR(200);
  DECLARE _$STDTP      VARCHAR(10);
  DECLARE _$MINVAL     VARCHAR(100);
  DECLARE _$MAXVAL     VARCHAR(100);

  DECLARE _$EQMGRPNM   VARCHAR(1000);
  DECLARE _$LOCKKEY    VARCHAR(50);
  DECLARE _$REVCD      VARCHAR(20);
  DECLARE _$OLDREVCD   VARCHAR(20);
  DECLARE _$COPYREVCD  VARCHAR(20);
  DECLARE _$REVNUM     INT;
  DECLARE _$APRVSTT    CHAR(1);
  DECLARE _$REQTIME    VARCHAR(19);
-- ****************************************************************************
CASE $CALLTYPE
-- ****************************************************************************
WHEN 'LIST_MSTEQM_GRP' THEN  -- 설비그룹 목록 (최신 REV 상태)

  -- 같은 이름의 설비그룹코드 함께 조회
  SET _$EQMGRPNM = (SELECT COMTYPE.TPNM FROM COMTYPE WHERE COMTYPE.GPCD = 'FM116' AND COMTYPE.TPCD = $EQMGRP LIMIT 1);

  SELECT
      COMTYPE.TPCD AS EQMGUBUN
    , COMTYPE.TPNM AS EQMGRPNM
    , IFNULL(CONCAT('REV.', MSTEQMREV_HEADER.REVNUM), '') AS REVNM
    , CASE
        WHEN MSTEQMREV_HEADER.REVCD IS NULL THEN ''
        WHEN MSTEQMREV_HEADER.APRVSTT = 'A' THEN '승인'
      ELSE '대기' END AS APRVSTTNM
  FROM COMTYPE
  LEFT JOIN MSTEQMREV_HEADER
    ON MSTEQMREV_HEADER.CHKTP = '01'
   AND MSTEQMREV_HEADER.PLANTP = 'G'
   AND MSTEQMREV_HEADER.PLANCD = COMTYPE.TPCD
   AND MSTEQMREV_HEADER.REVNUM = (
                                   SELECT MAX(MSTEQMREV_HEADER2.REVNUM)
                                   FROM MSTEQMREV_HEADER AS MSTEQMREV_HEADER2
                                   WHERE MSTEQMREV_HEADER2.CHKTP = '01'
                                     AND MSTEQMREV_HEADER2.PLANTP = 'G'
                                     AND MSTEQMREV_HEADER2.PLANCD = COMTYPE.TPCD
                                 )
  WHERE COMTYPE.GPCD = 'FM116'
    AND COMTYPE.USEYN = 'Y'
    AND EXISTS (SELECT 1 FROM MSTEQM WHERE MSTEQM.EQMGUBUN = COMTYPE.TPCD AND MSTEQM.FACTORYCD = '07' AND MSTEQM.USEYN = 'Y')
    AND ($EQMGRP = '' OR COMTYPE.TPNM = _$EQMGRPNM)
  ORDER BY COMTYPE.SORTNO, COMTYPE.TPCD
  ;

-- ****************************************************************************
WHEN 'LIST_MSTEQM' THEN  -- 설비 목록 (최신 REV 상태)

  SELECT
      MSTEQM.FANO
    , MSTEQM.EQMGUBUN
    , MSTEQM.EQMNM
    , IFNULL(MSTLINE.LINENM, '') AS LINENM
    , GPCD('FM100', MSTEQM.EQMTP) AS EQMTPNM
    , GPCD('FM113', MSTEQM.EQMGROUP1) AS EQMGROUP1NM
    , GPCD('FM116', MSTEQM.EQMGUBUN) AS EQMGUBUNNM
    , IFNULL(CONCAT('REV.', MSTEQMREV_HEADER.REVNUM), '') AS REVNM
    , CASE
        WHEN MSTEQMREV_HEADER.REVCD IS NULL THEN ''
        WHEN MSTEQMREV_HEADER.APRVSTT = 'A' THEN '승인'
      ELSE '대기' END AS APRVSTTNM
  FROM MSTEQM
  LEFT JOIN MSTLINE
    ON MSTLINE.LINECD = MSTEQM.LINECD
  LEFT JOIN MSTEQMREV_HEADER
    ON MSTEQMREV_HEADER.CHKTP = '01'
   AND MSTEQMREV_HEADER.PLANTP = 'E'
   AND MSTEQMREV_HEADER.PLANCD = MSTEQM.FANO
   AND MSTEQMREV_HEADER.REVNUM = (
                                   SELECT MAX(MSTEQMREV_HEADER2.REVNUM)
                                   FROM MSTEQMREV_HEADER AS MSTEQMREV_HEADER2
                                   WHERE MSTEQMREV_HEADER2.CHKTP = '01'
                                     AND MSTEQMREV_HEADER2.PLANTP = 'E'
                                     AND MSTEQMREV_HEADER2.PLANCD = MSTEQM.FANO
                                 )
  WHERE MSTEQM.FACTORYCD = '07'
    AND MSTEQM.USEYN = 'Y'
    AND ($EQMGRP = '' OR MSTEQM.EQMGUBUN LIKE CONCAT('%', $EQMGRP, '%'))
    AND ($FANO = '' OR MSTEQM.FANO LIKE CONCAT('%', $FANO, '%') OR MSTEQM.EQMNM LIKE CONCAT('%', $FANO, '%'))
    AND ($LINECD = '' OR MSTEQM.LINECD = $LINECD)
    AND ($EQMTP = '' OR MSTEQM.EQMTP = $EQMTP)
    AND ($EQMGROUP1 = '' OR MSTEQM.EQMGROUP1 = $EQMGROUP1)
  ORDER BY MSTEQM.LINECD, MSTEQM.EQMTP, MSTEQM.EQMGROUP1, MSTEQM.EQMGUBUN, MSTEQM.FANO
  ;

-- ****************************************************************************
WHEN 'LIST_PLAN_REV' THEN  -- 리비전 이력 조회

  SELECT
      CONCAT('REV.', MSTEQMREV_HEADER.REVNUM) AS REVNM
    , IF(MSTEQMREV_HEADER.APRVSTT = 'A', '승인', '대기') AS APRVSTTNM
    , MSTEQMREV_HEADER.REMARK
    , IFNULL(MSTEMP1.EMPNM, MSTEQMREV_HEADER.REQEMP) AS REQEMP
    , MSTEQMREV_HEADER.REQTIME
    , IF(MSTEQMREV_HEADER.APRVSTT = 'A', IFNULL(MSTEMP2.EMPNM, MSTEQMREV_HEADER.APRVEMP), '') AS APRVEMP
    , IF(MSTEQMREV_HEADER.APRVSTT = 'A', MSTEQMREV_HEADER.APRVTIME, '') AS APRVTIME
    , MSTEQMREV_HEADER.REVNUM
    , MSTEQMREV_HEADER.APRVSTT
  FROM MSTEQMREV_HEADER
  LEFT JOIN MSTEMP AS MSTEMP1
    ON MSTEMP1.EMPCD = MSTEQMREV_HEADER.REQEMP
  LEFT JOIN MSTEMP AS MSTEMP2
    ON MSTEMP2.EMPCD = MSTEQMREV_HEADER.APRVEMP
  WHERE MSTEQMREV_HEADER.CHKTP = '01'
    AND MSTEQMREV_HEADER.PLANTP = $PLANTP
    AND MSTEQMREV_HEADER.PLANCD = $PLANCD
  ORDER BY MSTEQMREV_HEADER.REVNUM DESC
  ;

-- ****************************************************************************
WHEN 'LIST_PLAN_REV_ITEM' THEN  -- 리비전 점검항목 조회 ($REVNUM 이 빈 값이면 최신 REV)

  IF $REVNUM = '' THEN
    SET _$REVCD = (SELECT MSTEQMREV_HEADER.REVCD FROM MSTEQMREV_HEADER
                   WHERE MSTEQMREV_HEADER.CHKTP = '01' AND MSTEQMREV_HEADER.PLANTP = $PLANTP AND MSTEQMREV_HEADER.PLANCD = $PLANCD
                   ORDER BY MSTEQMREV_HEADER.REVNUM DESC LIMIT 1);
  ELSE
    SET _$REVCD = (SELECT MSTEQMREV_HEADER.REVCD FROM MSTEQMREV_HEADER
                   WHERE MSTEQMREV_HEADER.CHKTP = '01' AND MSTEQMREV_HEADER.PLANTP = $PLANTP AND MSTEQMREV_HEADER.PLANCD = $PLANCD
                     AND MSTEQMREV_HEADER.REVNUM = $REVNUM);
  END IF;

  SELECT
      MSTEQMREV_DETAIL.CHKKNDCD
    , MSTEQMREV_DETAIL.CHKKNDNM
    , COALESCE(NULLIF(GPCD('CHKLOC', MSTEQMREV_DETAIL.CHKLOC), ''), MSTEQMREV_DETAIL.CHKLOC) AS CHKLOCNM
    , COALESCE(NULLIF(GPCD('CHKMTH', MSTEQMREV_DETAIL.CHKMTH), ''), MSTEQMREV_DETAIL.CHKMTH) AS CHKMTHNM
    , COALESCE(NULLIF(GPCD('CHKVALTP', MSTEQMREV_DETAIL.CHKVALTP), ''), MSTEQMREV_DETAIL.CHKVALTP) AS CHKVALTPNM
    , MSTEQMREV_DETAIL.CHKVALTP
    , MSTEQMREV_DETAIL.CHKSTD
    , MSTEQMREV_DETAIL.STDTP
    -- 소수점 뒤 0 은 지움 (0.400000 → 0.4, 30.000000 → 30), NULL 이면 빈값
    , IFNULL(TRIM(TRAILING '.' FROM TRIM(TRAILING '0' FROM CAST(MSTEQMREV_DETAIL.MINVAL AS CHAR))), '') AS MINVAL
    , IFNULL(TRIM(TRAILING '.' FROM TRIM(TRAILING '0' FROM CAST(MSTEQMREV_DETAIL.MAXVAL AS CHAR))), '') AS MAXVAL
    , MSTEQMREV_DETAIL.CHKCYCLE
    , MSTEQMREV_DETAIL.SORTNO
    , MSTEQMREV_DETAIL.REMARK
    , (SELECT COUNT(*) FROM MSTEQMREV_DETAIL_IMG
       WHERE MSTEQMREV_DETAIL_IMG.REVCD = MSTEQMREV_DETAIL.REVCD
         AND MSTEQMREV_DETAIL_IMG.CHKKNDCD = MSTEQMREV_DETAIL.CHKKNDCD) AS IMGCNT
  FROM MSTEQMREV_DETAIL
  WHERE MSTEQMREV_DETAIL.REVCD = _$REVCD
  ORDER BY MSTEQMREV_DETAIL.SORTNO, MSTEQMREV_DETAIL.CHKKNDCD
  ;

-- ****************************************************************************
WHEN 'LIST_CHKKND_ADD' THEN  -- 추가할 수 있는 일상점검 항목 (최신 REV 에 없는 항목)

  SET _$REVCD = (SELECT MSTEQMREV_HEADER.REVCD FROM MSTEQMREV_HEADER
                 WHERE MSTEQMREV_HEADER.CHKTP = '01' AND MSTEQMREV_HEADER.PLANTP = $PLANTP AND MSTEQMREV_HEADER.PLANCD = $PLANCD
                 ORDER BY MSTEQMREV_HEADER.REVNUM DESC LIMIT 1);

  SELECT
      MSTCHKKND.CHKKNDCD
    , MSTCHKKND.CHKKNDNM
    , COALESCE(NULLIF(GPCD('CHKLOC', MSTCHKKND.CHKLOC), ''), MSTCHKKND.CHKLOC) AS CHKLOCNM
    , COALESCE(NULLIF(GPCD('CHKMTH', MSTCHKKND.CHKMTH), ''), MSTCHKKND.CHKMTH) AS CHKMTHNM
    , COALESCE(NULLIF(GPCD('CHKVALTP', MSTCHKKND.CHKVALTP), ''), MSTCHKKND.CHKVALTP) AS CHKVALTPNM
    , '' AS REMARK
  FROM MSTCHKKND
  WHERE MSTCHKKND.CHKTP = '01'
    AND MSTCHKKND.USEYN = 'Y'
    AND NOT EXISTS (SELECT 1 FROM MSTEQMREV_DETAIL WHERE MSTEQMREV_DETAIL.REVCD = _$REVCD AND MSTEQMREV_DETAIL.CHKKNDCD = MSTCHKKND.CHKKNDCD)
  ORDER BY MSTCHKKND.SORTNO, MSTCHKKND.CHKKNDCD
  ;

-- ****************************************************************************
WHEN 'LIST_COPY_PLAN' THEN  -- 복사 원본 목록 (최신 REV 에 점검항목이 있는 다른 설비그룹·설비)

  SELECT
      MSTEQMREV_HEADER.PLANCD
    , IF($PLANTP = 'G', COMTYPE.TPNM, MSTEQM.EQMNM) AS PLANNM
    , COUNT(*) AS ITEMCNT
  FROM MSTEQMREV_HEADER
  INNER JOIN MSTEQMREV_DETAIL
    ON MSTEQMREV_DETAIL.REVCD = MSTEQMREV_HEADER.REVCD
  LEFT JOIN COMTYPE
    ON COMTYPE.GPCD = 'FM116'
   AND COMTYPE.TPCD = MSTEQMREV_HEADER.PLANCD
  LEFT JOIN MSTEQM
    ON MSTEQM.FANO = MSTEQMREV_HEADER.PLANCD
   AND MSTEQM.FACTORYCD = '07'
  WHERE MSTEQMREV_HEADER.CHKTP = '01'
    AND MSTEQMREV_HEADER.PLANTP = $PLANTP
    AND MSTEQMREV_HEADER.PLANCD <> $PLANCD
    AND MSTEQMREV_HEADER.REVNUM = (
                                    SELECT MAX(MSTEQMREV_HEADER2.REVNUM)
                                    FROM MSTEQMREV_HEADER AS MSTEQMREV_HEADER2
                                    WHERE MSTEQMREV_HEADER2.CHKTP = '01'
                                      AND MSTEQMREV_HEADER2.PLANTP = MSTEQMREV_HEADER.PLANTP
                                      AND MSTEQMREV_HEADER2.PLANCD = MSTEQMREV_HEADER.PLANCD
                                  )
    AND IF($PLANTP = 'G', COMTYPE.USEYN, MSTEQM.USEYN) = 'Y'
  GROUP BY MSTEQMREV_HEADER.PLANCD, COMTYPE.TPNM, MSTEQM.EQMNM
  ORDER BY MSTEQMREV_HEADER.PLANCD
  ;

-- ****************************************************************************
WHEN 'ADD_PLAN_ITEM' THEN  -- 점검항목 추가

  IF $PLANTP NOT IN ('G', 'E') OR $PLANCD = '' THEN
    CALL COMERR('설비그룹 또는 설비를 선택하세요.');
    LEAVE PROC;
  END IF;

  IF $CHKKNDCD_LIST = '' THEN
    CALL COMERR('추가할 점검항목을 선택하세요.');
    LEAVE PROC;
  END IF;

  -- 같은 대상 동시 변경 방지 (기준정보 행 잠금)
  IF $PLANTP = 'G' THEN
    SET _$LOCKKEY = (SELECT COMTYPE.TPCD FROM COMTYPE WHERE COMTYPE.GPCD = 'FM116' AND COMTYPE.TPCD = $PLANCD AND COMTYPE.USEYN = 'Y' LIMIT 1 FOR UPDATE);
  ELSE
    SET _$LOCKKEY = (SELECT MSTEQM.FANO FROM MSTEQM WHERE MSTEQM.FANO = $PLANCD AND MSTEQM.FACTORYCD = '07' AND MSTEQM.USEYN = 'Y' LIMIT 1 FOR UPDATE);
  END IF;

  IF _$LOCKKEY IS NULL THEN
    CALL COMERR('사용 중인 설비그룹 또는 설비를 선택하세요.');
    LEAVE PROC;
  END IF;

  SET _$REVCD   = (SELECT MSTEQMREV_HEADER.REVCD FROM MSTEQMREV_HEADER
                   WHERE MSTEQMREV_HEADER.CHKTP = '01' AND MSTEQMREV_HEADER.PLANTP = $PLANTP AND MSTEQMREV_HEADER.PLANCD = $PLANCD
                   ORDER BY MSTEQMREV_HEADER.REVNUM DESC LIMIT 1);
  SET _$REVNUM  = (SELECT MSTEQMREV_HEADER.REVNUM FROM MSTEQMREV_HEADER WHERE MSTEQMREV_HEADER.REVCD = _$REVCD);
  SET _$APRVSTT = (SELECT MSTEQMREV_HEADER.APRVSTT FROM MSTEQMREV_HEADER WHERE MSTEQMREV_HEADER.REVCD = _$REVCD);

  IF IFNULL(CAST(_$REVNUM AS CHAR), '') <> $REVNUM THEN
    CALL COMERR('점검계획이 변경되었습니다. 다시 조회하세요.');
    LEAVE PROC;
  END IF;

  -- 최신 REV 가 없거나 승인됐으면 다음 REV 를 만들고 항목 복사
  IF _$REVCD IS NULL OR _$APRVSTT = 'A' THEN
    SET _$OLDREVCD = _$REVCD;
    SET _$REVCD = GETKEY('REVCD');

    INSERT INTO MSTEQMREV_HEADER (
        REVCD, CHKTP, PLANTP, PLANCD, REVNUM
      , RTIME, REMP, RPRG)
    VALUES (
        _$REVCD, '01', $PLANTP, $PLANCD, IFNULL(_$REVNUM + 1, 0)
      , CALLTIME(), CALLEMP(), CALLPRG());

    INSERT INTO MSTEQMREV_DETAIL (
        REVCD, CHKKNDCD, CHKCYCLE, SORTNO, CHKKNDNM
      , CHKLOC, CHKMTH, CHKVALTP, REMARK
      , CHKSTD, STDTP, MINVAL, MAXVAL
      , RTIME, REMP, RPRG)
    SELECT
        _$REVCD, MSTEQMREV_DETAIL.CHKKNDCD, MSTEQMREV_DETAIL.CHKCYCLE, MSTEQMREV_DETAIL.SORTNO, MSTEQMREV_DETAIL.CHKKNDNM
      , MSTEQMREV_DETAIL.CHKLOC, MSTEQMREV_DETAIL.CHKMTH, MSTEQMREV_DETAIL.CHKVALTP, MSTEQMREV_DETAIL.REMARK
      , MSTEQMREV_DETAIL.CHKSTD, MSTEQMREV_DETAIL.STDTP, MSTEQMREV_DETAIL.MINVAL, MSTEQMREV_DETAIL.MAXVAL
      , CALLTIME(), CALLEMP(), CALLPRG()
    FROM MSTEQMREV_DETAIL
    WHERE MSTEQMREV_DETAIL.REVCD = _$OLDREVCD;

    -- 2026-11-26 위치사진도 새 REV 로 복사 (파일은 그대로, 파일키만)
    INSERT INTO MSTEQMREV_DETAIL_IMG (
        REVCD, CHKKNDCD, FILEKEY
      , RTIME, REMP, RPRG)
    SELECT
        _$REVCD, MSTEQMREV_DETAIL_IMG.CHKKNDCD, MSTEQMREV_DETAIL_IMG.FILEKEY
      , CALLTIME(), CALLEMP(), CALLPRG()
    FROM MSTEQMREV_DETAIL_IMG
    WHERE MSTEQMREV_DETAIL_IMG.REVCD = _$OLDREVCD;
  END IF;

  WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
    CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);
    CALL COMSPLIT($REMARK_LIST, _$REMARK);

    IF NOT EXISTS (SELECT 1 FROM MSTCHKKND WHERE MSTCHKKND.CHKKNDCD = _$CHKKNDCD AND MSTCHKKND.CHKTP = '01' AND MSTCHKKND.USEYN = 'Y') THEN
      CALL COMERR(CONCAT('사용 중인 일상점검 항목만 추가할 수 있습니다.', '\n- 점검코드: ', _$CHKKNDCD));
      LEAVE PROC;
    END IF;

    IF EXISTS (SELECT 1 FROM MSTEQMREV_DETAIL WHERE MSTEQMREV_DETAIL.REVCD = _$REVCD AND MSTEQMREV_DETAIL.CHKKNDCD = _$CHKKNDCD) THEN
      CALL COMERR(CONCAT('이미 등록된 점검항목입니다.', '\n- 점검코드: ', _$CHKKNDCD));
      LEAVE PROC;
    END IF;

    INSERT INTO MSTEQMREV_DETAIL (
        REVCD, CHKKNDCD, CHKCYCLE, SORTNO, CHKKNDNM
      , CHKLOC, CHKMTH, CHKVALTP, REMARK
      , RTIME, REMP, RPRG)
    SELECT
        _$REVCD, MSTCHKKND.CHKKNDCD, ''  -- 2026-11-26 점검주기는 기준정보에서 가져오지 않음 (이 화면 그리드에서 선택 후 저장)
      , (SELECT IFNULL(MAX(MSTEQMREV_DETAIL.SORTNO), 0) + 1 FROM MSTEQMREV_DETAIL WHERE MSTEQMREV_DETAIL.REVCD = _$REVCD)
      , MSTCHKKND.CHKKNDNM
      , MSTCHKKND.CHKLOC, MSTCHKKND.CHKMTH, MSTCHKKND.CHKVALTP, _$REMARK
      , CALLTIME(), CALLEMP(), CALLPRG()
    FROM MSTCHKKND
    WHERE MSTCHKKND.CHKKNDCD = _$CHKKNDCD;
  END WHILE;

  -- 점검계획이 바뀌었으므로 개정내용 저장(승인요청)을 다시 받는다
