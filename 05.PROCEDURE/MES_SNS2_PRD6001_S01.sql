CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.PRD6001_S01(
-- *****************************************************************************
-- Comment: 설비 일상점검 조회 (EQM1001_S04 설비 정기점검 조회 기준, CHKTP = '01' 일상점검 고정)
-- Create: 2026-10-23 13:58:
-- Modify: 2026-11-26 점검월 기준 조회로 변경 (화면 B안: 설비 목록 + 월간 표 + 점검표 출력)
--         - LIST_EQM_MONTH   : 설비 목록 (점검월의 점검횟수·점검일수·NG 건수·마지막 점검일), 작업장·공정·라인·설비 조건
--         - LIST_MONTH_SHEET : 고른 설비의 월간 표 (점검항목 × 1~31일, D01~D31 표시값 / N01~N31 NG 여부)
--         - PRINT_MONTH_SHEET: 점검표 출력 (리포트 PRD6001_S01, 설비 여러 대 = $FANO_LIST)
--         - 표시값: 수치는 점검값, OK → ○, NG → X, 같은 날 여러 번이면 점검시간 순 '/' 로 이음
--         - NG  : 점검값 NG, 또는 그 점검에 쓴 계획 REV 의 판정범위(MSTEQMREV_DETAIL.MINVAL~MAXVAL) 밖
--         - LIST_CHKRSTEQM / LIST_CHKRSTEQMKND 는 그대로 (월간 표 칸 더블클릭 팝업에서 씀)
--         $SMONTH, $LINECD, $EQMTP, $EQMGROUP1, $FANO_LIST 파라미터 추가
-- *****************************************************************************
  IN $SDATE       VARCHAR(20),      -- 점검일자 시작
  IN $EDATE       VARCHAR(20),      -- 점검일자 끝
  IN $EQMCD       VARCHAR(20),      -- 설비코드
  IN $CHKRSTKEY   VARCHAR(20),      -- 점검키
  IN $SMONTH      VARCHAR(7),       -- 점검월 (YYYY-MM)
  IN $LINECD      VARCHAR(20),      -- 작업장
  IN $EQMTP       VARCHAR(50),      -- 공정 (MSTEQM.EQMTP, FM100)
  IN $EQMGROUP1   VARCHAR(50),      -- 라인 (MSTEQM.EQMGROUP1, FM113)
  IN $FANO_LIST   MEDIUMTEXT,       -- 설비코드 목록 (쉼표 구분, 월간 표·점검표 출력)
-- *****************************************************************************
  IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- SET @DEBUGLOGYN = 'Y';
-- *****************************************************************************
  DECLARE _$SDATE VARCHAR(10);
  DECLARE _$EDATE VARCHAR(10);
-- ****************************************************************************
  -- 점검월 조회 공통: 그 달 일상점검 결과(값이 있는 것만)를 임시표에 모음
  IF $CALLTYPE IN ('LIST_EQM_MONTH', 'LIST_MONTH_SHEET', 'PRINT_MONTH_SHEET') THEN
    IF IFNULL($SMONTH, '') NOT REGEXP '^[0-9]{4}-[0-9]{2}$' THEN
      CALL COMERR('점검월을 선택하세요.');
      LEAVE PROC;
    END IF;

    IF $CALLTYPE IN ('LIST_MONTH_SHEET', 'PRINT_MONTH_SHEET') AND IFNULL($FANO_LIST, '') = '' THEN
      CALL COMERR('설비를 선택하세요.');
      LEAVE PROC;
    END IF;

    SET _$SDATE = CONCAT($SMONTH, '-01');
    SET _$EDATE = DATE_FORMAT(LAST_DAY(_$SDATE), '%Y-%m-%d');

    DROP TABLE IF EXISTS TEMP_S01_RST;
    CREATE TEMPORARY TABLE TEMP_S01_RST (
        FANO VARCHAR(100) NOT NULL, CHKRSTKEY VARCHAR(100) NOT NULL, DAYNO INT NOT NULL, CHKTIME VARCHAR(19) NOT NULL
      , CHKKNDCD VARCHAR(100) NOT NULL, CHKKNDNM VARCHAR(1000) NOT NULL, CHKLOCNM VARCHAR(1000) NOT NULL
      , DISP VARCHAR(1000) NOT NULL, NGYN CHAR(1) NOT NULL, BASEDATE VARCHAR(10) NOT NULL);

    INSERT INTO TEMP_S01_RST (FANO, CHKRSTKEY, DAYNO, CHKTIME, CHKKNDCD, CHKKNDNM, CHKLOCNM, DISP, NGYN, BASEDATE)
    SELECT
        CHKRSTEQM.EQMCD
      , CHKRSTEQM.CHKRSTKEY
      , DAY(CHKRSTEQM.BASEDATE)
      , CHKRSTEQM.CHKTIME
      , CHKRSTEQMKND.CHKKNDCD
      , CHKRSTEQMKND.CHKKNDNM
      , COALESCE(NULLIF(GPCD('CHKLOC', CHKRSTEQMKND.CHKLOC), ''), CHKRSTEQMKND.CHKLOC)
      , CASE UPPER(TRIM(CHKRSTEQMKND.CHKVALUE)) WHEN 'OK' THEN '○' WHEN 'NG' THEN 'X' ELSE TRIM(CHKRSTEQMKND.CHKVALUE) END
      , CASE
          WHEN UPPER(TRIM(CHKRSTEQMKND.CHKVALUE)) = 'NG' THEN 'Y'
          WHEN MSTEQMREV_DETAIL.STDTP = 'RANGE'
           AND TRIM(CHKRSTEQMKND.CHKVALUE) REGEXP '^-?[0-9]+(\\.[0-9]+)?$'
           AND (   (MSTEQMREV_DETAIL.MINVAL IS NOT NULL AND CAST(TRIM(CHKRSTEQMKND.CHKVALUE) AS DECIMAL(20, 6)) < MSTEQMREV_DETAIL.MINVAL)
                OR (MSTEQMREV_DETAIL.MAXVAL IS NOT NULL AND CAST(TRIM(CHKRSTEQMKND.CHKVALUE) AS DECIMAL(20, 6)) > MSTEQMREV_DETAIL.MAXVAL)) THEN 'Y'
          ELSE 'N' END
      , CHKRSTEQM.BASEDATE
    FROM CHKRSTEQM
    INNER JOIN CHKRSTEQMKND
      ON CHKRSTEQMKND.CHKRSTKEY = CHKRSTEQM.CHKRSTKEY
    INNER JOIN MSTEQM
      ON MSTEQM.FANO = CHKRSTEQM.EQMCD
     AND MSTEQM.FACTORYCD = '07'
    LEFT JOIN MSTEQMREV_DETAIL   -- 그 점검에 쓴 계획 REV 의 판정범위
      ON MSTEQMREV_DETAIL.REVCD = IF(CHKRSTEQMKND.PLANTP = 'G', CHKRSTEQM.GRPREVCD, CHKRSTEQM.REVCD)
     AND MSTEQMREV_DETAIL.CHKKNDCD = CHKRSTEQMKND.CHKKNDCD
    WHERE CHKRSTEQM.CHKTP = '01'
      AND CHKRSTEQM.BASEDATE BETWEEN _$SDATE AND _$EDATE
      AND TRIM(CHKRSTEQMKND.CHKVALUE) <> ''
      AND (IFNULL($FANO_LIST, '') = '' OR FIND_IN_SET(CHKRSTEQM.EQMCD, $FANO_LIST) > 0)
      AND (IFNULL($EQMCD, '') = '' OR CHKRSTEQM.EQMCD = $EQMCD)
      AND (IFNULL($LINECD, '') = '' OR MSTEQM.LINECD = $LINECD)
      AND (IFNULL($EQMTP, '') = '' OR MSTEQM.EQMTP = $EQMTP)
      AND (IFNULL($EQMGROUP1, '') = '' OR MSTEQM.EQMGROUP1 = $EQMGROUP1);
  END IF;

  -- 월간 표·점검표 출력 공통: 설비별 점검항목 (최신 계획 REV 항목 + 그 달 결과에만 있는 항목)
  IF $CALLTYPE IN ('LIST_MONTH_SHEET', 'PRINT_MONTH_SHEET') THEN
    DROP TABLE IF EXISTS TEMP_S01_ITEM;
    CREATE TEMPORARY TABLE TEMP_S01_ITEM (
        FANO VARCHAR(100) NOT NULL, CHKKNDCD VARCHAR(100) NOT NULL, SORTNO DECIMAL(20, 0) NOT NULL
      , CHKLOCNM VARCHAR(1000) NOT NULL, CHKKNDNM VARCHAR(1000) NOT NULL, CHKSTD VARCHAR(200) NOT NULL, CHKCYCLENM VARCHAR(200) NOT NULL);

    INSERT INTO TEMP_S01_ITEM (FANO, CHKKNDCD, SORTNO, CHKLOCNM, CHKKNDNM, CHKSTD, CHKCYCLENM)
    SELECT
        U.FANO, U.CHKKNDCD, MIN(U.SORTNO)
      , IFNULL(MAX(CASE WHEN U.SRC = 'P' THEN U.CHKLOCNM END), MAX(U.CHKLOCNM))   -- 계획 값 우선
      , IFNULL(MAX(CASE WHEN U.SRC = 'P' THEN U.CHKKNDNM END), MAX(U.CHKKNDNM))
      , IFNULL(MAX(CASE WHEN U.SRC = 'P' THEN U.CHKSTD END), '')
      , IFNULL(MAX(CASE WHEN U.SRC = 'P' THEN U.CHKCYCLENM END), '')
    FROM (
          SELECT
              'P' AS SRC
            , MSTEQMREV_HEADER.PLANCD AS FANO
            , MSTEQMREV_DETAIL.CHKKNDCD
            , MSTEQMREV_DETAIL.SORTNO
            , COALESCE(NULLIF(GPCD('CHKLOC', MSTEQMREV_DETAIL.CHKLOC), ''), MSTEQMREV_DETAIL.CHKLOC) AS CHKLOCNM
            , MSTEQMREV_DETAIL.CHKKNDNM
            , MSTEQMREV_DETAIL.CHKSTD
            , COALESCE(NULLIF(GPCD('CHKCYCLE', MSTEQMREV_DETAIL.CHKCYCLE), ''), MSTEQMREV_DETAIL.CHKCYCLE) AS CHKCYCLENM
          FROM MSTEQMREV_HEADER
          INNER JOIN MSTEQMREV_DETAIL
            ON MSTEQMREV_DETAIL.REVCD = MSTEQMREV_HEADER.REVCD
          WHERE MSTEQMREV_HEADER.CHKTP = '01'
            AND MSTEQMREV_HEADER.PLANTP = 'E'
            AND FIND_IN_SET(MSTEQMREV_HEADER.PLANCD, $FANO_LIST) > 0
            AND MSTEQMREV_HEADER.REVNUM = (SELECT MAX(MSTEQMREV_HEADER2.REVNUM)
                                             FROM MSTEQMREV_HEADER AS MSTEQMREV_HEADER2
                                             WHERE MSTEQMREV_HEADER2.CHKTP = '01'
                                               AND MSTEQMREV_HEADER2.PLANTP = 'E'
                                               AND MSTEQMREV_HEADER2.PLANCD = MSTEQMREV_HEADER.PLANCD)
          UNION ALL
          SELECT 'R', TEMP_S01_RST.FANO, TEMP_S01_RST.CHKKNDCD, 99999, TEMP_S01_RST.CHKLOCNM, TEMP_S01_RST.CHKKNDNM, '', ''
          FROM TEMP_S01_RST
         ) AS U
    GROUP BY U.FANO, U.CHKKNDCD;
  END IF;
-- ****************************************************************************
CASE $CALLTYPE
-- ****************************************************************************
WHEN 'LIST_CHKRSTEQM' THEN  -- 일상점검 이력

  SELECT
      CHKRSTEQM.BASEDATE
    , LEFT(CHKRSTEQM.CHKTIME, 16) AS CHKTIME
    , CHKRSTEQM.EMPCD
    , CHKRSTEQM.EQMCD
    , GPCD('EQMCD', CHKRSTEQM.EQMCD) AS EQMNM
    , CHKRSTEQM.PROBLEM
    , CHKRSTEQM.SOLUTION
    , CHKRSTEQM.CHKRSTKEY
    , CHKRSTEQM.RTIME
  FROM CHKRSTEQM
  WHERE CHKRSTEQM.CHKTP = '01'
    AND CHKRSTEQM.BASEDATE BETWEEN $SDATE AND $EDATE
    AND CHKRSTEQM.EQMCD LIKE CONCAT('%', $EQMCD, '%')
  ORDER BY CHKRSTEQM.BASEDATE, CHKRSTEQM.EQMCD, CHKRSTEQM.CHKTIME
  ;

-- ****************************************************************************
WHEN 'LIST_CHKRSTEQMKND' THEN  -- 일상점검 항목

  SELECT
      CHKRSTEQMKND.CHKRSTKEY
    , CHKRSTEQMKND.CHKKNDCD
    , CHKRSTEQMKND.CHKKNDNM
    , CHKRSTEQMKND.CHKLOC
    , CHKRSTEQMKND.CHKMTH
    , CHKRSTEQMKND.CHKVALTP
    , CHKRSTEQMKND.CHKVALUE
    , CHKRSTEQMKND.REMARK
  FROM CHKRSTEQMKND
  WHERE CHKRSTEQMKND.CHKRSTKEY = $CHKRSTKEY
  ORDER BY (CHKRSTEQMKND.PLANTP = 'G') DESC, CHKRSTEQMKND.SORTNO, CHKRSTEQMKND.CHKKNDCD
  ;

-- ****************************************************************************
WHEN 'LIST_EQM_MONTH' THEN  -- 설비 목록: 그 달 일상점검 계획이나 결과가 있는 2공장 설비  2026-11-26

  SELECT
      'N' AS ISCHECKED
    , MSTEQM.FANO
    , MSTEQM.EQMNM
    , IFNULL(MSTLINE.LINENM, '') AS LINENM
    , IFNULL(GPCD('FM100', MSTEQM.EQMTP), '') AS EQMTPNM
    , IFNULL(GPCD('FM113', MSTEQM.EQMGROUP1), '') AS EQMGROUP1NM
    , IFNULL(RST.CHKCNT, 0) AS CHKCNT
    , IFNULL(RST.CHKDAYS, 0) AS CHKDAYS
    , IFNULL(RST.NGCNT, 0) AS NGCNT
    , IFNULL(RST.LASTDATE, '') AS LASTDATE
  FROM MSTEQM
  LEFT JOIN MSTLINE
    ON MSTLINE.LINECD = MSTEQM.LINECD
  LEFT JOIN (SELECT
                 TEMP_S01_RST.FANO
               , COUNT(DISTINCT TEMP_S01_RST.CHKRSTKEY) AS CHKCNT
               , COUNT(DISTINCT TEMP_S01_RST.BASEDATE) AS CHKDAYS
               , SUM(TEMP_S01_RST.NGYN = 'Y') AS NGCNT
               , MAX(TEMP_S01_RST.BASEDATE) AS LASTDATE
             FROM TEMP_S01_RST
             GROUP BY TEMP_S01_RST.FANO) AS RST
    ON RST.FANO = MSTEQM.FANO
  WHERE MSTEQM.FACTORYCD = '07'
    AND MSTEQM.USEYN = 'Y'
    AND (IFNULL($EQMCD, '') = '' OR MSTEQM.FANO = $EQMCD)
    AND (IFNULL($LINECD, '') = '' OR MSTEQM.LINECD = $LINECD)
    AND (IFNULL($EQMTP, '') = '' OR MSTEQM.EQMTP = $EQMTP)
    AND (IFNULL($EQMGROUP1, '') = '' OR MSTEQM.EQMGROUP1 = $EQMGROUP1)
    AND (RST.FANO IS NOT NULL
         OR EXISTS (SELECT 1 FROM MSTEQMREV_HEADER
                     WHERE MSTEQMREV_HEADER.CHKTP = '01' AND MSTEQMREV_HEADER.PLANTP = 'E' AND MSTEQMREV_HEADER.PLANCD = MSTEQM.FANO))
  ORDER BY MSTEQM.LINECD, MSTEQM.EQMTP, MSTEQM.EQMGROUP1, MSTEQM.FANO
  ;

-- ****************************************************************************
WHEN 'LIST_MONTH_SHEET' THEN  -- 월간 표 (점검항목 × 1~31일)  2026-11-26

  SELECT
      ITEM.FANO
    , ROW_NUMBER() OVER (PARTITION BY ITEM.FANO ORDER BY ITEM.SORTNO, ITEM.CHKKNDCD) AS SEQ
    , ITEM.CHKKNDCD
    , ITEM.CHKLOCNM
    , ITEM.CHKKNDNM
    , ITEM.CHKSTD
    , ITEM.CHKCYCLENM
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 1 THEN DAYS.DAYTXT END), '') AS D01
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 2 THEN DAYS.DAYTXT END), '') AS D02
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 3 THEN DAYS.DAYTXT END), '') AS D03
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 4 THEN DAYS.DAYTXT END), '') AS D04
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 5 THEN DAYS.DAYTXT END), '') AS D05
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 6 THEN DAYS.DAYTXT END), '') AS D06
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 7 THEN DAYS.DAYTXT END), '') AS D07
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 8 THEN DAYS.DAYTXT END), '') AS D08
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 9 THEN DAYS.DAYTXT END), '') AS D09
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 10 THEN DAYS.DAYTXT END), '') AS D10
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 11 THEN DAYS.DAYTXT END), '') AS D11
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 12 THEN DAYS.DAYTXT END), '') AS D12
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 13 THEN DAYS.DAYTXT END), '') AS D13
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 14 THEN DAYS.DAYTXT END), '') AS D14
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 15 THEN DAYS.DAYTXT END), '') AS D15
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 16 THEN DAYS.DAYTXT END), '') AS D16
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 17 THEN DAYS.DAYTXT END), '') AS D17
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 18 THEN DAYS.DAYTXT END), '') AS D18
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 19 THEN DAYS.DAYTXT END), '') AS D19
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 20 THEN DAYS.DAYTXT END), '') AS D20
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 21 THEN DAYS.DAYTXT END), '') AS D21
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 22 THEN DAYS.DAYTXT END), '') AS D22
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 23 THEN DAYS.DAYTXT END), '') AS D23
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 24 THEN DAYS.DAYTXT END), '') AS D24
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 25 THEN DAYS.DAYTXT END), '') AS D25
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 26 THEN DAYS.DAYTXT END), '') AS D26
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 27 THEN DAYS.DAYTXT END), '') AS D27
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 28 THEN DAYS.DAYTXT END), '') AS D28
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 29 THEN DAYS.DAYTXT END), '') AS D29
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 30 THEN DAYS.DAYTXT END), '') AS D30
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 31 THEN DAYS.DAYTXT END), '') AS D31
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 1 THEN DAYS.NGYN END), '') AS N01
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 2 THEN DAYS.NGYN END), '') AS N02
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 3 THEN DAYS.NGYN END), '') AS N03
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 4 THEN DAYS.NGYN END), '') AS N04
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 5 THEN DAYS.NGYN END), '') AS N05
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 6 THEN DAYS.NGYN END), '') AS N06
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 7 THEN DAYS.NGYN END), '') AS N07
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 8 THEN DAYS.NGYN END), '') AS N08
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 9 THEN DAYS.NGYN END), '') AS N09
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 10 THEN DAYS.NGYN END), '') AS N10
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 11 THEN DAYS.NGYN END), '') AS N11
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 12 THEN DAYS.NGYN END), '') AS N12
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 13 THEN DAYS.NGYN END), '') AS N13
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 14 THEN DAYS.NGYN END), '') AS N14
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 15 THEN DAYS.NGYN END), '') AS N15
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 16 THEN DAYS.NGYN END), '') AS N16
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 17 THEN DAYS.NGYN END), '') AS N17
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 18 THEN DAYS.NGYN END), '') AS N18
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 19 THEN DAYS.NGYN END), '') AS N19
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 20 THEN DAYS.NGYN END), '') AS N20
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 21 THEN DAYS.NGYN END), '') AS N21
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 22 THEN DAYS.NGYN END), '') AS N22
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 23 THEN DAYS.NGYN END), '') AS N23
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 24 THEN DAYS.NGYN END), '') AS N24
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 25 THEN DAYS.NGYN END), '') AS N25
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 26 THEN DAYS.NGYN END), '') AS N26
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 27 THEN DAYS.NGYN END), '') AS N27
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 28 THEN DAYS.NGYN END), '') AS N28
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 29 THEN DAYS.NGYN END), '') AS N29
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 30 THEN DAYS.NGYN END), '') AS N30
    , IFNULL(MAX(CASE WHEN DAYS.DAYNO = 31 THEN DAYS.NGYN END), '') AS N31
  FROM TEMP_S01_ITEM AS ITEM
  LEFT JOIN (SELECT
                 TEMP_S01_RST.FANO, TEMP_S01_RST.CHKKNDCD, TEMP_S01_RST.DAYNO
               , GROUP_CONCAT(TEMP_S01_RST.DISP ORDER BY TEMP_S01_RST.CHKTIME SEPARATOR '/') AS DAYTXT
               , MAX(TEMP_S01_RST.NGYN) AS NGYN
             FROM TEMP_S01_RST
             GROUP BY TEMP_S01_RST.FANO, TEMP_S01_RST.CHKKNDCD, TEMP_S01_RST.DAYNO) AS DAYS
    ON DAYS.FANO = ITEM.FANO
   AND DAYS.CHKKNDCD = ITEM.CHKKNDCD
  GROUP BY ITEM.FANO, ITEM.CHKKNDCD, ITEM.SORTNO, ITEM.CHKLOCNM, ITEM.CHKKNDNM, ITEM.CHKSTD, ITEM.CHKCYCLENM
  ORDER BY ITEM.FANO, ITEM.SORTNO, ITEM.CHKKNDCD
  ;

-- ****************************************************************************
WHEN 'PRINT_MONTH_SHEET' THEN  -- 점검표 출력 (리포트 PRD6001_S01, 설비마다 1장)  2026-11-26
                               -- [0] 머리글 (설비마다 1행)  [1] 월간 표 (LIST_MONTH_SHEET 와 같음)  [2] 위치사진 (최신 REV)

  -- [0] 머리글: PRD6001_R02 PRINT_CHKSHEET 와 같은 항목, 설비마다 최신 REV 기준
  SELECT
      MSTEQM.FANO
    , MSTEQM.EQMNM
    , MONTH(_$SDATE) AS MON
    , IFNULL((SELECT GROUP_CONCAT(DISTINCT MSTLINE_EQM.EQMNM ORDER BY MSTLINE_EQM.EQMNM SEPARATOR ', ')
                FROM MSTEQM_MATCH
                INNER JOIN MSTLINE_EQM
                  ON MSTLINE_EQM.EQMCD = MSTEQM_MATCH.EQMCD
                WHERE MSTEQM_MATCH.FANO = MSTEQM.FANO), '') AS LINENM
    , IFNULL((SELECT GROUP_CONCAT(DISTINCT MSTITEM.ITEMNM ORDER BY MSTITEM.ITEMCD SEPARATOR '|')
                FROM MSTEQM_MATCH
                INNER JOIN MSTEQM_STD
                  ON MSTEQM_STD.EQMCD = MSTEQM_MATCH.EQMCD
                 AND MSTEQM_STD.FACTORYCD = '07'
                INNER JOIN MSTITEM
                  ON MSTITEM.ITEMID = MSTEQM_STD.ITEMID
                WHERE MSTEQM_MATCH.FANO = MSTEQM.FANO), '') AS ITEMNM_LIST
    , IFNULL((SELECT LEFT(COALESCE(NULLIF(FIRST_REV.APRVTIME, ''), NULLIF(FIRST_REV.REQTIME, ''), FIRST_REV.RTIME), 10)
                FROM MSTEQMREV_HEADER AS FIRST_REV
                WHERE FIRST_REV.CHKTP = '01' AND FIRST_REV.PLANTP = 'E' AND FIRST_REV.PLANCD = MSTEQM.FANO
                ORDER BY FIRST_REV.REVNUM LIMIT 1), '') AS FIRSTDATE
    , IFNULL((SELECT LEFT(COALESCE(NULLIF(LAST_REV.APRVTIME, ''), NULLIF(LAST_REV.REQTIME, ''), LAST_REV.RTIME), 10)
                FROM MSTEQMREV_HEADER AS LAST_REV
                WHERE LAST_REV.CHKTP = '01' AND LAST_REV.PLANTP = 'E' AND LAST_REV.PLANCD = MSTEQM.FANO
                ORDER BY LAST_REV.REVNUM DESC LIMIT 1), '') AS REVDATE
    , IFNULL((SELECT MAX(LAST_REV.REVNUM)
                FROM MSTEQMREV_HEADER AS LAST_REV
                WHERE LAST_REV.CHKTP = '01' AND LAST_REV.PLANTP = 'E' AND LAST_REV.PLANCD = MSTEQM.FANO), '') AS REVNUM
  FROM MSTEQM
  WHERE MSTEQM.FACTORYCD = '07'
