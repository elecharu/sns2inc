CREATE DEFINER=`root`@`%` PROCEDURE `MES_SNS2`.`PRD6001_S02`(
-- *****************************************************************************
-- Comment: MTBF (설비별 월 부하시간·고장시간·고장건수·고장율·MTBF·MTTR, 2공장)
--          설비     = 2공장(MSTLINE.FACTORYCD 07) 작업장의 사용 설비(MSTLINE_EQM.USEYN Y) 전체 + 종합
--          비가동   = 비가동 이력(PRDRSTNON), 등록시간(RTIME) 월 기준
--          고장     = 비가동 대분류 TO 그룹(MSTNON.NONGROUPCD1 PP409I210N) 전체
--          부하시간 = 월 일수 x 하루 근무시간(PP161 2공장 근무조 합, 1200분) - 제외 비가동(근무시간에 걸친 만큼)
--          제외 비가동 = 소재대기(I2121N)·측정대기(I2122N)·조회/교육(I2111N)·계획정지(I2113N)
--          고장율(%) = 고장시간 / 부하시간 x 100, MTBF = 부하시간 / 고장건수, MTTR = 고장시간 / 고장건수
--          합계 = 시간·건수는 12개월 합, 고장율·MTBF·MTTR 은 연간 합계로 다시 계산
-- Create:  2024-12-30 13:17 : 김영철
-- Modify:  2026-11-05 : 김영철 2공장 테이블 기준으로 변경 (설비 MSTLINE_EQM 2공장, 비가동코드 MSTNON)
--                        비가동 이력을 한 번만 읽어 임시 테이블로 집계하도록 개선 (조회 속도)
--                        월 일수를 조회년도 기준으로 (기존 올해 기준), 고장율·MTBF 분모를 부하시간으로 통일
-- *****************************************************************************
  IN $SYEAR VARCHAR(10),            -- 조회년도
-- *****************************************************************************
  IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- SET @DEBUGLOGYN = 'Y';
-- *****************************************************************************
  DECLARE _$SYEAR    VARCHAR(4);
  DECLARE _$SDATE    VARCHAR(19);
  DECLARE _$EDATE    VARCHAR(19);
  DECLARE _$DAYMIN   INT;
-- ****************************************************************************
CASE $CALLTYPE
-- ****************************************************************************
WHEN 'LIST_EQMDATA' THEN

  SET _$SYEAR = LEFT(IFNULL($SYEAR, ''), 4);
  IF _$SYEAR = '' THEN
    CALL COMERR('조회년도를 선택하세요.');
    LEAVE PROC;
  END IF;

  SET _$SDATE = CONCAT(_$SYEAR, '-01-01 00:00:00');
  SET _$EDATE = CONCAT(CAST(_$SYEAR AS UNSIGNED) + 1, '-01-01 00:00:00');

  -- 하루 근무시간(분) = 2공장 근무조(PP161, REF05 07) 시간 합 (야간은 자정을 넘김)
  SELECT
      IFNULL(SUM(MOD(TIME_TO_SEC(COMTYPE.REF02) - TIME_TO_SEC(COMTYPE.REF01) + 86400, 86400)) / 60, 0)
  INTO _$DAYMIN
  FROM COMTYPE
  WHERE COMTYPE.GPCD = 'PP161'
    AND COMTYPE.USEYN = 'Y'
    AND COMTYPE.REF05 = '07';

  -- 1. 대상 설비: 2공장 작업장의 사용 설비
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD6001_EQM;
  CREATE TEMPORARY TABLE TMP_PRD6001_EQM (
    EQMCD     VARCHAR(20)   NOT NULL,
    EQMNM     VARCHAR(200)  NOT NULL,
    LINECD    VARCHAR(100)  NOT NULL,
    SORTNO    INT           NOT NULL DEFAULT 0,
    PRIMARY KEY (EQMCD)
  );

  INSERT INTO TMP_PRD6001_EQM (EQMCD, EQMNM, LINECD, SORTNO)
  SELECT
      MSTLINE_EQM.EQMCD
    , IFNULL(MSTLINE_EQM.EQMNM, MSTLINE_EQM.EQMCD)
    , MSTLINE_EQM.LINECD
    , IFNULL(MSTLINE_EQM.SORTNO, 0)
  FROM MSTLINE_EQM
  INNER JOIN MSTLINE
    ON MSTLINE.LINECD = MSTLINE_EQM.LINECD
  WHERE MSTLINE.FACTORYCD = '07'
    AND MSTLINE_EQM.USEYN = 'Y';

  -- 2. 비가동코드 구분: F = 고장(TO 그룹), X = 부하시간 제외 (대기·교육·계획정지)
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD6001_NONCD;
  CREATE TEMPORARY TABLE TMP_PRD6001_NONCD (
    NONCD     VARCHAR(20)   NOT NULL,
    KIND      VARCHAR(1)    NOT NULL,
    PRIMARY KEY (NONCD)
  );

  INSERT IGNORE INTO TMP_PRD6001_NONCD (NONCD, KIND)
  SELECT DISTINCT
      MSTNON.NONCD
    , 'F'
  FROM MSTNON
  WHERE MSTNON.FACTORYCD = '07'
    AND MSTNON.NONGROUPCD1 = 'PP409I210N';

  INSERT IGNORE INTO TMP_PRD6001_NONCD (NONCD, KIND)
  VALUES
    ('I2121N', 'X'),  -- 소재대기
    ('I2122N', 'X'),  -- 측정대기
    ('I2111N', 'X'),  -- 조회/교육
    ('I2113N', 'X');  -- 계획정지

  -- 3. 근무조 시간대 (전년도 12/31 야간 ~ 조회년도 12/31 야간): 제외 비가동을 근무시간에 걸친 만큼만 빼기 위함
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD6001_SHIFT;
  CREATE TEMPORARY TABLE TMP_PRD6001_SHIFT (
    STIME     VARCHAR(19)   NOT NULL,
    ETIME     VARCHAR(19)   NOT NULL,
    INDEX (STIME)
  );

  INSERT INTO TMP_PRD6001_SHIFT (STIME, ETIME)
  SELECT
      CONCAT(WORKDAY.WORKDATE, ' ', COMTYPE.REF01, ':00')
    , CONCAT(IF(COMTYPE.REF02 <= COMTYPE.REF01, DATE_FORMAT(DATE_ADD(WORKDAY.WORKDATE, INTERVAL 1 DAY), '%Y-%m-%d'), WORKDAY.WORKDATE), ' ', COMTYPE.REF02, ':00')
  FROM (
    SELECT
        DATE_FORMAT(DATE_ADD(CONCAT(CAST(_$SYEAR AS UNSIGNED) - 1, '-12-31'), INTERVAL NUM1.N + NUM2.N * 10 + NUM3.N * 100 DAY), '%Y-%m-%d') AS WORKDATE
    FROM (SELECT 0 AS N UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
          UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) AS NUM1
    CROSS JOIN (SELECT 0 AS N UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
          UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) AS NUM2
    CROSS JOIN (SELECT 0 AS N UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3) AS NUM3
  ) AS WORKDAY
  INNER JOIN COMTYPE
    ON COMTYPE.GPCD = 'PP161'
    AND COMTYPE.USEYN = 'Y'
    AND COMTYPE.REF05 = '07'
  WHERE WORKDAY.WORKDATE <= CONCAT(_$SYEAR, '-12-31');

  -- 4. 조회년도 비가동 (고장·제외 코드만, 비가동 이력은 여기서 한 번만 읽음)
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD6001_NON;
  CREATE TEMPORARY TABLE TMP_PRD6001_NON (
    PRDNONKEY VARCHAR(20)   NOT NULL,
    EQMCD     VARCHAR(20)   NOT NULL,
    MON       VARCHAR(2)    NOT NULL,
    KIND      VARCHAR(1)    NOT NULL,
    NONSTIME  VARCHAR(19)   NOT NULL,
    NONETIME  VARCHAR(19)   NOT NULL,
    PRIMARY KEY (PRDNONKEY)
  );

  INSERT INTO TMP_PRD6001_NON (PRDNONKEY, EQMCD, MON, KIND, NONSTIME, NONETIME)
  SELECT
      PRDRSTNON.PRDNONKEY
    , PRDRSTNON.EQMCD
    , SUBSTRING(PRDRSTNON.RTIME, 6, 2)
    , TMP_PRD6001_NONCD.KIND
    , PRDRSTNON.NONSTIME
    , IF(PRDRSTNON.NONETIME = '', PRDRSTNON.NONSTIME, PRDRSTNON.NONETIME)  -- 종료 전은 0분
  FROM PRDRSTNON
  INNER JOIN TMP_PRD6001_NONCD
    ON TMP_PRD6001_NONCD.NONCD = PRDRSTNON.NONCD
  INNER JOIN TMP_PRD6001_EQM
    ON TMP_PRD6001_EQM.EQMCD = PRDRSTNON.EQMCD
  WHERE PRDRSTNON.RTIME >= _$SDATE
    AND PRDRSTNON.RTIME < _$EDATE
    AND PRDRSTNON.NONSTIME <> '';

  -- 5. 설비·월별 기본값 (부하시간, 고장시간, 고장건수) + 종합
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD6001_SUM;
  CREATE TEMPORARY TABLE TMP_PRD6001_SUM (
    EQMCD     VARCHAR(20)   NOT NULL,
    MON       VARCHAR(2)    NOT NULL,
    FAILMIN   DECIMAL(20,2) NOT NULL DEFAULT 0,  -- 고장시간(분)
    FAILCNT   INT           NOT NULL DEFAULT 0,  -- 고장건수
    EXCMIN    DECIMAL(20,2) NOT NULL DEFAULT 0,  -- 제외 비가동(분)
    PRIMARY KEY (EQMCD, MON)
  );

  INSERT INTO TMP_PRD6001_SUM (EQMCD, MON, FAILMIN, FAILCNT)
  SELECT
      TMP_PRD6001_NON.EQMCD
    , TMP_PRD6001_NON.MON
    , SUM(TIMESTAMPDIFF(MINUTE, TMP_PRD6001_NON.NONSTIME, TMP_PRD6001_NON.NONETIME))
    , COUNT(*)
  FROM TMP_PRD6001_NON
  WHERE TMP_PRD6001_NON.KIND = 'F'
  GROUP BY TMP_PRD6001_NON.EQMCD, TMP_PRD6001_NON.MON;

  -- 제외 비가동은 근무시간(02:00~06:00 제외)과 겹친 만큼만
  INSERT INTO TMP_PRD6001_SUM (EQMCD, MON, EXCMIN)
  SELECT
      EXC.EQMCD
    , EXC.MON
    , EXC.EXCMIN
  FROM (
    SELECT
        TMP_PRD6001_NON.EQMCD
      , TMP_PRD6001_NON.MON
      , SUM(TIMESTAMPDIFF(MINUTE, GREATEST(TMP_PRD6001_NON.NONSTIME, TMP_PRD6001_SHIFT.STIME), LEAST(TMP_PRD6001_NON.NONETIME, TMP_PRD6001_SHIFT.ETIME))) AS EXCMIN
    FROM TMP_PRD6001_NON
    INNER JOIN TMP_PRD6001_SHIFT
      ON TMP_PRD6001_SHIFT.STIME < TMP_PRD6001_NON.NONETIME
      AND TMP_PRD6001_SHIFT.ETIME > TMP_PRD6001_NON.NONSTIME
    WHERE TMP_PRD6001_NON.KIND = 'X'
    GROUP BY TMP_PRD6001_NON.EQMCD, TMP_PRD6001_NON.MON
  ) AS EXC
  ON DUPLICATE KEY UPDATE TMP_PRD6001_SUM.EXCMIN = EXC.EXCMIN;

  -- 6. 설비 x 월 (비가동 없는 달도) 부하시간 계산, 종합 = 전체 설비 합
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD6001_BASE;
  CREATE TEMPORARY TABLE TMP_PRD6001_BASE (
    SORTKEY   INT           NOT NULL,              -- 0 = 설비, 1 = 종합
    LINECD    VARCHAR(100)  NOT NULL,
    SORTNO    INT           NOT NULL,
    EQMCD     VARCHAR(20)   NOT NULL,
    EQMNM     VARCHAR(200)  NOT NULL,
    MON       VARCHAR(2)    NOT NULL,
    LOADMIN   DECIMAL(20,2) NOT NULL DEFAULT 0,    -- 부하시간(분)
    FAILMIN   DECIMAL(20,2) NOT NULL DEFAULT 0,
    FAILCNT   INT           NOT NULL DEFAULT 0,
    PRIMARY KEY (EQMCD, MON)
  );

  INSERT INTO TMP_PRD6001_BASE (SORTKEY, LINECD, SORTNO, EQMCD, EQMNM, MON, LOADMIN, FAILMIN, FAILCNT)
  SELECT
      0
    , TMP_PRD6001_EQM.LINECD
    , TMP_PRD6001_EQM.SORTNO
    , TMP_PRD6001_EQM.EQMCD
    , TMP_PRD6001_EQM.EQMNM
    , MONTHS.MON
    , DAY(LAST_DAY(CONCAT(_$SYEAR, '-', MONTHS.MON, '-01'))) * _$DAYMIN - IFNULL(TMP_PRD6001_SUM.EXCMIN, 0)
    , IFNULL(TMP_PRD6001_SUM.FAILMIN, 0)
    , IFNULL(TMP_PRD6001_SUM.FAILCNT, 0)
  FROM TMP_PRD6001_EQM
  CROSS JOIN (
    SELECT '01' AS MON UNION ALL SELECT '02' UNION ALL SELECT '03' UNION ALL SELECT '04'
    UNION ALL SELECT '05' UNION ALL SELECT '06' UNION ALL SELECT '07' UNION ALL SELECT '08'
    UNION ALL SELECT '09' UNION ALL SELECT '10' UNION ALL SELECT '11' UNION ALL SELECT '12'
  ) AS MONTHS
  LEFT JOIN TMP_PRD6001_SUM
    ON TMP_PRD6001_SUM.EQMCD = TMP_PRD6001_EQM.EQMCD
    AND TMP_PRD6001_SUM.MON = MONTHS.MON;

  -- 종합은 같은 임시 테이블을 한 문장에서 두 번 열 수 없어 설비 행 합계를 따로 만들어 넣음
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD6001_TOT;
  CREATE TEMPORARY TABLE TMP_PRD6001_TOT
  SELECT
      TMP_PRD6001_BASE.MON
    , SUM(TMP_PRD6001_BASE.LOADMIN) AS LOADMIN
    , SUM(TMP_PRD6001_BASE.FAILMIN) AS FAILMIN
    , SUM(TMP_PRD6001_BASE.FAILCNT) AS FAILCNT
  FROM TMP_PRD6001_BASE
  GROUP BY TMP_PRD6001_BASE.MON;

  INSERT INTO TMP_PRD6001_BASE (SORTKEY, LINECD, SORTNO, EQMCD, EQMNM, MON, LOADMIN, FAILMIN, FAILCNT)
  SELECT
      1, '', 0, '', '종합'
    , TMP_PRD6001_TOT.MON
    , TMP_PRD6001_TOT.LOADMIN
    , TMP_PRD6001_TOT.FAILMIN
    , TMP_PRD6001_TOT.FAILCNT
  FROM TMP_PRD6001_TOT;

  -- 7. 항목(부하시간·고장시간·고장건수·고장율·MTBF·MTTR) x 월 피벗
  SELECT
      PIVOT.SEQ
    , PIVOT.EQMNM AS EQM
    , PIVOT.ITEM
    , IFNULL(MAX(IF(PIVOT.MON = '01', PIVOT.VAL, NULL)), 0) AS M1
    , IFNULL(MAX(IF(PIVOT.MON = '02', PIVOT.VAL, NULL)), 0) AS M2
    , IFNULL(MAX(IF(PIVOT.MON = '03', PIVOT.VAL, NULL)), 0) AS M3
    , IFNULL(MAX(IF(PIVOT.MON = '04', PIVOT.VAL, NULL)), 0) AS M4
    , IFNULL(MAX(IF(PIVOT.MON = '05', PIVOT.VAL, NULL)), 0) AS M5
    , IFNULL(MAX(IF(PIVOT.MON = '06', PIVOT.VAL, NULL)), 0) AS M6
    , IFNULL(MAX(IF(PIVOT.MON = '07', PIVOT.VAL, NULL)), 0) AS M7
    , IFNULL(MAX(IF(PIVOT.MON = '08', PIVOT.VAL, NULL)), 0) AS M8
    , IFNULL(MAX(IF(PIVOT.MON = '09', PIVOT.VAL, NULL)), 0) AS M9
    , IFNULL(MAX(IF(PIVOT.MON = '10', PIVOT.VAL, NULL)), 0) AS M10
    , IFNULL(MAX(IF(PIVOT.MON = '11', PIVOT.VAL, NULL)), 0) AS M11
    , IFNULL(MAX(IF(PIVOT.MON = '12', PIVOT.VAL, NULL)), 0) AS M12
    , IFNULL(CASE PIVOT.SEQ
        WHEN '0' THEN SUM(PIVOT.LOADMIN)
        WHEN '1' THEN SUM(PIVOT.FAILMIN)
        WHEN '2' THEN SUM(PIVOT.FAILCNT)
        WHEN '3' THEN ROUND(SUM(PIVOT.FAILMIN) / NULLIF(SUM(PIVOT.LOADMIN), 0) * 100, 1)
        WHEN '4' THEN ROUND(SUM(PIVOT.LOADMIN) / NULLIF(SUM(PIVOT.FAILCNT), 0), 0)
        WHEN '5' THEN ROUND(SUM(PIVOT.FAILMIN) / NULLIF(SUM(PIVOT.FAILCNT), 0), 0)
      END, 0) AS MSUM
  FROM (
    SELECT
        TMP_PRD6001_BASE.SORTKEY
      , TMP_PRD6001_BASE.LINECD
      , TMP_PRD6001_BASE.SORTNO
      , TMP_PRD6001_BASE.EQMCD
      , TMP_PRD6001_BASE.EQMNM
      , TMP_PRD6001_BASE.MON
      , TMP_PRD6001_BASE.LOADMIN
      , TMP_PRD6001_BASE.FAILMIN
      , TMP_PRD6001_BASE.FAILCNT
      , ITEMS.SEQ
      , ITEMS.ITEM
      , CASE ITEMS.SEQ
          WHEN '0' THEN TMP_PRD6001_BASE.LOADMIN
          WHEN '1' THEN TMP_PRD6001_BASE.FAILMIN
          WHEN '2' THEN TMP_PRD6001_BASE.FAILCNT
          WHEN '3' THEN ROUND(TMP_PRD6001_BASE.FAILMIN / NULLIF(TMP_PRD6001_BASE.LOADMIN, 0) * 100, 1)
          WHEN '4' THEN ROUND(TMP_PRD6001_BASE.LOADMIN / NULLIF(TMP_PRD6001_BASE.FAILCNT, 0), 0)
          WHEN '5' THEN ROUND(TMP_PRD6001_BASE.FAILMIN / NULLIF(TMP_PRD6001_BASE.FAILCNT, 0), 0)
        END AS VAL
    FROM TMP_PRD6001_BASE
    CROSS JOIN (
      SELECT '0' AS SEQ, '부하시간(분)' AS ITEM
      UNION ALL SELECT '1', '고장시간(분)'
      UNION ALL SELECT '2', '고장건수'
      UNION ALL SELECT '3', '고장율(%)'
      UNION ALL SELECT '4', 'MTBF(분)'
      UNION ALL SELECT '5', 'MTTR(분)'
    ) AS ITEMS
  ) AS PIVOT
  GROUP BY PIVOT.SORTKEY, PIVOT.LINECD, PIVOT.SORTNO, PIVOT.EQMCD, PIVOT.EQMNM, PIVOT.SEQ, PIVOT.ITEM
  ORDER BY PIVOT.SORTKEY, PIVOT.LINECD, PIVOT.SORTNO, PIVOT.EQMCD, PIVOT.SEQ;

  DROP TEMPORARY TABLE IF EXISTS TMP_PRD6001_EQM;
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD6001_NONCD;
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD6001_SHIFT;
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD6001_NON;
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD6001_SUM;
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD6001_BASE;
  DROP TEMPORARY TABLE IF EXISTS TMP_PRD6001_TOT;

-- ****************************************************************************
END CASE; END