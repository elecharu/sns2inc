CREATE DEFINER=`root`@`%` PROCEDURE `MES_SNS2`.`PRD6001_S03`(
-- *****************************************************************************
-- Comment: 공무작업일보 (2공장)
--          설비수리 = EQMREP (EQMCD = MSTEQM.FANO), 수리일자 = 완료시간(REPETIME)이 해당일 06:00 ~ 다음날 05:59
--          고장유형 자리 = 수리유형(EQMREP.ISSUE, 공통코드 ISSUE), 고장내용 = 고장원인(MALFUNCTION), 수리내용 = 처리내용(HANDLE)
--          개선업무(GUBUN 1)·요청사항(GUBUN 2) = EQMREPDAILY
-- Create: 2024-04-30 11:30: 김영철
-- Modify: 2026-11-05 : 김영철 2공장 테이블 기준으로 변경
--                       설비수리 EQMREP 2공장 컬럼으로 (비가동 PRDRSTNON 연결 없음), 고장유형(FM307) → 수리유형(ISSUE)
--                       근무일 함수(MAKEINS_IFDT) 대신 완료시간 06:00 기준 범위 조건, MSTEMP.WORKDUTY 없음 → ''
--         2026-11-06 : 김영철 SEL_EQMREP 에 작업장(LINENM)·설비구분(EQMTPNM)·설비대분류(EQMGROUP1NM) 추가
--         2026-11-18 : 한성수 SEL_EQMREPDAILY 개선업무에 설비명(EQMNM) 추가
-- *****************************************************************************
  IN $DATE VARCHAR(19),               -- 수리일자 / 입력일자
  IN $TITLE VARCHAR(255),             -- 타이틀 (개선업무 = 설비번호)
  IN $GUBUN VARCHAR(1),               -- 구분 (1 개선업무, 2 요청사항)
  IN $REMARK VARCHAR(255),            -- 개선사항 / 요구사항
  IN $REPTP VARCHAR(20),              -- 수리유형 (ISSUE, '' = 전체)
  IN $DAILYINFOTP VARCHAR(20),        -- 업무정보
  IN $DAILYSTATUSTP VARCHAR(20),      -- 진행상태

  IN $EMPCD VARCHAR(20),              -- 작업자
  IN $WORKTIME VARCHAR(20),           -- 작업시간(분)

  IN $EQMREPNOLIST MEDIUMTEXT,        -- 설비수리키 목록
  IN $REPREMARKLIST MEDIUMTEXT,       -- 고장원인 목록
  IN $HANDLEREMARKLIST MEDIUMTEXT,    -- 처리내용 목록
  IN $DAILYINFOTPLIST MEDIUMTEXT,
  IN $DAILYSTATUSTPLIST MEDIUMTEXT,

  IN $DATETIMELIST MEDIUMTEXT,
  IN $GUBUNLIST MEDIUMTEXT,
  IN $SEQLIST MEDIUMTEXT,
  IN $TITLELIST MEDIUMTEXT,
  IN $REMARKLIST MEDIUMTEXT,
  IN $WORKTIMELIST MEDIUMTEXT,

-- *****************************************************************************
  IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- SET @DEBUGLOGYN = 'Y';
-- *****************************************************************************

  DECLARE _$EQMREPNO VARCHAR(100);
  DECLARE _$REPREMARK VARCHAR(255);
  DECLARE _$HANDLEREMARK VARCHAR(255);

  DECLARE _$SEQ INT;
  DECLARE _$DATETIME VARCHAR(19);
  DECLARE _$GUBUN VARCHAR(1);
  DECLARE _$TITLE VARCHAR(255);
  DECLARE _$REMARK VARCHAR(255);

  DECLARE _$DAILYINFOTP VARCHAR(20);
  DECLARE _$DAILYSTATUSTP VARCHAR(20);
  DECLARE _$WORKTIME VARCHAR(20);

  DECLARE _$STIME VARCHAR(19);
  DECLARE _$ETIME VARCHAR(19);

CASE $CALLTYPE
-- ****************************************************************************
WHEN 'SEL_EQMREP' THEN  -- 설비수리 (수리일자 06:00 ~ 다음날 05:59 에 완료된 건)

  SET _$STIME = CONCAT(LEFT($DATE, 10), ' 06:00');
  SET _$ETIME = CONCAT(DATE_FORMAT(DATE_ADD(LEFT($DATE, 10), INTERVAL 1 DAY), '%Y-%m-%d'), ' 06:00');

  SELECT
      IFNULL(MSTLINE.LINENM, MSTEQM.LINECD) AS LINENM    -- 작업장
    , GPCD('FM100', MSTEQM.EQMTP) AS EQMTPNM              -- 설비구분
    , GPCD('FM113', MSTEQM.EQMGROUP1) AS EQMGROUP1NM      -- 설비대분류
    , MSTEQM.EQMGROUP2
    , EQMREP.EQMCD AS FANO
    , EQMREP.REPSTIME AS NONSTIME
    , EQMREP.REPETIME AS NONETIME
    , IFNULL(MSTEQM.EQMNM, EQMREP.EQMCD) AS EQMNM
    , CONCAT(TIMESTAMPDIFF(MINUTE, EQMREP.REPSTIME, EQMREP.REPETIME), '분') AS REPSTOPTIME  -- 정지시간(분)
    , EQMREP.MALFUNCTION AS REPREMARK   -- 고장원인
    , EQMREP.HANDLE AS HANDLEREMARK     -- 처리내용
    , EQMREP.EQMREPKEY AS EQMREPNO
    , EQMREP.ISSUE AS REPTP             -- 수리유형
  FROM EQMREP
  LEFT JOIN MSTEQM
    ON MSTEQM.FANO = EQMREP.EQMCD
  LEFT JOIN MSTLINE
    ON MSTLINE.LINECD = MSTEQM.LINECD
  WHERE EQMREP.REPETIME >= _$STIME
    AND EQMREP.REPETIME < _$ETIME
    AND (IFNULL($REPTP, '') = '' OR EQMREP.ISSUE = $REPTP)
  ORDER BY TIMESTAMPDIFF(MINUTE, EQMREP.REPSTIME, EQMREP.REPETIME) DESC;

-- ****************************************************************************
WHEN 'SEL_EQMREPDAILY' THEN  -- [0] 그날 개선업무, [1] 진행 중인 요청사항 (요청중·발주중)

  SELECT
      EQMREPDAILY.DATETIME
    , EQMREPDAILY.SEQ
    , EQMREPDAILY.GUBUN
    , EQMREPDAILY.DAILYINFO AS DAILYINFOTP
    , EQMREPDAILY.WORKTIME
    , EQMREPDAILY.EMPCD
    , EQMREPDAILY.TITLE
    , IFNULL(MSTEQM.EQMNM, '') AS EQMNM  -- 설비명
    , EQMREPDAILY.REMARK
    , MSTEMP.DEPTCD
    , '' AS WORKDUTY  -- 2공장 MSTEMP 에 근무직구분 없음 (화면에서 숨김 컬럼)
  FROM EQMREPDAILY
  LEFT JOIN MSTEMP
    ON MSTEMP.EMPCD = EQMREPDAILY.EMPCD
  LEFT JOIN MSTEQM
    ON MSTEQM.FANO = EQMREPDAILY.TITLE
  WHERE EQMREPDAILY.DATETIME = $DATE
    AND EQMREPDAILY.GUBUN = '1';

  SELECT
      EQMREPDAILY.DATETIME
    , EQMREPDAILY.SEQ
    , EQMREPDAILY.GUBUN
    , EQMREPDAILY.DAILYSTATUS AS DAILYSTATUSTP
    , EQMREPDAILY.TITLE
    , EQMREPDAILY.REMARK
  FROM EQMREPDAILY
  WHERE EQMREPDAILY.DAILYSTATUS IN ('01', '02')
    AND EQMREPDAILY.GUBUN = '2';

-- ****************************************************************************
WHEN 'INS_EQMREPDAILY' THEN  -- 개선업무·요청사항 추가 (순번 = 같은 입력일자·구분의 마지막 + 1)

  SELECT
      IFNULL(MAX(EQMREPDAILY.SEQ), 0) + 1
  INTO _$SEQ
  FROM EQMREPDAILY
  WHERE EQMREPDAILY.DATETIME = $DATE
    AND EQMREPDAILY.GUBUN = $GUBUN;

  INSERT INTO EQMREPDAILY (
      DATETIME, GUBUN, SEQ, TITLE, WORKTIME, EMPCD, REMARK, DAILYINFO, DAILYSTATUS
    , RTIME, REMP, RPRG)
  VALUES (
      $DATE, $GUBUN, _$SEQ, IFNULL($TITLE, ''), IFNULL($WORKTIME, ''), IFNULL($EMPCD, ''), IFNULL($REMARK, '')
    , IFNULL($DAILYINFOTP, ''), IFNULL($DAILYSTATUSTP, '')
    , GETTIME(), CALLEMP(), CALLPRG());

-- ****************************************************************************
WHEN 'UP_EQMREP' THEN  -- 설비수리 고장원인·처리내용, 개선업무·요청사항 저장

  WHILE LENGTH($EQMREPNOLIST) > 0 DO
    CALL COMSPLIT($EQMREPNOLIST, _$EQMREPNO);
    CALL COMSPLIT($REPREMARKLIST, _$REPREMARK);
    CALL COMSPLIT($HANDLEREMARKLIST, _$HANDLEREMARK);

    UPDATE EQMREP
    SET EQMREP.MALFUNCTION = LEFT(_$REPREMARK, 100)
      , EQMREP.HANDLE = LEFT(_$HANDLEREMARK, 100)
      , EQMREP.MTIME = GETTIME()
      , EQMREP.MEMP = CALLEMP()
      , EQMREP.MPRG = CALLPRG()
    WHERE EQMREP.EQMREPKEY = _$EQMREPNO;
  END WHILE;

  WHILE LENGTH($SEQLIST) > 0 DO
    CALL COMSPLIT($DATETIMELIST, _$DATETIME);
    CALL COMSPLIT($GUBUNLIST, _$GUBUN);
    CALL COMSPLIT($SEQLIST, _$SEQ);
    CALL COMSPLIT($TITLELIST, _$TITLE);
    CALL COMSPLIT($WORKTIMELIST, _$WORKTIME);
    CALL COMSPLIT($REMARKLIST, _$REMARK);
    CALL COMSPLIT($DAILYINFOTPLIST, _$DAILYINFOTP);
    CALL COMSPLIT($DAILYSTATUSTPLIST, _$DAILYSTATUSTP);

    UPDATE EQMREPDAILY
    SET EQMREPDAILY.TITLE = IFNULL(_$TITLE, '')
      , EQMREPDAILY.WORKTIME = IFNULL(_$WORKTIME, '')
      , EQMREPDAILY.REMARK = IFNULL(_$REMARK, '')
      , EQMREPDAILY.DAILYINFO = IFNULL(_$DAILYINFOTP, '')
      , EQMREPDAILY.DAILYSTATUS = IFNULL(_$DAILYSTATUSTP, '')
      , EQMREPDAILY.MTIME = GETTIME()
      , EQMREPDAILY.MEMP = CALLEMP()
      , EQMREPDAILY.MPRG = CALLPRG()
    WHERE EQMREPDAILY.GUBUN = _$GUBUN
      AND EQMREPDAILY.SEQ = _$SEQ
      AND EQMREPDAILY.DATETIME = _$DATETIME;
  END WHILE;

-- ****************************************************************************
WHEN 'DEL_EQMREP' THEN  -- 개선업무·요청사항 삭제 (설비수리는 삭제하지 않음)

  WHILE LENGTH($GUBUNLIST) > 0 DO
    CALL COMSPLIT($DATETIMELIST, _$DATETIME);
    CALL COMSPLIT($GUBUNLIST, _$GUBUN);
    CALL COMSPLIT($SEQLIST, _$SEQ);

    DELETE FROM EQMREPDAILY
    WHERE EQMREPDAILY.GUBUN = _$GUBUN
      AND EQMREPDAILY.SEQ = _$SEQ
      AND EQMREPDAILY.DATETIME = _$DATETIME;
  END WHILE;

-- ****************************************************************************
WHEN 'PRINT_EQMREP' THEN  -- 공무작업일보 출력

  SET _$STIME = CONCAT(LEFT($DATE, 10), ' 06:00');
  SET _$ETIME = CONCAT(DATE_FORMAT(DATE_ADD(LEFT($DATE, 10), INTERVAL 1 DAY), '%Y-%m-%d'), ' 06:00');

  -- [0] 설비수리 (정지시간 긴 순 10건)
  SELECT
      IFNULL(MSTEQM.EQMNM, EQMREP.EQMCD) AS FANO
    , DATE_FORMAT(EQMREP.REPSTIME, '%m-%d %H:%i') AS NONSTIME
    , CONCAT(TIMESTAMPDIFF(MINUTE, EQMREP.REPSTIME, EQMREP.REPETIME), '분') AS REPSTOPTIME
    , EQMREP.MALFUNCTION AS REPREMARK
    , EQMREP.HANDLE AS HANDLEREMARK
    , IFNULL(COMTYPE.TPNM, EQMREP.ISSUE) AS REPTP
  FROM EQMREP
  LEFT JOIN MSTEQM
    ON MSTEQM.FANO = EQMREP.EQMCD
  LEFT JOIN COMTYPE
    ON COMTYPE.GPCD = 'ISSUE'
    AND COMTYPE.TPCD = EQMREP.ISSUE
  WHERE EQMREP.REPETIME >= _$STIME
    AND EQMREP.REPETIME < _$ETIME
    AND (IFNULL($REPTP, '') = '' OR EQMREP.ISSUE = $REPTP)
  ORDER BY TIMESTAMPDIFF(MINUTE, EQMREP.REPSTIME, EQMREP.REPETIME) DESC
  LIMIT 10;

  -- [1] 개선업무
  SELECT
      GPCD('DAILYINFOTP', EQMREPDAILY.DAILYINFO) AS DAILYINFOTP
    , CONCAT(EQMREPDAILY.WORKTIME, '분') AS WORKTIME
    , GPCD('EMPCD', EQMREPDAILY.EMPCD) AS EMPCD
    , IFNULL(MSTEQM.EQMNM, EQMREPDAILY.TITLE) AS TITLE
    , EQMREPDAILY.REMARK
  FROM EQMREPDAILY
  LEFT JOIN MSTEQM
    ON MSTEQM.FANO = EQMREPDAILY.TITLE
  WHERE EQMREPDAILY.DATETIME = $DATE
    AND EQMREPDAILY.GUBUN = '1'
  LIMIT 10;

  -- [2] 요청사항 (요청중·발주중)
  SELECT
      EQMREPDAILY.DATETIME
    , GPCD('DAILYSTATUSTP', EQMREPDAILY.DAILYSTATUS) AS DAILYSTATUSTP
    , EQMREPDAILY.TITLE
    , EQMREPDAILY.REMARK
  FROM EQMREPDAILY
  WHERE EQMREPDAILY.DAILYSTATUS IN ('01', '02')
    AND EQMREPDAILY.GUBUN = '2'
  LIMIT 5;

  -- [3] 출력일자 (yyyy년 mm월 dd일 요일)
  SELECT
      CONCAT(
          DATE_FORMAT($DATE, '%Y년 %m월 %d일 ')
        , CASE DAYOFWEEK($DATE)
            WHEN 1 THEN '일요일'
            WHEN 2 THEN '월요일'
            WHEN 3 THEN '화요일'
            WHEN 4 THEN '수요일'
            WHEN 5 THEN '목요일'
            WHEN 6 THEN '금요일'
            WHEN 7 THEN '토요일'
          END) AS HANDLEDATE;

-- ****************************************************************************
END CASE; END