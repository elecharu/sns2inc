CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.PRDMONITOR(
-- *****************************************************************************
-- Comment: 생산 모니터링 (로그인 화면 [생산 모니터링] → 새 창 PAGECOM/MONITOR/PrdMonitor.aspx)
--          ) 기준 작업일 = 지금 시각이 주간 근무 시작(PP161 PP161100N REF01, 2공장 REF05 07) 전이면 어제
--          ) LIST : 결과셋 0 기준정보(작업일·현재시각·연월·목표 PPM)
--                   결과셋 1 당월 판매계획 대비 실적 (지역구분 SD300 별 금액, 원 단위. 화면에서 백만원 환산)
--                            계획 = 수주일자가 당월인 2공장 사업장(71) 수주 금액, 실적 = 그 수주에 연결된 출하 금액 (SAL3002_S02 와 같은 방식)
--                            유상사급 수주(매출구분 SD310 이름에 '유상사급') 제외, 2공장 품목(공장 07)만
--                   결과셋 2 올해 월별 불량 PPM (사내공정 실적, 2공장 라인 설비, 작업일자 월 기준)
--                   결과셋 3 라인(설비)별 금일 목표·생산수량·달성율·시간가동율
--                            목표 = 주간생산계획(PRDPLAN_W) 주간+야간, 생산 = 양품(GOODQTY)
--                            시간가동율 = (경과 근무시간 - 비가동 등록시간) / 경과 근무시간 (계획·실적 없는 설비는 0)
--                            가동상태 = PLC 연계 전이라 빈칸
--          ) SAVE_PPM : 목표 PPM 저장 (TQMTARGETPPM, 연도별)
-- Create: 2026-11-27 신정수
-- Modify: 2026-11-27 신정수 라인은 MSTLINE_EQM.MONITORYN = 'Y' 만 (MST1002_R05 에서 설정), 정렬은 LINECD → 라인명
-- *****************************************************************************
  IN $TARGETYEAR VARCHAR(4),          -- 목표년도 (SAVE_PPM)
  IN $TARGETPPM VARCHAR(30),          -- 목표 PPM (SAVE_PPM)
-- *****************************************************************************
  IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  DECLARE _$NOW VARCHAR(19);
  DECLARE _$DAYSTART VARCHAR(5);
  DECLARE _$WORKDATE VARCHAR(10);
  DECLARE _$MONTH VARCHAR(7);
  DECLARE _$YEAR VARCHAR(4);
  DECLARE _$WORKMIN DECIMAL(20, 2);
-- *****************************************************************************
  SET _$NOW = CALLTIME();
-- *****************************************************************************
CASE $CALLTYPE
-- ****************************************************************************
WHEN 'LIST' THEN

  -- 기준 작업일 (주간 근무 시작 전이면 전날 야간 근무 중)
  SET _$DAYSTART = IFNULL((SELECT
                               COMTYPE.REF01
                             FROM COMTYPE
                             WHERE COMTYPE.GPCD = 'PP161'
                               AND COMTYPE.TPCD = 'PP161100N'
                               AND COMTYPE.USEYN = 'Y'
                               AND COMTYPE.REF05 = '07'
                             LIMIT 1), '00:00');

  SET _$WORKDATE = IF(SUBSTRING(_$NOW, 12, 5) < _$DAYSTART
                    , DATE_FORMAT(DATE_ADD(LEFT(_$NOW, 10), INTERVAL -1 DAY), '%Y-%m-%d')
                    , LEFT(_$NOW, 10));
  SET _$MONTH = LEFT(_$WORKDATE, 7);
  SET _$YEAR = LEFT(_$WORKDATE, 4);

  -- 0. 기준정보
  SELECT
      _$WORKDATE AS WORKDATE
    , _$NOW AS NOWTIME
    , _$YEAR AS YEAR
    , CAST(SUBSTRING(_$MONTH, 6, 2) AS UNSIGNED) AS MONTH
    , IFNULL((SELECT TQMTARGETPPM.TARGETPPM FROM TQMTARGETPPM WHERE TQMTARGETPPM.TARGETYEAR = _$YEAR), 0) AS TARGETPPM;

  -- 1. 당월 판매계획(수주) 대비 출하실적 금액 (지역구분별)
  DROP TEMPORARY TABLE IF EXISTS TEMP_SALOUT;
  CREATE TEMPORARY TABLE TEMP_SALOUT AS
    SELECT
        SALOUT.SALODRKEY
      , SALOUT.ODRSEQ
      , SUM(SALOUT.OUTQTY) AS OUTQTY
    FROM SALOUT
    INNER JOIN SALODR
      ON SALODR.SALODRKEY = SALOUT.SALODRKEY
    WHERE LEFT(SALODR.ODRDATE, 7) = _$MONTH
      AND SALODR.BDVCD = '71'   -- 2공장 사업장 수주만
    GROUP BY SALOUT.SALODRKEY, SALOUT.ODRSEQ;

  SELECT
      SALODR.DEBC
    , IFNULL(GPCD('SD300', SALODR.DEBC), SALODR.DEBC) AS DEBCNM
    , SUM(SALODRD.SALQTY * IF(SALODRD.SALUP <> 0, SALODRD.SALUP, SALODRD.SALFUP * SALODR.EXRT)) AS PLANAMT
    , SUM(IFNULL(TEMP_SALOUT.OUTQTY, 0) * IF(SALODRD.SALUP <> 0, SALODRD.SALUP, SALODRD.SALFUP * SALODR.EXRT)) AS RSTAMT
  FROM SALODR
  INNER JOIN SALODRD
    ON SALODRD.SALODRKEY = SALODR.SALODRKEY
  LEFT JOIN TEMP_SALOUT
    ON TEMP_SALOUT.SALODRKEY = SALODRD.SALODRKEY
    AND TEMP_SALOUT.ODRSEQ = SALODRD.ODRSEQ
  WHERE LEFT(SALODR.ODRDATE, 7) = _$MONTH
    AND SALODR.BDVCD = '71'
    AND NOT EXISTS (SELECT COMTYPE.TPCD    -- 유상사급 수주 제외 (사용자 지시)
                      FROM COMTYPE
                      WHERE COMTYPE.GPCD = 'SD310'
                        AND COMTYPE.TPCD = SALODR.SALBC
                        AND COMTYPE.TPNM LIKE '%유상사급%')
    AND EXISTS (SELECT MSTITEM_FACTORY.ITEMID
                  FROM MSTITEM_FACTORY
                  WHERE MSTITEM_FACTORY.ITEMID = SALODRD.ITEMID
                    AND MSTITEM_FACTORY.FACTORYCD = '07')
  GROUP BY SALODR.DEBC
  ORDER BY SALODR.DEBC;

  -- 2. 올해 월별 불량 PPM
  SELECT
      MONTHS.MM AS MONTH
    , IFNULL(MONTH_RST.PRODQTY, 0) AS PRODQTY
    , IFNULL(MONTH_RST.BADQTY, 0) AS BADQTY
    , IF(IFNULL(MONTH_RST.PRODQTY, 0) > 0, ROUND(MONTH_RST.BADQTY / MONTH_RST.PRODQTY * 1000000, 0), 0) AS PPM
  FROM (SELECT 1 AS MM UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6
        UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9 UNION ALL SELECT 10 UNION ALL SELECT 11 UNION ALL SELECT 12) AS MONTHS
  LEFT JOIN (
              SELECT
                  CAST(SUBSTRING(PRDWORK.WORKDATE, 6, 2) AS UNSIGNED) AS MM
                , SUM(PRDRST.PRODQTY) AS PRODQTY
                , SUM(PRDRST.BADQTY) AS BADQTY
              FROM PRDRST
              INNER JOIN PRDWORK
                ON PRDWORK.PRDWORKKEY = PRDRST.PRDWORKKEY
              INNER JOIN PRDINS
                ON PRDINS.PRDINSKEY = PRDWORK.PRDINSKEY
              INNER JOIN MSTPRC
                ON MSTPRC.PRCCD = PRDINS.PRCCD
                AND MSTPRC.GUBUN_BC = 'PP412001' -- 사내공정
              WHERE PRDWORK.WORKDATE BETWEEN CONCAT(_$YEAR, '-01-01') AND CONCAT(_$YEAR, '-12-31')
                AND EXISTS (SELECT MSTLINE_EQM.EQMCD
                              FROM MSTLINE_EQM
                              INNER JOIN MSTLINE
                                ON MSTLINE.LINECD = MSTLINE_EQM.LINECD
                              WHERE MSTLINE_EQM.EQMCD = PRDRST.EQMCD
                                AND MSTLINE.FACTORYCD = '07')
              GROUP BY CAST(SUBSTRING(PRDWORK.WORKDATE, 6, 2) AS UNSIGNED)
            ) AS MONTH_RST
    ON MONTH_RST.MM = MONTHS.MM
  ORDER BY MONTHS.MM;

  -- 3. 라인(설비)별 금일 현황
  -- 3-1. 2공장 사내 라인 설비
  DROP TEMPORARY TABLE IF EXISTS TEMP_LINE;
  CREATE TEMPORARY TABLE TEMP_LINE AS
    SELECT
        MSTLINE_EQM.LINECD
      , MSTLINE_EQM.EQMCD
      , IFNULL(MSTLINE.LINENM, MSTLINE_EQM.LINECD) AS LINENM
      , IFNULL(MSTLINE_EQM.EQMNM, MSTLINE_EQM.EQMCD) AS EQMNM
    FROM MSTLINE_EQM
    INNER JOIN MSTLINE
      ON MSTLINE.LINECD = MSTLINE_EQM.LINECD
    WHERE MSTLINE_EQM.USEYN = 'Y'
      AND MSTLINE_EQM.MONITORYN = 'Y'  -- 모니터링 표시 라인만 (MST1002_R05)
      AND MSTLINE.USEYN = 'Y'
      AND MSTLINE.EDT = ''
      AND MSTLINE.FACTORYCD = '07'  -- 2공장
      AND MSTLINE.OSCCUSTCD = '';   -- 사내 작업장

  -- 3-2. 금일 계획·실적 (품목별)
  DROP TEMPORARY TABLE IF EXISTS TEMP_LINEDATA;
  CREATE TEMPORARY TABLE TEMP_LINEDATA (
    EQMCD   VARCHAR(100) NOT NULL,
    ITEMID  VARCHAR(100) NOT NULL,
    PLANQTY DECIMAL(20, 8) NOT NULL DEFAULT 0,
    GOODQTY DECIMAL(20, 8) NOT NULL DEFAULT 0
  );

  -- 같은 날짜가 계획월별로 여러 줄일 수 있어 MAX (PRD2001_S02 와 같음)
  INSERT INTO TEMP_LINEDATA (EQMCD, ITEMID, PLANQTY)
  SELECT
      PRDPLAN_W.EQMCD
    , CAST(PRDPLAN_W.ITEMID AS CHAR)
    , MAX(PRDPLAN_W.PLANQTY_DAY) + MAX(PRDPLAN_W.PLANQTY_NIGHT)
  FROM PRDPLAN_W
  WHERE PRDPLAN_W.PDATE = _$WORKDATE
  GROUP BY PRDPLAN_W.EQMCD, PRDPLAN_W.ITEMID;

  INSERT INTO TEMP_LINEDATA (EQMCD, ITEMID, GOODQTY)
  SELECT
      PRDRST.EQMCD
    , CAST(PRDRST.ITEMID AS CHAR)
    , SUM(PRDRST.GOODQTY)
  FROM PRDRST
  INNER JOIN PRDWORK
    ON PRDWORK.PRDWORKKEY = PRDRST.PRDWORKKEY
  INNER JOIN PRDINS
    ON PRDINS.PRDINSKEY = PRDWORK.PRDINSKEY
  INNER JOIN MSTPRC
    ON MSTPRC.PRCCD = PRDINS.PRCCD
    AND MSTPRC.GUBUN_BC = 'PP412001' -- 사내공정
  WHERE PRDWORK.WORKDATE = _$WORKDATE
  GROUP BY PRDRST.EQMCD, PRDRST.ITEMID;

  DROP TEMPORARY TABLE IF EXISTS TEMP_LINEITEM;
  CREATE TEMPORARY TABLE TEMP_LINEITEM AS
    SELECT
        TEMP_LINEDATA.EQMCD
      , TEMP_LINEDATA.ITEMID
      , SUM(TEMP_LINEDATA.PLANQTY) AS PLANQTY
      , SUM(TEMP_LINEDATA.GOODQTY) AS GOODQTY
    FROM TEMP_LINEDATA
    GROUP BY TEMP_LINEDATA.EQMCD, TEMP_LINEDATA.ITEMID
    HAVING SUM(TEMP_LINEDATA.PLANQTY) <> 0 OR SUM(TEMP_LINEDATA.GOODQTY) <> 0;

  -- 설비별 합계, 대표 품목 = 계획+실적이 가장 많은 품목
  DROP TEMPORARY TABLE IF EXISTS TEMP_EQMSUM;
  CREATE TEMPORARY TABLE TEMP_EQMSUM AS
    SELECT
        TEMP_LINEITEM.EQMCD
      , SUM(TEMP_LINEITEM.PLANQTY) AS PLANQTY
      , SUM(TEMP_LINEITEM.GOODQTY) AS GOODQTY
      , COUNT(*) AS ITEMCNT
      , SUBSTRING_INDEX(GROUP_CONCAT(TEMP_LINEITEM.ITEMID ORDER BY TEMP_LINEITEM.PLANQTY + TEMP_LINEITEM.GOODQTY DESC SEPARATOR '|'), '|', 1) AS ITEMID
    FROM TEMP_LINEITEM
    GROUP BY TEMP_LINEITEM.EQMCD;

  -- 3-3. 금일 근무조 시간 (지금 시각까지만)
  DROP TEMPORARY TABLE IF EXISTS TEMP_SHIFT;
  CREATE TEMPORARY TABLE TEMP_SHIFT AS
    SELECT
        CONCAT(_$WORKDATE, ' ', COMTYPE.REF01, ':00') AS STIME
      , LEAST(_$NOW, CONCAT(IF(COMTYPE.REF02 <= COMTYPE.REF01, DATE_FORMAT(DATE_ADD(_$WORKDATE, INTERVAL 1 DAY), '%Y-%m-%d'), _$WORKDATE), ' ', COMTYPE.REF02, ':00')) AS ETIME
    FROM COMTYPE
    WHERE COMTYPE.GPCD = 'PP161'
      AND COMTYPE.USEYN = 'Y'
      AND COMTYPE.REF05 = '07';  -- 2공장 근무조

  DELETE FROM TEMP_SHIFT
  WHERE TEMP_SHIFT.ETIME <= TEMP_SHIFT.STIME;  -- 아직 시작 안 한 근무조

  SELECT
      IFNULL(SUM(TIMESTAMPDIFF(MINUTE, TEMP_SHIFT.STIME, TEMP_SHIFT.ETIME)), 0)
  INTO _$WORKMIN
  FROM TEMP_SHIFT;

  -- 설비별 비가동(분): 근무조 시간과 겹치는 만큼, 끝나지 않은 비가동은 지금까지
  DROP TEMPORARY TABLE IF EXISTS TEMP_NON;
  CREATE TEMPORARY TABLE TEMP_NON AS
    SELECT
        PRDRSTNON.EQMCD
      , SUM(TIMESTAMPDIFF(MINUTE, GREATEST(PRDRSTNON.NONSTIME, TEMP_SHIFT.STIME)
                                , LEAST(IF(PRDRSTNON.NONETIME = '', _$NOW, PRDRSTNON.NONETIME), TEMP_SHIFT.ETIME))) AS NONMIN
    FROM PRDRSTNON
    INNER JOIN TEMP_SHIFT
      ON PRDRSTNON.NONSTIME < TEMP_SHIFT.ETIME
      AND (PRDRSTNON.NONETIME = '' OR PRDRSTNON.NONETIME > TEMP_SHIFT.STIME)
    WHERE PRDRSTNON.NONSTIME < _$NOW
    GROUP BY PRDRSTNON.EQMCD;

  SELECT
      TEMP_LINE.LINECD
    , TEMP_LINE.EQMCD
    , TEMP_LINE.LINENM
    , TEMP_LINE.EQMNM
    , CONCAT(IFNULL(MSTITEM.ITEMNM, ''), IF(IFNULL(TEMP_EQMSUM.ITEMCNT, 0) > 1, CONCAT(' 외 ', TEMP_EQMSUM.ITEMCNT - 1), '')) AS ITEMNM
    , IFNULL(TEMP_EQMSUM.PLANQTY, 0) AS PLANQTY
    , IFNULL(TEMP_EQMSUM.GOODQTY, 0) AS GOODQTY
    , IF(IFNULL(TEMP_EQMSUM.PLANQTY, 0) > 0, TRUNCATE(TEMP_EQMSUM.GOODQTY / TEMP_EQMSUM.PLANQTY * 100, 0), 0) AS RATE
    , '' AS RUNSTT   -- 가동상태 : PLC 연계 후 채움
    , IF(_$WORKMIN > 0 AND TEMP_EQMSUM.EQMCD IS NOT NULL
       , TRUNCATE((_$WORKMIN - LEAST(IFNULL(TEMP_NON.NONMIN, 0), _$WORKMIN)) / _$WORKMIN * 100, 0)
       , 0) AS TIMERATE
  FROM TEMP_LINE
  LEFT JOIN TEMP_EQMSUM
    ON TEMP_EQMSUM.EQMCD = TEMP_LINE.EQMCD
  LEFT JOIN MSTITEM
    ON CAST(MSTITEM.ITEMID AS CHAR) = TEMP_EQMSUM.ITEMID
  LEFT JOIN TEMP_NON
    ON TEMP_NON.EQMCD = TEMP_LINE.EQMCD
  ORDER BY TEMP_LINE.LINECD, TEMP_LINE.EQMNM;

-- ****************************************************************************
WHEN 'SAVE_PPM' THEN  -- 목표 PPM 저장

  IF IFNULL($TARGETYEAR, '') NOT REGEXP '^[0-9]{4}$' THEN
    CALL COMERR('목표년도가 올바르지 않습니다.');
    LEAVE PROC;
  END IF;

  IF IFNULL($TARGETPPM, '') NOT REGEXP '^[0-9]+(\\.[0-9]+)?$' THEN
    CALL COMERR('목표 PPM 을 숫자로 입력하세요.');
    LEAVE PROC;
  END IF;

  INSERT INTO TQMTARGETPPM (
    TARGETYEAR, TARGETPPM,
    RTIME, REMP, RPRG, MTIME, MEMP, MPRG
  ) VALUES (
    $TARGETYEAR, $TARGETPPM,
    _$NOW, @CALLEMP, @CALLPRG, _$NOW, @CALLEMP, @CALLPRG
  )
  ON DUPLICATE KEY UPDATE
    TARGETPPM = $TARGETPPM,
    MTIME = _$NOW,
    MEMP = @CALLEMP,
    MPRG = @CALLPRG;

END CASE;
END
