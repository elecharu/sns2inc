CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.SAL3002_S02(
-- *****************************************************************************
-- Comment: 판매계획(수주) 대비 출하실적조회 - 생산관리팀 "판매계획대비 출하실적(세부)_2공장" 엑셀 양식
--          ) 계획 = 수주일자(SALODR.ODRDATE)가 조회년월이고 사업장이 2공장(SALODR.BDVCD 71)인 수주의 수량·금액
--          ) 2공장 = 품목 공장 07, 1공장 = 품목 공장 06 (둘 다면 2공장). 1공장은 엑셀처럼
--            메인 1번 표 Total(1공장포함) 과 상세탭 맨 아래 '1공장' 구간에만 넣는다. 메인 2·3·4번 표는 2공장만
--          ) 실적 = 그 수주 품목(SALODRKEY + ODRSEQ)에 연결된 출하(SALOUT.OUTQTY) 합. 출고일자는 따지지 않는다
--          ) 금액 = 수량 × 원화 단가(SALODRD.SALUP, 없으면 외화단가 SALFUP × 수주 환율 SALODR.EXRT)
--          ) 수출/내수 = 수주 지역구분(SALODR.DEBC, 공통코드 SD300)
--          ) 상세 줄 = 지역구분 + 거래처 + 품목. 변동사유·미출고원인·대책·비고는 SALOUTRST_M (월 × 거래처 × 품목)
--          ) LIST : 결과셋 1 구분별 / 2 고객사별 / 3 변동사유별 / 4 판매계획 대비 실적 (메인탭)
--                   결과셋 5 상세 (상세탭, ROWTP D 품목 / C 고객사 Total / G 구분 Total / T Grand Total)
--          ) SAVE : 상세탭 변동사유·미출고원인·대책·비고 저장 (네 칸이 다 비면 지운다)
--          ) DELETE : 상세탭 체크한 품목 줄들 삭제
-- Create: 2026-11-17
-- Modify: 2026-11-17 달성율(RATE) 소수점 버림 (사용자 지시)
--         2026-11-17 1공장(품목 공장 06) 수주 추가: 1번 표 Total(1공장제외)/Total(1공장포함),
--                    상세탭 Grand Total (1공장 제외) → 1공장 구간 → Grand Total (1공장 포함) (사용자 지시)
--         2026-11-17 3번 표 '(미입력)' → '정상출고' (변동사유 미입력 = 정상출고, 공통코드 NORMAL 삭제) (사용자 지시)
--         2026-11-17 DELETE 추가: 상세탭 체크한 품목 줄들의 변동사유·미출고원인·대책·비고 삭제 (사용자 지시)
--         2026-11-17 수주를 2공장 사업장(SALODR.BDVCD 71)으로 한정. 품목 공장 06/07 구분은 그대로 (사용자 지시)
--         2026-11-17 상세탭 구분 Total·Grand Total 줄의 고객사 칸 비움 (사용자 지시)
--         2026-11-17 상세탭 통화가 원화(BC400KRW)면 외화단가 빈칸 (사용자 지시)
--         2026-11-17 결과셋 5 에 CURYNM·OUTCHGNM 추가 (리포트 SAL3002.exe S02 출력용)
--         2026-11-17 결과셋 5 에 DEBC 추가 (상세탭 [상세조회] 버튼 → 출하실적조회 SAL3002_S04 로 넘김. 1공장 줄은 FAC1)
-- *****************************************************************************
  IN $SMONTH VARCHAR(10),             -- 조회년월 (YYYY-MM)
  IN $CUSTCD_LIST MEDIUMTEXT,         -- 거래처 목록 (SAVE)
  IN $ITEMID_LIST MEDIUMTEXT,         -- 품목ID 목록
  IN $OUTCHGTP_LIST MEDIUMTEXT,       -- 변동사유 목록
  IN $NOOUTCAUSE_LIST MEDIUMTEXT,     -- 미출고 원인 목록
  IN $MEASURE_LIST MEDIUMTEXT,        -- 대책 목록
  IN $REMARK_LIST MEDIUMTEXT,         -- 비고 목록
-- *****************************************************************************
  IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  DECLARE _$MONTH VARCHAR(7);
  DECLARE _$CUSTCD_LIST MEDIUMTEXT;
  DECLARE _$ITEMID_LIST MEDIUMTEXT;
  DECLARE _$OUTCHGTP_LIST MEDIUMTEXT;
  DECLARE _$NOOUTCAUSE_LIST MEDIUMTEXT;
  DECLARE _$MEASURE_LIST MEDIUMTEXT;
  DECLARE _$REMARK_LIST MEDIUMTEXT;
  DECLARE _$CUSTCD VARCHAR(100);
  DECLARE _$ITEMID VARCHAR(100);
  DECLARE _$OUTCHGTP VARCHAR(100);
  DECLARE _$NOOUTCAUSE VARCHAR(1000);
  DECLARE _$MEASURE VARCHAR(1000);
  DECLARE _$REMARK VARCHAR(1000);
-- *****************************************************************************
  IF IFNULL($SMONTH, '') = '' THEN
    CALL COMERR('조회년월을 입력하세요.');
    LEAVE PROC;
  END IF;

  SET _$MONTH = LEFT($SMONTH, 7);
-- *****************************************************************************
CASE $CALLTYPE
-- ****************************************************************************
WHEN 'LIST' THEN  -- 메인탭 4개 표 + 상세탭

  -- 1. 조회년월 수주 품목별 출하 수량 (수주번호 + 순번으로 연결)
  DROP TEMPORARY TABLE IF EXISTS TEMP_SALOUT;
  CREATE TEMPORARY TABLE TEMP_SALOUT AS
    SELECT
        SALOUT.SALODRKEY
      , SALOUT.ODRSEQ
      , SUM(SALOUT.OUTQTY) AS OUTQTY
    FROM SALOUT
    INNER JOIN SALODR
      ON SALODR.SALODRKEY = SALOUT.SALODRKEY
    WHERE LEFT(SALODR.ODRDATE, 7) = _$MONTH
      AND SALODR.BDVCD = '71'   -- 2공장 사업장 수주만
    GROUP BY SALOUT.SALODRKEY, SALOUT.ODRSEQ;

  -- 2. 지역구분 + 거래처 + 품목별 계획·실적 (2공장 사업장 71 수주 중 2공장 07 · 1공장 06 품목)
  DROP TEMPORARY TABLE IF EXISTS TEMP_ITEM;
  CREATE TEMPORARY TABLE TEMP_ITEM AS
    SELECT
        SALODR.DEBC
      , SALODR.CUSTCD
      , SALODRD.ITEMID
      , MAX(SALODR.CURYBC) AS CURYBC
      , MAX(SALODRD.SALFUP) AS FUP
      , MAX(IF(SALODRD.SALUP <> 0, SALODRD.SALUP, SALODRD.SALFUP * SALODR.EXRT)) AS UP
      , SUM(SALODRD.SALQTY) AS PLANQTY
      , SUM(SALODRD.SALQTY * IF(SALODRD.SALUP <> 0, SALODRD.SALUP, SALODRD.SALFUP * SALODR.EXRT)) AS PLANAMT
      , SUM(IFNULL(TEMP_SALOUT.OUTQTY, 0)) AS RSTQTY
      , SUM(IFNULL(TEMP_SALOUT.OUTQTY, 0) * IF(SALODRD.SALUP <> 0, SALODRD.SALUP, SALODRD.SALFUP * SALODR.EXRT)) AS RSTAMT
    FROM SALODR
    INNER JOIN SALODRD
      ON SALODRD.SALODRKEY = SALODR.SALODRKEY
    LEFT JOIN TEMP_SALOUT
      ON TEMP_SALOUT.SALODRKEY = SALODRD.SALODRKEY
     AND TEMP_SALOUT.ODRSEQ = SALODRD.ODRSEQ
    WHERE LEFT(SALODR.ODRDATE, 7) = _$MONTH
      AND SALODR.BDVCD = '71'   -- 2공장 사업장 수주만
      AND EXISTS (SELECT MSTITEM_FACTORY.ITEMID
                    FROM MSTITEM_FACTORY
                    WHERE MSTITEM_FACTORY.ITEMID = SALODRD.ITEMID
                      AND MSTITEM_FACTORY.FACTORYCD IN ('06', '07'))
    GROUP BY SALODR.DEBC, SALODR.CUSTCD, SALODRD.ITEMID;

  -- 3. 품목 줄에 이름·정렬값·변동사유를 붙인다 (임시테이블은 한 쿼리에서 두 번 못 열어 미리 만든다)
  DROP TEMPORARY TABLE IF EXISTS TEMP_DATA;
  CREATE TEMPORARY TABLE TEMP_DATA AS
    SELECT
        IF(EXISTS (SELECT MSTITEM_FACTORY.ITEMID
                     FROM MSTITEM_FACTORY
                     WHERE MSTITEM_FACTORY.ITEMID = TEMP_ITEM.ITEMID
                       AND MSTITEM_FACTORY.FACTORYCD = '07'), '2', '1') AS FACTYP   -- 2 = 2공장, 1 = 1공장
      , TEMP_ITEM.DEBC
      , IFNULL(NULLIF(GPCD('SD300', TEMP_ITEM.DEBC), ''), TEMP_ITEM.DEBC) AS DEBCNM
      , CAST(IFNULL((SELECT COMTYPE.SORTNO
                       FROM COMTYPE
                       WHERE COMTYPE.GPCD = 'SD300'
                         AND COMTYPE.TPCD = TEMP_ITEM.DEBC), 999) AS SIGNED) AS DEBCSORT
      , TEMP_ITEM.CUSTCD
      , IFNULL(MSTCUST.CUSTNM, TEMP_ITEM.CUSTCD) AS CUSTNM
      , TEMP_ITEM.ITEMID
      , IFNULL(MSTITEM.ITEMCD, '') AS ITEMCD
      , IFNULL(MSTITEM.ITEMNM, '') AS ITEMNM
      , TEMP_ITEM.CURYBC
      , TEMP_ITEM.FUP
      , TEMP_ITEM.UP
      , TEMP_ITEM.PLANQTY
      , TEMP_ITEM.PLANAMT
      , TEMP_ITEM.RSTQTY
      , TEMP_ITEM.RSTAMT
      , IFNULL(SALOUTRST_M.OUTCHGTP, '') AS OUTCHGTP
      , IFNULL(SALOUTRST_M.NOOUTCAUSE, '') AS NOOUTCAUSE
      , IFNULL(SALOUTRST_M.MEASURE, '') AS MEASURE
      , IFNULL(SALOUTRST_M.REMARK, '') AS REMARK
    FROM TEMP_ITEM
    LEFT JOIN MSTCUST
      ON MSTCUST.CUSTCD = TEMP_ITEM.CUSTCD
    LEFT JOIN MSTITEM
      ON MSTITEM.ITEMID = TEMP_ITEM.ITEMID
    LEFT JOIN SALOUTRST_M
      ON SALOUTRST_M.RSTMONTH = _$MONTH
     AND SALOUTRST_M.CUSTCD = TEMP_ITEM.CUSTCD
     AND SALOUTRST_M.ITEMID = TEMP_ITEM.ITEMID;

  -- 1공장은 수출/내수로 나누지 않고 '1공장' 한 구간으로 맨 뒤에 둔다 (엑셀 세부내역)
  UPDATE TEMP_DATA
    SET DEBC = 'FAC1'
      , DEBCNM = '1공장'
      , DEBCSORT = 10000
    WHERE TEMP_DATA.FACTYP = '1';

  -- 4. 메인탭 표 (GRIDNO 1 구분별 / 2 고객사별 / 3 변동사유별)
  DROP TEMPORARY TABLE IF EXISTS TEMP_SUM;
  CREATE TEMPORARY TABLE TEMP_SUM (
      GRIDNO INT NOT NULL
    , ROWTP VARCHAR(1) NOT NULL DEFAULT 'D'     -- D 줄 / G 구분 합계 / T 총합계
    , SORT1 INT NOT NULL DEFAULT 0
    , SORT2 VARCHAR(200) NOT NULL DEFAULT ''
    , CODE VARCHAR(100) NOT NULL DEFAULT ''
    , NAME1 VARCHAR(200) NOT NULL DEFAULT ''
    , NAME2 VARCHAR(200) NOT NULL DEFAULT ''
    , PLANAMT DECIMAL(30, 8) NOT NULL DEFAULT 0
    , RSTAMT DECIMAL(30, 8) NOT NULL DEFAULT 0
  );

  -- 4-1. 구분별(2공장) + Total(1공장제외) + Total(1공장포함)
  INSERT INTO TEMP_SUM (GRIDNO, ROWTP, SORT1, CODE, NAME1, PLANAMT, RSTAMT)
    SELECT 1, 'D', TEMP_DATA.DEBCSORT, TEMP_DATA.DEBC, MAX(TEMP_DATA.DEBCNM), SUM(TEMP_DATA.PLANAMT), SUM(TEMP_DATA.RSTAMT)
    FROM TEMP_DATA
    WHERE TEMP_DATA.FACTYP = '2'
    GROUP BY TEMP_DATA.DEBCSORT, TEMP_DATA.DEBC;

  INSERT INTO TEMP_SUM (GRIDNO, ROWTP, SORT1, CODE, NAME1, PLANAMT, RSTAMT)
    SELECT 1, 'T', 99998, '', 'Total(1공장제외)', IFNULL(SUM(TEMP_DATA.PLANAMT), 0), IFNULL(SUM(TEMP_DATA.RSTAMT), 0)
    FROM TEMP_DATA
    WHERE TEMP_DATA.FACTYP = '2';

  INSERT INTO TEMP_SUM (GRIDNO, ROWTP, SORT1, CODE, NAME1, PLANAMT, RSTAMT)
    SELECT 1, 'T', 99999, '', 'Total(1공장포함)', IFNULL(SUM(TEMP_DATA.PLANAMT), 0), IFNULL(SUM(TEMP_DATA.RSTAMT), 0)
    FROM TEMP_DATA;

  -- 4-2. 고객사별 + 구분 합계 + 총합계 (2공장만)
  INSERT INTO TEMP_SUM (GRIDNO, ROWTP, SORT1, SORT2, CODE, NAME1, NAME2, PLANAMT, RSTAMT)
    SELECT 2, 'D', TEMP_DATA.DEBCSORT, MAX(TEMP_DATA.CUSTNM), TEMP_DATA.DEBC, MAX(TEMP_DATA.DEBCNM), MAX(TEMP_DATA.CUSTNM)
         , SUM(TEMP_DATA.PLANAMT), SUM(TEMP_DATA.RSTAMT)
    FROM TEMP_DATA
    WHERE TEMP_DATA.FACTYP = '2'
    GROUP BY TEMP_DATA.DEBCSORT, TEMP_DATA.DEBC, TEMP_DATA.CUSTCD;

  INSERT INTO TEMP_SUM (GRIDNO, ROWTP, SORT1, CODE, NAME1, NAME2, PLANAMT, RSTAMT)
    SELECT 2, 'G', TEMP_DATA.DEBCSORT, TEMP_DATA.DEBC, MAX(TEMP_DATA.DEBCNM), '합계', SUM(TEMP_DATA.PLANAMT), SUM(TEMP_DATA.RSTAMT)
    FROM TEMP_DATA
    WHERE TEMP_DATA.FACTYP = '2'
    GROUP BY TEMP_DATA.DEBCSORT, TEMP_DATA.DEBC;

  INSERT INTO TEMP_SUM (GRIDNO, ROWTP, SORT1, CODE, NAME1, NAME2, PLANAMT, RSTAMT)
    SELECT 2, 'T', 99999, '', '총합계', '', IFNULL(SUM(TEMP_DATA.PLANAMT), 0), IFNULL(SUM(TEMP_DATA.RSTAMT), 0)
    FROM TEMP_DATA
    WHERE TEMP_DATA.FACTYP = '2';

  -- 4-3. 변동사유별 (사유 코드는 금액이 없어도 다 보인다) + 정상출고(사유를 안 넣은 품목) + 합계 (2공장만)
  INSERT INTO TEMP_SUM (GRIDNO, ROWTP, SORT1, CODE, NAME1)
    SELECT 3, 'D', COMTYPE.SORTNO, COMTYPE.TPCD, COMTYPE.TPNM
    FROM COMTYPE
    WHERE COMTYPE.GPCD = 'OUTCHGTP'
      AND COMTYPE.USEYN = 'Y';

  INSERT INTO TEMP_SUM (GRIDNO, ROWTP, SORT1, CODE, NAME1, PLANAMT, RSTAMT)
    SELECT 3, 'D'
         , IF(TEMP_DATA.OUTCHGTP = '', 9000, IFNULL(MAX(COMTYPE.SORTNO), 8000))
         , TEMP_DATA.OUTCHGTP
         , IF(TEMP_DATA.OUTCHGTP = '', '정상출고', IFNULL(MAX(COMTYPE.TPNM), TEMP_DATA.OUTCHGTP))  -- 변동사유 미입력 = 정상출고
         , SUM(TEMP_DATA.PLANAMT), SUM(TEMP_DATA.RSTAMT)
    FROM TEMP_DATA
    LEFT JOIN COMTYPE
      ON COMTYPE.GPCD = 'OUTCHGTP'
     AND COMTYPE.TPCD = TEMP_DATA.OUTCHGTP
    WHERE TEMP_DATA.FACTYP = '2'
    GROUP BY TEMP_DATA.OUTCHGTP;

  INSERT INTO TEMP_SUM (GRIDNO, ROWTP, SORT1, CODE, NAME1, PLANAMT, RSTAMT)
    SELECT 3, 'T', 99999, '', '합계', IFNULL(SUM(TEMP_DATA.PLANAMT), 0), IFNULL(SUM(TEMP_DATA.RSTAMT), 0)
    FROM TEMP_DATA
    WHERE TEMP_DATA.FACTYP = '2';

  -- 결과셋 1: 구분별 (수출 / 내수 / Total(1공장제외) / Total(1공장포함))
  SELECT
      TEMP_SUM.ROWTP
    , TEMP_SUM.NAME1 AS DEBCNM
    , TEMP_SUM.PLANAMT
    , TEMP_SUM.RSTAMT
    , TEMP_SUM.RSTAMT - TEMP_SUM.PLANAMT AS DIFFAMT
    , IF(TEMP_SUM.PLANAMT = 0, NULL, TRUNCATE(TEMP_SUM.RSTAMT / TEMP_SUM.PLANAMT * 100, 0)) AS RATE  -- 달성율 소수점 버림
    , IF(TEMP_SUM.ROWTP = 'T', '#E4DFEC', '') AS BACKGROUND
  FROM TEMP_SUM
  WHERE TEMP_SUM.GRIDNO = 1
  ORDER BY TEMP_SUM.SORT1, TEMP_SUM.CODE;

  -- 결과셋 2: 고객사별 (구분 안에서 고객사, 구분 합계, 총합계)
  SELECT
      TEMP_SUM.ROWTP
    , TEMP_SUM.NAME1 AS DEBCNM
    , TEMP_SUM.NAME2 AS CUSTNM
    , TEMP_SUM.PLANAMT
    , TEMP_SUM.RSTAMT
    , IF(TEMP_SUM.PLANAMT = 0, NULL, TRUNCATE(TEMP_SUM.RSTAMT / TEMP_SUM.PLANAMT * 100, 0)) AS RATE  -- 달성율 소수점 버림
    , CASE
        WHEN TEMP_SUM.ROWTP = 'G' THEN '#F2F2F2'
        WHEN TEMP_SUM.ROWTP = 'T' THEN '#E4DFEC'
        ELSE '' END AS BACKGROUND
  FROM TEMP_SUM
  WHERE TEMP_SUM.GRIDNO = 2
  ORDER BY TEMP_SUM.SORT1, TEMP_SUM.CODE, IF(TEMP_SUM.ROWTP = 'D', 0, 1), TEMP_SUM.SORT2;

  -- 결과셋 3: 변동사유별
  SELECT
      MAX(TEMP_SUM.ROWTP) AS ROWTP
    , MAX(TEMP_SUM.NAME1) AS OUTCHGNM
    , SUM(TEMP_SUM.PLANAMT) AS PLANAMT
    , SUM(TEMP_SUM.RSTAMT) AS RSTAMT
    , SUM(TEMP_SUM.RSTAMT) - SUM(TEMP_SUM.PLANAMT) AS DIFFAMT
    , IF(MAX(TEMP_SUM.ROWTP) = 'T', '#E4DFEC', '') AS BACKGROUND
  FROM TEMP_SUM
  WHERE TEMP_SUM.GRIDNO = 3
  GROUP BY TEMP_SUM.ROWTP, TEMP_SUM.CODE
  ORDER BY MIN(TEMP_SUM.SORT1), TEMP_SUM.CODE;

  -- 결과셋 4: 판매계획 대비 실적 (2공장만)
  --   A = 판매계획 합, B = 조정대상 사유(OUTCHGTP REF01 = Y)의 차액(실적 - 계획) 합, C = A + B, 달성율 = 실적 / C
  SELECT
      PLAN.PLANAMT
    , IFNULL((SELECT GROUP_CONCAT(COMTYPE.TPNM ORDER BY COMTYPE.SORTNO SEPARATOR '+')
                FROM COMTYPE
                WHERE COMTYPE.GPCD = 'OUTCHGTP'
                  AND COMTYPE.USEYN = 'Y'
                  AND COMTYPE.REF01 = 'Y'), '') AS ADJNM
    , PLAN.ADJAMT
    , PLAN.PLANAMT + PLAN.ADJAMT AS ADJPLANAMT
    , PLAN.RSTAMT
    , IF(PLAN.PLANAMT + PLAN.ADJAMT = 0, NULL, TRUNCATE(PLAN.RSTAMT / (PLAN.PLANAMT + PLAN.ADJAMT) * 100, 0)) AS RATE  -- 달성율 소수점 버림
  FROM (
         SELECT
             IFNULL(SUM(TEMP_DATA.PLANAMT), 0) AS PLANAMT
           , IFNULL(SUM(IF(COMTYPE.REF01 = 'Y', TEMP_DATA.RSTAMT - TEMP_DATA.PLANAMT, 0)), 0) AS ADJAMT
           , IFNULL(SUM(TEMP_DATA.RSTAMT), 0) AS RSTAMT
         FROM TEMP_DATA
         LEFT JOIN COMTYPE
           ON COMTYPE.GPCD = 'OUTCHGTP'
          AND COMTYPE.TPCD = TEMP_DATA.OUTCHGTP
         WHERE TEMP_DATA.FACTYP = '2'
       ) AS PLAN;

  -- 5. 상세탭 줄 (품목 + 고객사 Total + 구분 Total + Grand Total, 1공장은 맨 아래 '1공장' 구간)
  DROP TEMPORARY TABLE IF EXISTS TEMP_ROW;
  CREATE TEMPORARY TABLE TEMP_ROW (
      ROWTP VARCHAR(1) NOT NULL DEFAULT 'D'     -- D 품목 / C 고객사 Total / G 구분 Total / T Grand Total
    , SORTT INT NOT NULL DEFAULT 0
    , DEBCSORT INT NOT NULL DEFAULT 0
    , DEBC VARCHAR(100) NOT NULL DEFAULT ''
    , SORTG INT NOT NULL DEFAULT 0
    , CUSTNMSORT VARCHAR(200) NOT NULL DEFAULT ''
    , CUSTCD VARCHAR(100) NOT NULL DEFAULT ''
    , SORTC INT NOT NULL DEFAULT 0
    , DEBCNM VARCHAR(200) NOT NULL DEFAULT ''
    , CUSTNM VARCHAR(200) NOT NULL DEFAULT ''
    , ITEMID INT NULL
    , ITEMCD VARCHAR(200) NOT NULL DEFAULT ''
    , ITEMNM VARCHAR(500) NOT NULL DEFAULT ''
    , CURYBC VARCHAR(100) NOT NULL DEFAULT ''
    , FUP DECIMAL(30, 8) NULL
    , UP DECIMAL(30, 8) NULL
    , PLANQTY DECIMAL(30, 8) NOT NULL DEFAULT 0
    , PLANAMT DECIMAL(30, 8) NOT NULL DEFAULT 0
    , RSTQTY DECIMAL(30, 8) NOT NULL DEFAULT 0
    , RSTAMT DECIMAL(30, 8) NOT NULL DEFAULT 0
    , OUTCHGTP VARCHAR(100) NOT NULL DEFAULT ''
    , NOOUTCAUSE VARCHAR(1000) NOT NULL DEFAULT ''
    , MEASURE VARCHAR(1000) NOT NULL DEFAULT ''
    , REMARK VARCHAR(1000) NOT NULL DEFAULT ''
  );

  -- 줄 순서(SORTT): 0 2공장 구간 → 1 Grand Total (1공장 제외) → 2 1공장 구간 → 3 Grand Total (1공장 포함)
  INSERT INTO TEMP_ROW (ROWTP, SORTT, DEBCSORT, DEBC, CUSTNMSORT, CUSTCD, DEBCNM, CUSTNM, ITEMID, ITEMCD, ITEMNM, CURYBC, FUP, UP
                      , PLANQTY, PLANAMT, RSTQTY, RSTAMT, OUTCHGTP, NOOUTCAUSE, MEASURE, REMARK)
    SELECT
        'D', IF(TEMP_DATA.FACTYP = '1', 2, 0), TEMP_DATA.DEBCSORT, TEMP_DATA.DEBC, TEMP_DATA.CUSTNM, TEMP_DATA.CUSTCD, TEMP_DATA.DEBCNM, TEMP_DATA.CUSTNM
      , TEMP_DATA.ITEMID, TEMP_DATA.ITEMCD, TEMP_DATA.ITEMNM, TEMP_DATA.CURYBC, TEMP_DATA.FUP, TEMP_DATA.UP
      , TEMP_DATA.PLANQTY, TEMP_DATA.PLANAMT, TEMP_DATA.RSTQTY, TEMP_DATA.RSTAMT
      , TEMP_DATA.OUTCHGTP, TEMP_DATA.NOOUTCAUSE, TEMP_DATA.MEASURE, TEMP_DATA.REMARK
    FROM TEMP_DATA;

  INSERT INTO TEMP_ROW (ROWTP, SORTT, DEBCSORT, DEBC, CUSTNMSORT, CUSTCD, SORTC, DEBCNM, CUSTNM, PLANQTY, PLANAMT, RSTQTY, RSTAMT)
    SELECT
        'C', IF(MAX(TEMP_DATA.FACTYP) = '1', 2, 0), TEMP_DATA.DEBCSORT, TEMP_DATA.DEBC, MAX(TEMP_DATA.CUSTNM), TEMP_DATA.CUSTCD, 1
      , MAX(TEMP_DATA.DEBCNM), CONCAT(MAX(TEMP_DATA.CUSTNM), ' Total')
      , SUM(TEMP_DATA.PLANQTY), SUM(TEMP_DATA.PLANAMT), SUM(TEMP_DATA.RSTQTY), SUM(TEMP_DATA.RSTAMT)
    FROM TEMP_DATA
    GROUP BY TEMP_DATA.DEBCSORT, TEMP_DATA.DEBC, TEMP_DATA.CUSTCD;

  INSERT INTO TEMP_ROW (ROWTP, SORTT, DEBCSORT, DEBC, SORTG, DEBCNM, CUSTNM, PLANQTY, PLANAMT, RSTQTY, RSTAMT)
    SELECT
        'G', IF(MAX(TEMP_DATA.FACTYP) = '1', 2, 0), TEMP_DATA.DEBCSORT, TEMP_DATA.DEBC, 1
      , CONCAT(MAX(TEMP_DATA.DEBCNM), ' Total'), ''   -- 고객사 칸은 비운다 (구분 칸과 같은 글자라서)
      , SUM(TEMP_DATA.PLANQTY), SUM(TEMP_DATA.PLANAMT), SUM(TEMP_DATA.RSTQTY), SUM(TEMP_DATA.RSTAMT)
    FROM TEMP_DATA
    GROUP BY TEMP_DATA.DEBCSORT, TEMP_DATA.DEBC;

  INSERT INTO TEMP_ROW (ROWTP, SORTT, DEBCNM, CUSTNM, PLANQTY, PLANAMT, RSTQTY, RSTAMT)
    SELECT
        'T', 1, 'Grand Total (1공장 제외)', ''
      , IFNULL(SUM(TEMP_DATA.PLANQTY), 0), IFNULL(SUM(TEMP_DATA.PLANAMT), 0), IFNULL(SUM(TEMP_DATA.RSTQTY), 0), IFNULL(SUM(TEMP_DATA.RSTAMT), 0)
    FROM TEMP_DATA
    WHERE TEMP_DATA.FACTYP = '2';

  INSERT INTO TEMP_ROW (ROWTP, SORTT, DEBCNM, CUSTNM, PLANQTY, PLANAMT, RSTQTY, RSTAMT)
    SELECT
        'T', 3, 'Grand Total (1공장 포함)', ''
      , IFNULL(SUM(TEMP_DATA.PLANQTY), 0), IFNULL(SUM(TEMP_DATA.PLANAMT), 0), IFNULL(SUM(TEMP_DATA.RSTQTY), 0), IFNULL(SUM(TEMP_DATA.RSTAMT), 0)
    FROM TEMP_DATA;

  -- 결과셋 5: 상세 (엑셀 "세부내역" A~Q 열: 고객사 ~ 비고)
  SELECT
      TEMP_ROW.ROWTP
    , TEMP_ROW.DEBC                       -- 구분 코드 (SD300, 1공장 구간은 FAC1)
    , TEMP_ROW.DEBCNM
    , TEMP_ROW.CUSTCD
    , TEMP_ROW.CUSTNM
    , IFNULL(CAST(TEMP_ROW.ITEMID AS CHAR), '') AS ITEMID
    , TEMP_ROW.ITEMNM
    , TEMP_ROW.ITEMCD
    , TEMP_ROW.CURYBC
    , IFNULL(GPCD('BC400', TEMP_ROW.CURYBC), '') AS CURYNM   -- 리포트용 통화 이름 (KRW / USD)
    , IF(TEMP_ROW.CURYBC = 'BC400KRW', NULL, TEMP_ROW.FUP) AS FUP   -- 원화 수주는 외화단가 빈칸
    , TEMP_ROW.UP
    , TEMP_ROW.PLANQTY
    , TEMP_ROW.PLANAMT
    , TEMP_ROW.RSTQTY
    , TEMP_ROW.RSTAMT
    , IF(TEMP_ROW.PLANAMT = 0, NULL, TRUNCATE(TEMP_ROW.RSTAMT / TEMP_ROW.PLANAMT * 100, 0)) AS RATE  -- 달성율 소수점 버림
    , TEMP_ROW.RSTQTY - TEMP_ROW.PLANQTY AS DIFFQTY
    , TEMP_ROW.RSTAMT - TEMP_ROW.PLANAMT AS DIFFAMT
    , TEMP_ROW.OUTCHGTP
    , IFNULL(GPCD('OUTCHGTP', TEMP_ROW.OUTCHGTP), '') AS OUTCHGNM   -- 리포트용 변동사유 이름
    , TEMP_ROW.NOOUTCAUSE
    , TEMP_ROW.MEASURE
    , TEMP_ROW.REMARK
    , CASE
        WHEN TEMP_ROW.ROWTP = 'C' THEN '#F2F2F2'
        WHEN TEMP_ROW.ROWTP = 'G' THEN '#DDEBF7'
        WHEN TEMP_ROW.ROWTP = 'T' THEN '#E4DFEC'
        ELSE '' END AS BACKGROUND
  FROM TEMP_ROW
  ORDER BY TEMP_ROW.SORTT, TEMP_ROW.DEBCSORT, TEMP_ROW.DEBC, TEMP_ROW.SORTG, TEMP_ROW.CUSTNMSORT, TEMP_ROW.CUSTCD
         , TEMP_ROW.SORTC, TEMP_ROW.ITEMCD, TEMP_ROW.ITEMID;

-- ****************************************************************************
WHEN 'SAVE' THEN  -- 상세탭 변동사유·미출고원인·대책·비고 저장

  IF IFNULL($CUSTCD_LIST, '') = '' THEN
    CALL COMERR('저장할 품목이 없습니다.');
    LEAVE PROC;
  END IF;

  SET _$CUSTCD_LIST = $CUSTCD_LIST;
  SET _$ITEMID_LIST = $ITEMID_LIST;
  SET _$OUTCHGTP_LIST = $OUTCHGTP_LIST;
  SET _$NOOUTCAUSE_LIST = $NOOUTCAUSE_LIST;
  SET _$MEASURE_LIST = $MEASURE_LIST;
  SET _$REMARK_LIST = $REMARK_LIST;

  WHILE LENGTH(_$CUSTCD_LIST) > 0 DO
    CALL COMSPLIT(_$CUSTCD_LIST, _$CUSTCD);
    CALL COMSPLIT(_$ITEMID_LIST, _$ITEMID);
    CALL COMSPLIT(_$OUTCHGTP_LIST, _$OUTCHGTP);
    CALL COMSPLIT(_$NOOUTCAUSE_LIST, _$NOOUTCAUSE);
    CALL COMSPLIT(_$MEASURE_LIST, _$MEASURE);
    CALL COMSPLIT(_$REMARK_LIST, _$REMARK);

    IF IFNULL(_$CUSTCD, '') = '' OR IFNULL(_$ITEMID, '') = '' THEN
      CALL COMERR('거래처나 품목이 없는 줄이 있습니다.');
      LEAVE PROC;
    END IF;

    IF IFNULL(_$OUTCHGTP, '') = '' AND IFNULL(_$NOOUTCAUSE, '') = '' AND IFNULL(_$MEASURE, '') = '' AND IFNULL(_$REMARK, '') = '' THEN
      -- 네 칸이 다 비면 지운다
      DELETE FROM SALOUTRST_M
        WHERE SALOUTRST_M.RSTMONTH = _$MONTH
          AND SALOUTRST_M.CUSTCD = _$CUSTCD
          AND SALOUTRST_M.ITEMID = _$ITEMID;
    ELSE
      INSERT INTO SALOUTRST_M (
          RSTMONTH
        , CUSTCD
        , ITEMID
        , OUTCHGTP
        , NOOUTCAUSE
        , MEASURE
        , REMARK
        , RTIME, REMP, RPRG)
      VALUES (
          _$MONTH
        , _$CUSTCD
        , _$ITEMID
        , IFNULL(_$OUTCHGTP, '')
        , IFNULL(_$NOOUTCAUSE, '')
        , IFNULL(_$MEASURE, '')
        , IFNULL(_$REMARK, '')
        , CALLTIME(), CALLEMP(), CALLPRG()
      )
      ON DUPLICATE KEY UPDATE
          OUTCHGTP = IFNULL(_$OUTCHGTP, '')
        , NOOUTCAUSE = IFNULL(_$NOOUTCAUSE, '')
        , MEASURE = IFNULL(_$MEASURE, '')
        , REMARK = IFNULL(_$REMARK, '')
        , MTIME = CALLTIME()
        , MEMP = CALLEMP()
        , MPRG = CALLPRG();
    END IF;
  END WHILE;

-- ****************************************************************************
WHEN 'DELETE' THEN  -- 상세탭 체크한 품목 줄들의 변동사유·미출고원인·대책·비고 삭제

  IF IFNULL($CUSTCD_LIST, '') = '' THEN
    CALL COMERR('삭제할 품목을 체크하세요.');
    LEAVE PROC;
  END IF;

  SET _$CUSTCD_LIST = $CUSTCD_LIST;
  SET _$ITEMID_LIST = $ITEMID_LIST;

  WHILE LENGTH(_$CUSTCD_LIST) > 0 DO
    CALL COMSPLIT(_$CUSTCD_LIST, _$CUSTCD);
    CALL COMSPLIT(_$ITEMID_LIST, _$ITEMID);

    IF IFNULL(_$CUSTCD, '') = '' OR IFNULL(_$ITEMID, '') = '' THEN
      CALL COMERR('거래처나 품목이 없는 줄이 있습니다.');
      LEAVE PROC;
    END IF;

    DELETE FROM SALOUTRST_M
      WHERE SALOUTRST_M.RSTMONTH = _$MONTH
        AND SALOUTRST_M.CUSTCD = _$CUSTCD
        AND SALOUTRST_M.ITEMID = _$ITEMID;
  END WHILE;

-- ****************************************************************************
END CASE;
-- *****************************************************************************
END
