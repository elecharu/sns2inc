CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.TAL0001_R05(
-- *****************************************************************************
-- Comment: 설비 일상점검 등록 (태블릿)
-- Create: 2026-05-12 : 이대규
-- Modify: 2026-10-23 11:30:      2공장 기준으로 재작성 (설비=MSTEQM.FANO·FACTORYCD '07', 점검항목=일상점검 계획 최신 승인 REV, 작업장·라인 조회조건 추가)
--         2026-10-23 11:50:      라인 조회조건 제거 (작업장만 사용, LIST_LINEEQM·$LINEEQMCD 삭제)
--         2026-10-23 15:24:      공정(EQMTP)·라인(EQMGROUP1) 조회조건 추가 (DC_COMBO EQMTP·EQMGROUP1 콤보 기준)
-- *****************************************************************************
  IN $LINECD          VARCHAR(20),      -- 조회조건 작업장
  IN $EQMTP           VARCHAR(50),      -- 조회조건 공정 (MSTEQM.EQMTP, FM100)
  IN $EQMGROUP1       VARCHAR(50),      -- 조회조건 라인 (MSTEQM.EQMGROUP1, FM113)
  IN $EQMCD           VARCHAR(20),      -- 설비 (MSTEQM.FANO)
  IN $SDATE           VARCHAR(20),
  IN $EDATE           VARCHAR(20),
  IN $EMPCD           VARCHAR(20),      -- 점검자
  IN $CHKRSTKEY       VARCHAR(20),
  IN $BASEDATE        VARCHAR(20),      -- 점검일자
  IN $DATE            VARCHAR(20),      -- 등록일자
  IN $BASETIME        VARCHAR(20),      -- 등록시간 (HH:MM)
  IN $REVCD           VARCHAR(20),      -- 적용 설비 리비전키
  IN $GRPREVCD        VARCHAR(20),      -- 적용 설비그룹 리비전키
  IN $PROBLEM         VARCHAR(1000),
  IN $SOLUTION        VARCHAR(1000),

  IN $PLANTP_LIST     MEDIUMTEXT,
  IN $CHKKNDCD_LIST   MEDIUMTEXT,
  IN $CHKVALUE_LIST   MEDIUMTEXT,
  IN $REMARK_LIST     MEDIUMTEXT,
-- *****************************************************************************
  IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- SET @DEBUGLOGYN = 'Y';
-- *****************************************************************************
  DECLARE _$PLANTP     CHAR(1);
  DECLARE _$CHKKNDCD   VARCHAR(20);
  DECLARE _$CHKVALUE   VARCHAR(1000);
  DECLARE _$REMARK     VARCHAR(1000);

  DECLARE _$EQMGRP     VARCHAR(50);
  DECLARE _$REVCD      VARCHAR(20);
  DECLARE _$GRPREVCD   VARCHAR(20);
  DECLARE _$ITEMREVCD  VARCHAR(20);
  DECLARE _$CHKRSTKEY  VARCHAR(20);
  DECLARE _$ITEMCNT    INT;
  DECLARE _$ROWCNT     INT DEFAULT 0;
-- ****************************************************************************
CASE $CALLTYPE
-- ****************************************************************************
WHEN 'LIST_EQMCD' THEN  -- 설비 목록 (2공장, 작업장·공정·라인 조건)

  SELECT
      MSTEQM.FANO AS EQMCD
    , MSTEQM.EQMNM
  FROM MSTEQM
  WHERE MSTEQM.FACTORYCD = '07'
    AND MSTEQM.USEYN = 'Y'
    AND ($LINECD = '' OR MSTEQM.LINECD = $LINECD)
    AND ($EQMTP = '' OR MSTEQM.EQMTP = $EQMTP)
    AND ($EQMGROUP1 = '' OR MSTEQM.EQMGROUP1 = $EQMGROUP1)
  ORDER BY MSTEQM.FANO
  ;

-- ****************************************************************************
WHEN 'LIST_CHKRSTEQM' THEN  -- 일상점검 실적 목록

  SELECT
      LEFT(CHKRSTEQM.CHKTIME, 16) AS CHKTIME
    , CHKRSTEQM.EMPCD
    , CHKRSTEQM.CHKRSTKEY
  FROM CHKRSTEQM
  WHERE CHKRSTEQM.EQMCD = $EQMCD
    AND CHKRSTEQM.CHKTP = '01'
    AND CHKRSTEQM.BASEDATE BETWEEN $SDATE AND $EDATE
    AND CHKRSTEQM.EMPCD LIKE CONCAT('%', $EMPCD, '%')
  ORDER BY CHKRSTEQM.CHKTIME
  ;

-- ****************************************************************************
WHEN 'LIST_CHKRSTEQMKND' THEN  -- 일상점검 실적 항목

  SELECT
      CHKRSTEQMKND.PLANTP
    , CHKRSTEQMKND.CHKKNDCD
    , CHKRSTEQMKND.CHKKNDNM
    , CHKRSTEQMKND.CHKLOC
    , CHKRSTEQMKND.CHKMTH
    , CHKRSTEQMKND.CHKVALTP
    , CHKRSTEQMKND.CHKVALUE
    , MSTCHKKND.CHKCYCLE
    , CHKRSTEQMKND.REMARK
    , CHKRSTEQMKND.SORTNO
  FROM CHKRSTEQMKND
  LEFT JOIN MSTCHKKND
    ON MSTCHKKND.CHKKNDCD = CHKRSTEQMKND.CHKKNDCD
  WHERE CHKRSTEQMKND.CHKRSTKEY = $CHKRSTKEY
  ORDER BY (CHKRSTEQMKND.PLANTP = 'G') DESC, CHKRSTEQMKND.SORTNO, CHKRSTEQMKND.CHKKNDCD
  ;

-- ****************************************************************************
WHEN 'LIST_PLAN_ITEM' THEN  -- 점검 등록 팝업: 설비그룹·설비의 최신 승인 일상점검 항목

  SET _$EQMGRP = (SELECT IFNULL(MSTEQM.EQMGUBUN, '') FROM MSTEQM
                  WHERE MSTEQM.FANO = $EQMCD AND MSTEQM.FACTORYCD = '07' AND MSTEQM.USEYN = 'Y' LIMIT 1);

  IF _$EQMGRP IS NULL THEN
    CALL COMERR('사용 중인 설비를 선택하세요.');
    LEAVE PROC;
  END IF;

  SET _$GRPREVCD = (SELECT MSTEQMREV_HEADER.REVCD FROM MSTEQMREV_HEADER
                    WHERE MSTEQMREV_HEADER.CHKTP = '01' AND MSTEQMREV_HEADER.PLANTP = 'G' AND MSTEQMREV_HEADER.PLANCD = _$EQMGRP
                      AND MSTEQMREV_HEADER.APRVSTT = 'A'
                    ORDER BY MSTEQMREV_HEADER.REVNUM DESC LIMIT 1);
  SET _$REVCD    = (SELECT MSTEQMREV_HEADER.REVCD FROM MSTEQMREV_HEADER
                    WHERE MSTEQMREV_HEADER.CHKTP = '01' AND MSTEQMREV_HEADER.PLANTP = 'E' AND MSTEQMREV_HEADER.PLANCD = $EQMCD
                      AND MSTEQMREV_HEADER.APRVSTT = 'A'
                    ORDER BY MSTEQMREV_HEADER.REVNUM DESC LIMIT 1);

  IF NOT EXISTS (SELECT 1 FROM MSTEQMREV_DETAIL WHERE MSTEQMREV_DETAIL.REVCD IN (_$GRPREVCD, _$REVCD)) THEN
    CALL COMERR('해당 설비에 승인된 일상점검 항목이 없습니다.');
    LEAVE PROC;
  END IF;

  -- 설비그룹 항목을 먼저, 설비 항목을 뒤에 표시
  SELECT
      'G' AS PLANTP
    , IFNULL(_$REVCD, '') AS REVCD
    , IFNULL(_$GRPREVCD, '') AS GRPREVCD
    , MSTEQMREV_DETAIL.CHKKNDCD
    , MSTEQMREV_DETAIL.CHKKNDNM
    , MSTEQMREV_DETAIL.CHKLOC
    , MSTEQMREV_DETAIL.CHKMTH
    , MSTEQMREV_DETAIL.CHKVALTP
    , MSTEQMREV_DETAIL.CHKCYCLE
    , MSTEQMREV_DETAIL.SORTNO
    , '' AS CHKVALUE
    , '' AS REMARK
  FROM MSTEQMREV_DETAIL
  WHERE MSTEQMREV_DETAIL.REVCD = _$GRPREVCD

  UNION ALL

  SELECT
      'E' AS PLANTP
    , IFNULL(_$REVCD, '') AS REVCD
    , IFNULL(_$GRPREVCD, '') AS GRPREVCD
    , MSTEQMREV_DETAIL.CHKKNDCD
    , MSTEQMREV_DETAIL.CHKKNDNM
    , MSTEQMREV_DETAIL.CHKLOC
    , MSTEQMREV_DETAIL.CHKMTH
    , MSTEQMREV_DETAIL.CHKVALTP
    , MSTEQMREV_DETAIL.CHKCYCLE
    , MSTEQMREV_DETAIL.SORTNO
    , '' AS CHKVALUE
    , '' AS REMARK
  FROM MSTEQMREV_DETAIL
  WHERE MSTEQMREV_DETAIL.REVCD = _$REVCD

  ORDER BY PLANTP DESC, SORTNO, CHKKNDCD
  ;

-- ****************************************************************************
WHEN 'ADD_CHKRSTEQM' THEN  -- 일상점검 등록

  IF $EQMCD = '' THEN
    CALL COMERR('설비를 선택하세요.');
    LEAVE PROC;
  END IF;

  IF $EMPCD = '' THEN
    CALL COMERR('점검자를 선택하세요.');
    LEAVE PROC;
  END IF;

  IF $BASEDATE = '' THEN
    CALL COMERR('점검일자를 지정하세요.');
    LEAVE PROC;
  END IF;

  IF $DATE = '' OR $BASETIME = '' THEN
    CALL COMERR('등록일자와 등록시간을 지정하세요.');
    LEAVE PROC;
  END IF;

  IF $CHKKNDCD_LIST = '' THEN
    CALL COMERR('일상점검 항목이 없습니다.');
    LEAVE PROC;
  END IF;

  SET _$EQMGRP = (SELECT IFNULL(MSTEQM.EQMGUBUN, '') FROM MSTEQM
                  WHERE MSTEQM.FANO = $EQMCD AND MSTEQM.FACTORYCD = '07' AND MSTEQM.USEYN = 'Y' LIMIT 1);

  IF _$EQMGRP IS NULL THEN
    CALL COMERR('사용 중인 설비를 선택하세요.');
    LEAVE PROC;
  END IF;

  -- 팝업에서 조회한 승인 REV 가 지금도 최신 승인본인지 확인
  SET _$GRPREVCD = (SELECT MSTEQMREV_HEADER.REVCD FROM MSTEQMREV_HEADER
                    WHERE MSTEQMREV_HEADER.CHKTP = '01' AND MSTEQMREV_HEADER.PLANTP = 'G' AND MSTEQMREV_HEADER.PLANCD = _$EQMGRP
                      AND MSTEQMREV_HEADER.APRVSTT = 'A'
                    ORDER BY MSTEQMREV_HEADER.REVNUM DESC LIMIT 1);
  SET _$REVCD    = (SELECT MSTEQMREV_HEADER.REVCD FROM MSTEQMREV_HEADER
                    WHERE MSTEQMREV_HEADER.CHKTP = '01' AND MSTEQMREV_HEADER.PLANTP = 'E' AND MSTEQMREV_HEADER.PLANCD = $EQMCD
                      AND MSTEQMREV_HEADER.APRVSTT = 'A'
                    ORDER BY MSTEQMREV_HEADER.REVNUM DESC LIMIT 1);

  IF IFNULL(_$GRPREVCD, '') <> $GRPREVCD OR IFNULL(_$REVCD, '') <> $REVCD THEN
    CALL COMERR('일상점검 계획이 변경되었습니다. 점검 창을 다시 열어주세요.');
    LEAVE PROC;
  END IF;

  SET _$ITEMCNT = (SELECT COUNT(*) FROM MSTEQMREV_DETAIL WHERE MSTEQMREV_DETAIL.REVCD IN (_$GRPREVCD, _$REVCD));

  SET _$CHKRSTKEY = GETKEY('CHKRSTKEY');

  INSERT INTO CHKRSTEQM (
      CHKRSTKEY, CHKTP, EQMCD, EMPCD, BASEDATE
    , BASEWGTP, CHKTIME, REVCD, GRPREVCD
    , PROBLEM, SOLUTION, REMARK
    , RTIME, REMP, RPRG)
  VALUES (
      _$CHKRSTKEY, '01', $EQMCD, $EMPCD, $BASEDATE
    , '', CONCAT($DATE, ' ', $BASETIME, ':00'), IFNULL(_$REVCD, ''), IFNULL(_$GRPREVCD, '')
    , '', '', ''
    , CALLTIME(), CALLEMP(), CALLPRG());

  WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
    CALL COMSPLIT($PLANTP_LIST, _$PLANTP);
    CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);
    CALL COMSPLIT($CHKVALUE_LIST, _$CHKVALUE);
    CALL COMSPLIT($REMARK_LIST, _$REMARK);

    SET _$ITEMREVCD = IF(_$PLANTP = 'G', _$GRPREVCD, _$REVCD);

    IF NOT EXISTS (SELECT 1 FROM MSTEQMREV_DETAIL WHERE MSTEQMREV_DETAIL.REVCD = _$ITEMREVCD AND MSTEQMREV_DETAIL.CHKKNDCD = _$CHKKNDCD) THEN
      CALL COMERR('승인된 계획에 없는 점검항목입니다. 점검 창을 다시 열어주세요.');
      LEAVE PROC;
    END IF;

    IF TRIM(_$CHKVALUE) = '' THEN
      CALL COMERR('점검값을 모두 입력하세요.');
      LEAVE PROC;
    END IF;

    -- 승인본의 항목정보를 그대로 저장
    INSERT INTO CHKRSTEQMKND (
        CHKRSTKEY, PLANTP, CHKKNDCD, CHKKNDNM
      , CHKLOC, CHKMTH, CHKVALTP
      , SORTNO, CHKVALUE, REMARK
      , RTIME, REMP, RPRG)
    SELECT
        _$CHKRSTKEY, _$PLANTP, MSTEQMREV_DETAIL.CHKKNDCD, MSTEQMREV_DETAIL.CHKKNDNM
      , MSTEQMREV_DETAIL.CHKLOC, MSTEQMREV_DETAIL.CHKMTH, MSTEQMREV_DETAIL.CHKVALTP
      , MSTEQMREV_DETAIL.SORTNO, _$CHKVALUE, _$REMARK
      , CALLTIME(), CALLEMP(), CALLPRG()
    FROM MSTEQMREV_DETAIL
    WHERE MSTEQMREV_DETAIL.REVCD = _$ITEMREVCD
      AND MSTEQMREV_DETAIL.CHKKNDCD = _$CHKKNDCD
    ;

    SET _$ROWCNT = _$ROWCNT + 1;
  END WHILE;

  IF _$ROWCNT <> _$ITEMCNT THEN
    CALL COMERR('승인된 계획의 모든 점검항목을 입력하세요. 점검 창을 다시 열어주세요.');
    LEAVE PROC;
  END IF;

-- ****************************************************************************
WHEN 'LIST_CHKRSTEQM_EDIT' THEN  -- 수정 팝업: 실적 헤더·항목

  SELECT
      CHKRSTEQMKND.PLANTP
    , CHKRSTEQMKND.CHKKNDCD
    , CHKRSTEQMKND.CHKKNDNM
    , CHKRSTEQMKND.CHKLOC
    , CHKRSTEQMKND.CHKMTH
    , CHKRSTEQMKND.CHKVALTP
    , MSTCHKKND.CHKCYCLE
    , CHKRSTEQMKND.CHKVALUE
    , CHKRSTEQMKND.REMARK
    , CHKRSTEQMKND.SORTNO
    , CHKRSTEQM.EQMCD
    , CHKRSTEQM.BASEDATE
    , CHKRSTEQM.EMPCD
    , LEFT(CHKRSTEQM.CHKTIME, 10) AS DATE
    , SUBSTRING(CHKRSTEQM.CHKTIME, 12, 5) AS TIME
  FROM CHKRSTEQMKND
  INNER JOIN CHKRSTEQM
    ON CHKRSTEQM.CHKRSTKEY = CHKRSTEQMKND.CHKRSTKEY
  LEFT JOIN MSTCHKKND
    ON MSTCHKKND.CHKKNDCD = CHKRSTEQMKND.CHKKNDCD
  WHERE CHKRSTEQMKND.CHKRSTKEY = $CHKRSTKEY
    AND CHKRSTEQM.CHKTP = '01'
  ORDER BY (CHKRSTEQMKND.PLANTP = 'G') DESC, CHKRSTEQMKND.SORTNO, CHKRSTEQMKND.CHKKNDCD
  ;

-- ****************************************************************************
WHEN 'SAVE_CHKRSTEQM' THEN  -- 일상점검 수정

  IF $EMPCD = '' THEN
    CALL COMERR('점검자를 선택하세요.');
    LEAVE PROC;
  END IF;

  IF $BASEDATE = '' THEN
    CALL COMERR('점검일자를 지정하세요.');
    LEAVE PROC;
  END IF;

  IF $DATE = '' OR $BASETIME = '' THEN
    CALL COMERR('등록일자와 등록시간을 지정하세요.');
    LEAVE PROC;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM CHKRSTEQM WHERE CHKRSTEQM.CHKRSTKEY = $CHKRSTKEY AND CHKRSTEQM.EQMCD = $EQMCD AND CHKRSTEQM.CHKTP = '01') THEN
    CALL COMERR('수정할 일상점검 실적이 없습니다. 다시 조회하세요.');
    LEAVE PROC;
  END IF;

  UPDATE CHKRSTEQM
  SET EMPCD = $EMPCD
    , BASEDATE = $BASEDATE
    , CHKTIME = CONCAT($DATE, ' ', $BASETIME, ':00')
    , MTIME = CALLTIME()
    , MEMP = CALLEMP()
    , MPRG = CALLPRG()
  WHERE CHKRSTEQM.CHKRSTKEY = $CHKRSTKEY
  ;

  WHILE LENGTH($CHKKNDCD_LIST) > 0 DO
    CALL COMSPLIT($PLANTP_LIST, _$PLANTP);
    CALL COMSPLIT($CHKKNDCD_LIST, _$CHKKNDCD);
    CALL COMSPLIT($CHKVALUE_LIST, _$CHKVALUE);
    CALL COMSPLIT($REMARK_LIST, _$REMARK);

    IF TRIM(_$CHKVALUE) = '' THEN
      CALL COMERR('점검값을 모두 입력하세요.');
      LEAVE PROC;
    END IF;

    UPDATE CHKRSTEQMKND
    SET CHKVALUE = _$CHKVALUE
      , REMARK = _$REMARK
      , MTIME = CALLTIME()
      , MEMP = CALLEMP()
      , MPRG = CALLPRG()
    WHERE CHKRSTEQMKND.CHKRSTKEY = $CHKRSTKEY
      AND CHKRSTEQMKND.PLANTP = _$PLANTP
      AND CHKRSTEQMKND.CHKKNDCD = _$CHKKNDCD
    ;
  END WHILE;

-- ****************************************************************************
WHEN 'DELETE_CHKRSTEQM' THEN  -- 일상점검 삭제

  IF NOT EXISTS (SELECT 1 FROM CHKRSTEQM WHERE CHKRSTEQM.CHKRSTKEY = $CHKRSTKEY AND CHKRSTEQM.EQMCD = $EQMCD AND CHKRSTEQM.CHKTP = '01') THEN
    CALL COMERR('삭제할 일상점검 실적이 없습니다. 다시 조회하세요.');
    LEAVE PROC;
  END IF;

  DELETE FROM CHKRSTEQMKND WHERE CHKRSTEQMKND.CHKRSTKEY = $CHKRSTKEY;
  DELETE FROM CHKRSTEQM WHERE CHKRSTEQM.CHKRSTKEY = $CHKRSTKEY;

-- ****************************************************************************
WHEN 'LIST_ERR' THEN  -- 문제점/조치사항 조회

  SELECT
      CHKRSTEQM.PROBLEM
    , CHKRSTEQM.SOLUTION
  FROM CHKRSTEQM
  WHERE CHKRSTEQM.CHKRSTKEY = $CHKRSTKEY
    AND CHKRSTEQM.EQMCD = $EQMCD
    AND CHKRSTEQM.CHKTP = '01'
  ;

-- ****************************************************************************
WHEN 'SAVE_ERR' THEN  -- 문제점/조치사항 저장

  UPDATE CHKRSTEQM
  SET PROBLEM = $PROBLEM
    , SOLUTION = $SOLUTION
    , MTIME = CALLTIME()
    , MEMP = CALLEMP()
    , MPRG = CALLPRG()
  WHERE CHKRSTEQM.CHKRSTKEY = $CHKRSTKEY
    AND CHKRSTEQM.EQMCD = $EQMCD
    AND CHKRSTEQM.CHKTP = '01'
  ;

-- ****************************************************************************
END CASE; END
