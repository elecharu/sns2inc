CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.TML1010_R03(
-- *****************************************************************************
-- Comment: 무상사급 생산실적 등록 (외주처 현장)
-- Create: 2026-09-29 김영철
-- Modify: 2026-11-09: TML2010_R01(사내 생산실적등록)과 같은 방식으로 변경
-- Modify: 2026-11-16: 사내 계정은 외주작업장을 선택 (화면에서 작업장 콤보 REF02 = '*', 외주처는 작업장의 OSCCUSTCD 로 설정), WORK_DONE 에 외주처·작업장 일치 확인
--                     작업장 = 로그인 외주처의 작업장 고정 (화면 작업장 콤보 DC_COMBO LINECD 의 REF02 = 외주처), 공정 선택, 설비 없음(EQMCD '')
--                     투입바코드 스캔 → BOM·라우팅 확인(같은 작업장의 다른 공정이면 기본공정으로 자동변경 안내)
--                     작업완료 → IO_PRDRST_OSC_LOT (스캔 LOT·사용량으로 외주실적 OSCRST), 실적삭제, 공정이동표(TMLPRINT.PRD_1)
-- *****************************************************************************
  IN $CUSTCD       VARCHAR(100),   -- 외주처 (로그인)
  IN $LINECD       VARCHAR(100),   -- 작업장
  IN $PRCCD        VARCHAR(100),   -- 공정
  IN $SCANLOT      VARCHAR(100),   -- 투입바코드
  IN $ITEMID       VARCHAR(100),   -- 생산품
  IN $DNTP         VARCHAR(100),   -- 주야구분 (PP161)
  IN $WORKSDAY     VARCHAR(10),    -- 작업시작일
  IN $WORKSTIME    VARCHAR(8),     -- 작업시작시간
  IN $WORKEDAY     VARCHAR(10),    -- 작업종료일
  IN $WORKETIME    VARCHAR(8),     -- 작업종료시간
  IN $LOTKEY_LIST  MEDIUMTEXT,     -- 투입 LOT
  IN $USEQTY_LIST  MEDIUMTEXT,     -- 투입 LOT 별 사용량
  IN $OSCRSTKEY    VARCHAR(100),   -- 외주실적키 (실적삭제)
  IN $LOTKEY       VARCHAR(100),   -- 실적로트 (공정이동표)
-- *****************************************************************************
  IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- SET @DEBUGLOGYN = 'Y';
-- *****************************************************************************

  DECLARE _$WARECD    VARCHAR(100);
  DECLARE _$ITEMID    VARCHAR(100);
  DECLARE _$GROUPKEY  VARCHAR(100);
  DECLARE _$LVL       INT;

-- ****************************************************************************
CASE $CALLTYPE

-- ****************************************************************************
WHEN 'SCAN_LOT' THEN -- 투입바코드 스캔 : 재고 확인 → BOM·라우팅 확인 → 생산품 목록

  IF IFNULL($LINECD, '') = '' THEN
    CALL COMERR('생산작업장이 없습니다.');
    LEAVE PROC;
  END IF;

  IF IFNULL($PRCCD, '') = '' THEN
    CALL COMERR('생산공정을 선택하세요.');
    LEAVE PROC;
  END IF;

  IF IFNULL($SCANLOT, '') = '' THEN
    CALL COMERR('로트번호가 없습니다.');
    LEAVE PROC;
  END IF;

  -- 투입 LOT 는 이 작업장의 투입창고(원자재·반제품 출고창고)에 있어야 함
  SET _$WARECD = (SELECT COMLOT.WARECD
                    FROM COMLOT
                    WHERE COMLOT.LOTKEY = $SCANLOT
                      AND COMLOT.WARECD IN (SELECT MSTLINE_PRC.PART_OUT_WH FROM MSTLINE_PRC WHERE MSTLINE_PRC.LINECD = $LINECD
                                            UNION
                                            SELECT MSTLINE_PRC.SEMI_OUT_WH FROM MSTLINE_PRC WHERE MSTLINE_PRC.LINECD = $LINECD)
                    ORDER BY COMLOT.LOTQTY DESC
                    LIMIT 1);

  IF IFNULL(_$WARECD, '') = '' THEN
    CALL COMERR(CONCAT('외주처 창고에 없는 로트번호입니다.', '\n- 로트번호: ', $SCANLOT));
    LEAVE PROC;
  END IF;

  IF (SELECT COMLOT.LOTQTY FROM COMLOT WHERE COMLOT.LOTKEY = $SCANLOT AND COMLOT.WARECD = _$WARECD) <= 0 THEN
    CALL COMERR(CONCAT('재고수량이 0 입니다.'
                      , '\n- 창고: ', (SELECT MSTWARE.WARENM FROM MSTWARE WHERE MSTWARE.WARECD = _$WARECD)
                      , '\n- 로트번호: ', $SCANLOT));
    LEAVE PROC;
  END IF;

  SET _$ITEMID = (SELECT COMLOT.ITEMID FROM COMLOT WHERE COMLOT.LOTKEY = $SCANLOT AND COMLOT.WARECD = _$WARECD);

  -- 1. BOM 으로 모품목
  IF NOT EXISTS (SELECT MSTBOM.MITEMID
                   FROM MSTBOM
                   WHERE MSTBOM.CITEMID = _$ITEMID
                     AND MSTBOM.USEYN = 'Y'
                     AND (MSTBOM.USETODT IS NULL OR MSTBOM.USETODT = '' OR LEFT(MSTBOM.USETODT, 4) = '9999')) THEN
    CALL COMERR(CONCAT('BOM에 등록된 모품목이 없습니다.'
                      , '\n- 품목코드: ', (SELECT MSTITEM.ITEMCD FROM MSTITEM WHERE MSTITEM.ITEMID = _$ITEMID)
                      , '\n- 품명: ', (SELECT MSTITEM.ITEMNM FROM MSTITEM WHERE MSTITEM.ITEMID = _$ITEMID)));
    LEAVE PROC;
  END IF;

  -- 2. 선택한 작업장·공정에서 생산하는 모품목이 있는지 (기본 라우팅)
  IF NOT EXISTS (SELECT MSTBOM.MITEMID
                   FROM MSTBOM
                   INNER JOIN MSTROUT_MATCH ON MSTROUT_MATCH.ITEMID = MSTBOM.MITEMID
                   INNER JOIN MSTROUT_DETAIL ON MSTROUT_DETAIL.ROUTCD = MSTROUT_MATCH.ROUTCD
                                            AND MSTROUT_DETAIL.LINCD = $LINECD
                                            AND MSTROUT_DETAIL.PRCCD = $PRCCD
                   INNER JOIN MSTROUT ON MSTROUT.ROUTCD = MSTROUT_MATCH.ROUTCD
                   WHERE MSTBOM.CITEMID = _$ITEMID
                     AND MSTBOM.USEYN = 'Y'
                     AND (MSTBOM.USETODT IS NULL OR MSTBOM.USETODT = '' OR LEFT(MSTBOM.USETODT, 4) = '9999')
                     AND MSTROUT_MATCH.BASEYN = 'Y'
                     AND MSTROUT.USEYN = 'Y') THEN

    -- 같은 작업장(외주처)의 다른 공정으로 라우팅되어 있으면 그 공정으로 자동변경 안내 (외주처는 작업장을 바꾸지 않음)
    IF NOT EXISTS (SELECT MSTBOM.MITEMID
                     FROM MSTBOM
                     INNER JOIN MSTROUT_MATCH ON MSTROUT_MATCH.ITEMID = MSTBOM.MITEMID
                     INNER JOIN MSTROUT_DETAIL ON MSTROUT_DETAIL.ROUTCD = MSTROUT_MATCH.ROUTCD
                                              AND MSTROUT_DETAIL.LINCD = $LINECD
                     INNER JOIN MSTROUT ON MSTROUT.ROUTCD = MSTROUT_MATCH.ROUTCD
                     WHERE MSTBOM.CITEMID = _$ITEMID
                       AND MSTBOM.USEYN = 'Y'
                       AND (MSTBOM.USETODT IS NULL OR MSTBOM.USETODT = '' OR LEFT(MSTBOM.USETODT, 4) = '9999')
                       AND MSTROUT_MATCH.BASEYN = 'Y'
                       AND MSTROUT.USEYN = 'Y') THEN
      CALL COMERR(CONCAT('이 작업장에서 스캔한 투입품목으로 생산하도록 지정된 라우팅이 없습니다.'
                        , '\n- 품목코드: ', (SELECT MSTITEM.ITEMCD FROM MSTITEM WHERE MSTITEM.ITEMID = _$ITEMID)
                        , '\n- 품명: ', (SELECT MSTITEM.ITEMNM FROM MSTITEM WHERE MSTITEM.ITEMID = _$ITEMID)
                        , '\n- 작업장: ', IFNULL((SELECT MSTLINE.LINENM FROM MSTLINE WHERE MSTLINE.LINECD = $LINECD), $LINECD)));
      LEAVE PROC;
    END IF;

    SELECT
        'NO_BOM' AS RESULT
      , MSTROUT_DETAIL.LINCD AS LINECD
      , MSTROUT_DETAIL.PRCCD
      , CONCAT('품목 : ', (SELECT MSTITEM.ITEMCD FROM MSTITEM WHERE MSTITEM.ITEMID = _$ITEMID)
              , '\n작업장 : ', IFNULL((SELECT MSTLINE.LINENM FROM MSTLINE WHERE MSTLINE.LINECD = $LINECD), $LINECD)
              , ', 공정 : ', IFNULL((SELECT MSTPRC.PRCNM FROM MSTPRC WHERE MSTPRC.PRCCD = $PRCCD), $PRCCD)
              , '\n선택한 작업장 및 공정으로 지정된 라우팅이 없습니다.\n'
              , '\n기본작업장 : ', IFNULL(MSTLINE.LINENM, MSTROUT_DETAIL.LINCD), ', 기본공정 : ', IFNULL(MSTPRC.PRCNM, MSTROUT_DETAIL.PRCCD)
              , '\n해당 작업장 및 기본공정으로 자동변경됩니다.\n스캔을 다시 진행해주세요.') AS MSG
    FROM MSTBOM
    INNER JOIN MSTROUT_MATCH ON MSTROUT_MATCH.ITEMID = MSTBOM.MITEMID
    INNER JOIN MSTROUT_DETAIL ON MSTROUT_DETAIL.ROUTCD = MSTROUT_MATCH.ROUTCD
                             AND MSTROUT_DETAIL.LINCD = $LINECD
    INNER JOIN MSTROUT ON MSTROUT.ROUTCD = MSTROUT_MATCH.ROUTCD
    LEFT JOIN MSTLINE ON MSTLINE.LINECD = MSTROUT_DETAIL.LINCD
    LEFT JOIN MSTPRC ON MSTPRC.PRCCD = MSTROUT_DETAIL.PRCCD
    WHERE MSTBOM.CITEMID = _$ITEMID
      AND MSTBOM.USEYN = 'Y'
      AND (MSTBOM.USETODT IS NULL OR MSTBOM.USETODT = '' OR LEFT(MSTBOM.USETODT, 4) = '9999')
      AND MSTROUT_MATCH.BASEYN = 'Y'
      AND MSTROUT.USEYN = 'Y'
    ORDER BY MSTROUT.ROUTCD
    LIMIT 1;

  ELSE
    -- 3. 생산품 목록 (2개 이상이면 화면에서 선택)
    SELECT
        'YES_BOM' AS RESULT
      , CAST(MSTITEM.ITEMID AS CHAR) AS ITEMID
      , MSTITEM.ITEMCD
      , MSTITEM.ITEMNM
      , MSTITEM.ITEMSPEC
      , $SCANLOT AS LOTKEY
    FROM MSTBOM
    INNER JOIN MSTITEM ON MSTITEM.ITEMID = MSTBOM.MITEMID
    INNER JOIN MSTROUT_MATCH ON MSTROUT_MATCH.ITEMID = MSTBOM.MITEMID
    INNER JOIN MSTROUT_DETAIL ON MSTROUT_DETAIL.ROUTCD = MSTROUT_MATCH.ROUTCD
                             AND MSTROUT_DETAIL.LINCD = $LINECD
                             AND MSTROUT_DETAIL.PRCCD = $PRCCD
    INNER JOIN MSTROUT ON MSTROUT.ROUTCD = MSTROUT_MATCH.ROUTCD
    WHERE MSTBOM.CITEMID = _$ITEMID
      AND MSTBOM.USEYN = 'Y'
      AND (MSTBOM.USETODT IS NULL OR MSTBOM.USETODT = '' OR LEFT(MSTBOM.USETODT, 4) = '9999')
      AND MSTROUT_MATCH.BASEYN = 'Y'
      AND MSTROUT.USEYN = 'Y'
    GROUP BY MSTITEM.ITEMID
    ORDER BY MSTITEM.ITEMCD;
  END IF;

-- ****************************************************************************
WHEN 'SET_LINEITEM' THEN -- 생산품 선택

  IF IFNULL($LINECD, '') = '' OR IFNULL($PRCCD, '') = '' THEN
    CALL COMERR('생산작업장·공정을 선택하세요.');
    LEAVE PROC;
  END IF;

  IF IFNULL($ITEMID, '') = '' THEN
    CALL COMERR('생산품목을 선택하세요.');
    LEAVE PROC;
  END IF;

  INSERT INTO PRDLINEITEM (LINECD, PRCCD, EQMCD, ITEMID, INPUTTIME, RTIME, REMP, RPRG)
  VALUES ($LINECD, $PRCCD, '', $ITEMID, CALLTIME(), CALLTIME(), CALLEMP(), CALLPRG())
  ON DUPLICATE KEY UPDATE
      ITEMID    = $ITEMID
    , INPUTTIME = CALLTIME()
    , MTIME     = CALLTIME()
    , MEMP      = CALLEMP()
    , MPRG      = CALLPRG();

-- ****************************************************************************
WHEN 'ADD_INPUT' THEN -- 투입 LOT 등록

  IF IFNULL($LINECD, '') = '' OR IFNULL($PRCCD, '') = '' THEN
    CALL COMERR('생산작업장·공정을 선택하세요.');
    LEAVE PROC;
  END IF;

  IF IFNULL($SCANLOT, '') = '' THEN
    CALL COMERR('로트번호가 없습니다.');
    LEAVE PROC;
  END IF;

  SET _$WARECD = (SELECT COMLOT.WARECD
                    FROM COMLOT
                    WHERE COMLOT.LOTKEY = $SCANLOT
                      AND COMLOT.LOTQTY > 0
                      AND COMLOT.WARECD IN (SELECT MSTLINE_PRC.PART_OUT_WH FROM MSTLINE_PRC WHERE MSTLINE_PRC.LINECD = $LINECD
                                            UNION
                                            SELECT MSTLINE_PRC.SEMI_OUT_WH FROM MSTLINE_PRC WHERE MSTLINE_PRC.LINECD = $LINECD)
                    ORDER BY COMLOT.LOTQTY DESC
                    LIMIT 1);

  IF IFNULL(_$WARECD, '') = '' THEN
    CALL COMERR(CONCAT('외주처 창고에 재고가 없는 로트번호입니다.', '\n- 로트번호: ', $SCANLOT));
    LEAVE PROC;
  END IF;

  IF EXISTS (SELECT 1 FROM PRDLINESCAN
               WHERE PRDLINESCAN.LINECD = $LINECD AND PRDLINESCAN.PRCCD = $PRCCD AND PRDLINESCAN.EQMCD = ''
                 AND PRDLINESCAN.LOTKEY = $SCANLOT) THEN
    CALL COMERR(CONCAT('이미 투입된 로트입니다.', '\n- 로트번호: ', $SCANLOT));
    LEAVE PROC;
  END IF;

  INSERT INTO PRDLINESCAN (LINECD, PRCCD, EQMCD, WARECD, LOTKEY, SCANTIME, RTIME, REMP, RPRG)
  VALUES ($LINECD, $PRCCD, '', _$WARECD, $SCANLOT, CALLTIME(), CALLTIME(), CALLEMP(), CALLPRG());

-- ****************************************************************************
WHEN 'LIST_INPUT' THEN -- 투입 LOT, 생산품, 최근 실적

  IF IFNULL($LINECD, '') = '' OR IFNULL($PRCCD, '') = '' THEN
    CALL COMERR('생산작업장·공정을 선택하세요.');
    LEAVE PROC;
  END IF;

  -- [0] 투입 LOT (사용량 기본값 = 재고수량)
  SELECT
      MSTITEM.ITEMID
    , MSTITEM.ITEMCD
    , MSTITEM.ITEMNM
    , MSTITEM.ITEMSPEC
    , GPCD('DM100', MSTITEM.ITEMCG) AS ITEMCG
    , GPCD('DM150', MSTITEM.ITEMUNIT) AS ITEMUNIT
    , COMLOT.LOTKEY
    , COMLOT.LOTQTY
    , COMLOT.LOTQTY AS USEQTY
    , IFNULL(COMLOT.HEATNO, '') AS HEATNO
    , COMLOT.WARECD
  FROM PRDLINESCAN
  INNER JOIN COMLOT ON COMLOT.WARECD = PRDLINESCAN.WARECD
                   AND COMLOT.LOTKEY = PRDLINESCAN.LOTKEY
  INNER JOIN MSTITEM ON MSTITEM.ITEMID = COMLOT.ITEMID
  WHERE PRDLINESCAN.LINECD = $LINECD
    AND PRDLINESCAN.PRCCD = $PRCCD
    AND PRDLINESCAN.EQMCD = ''
  ORDER BY PRDLINESCAN.SCANTIME;

  -- [1] 생산품
  SELECT
      CAST(MSTITEM.ITEMID AS CHAR) AS ITEMID
    , MSTITEM.ITEMCD
    , MSTITEM.ITEMNM
    , MSTITEM.ITEMSPEC
  FROM PRDLINEITEM
  INNER JOIN MSTITEM ON MSTITEM.ITEMID = PRDLINEITEM.ITEMID
  WHERE PRDLINEITEM.LINECD = $LINECD
    AND PRDLINEITEM.PRCCD = $PRCCD
    AND PRDLINEITEM.EQMCD = '';

  -- [2] 이 작업장의 최근 실적 (어제·오늘, 실적삭제·공정이동표 재출력용)
  SELECT
      OSCRST.OSCRSTKEY
    , LEFT(OSCRST.RSTTIME, 16) AS RSTTIME
    , IFNULL(MSTPRC.PRCNM, OSCRST.PRCCD) AS PRCNM
    , MSTITEM.ITEMCD
    , MSTITEM.ITEMNM
    , OSCRST.GOODQTY
    , SUBSTRING_INDEX(IFNULL(GPCD('PP161', OSCRST.DNTP), ''), '(', 1) AS DNTPNM  -- 주간 / 야간 (시간대는 빼고)
    , IFNULL((SELECT OSCRSTLOT.LOTKEY FROM OSCRSTLOT WHERE OSCRSTLOT.OSCRSTKEY = OSCRST.OSCRSTKEY AND OSCRSTLOT.LOTTP = '01' LIMIT 1), '') AS LOTKEY
  FROM OSCRST
  INNER JOIN MSTITEM ON MSTITEM.ITEMID = OSCRST.ITEMID
  LEFT JOIN MSTPRC ON MSTPRC.PRCCD = OSCRST.PRCCD
  WHERE OSCRST.LINECD = $LINECD
    AND OSCRST.RSTTIME >= DATE_FORMAT(DATE_SUB(GETDATE(), INTERVAL 1 DAY), '%Y-%m-%d')
  ORDER BY OSCRST.RSTTIME DESC;

-- ****************************************************************************
WHEN 'DEL_INPUT' THEN -- 투입 LOT 삭제

  IF IFNULL($LINECD, '') = '' OR IFNULL($PRCCD, '') = '' OR IFNULL($SCANLOT, '') = '' THEN
    CALL COMERR('삭제할 투입 LOT 가 없습니다.');
    LEAVE PROC;
  END IF;

  DELETE FROM PRDLINESCAN
   WHERE PRDLINESCAN.LINECD = $LINECD
     AND PRDLINESCAN.PRCCD = $PRCCD
     AND PRDLINESCAN.EQMCD = ''
     AND PRDLINESCAN.LOTKEY = $SCANLOT;

  -- 남은 투입 LOT 가 없으면 생산품도 비움
  IF NOT EXISTS (SELECT 1 FROM PRDLINESCAN
                   WHERE PRDLINESCAN.LINECD = $LINECD AND PRDLINESCAN.PRCCD = $PRCCD AND PRDLINESCAN.EQMCD = '') THEN
    DELETE FROM PRDLINEITEM
     WHERE PRDLINEITEM.LINECD = $LINECD
       AND PRDLINEITEM.PRCCD = $PRCCD
       AND PRDLINEITEM.EQMCD = '';
  END IF;

-- ****************************************************************************
WHEN 'CLEAR_INPUT' THEN -- 초기화 : 투입 LOT·생산품 모두 비움

  IF IFNULL($LINECD, '') = '' OR IFNULL($PRCCD, '') = '' THEN
    CALL COMERR('생산작업장·공정을 선택하세요.');
    LEAVE PROC;
  END IF;

  DELETE FROM PRDLINESCAN
   WHERE PRDLINESCAN.LINECD = $LINECD
     AND PRDLINESCAN.PRCCD = $PRCCD
     AND PRDLINESCAN.EQMCD = '';

  DELETE FROM PRDLINEITEM
   WHERE PRDLINEITEM.LINECD = $LINECD
     AND PRDLINEITEM.PRCCD = $PRCCD
     AND PRDLINEITEM.EQMCD = '';

-- ****************************************************************************
WHEN 'WORK_DONE' THEN -- 작업완료 (외주실적 등록)

  -- 외주처() 는 작업장()의 외주처여야 함 (사내 계정이 외주작업장을 선택한 경우 화면이 작업장의 외주처를 넘김)
  IF NOT EXISTS (SELECT 1 FROM MSTLINE WHERE MSTLINE.LINECD = $LINECD AND MSTLINE.OSCCUSTCD = $CUSTCD AND MSTLINE.OSCCUSTCD <> '') THEN
    CALL COMERR('선택한 작업장이 외주처의 작업장이 아닙니다.');
    LEAVE PROC;
  END IF;

  CALL IO_PRDRST_OSC_LOT($CUSTCD, $LINECD, $PRCCD, $ITEMID, $DNTP
                        , $WORKSDAY, $WORKSTIME, $WORKEDAY, $WORKETIME
                        , $LOTKEY_LIST, $USEQTY_LIST);

-- ****************************************************************************
WHEN 'DEL_RST' THEN -- 실적삭제 (실적로트를 아직 쓰지 않았을 때만)

  IF IFNULL($OSCRSTKEY, '') = '' THEN
    CALL COMERR('삭제할 실적을 선택하세요.');
    LEAVE PROC;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM OSCRST WHERE OSCRST.OSCRSTKEY = $OSCRSTKEY AND OSCRST.LINECD = $LINECD) THEN
    CALL COMERR('이 작업장의 실적이 아닙니다.');
    LEAVE PROC;
  END IF;

  -- 실적로트가 이동·투입되었으면 삭제 불가
  IF EXISTS (SELECT 1
               FROM OSCRSTLOT
               LEFT JOIN COMLOT ON COMLOT.LOTKEY = OSCRSTLOT.LOTKEY
                               AND COMLOT.OSCRSTKEY = OSCRSTLOT.OSCRSTKEY
               WHERE OSCRSTLOT.OSCRSTKEY = $OSCRSTKEY
                 AND (COMLOT.LOTKEY IS NULL OR COMLOT.LOTQTY <> COMLOT.CRTQTY)) THEN
    CALL COMERR('실적로트를 이미 사용(이동·투입)하여 삭제할 수 없습니다.');
    LEAVE PROC;
  END IF;

  SET _$GROUPKEY = (SELECT COMIN.GROUPKEY FROM COMIN WHERE COMIN.OSCRSTKEY = $OSCRSTKEY LIMIT 1);

  -- 1. 실적로트 입고이력
  DELETE FROM COMINLOT WHERE COMINLOT.INKEY IN (SELECT COMIN.INKEY FROM COMIN WHERE COMIN.OSCRSTKEY = $OSCRSTKEY);
  DELETE FROM COMIN WHERE COMIN.OSCRSTKEY = $OSCRSTKEY;

  -- 2. 실적로트
  DELETE COMLOT
    FROM COMLOT
    INNER JOIN OSCRSTLOT ON OSCRSTLOT.LOTKEY = COMLOT.LOTKEY
    WHERE OSCRSTLOT.OSCRSTKEY = $OSCRSTKEY
      AND COMLOT.OSCRSTKEY = $OSCRSTKEY;

  -- 3. 투입 LOT 재고 원복, 자재출고이력
  UPDATE COMLOT
   INNER JOIN OSCRSTUSE ON OSCRSTUSE.USELOTKEY = COMLOT.LOTKEY
                       AND OSCRSTUSE.USEWARECD = COMLOT.WARECD
     SET COMLOT.LOTQTY = COMLOT.LOTQTY + OSCRSTUSE.USEQTY
       , COMLOT.MTIME  = CALLTIME()
       , COMLOT.MEMP   = CALLEMP()
       , COMLOT.MPRG   = CALLPRG()
   WHERE OSCRSTUSE.OSCRSTKEY = $OSCRSTKEY;

  DELETE FROM COMOUTLOT WHERE COMOUTLOT.OUTKEY IN (SELECT COMOUT.OUTKEY FROM COMOUT WHERE COMOUT.OSCRSTKEY = $OSCRSTKEY);
  DELETE FROM COMOUT WHERE COMOUT.OSCRSTKEY = $OSCRSTKEY;

  -- 4. 생산실적
  DELETE FROM OSCRSTUSE WHERE OSCRSTUSE.OSCRSTKEY = $OSCRSTKEY;
  DELETE FROM OSCRSTLOT WHERE OSCRSTLOT.OSCRSTKEY = $OSCRSTKEY;
  DELETE FROM OSCRST WHERE OSCRST.OSCRSTKEY = $OSCRSTKEY;

-- ****************************************************************************
WHEN 'PRINT_MOVE' THEN -- 실적로트 공정이동표 (TMLPRINT.PRD_1, TML2010_R01 PRINT_MOVE 와 같은 결과 구조)

  IF IFNULL($LOTKEY, '') = '' THEN
    CALL COMERR('실적로트번호가 없습니다.');
    LEAVE PROC;
  END IF;

  -- 0. 생산품·생산정보·생산로트
  SELECT
      MSTITEM.ITEMCD
    , MSTITEM.ITEMNM
    , MSTITEM.ITEMSPEC
    , '' AS HEATNO
    , '' AS HEATLOTKEY
    , LEFT(OSCRST.WORKSTIME, 10) AS PRDDATE
    , IFNULL(NULLIF(GPCD('EMPCD', OSCRST.REMP), ''), IFNULL(MSTCUST.CUSTNM, '')) AS EMPNM
    , LEFT(OSCRST.RSTTIME, 16) AS RSTTIME
    , OSCRSTLOT.LOTKEY
    , IFNULL(MSTLINE.LINENM, OSCRST.LINECD) AS LINENM
    , IFNULL(MSTPRC.PRCNM, OSCRST.PRCCD) AS PRCNM
    , '' AS EQMNM
    , IFNULL(GPCD('DM150', MSTITEM.ITEMUNIT), '') AS UNITNM
    , FORMAT(OSCRSTLOT.LOTQTY, 0) AS GOODQTY
    , '0' AS BADQTY
    , '' AS BADTPNM
    , IFNULL(NULLIF(GPCD('EMPCD', CALLEMP()), ''), IFNULL(MSTCUST.CUSTNM, '')) AS PRINTEMPNM
    , CALLTIME() AS PRINTTIME
  FROM OSCRSTLOT
  INNER JOIN OSCRST ON OSCRST.OSCRSTKEY = OSCRSTLOT.OSCRSTKEY
  INNER JOIN MSTITEM ON MSTITEM.ITEMID = OSCRST.ITEMID
  LEFT JOIN MSTCUST ON MSTCUST.CUSTCD = OSCRST.CUSTCD
  LEFT JOIN MSTLINE ON MSTLINE.LINECD = OSCRST.LINECD
  LEFT JOIN MSTPRC ON MSTPRC.PRCCD = OSCRST.PRCCD
  WHERE OSCRSTLOT.LOTKEY = $LOTKEY
  LIMIT 1;

  -- 1. 로트추적: 실적로트부터 투입로트를 거슬러 원소재까지 (사내 PRDRST·외주 OSCRST)
  DROP TEMPORARY TABLE IF EXISTS TEMP_TRACE;
  CREATE TEMPORARY TABLE TEMP_TRACE (
    SEQ    INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    LVL    INT NOT NULL,
    LOTKEY VARCHAR(100) NOT NULL,
    RSTTP  VARCHAR(1) NOT NULL,     -- P 사내, O 외주, '' 원소재
    RSTKEY VARCHAR(100) NOT NULL
  );

  DROP TEMPORARY TABLE IF EXISTS TEMP_CUR;
  CREATE TEMPORARY TABLE TEMP_CUR (
    LOTKEY VARCHAR(100) NOT NULL,
    RSTTP  VARCHAR(1) NOT NULL,
    RSTKEY VARCHAR(100) NOT NULL
  );

  DROP TEMPORARY TABLE IF EXISTS TEMP_NEXT;
  CREATE TEMPORARY TABLE TEMP_NEXT (
    LOTKEY VARCHAR(100) NOT NULL
  );

  INSERT INTO TEMP_CUR (LOTKEY, RSTTP, RSTKEY)
  SELECT OSCRSTLOT.LOTKEY, 'O', OSCRSTLOT.OSCRSTKEY
  FROM OSCRSTLOT
  WHERE OSCRSTLOT.LOTKEY = $LOTKEY
  LIMIT 1;

  SET _$LVL = 0;
  WHILE _$LVL < 30 AND EXISTS (SELECT TEMP_CUR.LOTKEY FROM TEMP_CUR) DO  -- 30단계 넘으면 끊음 (잘못된 순환 방지)
    INSERT INTO TEMP_TRACE (LVL, LOTKEY, RSTTP, RSTKEY)
    SELECT _$LVL, TEMP_CUR.LOTKEY, TEMP_CUR.RSTTP, TEMP_CUR.RSTKEY
    FROM TEMP_CUR
    ORDER BY TEMP_CUR.LOTKEY;

    DELETE FROM TEMP_NEXT;

    INSERT INTO TEMP_NEXT (LOTKEY)
    SELECT PRDRSTUSE.USELOTKEY
    FROM PRDRSTUSE
    INNER JOIN TEMP_CUR ON TEMP_CUR.RSTTP = 'P'
                       AND TEMP_CUR.RSTKEY = PRDRSTUSE.PRDRSTKEY;

    INSERT INTO TEMP_NEXT (LOTKEY)
    SELECT OSCRSTUSE.USELOTKEY
    FROM OSCRSTUSE
    INNER JOIN TEMP_CUR ON TEMP_CUR.RSTTP = 'O'
                       AND TEMP_CUR.RSTKEY = OSCRSTUSE.OSCRSTKEY;

    DELETE FROM TEMP_CUR;

    INSERT INTO TEMP_CUR (LOTKEY, RSTTP, RSTKEY)
    SELECT
        NEXTLOT.LOTKEY
      , IF(NEXTLOT.PRDRSTKEY <> '', 'P', IF(NEXTLOT.OSCRSTKEY <> '', 'O', ''))
      , IF(NEXTLOT.PRDRSTKEY <> '', NEXTLOT.PRDRSTKEY, NEXTLOT.OSCRSTKEY)
    FROM (SELECT DISTINCT
              TEMP_NEXT.LOTKEY
            , IFNULL((SELECT PRDRSTLOT.PRDRSTKEY FROM PRDRSTLOT WHERE PRDRSTLOT.LOTKEY = TEMP_NEXT.LOTKEY LIMIT 1), '') AS PRDRSTKEY
            , IFNULL((SELECT OSCRSTLOT.OSCRSTKEY FROM OSCRSTLOT WHERE OSCRSTLOT.LOTKEY = TEMP_NEXT.LOTKEY LIMIT 1), '') AS OSCRSTKEY
          FROM TEMP_NEXT) AS NEXTLOT;

    SET _$LVL = _$LVL + 1;
  END WHILE;

  SELECT
      TEMP_TRACE.SEQ AS NO
    , IFNULL(MSTITEM.ITEMCD, '') AS ITEMCD
    , CASE
        WHEN TEMP_TRACE.RSTTP = 'P' THEN IFNULL(PLINE.LINENM, PRDRST.LINECD)
        WHEN TEMP_TRACE.RSTTP = 'O' THEN IFNULL(OLINE.LINENM, IFNULL(MSTCUST.CUSTNM, OSCRST.CUSTCD))
      ELSE '' END AS LINENM
    , IF(TEMP_TRACE.RSTTP = '', '', IFNULL(MSTPRC.PRCNM, '')) AS PRCNM
    , TEMP_TRACE.LOTKEY
  FROM TEMP_TRACE
  LEFT JOIN PRDRST ON TEMP_TRACE.RSTTP = 'P'
                  AND PRDRST.PRDRSTKEY = TEMP_TRACE.RSTKEY
  LEFT JOIN OSCRST ON TEMP_TRACE.RSTTP = 'O'
                  AND OSCRST.OSCRSTKEY = TEMP_TRACE.RSTKEY
  LEFT JOIN MSTITEM ON MSTITEM.ITEMID = COALESCE(PRDRST.ITEMID, OSCRST.ITEMID, (SELECT COMLOT.ITEMID FROM COMLOT WHERE COMLOT.LOTKEY = TEMP_TRACE.LOTKEY LIMIT 1))
  LEFT JOIN MSTLINE AS PLINE ON PLINE.LINECD = PRDRST.LINECD
  LEFT JOIN MSTLINE AS OLINE ON OLINE.LINECD = OSCRST.LINECD
  LEFT JOIN MSTCUST ON MSTCUST.CUSTCD = OSCRST.CUSTCD
  LEFT JOIN MSTPRC ON MSTPRC.PRCCD = CASE WHEN TEMP_TRACE.RSTTP = 'P' THEN PRDRST.PRCCD
                                         WHEN TEMP_TRACE.RSTTP = 'O' AND IFNULL(OSCRST.PRCCD, '') <> '' THEN OSCRST.PRCCD
                                         ELSE (SELECT COMLOT.PRCCD FROM COMLOT WHERE COMLOT.LOTKEY = TEMP_TRACE.LOTKEY LIMIT 1) END
  ORDER BY TEMP_TRACE.SEQ;

  DROP TEMPORARY TABLE IF EXISTS TEMP_TRACE;
  DROP TEMPORARY TABLE IF EXISTS TEMP_CUR;
  DROP TEMPORARY TABLE IF EXISTS TEMP_NEXT;

