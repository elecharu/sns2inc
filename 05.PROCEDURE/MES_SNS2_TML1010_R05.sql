CREATE DEFINER=`root`@`%` 
PROCEDURE `MES_SNS2`.`TML1010_R05`(
-- *****************************************************************************
-- Comment: 현장터미널 설비부품 입출고 재고관리
-- Create:  2025-10-27  신정수
-- Modify:  2026-10-16  한성수  발주 조회 중복 조인 제거, 재고조회 미등록 품목 필터링 및 쿼리 최적화
--          2026-10-19  한성수  입출고자 검증, 재고 잠금 및 입고·재발행 라벨 데이터 반환
-- *****************************************************************************
  IN $SDATE       VARCHAR(10),
  IN $EDATE       VARCHAR(10),
  IN $ITEMCD      VARCHAR(100),
  IN $ITEMID      VARCHAR(100),
  IN $FACTORYCD   VARCHAR(100),
  IN $CUSTCD      VARCHAR(100),
  IN $INDATE      VARCHAR(10),  
  IN $INTP        VARCHAR(100),
  IN $INQTY       DECIMAL(20, 8),
  IN $OUTDATE     VARCHAR(10),  
  IN $OUTTP       VARCHAR(100),
  IN $OUTQTY      DECIMAL(20, 8),
  IN $LOCACD      VARCHAR(100),
  IN $MTRODRKEY   VARCHAR(100),
  IN $MTRODRSEQ   VARCHAR(100),
  IN $EMPCD       VARCHAR(100),
  IN $REMARK      VARCHAR(500),
-- *****************************************************************************
  IN $CALLTYPE    VARCHAR(50), 
  IN $KEYWORD     VARCHAR(1000)
)
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- *****************************************************************************
  DECLARE _$ITEMID    VARCHAR(100);
  DECLARE _$OLDQTY    DECIMAL(20, 8);
  DECLARE _$COMPANYCD VARCHAR(10);
  DECLARE _$REMAINQTY DECIMAL(20, 8);

-- *****************************************************************************
  -- 선택 공장의 법인과 재고를 같은 기준으로 사용
  SET $FACTORYCD = COALESCE(NULLIF(TRIM($FACTORYCD), ''), '07');
  SET _$COMPANYCD = (SELECT COMPANYCD FROM MSTFACTORY WHERE FACTORYCD = $FACTORYCD LIMIT 1);
  IF COALESCE(_$COMPANYCD, '') = '' THEN
    CALL COMERR('공장을 선택해주세요.');
    LEAVE PROC;
  END IF;

  -- 입출고·발주·이력 조회는 화면에서 선택한 품목키로 확인
  IF $CALLTYPE IN ('LIST_ODR_EQMPARTS', 'IN_EQMPARTS', 'OUT_EQMPARTS', 'LIST_INOUT_EQMPARTS', 'LABEL_REPRINT') THEN
    SET _$ITEMID = (SELECT CAST(ITEMID AS CHAR) FROM MSTITEM
                   WHERE ITEMID = $ITEMID AND COMPANYCD = _$COMPANYCD
                     AND ITEMCG = 'DM100700' AND COALESCE(ENDYN, 'N') <> 'Y' LIMIT 1);
    IF _$ITEMID IS NULL THEN
      CALL COMERR('선택한 공장의 설비부품이 아닙니다. 다시 조회해주세요.');
      LEAVE PROC;
    END IF;
  END IF;

  -- 입출고 처리자 확인
  IF $CALLTYPE IN ('IN_EQMPARTS', 'OUT_EQMPARTS') THEN
    IF COALESCE(TRIM($EMPCD), '') = '' THEN
      CALL COMERR(CASE WHEN $CALLTYPE = 'IN_EQMPARTS' THEN '입고자를 선택해주세요.' ELSE '출고자를 선택해주세요.' END);
      LEAVE PROC;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM MSTEMP WHERE EMPCD = $EMPCD LIMIT 1) THEN
      CALL COMERR('등록된 사원을 선택해주세요.');
      LEAVE PROC;
    END IF;
  END IF;

  CASE $CALLTYPE
-- *****************************************************************************

  WHEN 'LIST_EQMPARTS' THEN -- 공장별 설비부품 재고 조회
    
    SELECT CAST(MSTITEM.ITEMID AS CHAR) AS ITEMID,
           $FACTORYCD AS FACTORYCD,
           MSTITEM.ITEMCD,
           MSTITEM.ITEMNM,
           MSTITEM.ITEMSPEC,
           COALESCE(MSTITEM_EQMPARTS.GRADE, MSTITEM.GRADE, '') AS GRADE,
           COALESCE(MSTLOCA_EQMPARTS.LOCANM, MSTITEM_EQMPARTS.LOCACD, '') AS LOCANM,
           COALESCE(MSTITEM_EQMPARTS.LOCACD, '') AS LOCACD,
           CAST(COALESCE(MSTITEM_EQMPARTS.SAFEQTY, 0) AS DOUBLE) AS SAFEQTY,
           CAST(COALESCE(MSTITEM_EQMPARTS.LOTQTY, 0) AS DOUBLE) AS LOTQTY,
           MSTITEM.ITEMUNIT,
           CASE WHEN COALESCE(MSTITEM_EQMPARTS.LOTQTY, 0) < COALESCE(MSTITEM_EQMPARTS.SAFEQTY, 0)
                THEN 'PINK'
                ELSE ''
           END AS BACKGROUND
    FROM MSTITEM
    LEFT JOIN MSTITEM_EQMPARTS
      ON MSTITEM_EQMPARTS.ITEMID = MSTITEM.ITEMID
     AND MSTITEM_EQMPARTS.FACTORYCD = $FACTORYCD
    LEFT JOIN MSTLOCA_EQMPARTS
      ON MSTLOCA_EQMPARTS.LOCACD = MSTITEM_EQMPARTS.LOCACD
     AND MSTITEM_EQMPARTS.LOCACD <> ''
    WHERE MSTITEM.COMPANYCD = _$COMPANYCD
      AND MSTITEM.ITEMCG = 'DM100700'
      AND COALESCE(MSTITEM.ENDYN, 'N') <> 'Y'
      AND (   COALESCE($KEYWORD, '') <> ''
           OR COALESCE($ITEMCD, '') <> ''
           OR MSTITEM_EQMPARTS.ITEMID IS NOT NULL
          )
      AND (   COALESCE($KEYWORD, '') = ''
           OR MSTITEM.ITEMCD LIKE CONCAT('%', $KEYWORD, '%')
           OR MSTITEM.ITEMNM LIKE CONCAT('%', $KEYWORD, '%')
           OR MSTITEM.ITEMSPEC LIKE CONCAT('%', $KEYWORD, '%')
          )
      AND (   COALESCE($ITEMCD, '') = ''
           OR MSTITEM.ITEMCD LIKE CONCAT('%', $ITEMCD, '%')
          )
    ORDER BY MSTITEM.ITEMCD, MSTITEM.ITEMID;

-- *****************************************************************************

  WHEN 'LIST_ODR_EQMPARTS' THEN -- 선택된 설비부품 발주 목록 조회 (입고 팝업용)

    SELECT MTRODRD.MTRODRKEY, MTRODRD.MTRODRSEQ, MTRODR.MTRODRDATE,
           COALESCE(MSTCUST.CUSTNM, MTRODR.CUSTCD, '') AS CUSTNM,
           CAST(MTRODRD.ODRQTY AS DOUBLE) AS ODRQTY,
           CAST(COALESCE(MTRODRD.INQTY, 0) AS DOUBLE) AS PREV_INQTY,
           CAST(MTRODRD.ODRQTY - COALESCE(MTRODRD.INQTY, 0) AS DOUBLE) AS REMAINQTY
    FROM MTRODRD
    INNER JOIN MTRODR ON MTRODR.MTRODRKEY = MTRODRD.MTRODRKEY
    LEFT JOIN MSTCUST ON MSTCUST.CUSTCD = MTRODR.CUSTCD
    WHERE MTRODRD.ITEMID = _$ITEMID
      AND COALESCE(NULLIF(MTRODR.INFACTORYCD, ''), MTRODR.ODRFACTORY) = $FACTORYCD
      AND (COALESCE($SDATE, '') = '' OR MTRODR.MTRODRDATE >= $SDATE)
      AND (COALESCE($EDATE, '') = '' OR MTRODR.MTRODRDATE <= $EDATE)
      AND (COALESCE($CUSTCD, '') = '' OR MTRODR.CUSTCD = $CUSTCD)
      AND MTRODRD.MTRODRSTT IN ('MM110201', 'MM110300')
      AND MTRODRD.ODRQTY > COALESCE(MTRODRD.INQTY, 0)
    ORDER BY MTRODR.MTRODRDATE DESC, MTRODRD.MTRODRKEY DESC, MTRODRD.MTRODRSEQ;

-- *****************************************************************************

  WHEN 'IN_EQMPARTS' THEN -- 설비부품 입고등록

    IF COALESCE($MTRODRKEY, '') = '' OR COALESCE($MTRODRSEQ, '') = '' THEN
      CALL COMERR('입고할 발주를 선택해주세요.');
      LEAVE PROC;
    END IF;

    IF COALESCE($INDATE, '') = '' THEN
      CALL COMERR('입고일자를 입력하십시오.');
      LEAVE PROC;
    END IF;

    IF COALESCE($INQTY, 0) <= 0 THEN
      CALL COMERR('입고수량을 0보다 크게 입력하십시오.');
      LEAVE PROC;
    END IF;

    IF LEFT(COALESCE($INTP, ''), 3) <> 'IN_' THEN
      CALL COMERR('입고구분을 선택해주세요.');
      LEAVE PROC;
    END IF;

    -- 같은 부품·입고공장의 발주잔량 확인
    SET _$REMAINQTY = (SELECT MTRODRD.ODRQTY - COALESCE(MTRODRD.INQTY, 0)
                        FROM MTRODRD INNER JOIN MTRODR ON MTRODR.MTRODRKEY = MTRODRD.MTRODRKEY
                        WHERE MTRODRD.MTRODRKEY = $MTRODRKEY AND MTRODRD.MTRODRSEQ = $MTRODRSEQ
                          AND MTRODRD.ITEMID = _$ITEMID
                          AND COALESCE(NULLIF(MTRODR.INFACTORYCD, ''), MTRODR.ODRFACTORY) = $FACTORYCD
                          AND MTRODRD.MTRODRSTT IN ('MM110201', 'MM110300') FOR UPDATE);
    IF _$REMAINQTY IS NULL OR $INQTY > _$REMAINQTY THEN
      CALL COMERR('선택한 발주의 부품·입고공장 또는 잔여수량을 확인해주세요.');
      LEAVE PROC;
    END IF;

    -- 기존 재고량 취득
    SET _$OLDQTY = COALESCE((SELECT LOTQTY FROM MSTITEM_EQMPARTS WHERE ITEMID = _$ITEMID AND FACTORYCD = $FACTORYCD LIMIT 1 FOR UPDATE), 0);

    -- 입출고 이력 등록
    INSERT INTO INOUT_EQMPARTS (
        INOUTKEY, INOROUT, INOUTDATE, INOUTTP_EQMPARTS, INOUTQTY, OLDQTY,
        ITEMID, EMPCD, MTRODRKEY, MTRODRSEQ, REMARK,
        RTIME, REMP, RPRG
    ) VALUES (
        GETKEY('INOUTKEY'), 'IN', $INDATE, $INTP, $INQTY, _$OLDQTY,
        _$ITEMID, $EMPCD, $MTRODRKEY, $MTRODRSEQ, COALESCE($REMARK, ''),
        CALLTIME(), CALLEMP(), CALLPRG()
    );

    -- 설비부품 재고 반영 (신규 또는 누적)
    INSERT INTO MSTITEM_EQMPARTS (
        ITEMID, FACTORYCD, LOTQTY, SAFEQTY, LOCACD,
        RTIME, REMP, RPRG
    ) VALUES (
        _$ITEMID, $FACTORYCD, $INQTY, 0, COALESCE($LOCACD, ''),
        CALLTIME(), CALLEMP(), CALLPRG()
    )
    ON DUPLICATE KEY UPDATE
        LOTQTY = LOTQTY + $INQTY,
        LOCACD = CASE WHEN COALESCE($LOCACD, '') <> '' THEN $LOCACD ELSE LOCACD END,
        MTIME = CALLTIME(),
        MEMP = CALLEMP(),
        MPRG = CALLPRG();

    -- 선택 발주의 입고수량과 진행상태 반영
    UPDATE MTRODRD
    SET MTRODRSTT = CASE WHEN COALESCE(INQTY, 0) + $INQTY >= ODRQTY THEN 'MM110500' ELSE 'MM110300' END,
        INQTY = COALESCE(INQTY, 0) + $INQTY,
        MTIME = CALLTIME(), MEMP = CALLEMP(), MPRG = CALLPRG()
    WHERE MTRODRKEY = $MTRODRKEY
      AND MTRODRSEQ = $MTRODRSEQ;

-- *****************************************************************************

  WHEN 'OUT_EQMPARTS' THEN -- 설비부품 출고등록

    IF COALESCE($OUTDATE, '') = '' THEN
      CALL COMERR('출고일자를 입력하십시오.');
      LEAVE PROC;
    END IF;

    IF COALESCE($OUTQTY, 0) <= 0 THEN
      CALL COMERR('출고수량을 0보다 크게 입력하십시오.');
      LEAVE PROC;
    END IF;

    IF LEFT(COALESCE($OUTTP, ''), 4) <> 'OUT_' THEN
      CALL COMERR('출고구분을 선택해주세요.');
      LEAVE PROC;
    END IF;

    -- 기존 재고량 취득
    SET _$OLDQTY = COALESCE((SELECT LOTQTY FROM MSTITEM_EQMPARTS WHERE ITEMID = _$ITEMID AND FACTORYCD = $FACTORYCD LIMIT 1 FOR UPDATE), 0);

    IF (_$OLDQTY - $OUTQTY) < 0 THEN
      CALL COMERR('현재고가 부족합니다.');
      LEAVE PROC;
    END IF;

    -- 입출고 이력 등록
    INSERT INTO INOUT_EQMPARTS (
        INOUTKEY, INOROUT, INOUTDATE, INOUTTP_EQMPARTS, INOUTQTY, OLDQTY,
        ITEMID, EMPCD, REMARK,
        RTIME, REMP, RPRG
    ) VALUES (
        GETKEY('INOUTKEY'), 'OUT', $OUTDATE, $OUTTP, $OUTQTY, _$OLDQTY,
        _$ITEMID, $EMPCD, COALESCE($REMARK, ''),
        CALLTIME(), CALLEMP(), CALLPRG()
    );

    -- 설비부품 재고 차감
    UPDATE MSTITEM_EQMPARTS
    SET LOTQTY = LOTQTY - $OUTQTY,
        MTIME = CALLTIME(),
        MEMP = CALLEMP(),
        MPRG = CALLPRG()
    WHERE ITEMID = _$ITEMID
      AND FACTORYCD = $FACTORYCD;

-- *****************************************************************************

  WHEN 'LIST_INOUT_EQMPARTS' THEN -- 설비부품 입출고 이력 조회

    SELECT INOUT_EQMPARTS.INOUTDATE,
           CASE INOUT_EQMPARTS.INOROUT WHEN 'IN' THEN '입고' WHEN 'OUT' THEN '출고' END AS INOROUT,
           GPCD('INOUTTP_EQMPARTS', INOUT_EQMPARTS.INOUTTP_EQMPARTS) AS INOUTTPNM,
           CAST(CASE WHEN INOUT_EQMPARTS.INOROUT = 'IN' THEN INOUT_EQMPARTS.INOUTQTY ELSE 0 END AS DOUBLE) AS INQTY,
           CAST(CASE WHEN INOUT_EQMPARTS.INOROUT = 'OUT' THEN INOUT_EQMPARTS.INOUTQTY ELSE 0 END AS DOUBLE) AS OUTQTY,
           GPCD('EMPCD', INOUT_EQMPARTS.EMPCD) AS EMPNM
    FROM INOUT_EQMPARTS
    WHERE INOUT_EQMPARTS.ITEMID = _$ITEMID
      AND (COALESCE($SDATE, '') = '' OR INOUT_EQMPARTS.INOUTDATE >= $SDATE)
      AND (COALESCE($EDATE, '') = '' OR INOUT_EQMPARTS.INOUTDATE <= $EDATE)
    ORDER BY INOUT_EQMPARTS.RTIME ASC, INOUT_EQMPARTS.INOUTKEY ASC;

-- *****************************************************************************

  WHEN 'LABEL_REPRINT' THEN -- 선택 부품 라벨 재발행

    SET $INDATE = LEFT(CALLTIME(), 10);

-- *****************************************************************************

  END CASE;

  -- 입고는 등록 수량, 재발행은 현재고로 라벨 출력
  IF $CALLTYPE IN ('IN_EQMPARTS', 'LABEL_REPRINT') THEN
    SELECT 'EQMPARTS' AS LABELCD;

    SELECT MSTITEM.ITEMCD AS LOTKEY, MSTITEM.ITEMCD, MSTITEM.ITEMNM, MSTITEM.ITEMSPEC,
           $INDATE AS PRDDATE,
           CAST(CASE WHEN $CALLTYPE = 'IN_EQMPARTS' THEN $INQTY ELSE COALESCE(MSTITEM_EQMPARTS.LOTQTY, 0) END AS DOUBLE) AS LOTQTY,
           COALESCE(MSTLOCA_EQMPARTS.LOCANM, MSTITEM_EQMPARTS.LOCACD, '') AS WARENM
    FROM MSTITEM
    LEFT JOIN MSTITEM_EQMPARTS
      ON MSTITEM_EQMPARTS.ITEMID = MSTITEM.ITEMID
     AND MSTITEM_EQMPARTS.FACTORYCD = $FACTORYCD
    LEFT JOIN MSTLOCA_EQMPARTS
      ON MSTLOCA_EQMPARTS.LOCACD = MSTITEM_EQMPARTS.LOCACD
    WHERE MSTITEM.ITEMID = _$ITEMID;
  END IF;
END
