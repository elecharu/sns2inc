-- 최신 TML1010_R05 프로시저 적용 후 MES_SNS2에서 전체 선택 → Alt+X 실행
-- 부품 000-TEST-R05 / 공장 07 / 현재고 10,000 / 발주 TEST-R05
-- 기존 거래처·사원·로케이션은 참조만 하며, 같은 테스트 부품이 있으면 중단
-- 테스트 결과를 초기화하거나 기존 업무 데이터를 수정·삭제하지 않음

USE MES_SNS2;

DELIMITER $$
BEGIN NOT ATOMIC
  DECLARE _$ITEMID     INT;
  DECLARE _$COMPANYCD  VARCHAR(10);
  DECLARE _$CUSTCD     VARCHAR(20);
  DECLARE _$EMPCD      VARCHAR(20);
  DECLARE _$LOCACD     VARCHAR(100);
  DECLARE _$TODAY      VARCHAR(10);
  DECLARE _$OLD_EMP    VARCHAR(100) DEFAULT @CALLEMP;
  DECLARE _$OLD_PRG    VARCHAR(100) DEFAULT @CALLPRG;
  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    ROLLBACK;
    SET @CALLEMP = _$OLD_EMP;
    SET @CALLPRG = _$OLD_PRG;
    RESIGNAL;
  END;

  START TRANSACTION;

  IF EXISTS (SELECT 1 FROM MSTITEM WHERE ITEMCD = '000-TEST-R05' LIMIT 1)
     OR EXISTS (SELECT 1 FROM MTRODR WHERE MTRODRKEY = 'TEST-R05' LIMIT 1) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '이미 생성된 테스트 데이터입니다. 기존 테스트 결과를 유지하고 중단합니다.';
  END IF;

  SET _$COMPANYCD = (SELECT COMPANYCD FROM MSTFACTORY WHERE FACTORYCD = '07' LIMIT 1);
  SET _$CUSTCD = (SELECT CUSTCD FROM MSTCUST WHERE USEYN = 'Y' AND PURYN IN ('1', 'Y') ORDER BY CUSTCD LIMIT 1);
  SET _$EMPCD = (SELECT EMPCD FROM MSTEMP WHERE FACTORYCD = '07' AND EMPCD <> '' ORDER BY EMPCD LIMIT 1);
  SET _$LOCACD = (SELECT LOCACD FROM MSTLOCA_EQMPARTS ORDER BY LOCACD LIMIT 1);
  SET _$TODAY = LEFT(CALLTIME(), 10);

  IF COALESCE(_$COMPANYCD, '') = '' OR _$CUSTCD IS NULL OR _$EMPCD IS NULL THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'INC 2공장·사용 중인 구매 거래처·공장 사원 정보를 확인해주세요.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM COMTYPE WHERE GPCD = 'DM150' AND TPCD = 'DM150100' AND USEYN = 'Y' LIMIT 1) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '사용 중인 EA 단위코드 DM150100을 확인해주세요.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM SYSLABEL WHERE LABELCD = 'EQMPARTS' AND XMLDATA <> '' LIMIT 1) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '설비부품 라벨 양식 EQMPARTS를 확인해주세요.';
  END IF;

  SET @CALLEMP = _$EMPCD;
  SET @CALLPRG = 'TML1010_R05_TEST';

  -- 테스트 전용 설비부품 (품목키는 AUTO_INCREMENT 사용)
  INSERT INTO MSTITEM (
    ITEMCD, COMPANYCD, ITEMNM, ITEMSPEC, ITEMUNIT, ITEMCG, ENDYN, GRADE, REMARK,
    RTIME, REMP, RPRG
  ) VALUES (
    '000-TEST-R05', _$COMPANYCD, '[테스트] 설비부품 입출고', 'R05 기능시험용', 'DM150100', 'DM100700', 'N', 'A', 'TML1010_R05 기능 테스트 전용',
    CALLTIME(), CALLEMP(), CALLPRG()
  );
  SET _$ITEMID = LAST_INSERT_ID();

  -- 같은 부품에 입고 가능한 발주 두 행 생성
  INSERT INTO MTRODR (
    MTRODRKEY, MTRODRDATE, EXPDATE, CUSTCD, ODRFACTORY, INFACTORYCD, MTRODRSTT, REMARK,
    RTIME, REMP, RPRG
  ) VALUES (
    'TEST-R05', _$TODAY, _$TODAY, _$CUSTCD, '07', '07', 'MM110300', 'TML1010_R05 기능 테스트 전용',
    CALLTIME(), CALLEMP(), CALLPRG()
  );

  INSERT INTO MTRODRD (
    MTRODRKEY, MTRODRSEQ, ITEMID, ODRQTY, INQTY, MTRODRSTT, REMARK,
    RTIME, REMP, RPRG
  ) VALUES (
    'TEST-R05', 1, _$ITEMID, 10000, 0, 'MM110201', '발주승인: 입고 가능 10,000',
    CALLTIME(), CALLEMP(), CALLPRG()
  ), (
    'TEST-R05', 2, _$ITEMID, 20000, 10000, 'MM110300', '납품진행: 입고 가능 10,000',
    CALLTIME(), CALLEMP(), CALLPRG()
  );

  -- 발주 2번 행에서 이미 입고된 수량과 현재고 일치
  INSERT INTO MSTITEM_EQMPARTS (
    FACTORYCD, ITEMID, GRADE, SAFEQTY, LOTQTY, LOCACD, RTIME, REMP, RPRG
  ) VALUES (
    '07', _$ITEMID, 'A', 100, 10000, COALESCE(_$LOCACD, ''), CALLTIME(), CALLEMP(), CALLPRG()
  );

  INSERT INTO INOUT_EQMPARTS (
    INOUTKEY, INOROUT, INOUTDATE, INOUTTP_EQMPARTS, INOUTQTY, OLDQTY,
    ITEMID, EMPCD, MTRODRKEY, MTRODRSEQ, REMARK, RTIME, REMP, RPRG
  ) VALUES (
    'TEST-R05-OPEN', 'IN', _$TODAY, 'IN_01', 10000, 0,
    _$ITEMID, _$EMPCD, 'TEST-R05', 2, '테스트 초기재고 입고 10,000', CALLTIME(), CALLEMP(), CALLPRG()
  );

  COMMIT;
  SET @CALLEMP = _$OLD_EMP;
  SET @CALLPRG = _$OLD_PRG;
END$$
DELIMITER ;

-- 생성 결과 확인
SELECT MSTITEM.ITEMID, MSTITEM.ITEMCD, MSTITEM.ITEMNM, MSTITEM.ITEMUNIT,
       MSTITEM_EQMPARTS.FACTORYCD, MSTITEM_EQMPARTS.LOTQTY, MSTITEM_EQMPARTS.SAFEQTY
FROM MSTITEM
INNER JOIN MSTITEM_EQMPARTS ON MSTITEM_EQMPARTS.ITEMID = MSTITEM.ITEMID
WHERE MSTITEM.ITEMCD = '000-TEST-R05' AND MSTITEM_EQMPARTS.FACTORYCD = '07';

SELECT MTRODRKEY, MTRODRSEQ, MTRODRSTT, ODRQTY, INQTY, ODRQTY - INQTY AS REMAINQTY
FROM MTRODRD
WHERE MTRODRKEY = 'TEST-R05'
ORDER BY MTRODRSEQ;

SELECT INOUTKEY, INOUTDATE, INOROUT, INOUTQTY, EMPCD, MTRODRKEY, MTRODRSEQ
FROM INOUT_EQMPARTS
WHERE INOUTKEY = 'TEST-R05-OPEN';

-- 화면 시험 예: 초기 10,000 → 출고 100 → 현재고 9,900 → 발주 1번 행 입고 200 → 현재고 10,100
-- 발주 2번 행에서 잔량 10,000 전체 입고 시 현재고 20,100, 해당 행은 발주완결로 조회 제외
-- 입출고이력은 초기 입고와 화면에서 등록한 입고·출고를 표시, 출력 버튼은 재고를 변경하지 않음
