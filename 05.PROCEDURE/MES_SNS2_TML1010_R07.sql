CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.TML1010_R07(
-- *****************************************************************************
-- Comment: 원자재·상품 납품 등록 (TML1010_R01 납품등록을 복사, 무상사급 구매(MM100910) 발주만. 재고는 등록 때 움직이지 않고 TML1020_R09 자재입고확인에서 입고)
-- Create: 2026-11-16 (TML1010_R01 복사)
-- Modify: 2026-11-18: ERP 인터페이스 - 납품등록 때 DLV(PO_BC MM100910) 송신 (IO_ERP_INTERFACE 'DLV_INV'), 납품 취소 때 D 송신. 입고확인은 TML1020_R09 에서 PUR 송신
-- Modify: 2026-11-19: [납품이력] 탭용 조회 LIST_INVOICE 추가 (납품일자 기간, 납품 취소는 기존 DEL_MTRCUSTLOT 을 거래명세서마다 호출)
-- *****************************************************************************
  IN $SDATE             VARCHAR(10),
  IN $EDATE             VARCHAR(10),
  IN $CUSTCD            VARCHAR(100),
  IN $ITEMID            VARCHAR(100),
  IN $INHOUSEYN         VARCHAR(1),
  IN $MTRODRKEY        VARCHAR(100),
  IN $MTRODRSEQ        VARCHAR(100),
  IN $PRDDATE           VARCHAR(10),
  IN $LOTKEY            VARCHAR(100),
  IN $LOTQTY            DECIMAL(20, 8),
  IN $CARINQTY          DECIMAL(20, 8),
  IN $INVOICEKEY        VARCHAR(100),
  IN $MTRODRKEY_LIST   MEDIUMTEXT,
  IN $MTRODRSEQ_LIST   MEDIUMTEXT,
  IN $ITEMID_LIST       MEDIUMTEXT,
  IN $LOTKEY_LIST       MEDIUMTEXT,
  IN $LOTQTY_LIST       MEDIUMTEXT,
  IN $CARINQTY_LIST     MEDIUMTEXT,
  IN $LOTUNIT_LIST      MEDIUMTEXT,
  IN $LABELCD           VARCHAR(100),
  IN $HEATNO            VARCHAR(100),
  IN $BOXQTY_LIST       MEDIUMTEXT,
  IN $BOXCNT_LIST       MEDIUMTEXT,
  IN $HEATNO_LIST       MEDIUMTEXT,
-- *****************************************************************************
  IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- SET @DEBUGLOGYN = 'Y';
-- *****************************************************************************

  DECLARE _$MTRODRKEY   VARCHAR(100);
  DECLARE _$MTRODRSEQ   VARCHAR(100);
  DECLARE _$ITEMID      VARCHAR(100);
  DECLARE _$LOTKEY      VARCHAR(100);
  DECLARE _$LOTQTY      DECIMAL(20, 8);
  DECLARE _$CARINQTY    DECIMAL(20, 8);
  DECLARE _$LOTUNIT     DECIMAL(20, 0);
  DECLARE _$QTY         DECIMAL(20, 8);
  DECLARE _$REMAINQTY   DECIMAL(20, 8);
  DECLARE _$CUSTCD      VARCHAR(100);
  DECLARE _$INVOICEKEY  VARCHAR(100);
  DECLARE _$ODRQTY      DECIMAL(20, 8) DEFAULT 0;
  DECLARE _$SUMLOTQTY   DECIMAL(20, 8) DEFAULT 0;
  DECLARE _$BOXQTY      DECIMAL(20, 8);
  DECLARE _$BOXCNT      DECIMAL(20, 8);
  DECLARE _$I           INT;
  DECLARE _$ITEMCG      VARCHAR(20);
  DECLARE _$MTRINKEY    VARCHAR(20);
  DECLARE _$SEQ         INT;
  DECLARE _$BOXHEATNO   VARCHAR(100);
  DECLARE _$ODRBC       VARCHAR(20);

-- ****************************************************************************
CASE $CALLTYPE

-- ****************************************************************************
WHEN 'LIST_MTRODR' THEN -- 발주별 납품현황 조회

  SELECT
    MTRODR.MTRODRKEY,
    MTRODRD.MTRODRSEQ,
    MSTITEM.ITEMID,
    MSTITEM.ITEMCD,
    MSTITEM.ITEMNM,
    MSTITEM.ITEMSPEC,
    GPCD('CUSTCD', MTRODR.CUSTCD) AS CUSTNM,
    GPCD('DM100', MSTITEM.ITEMCG) AS ITEMCGNM,
    LEFT(MTRODRD.EXPDATE, 10) AS EXPDATE,
    MTRODRD.ODRQTY,
    MTRODRD.ODRQTY - IFNULL(SUM(MTRCUSTLOT.LOTQTY), 0) AS OKQTY,
    GETDATE() AS PRDDATE,
    MTRODRD.ODRQTY - IFNULL(SUM(MTRCUSTLOT.LOTQTY), 0) AS LOTQTY,
    MTRODRD.REMARK,
    LEFT(MTRODR.MTRODRDATE, 10) AS MTRODRDATE,
    IFNULL(SUM(MTRCUSTLOT.LOTQTY), 0) AS CUSTLOTQTY,
    GPCD('DM150', MSTITEM.ITEMUNIT) AS ITEMUNIT,
    0 AS CARINQTY,
    CASE WHEN MTRODR.ODRBC = 'MM100900' THEN 'LIGHTPINK'
         ELSE 'WHITE' END AS BACKGROUND
  FROM MTRODR
  INNER JOIN MTRODRD ON MTRODRD.MTRODRKEY = MTRODR.MTRODRKEY
  INNER JOIN MSTITEM ON MSTITEM.ITEMID = MTRODRD.ITEMID
  LEFT JOIN MTRCUSTLOT ON MTRCUSTLOT.MTRODRKEY = MTRODRD.MTRODRKEY
                       AND MTRCUSTLOT.MTRODRSEQ = MTRODRD.MTRODRSEQ
  WHERE MTRODR.MTRODRDATE >= $SDATE  -- 2026-11-10 납기일자 → 발주일자로 조회
    AND MTRODR.MTRODRDATE < DATE_ADD($EDATE, INTERVAL 1 DAY)
    AND MTRODR.CUSTCD LIKE CONCAT('%', $CUSTCD, '%')
    AND MSTITEM.ITEMID LIKE CONCAT('%', $ITEMID, '%')
    AND MTRODR.ODRBC = 'MM100910'  -- 원자재·상품 납품등록은 무상사급 구매(MM100910) 발주만 (유상사급은 TML1010_R01)
  GROUP BY MTRODRD.MTRODRKEY, MTRODRD.MTRODRSEQ
  HAVING MTRODRD.ODRQTY - IFNULL(SUM(MTRCUSTLOT.LOTQTY), 0) > 0
  ORDER BY MTRODR.MTRODRDATE, MTRODR.MTRODRKEY, MTRODRD.MTRODRSEQ;

-- ****************************************************************************
WHEN 'ADD_MTRCUSTLOT' THEN  -- 납품로트 등록 (2026-11-10 화면 오른쪽 BOX 현황 전체를 한 번에 등록, 발주별로 거래명세서 1장)

  IF $PRDDATE = '' THEN
    CALL COMERR('출하일자를 입력하세요.');
    LEAVE PROC;
  END IF;

  IF IFNULL($MTRODRKEY_LIST, '') = '' THEN
    CALL COMERR('등록할 BOX 가 없습니다. 발주의 [입력] 에서 BOX 를 추가하세요.');
    LEAVE PROC;
  END IF;

  /* =========================================================
     1. BOX 현황 (행마다 발주·HEAT NO·BOX 단위 수량·BOX 수량)
     ========================================================= */
  DROP TEMPORARY TABLE IF EXISTS TEMP_BOX;
  CREATE TEMPORARY TABLE TEMP_BOX (
      SEQ       INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
      MTRODRKEY VARCHAR(20),
      MTRODRSEQ VARCHAR(20),
      HEATNO    VARCHAR(100),
      BOXQTY    DECIMAL(20, 8),
      BOXCNT    DECIMAL(20, 8),
      DONEYN    VARCHAR(1) DEFAULT 'N'
  );

  DROP TEMPORARY TABLE IF EXISTS TEMP_INV;
  CREATE TEMPORARY TABLE TEMP_INV (
      INVOICEKEY VARCHAR(50)
  );

  WHILE LENGTH($MTRODRKEY_LIST) > 0 DO
    CALL COMSPLIT($MTRODRKEY_LIST, _$MTRODRKEY);
    CALL COMSPLIT($MTRODRSEQ_LIST, _$MTRODRSEQ);
    CALL COMSPLIT($HEATNO_LIST,    _$BOXHEATNO);
    CALL COMSPLIT($BOXQTY_LIST,    _$BOXQTY);
    CALL COMSPLIT($BOXCNT_LIST,    _$BOXCNT);

    IF IFNULL(_$MTRODRKEY, '') <> '' THEN
      IF NOT EXISTS (SELECT 1
                       FROM MTRODRD
                       WHERE MTRODRD.MTRODRKEY = _$MTRODRKEY
                         AND MTRODRD.MTRODRSEQ = _$MTRODRSEQ) THEN
        CALL COMERR(CONCAT('존재하지 않는 발주입니다. (', _$MTRODRKEY, '-', _$MTRODRSEQ, ')'));
        LEAVE PROC;
      END IF;

      IF IFNULL(_$BOXQTY, 0) <= 0 THEN
        CALL COMERR('BOX 단위 수량이 0 이하입니다.');
        LEAVE PROC;
      END IF;

      IF IFNULL(_$BOXCNT, 0) <= 0 OR _$BOXCNT <> FLOOR(_$BOXCNT) THEN
        CALL COMERR('BOX 수량은 1 이상의 정수로 입력하세요.');
        LEAVE PROC;
      END IF;

      INSERT INTO TEMP_BOX (MTRODRKEY, MTRODRSEQ, HEATNO, BOXQTY, BOXCNT)
      VALUES (_$MTRODRKEY, _$MTRODRSEQ, TRIM(IFNULL(_$BOXHEATNO, '')), _$BOXQTY, _$BOXCNT);
    END IF;
  END WHILE;

  IF NOT EXISTS (SELECT 1 FROM TEMP_BOX) THEN
    CALL COMERR('등록할 BOX 가 없습니다.');
    LEAVE PROC;
  END IF;

  /* =========================================================
     2. 발주별로 : 미납량 확인 → 거래명세서 1장 → BOX 1개당 납품 LOT 1개
     ========================================================= */
  WHILE EXISTS (SELECT 1 FROM TEMP_BOX WHERE TEMP_BOX.DONEYN = 'N') DO

    SELECT TEMP_BOX.MTRODRKEY, TEMP_BOX.MTRODRSEQ
      INTO _$MTRODRKEY, _$MTRODRSEQ
      FROM TEMP_BOX
      WHERE TEMP_BOX.DONEYN = 'N'
      ORDER BY TEMP_BOX.SEQ
      LIMIT 1;

    SELECT MTRODRD.ITEMID, MTRODRD.ODRQTY, MTRODR.CUSTCD, MTRODR.ODRBC
      INTO _$ITEMID, _$ODRQTY, _$CUSTCD, _$ODRBC
      FROM MTRODRD
      INNER JOIN MTRODR ON MTRODR.MTRODRKEY = MTRODRD.MTRODRKEY
      WHERE MTRODRD.MTRODRKEY = _$MTRODRKEY
        AND MTRODRD.MTRODRSEQ = _$MTRODRSEQ;

    IF _$ODRBC <> 'MM100910' THEN
      CALL COMERR('원자재·상품 납품등록은 무상사급 구매 발주만 등록할 수 있습니다. (유상사급은 유상사급 납품등록 메뉴)');
      LEAVE PROC;
    END IF;

    -- 미납량 초과 확인 (이미 등록한 납품 LOT + 이번 등록분)
    SET _$SUMLOTQTY = IFNULL((SELECT SUM(MTRCUSTLOT.LOTQTY)
                                FROM MTRCUSTLOT
                                WHERE MTRCUSTLOT.MTRODRKEY = _$MTRODRKEY
                                  AND MTRCUSTLOT.MTRODRSEQ = _$MTRODRSEQ), 0);

    SET _$LOTQTY = IFNULL((SELECT SUM(TEMP_BOX.BOXQTY * TEMP_BOX.BOXCNT)
                             FROM TEMP_BOX
                             WHERE TEMP_BOX.MTRODRKEY = _$MTRODRKEY
                               AND TEMP_BOX.MTRODRSEQ = _$MTRODRSEQ), 0);

    IF _$LOTQTY + _$SUMLOTQTY > _$ODRQTY THEN
      CALL COMERR(CONCAT('납품량(', FORMAT(_$LOTQTY, 0), ')이 미납량(', FORMAT(_$ODRQTY - _$SUMLOTQTY, 0), ')을 초과하였습니다.'
                        , '\n- 품목코드: ', (SELECT MSTITEM.ITEMCD FROM MSTITEM WHERE MSTITEM.ITEMID = _$ITEMID)));
      LEAVE PROC;
    END IF;

    -- 거래명세서 헤더 (발주별 1장)
    SET _$INVOICEKEY = GETKEY('INVOICEKEY');

    INSERT INTO MTRCUST_INVOICE_HEADER (INVOICEKEY, INVOICETP, INVOICEDATE, CUSTCD_GIVER, CUSTCD_RECIEVER, INWARE, EMPCD, RTIME, REMP, RPRG)
    VALUES (_$INVOICEKEY, '01', LEFT($PRDDATE, 10), _$CUSTCD, '', '', CALLEMP(), CALLTIME(), CALLEMP(), CALLPRG());   -- 유상사급은 사내창고(04S100_N)로 입고

    INSERT INTO TEMP_INV (INVOICEKEY) VALUES (_$INVOICEKEY);

    -- 이 발주의 BOX 행마다 BOX 수량만큼 LOT 생성
    WHILE EXISTS (SELECT 1 FROM TEMP_BOX
                    WHERE TEMP_BOX.DONEYN = 'N'
                      AND TEMP_BOX.MTRODRKEY = _$MTRODRKEY
                      AND TEMP_BOX.MTRODRSEQ = _$MTRODRSEQ) DO

      SELECT TEMP_BOX.SEQ, TEMP_BOX.HEATNO, TEMP_BOX.BOXQTY, TEMP_BOX.BOXCNT
        INTO _$SEQ, _$BOXHEATNO, _$BOXQTY, _$BOXCNT
        FROM TEMP_BOX
        WHERE TEMP_BOX.DONEYN = 'N'
          AND TEMP_BOX.MTRODRKEY = _$MTRODRKEY
          AND TEMP_BOX.MTRODRSEQ = _$MTRODRSEQ
        ORDER BY TEMP_BOX.SEQ
        LIMIT 1;

      SET _$I = 0;
      BOX_LOOP: WHILE _$I < _$BOXCNT DO
        SET _$LOTKEY = GETLOTKEY_DLV(LEFT($PRDDATE, 10));

        INSERT INTO MTRCUSTLOT (MTRODRKEY, MTRODRSEQ, LOTKEY, ITEMID, PRDDATE, LOTQTY, CARINQTY, HEATNO, RTIME, REMP, RPRG)
        VALUES (_$MTRODRKEY, _$MTRODRSEQ, _$LOTKEY, _$ITEMID, LEFT($PRDDATE, 10), _$BOXQTY, _$BOXQTY, _$BOXHEATNO, CALLTIME(), CALLEMP(), CALLPRG());

        INSERT INTO MTRCUST_INVOICE_DETAIL (INVOICEKEY, LOTKEY, LOTQTY, ITEMID, LOTTP, RTIME, REMP, RPRG)
        VALUES (_$INVOICEKEY, _$LOTKEY, _$BOXQTY, _$ITEMID, '01', CALLTIME(), CALLEMP(), CALLPRG());

        SET _$I = _$I + 1;
      END WHILE BOX_LOOP;

      UPDATE TEMP_BOX SET TEMP_BOX.DONEYN = 'Y' WHERE TEMP_BOX.SEQ = _$SEQ;
    END WHILE;

  END WHILE;

  /* =========================================================
     2-1. ERP 인터페이스 : 납품등록 송신 (입고 없이 납품만. 입고는 TML1020_R09 입고확인 때 PUR 로 송신)
     ========================================================= */
  SET _$INVOICEKEY = (SELECT MIN(TEMP_INV.INVOICEKEY) FROM TEMP_INV);

  WHILE _$INVOICEKEY IS NOT NULL DO
    CALL IO_ERP_INTERFACE('DLV_INV', _$INVOICEKEY, 'I');

    IF IFNULL(@ERRMSG, '') <> '' THEN
      LEAVE PROC;
    END IF;

    SET _$INVOICEKEY = (SELECT MIN(TEMP_INV.INVOICEKEY) FROM TEMP_INV WHERE TEMP_INV.INVOICEKEY > _$INVOICEKEY);
  END WHILE;

  /* =========================================================
     3. 결과 : 이번에 만든 거래명세서들의 LOT (화면 결과 팝업·출력용)
     ========================================================= */
  SELECT
    MTRCUST_INVOICE_DETAIL.INVOICEKEY,
    MSTITEM.ITEMCD,
    MSTITEM.ITEMNM,
    MTRCUST_INVOICE_DETAIL.LOTKEY,
    MTRCUST_INVOICE_DETAIL.LOTQTY,
    MTRCUST_INVOICE_HEADER.INVOICEDATE AS PRDDATE,
    GPCD('CUSTCD', MTRCUST_INVOICE_HEADER.CUSTCD_GIVER) AS OUTCUSTCD,
    'S&S INC 2공장' AS INCUSTCD,
    GPCD('LOTTP', MTRCUST_INVOICE_DETAIL.LOTTP) AS LOTTP,
    MTRCUSTLOT.HEATNO
  FROM MTRCUST_INVOICE_DETAIL
  INNER JOIN MTRCUST_INVOICE_HEADER ON MTRCUST_INVOICE_HEADER.INVOICEKEY = MTRCUST_INVOICE_DETAIL.INVOICEKEY
  INNER JOIN MSTITEM ON MSTITEM.ITEMID = MTRCUST_INVOICE_DETAIL.ITEMID
  LEFT JOIN MTRCUSTLOT ON MTRCUSTLOT.LOTKEY = MTRCUST_INVOICE_DETAIL.LOTKEY
  WHERE MTRCUST_INVOICE_DETAIL.INVOICEKEY IN (SELECT TEMP_INV.INVOICEKEY FROM TEMP_INV)
  ORDER BY MTRCUST_INVOICE_DETAIL.INVOICEKEY, MTRCUST_INVOICE_DETAIL.LOTKEY;

  DROP TEMPORARY TABLE IF EXISTS TEMP_BOX;
  DROP TEMPORARY TABLE IF EXISTS TEMP_INV;

-- ****************************************************************************
WHEN 'LIST_MTRCUSTLOT' THEN -- 발주상세보기

  IF $MTRODRKEY = '' THEN
    CALL COMERR('발주번호가 없습니다.');
    LEAVE PROC;
  END IF;

  IF NOT EXISTS (SELECT 1
                   FROM MTRCUSTLOT
                   WHERE MTRCUSTLOT.MTRODRKEY = $MTRODRKEY
                     AND MTRCUSTLOT.MTRODRSEQ = $MTRODRSEQ) THEN
    CALL COMERR('거래내역이 없는 발주입니다.');
    LEAVE PROC;
  END IF;

  SELECT
    MTRCUSTLOT.MTRODRKEY,
    MTRCUSTLOT.MTRODRSEQ,
    MSTITEM.ITEMCD,
    MSTITEM.ITEMNM,
    MTRCUSTLOT.LOTKEY,
    FORMAT(MTRCUSTLOT.LOTQTY, 0) AS LOTQTY,
    MTRCUSTLOT.HEATNO,
    MTRCUSTLOT.PRDDATE,
    GPCD('CUSTCD', MTRCUST_INVOICE_HEADER.CUSTCD_GIVER) AS OUTCUSTCD,
    'S&S INC 2공장' AS INCUSTCD,
    GPCD('LOTTP', MTRCUST_INVOICE_DETAIL.LOTTP) AS LOTTP
  FROM MTRCUSTLOT
  INNER JOIN MSTITEM ON MSTITEM.ITEMID = MTRCUSTLOT.ITEMID
  INNER JOIN MTRCUST_INVOICE_DETAIL ON MTRCUST_INVOICE_DETAIL.LOTKEY = MTRCUSTLOT.LOTKEY
  INNER JOIN MTRCUST_INVOICE_HEADER ON MTRCUST_INVOICE_HEADER.INVOICEKEY = MTRCUST_INVOICE_DETAIL.INVOICEKEY
  WHERE MTRCUSTLOT.MTRODRKEY = $MTRODRKEY
    AND MTRCUSTLOT.MTRODRSEQ = $MTRODRSEQ
  ORDER BY MTRCUSTLOT.PRDDATE, MTRCUSTLOT.LOTKEY;

-- ****************************************************************************
WHEN 'LIST_INVOICE' THEN -- [납품이력] 탭 : 납품일자 기간의 거래명세서 목록 (원자재·상품 납품 = 무상사급 구매 MM100910 발주분)

  SELECT
      H.INVOICEKEY
    , H.INVOICEDATE
    , GPCD('CUSTCD', H.CUSTCD_GIVER) AS CUSTNM
    , COUNT(D.LOTKEY) AS LOTCNT
    , SUM(D.LOTQTY) AS LOTQTY
    , IF(EXISTS (SELECT 1 FROM MTRIN WHERE MTRIN.INVOICEKEY = H.INVOICEKEY), '입고완료', '입고대기') AS INSTATUS
    , GPCD('EMPCD', H.EMPCD) AS EMPNM
    , H.RTIME
  FROM MTRCUST_INVOICE_HEADER AS H
  INNER JOIN MTRCUST_INVOICE_DETAIL AS D ON D.INVOICEKEY = H.INVOICEKEY
  WHERE H.INVOICETP = '01'
    AND H.INVOICEDATE BETWEEN LEFT($SDATE, 10) AND LEFT($EDATE, 10)
    AND H.CUSTCD_GIVER LIKE CONCAT('%', IFNULL($CUSTCD, ''), '%')
    AND EXISTS (SELECT 1
                  FROM MTRCUST_INVOICE_DETAIL AS D2
                 INNER JOIN MTRCUSTLOT AS L2 ON L2.LOTKEY = D2.LOTKEY
                 INNER JOIN MTRODR AS O2 ON O2.MTRODRKEY = L2.MTRODRKEY
                 WHERE D2.INVOICEKEY = H.INVOICEKEY AND O2.ODRBC = 'MM100910')
  GROUP BY H.INVOICEKEY, H.INVOICEDATE, H.CUSTCD_GIVER, H.EMPCD, H.RTIME
  ORDER BY H.RTIME DESC;

-- ****************************************************************************
WHEN 'DEL_MTRCUSTLOT' THEN  -- 출하 취소

  IF $INVOICEKEY = '' THEN
    CALL COMERR('거래명세서 번호가 없습니다.');
    LEAVE PROC;
  END IF;

  IF NOT EXISTS (SELECT 1
                   FROM MTRCUST_INVOICE_HEADER
                   WHERE MTRCUST_INVOICE_HEADER.INVOICEKEY = $INVOICEKEY) THEN
    CALL COMERR('존재하지 않는 거래명세서입니다.');
    LEAVE PROC;
  END IF;

  -- 입고된 재고 LOT 를 이미 썼으면(이동·투입 등) 취소 불가
  IF EXISTS (SELECT 1
               FROM MTRIN
               INNER JOIN MTRINLOT ON MTRINLOT.MTRINKEY = MTRIN.MTRINKEY
               LEFT JOIN COMLOT ON COMLOT.LOTKEY = MTRINLOT.LOTKEY
                               AND COMLOT.WARECD = MTRIN.WARECD
               WHERE MTRIN.INVOICEKEY = $INVOICEKEY
                 AND (COMLOT.LOTKEY IS NULL OR COMLOT.LOTQTY <> COMLOT.CRTQTY)) THEN
    CALL COMERR('S&S 에 입고된 재고를 이미 사용(이동·투입)하여 납품 취소할 수 없습니다.');
    LEAVE PROC;
  END IF;

  -- 입고 취소 (자동입고 또는 TML1020 입고)
  SET _$MTRINKEY = (SELECT MIN(MTRIN.MTRINKEY) FROM MTRIN WHERE MTRIN.INVOICEKEY = $INVOICEKEY);

  WHILE _$MTRINKEY IS NOT NULL DO
    CALL IO_MTRINVOICE_DEL(_$MTRINKEY);

    IF IFNULL(@ERRMSG, '') <> '' THEN
      LEAVE PROC;
    END IF;

    SET _$MTRINKEY = (SELECT MIN(MTRIN.MTRINKEY) FROM MTRIN WHERE MTRIN.INVOICEKEY = $INVOICEKEY AND MTRIN.MTRINKEY > _$MTRINKEY);
  END WHILE;

  -- ERP 인터페이스 : 납품 취소 송신 (입고확인 취소 PUR D 는 위 IO_MTRINVOICE_DEL 에서 먼저 나감)
  CALL IO_ERP_INTERFACE('DLV_INV', $INVOICEKEY, 'D');

  IF IFNULL(@ERRMSG, '') <> '' THEN
    LEAVE PROC;
  END IF;

  DELETE FROM MTRCUSTLOT
  WHERE MTRCUSTLOT.LOTKEY IN (SELECT MTRCUST_INVOICE_DETAIL.LOTKEY
                                FROM MTRCUST_INVOICE_DETAIL
                                WHERE MTRCUST_INVOICE_DETAIL.INVOICEKEY = $INVOICEKEY);

  DELETE FROM MTRCUST_INVOICE_DETAIL
  WHERE MTRCUST_INVOICE_DETAIL.INVOICEKEY = $INVOICEKEY;

  DELETE FROM MTRCUST_INVOICE_HEADER
  WHERE MTRCUST_INVOICE_HEADER.INVOICEKEY = $INVOICEKEY;

-- ****************************************************************************
WHEN 'PRINT_INVOICE' THEN -- 거래명세서 + 공정이동표(재고) 출력 (TMLPRINT.MTR_1 / MTR_2)

  IF IFNULL($INVOICEKEY, '') = '' THEN
    CALL COMERR('거래명세서 번호가 없습니다.');
    LEAVE PROC;
  END IF;

  IF NOT EXISTS (SELECT 1
                   FROM MTRCUST_INVOICE_HEADER
                   WHERE MTRCUST_INVOICE_HEADER.INVOICEKEY = $INVOICEKEY) THEN
    CALL COMERR('존재하지 않는 거래명세서입니다.');
    LEAVE PROC;
  END IF;

  -- [0] 공급자 (납품한 외주처)
  SELECT
    MSTCUST.CUSTNM      AS INNM,
    MSTCUST.PRESIDENT   AS INPRES,
    MSTCUST.REGBUSSNUM  AS INNUM,
    MSTCUST.ADDR_PRT    AS INADDR,
    MSTCUST.REPRETEL    AS INTEL,
    MSTCUST.CUSTFAX     AS INFAX,
    MSTCUST.BIZTYPE_PRT AS INTYPE,
    MSTCUST.BIZKIND_PRT AS INKIND
  FROM MTRCUST_INVOICE_HEADER
  LEFT JOIN MSTCUST ON MSTCUST.CUSTCD = MTRCUST_INVOICE_HEADER.CUSTCD_GIVER
  WHERE MTRCUST_INVOICE_HEADER.INVOICEKEY = $INVOICEKEY;

  -- [1] 공급받는자 : 수신 거래처가 있으면(외주간 이동) 그 외주처, 없으면 S&S INC 2공장(사업장 71)
  SELECT
    IF(MSTCUST.CUSTCD IS NULL, MSTBDV.BDVBNM_PRT, IFNULL(MSTCUST.CUSTNM_PRT, MSTCUST.CUSTNM)) AS OUTNM,
    IF(MSTCUST.CUSTCD IS NULL, MSTBDV.BDVNMENG, MSTCUST.PRESIDENT)                           AS OUTPRES,
    IF(MSTCUST.CUSTCD IS NULL, MSTBDV.BDVREGNO, MSTCUST.REGBUSSNUM)                          AS OUTNUM,
    IF(MSTCUST.CUSTCD IS NULL, MSTBDV.ADDR, MSTCUST.ADDR_PRT)                                AS OUTADDR,
    IF(MSTCUST.CUSTCD IS NULL, MSTBDV.REPRETEL, MSTCUST.REPRETEL)                            AS OUTTEL,
    IF(MSTCUST.CUSTCD IS NULL, MSTBDV.FAXNO, MSTCUST.CUSTFAX)                                AS OUTFAX,
    IF(MSTCUST.CUSTCD IS NULL, MSTBDV.INDTYPE, MSTCUST.BIZTYPE_PRT)                          AS OUTTYPE,
    IF(MSTCUST.CUSTCD IS NULL, MSTBDV.INDKIND, MSTCUST.BIZKIND_PRT)                          AS OUTKIND
  FROM MTRCUST_INVOICE_HEADER
  LEFT JOIN MSTCUST ON MSTCUST.CUSTCD = MTRCUST_INVOICE_HEADER.CUSTCD_RECIEVER
                   AND IFNULL(MTRCUST_INVOICE_HEADER.CUSTCD_RECIEVER, '') <> ''
  INNER JOIN MSTBDV ON MSTBDV.BDVCD = '71'
  WHERE MTRCUST_INVOICE_HEADER.INVOICEKEY = $INVOICEKEY;

  -- [2] LOT 목록
  SELECT
    MSTITEM.ITEMCD,
    MSTITEM.ITEMNM,
    MSTITEM.ITEMSPEC AS SPEC,
    MTRCUST_INVOICE_DETAIL.LOTKEY,
    FORMAT(MTRCUST_INVOICE_DETAIL.LOTQTY - IFNULL(MTRCUST_INVOICE_DETAIL.TESTQTY, 0), 0) AS QTY,   -- 수량 = 이동량 - 시편수량
    MTRCUST_INVOICE_DETAIL.LOTQTY AS QTYNUM,   -- 품목별 수량(소계) 합산용 (이동량 = 수량 + 시편)
    IF(IFNULL(MTRCUST_INVOICE_DETAIL.TESTQTY, 0) > 0, FORMAT(MTRCUST_INVOICE_DETAIL.TESTQTY, 0), '') AS TESTQTY,   -- 시편
    '' AS REMARK
  FROM MTRCUST_INVOICE_DETAIL
  INNER JOIN MSTITEM ON MSTITEM.ITEMID = MTRCUST_INVOICE_DETAIL.ITEMID
  WHERE MTRCUST_INVOICE_DETAIL.INVOICEKEY = $INVOICEKEY
  ORDER BY MSTITEM.ITEMCD, MTRCUST_INVOICE_DETAIL.LOTKEY;

  -- [3] 거래일자·담당자·합계·거래명세서번호
  SELECT
    MTRCUST_INVOICE_HEADER.INVOICEDATE AS MOVEDATE,
    IFNULL(NULLIF(GPCD('EMPCD', MTRCUST_INVOICE_HEADER.EMPCD), ''), GPCD('CUSTCD', MTRCUST_INVOICE_HEADER.CUSTCD_GIVER)) AS EMPNM, -- 등록자가 없으면 외주처명
    FORMAT(IFNULL((SELECT SUM(MTRCUST_INVOICE_DETAIL.LOTQTY)
                     FROM MTRCUST_INVOICE_DETAIL
                     WHERE MTRCUST_INVOICE_DETAIL.INVOICEKEY = $INVOICEKEY), 0), 0) AS SUMQTY,
    MTRCUST_INVOICE_HEADER.INVOICEKEY AS OUTKEY,
    '' AS REMARK
  FROM MTRCUST_INVOICE_HEADER
  WHERE MTRCUST_INVOICE_HEADER.INVOICEKEY = $INVOICEKEY;

  -- [4] 공정이동표(재고) : LOT 1개당 1장
  SELECT
    MSTITEM.ITEMCD,
    MSTITEM.ITEMNM,
    MSTITEM.ITEMSPEC,
    IFNULL(MTRCUSTLOT.HEATNO, '') AS HEATNO,
    IFNULL(NULLIF(GPCD('EMPCD', MTRCUSTLOT.REMP), ''), GPCD('CUSTCD', MTRCUST_INVOICE_HEADER.CUSTCD_GIVER)) AS EMPNM, -- 발행자 (등록자가 없으면 외주처명)
    IFNULL(MTRCUSTLOT.PRDDATE, MTRCUST_INVOICE_HEADER.INVOICEDATE) AS PRINTDATE,
    MTRCUST_INVOICE_DETAIL.LOTKEY,
    IFNULL(GPCD('DM150', MSTITEM.ITEMUNIT), '') AS UNITNM,
    FORMAT(MTRCUST_INVOICE_DETAIL.LOTQTY, 0) AS LOTQTY
  FROM MTRCUST_INVOICE_DETAIL
  INNER JOIN MTRCUST_INVOICE_HEADER ON MTRCUST_INVOICE_HEADER.INVOICEKEY = MTRCUST_INVOICE_DETAIL.INVOICEKEY
  INNER JOIN MSTITEM ON MSTITEM.ITEMID = MTRCUST_INVOICE_DETAIL.ITEMID
  LEFT JOIN MTRCUSTLOT ON MTRCUSTLOT.LOTKEY = MTRCUST_INVOICE_DETAIL.LOTKEY
  WHERE MTRCUST_INVOICE_DETAIL.INVOICEKEY = $INVOICEKEY
  ORDER BY MTRCUST_INVOICE_DETAIL.LOTKEY;

