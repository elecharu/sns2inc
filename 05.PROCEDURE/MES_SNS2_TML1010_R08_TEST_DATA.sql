-- Create:  2026-11-18  한성수  7-AMP-50-245 발주 TEST-R08-1(발주승인 500)·TEST-R08-2(발주 300) 생성
-- *****************************************************************************
-- 최신 TML1010_R08 프로시저 적용 후 MES_SNS2에서 전체 선택 → Alt+X 실행
-- 발주 헤더는 최근 INC 2공장 ERP 발주 2건의 거래처·발주유형·구분·통화·부서·담당·창고를 그대로 사용
-- 발주일자는 실행일(발주조회 기본 기간 안), 납기일자는 실행일 + 14일, 입고공장 07
-- 같은 테스트 발주번호가 있으면 중단하며 기존 업무 데이터는 수정·삭제하지 않음

USE MES_SNS2;

DELIMITER $$
BEGIN NOT ATOMIC
  DECLARE _$ITEMID     INT;
  DECLARE _$EMPCD      VARCHAR(20);
  DECLARE _$SRCKEY1    VARCHAR(20);
  DECLARE _$SRCKEY2    VARCHAR(20);
  DECLARE _$TODAY      VARCHAR(10);
  DECLARE _$EXPDATE    VARCHAR(10);
  DECLARE _$OLD_EMP    VARCHAR(100) DEFAULT @CALLEMP;
  DECLARE _$OLD_PRG    VARCHAR(100) DEFAULT @CALLPRG;
  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    ROLLBACK;
    SET @CALLEMP = _$OLD_EMP;
    SET @CALLPRG = _$OLD_PRG;
    RESIGNAL;
  END;

  START TRANSACTION;

  IF EXISTS (SELECT 1 FROM MTRODR WHERE MTRODRKEY IN ('TEST-R08-1', 'TEST-R08-2') LIMIT 1) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '이미 생성된 테스트 발주입니다. 기존 테스트 결과를 유지하고 중단합니다.';
  END IF;

  SET _$ITEMID = (SELECT ITEMID FROM MSTITEM WHERE ITEMCD = '7-AMP-50-245' AND ENDYN = 'N' LIMIT 1);
  SET _$EMPCD = (SELECT EMPCD FROM MSTEMP WHERE FACTORYCD = '07' AND EMPCD <> '' ORDER BY EMPCD LIMIT 1);
  SET _$SRCKEY1 = (SELECT MTRODRKEY FROM MTRODR WHERE ODRFACTORY = '07' AND INFACTORYCD = '07' AND RPRG = 'IF'
                   ORDER BY MTRODRDATE DESC, MTRODRKEY DESC LIMIT 1);
  SET _$SRCKEY2 = (SELECT MTRODRKEY FROM MTRODR WHERE ODRFACTORY = '07' AND INFACTORYCD = '07' AND RPRG = 'IF'
                   ORDER BY MTRODRDATE DESC, MTRODRKEY DESC LIMIT 1 OFFSET 1);
  SET _$TODAY = LEFT(CALLTIME(), 10);
  SET _$EXPDATE = DATE_FORMAT(DATE_ADD(_$TODAY, INTERVAL 14 DAY), '%Y-%m-%d');

  IF _$ITEMID IS NULL THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '설비부품 7-AMP-50-245를 확인해주세요.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM MSTITEM_EQMPARTS WHERE ITEMID = _$ITEMID AND FACTORYCD = '07' LIMIT 1) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '7-AMP-50-245의 INC 2공장 설비부품 재고 정보를 확인해주세요.';
  END IF;
  IF _$EMPCD IS NULL OR _$SRCKEY1 IS NULL OR _$SRCKEY2 IS NULL THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'INC 2공장 사원·ERP 발주 정보를 확인해주세요.';
  END IF;

  SET @CALLEMP = _$EMPCD;
  SET @CALLPRG = 'TML1010_R08_TEST';

  -- 발주 헤더 2건 (기준 ERP 발주의 거래처·구분값 사용, 키·일자·상태·비고만 변경)
  INSERT INTO MTRODR (
    MTRODRKEY, MTRODRDATE, EXPDATE, CUSTEMPID, CUSTCD, ODRTP, ODRBC, URGBC, CURYBC, EXRT, DIBC,
    ODRDEPT, ODREMPID, ODRFACTORY, INFACTORYCD, INWARECD, INCUSTCD, MTRODRSTT, ODRENTBC, REMARK,
    RTIME, REMP, RPRG
  )
  SELECT 'TEST-R08-1', _$TODAY, _$EXPDATE, CUSTEMPID, CUSTCD, ODRTP, ODRBC, URGBC, CURYBC, EXRT, DIBC,
         ODRDEPT, ODREMPID, '07', '07', INWARECD, INCUSTCD, 'MM110201', ODRENTBC, 'TML1010_R08 발주조회 테스트 전용',
         CALLTIME(), CALLEMP(), CALLPRG()
  FROM MTRODR
  WHERE MTRODRKEY = _$SRCKEY1;

  INSERT INTO MTRODR (
    MTRODRKEY, MTRODRDATE, EXPDATE, CUSTEMPID, CUSTCD, ODRTP, ODRBC, URGBC, CURYBC, EXRT, DIBC,
    ODRDEPT, ODREMPID, ODRFACTORY, INFACTORYCD, INWARECD, INCUSTCD, MTRODRSTT, ODRENTBC, REMARK,
    RTIME, REMP, RPRG
  )
  SELECT 'TEST-R08-2', _$TODAY, _$EXPDATE, CUSTEMPID, CUSTCD, ODRTP, ODRBC, URGBC, CURYBC, EXRT, DIBC,
         ODRDEPT, ODREMPID, '07', '07', INWARECD, INCUSTCD, 'MM110100', ODRENTBC, 'TML1010_R08 발주조회 테스트 전용',
         CALLTIME(), CALLEMP(), CALLPRG()
  FROM MTRODR
  WHERE MTRODRKEY = _$SRCKEY2;

  -- 발주 상세 2건 (7-AMP-50-245, 입고수량 0)
  INSERT INTO MTRODRD (
    MTRODRKEY, MTRODRSEQ, ITEMID, ODRQTY, EXPDATE, DLVQTY, INQTY, MTRODRSTT, REMARK,
    RTIME, REMP, RPRG
  ) VALUES (
    'TEST-R08-1', 1, _$ITEMID, 500, _$EXPDATE, 0, 0, 'MM110201', '발주승인: 입고 가능 500',
    CALLTIME(), CALLEMP(), CALLPRG()
  ), (
    'TEST-R08-2', 1, _$ITEMID, 300, _$EXPDATE, 0, 0, 'MM110100', '발주: 입고 가능 300',
    CALLTIME(), CALLEMP(), CALLPRG()
  );

  COMMIT;
  SET @CALLEMP = _$OLD_EMP;
  SET @CALLPRG = _$OLD_PRG;
END$$
DELIMITER ;

-- 생성 결과 확인 (R08 발주조회와 같은 기준: 입고공장 07, 발주·발주확정·발주승인, 잔량 = 발주량 - MES 입고 합계)
SELECT MTRODRD.MTRODRKEY, MTRODRD.MTRODRSEQ, MTRODR.MTRODRDATE, MTRODR.CUSTCD, MSTCUST.CUSTNM,
       MTRODR.INFACTORYCD, MTRODRD.MTRODRSTT, MTRODRD.ODRQTY,
       MTRODRD.ODRQTY - IFNULL(INSUM.INQTY, 0) AS REMAINQTY
FROM MTRODRD
INNER JOIN MTRODR ON MTRODR.MTRODRKEY = MTRODRD.MTRODRKEY
LEFT JOIN MSTCUST ON MSTCUST.CUSTCD = MTRODR.CUSTCD
LEFT JOIN (SELECT MTRODRKEY, MTRODRSEQ, SUM(INOUTQTY) AS INQTY
           FROM INOUT_EQMPARTS
           WHERE INOROUT = 'IN' AND MTRODRKEY IN ('TEST-R08-1', 'TEST-R08-2')
           GROUP BY MTRODRKEY, MTRODRSEQ) INSUM
  ON INSUM.MTRODRKEY = MTRODRD.MTRODRKEY AND INSUM.MTRODRSEQ = MTRODRD.MTRODRSEQ
WHERE MTRODRD.MTRODRKEY IN ('TEST-R08-1', 'TEST-R08-2')
ORDER BY MTRODRD.MTRODRKEY;

