CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.TML1030_R02(
-- *****************************************************************************
-- Comment: 현장터미널 외주처 소모품 불출 (불출증 헤더 OSCCONSUM_RELEASE_FORM / 상세 OSCCONSUM_RELEASE_FORM_DETAIL)
--          소모품 = MSTITEM 소모공구류(ITEMCG DM100990)만, 분류 = MSTITEM_OSCCONSUM_CLASSIFY (2공장 07)
--          재고는 건드리지 않고 불출수량만 기록. 수령(RECIEVEDATE)·확정(CONFIRMDATE)된 불출증은 삭제 불가
-- Create:  2026-11-04 : 김영철
-- Modify:  2026-11-04 : 김영철 현재고(MSTITEM_OSCCONSUM) 검사·차감·되돌림 제거, LIST_POP_ITEM 현재고 제거
--          2026-11-04 : 김영철 PRINT_RELEASE 에 수령자(EMPNM_RECIEVE) 추가 (불출증 요청자 칸)
--          2026-11-04 : 김영철 LIST_RELEASE 수령된 불출증 노란색 표시(BACKGROUND)
--          2026-11-04 : 김영철 LIST_POP_ITEM·ADD_RELEASE 소모공구류(ITEMCG DM100990)만
--          2026-11-04 : 김영철 PRINT_RELEASE 에 확정자(EMPNM_CONFIRM) 추가 (불출증 S & S 칸)
--          2026-11-05 : 김영철 LIST_RELEASE 색상 변경 (수령 = 초록·흰 글씨, 확정 = 하늘색)
-- *****************************************************************************
  IN $SDATE           VARCHAR(10),      -- 조회 불출일자 시작
  IN $EDATE           VARCHAR(10),      -- 조회 불출일자 끝
  IN $RELEASEKEY      VARCHAR(50),      -- 불출증키
  IN $RELEASEDATE     VARCHAR(10),      -- 불출일자
  IN $EQMCD           VARCHAR(100),     -- 불출라인
  IN $EMPCD_RELEASE   VARCHAR(100),     -- 불출자
  IN $ITEMID_PRD      VARCHAR(100),     -- 소모품 필터: 제품
  IN $PRCDETAIL       VARCHAR(100),     -- 소모품 필터: 세부공정
  IN $TURRET          VARCHAR(100),     -- 소모품 필터: 터렛
  IN $ITEMID          VARCHAR(100),     -- 소모품ID (불출삭제)
  IN $ITEMID_LIST     MEDIUMTEXT,       -- 불출 소모품ID 목록
  IN $RELQTY_LIST     MEDIUMTEXT,       -- 불출수량 목록
-- *****************************************************************************
  IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- SET @DEBUGLOGYN = 'Y';
-- *****************************************************************************
  DECLARE _$NOW          VARCHAR(19);
  DECLARE _$RELEASEKEY   VARCHAR(50);
  DECLARE _$ITEMID_LIST  MEDIUMTEXT;
  DECLARE _$RELQTY_LIST  MEDIUMTEXT;
  DECLARE _$ITEMID       VARCHAR(100);
  DECLARE _$RELQTY       VARCHAR(100);
-- *****************************************************************************
CASE $CALLTYPE
-- *****************************************************************************
WHEN 'LIST_RELEASE' THEN  -- 불출증 헤더 조회 (불출일자 기간)

  SELECT
      OSCCONSUM_RELEASE_FORM.RELEASEKEY
    , OSCCONSUM_RELEASE_FORM.RELEASEDATE
    , OSCCONSUM_RELEASE_FORM.EQMCD
    , IFNULL(MSTLINE_EQM.EQMNM, OSCCONSUM_RELEASE_FORM.EQMCD) AS EQMNM
    , IFNULL((SELECT SUM(OSCCONSUM_RELEASE_FORM_DETAIL.RELQTY)
                FROM OSCCONSUM_RELEASE_FORM_DETAIL
               WHERE OSCCONSUM_RELEASE_FORM_DETAIL.RELEASEKEY = OSCCONSUM_RELEASE_FORM.RELEASEKEY), 0) AS TOTQTY
    , OSCCONSUM_RELEASE_FORM.EMPCD_RELEASE
    , IFNULL(MSTEMP.EMPNM, OSCCONSUM_RELEASE_FORM.EMPCD_RELEASE) AS EMPNM_RELEASE
    , IF(OSCCONSUM_RELEASE_FORM.RECIEVEDATE = '', 'N', 'Y') AS RECIEVEYN
    , OSCCONSUM_RELEASE_FORM.RECIEVEDATE
    , CASE  -- 확정 = 하늘색, 수령 = 초록([수령] 버튼 색)
        WHEN OSCCONSUM_RELEASE_FORM.CONFIRMDATE <> '' THEN 'SKYBLUE'
        WHEN OSCCONSUM_RELEASE_FORM.RECIEVEDATE <> '' THEN 'GREEN'
        ELSE ''
      END AS BACKGROUND
    , IF(OSCCONSUM_RELEASE_FORM.CONFIRMDATE = '' AND OSCCONSUM_RELEASE_FORM.RECIEVEDATE <> '', 'WHITE', '') AS FOREGROUND
  FROM OSCCONSUM_RELEASE_FORM
  LEFT JOIN MSTLINE_EQM
    ON MSTLINE_EQM.EQMCD = OSCCONSUM_RELEASE_FORM.EQMCD
  LEFT JOIN MSTEMP
    ON MSTEMP.EMPCD = OSCCONSUM_RELEASE_FORM.EMPCD_RELEASE
  WHERE OSCCONSUM_RELEASE_FORM.RELEASEDATE BETWEEN $SDATE AND $EDATE
  ORDER BY OSCCONSUM_RELEASE_FORM.RELEASEDATE DESC, OSCCONSUM_RELEASE_FORM.RELEASEKEY DESC;

-- *****************************************************************************
WHEN 'LIST_RELEASE_DETAIL' THEN  -- 불출증 상세 조회

  SELECT
      OSCCONSUM_RELEASE_FORM_DETAIL.RELEASEKEY
    , CAST(OSCCONSUM_RELEASE_FORM_DETAIL.ITEMID AS CHAR) AS ITEMID
    , MSTITEM.ITEMCD
    , MSTITEM.ITEMNM
    , MSTITEM.ITEMSPEC
    , OSCCONSUM_RELEASE_FORM_DETAIL.RELQTY
  FROM OSCCONSUM_RELEASE_FORM_DETAIL
  LEFT JOIN MSTITEM
    ON MSTITEM.ITEMID = OSCCONSUM_RELEASE_FORM_DETAIL.ITEMID
  WHERE OSCCONSUM_RELEASE_FORM_DETAIL.RELEASEKEY = $RELEASEKEY
  ORDER BY MSTITEM.ITEMCD;

-- *****************************************************************************
WHEN 'LIST_POP_ITEM' THEN  -- 불출 팝업: 불출라인에 분류등록된 소모품 (제품·세부공정·터렛 필터, 빈 값 = 전체)

  IF $EQMCD = '' THEN
    CALL COMERR('불출라인을 선택하십시오.');
    LEAVE PROC;
  END IF;

  SELECT
      CAST(MSTITEM.ITEMID AS CHAR) AS ITEMID
    , MSTITEM.ITEMCD
    , MSTITEM.ITEMNM
    , MSTITEM.ITEMSPEC
    , MSTITEM.ITEMUNIT
    , CAST(0 AS DECIMAL(20, 8)) AS RELQTY
  FROM MSTITEM
  WHERE MSTITEM.ITEMCG = 'DM100990'  -- 소모공구류만
    AND MSTITEM.ITEMID IN (SELECT MSTITEM_OSCCONSUM_CLASSIFY.ITEMID
                             FROM MSTITEM_OSCCONSUM_CLASSIFY
                            WHERE MSTITEM_OSCCONSUM_CLASSIFY.FACTORYCD = '07'
                              AND MSTITEM_OSCCONSUM_CLASSIFY.EQMCD = $EQMCD
                              AND ($ITEMID_PRD = '' OR MSTITEM_OSCCONSUM_CLASSIFY.ITEMID_PRD = CAST($ITEMID_PRD AS UNSIGNED))
                              AND ($PRCDETAIL = '' OR MSTITEM_OSCCONSUM_CLASSIFY.PRCDETAIL = $PRCDETAIL)
                              AND ($TURRET = '' OR MSTITEM_OSCCONSUM_CLASSIFY.TURRET = $TURRET))
  ORDER BY MSTITEM.ITEMCD;

-- *****************************************************************************
WHEN 'ADD_RELEASE' THEN  -- 불출증 생성 (헤더 + 상세). 생성한 불출증키를 돌려줌

  IF $RELEASEDATE = '' THEN
    CALL COMERR('불출일자를 입력하십시오.');
    LEAVE PROC;
  END IF;

  IF $EQMCD = '' THEN
    CALL COMERR('불출라인을 선택하십시오.');
    LEAVE PROC;
  END IF;

  IF $EMPCD_RELEASE = '' THEN
    CALL COMERR('불출자를 선택하십시오.');
    LEAVE PROC;
  END IF;

  IF IFNULL($ITEMID_LIST, '') = '' THEN
    CALL COMERR('불출할 소모품의 불출수량을 입력하십시오.');
    LEAVE PROC;
  END IF;

  -- 1) 먼저 전부 검사 (수량, 소모공구류 여부, 같은 소모품 중복)
  SET _$ITEMID_LIST = $ITEMID_LIST;
  SET _$RELQTY_LIST = $RELQTY_LIST;
  DROP TEMPORARY TABLE IF EXISTS TMP_RELEASE;
  CREATE TEMPORARY TABLE TMP_RELEASE (
    ITEMID  INT            NOT NULL,
    RELQTY  DECIMAL(20, 8) NOT NULL,
    PRIMARY KEY (ITEMID)
  );

  WHILE LENGTH(_$ITEMID_LIST) > 0 DO
    CALL COMSPLIT(_$ITEMID_LIST, _$ITEMID);
    CALL COMSPLIT(_$RELQTY_LIST, _$RELQTY);

    IF IFNULL(CAST(_$RELQTY AS DECIMAL(20, 8)), 0) <= 0 THEN
      CALL COMERR(CONCAT('불출수량을 0보다 크게 입력하십시오.'
                        , '\n- 소모품: ', IFNULL((SELECT MSTITEM.ITEMNM FROM MSTITEM WHERE MSTITEM.ITEMID = _$ITEMID), _$ITEMID)));
      LEAVE PROC;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM MSTITEM
                    WHERE MSTITEM.ITEMID = CAST(_$ITEMID AS UNSIGNED)
                      AND MSTITEM.ITEMCG = 'DM100990') THEN
      CALL COMERR(CONCAT('소모공구류 품목이 아닙니다.'
                        , '\n- 소모품: ', IFNULL((SELECT MSTITEM.ITEMNM FROM MSTITEM WHERE MSTITEM.ITEMID = _$ITEMID), _$ITEMID)));
      LEAVE PROC;
    END IF;

    IF EXISTS (SELECT 1 FROM TMP_RELEASE WHERE TMP_RELEASE.ITEMID = CAST(_$ITEMID AS UNSIGNED)) THEN
      CALL COMERR(CONCAT('같은 소모품이 두 번 선택되었습니다.'
                        , '\n- 소모품: ', IFNULL((SELECT MSTITEM.ITEMNM FROM MSTITEM WHERE MSTITEM.ITEMID = _$ITEMID), _$ITEMID)));
      LEAVE PROC;
    END IF;

    INSERT INTO TMP_RELEASE (ITEMID, RELQTY)
    VALUES (CAST(_$ITEMID AS UNSIGNED), CAST(_$RELQTY AS DECIMAL(20, 8)));
  END WHILE;

  -- 2) 불출증 생성
  SET _$NOW = CALLTIME();
  SET _$RELEASEKEY = GETKEY('OSCCONSUM_RELEASE');

  INSERT INTO OSCCONSUM_RELEASE_FORM (
      RELEASEKEY, RELEASEDATE, EQMCD, EMPCD_RELEASE
    , RTIME, REMP, RPRG)
  VALUES (
      _$RELEASEKEY, $RELEASEDATE, $EQMCD, $EMPCD_RELEASE
    , _$NOW, CALLEMP(), CALLPRG());

  INSERT INTO OSCCONSUM_RELEASE_FORM_DETAIL (
      RELEASEKEY, ITEMID, RELQTY
    , RTIME, REMP, RPRG)
  SELECT
      _$RELEASEKEY, TMP_RELEASE.ITEMID, TMP_RELEASE.RELQTY
    , _$NOW, CALLEMP(), CALLPRG()
  FROM TMP_RELEASE;

  DROP TEMPORARY TABLE IF EXISTS TMP_RELEASE;

  SELECT _$RELEASEKEY AS RELEASEKEY;

-- *****************************************************************************
WHEN 'DEL_RELEASE_DETAIL' THEN  -- 불출삭제 (소모품 1건, 남은 상세가 없으면 헤더도 삭제)

  IF NOT EXISTS (SELECT 1 FROM OSCCONSUM_RELEASE_FORM_DETAIL
                  WHERE OSCCONSUM_RELEASE_FORM_DETAIL.RELEASEKEY = $RELEASEKEY
                    AND OSCCONSUM_RELEASE_FORM_DETAIL.ITEMID = CAST($ITEMID AS UNSIGNED)) THEN
    CALL COMERR('이미 삭제되었거나 없는 불출 내역입니다.');
    LEAVE PROC;
  END IF;

  IF EXISTS (SELECT 1 FROM OSCCONSUM_RELEASE_FORM
              WHERE OSCCONSUM_RELEASE_FORM.RELEASEKEY = $RELEASEKEY
                AND (OSCCONSUM_RELEASE_FORM.RECIEVEDATE <> '' OR OSCCONSUM_RELEASE_FORM.CONFIRMDATE <> '')) THEN
    CALL COMERR('수령된 불출증은 삭제할 수 없습니다.');
    LEAVE PROC;
  END IF;

  DELETE FROM OSCCONSUM_RELEASE_FORM_DETAIL
  WHERE OSCCONSUM_RELEASE_FORM_DETAIL.RELEASEKEY = $RELEASEKEY
    AND OSCCONSUM_RELEASE_FORM_DETAIL.ITEMID = CAST($ITEMID AS UNSIGNED);

  IF NOT EXISTS (SELECT 1 FROM OSCCONSUM_RELEASE_FORM_DETAIL
                  WHERE OSCCONSUM_RELEASE_FORM_DETAIL.RELEASEKEY = $RELEASEKEY) THEN
    DELETE FROM OSCCONSUM_RELEASE_FORM
    WHERE OSCCONSUM_RELEASE_FORM.RELEASEKEY = $RELEASEKEY;
  END IF;

-- *****************************************************************************
WHEN 'PRINT_RELEASE' THEN  -- 불출증 출력 (1번째 = 헤더, 2번째 = 상세). TML1030_R03 수령 후 출력도 이것을 씀

  IF NOT EXISTS (SELECT 1 FROM OSCCONSUM_RELEASE_FORM WHERE OSCCONSUM_RELEASE_FORM.RELEASEKEY = $RELEASEKEY) THEN
    CALL COMERR('출력할 불출증이 없습니다.');
    LEAVE PROC;
  END IF;

  -- 서명칸: 대구텍 = 불출자, 요청자 = 수령자, S & S = 확정자 (안 했으면 '')
  -- 웹 수령확정(MST3001_R06) 출력물(04.Report MST3001 R06A)도 이것을 씀
  SELECT
      OSCCONSUM_RELEASE_FORM.RELEASEKEY
    , OSCCONSUM_RELEASE_FORM.RELEASEDATE
    , IFNULL(MSTLINE_EQM.EQMNM, OSCCONSUM_RELEASE_FORM.EQMCD) AS EQMNM
    , IFNULL(MSTEMP1.EMPNM, OSCCONSUM_RELEASE_FORM.EMPCD_RELEASE) AS EMPNM_RELEASE
    , IFNULL(MSTEMP2.EMPNM, OSCCONSUM_RELEASE_FORM.EMPCD_RECIEVE) AS EMPNM_RECIEVE
    , IFNULL(MSTEMP3.EMPNM, OSCCONSUM_RELEASE_FORM.EMPCD_CONFIRM) AS EMPNM_CONFIRM
  FROM OSCCONSUM_RELEASE_FORM
  LEFT JOIN MSTLINE_EQM
    ON MSTLINE_EQM.EQMCD = OSCCONSUM_RELEASE_FORM.EQMCD
  LEFT JOIN MSTEMP AS MSTEMP1
    ON MSTEMP1.EMPCD = OSCCONSUM_RELEASE_FORM.EMPCD_RELEASE
  LEFT JOIN MSTEMP AS MSTEMP2
    ON MSTEMP2.EMPCD = OSCCONSUM_RELEASE_FORM.EMPCD_RECIEVE
  LEFT JOIN MSTEMP AS MSTEMP3
    ON MSTEMP3.EMPCD = OSCCONSUM_RELEASE_FORM.EMPCD_CONFIRM
  WHERE OSCCONSUM_RELEASE_FORM.RELEASEKEY = $RELEASEKEY;

  SELECT
      IF(IFNULL(MSTITEM.ITEMSPEC, '') = '', IFNULL(MSTITEM.ITEMNM, ''), MSTITEM.ITEMSPEC) AS ITEMSPEC
    , OSCCONSUM_RELEASE_FORM_DETAIL.RELQTY
  FROM OSCCONSUM_RELEASE_FORM_DETAIL
  LEFT JOIN MSTITEM
    ON MSTITEM.ITEMID = OSCCONSUM_RELEASE_FORM_DETAIL.ITEMID
  WHERE OSCCONSUM_RELEASE_FORM_DETAIL.RELEASEKEY = $RELEASEKEY
  ORDER BY MSTITEM.ITEMCD;

-- *****************************************************************************
END CASE;
END
