CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.TML1030_R03(
-- *****************************************************************************
-- Comment: 현장터미널 외주처 소모품 수령 (불출증 OSCCONSUM_RELEASE_FORM / _DETAIL 의 수령일자·수령자·수령수량)
--          불출증 바코드(RELEASEKEY) 스캔 → 수령. 재고는 건드리지 않음
--          확정(CONFIRMDATE)된 불출증은 수령수량 수정·수령삭제 불가 (확정은 다른 메뉴)
-- Create:  2026-11-04 : 김영철
-- Modify:  2026-11-05 : 김영철 LIST_RELEASE 수령 색상 초록·흰 글씨로 변경 (확정 = 하늘색 그대로)
-- *****************************************************************************
  IN $SDATE           VARCHAR(10),      -- 조회 불출일자 시작
  IN $EDATE           VARCHAR(10),      -- 조회 불출일자 끝
  IN $RELEASEKEY      VARCHAR(50),      -- 불출증키 (스캔값)
  IN $RECIEVEDATE     VARCHAR(10),      -- 수령일자
  IN $EMPCD_RECIEVE   VARCHAR(100),     -- 수령자
  IN $ITEMID_LIST     MEDIUMTEXT,       -- 소모품ID 목록
  IN $RECQTY_LIST     MEDIUMTEXT,       -- 수령수량 목록
  IN $RELEASEKEY_LIST MEDIUMTEXT,       -- 수령삭제 불출증키 목록
-- *****************************************************************************
  IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- SET @DEBUGLOGYN = 'Y';
-- *****************************************************************************
  DECLARE _$NOW          VARCHAR(19);
  DECLARE _$ITEMID_LIST  MEDIUMTEXT;
  DECLARE _$RECQTY_LIST  MEDIUMTEXT;
  DECLARE _$KEY_LIST     MEDIUMTEXT;
  DECLARE _$ITEMID       VARCHAR(100);
  DECLARE _$RECQTY       VARCHAR(100);
  DECLARE _$RELEASEKEY   VARCHAR(50);
-- *****************************************************************************
CASE $CALLTYPE
-- *****************************************************************************
WHEN 'LIST_RELEASE' THEN  -- 불출증 헤더 조회 (불출일자 기간)

  SELECT
      OSCCONSUM_RELEASE_FORM.RELEASEKEY
    , OSCCONSUM_RELEASE_FORM.RELEASEDATE
    , IFNULL(MSTLINE_EQM.EQMNM, OSCCONSUM_RELEASE_FORM.EQMCD) AS EQMNM
    , IFNULL((SELECT SUM(OSCCONSUM_RELEASE_FORM_DETAIL.RELQTY)
                FROM OSCCONSUM_RELEASE_FORM_DETAIL
               WHERE OSCCONSUM_RELEASE_FORM_DETAIL.RELEASEKEY = OSCCONSUM_RELEASE_FORM.RELEASEKEY), 0) AS TOTQTY
    , IFNULL(MSTEMP1.EMPNM, OSCCONSUM_RELEASE_FORM.EMPCD_RELEASE) AS EMPNM_RELEASE
    , IFNULL(MSTEMP2.EMPNM, OSCCONSUM_RELEASE_FORM.EMPCD_RECIEVE) AS EMPNM_RECIEVE
    , OSCCONSUM_RELEASE_FORM.RECIEVEDATE
    , IF(OSCCONSUM_RELEASE_FORM.RECIEVEDATE = '', 'N', 'Y') AS RECIEVEYN
    , IF(OSCCONSUM_RELEASE_FORM.CONFIRMDATE = '', 'N', 'Y') AS CONFIRMYN
    , CASE
        WHEN OSCCONSUM_RELEASE_FORM.CONFIRMDATE <> '' THEN 'SKYBLUE'
        WHEN OSCCONSUM_RELEASE_FORM.RECIEVEDATE <> '' THEN 'GREEN'  -- [수령] 버튼 색
        ELSE ''
      END AS BACKGROUND
    , IF(OSCCONSUM_RELEASE_FORM.CONFIRMDATE = '' AND OSCCONSUM_RELEASE_FORM.RECIEVEDATE <> '', 'WHITE', '') AS FOREGROUND
  FROM OSCCONSUM_RELEASE_FORM
  LEFT JOIN MSTLINE_EQM
    ON MSTLINE_EQM.EQMCD = OSCCONSUM_RELEASE_FORM.EQMCD
  LEFT JOIN MSTEMP AS MSTEMP1
    ON MSTEMP1.EMPCD = OSCCONSUM_RELEASE_FORM.EMPCD_RELEASE
  LEFT JOIN MSTEMP AS MSTEMP2
    ON MSTEMP2.EMPCD = OSCCONSUM_RELEASE_FORM.EMPCD_RECIEVE
  WHERE OSCCONSUM_RELEASE_FORM.RELEASEDATE BETWEEN $SDATE AND $EDATE
  ORDER BY OSCCONSUM_RELEASE_FORM.RELEASEDATE DESC, OSCCONSUM_RELEASE_FORM.RELEASEKEY DESC;

-- *****************************************************************************
WHEN 'LIST_RELEASE_DETAIL' THEN  -- 불출증 상세 조회

  SELECT
      OSCCONSUM_RELEASE_FORM_DETAIL.RELEASEKEY
    , CAST(OSCCONSUM_RELEASE_FORM_DETAIL.ITEMID AS CHAR) AS ITEMID
    , MSTITEM.ITEMCD
    , MSTITEM.ITEMNM
    , MSTITEM.ITEMSPEC
    , OSCCONSUM_RELEASE_FORM_DETAIL.RELQTY
    , OSCCONSUM_RELEASE_FORM_DETAIL.RECQTY
  FROM OSCCONSUM_RELEASE_FORM_DETAIL
  LEFT JOIN MSTITEM
    ON MSTITEM.ITEMID = OSCCONSUM_RELEASE_FORM_DETAIL.ITEMID
  WHERE OSCCONSUM_RELEASE_FORM_DETAIL.RELEASEKEY = $RELEASEKEY
  ORDER BY MSTITEM.ITEMCD;

-- *****************************************************************************
WHEN 'SCAN_RELEASE' THEN  -- 불출증 스캔: 수령 전 불출증의 헤더 + 상세 (수령수량 기본값 = 불출수량)

  SET $RELEASEKEY = TRIM(IFNULL($RELEASEKEY, ''));

  IF $RELEASEKEY = '' THEN
    CALL COMERR('불출증을 스캔하십시오.');
    LEAVE PROC;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM OSCCONSUM_RELEASE_FORM WHERE OSCCONSUM_RELEASE_FORM.RELEASEKEY = $RELEASEKEY) THEN
    CALL COMERR(CONCAT('없는 불출증입니다.', '\n- 불출증: ', $RELEASEKEY));
    LEAVE PROC;
  END IF;

  IF EXISTS (SELECT 1 FROM OSCCONSUM_RELEASE_FORM
              WHERE OSCCONSUM_RELEASE_FORM.RELEASEKEY = $RELEASEKEY
                AND OSCCONSUM_RELEASE_FORM.RECIEVEDATE <> '') THEN
    CALL COMERR(CONCAT('이미 수령된 불출증입니다.', '\n- 불출증: ', $RELEASEKEY));
    LEAVE PROC;
  END IF;

  SELECT
      OSCCONSUM_RELEASE_FORM.RELEASEKEY
    , OSCCONSUM_RELEASE_FORM.RELEASEDATE
    , IFNULL(MSTLINE_EQM.EQMNM, OSCCONSUM_RELEASE_FORM.EQMCD) AS EQMNM
    , IFNULL(MSTEMP.EMPNM, OSCCONSUM_RELEASE_FORM.EMPCD_RELEASE) AS EMPNM_RELEASE
  FROM OSCCONSUM_RELEASE_FORM
  LEFT JOIN MSTLINE_EQM
    ON MSTLINE_EQM.EQMCD = OSCCONSUM_RELEASE_FORM.EQMCD
  LEFT JOIN MSTEMP
    ON MSTEMP.EMPCD = OSCCONSUM_RELEASE_FORM.EMPCD_RELEASE
  WHERE OSCCONSUM_RELEASE_FORM.RELEASEKEY = $RELEASEKEY;

  SELECT
      CAST(OSCCONSUM_RELEASE_FORM_DETAIL.ITEMID AS CHAR) AS ITEMID
    , MSTITEM.ITEMCD
    , MSTITEM.ITEMNM
    , MSTITEM.ITEMSPEC
    , OSCCONSUM_RELEASE_FORM_DETAIL.RELQTY
    , OSCCONSUM_RELEASE_FORM_DETAIL.RELQTY AS RECQTY
  FROM OSCCONSUM_RELEASE_FORM_DETAIL
  LEFT JOIN MSTITEM
    ON MSTITEM.ITEMID = OSCCONSUM_RELEASE_FORM_DETAIL.ITEMID
  WHERE OSCCONSUM_RELEASE_FORM_DETAIL.RELEASEKEY = $RELEASEKEY
  ORDER BY MSTITEM.ITEMCD;

-- *****************************************************************************
WHEN 'ADD_RECEIVE' THEN  -- 수령 (수령일자·수령자, 소모품별 수령수량)

  IF $RELEASEKEY = '' THEN
    CALL COMERR('불출증을 스캔하십시오.');
    LEAVE PROC;
  END IF;

  IF $RECIEVEDATE = '' THEN
    CALL COMERR('수령일자를 입력하십시오.');
    LEAVE PROC;
  END IF;

  IF $EMPCD_RECIEVE = '' THEN
    CALL COMERR('수령자를 선택하십시오.');
    LEAVE PROC;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM OSCCONSUM_RELEASE_FORM WHERE OSCCONSUM_RELEASE_FORM.RELEASEKEY = $RELEASEKEY) THEN
    CALL COMERR(CONCAT('없는 불출증입니다.', '\n- 불출증: ', $RELEASEKEY));
    LEAVE PROC;
  END IF;

  IF EXISTS (SELECT 1 FROM OSCCONSUM_RELEASE_FORM
              WHERE OSCCONSUM_RELEASE_FORM.RELEASEKEY = $RELEASEKEY
                AND OSCCONSUM_RELEASE_FORM.RECIEVEDATE <> '') THEN
    CALL COMERR(CONCAT('이미 수령된 불출증입니다.', '\n- 불출증: ', $RELEASEKEY));
    LEAVE PROC;
  END IF;

  -- 수령수량 검사 (0 이상, 이 불출증의 소모품)
  SET _$ITEMID_LIST = $ITEMID_LIST;
  SET _$RECQTY_LIST = $RECQTY_LIST;
  WHILE LENGTH(_$ITEMID_LIST) > 0 DO
    CALL COMSPLIT(_$ITEMID_LIST, _$ITEMID);
    CALL COMSPLIT(_$RECQTY_LIST, _$RECQTY);

    IF IFNULL(CAST(_$RECQTY AS DECIMAL(20, 8)), -1) < 0 THEN
      CALL COMERR(CONCAT('수령수량을 0 이상으로 입력하십시오.'
                        , '\n- 소모품: ', IFNULL((SELECT MSTITEM.ITEMNM FROM MSTITEM WHERE MSTITEM.ITEMID = _$ITEMID), _$ITEMID)));
      LEAVE PROC;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM OSCCONSUM_RELEASE_FORM_DETAIL
                    WHERE OSCCONSUM_RELEASE_FORM_DETAIL.RELEASEKEY = $RELEASEKEY
                      AND OSCCONSUM_RELEASE_FORM_DETAIL.ITEMID = CAST(_$ITEMID AS UNSIGNED)) THEN
      CALL COMERR(CONCAT('불출증에 없는 소모품입니다.', '\n- 소모품ID: ', _$ITEMID));
      LEAVE PROC;
    END IF;
  END WHILE;

  SET _$NOW = CALLTIME();

  UPDATE OSCCONSUM_RELEASE_FORM
  SET OSCCONSUM_RELEASE_FORM.RECIEVEDATE = $RECIEVEDATE
    , OSCCONSUM_RELEASE_FORM.EMPCD_RECIEVE = $EMPCD_RECIEVE
    , OSCCONSUM_RELEASE_FORM.MTIME = _$NOW
    , OSCCONSUM_RELEASE_FORM.MEMP = CALLEMP()
    , OSCCONSUM_RELEASE_FORM.MPRG = CALLPRG()
  WHERE OSCCONSUM_RELEASE_FORM.RELEASEKEY = $RELEASEKEY;

  SET _$ITEMID_LIST = $ITEMID_LIST;
  SET _$RECQTY_LIST = $RECQTY_LIST;
  WHILE LENGTH(_$ITEMID_LIST) > 0 DO
    CALL COMSPLIT(_$ITEMID_LIST, _$ITEMID);
    CALL COMSPLIT(_$RECQTY_LIST, _$RECQTY);

    UPDATE OSCCONSUM_RELEASE_FORM_DETAIL
    SET OSCCONSUM_RELEASE_FORM_DETAIL.RECQTY = CAST(_$RECQTY AS DECIMAL(20, 8))
      , OSCCONSUM_RELEASE_FORM_DETAIL.MTIME = _$NOW
      , OSCCONSUM_RELEASE_FORM_DETAIL.MEMP = CALLEMP()
      , OSCCONSUM_RELEASE_FORM_DETAIL.MPRG = CALLPRG()
    WHERE OSCCONSUM_RELEASE_FORM_DETAIL.RELEASEKEY = $RELEASEKEY
      AND OSCCONSUM_RELEASE_FORM_DETAIL.ITEMID = CAST(_$ITEMID AS UNSIGNED);
  END WHILE;

-- *****************************************************************************
WHEN 'SAVE_RECQTY' THEN  -- 수령수량 수정 (수령된 불출증만, 확정된 불출증은 불가)

  IF $RELEASEKEY = '' THEN
    CALL COMERR('불출증을 선택하십시오.');
    LEAVE PROC;
  END IF;

  IF EXISTS (SELECT 1 FROM OSCCONSUM_RELEASE_FORM
              WHERE OSCCONSUM_RELEASE_FORM.RELEASEKEY = $RELEASEKEY
                AND OSCCONSUM_RELEASE_FORM.RECIEVEDATE = '') THEN
    CALL COMERR('수령 전 불출증입니다. [수령] 으로 먼저 수령하십시오.');
    LEAVE PROC;
  END IF;

  IF EXISTS (SELECT 1 FROM OSCCONSUM_RELEASE_FORM
              WHERE OSCCONSUM_RELEASE_FORM.RELEASEKEY = $RELEASEKEY
                AND OSCCONSUM_RELEASE_FORM.CONFIRMDATE <> '') THEN
    CALL COMERR('수령확정된 불출증은 수정할 수 없습니다.');
    LEAVE PROC;
  END IF;

  SET _$ITEMID_LIST = $ITEMID_LIST;
  SET _$RECQTY_LIST = $RECQTY_LIST;
  WHILE LENGTH(_$ITEMID_LIST) > 0 DO
    CALL COMSPLIT(_$ITEMID_LIST, _$ITEMID);
    CALL COMSPLIT(_$RECQTY_LIST, _$RECQTY);

    IF IFNULL(CAST(_$RECQTY AS DECIMAL(20, 8)), -1) < 0 THEN
      CALL COMERR(CONCAT('수령수량을 0 이상으로 입력하십시오.'
                        , '\n- 소모품: ', IFNULL((SELECT MSTITEM.ITEMNM FROM MSTITEM WHERE MSTITEM.ITEMID = _$ITEMID), _$ITEMID)));
      LEAVE PROC;
    END IF;
  END WHILE;

  SET _$NOW = CALLTIME();

  SET _$ITEMID_LIST = $ITEMID_LIST;
  SET _$RECQTY_LIST = $RECQTY_LIST;
  WHILE LENGTH(_$ITEMID_LIST) > 0 DO
    CALL COMSPLIT(_$ITEMID_LIST, _$ITEMID);
    CALL COMSPLIT(_$RECQTY_LIST, _$RECQTY);

    UPDATE OSCCONSUM_RELEASE_FORM_DETAIL
    SET OSCCONSUM_RELEASE_FORM_DETAIL.RECQTY = CAST(_$RECQTY AS DECIMAL(20, 8))
      , OSCCONSUM_RELEASE_FORM_DETAIL.MTIME = _$NOW
      , OSCCONSUM_RELEASE_FORM_DETAIL.MEMP = CALLEMP()
      , OSCCONSUM_RELEASE_FORM_DETAIL.MPRG = CALLPRG()
    WHERE OSCCONSUM_RELEASE_FORM_DETAIL.RELEASEKEY = $RELEASEKEY
      AND OSCCONSUM_RELEASE_FORM_DETAIL.ITEMID = CAST(_$ITEMID AS UNSIGNED);
  END WHILE;

-- *****************************************************************************
WHEN 'DEL_RECEIVE' THEN  -- 수령삭제 (체크한 불출증의 수령일자·수령자·수령수량 비움, 확정된 불출증은 불가)

  IF IFNULL($RELEASEKEY_LIST, '') = '' THEN
    CALL COMERR('수령삭제할 불출증을 체크하십시오.');
    LEAVE PROC;
  END IF;

  -- 먼저 전부 검사
  SET _$KEY_LIST = $RELEASEKEY_LIST;
  WHILE LENGTH(_$KEY_LIST) > 0 DO
    CALL COMSPLIT(_$KEY_LIST, _$RELEASEKEY);

    IF EXISTS (SELECT 1 FROM OSCCONSUM_RELEASE_FORM
                WHERE OSCCONSUM_RELEASE_FORM.RELEASEKEY = _$RELEASEKEY
                  AND OSCCONSUM_RELEASE_FORM.CONFIRMDATE <> '') THEN
      CALL COMERR(CONCAT('수령확정된 불출증은 수령삭제할 수 없습니다.', '\n- 불출증: ', _$RELEASEKEY));
      LEAVE PROC;
    END IF;

    IF EXISTS (SELECT 1 FROM OSCCONSUM_RELEASE_FORM
                WHERE OSCCONSUM_RELEASE_FORM.RELEASEKEY = _$RELEASEKEY
                  AND OSCCONSUM_RELEASE_FORM.RECIEVEDATE = '') THEN
      CALL COMERR(CONCAT('수령 전 불출증입니다.', '\n- 불출증: ', _$RELEASEKEY));
      LEAVE PROC;
    END IF;
  END WHILE;

  SET _$NOW = CALLTIME();

  SET _$KEY_LIST = $RELEASEKEY_LIST;
  WHILE LENGTH(_$KEY_LIST) > 0 DO
    CALL COMSPLIT(_$KEY_LIST, _$RELEASEKEY);

    UPDATE OSCCONSUM_RELEASE_FORM
    SET OSCCONSUM_RELEASE_FORM.RECIEVEDATE = ''
      , OSCCONSUM_RELEASE_FORM.EMPCD_RECIEVE = ''
      , OSCCONSUM_RELEASE_FORM.MTIME = _$NOW
      , OSCCONSUM_RELEASE_FORM.MEMP = CALLEMP()
      , OSCCONSUM_RELEASE_FORM.MPRG = CALLPRG()
    WHERE OSCCONSUM_RELEASE_FORM.RELEASEKEY = _$RELEASEKEY;

    UPDATE OSCCONSUM_RELEASE_FORM_DETAIL
    SET OSCCONSUM_RELEASE_FORM_DETAIL.RECQTY = 0
      , OSCCONSUM_RELEASE_FORM_DETAIL.MTIME = _$NOW
      , OSCCONSUM_RELEASE_FORM_DETAIL.MEMP = CALLEMP()
      , OSCCONSUM_RELEASE_FORM_DETAIL.MPRG = CALLPRG()
    WHERE OSCCONSUM_RELEASE_FORM_DETAIL.RELEASEKEY = _$RELEASEKEY;
  END WHILE;

-- *****************************************************************************
END CASE;
END
