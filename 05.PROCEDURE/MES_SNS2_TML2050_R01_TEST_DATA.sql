-- Comment: TML2050_R01 생산기술팀 호출 테스트 데이터 (작업장 M1)
-- Create:  2026-11-19  한성수  M1 생기팀 호출사원 5명 배치 + 진행 중 호출 5건 생성, 테스트 후 삭제 쿼리
-- *****************************************************************************
-- 최신 TML2050_R01 프로시저 적용 후 MES_SNS2에서 전체 선택 → Alt+X 실행
-- 작업장 M1 = I2M010_N (INC 2공장, 사용 설비 8대)
-- 1) 호출사원 배치: 생기팀(44F30) 재직 사원 5명(이광우·김다정·전석진·김정훈·김동택)을 M1 설비 8대에 모두 등록 (40행)
--    호출·수리시작 인원 후보 = 이 5명, 지연시간은 기존 등록값과 같은 도착 10분·수리 10분
-- 2) 진행 중 호출 5건: M1 설비 5대에 호출 상태(도착 전) 1건씩, 호출자는 생산팀(44F20) 재직 사원 5명
--    호출키 TEST2050-01 ~ 05, 호출시각은 실행 시각 기준 25·20·15·10·5분 전
--    호출하지 않은 설비 3대(세척기+건조기 T1, 자동 검사기 T2, 세척기 T2)는 화면에서 새 호출 시험용
-- 테스트 데이터는 등록프로그램(RPRG) TML2050_TEST, 같은 테스트 데이터가 있으면 중단하며 기존 업무 데이터는 수정·삭제하지 않음

USE MES_SNS2;

DELIMITER $$
BEGIN NOT ATOMIC
  DECLARE _$LINECD     VARCHAR(100) DEFAULT 'I2M010_N';
  DECLARE _$EQMCNT     INT;
  DECLARE _$EMPCNT     INT;
  DECLARE _$CALLEMPCNT INT;
  DECLARE _$OLD_EMP    VARCHAR(100) DEFAULT @CALLEMP;
  DECLARE _$OLD_PRG    VARCHAR(100) DEFAULT @CALLPRG;
  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    ROLLBACK;
    SET @CALLEMP = _$OLD_EMP;
    SET @CALLPRG = _$OLD_PRG;
    RESIGNAL;
  END;

  START TRANSACTION;

  IF EXISTS (SELECT 1 FROM MSTEQM_CALLEMP WHERE RPRG = 'TML2050_TEST' LIMIT 1)
     OR EXISTS (SELECT 1 FROM EQMCALLEMP WHERE EQMCALLKEY LIKE 'TEST2050-%' LIMIT 1) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '이미 생성된 TML2050 테스트 데이터가 있습니다. 아래 삭제 쿼리로 지운 뒤 다시 실행하세요.';
  END IF;

  SET _$EQMCNT = (SELECT COUNT(*) FROM MSTEQM
                  WHERE LINECD = _$LINECD AND USEYN = 'Y'
                    AND FANO IN ('I2C-002N', 'I2G-001N', 'I2S-001N', 'I2G-009N', 'I2ROT-003N'));
  SET _$EMPCNT = (SELECT COUNT(*) FROM MSTEMP
                  WHERE FACTORYCD = '07' AND DEPTCD = '44F30' AND STATBC = 'HR125100'
                    AND EMPCD IN ('202507146', '202507156', '202507159', '202507161', '202507162'));
  SET _$CALLEMPCNT = (SELECT COUNT(*) FROM MSTEMP
                      WHERE FACTORYCD = '07' AND DEPTCD = '44F20' AND STATBC = 'HR125100'
                        AND EMPCD IN ('202507049', '202507155', '202507158', '202507160', '202507163'));

  IF _$EQMCNT <> 5 THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'M1(I2M010_N) 호출 대상 설비 5대를 확인해주세요.';
  END IF;
  IF _$EMPCNT <> 5 OR _$CALLEMPCNT <> 5 THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '생기팀·생산팀 재직 사원 각 5명을 확인해주세요.';
  END IF;

  IF EXISTS (SELECT 1 FROM EQMCALLEMP AS C
              INNER JOIN EQMCALLEMP_EQM AS E ON C.EQMCALLKEY = E.EQMCALLKEY
              WHERE E.EQMCD IN ('I2C-002N', 'I2G-001N', 'I2S-001N', 'I2G-009N', 'I2ROT-003N')
                AND NOT EXISTS (SELECT 1 FROM EQMREP AS R
                                 WHERE R.EQMCALLKEY = C.EQMCALLKEY
                                   AND R.EQMCD = E.EQMCD
                                   AND R.REPETIME <> '')) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'M1 테스트 설비에 이미 진행 중인 호출이 있습니다.';
  END IF;

  SET @CALLEMP = '202507146';
  SET @CALLPRG = 'TML2050_TEST';

  -- 1) M1 설비 8대 × 생기팀 5명 호출사원 배치 (MST1004_R01 설비별 생기팀 호출사원과 같은 테이블)
  INSERT INTO MSTEQM_CALLEMP (
    EQMCD, EMPCD, DELAYMIN_ARRIVE, DELAYMIN_REPAIR, REMARK,
    RTIME, REMP, RPRG
  )
  SELECT M.FANO, P.EMPCD, 10, 10, 'TML2050 테스트',
         CALLTIME(), CALLEMP(), CALLPRG()
  FROM MSTEQM AS M
  CROSS JOIN MSTEMP AS P
  WHERE M.LINECD = _$LINECD
    AND M.USEYN = 'Y'
    AND P.EMPCD IN ('202507146', '202507156', '202507159', '202507161', '202507162')
    AND NOT EXISTS (SELECT 1 FROM MSTEQM_CALLEMP AS C WHERE C.EQMCD = M.FANO AND C.EMPCD = P.EMPCD);

  -- 2) 진행 중 호출 5건 (설비 1대당 1건, 도착 전 호출 상태)
  INSERT INTO EQMCALLEMP (
    EQMCALLKEY, LINECD, EQMTP, EQMGROUP1, CALLDATE, CALLTIME, EMPCD_CALL, REMARK,
    RTIME, REMP, RPRG
  )
  SELECT T.EQMCALLKEY, M.LINECD, M.EQMTP, M.EQMGROUP1,
         LEFT(T.CALLTIME, 10), T.CALLTIME, T.EMPCD_CALL, T.REMARK,
         CALLTIME(), CALLEMP(), CALLPRG()
  FROM (
    SELECT 'TEST2050-01' AS EQMCALLKEY, 'I2C-002N' AS EQMCD, '202507049' AS EMPCD_CALL, '설비 고장' AS REMARK,
           DATE_FORMAT(NOW() - INTERVAL 25 MINUTE, '%Y-%m-%d %H:%i:%s') AS CALLTIME
    UNION ALL
    SELECT 'TEST2050-02', 'I2G-001N', '202507155', '금형 이상', DATE_FORMAT(NOW() - INTERVAL 20 MINUTE, '%Y-%m-%d %H:%i:%s')
    UNION ALL
    SELECT 'TEST2050-03', 'I2S-001N', '202507158', '전기/센서', DATE_FORMAT(NOW() - INTERVAL 15 MINUTE, '%Y-%m-%d %H:%i:%s')
    UNION ALL
    SELECT 'TEST2050-04', 'I2G-009N', '202507160', '누유', DATE_FORMAT(NOW() - INTERVAL 10 MINUTE, '%Y-%m-%d %H:%i:%s')
    UNION ALL
    SELECT 'TEST2050-05', 'I2ROT-003N', '202507163', '소음/진동', DATE_FORMAT(NOW() - INTERVAL 5 MINUTE, '%Y-%m-%d %H:%i:%s')
  ) AS T
  INNER JOIN MSTEQM AS M ON M.FANO = T.EQMCD;

  INSERT INTO EQMCALLEMP_EQM (
    EQMCALLKEY, EQMCD,
    RTIME, REMP, RPRG
  ) VALUES
    ('TEST2050-01', 'I2C-002N',   CALLTIME(), CALLEMP(), CALLPRG()),
    ('TEST2050-02', 'I2G-001N',   CALLTIME(), CALLEMP(), CALLPRG()),
    ('TEST2050-03', 'I2S-001N',   CALLTIME(), CALLEMP(), CALLPRG()),
    ('TEST2050-04', 'I2G-009N',   CALLTIME(), CALLEMP(), CALLPRG()),
    ('TEST2050-05', 'I2ROT-003N', CALLTIME(), CALLEMP(), CALLPRG());

  COMMIT;
  SET @CALLEMP = _$OLD_EMP;
  SET @CALLPRG = _$OLD_PRG;
END$$
DELIMITER ;

-- 생성 결과 확인
SELECT C.EQMCD, M.EQMNM, C.EMPCD, P.EMPNM, C.RPRG
FROM MSTEQM_CALLEMP AS C
INNER JOIN MSTEQM AS M ON M.FANO = C.EQMCD
LEFT JOIN MSTEMP AS P ON P.EMPCD = C.EMPCD
WHERE C.RPRG = 'TML2050_TEST'
ORDER BY C.EQMCD, C.EMPCD;

SELECT C.EQMCALLKEY, E.EQMCD, M.EQMNM, C.CALLTIME, C.EMPCD_CALL, P.EMPNM AS EMPNM_CALL, C.REMARK
FROM EQMCALLEMP AS C
INNER JOIN EQMCALLEMP_EQM AS E ON E.EQMCALLKEY = C.EQMCALLKEY
INNER JOIN MSTEQM AS M ON M.FANO = E.EQMCD
LEFT JOIN MSTEMP AS P ON P.EMPCD = C.EMPCD_CALL
WHERE C.EQMCALLKEY LIKE 'TEST2050-%'
ORDER BY C.EQMCALLKEY;

-- 화면 시험 예: TML2050 작업장 M1 선택 → 카드 5장(호출) 표시
-- 호출 카드 선택 → 수리시작 → 인원(생기팀 5명) 선택 → 도착·수리시작 함께 등록 → 수리종료(수리 중 설비 선택)
-- 빈 설비(세척기+건조기 T1 등)로 호출 → ③ 호출 대상에 생기팀 5명 전원 표시

-- *****************************************************************************
-- 테스트 데이터 삭제 (테스트가 끝난 뒤 주석 해제 후 실행)
-- 삭제 대상: M1(I2M010_N)에서 2026-11-19 이후 등록된 호출(테스트 호출 + 화면에서 시험한 호출)과 그 도착자·호출설비,
--            그 호출의 수리와 M1 설비에 TML2050 화면으로 등록한 직접 수리(수리유형 EQM01)와 수리 작업자,
--            (직접 수리는 등록프로그램 TML2050_R01 또는 빈 값: 단말 실행 방식에 따라 RPRG가 비어 저장되는 경우 포함)
--            테스트로 배치한 생기팀 호출사원(RPRG TML2050_TEST)
-- 설비이력 등 다른 화면에서 등록한 수리, 예방보전(EQM02), 기존 호출사원 등록은 지우지 않음
-- 자식 테이블부터 지우므로 아래 순서대로 실행
-- *****************************************************************************
DELETE W FROM EQMREP_EMP AS W
 INNER JOIN EQMREP AS R ON R.EQMREPKEY = W.EQMREPKEY
 WHERE R.EQMREPTP = 'EQM01'
   AND R.RTIME >= '2026-11-19'
   AND R.EQMCD IN (SELECT FANO FROM MSTEQM WHERE LINECD = 'I2M010_N')
   AND (   R.EQMCALLKEY IN (SELECT EQMCALLKEY FROM EQMCALLEMP WHERE LINECD = 'I2M010_N' AND RTIME >= '2026-11-19')
        OR (R.EQMCALLKEY = '' AND R.RPRG IN ('TML2050_R01', '')));

DELETE R FROM EQMREP AS R
 WHERE R.EQMREPTP = 'EQM01'
   AND R.RTIME >= '2026-11-19'
   AND R.EQMCD IN (SELECT FANO FROM MSTEQM WHERE LINECD = 'I2M010_N')
   AND (   R.EQMCALLKEY IN (SELECT EQMCALLKEY FROM EQMCALLEMP WHERE LINECD = 'I2M010_N' AND RTIME >= '2026-11-19')
        OR (R.EQMCALLKEY = '' AND R.RPRG IN ('TML2050_R01', '')));

DELETE A FROM EQMCALLEMP_ARRV AS A
 INNER JOIN EQMCALLEMP AS C ON C.EQMCALLKEY = A.EQMCALLKEY
 WHERE C.LINECD = 'I2M010_N' AND C.RTIME >= '2026-11-19';

DELETE E FROM EQMCALLEMP_EQM AS E
 INNER JOIN EQMCALLEMP AS C ON C.EQMCALLKEY = E.EQMCALLKEY
 WHERE C.LINECD = 'I2M010_N' AND C.RTIME >= '2026-11-19';

DELETE FROM EQMCALLEMP WHERE LINECD = 'I2M010_N' AND RTIME >= '2026-11-19';

DELETE FROM MSTEQM_CALLEMP WHERE RPRG = 'TML2050_TEST';

