CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.TML5000_R01(
-- *****************************************************************************
-- Comment: 출하등록 (현장) - 2공장 수주 선택(다중) → 출고창고 선택 후 LOT 바코드 스캔 → 출하량·비고 수정 → 등록
--          등록하면 수주(상세)마다 출하 1건(SALOUT) + LOT(SALOUTLOT) 만들고 바로 출고확정 (IO_SALOUT_LOT)
-- Create: 2026-11-10
-- Modify: 2026-11-17 등록(ADD_SALOUT) 때 납품처별 거래명세서 이력(SALINVOICE·SALINVOICED, INVOICEKEY) 생성,
--                    그 출하의 출고이력 COMOUT.INVOICEKEY 에도 기록. 거래명세서(PRINT_SALOUT) 번호 = INVOICEKEY
-- *****************************************************************************
  IN $SDATE           VARCHAR(10),    -- 납기일자 시작
  IN $EDATE           VARCHAR(10),    -- 납기일자 끝
  IN $CUSTCD          VARCHAR(20),    -- 납품처
  IN $ITEMID          VARCHAR(20),    -- 품목
  IN $OUTDATE         VARCHAR(10),    -- 출하일자
  IN $WARECD          VARCHAR(20),    -- 출고창고
  IN $SCANLOT         VARCHAR(100),   -- 스캔 LOT
  IN $SALODRKEY_LIST  MEDIUMTEXT,     -- 수주번호 (SCAN_LOT: 선택한 수주들 / ADD_SALOUT: 출하 행마다)
  IN $ODRSEQ_LIST     MEDIUMTEXT,     -- 수주순번
  IN $LOTKEY_LIST     MEDIUMTEXT,     -- 출하 LOT
  IN $OUTQTY_LIST     MEDIUMTEXT,     -- LOT 별 출하량
  IN $REMARK_LIST     MEDIUMTEXT,     -- LOT 별 비고
  IN $SALOUTGROUPKEY  VARCHAR(50),    -- 출하번호 (거래명세서 출력: 한 번 등록한 납품처별 묶음)
-- *****************************************************************************
  IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- SET @DEBUGLOGYN = 'Y';
-- *****************************************************************************

  DECLARE _$SALODRKEY  VARCHAR(20);
  DECLARE _$ODRSEQ     VARCHAR(20);
  DECLARE _$LOTKEY     VARCHAR(100);
  DECLARE _$OUTQTY     DECIMAL(20, 8);
  DECLARE _$REMARK     VARCHAR(1000);
  DECLARE _$ITEMID     VARCHAR(20);
  DECLARE _$LOTITEMID  VARCHAR(20);
  DECLARE _$LOTQTY     DECIMAL(20, 8);
  DECLARE _$REMQTY     DECIMAL(20, 8);
  DECLARE _$SUMQTY     DECIMAL(20, 8);
  DECLARE _$SALOUTKEY  VARCHAR(20);
  DECLARE _$FOUNDKEY   VARCHAR(20);
  DECLARE _$FOUNDSEQ   VARCHAR(20);
  DECLARE _$CUSTCD     VARCHAR(20);
  DECLARE _$GROUPKEY   VARCHAR(50);

-- ****************************************************************************
CASE $CALLTYPE

-- ****************************************************************************
WHEN 'LIST_SALODR' THEN -- 수주내역 : 2공장(71) 수주, 2공장 품목, 납기일자 기간, 출하잔량 남은 것

  SELECT
      SALODRD.SALODRKEY
    , SALODRD.ODRSEQ
    , IFNULL(NULLIF(SALODRD.DLVDT, ''), LEFT(SALODR.DELIVERYDT, 10)) AS DLVDT
    , SALODR.CUSTCD
    , GPCD('CUSTCD', SALODR.CUSTCD) AS CUSTNM
    , CAST(SALODRD.ITEMID AS CHAR) AS ITEMID
    , MSTITEM.ITEMCD
    , MSTITEM.ITEMNM
    , MSTITEM.ITEMSPEC
    , SALODRD.SALQTY
    , IFNULL(OUTSUM.OUTQTY, 0) AS OUTQTY
    , SALODRD.SALQTY - IFNULL(OUTSUM.OUTQTY, 0) AS REMQTY
    , IFNULL(GPCD('SD310', SALODR.SALBC), '') AS SALBCNM
    , SALODRD.SALUP
  FROM SALODR
  INNER JOIN SALODRD ON SALODRD.SALODRKEY = SALODR.SALODRKEY
  INNER JOIN MSTITEM ON MSTITEM.ITEMID = SALODRD.ITEMID
  INNER JOIN MSTITEM_FACTORY ON MSTITEM_FACTORY.ITEMID = SALODRD.ITEMID
                            AND MSTITEM_FACTORY.FACTORYCD = '07'
  LEFT JOIN (SELECT SALOUT.SALODRKEY, SALOUT.ODRSEQ, SUM(SALOUT.OUTQTY) AS OUTQTY
               FROM SALOUT
               GROUP BY SALOUT.SALODRKEY, SALOUT.ODRSEQ) AS OUTSUM
         ON OUTSUM.SALODRKEY = SALODRD.SALODRKEY
        AND OUTSUM.ODRSEQ = SALODRD.ODRSEQ
  WHERE SALODR.BDVCD = '71'
    AND IFNULL(NULLIF(SALODRD.DLVDT, ''), LEFT(SALODR.DELIVERYDT, 10)) BETWEEN $SDATE AND $EDATE
    AND SALODR.CUSTCD LIKE CONCAT('%', $CUSTCD, '%')
    AND SALODRD.ITEMID LIKE CONCAT('%', $ITEMID, '%')
    AND SALODRD.SALQTY - IFNULL(OUTSUM.OUTQTY, 0) > 0
  ORDER BY DLVDT, SALODRD.SALODRKEY, SALODRD.ODRSEQ;

-- ****************************************************************************
WHEN 'SCAN_LOT' THEN -- LOT 스캔 : 출고창고 재고 확인 → 선택한 수주 중 같은 품목 수주에 붙임

  IF IFNULL($WARECD, '') = '' THEN
    CALL COMERR('출고창고를 선택하세요.');
    LEAVE PROC;
  END IF;

  IF IFNULL($SCANLOT, '') = '' THEN
    CALL COMERR('로트번호가 없습니다.');
    LEAVE PROC;
  END IF;

  IF IFNULL($SALODRKEY_LIST, '') = '' THEN
    CALL COMERR('왼쪽 수주내역에서 출하할 수주를 선택하세요.');
    LEAVE PROC;
  END IF;

  SET _$LOTQTY = NULL;
  SELECT COMLOT.LOTQTY, CAST(COMLOT.ITEMID AS CHAR)
    INTO _$LOTQTY, _$LOTITEMID
    FROM COMLOT
    WHERE COMLOT.LOTKEY = $SCANLOT
      AND COMLOT.WARECD = $WARECD;

  IF _$LOTQTY IS NULL THEN
    CALL COMERR(CONCAT('출고창고에 없는 로트번호입니다.'
                      , '\n- 창고: ', IFNULL((SELECT MSTWARE.WARENM FROM MSTWARE WHERE MSTWARE.WARECD = $WARECD), $WARECD)
                      , '\n- 로트번호: ', $SCANLOT));
    LEAVE PROC;
  END IF;

  IF _$LOTQTY <= 0 THEN
    CALL COMERR(CONCAT('재고수량이 0 입니다.', '\n- 로트번호: ', $SCANLOT));
    LEAVE PROC;
  END IF;

  -- 선택한 수주 중 LOT 품목과 같은 첫 수주
  SET _$FOUNDKEY = NULL;
  WHILE LENGTH($SALODRKEY_LIST) > 0 AND _$FOUNDKEY IS NULL DO
    CALL COMSPLIT($SALODRKEY_LIST, _$SALODRKEY);
    CALL COMSPLIT($ODRSEQ_LIST, _$ODRSEQ);

    IF EXISTS (SELECT 1 FROM SALODRD
                 WHERE SALODRD.SALODRKEY = _$SALODRKEY
                   AND SALODRD.ODRSEQ = _$ODRSEQ
                   AND SALODRD.ITEMID = _$LOTITEMID) THEN
      SET _$FOUNDKEY = _$SALODRKEY;
      SET _$FOUNDSEQ = _$ODRSEQ;
    END IF;
  END WHILE;

  IF _$FOUNDKEY IS NULL THEN
    CALL COMERR(CONCAT('선택한 수주 품목에 해당하는 LOT 가 아닙니다.'
                      , '\n- 로트번호: ', $SCANLOT
                      , '\n- LOT 품목: ', IFNULL((SELECT MSTITEM.ITEMCD FROM MSTITEM WHERE MSTITEM.ITEMID = _$LOTITEMID), '')));
    LEAVE PROC;
  END IF;

  SELECT
      SALODRD.SALODRKEY
    , SALODRD.ODRSEQ
    , CAST(MSTITEM.ITEMID AS CHAR) AS ITEMID
    , MSTITEM.ITEMCD
    , MSTITEM.ITEMNM
    , MSTITEM.ITEMSPEC
    , COMLOT.LOTKEY
    , IFNULL(GPCD('DM150', MSTITEM.ITEMUNIT), '') AS UNITNM
    , COMLOT.LOTQTY AS OUTQTY       -- 출하량 기본 = 현재고
    , COMLOT.LOTQTY                 -- 잔여재고량
    , IFNULL(COMLOT.HEATNO, '') AS HEATNO
    , '' AS REMARK
    , IFNULL(GPCD('SD310', SALODR.SALBC), '') AS SALBCNM
    , IFNULL(MSTWARE.WARENM, '') AS WARENM
    , SALODRD.SALUP
    , GPCD('CUSTCD', SALODR.CUSTCD) AS CUSTNM
  FROM COMLOT
  INNER JOIN MSTITEM ON MSTITEM.ITEMID = COMLOT.ITEMID
  INNER JOIN SALODRD ON SALODRD.SALODRKEY = _$FOUNDKEY
                    AND SALODRD.ODRSEQ = _$FOUNDSEQ
  INNER JOIN SALODR ON SALODR.SALODRKEY = SALODRD.SALODRKEY
  LEFT JOIN MSTWARE ON MSTWARE.WARECD = COMLOT.WARECD
  WHERE COMLOT.LOTKEY = $SCANLOT
    AND COMLOT.WARECD = $WARECD;

-- ****************************************************************************
WHEN 'ADD_SALOUT' THEN -- 등록 : 출하 행마다 수주·LOT·출하량·비고 → 수주(상세)별 출하 1건 + 출고확정

  IF IFNULL($OUTDATE, '') = '' THEN
    CALL COMERR('출하일자를 입력하세요.');
    LEAVE PROC;
  END IF;

  IF IFNULL($WARECD, '') = '' THEN
    CALL COMERR('출고창고를 선택하세요.');
    LEAVE PROC;
  END IF;

  IF IFNULL($LOTKEY_LIST, '') = '' THEN
    CALL COMERR('출하할 LOT 를 스캔하세요.');
    LEAVE PROC;
  END IF;

  DROP TEMPORARY TABLE IF EXISTS TEMP_OUT;
  CREATE TEMPORARY TABLE TEMP_OUT (
      SEQ       INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
      SALODRKEY VARCHAR(20),
      ODRSEQ    VARCHAR(20),
      LOTKEY    VARCHAR(100),
      OUTQTY    DECIMAL(20, 8),
      REMARK    VARCHAR(1000),
      DONEYN    VARCHAR(1) DEFAULT 'N'
  );

  DROP TEMPORARY TABLE IF EXISTS TEMP_SALOUT;
  CREATE TEMPORARY TABLE TEMP_SALOUT (
      SALOUTKEY VARCHAR(20)
  );

  -- 납품처별 출하번호·거래명세서키 (같은 납품처의 수주는 거래명세서 1장으로 묶음)
  DROP TEMPORARY TABLE IF EXISTS TEMP_GRP;
  CREATE TEMPORARY TABLE TEMP_GRP (
      CUSTCD     VARCHAR(20),
      GROUPKEY   VARCHAR(50),
      INVOICEKEY VARCHAR(20)
  );

  -- 1. 행 검증 (같은 LOT 중복, 출하량 0 이하·재고 초과, 수주 품목과 LOT 품목)
  WHILE LENGTH($LOTKEY_LIST) > 0 DO
    CALL COMSPLIT($SALODRKEY_LIST, _$SALODRKEY);
    CALL COMSPLIT($ODRSEQ_LIST, _$ODRSEQ);
    CALL COMSPLIT($LOTKEY_LIST, _$LOTKEY);
    CALL COMSPLIT($OUTQTY_LIST, _$OUTQTY);
    CALL COMSPLIT($REMARK_LIST, _$REMARK);

    IF IFNULL(_$LOTKEY, '') <> '' THEN

      IF EXISTS (SELECT 1 FROM TEMP_OUT WHERE TEMP_OUT.LOTKEY = _$LOTKEY) THEN
        CALL COMERR(CONCAT('같은 LOT 가 두 번 들어 있습니다.', '\n- 로트번호: ', _$LOTKEY));
        LEAVE PROC;
      END IF;

      SET _$LOTQTY = NULL;
      SELECT COMLOT.LOTQTY, CAST(COMLOT.ITEMID AS CHAR)
        INTO _$LOTQTY, _$LOTITEMID
        FROM COMLOT
        WHERE COMLOT.LOTKEY = _$LOTKEY
          AND COMLOT.WARECD = $WARECD;

      IF _$LOTQTY IS NULL THEN
        CALL COMERR(CONCAT('출고창고에 없는 로트번호입니다.', '\n- 로트번호: ', _$LOTKEY));
        LEAVE PROC;
      END IF;

      IF IFNULL(_$OUTQTY, 0) <= 0 THEN
        CALL COMERR(CONCAT('출하량을 입력하세요.', '\n- 로트번호: ', _$LOTKEY));
        LEAVE PROC;
      END IF;

      IF _$OUTQTY > _$LOTQTY THEN
        CALL COMERR(CONCAT('출하량이 재고량보다 많습니다.'
                          , '\n- 로트번호: ', _$LOTKEY
                          , '\n- 재고량: ', FORMAT(_$LOTQTY, 0)
                          , '\n- 출하량: ', FORMAT(_$OUTQTY, 0)));
        LEAVE PROC;
      END IF;

      SET _$ITEMID = (SELECT CAST(SALODRD.ITEMID AS CHAR) FROM SALODRD
                        WHERE SALODRD.SALODRKEY = _$SALODRKEY AND SALODRD.ODRSEQ = _$ODRSEQ);

      IF IFNULL(_$ITEMID, '') = '' THEN
        CALL COMERR(CONCAT('수주가 없습니다. (', IFNULL(_$SALODRKEY, ''), '-', IFNULL(_$ODRSEQ, ''), ')'));
        LEAVE PROC;
      END IF;

      IF _$ITEMID <> _$LOTITEMID THEN
        CALL COMERR(CONCAT('수주 품목과 LOT 품목이 다릅니다.', '\n- 로트번호: ', _$LOTKEY));
        LEAVE PROC;
      END IF;

      INSERT INTO TEMP_OUT (SALODRKEY, ODRSEQ, LOTKEY, OUTQTY, REMARK)
      VALUES (_$SALODRKEY, _$ODRSEQ, _$LOTKEY, _$OUTQTY, IFNULL(_$REMARK, ''));
    END IF;
  END WHILE;

  -- 2. 수주(상세)별 : 출하잔량 확인 → 출하 1건 + LOT → 출고확정
  WHILE EXISTS (SELECT 1 FROM TEMP_OUT WHERE TEMP_OUT.DONEYN = 'N') DO

    SELECT TEMP_OUT.SALODRKEY, TEMP_OUT.ODRSEQ
      INTO _$SALODRKEY, _$ODRSEQ
      FROM TEMP_OUT
      WHERE TEMP_OUT.DONEYN = 'N'
      ORDER BY TEMP_OUT.SEQ
      LIMIT 1;

    SET _$REMQTY = (SELECT SALODRD.SALQTY FROM SALODRD WHERE SALODRD.SALODRKEY = _$SALODRKEY AND SALODRD.ODRSEQ = _$ODRSEQ)
                 - IFNULL((SELECT SUM(SALOUT.OUTQTY) FROM SALOUT WHERE SALOUT.SALODRKEY = _$SALODRKEY AND SALOUT.ODRSEQ = _$ODRSEQ), 0);

    SET _$SUMQTY = (SELECT SUM(TEMP_OUT.OUTQTY) FROM TEMP_OUT
                      WHERE TEMP_OUT.SALODRKEY = _$SALODRKEY AND TEMP_OUT.ODRSEQ = _$ODRSEQ);

    IF _$SUMQTY > _$REMQTY THEN
      CALL COMERR(CONCAT('출하량(', FORMAT(_$SUMQTY, 0), ')이 수주 출하잔량(', FORMAT(_$REMQTY, 0), ')보다 많습니다.'
                        , '\n- 수주: ', _$SALODRKEY, '-', _$ODRSEQ
                        , '\n- 품목코드: ', IFNULL((SELECT MSTITEM.ITEMCD FROM SALODRD INNER JOIN MSTITEM ON MSTITEM.ITEMID = SALODRD.ITEMID
                                                     WHERE SALODRD.SALODRKEY = _$SALODRKEY AND SALODRD.ODRSEQ = _$ODRSEQ), '')));
      LEAVE PROC;
    END IF;

    SET _$SALOUTKEY = GETKEY('SALOUT');

    SET _$CUSTCD = (SELECT SALODR.CUSTCD FROM SALODR WHERE SALODR.SALODRKEY = _$SALODRKEY);
    SET _$GROUPKEY = (SELECT TEMP_GRP.GROUPKEY FROM TEMP_GRP WHERE TEMP_GRP.CUSTCD = _$CUSTCD LIMIT 1);
    IF _$GROUPKEY IS NULL THEN
      SET _$GROUPKEY = GETKEY('SALOUTGROUP');
      INSERT INTO TEMP_GRP (CUSTCD, GROUPKEY, INVOICEKEY) VALUES (_$CUSTCD, _$GROUPKEY, GETKEY('INVOICEKEY'));
    END IF;

    INSERT INTO SALOUT (SALOUTKEY, SALODRKEY, ODRSEQ, SALOUTGROUPKEY, SALOUTTP, SALOUTDATE, CUSTCD, ITEMID, WARECD, EMPCD, OUTQTY, OUTYN, OUTTIME
                      , RTIME, REMP, RPRG)
    SELECT _$SALOUTKEY, SALODRD.SALODRKEY, SALODRD.ODRSEQ, _$GROUPKEY, '01', $OUTDATE, SALODR.CUSTCD, SALODRD.ITEMID, $WARECD, CALLEMP(), _$SUMQTY, 'N', ''
         , CALLTIME(), CALLEMP(), CALLPRG()
    FROM SALODRD
    INNER JOIN SALODR ON SALODR.SALODRKEY = SALODRD.SALODRKEY
    WHERE SALODRD.SALODRKEY = _$SALODRKEY
      AND SALODRD.ODRSEQ = _$ODRSEQ;

    INSERT INTO SALOUTLOT (SALOUTKEY, LOTKEY, LOTQTY, HEATNO, SCANTIME, REMARK, RTIME, REMP, RPRG)
    SELECT _$SALOUTKEY, TEMP_OUT.LOTKEY, TEMP_OUT.OUTQTY, IFNULL(COMLOT.HEATNO, ''), CALLTIME(), TEMP_OUT.REMARK, CALLTIME(), CALLEMP(), CALLPRG()
    FROM TEMP_OUT
    LEFT JOIN COMLOT ON COMLOT.LOTKEY = TEMP_OUT.LOTKEY
                    AND COMLOT.WARECD = $WARECD
    WHERE TEMP_OUT.SALODRKEY = _$SALODRKEY
      AND TEMP_OUT.ODRSEQ = _$ODRSEQ;

    CALL IO_SALOUT_LOT(_$SALOUTKEY, $OUTDATE);

    IF IFNULL(@ERRMSG, '') <> '' THEN
      LEAVE PROC;
    END IF;

    INSERT INTO TEMP_SALOUT (SALOUTKEY) VALUES (_$SALOUTKEY);

    UPDATE TEMP_OUT SET TEMP_OUT.DONEYN = 'Y'
     WHERE TEMP_OUT.SALODRKEY = _$SALODRKEY
       AND TEMP_OUT.ODRSEQ = _$ODRSEQ;
  END WHILE;

  -- 3. 거래명세서 이력 (납품처별 1장 = INVOICEKEY 1개, LOT 1개 = 상세 1줄)
  INSERT INTO SALINVOICE (INVOICEKEY, INVOICEDATE, CUSTCD, SALOUTGROUPKEY, WARECD, EMPCD, REMARK
                        , RTIME, REMP, RPRG)
  SELECT TEMP_GRP.INVOICEKEY, $OUTDATE, TEMP_GRP.CUSTCD, TEMP_GRP.GROUPKEY, $WARECD, CALLEMP(), ''
       , CALLTIME(), CALLEMP(), CALLPRG()
  FROM TEMP_GRP;

  INSERT INTO SALINVOICED (INVOICEKEY, SALOUTKEY, LOTKEY, ITEMID, OUTQTY, RTIME, REMP, RPRG)
  SELECT TEMP_GRP.INVOICEKEY, SALOUT.SALOUTKEY, SALOUTLOT.LOTKEY, SALOUT.ITEMID, SALOUTLOT.LOTQTY, CALLTIME(), CALLEMP(), CALLPRG()
  FROM TEMP_GRP
  INNER JOIN SALOUT ON SALOUT.SALOUTGROUPKEY = TEMP_GRP.GROUPKEY
  INNER JOIN SALOUTLOT ON SALOUTLOT.SALOUTKEY = SALOUT.SALOUTKEY;

  -- 출하 출고이력에도 거래명세서키 (재고 입출고 조회 SAL3002_S03 명세서번호)
  UPDATE COMOUT
  INNER JOIN SALOUT ON SALOUT.SALOUTKEY = COMOUT.SALOUTKEY
  INNER JOIN TEMP_GRP ON TEMP_GRP.GROUPKEY = SALOUT.SALOUTGROUPKEY
     SET COMOUT.INVOICEKEY = TEMP_GRP.INVOICEKEY
       , COMOUT.MTIME = CALLTIME()
       , COMOUT.MEMP = CALLEMP()
       , COMOUT.MPRG = CALLPRG()
   WHERE COMOUT.SALOUTKEY <> '';

  -- 4. 결과 : 만든 출하 (SALOUTGROUPKEY = 거래명세서 출력 단위, 납품처별 / INVOICEKEY = 거래명세서 번호)
  SELECT SALOUT.SALOUTKEY, SALOUT.SALODRKEY, SALOUT.ODRSEQ, SALOUT.OUTQTY, SALOUT.SALOUTGROUPKEY
       , IFNULL((SELECT SALINVOICE.INVOICEKEY FROM SALINVOICE WHERE SALINVOICE.SALOUTGROUPKEY = SALOUT.SALOUTGROUPKEY LIMIT 1), '') AS INVOICEKEY
    FROM SALOUT
    WHERE SALOUT.SALOUTKEY IN (SELECT TEMP_SALOUT.SALOUTKEY FROM TEMP_SALOUT)
    ORDER BY SALOUT.SALOUTKEY;

  DROP TEMPORARY TABLE IF EXISTS TEMP_OUT;
  DROP TEMPORARY TABLE IF EXISTS TEMP_SALOUT;
  DROP TEMPORARY TABLE IF EXISTS TEMP_GRP;

-- ****************************************************************************
WHEN 'PRINT_SALOUT' THEN -- 거래명세서 (출고부서용) : 출하번호(SALOUTGROUPKEY) 1개 = 납품처 1곳 (TMLPRINT.SAL_1)

  IF IFNULL($SALOUTGROUPKEY, '') = '' THEN
    CALL COMERR('출하번호가 없습니다.');
    LEAVE PROC;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM SALOUT WHERE SALOUT.SALOUTGROUPKEY = $SALOUTGROUPKEY) THEN
    CALL COMERR('존재하지 않는 출하번호입니다.');
    LEAVE PROC;
  END IF;

  -- [0] 공급자 (S&S INC 2공장, 사업장 71)
  SELECT
      TRIM(REPLACE(MSTBDV.BDVBNM_PRT, '2공장', '')) AS BDVNM
    , MSTBDV.BDVNMENG AS BNAME
    , MSTBDV.BDVREGNO AS BNUM
    , MSTBDV.ADDR AS ADDR
    , MSTBDV.REPRETEL AS TEL
    , MSTBDV.FAXNO AS FAX
    , MSTBDV.INDTYPE AS ITYPE
    , MSTBDV.INDKIND AS IKIND
  FROM MSTBDV
  WHERE MSTBDV.BDVCD = '71';

  -- [1] 공급받는자 (납품처) + 거래일자·담당자
  SELECT
      IFNULL(MSTCUST.CUSTNM_PRT, MSTCUST.CUSTNM) AS COMPNAME
    , MSTCUST.PRESIDENT AS PRES
    , MSTCUST.REGBUSSNUM AS BUSNM
    , MSTCUST.ADDR_PRT AS ADDR
    , MSTCUST.REPRETEL AS TEL
    , MSTCUST.CUSTFAX AS FAX
    , MSTCUST.BIZTYPE_PRT AS DTYPE
    , MSTCUST.BIZKIND_PRT AS DKIND
    , MAX(SALOUT.SALOUTDATE) AS SALTIME
    , IFNULL(NULLIF(GPCD('EMPCD', MAX(SALOUT.EMPCD)), ''), '') AS EMPNM
  FROM SALOUT
  LEFT JOIN MSTCUST ON MSTCUST.CUSTCD = SALOUT.CUSTCD
  WHERE SALOUT.SALOUTGROUPKEY = $SALOUTGROUPKEY
  GROUP BY SALOUT.CUSTCD;

  -- [2] 품목 (LOT 1개 = 1줄)
  SELECT
      MSTITEM.ITEMCD AS ITEMCD
    , MSTITEM.ITEMNM AS ITEMNM
    , MSTITEM.ITEMSPEC AS ITEMSPEC
    , FORMAT(SALOUTLOT.LOTQTY, 0) AS OUTQTY
    , '' AS BOX
    , '' AS BOXNM
    , IFNULL(SALOUTLOT.REMARK, '') AS REMARK
  FROM SALOUT
  INNER JOIN SALOUTLOT ON SALOUTLOT.SALOUTKEY = SALOUT.SALOUTKEY
  INNER JOIN MSTITEM ON MSTITEM.ITEMID = SALOUT.ITEMID
  WHERE SALOUT.SALOUTGROUPKEY = $SALOUTGROUPKEY
  ORDER BY SALOUT.SALOUTKEY, SALOUTLOT.LOTKEY;

  -- [3] 총 수량·거래명세서 번호 (INVOICEKEY. 이력이 없는 예전 출하는 출하번호)
  SELECT
      FORMAT(IFNULL(SUM(SALOUT.OUTQTY), 0), 0) AS SUMQTY
    , IFNULL((SELECT SALINVOICE.INVOICEKEY FROM SALINVOICE WHERE SALINVOICE.SALOUTGROUPKEY = $SALOUTGROUPKEY LIMIT 1), $SALOUTGROUPKEY) AS GROUPKEY
    , '' AS REMARK
  FROM SALOUT
  WHERE SALOUT.SALOUTGROUPKEY = $SALOUTGROUPKEY;

-- ****************************************************************************
END CASE; END