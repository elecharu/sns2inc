CREATE DEFINER = 'root'@'%'
PROCEDURE MES_SNS2.TQM4001_S01(
-- *****************************************************************************
-- Comment: Xbar-R 관리도 (자주검사)
-- Create: 2026-11-27 신정수 (SEA TQM3001_S02 참조, 고객사코드 제외 / 자주검사(PRCTEST) SPC 관리항목만 / 품목은 ITEMID / 검사항목 키는 STDCD+STDPART+PRCDETAIL)
-- Modify: 2026-11-27 신정수 표준편차(전체·군내)가 0 이어도 조회, CP·CPK·PP·PPK 는 NULL(계산불가)
-- *****************************************************************************
  IN $SDATE         VARCHAR(10),
  IN $EDATE         VARCHAR(10),
  IN $ITEMID        VARCHAR(100),
  IN $STDCD         VARCHAR(100),
  IN $STDPART       VARCHAR(100),
  IN $PRCDETAIL     VARCHAR(100),
  IN $NVALUE        VARCHAR(10),
-- *****************************************************************************
 IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC:  BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- SET @DEBUGLOGYN = 'Y';
-- *****************************************************************************
  DECLARE _$N_SUB INT;   -- n (군의 크기)

  DECLARE _$XBAR DECIMAL(20, 8);
  DECLARE _$R DECIMAL(20, 8);

  DECLARE _$SUMXBAR DECIMAL(20, 8);
  DECLARE _$SUMR DECIMAL(20, 8);
  DECLARE _$N DECIMAL(20, 8);

  DECLARE _$XBARCL DECIMAL(20, 8);
  DECLARE _$XBARUCL DECIMAL(20, 8);
  DECLARE _$XBARLCL DECIMAL(20, 8);
  DECLARE _$XBARUSL DECIMAL(20, 8);
  DECLARE _$XBARLSL DECIMAL(20, 8);

  DECLARE _$RCL DECIMAL(20, 8);
  DECLARE _$RUCL DECIMAL(20, 8);
  DECLARE _$RUSL DECIMAL(20, 8);

  DECLARE _$PPU DECIMAL(20, 8);
  DECLARE _$PPL DECIMAL(20, 8);
  DECLARE _$PP  DECIMAL(20, 8);
  DECLARE _$PPK DECIMAL(20, 8);

  DECLARE _$CPU DECIMAL(20, 8);
  DECLARE _$CPL DECIMAL(20, 8);
  DECLARE _$CP  DECIMAL(20, 8);
  DECLARE _$CPK DECIMAL(20, 8);

  DECLARE _$STDEV_ALL DECIMAL(20, 8);
  DECLARE _$STDEV_GROUP DECIMAL(20, 8);

  DECLARE _$AVG DECIMAL(20, 8);
  DECLARE _$d2 DECIMAL(20, 8);

  DECLARE _$STDMIN VARCHAR(100);
  DECLARE _$STDMAX VARCHAR(100);
  DECLARE _$BIGN   INT;

  DECLARE _$id INT;

-- ****************************************************************************
CASE $CALLTYPE
-- ****************************************************************************
WHEN 'LIST_STDCD' THEN -- 자주검사 SPC 관리항목 중 조회기간에 검사값이 있는 항목 (grid2)

  IF IFNULL($SDATE, '') = '' OR IFNULL($EDATE, '') = '' THEN
    CALL COMERR('조회일자를 입력하세요.');
    LEAVE PROC;
  END IF;

  SELECT
      CAST(SPC_TYPE_CPKPPK.ITEMID AS CHAR) AS ITEMID
    , MSTITEM.ITEMCD
    , MSTITEM.ITEMNM
    , SPC_TYPE_CPKPPK.STDCD
    , MAX(MSTRPTREV_DETAIL.STDNM) AS STDNM
    , SPC_TYPE_CPKPPK.STDPART
    , SPC_TYPE_CPKPPK.PRCDETAIL
    , MAX(MSTRPTREV_DETAIL.FEATURE) AS FEATURE
    , SPC_TYPE_CPKPPK.CPK
    , SPC_TYPE_CPKPPK.PPK
    , SPC_TYPE_CPKPPK.XBAR_UCL
    , SPC_TYPE_CPKPPK.XBAR_LCL
    , SPC_TYPE_CPKPPK.XBAR_USL
    , SPC_TYPE_CPKPPK.XBAR_LSL
    , SPC_TYPE_CPKPPK.R_UCL
    , SPC_TYPE_CPKPPK.R_USL
  FROM SPC_TYPE_CPKPPK
  INNER JOIN SPC_TYPE
          ON SPC_TYPE.STDTP = SPC_TYPE_CPKPPK.STDTP
         AND SPC_TYPE.ITEMID = SPC_TYPE_CPKPPK.ITEMID
  INNER JOIN MSTITEM
          ON MSTITEM.ITEMID = SPC_TYPE_CPKPPK.ITEMID
  INNER JOIN TQMRST
          ON TQMRST.ITEMID = SPC_TYPE_CPKPPK.ITEMID
         AND TQMRST.TQMDATE BETWEEN $SDATE AND $EDATE
  INNER JOIN MSTRPTREV_HEADER
          ON MSTRPTREV_HEADER.REVCD = TQMRST.REVCD
         AND MSTRPTREV_HEADER.STDTP = 'PRCTEST'
  INNER JOIN MSTRPTREV_DETAIL
          ON MSTRPTREV_DETAIL.REVCD = TQMRST.REVCD
         AND MSTRPTREV_DETAIL.STDCD = SPC_TYPE_CPKPPK.STDCD
         AND MSTRPTREV_DETAIL.STDPART = SPC_TYPE_CPKPPK.STDPART
         AND MSTRPTREV_DETAIL.PRCDETAIL = SPC_TYPE_CPKPPK.PRCDETAIL
  INNER JOIN TQMRST_VALUE
          ON TQMRST_VALUE.TQMRSTKEY = TQMRST.TQMRSTKEY
         AND TQMRST_VALUE.STDCD = SPC_TYPE_CPKPPK.STDCD
         AND TQMRST_VALUE.STDPART = SPC_TYPE_CPKPPK.STDPART
         AND TQMRST_VALUE.PRCDETAIL = SPC_TYPE_CPKPPK.PRCDETAIL
  WHERE SPC_TYPE_CPKPPK.STDTP = 'PRCTEST'
    AND SPC_TYPE_CPKPPK.ITEMID LIKE CONCAT('%', IFNULL($ITEMID, ''), '%')
  GROUP BY SPC_TYPE_CPKPPK.ITEMID, SPC_TYPE_CPKPPK.STDCD, SPC_TYPE_CPKPPK.STDPART, SPC_TYPE_CPKPPK.PRCDETAIL
  ORDER BY SPC_TYPE_CPKPPK.ITEMID, MIN(MSTRPTREV_DETAIL.SORTNO);

-- ****************************************************************************
WHEN 'SEARCH_TQMVALUE_N' THEN -- 검사값을 n 개씩 묶어 Xbar, R 및 공정능력 계산

  IF IFNULL($SDATE, '') = '' OR IFNULL($EDATE, '') = '' THEN
    CALL COMERR('조회일자를 입력하세요.');
    LEAVE PROC;
  END IF;

  IF IFNULL($ITEMID, '') = '' THEN
    CALL COMERR('품목을 선택하세요.');
    LEAVE PROC;
  END IF;

  IF IFNULL($STDCD, '') = '' THEN
    CALL COMERR('검사항목을 선택하세요.');
    LEAVE PROC;
  END IF;

  SET _$N_SUB = CAST(IFNULL(NULLIF($NVALUE, ''), '0') AS SIGNED);

  IF _$N_SUB < 2 OR _$N_SUB > 25 THEN
    CALL COMERR('n값이 범위를 벗어났습니다.\n( 2 <= n <= 25 )');
    LEAVE PROC;
  END IF;

  -- d2 (군의 크기 n 별 관리도 계수)
  SET _$d2 = ELT(_$N_SUB - 1, 1.128, 1.693, 2.059, 2.326, 2.534, 2.704, 2.847, 2.970, 3.078, 3.173, 3.258, 3.336
                            , 3.407, 3.472, 3.532, 3.588, 3.640, 3.689, 3.735, 3.778, 3.819, 3.858, 3.895, 3.931);

  DROP TEMPORARY TABLE IF EXISTS TEMP_VALUE;
  CREATE TEMPORARY TABLE TEMP_VALUE
  (
    NO          INT AUTO_INCREMENT PRIMARY KEY,
    TQMRSTKEY   VARCHAR(100),
    TQMDATE     VARCHAR(10),
    VALUE       DECIMAL(20, 8)
  );

  DROP TEMPORARY TABLE IF EXISTS TEMP_RESULT;
  CREATE TEMPORARY TABLE TEMP_RESULT
  (
    id INT AUTO_INCREMENT PRIMARY KEY,
    XBAR        DECIMAL(20, 8),
    R           DECIMAL(20, 8),
    VALUE1 VARCHAR(100), VALUE2 VARCHAR(100), VALUE3 VARCHAR(100), VALUE4 VARCHAR(100), VALUE5 VARCHAR(100),
    VALUE6 VARCHAR(100), VALUE7 VARCHAR(100), VALUE8 VARCHAR(100), VALUE9 VARCHAR(100), VALUE10 VARCHAR(100),
    VALUE11 VARCHAR(100), VALUE12 VARCHAR(100), VALUE13 VARCHAR(100), VALUE14 VARCHAR(100), VALUE15 VARCHAR(100),
    VALUE16 VARCHAR(100), VALUE17 VARCHAR(100), VALUE18 VARCHAR(100), VALUE19 VARCHAR(100), VALUE20 VARCHAR(100),
    VALUE21 VARCHAR(100), VALUE22 VARCHAR(100), VALUE23 VARCHAR(100), VALUE24 VARCHAR(100), VALUE25 VARCHAR(100)
  );

  -- 검사값 (합격 검사만, 숫자값만, L/R 항목은 L·R 을 각각 한 개 값으로) 검사시각·시료 순서
  INSERT INTO TEMP_VALUE (TQMRSTKEY, TQMDATE, VALUE)
  SELECT
      LIST_VALUE.TQMRSTKEY
    , LIST_VALUE.TQMDATE
    , CAST(LIST_VALUE.VALUE AS DECIMAL(20, 8))
  FROM (
        SELECT
            TQMRST.TQMRSTKEY
          , TQMRST.TQMDATE
          , TQMRST.FIXTIME
          , TQMRST_VALUE.VALUEKEY
          , 1 AS SIDE
          , TRIM(TQMRST_VALUE.VALUE) AS VALUE
        FROM TQMRST
        INNER JOIN MSTRPTREV_HEADER
                ON MSTRPTREV_HEADER.REVCD = TQMRST.REVCD
               AND MSTRPTREV_HEADER.STDTP = 'PRCTEST'
        INNER JOIN TQMRST_VALUE
                ON TQMRST_VALUE.TQMRSTKEY = TQMRST.TQMRSTKEY
        WHERE TQMRST.FINALJUDGE = 'Y'
          AND TQMRST.TQMDATE BETWEEN $SDATE AND $EDATE
          AND TQMRST.ITEMID = $ITEMID
          AND TQMRST_VALUE.STDCD = $STDCD
          AND TQMRST_VALUE.STDPART = IFNULL($STDPART, '')
          AND TQMRST_VALUE.PRCDETAIL = IFNULL($PRCDETAIL, '')
        UNION ALL
        SELECT
            TQMRST.TQMRSTKEY
          , TQMRST.TQMDATE
          , TQMRST.FIXTIME
          , TQMRST_VALUE.VALUEKEY
          , 2 AS SIDE
          , TRIM(TQMRST_VALUE.VALUE2) AS VALUE
        FROM TQMRST
        INNER JOIN MSTRPTREV_HEADER
                ON MSTRPTREV_HEADER.REVCD = TQMRST.REVCD
               AND MSTRPTREV_HEADER.STDTP = 'PRCTEST'
        INNER JOIN TQMRST_VALUE
                ON TQMRST_VALUE.TQMRSTKEY = TQMRST.TQMRSTKEY
        WHERE TQMRST.FINALJUDGE = 'Y'
          AND TQMRST.TQMDATE BETWEEN $SDATE AND $EDATE
          AND TQMRST.ITEMID = $ITEMID
          AND TQMRST_VALUE.STDCD = $STDCD
          AND TQMRST_VALUE.STDPART = IFNULL($STDPART, '')
          AND TQMRST_VALUE.PRCDETAIL = IFNULL($PRCDETAIL, '')
       ) AS LIST_VALUE
  WHERE LIST_VALUE.VALUE REGEXP '^-?[0-9]+(\\.[0-9]+)?$'
  ORDER BY LIST_VALUE.FIXTIME, LIST_VALUE.TQMRSTKEY, LIST_VALUE.VALUEKEY, LIST_VALUE.SIDE;

  SET _$BIGN = IFNULL((SELECT COUNT(*) FROM TEMP_VALUE), 0);

  IF _$BIGN < _$N_SUB THEN
    CALL COMERR(CONCAT('검사값이 부족합니다.\n( 검사값 ', _$BIGN, '개, n = ', _$N_SUB, ' )'));
    LEAVE PROC;
  END IF;

  IF NOT EXISTS (SELECT MSTRPTREV_DETAIL.STDCD
                   FROM MSTRPTREV_HEADER
                   INNER JOIN MSTRPTREV_ITEM
                           ON MSTRPTREV_ITEM.REVCD = MSTRPTREV_HEADER.REVCD
                   INNER JOIN MSTRPTREV_DETAIL
                           ON MSTRPTREV_DETAIL.REVCD = MSTRPTREV_HEADER.REVCD
                  WHERE MSTRPTREV_HEADER.STDTP = 'PRCTEST'
                    AND MSTRPTREV_HEADER.USEYN = 'Y'
                    AND MSTRPTREV_ITEM.ITEMID = $ITEMID
                    AND MSTRPTREV_DETAIL.STDCD = $STDCD
                    AND MSTRPTREV_DETAIL.STDPART = IFNULL($STDPART, '')
                    AND MSTRPTREV_DETAIL.PRCDETAIL = IFNULL($PRCDETAIL, '')) THEN
    CALL COMERR('사용중인 자주검사 기준에 이 검사항목이 없습니다.');
    LEAVE PROC;
  END IF;

  -- 판정기준 최소·최대 (사용중 리비전, STDRANGE 01 최대·04 이내 → 최대 / 02 최소·03 이상 → 최소 / 05 = → 둘 다 / 06·07 ~ → 기준값+오차)
  SELECT
      CASE
        WHEN MSTRPTREV_DETAIL.STDRANGE IN ('02', '03', '05') THEN CAST(CAST(MSTRPTREV_DETAIL.STDVAL AS DOUBLE) AS CHAR)
        WHEN MSTRPTREV_DETAIL.STDRANGE IN ('06', '07') THEN CAST(CAST(MSTRPTREV_DETAIL.STDVAL + MSTRPTREV_DETAIL.STDMINUS AS DOUBLE) AS CHAR)
        ELSE ''
      END AS STDMIN
    , CASE
        WHEN MSTRPTREV_DETAIL.STDRANGE IN ('01', '04', '05') THEN CAST(CAST(MSTRPTREV_DETAIL.STDVAL AS DOUBLE) AS CHAR)
        WHEN MSTRPTREV_DETAIL.STDRANGE IN ('06', '07') THEN CAST(CAST(MSTRPTREV_DETAIL.STDVAL + MSTRPTREV_DETAIL.STDPLUS AS DOUBLE) AS CHAR)
        ELSE ''
      END AS STDMAX
  INTO
      _$STDMIN
    , _$STDMAX
  FROM MSTRPTREV_HEADER
  INNER JOIN MSTRPTREV_ITEM
          ON MSTRPTREV_ITEM.REVCD = MSTRPTREV_HEADER.REVCD
  INNER JOIN MSTRPTREV_DETAIL
          ON MSTRPTREV_DETAIL.REVCD = MSTRPTREV_HEADER.REVCD
  WHERE MSTRPTREV_HEADER.STDTP = 'PRCTEST'
    AND MSTRPTREV_HEADER.USEYN = 'Y'
    AND MSTRPTREV_ITEM.ITEMID = $ITEMID
    AND MSTRPTREV_DETAIL.STDCD = $STDCD
    AND MSTRPTREV_DETAIL.STDPART = IFNULL($STDPART, '')
    AND MSTRPTREV_DETAIL.PRCDETAIL = IFNULL($PRCDETAIL, '')
  LIMIT 1;

  SET _$STDMIN = IFNULL(_$STDMIN, '');
  SET _$STDMAX = IFNULL(_$STDMAX, '');

  IF _$STDMIN = '' AND _$STDMAX = '' THEN
    CALL COMERR('사용중인 자주검사 기준에서 판정기준(최소·최대)을 찾을 수 없습니다.');
    LEAVE PROC;
  END IF;

  SET _$AVG = IFNULL((SELECT AVG(TEMP_VALUE.VALUE) FROM TEMP_VALUE), 0);

  -- 표준편차(전체)
  SELECT
      SQRT(SUM(POW((TEMP_VALUE.VALUE - _$AVG), 2)) / IF(_$BIGN = 1, 1, (_$BIGN - 1)))
  INTO
      _$STDEV_ALL
  FROM TEMP_VALUE;

  SET _$STDEV_ALL = IFNULL(_$STDEV_ALL, 0);   -- 0 이어도 조회는 하고 PP·PPK 만 계산불가(NULL)

  -- 검사값을 n 개씩 묶기 (마지막에 n 개가 안 되는 나머지 묶음도 포함 - 참조 화면과 같음)
  SET _$id = 0;
  WHILE _$id * _$N_SUB < _$BIGN DO
    INSERT INTO TEMP_RESULT (
        XBAR, R
      , VALUE1, VALUE2, VALUE3, VALUE4, VALUE5, VALUE6, VALUE7, VALUE8, VALUE9, VALUE10
      , VALUE11, VALUE12, VALUE13, VALUE14, VALUE15, VALUE16, VALUE17, VALUE18, VALUE19, VALUE20
      , VALUE21, VALUE22, VALUE23, VALUE24, VALUE25
    )
    SELECT
        AVG(GROUP_VALUE.VALUE)
      , MAX(GROUP_VALUE.VALUE) - MIN(GROUP_VALUE.VALUE)
      , MAX(IF(GROUP_VALUE.NUM = 1, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 2, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 3, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 4, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 5, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 6, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 7, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 8, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 9, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 10, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 11, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 12, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 13, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 14, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 15, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 16, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 17, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 18, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 19, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 20, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 21, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 22, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 23, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 24, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
      , MAX(IF(GROUP_VALUE.NUM = 25, CAST(CAST(GROUP_VALUE.VALUE AS DOUBLE) AS CHAR), ''))
    FROM (
          SELECT
              TEMP_VALUE.VALUE
            , TEMP_VALUE.NO - (_$id * _$N_SUB) AS NUM
          FROM TEMP_VALUE
          WHERE TEMP_VALUE.NO > _$id * _$N_SUB
            AND TEMP_VALUE.NO <= (_$id + 1) * _$N_SUB
         ) AS GROUP_VALUE;

    SET _$id = _$id + 1;
  END WHILE;

  -- 표준편차(군내) = R평균 / d2
  SELECT
      AVG(ABS(TEMP_RESULT.R)) / _$d2
    , SUM(TEMP_RESULT.XBAR)
    , SUM(TEMP_RESULT.R)
    , COUNT(TEMP_RESULT.id)
  INTO
      _$STDEV_GROUP
    , _$SUMXBAR
    , _$SUMR
    , _$N
  FROM TEMP_RESULT;

  SET _$STDEV_GROUP = IFNULL(_$STDEV_GROUP, 0);   -- 0 이어도 조회는 하고 CP·CPK 만 계산불가(NULL)

  SET _$RCL = _$SUMR / _$N;
  SET _$XBARCL = _$SUMXBAR / _$N;

  -- 관리한계는 SPC 관리항목 등록(TQM4001_R01)에서 입력한 값
  SELECT
      SPC_TYPE_CPKPPK.XBAR_UCL
    , SPC_TYPE_CPKPPK.XBAR_LCL
    , SPC_TYPE_CPKPPK.XBAR_USL
    , SPC_TYPE_CPKPPK.XBAR_LSL
    , SPC_TYPE_CPKPPK.R_UCL
    , SPC_TYPE_CPKPPK.R_USL
  INTO
      _$XBARUCL
    , _$XBARLCL
    , _$XBARUSL
    , _$XBARLSL
    , _$RUCL
    , _$RUSL
  FROM SPC_TYPE_CPKPPK
  WHERE SPC_TYPE_CPKPPK.STDTP = 'PRCTEST'
    AND SPC_TYPE_CPKPPK.ITEMID = $ITEMID
    AND SPC_TYPE_CPKPPK.STDCD = $STDCD
    AND SPC_TYPE_CPKPPK.STDPART = IFNULL($STDPART, '')
    AND SPC_TYPE_CPKPPK.PRCDETAIL = IFNULL($PRCDETAIL, '');

  -- CPK, PPK 계산 (한쪽 규격만 있으면 그쪽으로만, 표준편차 0 이면 NULL)
  IF _$STDMIN = '' AND _$STDMAX != '' THEN
    SET _$CP = ABS(_$STDMAX - _$AVG) / (3 * NULLIF(_$STDEV_GROUP, 0));
    SET _$CPU = _$CP;
    SET _$CPL = _$CP;
    SET _$CPK = _$CP;

    SET _$PP = ABS(_$STDMAX - _$AVG) / (3 * NULLIF(_$STDEV_ALL, 0));
    SET _$PPU = _$PP;
    SET _$PPL = _$PP;
    SET _$PPK = _$PP;
  ELSEIF _$STDMIN != '' AND _$STDMAX = '' THEN
    SET _$CP = ABS(_$STDMIN - _$AVG) / (3 * NULLIF(_$STDEV_GROUP, 0));
    SET _$CPU = _$CP;
    SET _$CPL = _$CP;
    SET _$CPK = _$CP;

    SET _$PP = ABS(_$STDMIN - _$AVG) / (3 * NULLIF(_$STDEV_ALL, 0));
    SET _$PPU = _$PP;
    SET _$PPL = _$PP;
    SET _$PPK = _$PP;
  ELSE
    SET _$CP = ABS(_$STDMIN - _$STDMAX) / (6 * NULLIF(_$STDEV_GROUP, 0));
    SET _$CPU = ABS(_$STDMAX - _$AVG) / (3 * NULLIF(_$STDEV_GROUP, 0));
    SET _$CPL = ABS(_$STDMIN - _$AVG) / (3 * NULLIF(_$STDEV_GROUP, 0));
    SET _$CPK = LEAST(_$CPU, _$CPL);

    SET _$PP = ABS(_$STDMIN - _$STDMAX) / (6 * NULLIF(_$STDEV_ALL, 0));
    SET _$PPU = ABS(_$STDMAX - _$AVG) / (3 * NULLIF(_$STDEV_ALL, 0));
    SET _$PPL = ABS(_$STDMIN - _$AVG) / (3 * NULLIF(_$STDEV_ALL, 0));
    SET _$PPK = LEAST(_$PPU, _$PPL);
  END IF;

  -- 0. SPC 계산값
  SELECT
      _$STDMIN AS STDMIN
    , _$STDMAX AS STDMAX
    , _$BIGN AS BIGN
    , _$N_SUB AS NVALUE
    , _$AVG AS AVG
    , _$d2 AS d2
    , _$STDEV_ALL AS STDEV_ALL
    , _$STDEV_GROUP AS STDEV_GROUP
    , ROUND(_$CP, 2) AS CP
    , ROUND(_$CPU, 2) AS CPU
    , ROUND(_$CPL, 2) AS CPL
    , ROUND(_$CPK, 2) AS CPK
    , ROUND(_$PP, 2) AS PP
    , ROUND(_$PPU, 2) AS PPU
    , ROUND(_$PPL, 2) AS PPL
    , ROUND(_$PPK, 2) AS PPK
    , _$XBARCL AS XBARCL
    , IFNULL(_$XBARUCL, 0) AS XBARUCL
    , IFNULL(_$XBARLCL, 0) AS XBARLCL
    , IFNULL(_$XBARUSL, 0) AS XBARUSL
    , IFNULL(_$XBARLSL, 0) AS XBARLSL
    , _$RCL AS RCL
    , IFNULL(_$RUCL, 0) AS RUCL
    , IFNULL(_$RUSL, 0) AS RUSL;

  -- 1. 군별 Xbar, R 과 검사값
  SELECT
      TEMP_RESULT.id AS GROUPNO
    , ROUND(TEMP_RESULT.XBAR, 4) AS XBAR
    , ROUND(TEMP_RESULT.R, 4) AS R
    , TEMP_RESULT.VALUE1, TEMP_RESULT.VALUE2, TEMP_RESULT.VALUE3, TEMP_RESULT.VALUE4, TEMP_RESULT.VALUE5
    , TEMP_RESULT.VALUE6, TEMP_RESULT.VALUE7, TEMP_RESULT.VALUE8, TEMP_RESULT.VALUE9, TEMP_RESULT.VALUE10
    , TEMP_RESULT.VALUE11, TEMP_RESULT.VALUE12, TEMP_RESULT.VALUE13, TEMP_RESULT.VALUE14, TEMP_RESULT.VALUE15
    , TEMP_RESULT.VALUE16, TEMP_RESULT.VALUE17, TEMP_RESULT.VALUE18, TEMP_RESULT.VALUE19, TEMP_RESULT.VALUE20
