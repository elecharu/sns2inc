--         2020-01-23 11:58: 문재원 192.168.0.xxx 로 접속 시 내부 ip로 간주
-- *****************************************************************************
 IN $SESSION_USERID VARCHAR(20), -- ID
 IN $PRGCD VARCHAR(100), -- 프로그램 코드
 IN $MENUNM VARCHAR(100), -- 메뉴명
 IN $GRIDID VARCHAR(10), -- grid id
 IN $STYLEINFO MEDIUMTEXT, -- 스타일값
-- *****************************************************************************
 IN $CALLTYPE VARCHAR(50), IN $KEYWORD VARCHAR(1000))
PROC: BEGIN -- @CALLEMP, @CALLPRG, @CALLHOST, @CALLIP, @CALLMAC
-- SET @DEBUGLOGYN = 'Y';
-- *****************************************************************************

-- DECLARE _$V01 VARCHAR(1000);
  DECLARE _$AUTCD VARCHAR(20);
  DECLARE _$PAYRULE VARCHAR(20);
  DECLARE _$MENUNM VARCHAR(100);
  DECLARE _$HOTYN VARCHAR(1);
  DECLARE _$CENTERCD VARCHAR(20);
  DECLARE _$EMPCD VARCHAR(20);
  DECLARE _$MASTERYN VARCHAR(1);
  DECLARE _$PLUSKEYYN   VARCHAR(1);

  DECLARE _$USERAUTCD   VARCHAR(10);
  DECLARE _$USERDEPTCD  VARCHAR(10);
  DECLARE _$USEREMPCD   VARCHAR(10);
  DECLARE _$USERINOUTTP VARCHAR(10);

  DECLARE _$ICONURL VARCHAR(100);
  
  DECLARE _$ALERTYN VARCHAR(1);
-- ****************************************************************************
CASE $CALLTYPE
-- * ***************************************************************************
WHEN 'LIST_MENU2' THEN

  SET _$USERINOUTTP = 'IN';
  SET _$ICONURL = '../../images/menu/';

  SELECT
    SYSUSER.AUTCD, MSTEMP.DEPTCD, SYSUSER.EMPCD
    INTO _$USERAUTCD, _$USERDEPTCD, _$USEREMPCD
    FROM SYSUSER
    INNER JOIN MSTEMP ON SYSUSER.EMPCD = MSTEMP.EMPCD
    WHERE USERID = $SESSION_USERID;

  SELECT
    A.PKGTP, A.CATECD, 
    CONCAT(_$ICONURL, A.ICONCLS) AS ICONCLS,
    A.MENUCD, A.MENUNM, A.PMENUCD, A.MENUPATH
    FROM (
    SELECT
      SYSPKG.SORTNO AS SORTNO, 0 AS MENUSORT,
      PKGTP AS PKGTP,     '' AS CATECD,    ICONCLS,
      PKGTP AS MENUCD,    PKGNM AS MENUNM,  '' AS PMENUCD, 
      '' AS MENUPATH
      FROM SYSPKG
      WHERE USEYN = 'Y'
        AND PKGTP NOT IN ('TML', 'PDA', 'IFP', 'ETC', 'TAL') -- 
    UNION ALL -- 카테고리
    SELECT
      SYSPKG.SORTNO AS SORTNO, 0 AS MENUSORT,
      SYSCATE.PKGTP AS PKGTP,      SYSCATE.CATECD AS CATECD, IF(SYSCATE.PKGTP='MY' AND CATECD=20, 'ic_menu_star_n.png' ,'ic_menu_folder_n.png') AS ICONCLS,
      CONCAT(SYSCATE.PKGTP, SYSCATE.CATECD) AS MENUCD, SYSCATE.CATENM AS MENUNM, 
      IF(SYSCATE.PCATECD = SYSPKG.PKGTP, SYSCATE.PKGTP, CONCAT(SYSCATE.PKGTP, PCATECD)) AS PMENUCD, 
      '' AS MENUPATH
      FROM SYSCATE
      JOIN SYSPKG ON SYSCATE.PKGTP = SYSPKG.PKGTP AND SYSPKG.USEYN = 'Y'
      WHERE SYSCATE.USEYN = 'Y'
        AND SYSCATE.PKGTP NOT IN ('TML', 'PDA', 'IFP', 'ETC', 'TAL')
    UNION ALL -- 상세 메뉴
    SELECT 
      SYSPKG.SORTNO AS SORTNO, SYSMENU.SORTNO AS MENUSORT,
      SYSMENU.PKGTP, SYSMENU.CATECD, 'ic_menu_file_n.png' AS ICONCLS,
      SYSMENU.PRGCD AS MENUCD, SYSMENU.MENUNM AS MENUNM,
      CONCAT(SYSMENU.PKGTP, SYSMENU.CATECD) AS PMENUCD,
      CASE
        WHEN SYSPRG.PRGSTT NOT IN ('30', '40') THEN '../../PAGESYS/SYS0000/SYS0000_R01.aspx'
        WHEN MAX(IFNULL(IFNULL(SYSAUTPRGUSER.SEARCHYN,  SYSAUTPRG.SEARCHYN), 'N')) = 'N' THEN '../../PAGESYS/SYS0000/SYS0000_R01.aspx'
        ELSE CONCAT('../../PAGE', LEFT(SYSMENU.PRGCD, 3), '/', LEFT(SYSMENU.PRGCD, 7), '/', SYSMENU.PRGCD, '.aspx')
      END AS MENUPATH
    FROM SYSMENU
    LEFT JOIN SYSPRG ON SYSMENU.PRGCD = SYSPRG.PRGCD
    LEFT JOIN SYSAUTPRG ON SYSAUTPRG.INOUTTP = _$USERINOUTTP
                       AND SYSMENU.PRGCD = SYSAUTPRG.PRGCD
                       AND SYSAUTPRG.AUTCD IN ( SELECT AUTCD FROM SYSAUTUSER WHERE USERID = $SESSION_USERID AND SYSAUTUSER.USEYN = 'Y' )
                       -- AND SYSAUTPRG.AUTCD = _$USERAUTCD
    LEFT JOIN SYSAUTPRGUSER ON SYSAUTPRGUSER.USERID = $SESSION_USERID 
          AND SYSMENU.PRGCD = SYSAUTPRGUSER.PRGCD
          AND SYSAUTPRGUSER.INOUTTP = _$USERINOUTTP
    LEFT JOIN SYSCATE ON SYSMENU.PKGTP = SYSCATE.PKGTP
                AND SYSMENU.CATECD = SYSCATE.CATECD
                AND SYSCATE.USEYN = 'Y'
    JOIN SYSPKG  ON SYSPKG.PKGTP = SYSMENU.PKGTP
                AND SYSPKG.USEYN = 'Y'
    WHERE PRGSTT NOT IN ('50', '60')  -- 50:삭제, 60:숨김
      AND SYSMENU.PKGTP NOT IN ('TML', 'PDA', 'IFP', 'ETC', 'TAL')
      AND IF(SYSAUTPRGUSER.SEARCHYN IS NULL, SYSAUTPRG.SEARCHYN = 'Y', SYSAUTPRGUSER.SEARCHYN = 'Y') -- 조회권한 있는 메뉴만 보이도록 수정, 계정권한우선 (2026-07-28 신정수)
    GROUP BY SYSMENU.PRGCD
    UNION ALL -- 마이 메뉴
    SELECT
      SYSPKG.SORTNO AS SORTNO, 0 AS MENUSORT,
      'MY' AS PKGTP, '20' AS CATECD, 'ic_menu_file_n.png' AS ICONCLS,
      SYSMENUUSER.PRGCD AS MENUCD, GPCD('MENUCD', SYSMENUUSER.PRGCD) AS MENUNM, 'MY20' AS PMENUCD,
      CONCAT('../../PAGE', LEFT(SYSMENUUSER.PRGCD, 3), '/', LEFT(SYSMENUUSER.PRGCD, 7), '/', SYSMENUUSER.PRGCD, '.aspx') AS MENUPATH
      FROM SYSMENUUSER
      JOIN SYSMENU ON SYSMENUUSER.PRGCD = SYSMENU.PRGCD
      JOIN SYSPKG  ON SYSPKG.PKGTP = SYSMENU.PKGTP
                  AND SYSPKG.USEYN = 'Y'
      WHERE USERID = $SESSION_USERID
  ) AS A
  ORDER BY A.SORTNO, A.CATECD, A.MENUSORT
  ;
  -- 자주 사용한 메뉴 따로 조회
  SELECT
    'MY' AS PKGTP, '10' AS CATECD, CONCAT(_$ICONURL,'ic_menu_file_n.png') AS ICONCLS,  
    HIS.PRGCD AS MENUCD, GPCD('PRGCD', HIS.PRGCD) AS MENUNM, 'MY10' AS PMENUCD,
    CONCAT('../../PAGE', LEFT(HIS.PRGCD, 3), '/', LEFT(HIS.PRGCD, 7), '/', HIS.PRGCD, '.aspx') AS MENUPATH
    FROM SYSMENUUSERHIS AS HIS
    INNER JOIN SYSPRG ON HIS.PRGCD = SYSPRG.PRGCD
    WHERE HIS.USERID = $SESSION_USERID
      AND HIS.PRGCD NOT IN (
                              SELECT 
                                SYSMENUUSER.PRGCD 
                                FROM SYSMENUUSER 
                                WHERE SYSMENUUSER.USERID = $SESSION_USERID
      )
      AND HIS.PRGCD NOT IN ('ITEMCD', 'SYS0000_R01')
    ORDER BY HIS.CNT DESC
    LIMIT 5
  ;

  -- 마이메뉴
  SELECT
    USERID, PRGCD,  GPCD('MENUCD', PRGCD) AS MENUNM, HOTYN, 
    CONCAT('../../PAGE', LEFT(PRGCD, 3), '/', LEFT(PRGCD, 7), '/', PRGCD, '.aspx') AS MENUPATH
    FROM SYSMENUUSER
    WHERE USERID = $SESSION_USERID
    ORDER BY RTIME DESC;

  SET _$ALERTYN = 'N';

  -- 대봉 미사용
--   IF EXISTS (SELECT USERID
--                FROM SYSUSER 
--                WHERE USERID = $SESSION_USERID
--                  AND (PIFODRYN = 'Y' 
--                   OR PIFCHGYN = 'Y')
--               ) THEN
-- 
--     SET _$ALERTYN = 'Y';
-- 
--   END IF;

  -- 기타 정보
  SELECT
  _$ALERTYN AS ALERTYN,
  (SELECT REF01 FROM COMTYPE WHERE GPCD = 'GLOBAL' AND TPCD = 'SRCVERSION') AS SRCVERSION,
  '12' AS FONTSIZE -- 현재 미사용
  ;
  
-- ****************************************************************************
WHEN 'SEARCH_MENU' THEN

  SET _$ICONURL = '';
  IF $MENUNM = '' THEN
    SET $MENUNM = '!@#$';
  END IF;

  SELECT
    SYSUSER.AUTCD, MSTEMP.DEPTP, SYSUSER.EMPCD
    INTO _$USERAUTCD, _$USERDEPTCD, _$USEREMPCD
    FROM SYSUSER
    INNER JOIN MSTEMP ON SYSUSER.EMPCD = MSTEMP.EMPCD
    WHERE USERID = $SESSION_USERID;


  SELECT 
    SYSMENU.PKGTP, SYSMENU.CATECD, 
    SYSMENU.PRGCD AS MENUCD, SYSMENU.MENUNM,
    '../../images/menu/ic_menu_file_n.png' AS ICONCLS,
    CONCAT(GPCD('PKGTP', SYSMENU.PKGTP), '>', IFNULL(SYSCATE.CATENM, SYSPRG.PRGNM)) AS PMENUCD,
    CONCAT('../../PAGE', LEFT(SYSMENU.PRGCD, 3), '/', LEFT(SYSMENU.PRGCD, 7), '/', SYSMENU.PRGCD, '.aspx') AS MENUPATH
    FROM SYSMENU
    INNER JOIN SYSAUTPRG ON SYSMENU.PRGCD = SYSAUTPRG.PRGCD
    INNER JOIN SYSPRG ON SYSMENU.PRGCD = SYSPRG.PRGCD
    LEFT JOIN SYSCATE ON SYSMENU.PKGTP = SYSCATE.PKGTP
          AND SYSMENU.CATECD = SYSCATE.CATECD
    -- WHERE SYSAUTPRG.AUTCD IN (SELECT AUTCD FROM SYSAUTUSER WHERE USERID = $SESSION_USERID)
    WHERE SYSAUTPRG.AUTCD = _$USERAUTCD
      AND SYSPRG.PRGSTT NOT IN ( '50', '60' )
      AND SYSMENU.PKGTP NOT IN ('TML', 'PDA', 'IFP', 'ETC', 'HRM', 'DVP', 'ENT')
      AND SYSMENU.PRGCD NOT LIKE 'GWS%'
      AND MENUNM LIKE CONCAT('%', $MENUNM, '%')
    GROUP BY SYSMENU.PRGCD
  ;
  -- 검색 결과에도 메뉴구조를 표시하기 위해 추가 조회
  SELECT 
    SYSMENU.PKGTP, SYSMENU.CATECD, 
    CONCAT(GPCD('PKGTP', SYSMENU.PKGTP), '>', IFNULL(SYSCATE.CATENM, SYSPRG.PRGNM)) AS MENUCD, 
    CONCAT(GPCD('PKGTP', SYSMENU.PKGTP), '>', IFNULL(SYSCATE.CATENM, SYSPRG.PRGNM)) AS MENUNM,
    CONCAT('../../images/menu/', REPLACE(SYSPKG.ICONCLS, '_n.png', '_p.png')) AS ICONCLS,
    '' AS PMENUCD,
    '' AS MENUPATH
    FROM SYSMENU
    INNER JOIN SYSPKG ON SYSMENU.PKGTP = SYSPKG.PKGTP
    INNER JOIN SYSAUTPRG ON SYSMENU.PRGCD = SYSAUTPRG.PRGCD
    INNER JOIN SYSPRG ON SYSMENU.PRGCD = SYSPRG.PRGCD
    LEFT JOIN SYSCATE ON SYSMENU.PKGTP = SYSCATE.PKGTP
          AND SYSMENU.CATECD = SYSCATE.CATECD
    -- WHERE SYSAUTPRG.AUTCD IN (SELECT AUTCD FROM SYSAUTUSER WHERE USERID = $SESSION_USERID)
    WHERE SYSAUTPRG.AUTCD = _$USERAUTCD
      AND SYSPRG.PRGSTT NOT IN ( '50', '60' )
      AND SYSMENU.PKGTP NOT IN ('TML', 'PDA', 'IFP', 'ETC', 'HRM', 'DVP')
      AND SYSMENU.PRGCD NOT LIKE 'GWS%'
      AND MENUNM LIKE CONCAT('%', $MENUNM, '%')
    GROUP BY CONCAT(SYSMENU.PKGTP, SYSMENU.CATECD)
  ;

-- ****************************************************************************
WHEN 'PAGE_LOAD' THEN -- 권한설정 
  
  SELECT
    SYSUSER.AUTCD, MSTEMP.BDVCD, SYSUSER.EMPCD, 'Y'
    INTO _$AUTCD, _$CENTERCD, _$EMPCD, _$PLUSKEYYN
    FROM SYSUSER
    INNER JOIN MSTEMP ON SYSUSER.EMPCD = MSTEMP.EMPCD
    WHERE SYSUSER.USERID = $SESSION_USERID;

  SET _$USERINOUTTP = 'IN';

--   IF EXISTS (SELECT TPCD FROM COMTYPE WHERE GPCD = 'INSIDEIP' AND USEYN = 'Y' and REF01 = @CALLIP) THEN
--     
--     SET _$USERINOUTTP = 'IN';
-- 
--   END IF;

  SELECT 
    SYSAUTPRG.PRGCD AS NAME,
    REPLACE(REPLACE(GPCD('PRGCD', SYSAUTPRG.PRGCD), '<br>', ''), '&nbsp;', '') AS TITLE,
    SYSPKG.PKGNM AS NAVINAME1,
    SYSCATE.CATENM AS NAVINAME2,
    _$CENTERCD AS CENTERCD, _$PLUSKEYYN AS PLUSKEYYN,
    _$EMPCD AS EMPCD,   $SESSION_USERID AS USERID,
    MAX(IFNULL(SYSAUTPRGUSER.SEARCHYN,  SYSAUTPRG.SEARCHYN)) AS SEARCHYN, 
    MAX(IFNULL(SYSAUTPRGUSER.ADDYN,     SYSAUTPRG.ADDYN))    AS ADDYN,
    MAX(IFNULL(SYSAUTPRGUSER.SAVEYN,    SYSAUTPRG.SAVEYN))   AS SAVEYN,
    MAX(IFNULL(SYSAUTPRGUSER.DELETEYN,  SYSAUTPRG.DELETEYN)) AS DELETEYN,
    MAX(IFNULL(SYSAUTPRGUSER.PRINTYN,   SYSAUTPRG.PRINTYN))  AS PRINTYN,
    MAX(IFNULL(SYSAUTPRGUSER.EXPORTYN,  SYSAUTPRG.EXPORTYN)) AS EXPORTYN,
    MAX(IFNULL(SYSAUTPRGUSER.FAXYN,     SYSAUTPRG.FAXYN))    AS FAXYN,
    MAX(IFNULL((SELECT REF01 FROM COMTYPE WHERE GPCD = 'GLOBAL' AND TPCD = 'TOAST'), '')) AS TOAST
    FROM SYSAUTPRG
    LEFT JOIN SYSAUTPRGUSER ON SYSAUTPRGUSER.USERID = $SESSION_USERID 
                           AND SYSAUTPRGUSER.INOUTTP = _$USERINOUTTP 
                           AND SYSAUTPRGUSER.PRGCD = $PRGCD
    LEFT JOIN SYSMENU ON SYSAUTPRG.PRGCD = SYSMENU.PRGCD
    LEFT JOIN SYSCATE ON SYSMENU.PKGTP = SYSCATE.PKGTP 
                     AND SYSMENU.CATECD = SYSCATE.CATECD
    LEFT JOIN SYSPKG
      ON SYSPKG.PKGTP = SYSMENU.PKGTP
    WHERE SYSAUTPRG.INOUTTP = _$USERINOUTTP
      AND SYSAUTPRG.PRGCD = $PRGCD
      -- AND SYSAUTPRG.AUTCD IN ( SELECT AUTCD FROM SYSAUTUSER WHERE USERID = $SESSION_USERID AND SYSAUTUSER.USEYN = 'Y' );
      AND SYSAUTPRG.AUTCD = _$AUTCD;     

  SELECT
    USERID, PRGCD, GRIDID,
    CONCAT(
    REPLACE(
        REPLACE(
          REPLACE(
            REPLACE(LEFT(STYLEINFO, LENGTH(STYLEINFO) - 2), '\"', '\\"'),
          '\\"columns\\":\\"', '\"columns\":\"'),
        '\\",\\"filterDefinition\\":\\"', '\",\"filterDefinition\":\"'),
      '\\",\\"sortDescriptions\\":', '\",\"sortDescriptions\":\"')
    , ']\"}')
       AS STYLEINFO
    FROM SYSGRIDSTYLE
    WHERE USERID = $SESSION_USERID
      AND PRGCD = $PRGCD;

  INSERT INTO SYSMENUUSERHIS(
    USERID, PRGCD, CNT,
    RTIME, REMP, RPRG,
    MTIME, MEMP, MPRG
    ) VALUES (
    $SESSION_USERID, $PRGCD, 1,
    CALLTIME(), CALLEMP(), CALLPRG(),
    CALLTIME(), CALLEMP(), CALLPRG()
    ) ON DUPLICATE KEY UPDATE
    CNT = CNT + 1,
    MTIME = CALLTIME(),
    MEMP = CALLEMP(),
    MPRG = CALLPRG()
    ;

  INSERT INTO SYSMENUUSERLOG (
    USERID, PRGCD, REMARK,
    RTIME, REMP, RPRG
    ) VALUES (
    $SESSION_USERID, $PRGCD, '',
    CALLTIME(), CALLEMP(), CALLPRG()
    );

-- ****************************************************************************
WHEN 'PRG_INFO' THEN 

  SELECT 
    PRGNM AS MENUNM,
    CONCAT('../../PAGE', LEFT(PRGCD, 3), '/', LEFT(PRGCD, 7), '/', PRGCD, '.aspx') AS MENUPATH
    FROM SYSPRG
    WHERE PRGCD = $PRGCD;

-- ****************************************************************************
WHEN 'LIST_MENU_TAB' THEN

  SET _$USERINOUTTP = 'IN';
  SET _$ICONURL = '../../images/menu/';

  SELECT
    SYSUSER.AUTCD, MSTEMP.DEPTP, SYSUSER.EMPCD
    INTO _$USERAUTCD, _$USERDEPTCD, _$USEREMPCD
    FROM SYSUSER
    INNER JOIN MSTEMP ON SYSUSER.EMPCD = MSTEMP.EMPCD
    WHERE USERID = $SESSION_USERID;

  -- 0.
  SELECT
    A.PKGTP, A.CATECD, 
    CONCAT(_$ICONURL, A.ICONCLS) AS ICONCLS,
    A.MENUCD, A.MENUNM, A.PMENUCD, A.MENUPATH, A.PRGSTT
    FROM (
    SELECT
      SYSPKG.SORTNO AS SORTNO, 0 AS MENUSORT,
      PKGTP AS PKGTP,     '' AS CATECD,    ICONCLS,
      PKGTP AS MENUCD,    PKGNM AS MENUNM,  '' AS PMENUCD, 
      '' AS MENUPATH, '40' AS PRGSTT
      FROM SYSPKG
      WHERE USEYN = 'Y'
        AND PKGTP NOT IN ('PDA', 'IFP', 'ETC')
    UNION ALL -- 카테고리
    SELECT
      SYSPKG.SORTNO AS SORTNO, 0 AS MENUSORT,
      SYSCATE.PKGTP AS PKGTP,      SYSCATE.CATECD AS CATECD, IF(SYSCATE.PKGTP='MY' AND CATECD=20, 'ic_menu_star_n.png' ,'ic_menu_folder_n.png') AS ICONCLS,
      CONCAT(SYSCATE.PKGTP, SYSCATE.CATECD) AS MENUCD, SYSCATE.CATENM AS MENUNM, 
      IF(SYSCATE.PCATECD = SYSPKG.PKGTP, SYSCATE.PKGTP, CONCAT(SYSCATE.PKGTP, PCATECD)) AS PMENUCD, 
      '' AS MENUPATH, '40' AS PRGSTT
      FROM SYSCATE
      JOIN SYSPKG ON SYSCATE.PKGTP = SYSPKG.PKGTP AND SYSPKG.USEYN = 'Y'
      WHERE SYSCATE.USEYN = 'Y'
        AND SYSCATE.PKGTP NOT IN ('TML')
    UNION ALL -- 상세 메뉴
    SELECT 
      SYSPKG.SORTNO AS SORTNO, SYSMENU.SORTNO AS MENUSORT,
      SYSMENU.PKGTP, SYSMENU.CATECD, 'ic_menu_file_n.png' AS ICONCLS,
      SYSMENU.PRGCD AS MENUCD, SYSMENU.MENUNM AS MENUNM,
      CONCAT(SYSMENU.PKGTP, SYSMENU.CATECD) AS PMENUCD,
      CASE
        WHEN SYSPRG.PRGSTT NOT IN ('30', '40') THEN '../../PAGESYS/SYS0000/SYS0000_R01.aspx'
        WHEN IFNULL(MAX(SYSAUTPRG.SEARCHYN), 'N') = 'N' AND IFNULL(MAX(SYSAUTPRGUSER.SEARCHYN), 'N') = 'N' THEN '../../PAGESYS/SYS0000/SYS0000_R01.aspx'
        ELSE CONCAT('../../PAGE', LEFT(SYSMENU.PRGCD, 3), '/', LEFT(SYSMENU.PRGCD, 7), '/', SYSMENU.PRGCD, '.aspx')
      END AS MENUPATH,
      SYSPRG.PRGSTT
      FROM SYSMENU
      LEFT JOIN SYSPRG 
        ON SYSPRG.PRGCD = SYSMENU.PRGCD
      LEFT JOIN SYSAUTPRG 
        ON SYSAUTPRG.INOUTTP = _$USERINOUTTP
       AND SYSAUTPRG.PRGCD = SYSMENU.PRGCD
       AND SYSAUTPRG.AUTCD IN ( SELECT AUTCD FROM SYSAUTUSER WHERE USERID = $SESSION_USERID AND SYSAUTUSER.USEYN = 'Y' )
      LEFT JOIN SYSAUTPRGUSER 
        ON SYSAUTPRGUSER.USERID = $SESSION_USERID 
       AND SYSAUTPRGUSER.PRGCD = SYSMENU.PRGCD
       AND SYSAUTPRGUSER.INOUTTP = _$USERINOUTTP
      LEFT JOIN SYSCATE ON SYSMENU.PKGTP = SYSCATE.PKGTP
                  AND SYSMENU.CATECD = SYSCATE.CATECD
                  AND SYSCATE.USEYN = 'Y'
      JOIN SYSPKG  ON SYSPKG.PKGTP = SYSMENU.PKGTP
                  AND SYSPKG.USEYN = 'Y'
      WHERE PRGSTT <> '50'
        AND SYSMENU.PKGTP NOT IN ('PDA', 'IFP', 'ETC')
        AND IF(SYSAUTPRGUSER.SEARCHYN IS NULL, SYSAUTPRG.SEARCHYN = 'Y', SYSAUTPRGUSER.SEARCHYN = 'Y') -- 조회권한 있는 메뉴만 보이도록 수정, 계정권한우선 (2026-07-28 신정수)
      GROUP BY SYSMENU.PRGCD
    UNION ALL -- 마이 메뉴
    SELECT
      0 AS SORTNO, 0 AS MENUSORT,
      'MY' AS PKGTP, '20' AS CATECD, 'ic_menu_file_n.png' AS ICONCLS,
      SYSMENUUSER.PRGCD AS MENUCD, SYSMENU.MENUNM AS MENUNM, 'MY20' AS PMENUCD,
      CONCAT('../../PAGE', LEFT(SYSMENUUSER.PRGCD, 3), '/', LEFT(SYSMENUUSER.PRGCD, 7), '/', SYSMENUUSER.PRGCD, '.aspx') AS MENUPATH,
      '05' AS PRGSTT
      FROM SYSMENUUSER
      JOIN SYSMENU ON SYSMENUUSER.PRGCD = SYSMENU.PRGCD
      JOIN SYSPKG  ON SYSPKG.PKGTP = SYSMENU.PKGTP
                  AND SYSPKG.USEYN = 'Y'
      WHERE USERID = $SESSION_USERID
  ) AS A
  ORDER BY A.SORTNO, A.CATECD, A.MENUSORT, MENUNM
  ;

  -- 1. 자주 사용한 메뉴 따로 조회
  SELECT
    'MY' AS PKGTP, '10' AS CATECD, CONCAT(_$ICONURL,'ic_menu_file_n.png') AS ICONCLS,  
    HIS.PRGCD AS MENUCD, GPCD('PRGCD', HIS.PRGCD) AS MENUNM, 'MY10' AS PMENUCD,
    CONCAT('../../PAGE', LEFT(HIS.PRGCD, 3), '/', LEFT(HIS.PRGCD, 7), '/', HIS.PRGCD, '.aspx') AS MENUPATH
    FROM SYSMENUUSERHIS AS HIS
    INNER JOIN SYSPRG ON HIS.PRGCD = SYSPRG.PRGCD
    WHERE HIS.USERID = $SESSION_USERID
      AND HIS.PRGCD NOT IN (
                              SELECT 
                                SYSMENUUSER.PRGCD 
                                FROM SYSMENUUSER 
                                WHERE SYSMENUUSER.USERID = $SESSION_USERID
      )
      AND HIS.PRGCD NOT IN ('ITEMCD', 'SYS0000_R01')
    ORDER BY HIS.CNT DESC
    LIMIT 10
  ;

  -- 2. 테블릿 메뉴 
  SELECT
    SYSMENU.PRGCD,  GPCD('PRGCD', SYSMENU.PRGCD) AS MENUNM,
    CONCAT('../../PAGE', LEFT(SYSMENU.PRGCD, 3), '/', LEFT(SYSMENU.PRGCD, 7), '/', SYSMENU.PRGCD, '.aspx') AS MENUPATH
  FROM SYSMENU
  LEFT JOIN SYSPRG 
    ON SYSPRG.PRGCD = SYSMENU.PRGCD
  LEFT JOIN SYSAUTPRG 
    ON SYSAUTPRG.INOUTTP = _$USERINOUTTP
   AND SYSAUTPRG.PRGCD = SYSMENU.PRGCD
   AND SYSAUTPRG.AUTCD IN ( SELECT AUTCD FROM SYSAUTUSER WHERE USERID = $SESSION_USERID AND SYSAUTUSER.USEYN = 'Y' )
  LEFT JOIN SYSAUTPRGUSER 
    ON SYSAUTPRGUSER.USERID = $SESSION_USERID 
   AND SYSAUTPRGUSER.PRGCD = SYSMENU.PRGCD
   AND SYSAUTPRGUSER.INOUTTP = _$USERINOUTTP
  WHERE SYSMENU.PKGTP = 'TAL'
