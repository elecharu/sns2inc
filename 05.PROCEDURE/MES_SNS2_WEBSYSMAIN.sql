PROCEDURE MES_SNS2.WEBSYSMAIN(
-- *****************************************************************************
-- Comment: 메인화면
-- Create: 2018-06-12 13:49: 문재원
-- Modify: 2019-08-01 09:00: 문재원 영진 이관
