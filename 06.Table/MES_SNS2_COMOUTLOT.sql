CREATE TABLE MES_SNS2.COMOUTLOT (
  OUTKEY VARCHAR(20) NOT NULL DEFAULT '' COMMENT '출고키',
  LOTKEY VARCHAR(100) NOT NULL DEFAULT '' COMMENT '출고로트키',
  WARECD VARCHAR(10) NOT NULL DEFAULT '' COMMENT '창고코드',
  OUTTP VARCHAR(10) NOT NULL DEFAULT '' COMMENT '출고유형',
  OUTDATE VARCHAR(10) NOT NULL DEFAULT '' COMMENT '출고일자',
  OUTQTY DECIMAL(20, 8) NOT NULL DEFAULT 0.00000000 COMMENT '출고수량',
  PRCCD VARCHAR(20) NOT NULL DEFAULT '' COMMENT '공정코드',
  ITEMID VARCHAR(20) NOT NULL DEFAULT '' COMMENT '품목ID',
  OLDQTY DECIMAL(20, 8) NOT NULL DEFAULT 0.00000000 COMMENT '초기수량',
  ETCTP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '출고구분',
  REMARK VARCHAR(100) NOT NULL DEFAULT '' COMMENT '비고',
  RTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '등록시간',
  REMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '등록자',
  RPRG VARCHAR(100) NOT NULL DEFAULT '' COMMENT '등록프로그램',
  MTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '수정시간',
  MEMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '수정자',
  MPRG VARCHAR(100) NOT NULL DEFAULT '' COMMENT '수정프로그램',
  PRIMARY KEY (OUTKEY, LOTKEY),
  INDEX IDX_COMOUTLOT_LOTKEY (LOTKEY),
  INDEX IDX_COMOUTLOT_OUTKEY (OUTKEY)
)
ENGINE = INNODB
