CREATE TABLE MES_SNS2.MOVEINVOICE (
  INVOICEKEY VARCHAR(20) NOT NULL COMMENT '거래명세서키 (GETKEY INVOICEKEY)',
  INVOICEDATE VARCHAR(10) NOT NULL DEFAULT '' COMMENT '거래일자 (이동일자)',
  GROUPKEY VARCHAR(20) NOT NULL DEFAULT '' COMMENT '이동 그룹키 (COMOUT·COMIN.GROUPKEY)',
  OUTWARE VARCHAR(10) NOT NULL DEFAULT '' COMMENT '출고창고 (사내)',
  INWARE VARCHAR(10) NOT NULL DEFAULT '' COMMENT '입고창고 (외주처)',
  CUSTCD VARCHAR(100) NOT NULL DEFAULT '' COMMENT '외주처 (입고창고 MSTWARE.CUSTCD)',
  EMPCD VARCHAR(20) NOT NULL DEFAULT '' COMMENT '처리자',
  REMARK VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '비고',
  RTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '등록시간',
  REMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '등록자',
  RPRG VARCHAR(100) NOT NULL DEFAULT '' COMMENT '등록프로그램',
  MTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '수정시간',
  MEMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '수정자',
  MPRG VARCHAR(100) NOT NULL DEFAULT '' COMMENT '수정프로그램',
  PRIMARY KEY (INVOICEKEY),
  INDEX IDX_MOVEINVOICE_INVOICEDATE (INVOICEDATE),
  INDEX IDX_MOVEINVOICE_GROUPKEY (GROUPKEY)
)
ENGINE = INNODB
CHARACTER SET utf8
COLLATE utf8_general_ci
COMMENT = '재고이동(외주반출) 거래명세서 이력 헤더'
ROW_FORMAT = DYNAMIC;
