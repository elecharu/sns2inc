CREATE TABLE MES_SNS2.MOVEINVOICED (
  INVOICEKEY VARCHAR(20) NOT NULL COMMENT '거래명세서키',
  LOTKEY VARCHAR(100) NOT NULL DEFAULT '' COMMENT '이동로트키',
  ITEMID VARCHAR(100) NOT NULL DEFAULT '' COMMENT '품목ID',
  MOVEQTY DECIMAL(20, 8) NOT NULL DEFAULT 0.00000000 COMMENT '이동수량 (LOT)',
  RTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '등록시간',
  REMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '등록자',
  RPRG VARCHAR(100) NOT NULL DEFAULT '' COMMENT '등록프로그램',
  MTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '수정시간',
  MEMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '수정자',
  MPRG VARCHAR(100) NOT NULL DEFAULT '' COMMENT '수정프로그램',
  PRIMARY KEY (INVOICEKEY, LOTKEY)
)
ENGINE = INNODB
CHARACTER SET utf8
COLLATE utf8_general_ci
COMMENT = '재고이동(외주반출) 거래명세서 이력 상세 (LOT)'
ROW_FORMAT = DYNAMIC;
