CREATE TABLE MES_SNS2.MTRIN (
  MTRINKEY VARCHAR(20) NOT NULL DEFAULT '' COMMENT '가입고키',
  MTRODRKEY VARCHAR(20) NOT NULL DEFAULT '' COMMENT '발주키',
  MTRODRSEQ INT(11) NOT NULL DEFAULT 0 COMMENT '발주상세순번',
  INVOICEKEY VARCHAR(20) NOT NULL DEFAULT '' COMMENT '거래명세서 번호',
  MTRINTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '가입고시간',
  MTRINTP VARCHAR(10) NOT NULL DEFAULT '10' COMMENT '입고구분',
  CUSTCD VARCHAR(10) NOT NULL DEFAULT '' COMMENT '거래처코드',
  ITEMID INT(11) NOT NULL DEFAULT 0 COMMENT '품목코드',
  PRCCD VARCHAR(10) NOT NULL DEFAULT '' COMMENT '공정코드',
  WARECD VARCHAR(10) NOT NULL DEFAULT '' COMMENT '창고코드',
  EMPCD VARCHAR(20) NOT NULL DEFAULT '' COMMENT '가입고사원',
  INDATE VARCHAR(10) NOT NULL DEFAULT '' COMMENT '입고일자',
  APPEMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '검수인',
  APPDT VARCHAR(10) NOT NULL DEFAULT '' COMMENT '검수일자',
  APPYN VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '입고검수여부',
  INQTY DECIMAL(20, 8) NOT NULL DEFAULT 0.00000000 COMMENT '입고수량',
  REMARK VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '비고',
  RTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '등록시간',
  REMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '등록자',
  RPRG VARCHAR(100) NOT NULL DEFAULT '' COMMENT '등록프로그램',
  MTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '수정시간',
  MEMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '수정자',
  MPRG VARCHAR(100) NOT NULL DEFAULT '' COMMENT '수정프로그램',
  PRIMARY KEY (MTRINKEY),
  INDEX IDX_MTRIN_CUSTCD (CUSTCD),
  INDEX IDX_MTRIN_ITEMID (ITEMID),
  INDEX IDX_MTRIN_MTRINTP (MTRINTP),
  INDEX IDX_MTRIN_MTRODRDKEY (MTRODRKEY)
)
ENGINE = INNODB
AVG_ROW_LENGTH = 285
CHARACTER SET utf8
COLLATE utf8_general_ci
COMMENT = '가입고'
ROW_FORMAT = DYNAMIC;