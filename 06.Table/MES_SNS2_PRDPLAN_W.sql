CREATE TABLE MES_SNS2.PRDPLAN_W (
  PMONTH VARCHAR(7) NOT NULL DEFAULT '' COMMENT '계획월',
  PDATE VARCHAR(10) NOT NULL DEFAULT '' COMMENT '계획일자',
  ITEMID INT(11) NOT NULL DEFAULT 0 COMMENT '품목코드',
  EQMCD VARCHAR(100) NOT NULL DEFAULT '' COMMENT '라인코드',
  CT DECIMAL(20, 8) NOT NULL DEFAULT 0.00000000 COMMENT 'CT',
  EFFI DECIMAL(20, 8) NOT NULL DEFAULT 0.00000000 COMMENT '설비종합효율',
  UPH DECIMAL(20, 8) NOT NULL DEFAULT 0.00000000 COMMENT 'UPH = 3600 / CT * (UPD / 100)',
  ONESQTY DECIMAL(20, 8) NOT NULL DEFAULT 0.00000000 COMMENT '1S수량 = 한작업조 생산CAPA = ROUND(9시간*UPH)',
  PLANQTY_DAY DECIMAL(20, 8) NOT NULL DEFAULT 0.00000000 COMMENT '생산계획수량_주간',
  PLANQTY_NIGHT DECIMAL(20, 8) NOT NULL DEFAULT 0.00000000 COMMENT '생산계획수량_야간',
  PLANSTOP_DAY VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '계획정지_주간',
  PLANSTOP_NIGHT VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '계획정지_야간',
  REMARK VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '비고',
  RTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '등록시간',
  REMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '등록자',
  RPRG VARCHAR(100) NOT NULL DEFAULT '' COMMENT '등록프로그램',
  MTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '수정시간',
  MEMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '수정자',
  MPRG VARCHAR(100) NOT NULL DEFAULT '' COMMENT '수정프로그램',
  PRIMARY KEY (PDATE, ITEMID, EQMCD, PMONTH)
)
ENGINE = INNODB
CHARACTER SET utf8
COLLATE utf8_general_ci
COMMENT = '주간생산계획'
ROW_FORMAT = DYNAMIC;