CREATE TABLE MES_SNS2.SALINVOICE (
  INVOICEKEY VARCHAR(20) NOT NULL COMMENT '거래명세서키 (GETKEY INVOICEKEY)',
  INVOICEDATE VARCHAR(10) NOT NULL DEFAULT '' COMMENT '거래일자 (출하일자)',
  CUSTCD VARCHAR(100) NOT NULL DEFAULT '' COMMENT '납품처',
  SALOUTGROUPKEY VARCHAR(20) NOT NULL DEFAULT '' COMMENT '출하그룹키 (TML5000_R01 납품처별 묶음, R02 는 빈값)',
  WARECD VARCHAR(10) NOT NULL DEFAULT '' COMMENT '출고창고',
  EMPCD VARCHAR(20) NOT NULL DEFAULT '' COMMENT '처리자',
  REMARK VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '비고',
  RTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '등록시간',
  REMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '등록자',
  RPRG VARCHAR(100) NOT NULL DEFAULT '' COMMENT '등록프로그램',
  MTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '수정시간',
  MEMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '수정자',
  MPRG VARCHAR(100) NOT NULL DEFAULT '' COMMENT '수정프로그램',
  PRIMARY KEY (INVOICEKEY),
  INDEX IDX_SALINVOICE_INVOICEDATE (INVOICEDATE),
  INDEX IDX_SALINVOICE_SALOUTGROUPKEY (SALOUTGROUPKEY)
)
ENGINE = INNODB
CHARACTER SET utf8
COLLATE utf8_general_ci
COMMENT = '출하 거래명세서 이력 헤더'
ROW_FORMAT = DYNAMIC;
