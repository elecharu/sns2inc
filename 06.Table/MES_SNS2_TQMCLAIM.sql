CREATE TABLE MES_SNS2.TQMCLAIM (
  CLAIMKEY VARCHAR(100) NOT NULL DEFAULT '' COMMENT '클레임키 = 문서번호 (SSI-yy-mm-NNN, 처음 저장할 때 예정일자의 연·월로 순번을 매김)',
  CLAIMMONTH VARCHAR(7) NOT NULL DEFAULT '' COMMENT '발생월 (YYYY-MM, 발생기간 = 이 달 1일~말일)',
  CUSTCD VARCHAR(100) NOT NULL DEFAULT '' COMMENT '귀책처 (외주실적 거래처 MSTCUST.CUSTCD, 외주 로트가 아니면 불량구분 JUDGEBADTP 코드)',
  PLANDATE VARCHAR(10) NOT NULL DEFAULT '' COMMENT '예정일자 = 작성일 (공문서 작성일, 산출내역서 ■ 예정일자)',
  CONFDATE VARCHAR(10) NOT NULL DEFAULT '' COMMENT '확정일자 (산출내역서 □ 확정일자, 공문서 "MM/dd 限 서면 제출")',
  EMPCD VARCHAR(100) NOT NULL DEFAULT '' COMMENT '담당',
  RECVNM VARCHAR(200) NOT NULL DEFAULT '' COMMENT '수신',
  REFNM VARCHAR(200) NOT NULL DEFAULT '' COMMENT '참조',
  TITLE VARCHAR(500) NOT NULL DEFAULT '' COMMENT '제목',
  TOTAMT DECIMAL(20, 8) NOT NULL DEFAULT 0.00000000 COMMENT '발생 손실 비용 합계 (TQMCLAIMD.CLAIMAMT 합)',
  REMARK VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '비고',
  RTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '등록시간',
  REMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '등록자',
  RPRG VARCHAR(100) NOT NULL DEFAULT '' COMMENT '등록프로그램',
  MTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '수정시간',
  MEMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '수정자',
  MPRG VARCHAR(100) NOT NULL DEFAULT '' COMMENT '수정프로그램',
  PRIMARY KEY (CLAIMKEY),
  UNIQUE INDEX UK_TQMCLAIM_MONTH_CUST (CLAIMMONTH, CUSTCD)
)
ENGINE = INNODB
CHARACTER SET utf8
COLLATE utf8_general_ci
COMMENT = '협력사 클레임 (협력사 × 월)'
ROW_FORMAT = DYNAMIC;
