CREATE TABLE MES_SNS2.TQMJUDGE (
  JUDGEKEY VARCHAR(100) NOT NULL DEFAULT '' COMMENT '부적합판정키',
  JUDGEDATE VARCHAR(10) NOT NULL DEFAULT '' COMMENT '판정일자',
  LOTKEY VARCHAR(100) NOT NULL DEFAULT '' COMMENT '로트번호 (COMLOT.LOTKEY)',
  WARECD VARCHAR(100) NOT NULL DEFAULT '' COMMENT '불량창고 (COMLOT.WARECD)',
  ITEMID INT(11) NOT NULL DEFAULT 0 COMMENT '품목ID',
  JUDGETP VARCHAR(100) NOT NULL DEFAULT '' COMMENT '판정유형 (공통코드 JUDGETP: 양품/불량/재작업)',
  JUDGEBADTP VARCHAR(100) NOT NULL DEFAULT '' COMMENT '불량구분 (공통코드 JUDGEBADTP: 1공장/2공장/외주, 판정유형이 불량일 때만)',
  JUDGEQTY DECIMAL(20, 8) NOT NULL DEFAULT 0.00000000 COMMENT '판정수량',
  EMPCD VARCHAR(100) NOT NULL DEFAULT '' COMMENT '판정자',
  PROCYN VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '후처리여부 (후처리 화면에서 Y)',
  REMARK VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '비고',
  RTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '등록시간',
  REMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '등록자',
  RPRG VARCHAR(100) NOT NULL DEFAULT '' COMMENT '등록프로그램',
  MTIME VARCHAR(19) NOT NULL DEFAULT '' COMMENT '수정시간',
  MEMP VARCHAR(20) NOT NULL DEFAULT '' COMMENT '수정자',
  MPRG VARCHAR(100) NOT NULL DEFAULT '' COMMENT '수정프로그램',
  PRIMARY KEY (JUDGEKEY),
  INDEX IDX_TQMJUDGE_LOT (LOTKEY, WARECD)
)
ENGINE = INNODB
CHARACTER SET utf8
COLLATE utf8_general_ci
COMMENT = '부적합 판정이력'
ROW_FORMAT = DYNAMIC;
