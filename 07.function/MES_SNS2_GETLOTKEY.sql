CREATE DEFINER = 'root'@'%'
FUNCTION MES_SNS2.GETLOTKEY($LABELCD VARCHAR(10))
  RETURNS varchar(100) CHARSET utf8
BEGIN

  DECLARE _$KEYTYPE VARCHAR(20);
  DECLARE _$KEYDATE VARCHAR(10);
  DECLARE _$KEYVALUE VARCHAR(100);

  DECLARE _$FORMAT VARCHAR(20);
  DECLARE _$SEQLENG INT;

  SET _$KEYTYPE = CONCAT('LOTKEY_', $LABELCD);

  IF NOT EXISTS (
    SELECT LABELCD FROM SYSLABEL WHERE LABELCD = $LABELCD
  ) THEN
    SET @ERRMSG = FORMAT_V1('GETLOTKEY: 라벨유형이 유효하지 않습니다. {0}', $LABELCD);
    RETURN '';
  END IF;

  SELECT LOTFORMAT INTO _$FORMAT FROM SYSLABEL WHERE LABELCD = $LABELCD;
  IF INSTR(_$FORMAT, '{D}') < 1 OR INSTR(_$FORMAT, '{S') < 1 THEN
    SET @ERRMSG = FORMAT_V1('GETLOTKEY: 라벨포멧을 인식할수 없습니다. {0}', _$FORMAT);
    RETURN '';
  END IF;

  SET _$SEQLENG = SUBSTRING(_$FORMAT, INSTR(_$FORMAT, '{S') + 2, 1) + 0;

  SET _$KEYDATE = GETDATE();

  IF NOT EXISTS (SELECT KEYSEQ FROM COMKEY WHERE KEYTYPE = _$KEYTYPE AND KEYDATE = _$KEYDATE) THEN

    INSERT INTO COMKEY (KEYTYPE, KEYDATE, KEYSEQ, KEYVALUE, RTIME, REMP, RPRG) 
      VALUES (_$KEYTYPE, _$KEYDATE, 1, 
        REPLACE(REPLACE(_$FORMAT, '{D}', RIGHT(REPLACE(_$KEYDATE, '-', ''), 6)), CONCAT('{S', _$SEQLENG, '}'), RIGHT(CONCAT('0000000000', 1), _$SEQLENG)),
        GETTIME(), IFNULL(@CALLEMP, ''), IFNULL(@CALLPRG, ''));

    SELECT KEYVALUE INTO _$KEYVALUE
      FROM COMKEY 
      WHERE KEYTYPE = _$KEYTYPE AND KEYDATE = _$KEYDATE;

  ELSE

    UPDATE COMKEY SET 
      KEYSEQ = KEYSEQ + 1,
      KEYVALUE = REPLACE(REPLACE(_$FORMAT, '{D}', RIGHT(REPLACE(_$KEYDATE, '-', ''), 6)), CONCAT('{S', _$SEQLENG, '}'), RIGHT(CONCAT('0000000000', CAST(KEYSEQ AS INT)), _$SEQLENG)),
      MTIME = GETTIME(),
      MEMP = IFNULL(@CALLEMP, ''),
      MPRG = IFNULL(@CALLPRG, '')
      WHERE KEYTYPE = _$KEYTYPE AND KEYDATE = _$KEYDATE;

    SELECT KEYVALUE INTO _$KEYVALUE
      FROM COMKEY 
      WHERE KEYTYPE = _$KEYTYPE AND KEYDATE = _$KEYDATE;

  END IF;

  RETURN _$KEYVALUE;

END